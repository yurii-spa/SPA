(function () {
  var LANG_KEY = "mc_lang";

  // The choice lives in memory first: blocked storage (private window) must still let the owner
  // switch language for this page view. Storage only remembers it between visits.
  var current = null;

  function getLang() {
    if (current) return current;
    try {
      var v = localStorage.getItem(LANG_KEY);
      if (v === "ru" || v === "en") current = v;
    } catch (e) { /* private window / blocked storage: fall through to default */ }
    current = current || "ru";
    document.documentElement.lang = current;
    return current;
  }

  function setLang(lang) {
    current = lang === "en" ? "en" : "ru";
    document.documentElement.lang = current;
    try {
      localStorage.setItem(LANG_KEY, current);
    } catch (e) { /* per-viewer convenience only; losing it is harmless */ }
  }

  function t(key) {
    var lang = getLang();
    var dict = I18N[lang] || I18N.ru;
    if (Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
    if (Object.prototype.hasOwnProperty.call(I18N.ru, key)) return I18N.ru[key];
    return key;
  }

  // Template substitution for the chrome strings that carry {placeholder}s in the copy deck
  // (header.money_chip, header.data_age, header.stale, home.attention.*, decisions.age, …).
  // Composed model sentences (display_ru/display_en) never go through this — they already
  // ARE the final sentence, per the §2.0 cell contract.
  function tf(key, vars) {
    var s = t(key);
    if (typeof s !== "string") return s;
    return s.replace(/\{(\w+)\}/g, function (_, name) {
      var v = vars ? vars[name] : undefined;
      // Пустое место в предложении — та же ложь, что ноль: «1 из » читается как ответ.
      // Отсутствующее значение говорит «не измерено» (инв. #17; ревью Wave 2, раунд 3).
      return (v === undefined || v === null) ? t("common.not_measured") : String(v);
    });
  }

  window.MC_I18N = { t: t, tf: tf, getLang: getLang, setLang: setLang, dict: I18N };
})();
