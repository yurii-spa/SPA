#!/usr/bin/env python3
"""Буквенный перечень вариантов — «- **(а) …**» — читается, а не пропадает (#349).

КАЖДЫЙ тест здесь — положительный контроль ИЗМЕРЕННОЙ аварии, а не украшение.

**Что случилось.** `own-2026-08-19-sudba-voronki-chekapa-i-kanal-zayavok`, приоритет
`high`, висел неотвечаемым с 19.08 по 22.08. Обязательный шаг 0-офис каждый цикл
докладывал «вопросы владельцу без кнопок — ответить с телефона нельзя», а сторож
причин (`buttonless_reason`) называл причину `no_options_in_card`: «в карточке не
разобрано ни одного варианта; **отказ верен**, выдумывать выбор запрещено (ADR-075)»,
лекарство — «переписать вопрос перечнем».

Прогон настоящего разбора по этой самой карточке (цикл #343):

    looks_like_a_choice   -> True     ← это ВЫБОР
    parse_options         -> []       ← не разобрано ни одного
    has_unparsed_options  -> False    ← ровно этот случай он и обязан ловить

**Отказ был НЕ верен.** Варианты в карточке написаны ровно по §2.4 — буквами, с
рекомендацией агента. ADR-075 не нарушен и не оспаривается: их надо было не выдумать,
а ПРОЧИТАТЬ. Автор, послушавшись лекарства, переписал бы верную карточку.

**Класс — тот же, что #146–#348: сторож отвечает не на тот вопрос.**
`has_unparsed_options` делил слепое пятно с тем, кого сторожит: неизвестная разбору
форма была неизвестна и ему. Поэтому чинится не только разбор (он выучит одну форму —
и застынет до следующей), но и сторож: он спрашивает про СОСТОЯНИЕ «след перечня есть,
разобрано ноль», а не про конкретное написание.

**Цена расширения сторожа измерена, а не оценена** (см. `docs/journal/2026-W34.md`):
по всей живой очереди — 602 карточки с `origin/main` 4d9353c1c — вердикт меняется у 12,
и в каждой из 12 выбор действительно написан; ложных «заведи мне дефект» ноль. Кнопки
появляются у двух живых вопросов владельца, ни одна карточка их не теряет.

Время в тестах — не участвует: разбор чистая функция от текста.
"""
from __future__ import annotations

from spa_core.telegram import owner_decisions as od

_HEAD = ("## Что случилось и почему это важно\n\n"
         "Воронка бесплатного чекапа ведёт в никуда третий месяц.\n\n"
         "## Что от тебя нужно\n\n")
_TAIL = "\n## Как понять, что готово\n\nВ меню сайта нет слова «чекап».\n"


#: Форма живой карточки: жирная головка пункта + буква в скобках + рекомендация
#: ОТДЕЛЬНОЙ строкой после перечня (она физически лежит в хвосте последнего пункта).
CARD_LETTERED = _HEAD + (
    "- **(а) Похоронить.** Снять страницы, ссылки и подписку — адрес и меню тоже.\n"
    "- **(б) Воскресить.** Дать чекапу канал заявок и вернуть его в воронку.\n"
    "- **Рекомендация: (а).** Продукт не приносит заявок третий месяц.\n"
) + _TAIL

#: Живая `owner-decision-20260716-082215-k-1-22`: жирным выделен ТОЛЬКО рекомендованный
#: пункт, остальные — обычным текстом. Одна кнопка из трёх хуже, чем ни одной: владелец
#: видит один вариант там, где предложено три, и об остальных не узнаёт.
CARD_MIXED_BOLD = _HEAD + (
    "Реши по пилоту (моя рекомендация первая):\n\n"
    "- **(а, рекомендую)** запустить ступенчато: сначала $1,000 в пакет 1 около 22 июля.\n"
    "- (б) подождать ещё (не запускать пилот, копить только бумажный трек).\n"
    "- (в) другая сумма/пакет/дата — скажи.\n"
) + _TAIL

#: Живая `owner-decision-dva-agenta-ne-perezhivut-perezagruzku-ra`: подпись пункта
#: состоит ИЗ ОДНОЙ ПОМЕТКИ, суть стоит сразу за жирным.
CARD_MARK_ONLY_LABEL = _HEAD + (
    "Выбрать один из вариантов:\n\n"
    "- **(а) — рекомендую.** Разреши доустановить два недостающих plist через штатный гейт.\n"
    "- **(б) Починить и причину тоже** — то же, что (а), плюс правка гейта установки.\n"
) + _TAIL

#: ДВА решения в одной карточке: метки повторяются, разбор отказывает целиком
#: (fail-CLOSED). Слова «вариант» в теле нет вовсе — до #349 это означало, что и
#: `looks_like_a_choice` молчал, то есть карточке предлагалась кнопка «✅ Принято».
CARD_TWO_DECISIONS = _HEAD + (
    "**Решение 1 — судьба чекапа.**\n"
    "- **(а) Похоронить.** Признать продукт закрытым.\n"
    "- **(б) Воскресить.** Поднять сервис заново.\n\n"
    "**Решение 2 — канал заявок.**\n"
    "- **(а) Телеграм.** Заявки идут в чат.\n"
    "- **(б) Почта.** Заявки идут письмом.\n"
) + _TAIL

#: Форма, которой разбор НЕ учили намеренно (буква с точкой без скобок, живая
#: `agent-feeds-without-a-producer`). Сторож обязан назвать её сам — иначе он снова
#: слеп ровно там, где слеп разбор.
CARD_UNKNOWN_LETTER_FORM = _HEAD + (
    "По каждому фиду — выбрать одно из двух.\n\n"
    "- **А. Искать источник дальше** (собственный запрос к протоколу).\n"
    "- **Б. Честно признать «не поддерживаем»** и вывести из реестра.\n"
) + _TAIL

#: Граница в другую сторону: слово «вариант» в прозе перечнем НЕ является. Просьба
#: завести НЕСУЩЕСТВУЮЩИЙ дефект — такая же ложь, как «выбора не предлагали».
CARD_BARE_WORD = _HEAD + "- Вариант тот же, что вчера — ничего не менять.\n" + _TAIL


# ===========================================================================
# Разбор: выбор, написанный буквами, доезжает до кнопок целиком
# ===========================================================================
def test_a_bulleted_lettered_choice_becomes_buttons():
    """Ядро аварии: ровно та форма, из-за которой вопрос `high` висел три недели."""
    opts = od.parse_options(CARD_LETTERED)

    assert [o.num for o in opts] == ["а", "б"]
    assert [o.label for o in opts] == ["Похоронить", "Воскресить"]


def test_the_star_follows_the_letter_the_card_names_not_the_last_paragraph():
    """Ложная звезда хуже отсутствующей — подсказка в обратную сторону.

    Строка «**Рекомендация: (а).**» вариантом не является и физически лежит в хвосте
    ПОСЛЕДНЕГО пункта. Вывод по расположению абзаца поставил бы звезду на «(б)» —
    то есть ровно на тот вариант, который автор не советовал.
    """
    opts = od.parse_options(CARD_LETTERED)

    assert [o.recommended for o in opts] == [True, False]


def test_a_partly_bold_lettered_list_keeps_every_option():
    """Одна кнопка из трёх хуже, чем ни одной: остальные исчезают молча."""
    opts = od.parse_options(CARD_MIXED_BOLD)

    assert [o.num for o in opts] == ["а", "б", "в"]
    assert [o.recommended for o in opts] == [True, False, False]
    assert "подождать" in opts[1].label
    assert "другая сумма" in opts[2].label


def test_a_label_that_is_only_a_mark_takes_the_sentence_after_the_bold():
    """Кнопка «рекомендую» не называет варианта — и одинакова у всех рекомендованных."""
    opts = od.parse_options(CARD_MARK_ONLY_LABEL)

    assert [o.num for o in opts] == ["а", "б"]
    assert opts[0].recommended is True, "пометка не потеряна вместе с подписью"
    assert opts[0].label.startswith("Разреши доустановить"), opts[0].label
    assert "рекоменд" not in opts[0].label.lower()


# ===========================================================================
# Сторож: он обязан быть ШИРЕ подопечного, а не делить с ним слепое пятно
# ===========================================================================
def test_the_guard_names_a_choice_written_in_a_form_the_parser_never_learned():
    """Форму «А./Б.» разбор не знает НАМЕРЕННО — сторож обязан назвать её сам.

    Иначе следующая незнакомая форма уедет так же тихо, как «(а)/(б)» уехала 19.08.
    """
    assert od.parse_options(CARD_UNKNOWN_LETTER_FORM) == []
    assert od.has_unparsed_options(CARD_UNKNOWN_LETTER_FORM) is True


def test_two_decisions_in_one_card_stay_buttonless_and_are_called_our_defect():
    """Отказ разбора ВЕРЕН (смешать два вопроса нельзя) — но зовётся своим именем."""
    assert od.parse_options(CARD_TWO_DECISIONS) == []
    assert od.has_unparsed_options(CARD_TWO_DECISIONS) is True


def test_a_bold_lettered_choice_is_never_offered_a_blanket_ack():
    """Худший исход дефекта: выбор закрывался бы НЕ выбором.

    Жирная головка пункта разрывала буквенную альтернативу `_CHOICE_TRACE_RE` двумя
    звёздочками ⇒ `looks_like_a_choice` молчал ⇒ карточке с настоящим выбором
    предлагалась кнопка «✅ Принято». Нажатие закрыло бы вопрос «хоронить или
    воскрешать» ответом, которого карточка не предлагала (ADR-075).
    """
    assert od.looks_like_a_choice(CARD_TWO_DECISIONS) is True
    assert od.offers_ack(CARD_TWO_DECISIONS) is False


def test_the_guard_does_not_invent_a_defect_out_of_a_bare_word():
    """Обратный контроль. Сторож, кричащий всегда, — тоже украшение, только шумное."""
    assert od.parse_options(CARD_BARE_WORD) == []
    assert od.has_unparsed_options(CARD_BARE_WORD) is False


def test_the_letter_dialect_does_not_swallow_a_plain_prose_bullet():
    """Голый «- Текст» вариантом не становится: выдуманный выбор запрещён (ADR-075)."""
    body = _HEAD + (
        "- Открыть Cloudflare → домен `earn-defi.com` → раздел DNS.\n"
        "- Найти запись с именем `checkup` и удалить её.\n"
    ) + _TAIL

    assert od.parse_options(body) == []
