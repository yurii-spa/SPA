"""Вердикт теста не решает ОКРУЖЕНИЕ прогона: `SPA_SESSION_*` снимается на время теста.

Авария, по которой сторож написан (26.08, цикл #388, карточка
`inbox-commit-9cb8a7823-krasit-28-testov-zahvata`)
--------------------------------------------------------------------------------
Коммит `9cb8a7823` ввёл в `scripts/check_card_claim.py` fail-CLOSED отказ: захват
карточки под ярлыком без объявленного долгоживущего процесса не состоится
(`UnmeasurableClaim`). «Объявленный долгоживущий процесс» читается из переменной
окружения `SPA_SESSION_PID` — и `claim_card`/`release_card`/`gather` берут его из
окружения ПО УМОЛЧАНИЮ (`_ENV_ANCHOR`).

Дальше произошло ровно то, чего этот репозиторий боится больше красного теста —
**один и тот же sha дал два разных вердикта**:

* Мак под оркестратором (`scripts/agent_orchestrator.sh` экспортирует
  `SPA_SESSION_PID=$$`) — `197 passed`;
* CI (переменной нет) — `28 failed, 169 passed`.

Измерено на `2a9489d84` в чистом дереве, обе стороны, одной командой; разница —
только `env -u SPA_SESSION_PID -u SPA_SESSION_ID`. Пять часов ушло на «почему у
двух открытых PR красный `test`, хотя ни один из них не трогает этот код»:
автор коммита свой прогон видел зелёным и не мог воспроизвести падение.

Хуже красноты: тем же путём **четыре теста стали проходить вхолостую**. Текст
`UnmeasurableClaim` содержит и слово `unchecked`, и `` `stale` ``, и `--takeover` —
поэтому проверки вида `assert "unchecked" in str(exc.value)` продолжали зеленеть
в CI, ловя СОВСЕМ ДРУГОЙ отказ, случившийся на шаг раньше предмета проверки. Тест,
который зелен по неверной причине, хуже отсутствующего: он занимает место.

Что делает сторож
-----------------
Снимает `SPA_SESSION_PID` и `SPA_SESSION_ID` из `os.environ` на время КАЖДОГО теста
и возвращает как было после. Следствие: локальный прогон устроен так же, как прогон
в CI, и «у меня зелено» перестаёт быть свойством машины.

Это НЕ ослабление и не мок: ни одна ветка кода не подменяется. Тест, которому
объявленный процесс нужен по существу, объявляет его САМ и вслух —
`monkeypatch.setenv("SPA_SESSION_PID", str(os.getpid()))` (так уже сделано в классе
«режим автономного цикла» в `test_card_claim_guard.py`), либо подаёт якорь явным
аргументом `self_anchor=` (так уже сделано у `gather` в помощнике `run` там же).
Оба входа остались; закрыт ровно один — МОЛЧАЛИВОЕ наследование окружения.

Почему сторож, а не только починка 28 тестов
--------------------------------------------
Починка закрывает случай, сторож — класс. Любой следующий тест, который тронет
`check_card_claim` / `log_session_change` / `orchestrator_cycle_lock`, унаследовал бы
ту же невидимую зависимость, и следующий разбор снова начался бы с «в CI красный,
у меня зелёный». Родственные правила репозитория (`.claude/rules/deployment.md`,
раздел про фиксированные даты) требуют того же: время и личность сессии — ВХОД
проверки, а не свойство окружения, в котором её запустили.

Положительные контроли — `spa_core/tests/test_ambient_session_identity.py`: они
меряют эффект в ДОЧЕРНЕМ процессе с ЭКСПОРТИРОВАННЫМ `SPA_SESSION_PID`, потому что
в CI переменной нет и проверка «её не видно» была бы зелёной сама по себе, ничего
не проверяя (урок `guard-untested-when-default-state-makes-it-redundant`).

Только stdlib. LLM рядом не стоял.
"""

from __future__ import annotations

import os

import pytest

#: Переменные, которыми оркестратор объявляет личность сессии. Список закрытый и
#: короткий НАМЕРЕННО: сторож снимает ровно то, что делает вердикт зависимым от
#: запускающего, и не трогает остальное окружение прогона.
AMBIENT_SESSION_VARS = ("SPA_SESSION_PID", "SPA_SESSION_ID")


def scrub(environ=None):
    """Снять переменные и вернуть снимок снятого (для восстановления)."""
    environ = os.environ if environ is None else environ
    saved = {}
    for name in AMBIENT_SESSION_VARS:
        if name in environ:
            saved[name] = environ[name]
            del environ[name]
    return saved


def restore(saved, environ=None):
    """Вернуть ровно то, что было снято `scrub` — включая «не было вовсе»."""
    environ = os.environ if environ is None else environ
    for name in AMBIENT_SESSION_VARS:
        if name in saved:
            environ[name] = saved[name]
        else:
            environ.pop(name, None)


@pytest.fixture(autouse=True)
def _no_ambient_session_identity():
    """Прогон не наследует личность сессии оркестратора. Восстановление — всегда.

    Восстанавливаем в `finally`-семантике `yield`: переменные читает не только
    предмет теста, но и сам инструментарий цикла (`log_session_change` пишет ими
    объявления), и оставить прогон без них после последнего теста значило бы
    сломать сессию, которая его запустила.
    """
    saved = scrub()
    try:
        yield
    finally:
        restore(saved)
