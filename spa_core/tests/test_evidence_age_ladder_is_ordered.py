"""Три окна возраста наблюдения — ступени одной лестницы, и порядок обязан держаться.

# LLM_FORBIDDEN

В системе три окна свежести наблюдения, объявленные в трёх разных модулях:

| Окно | Где | Вопрос, на который отвечает | Обоснование |
|---|---|---|---|
| **36 ч** | `allocator._EVIDENCE_MAX_AGE_H` | брать ли в НОВУЮ аллокацию | ADR-060 §3, колонка paper |
| **48 ч** | `analytics.tier_curator.EVIDENCE_MAX_AGE_H` | считать ли доказательством для суждения о ТИРЕ | «двое суток покрывают выходной цикла» (комментарий у строки) |
| **168 ч** | `governance.evidence_staleness.HARD_STALE_H` | ослеп ли протокол насовсем | ADR-167, решение владельца |

**Поправка к моему же утверждению (2026-08-29).** Сначала я записал это как шестой
за день случай «источник правды продублирован» и как «48 ч без ADR». Проверка
показала, что это неверно: обоснование у 48 ч ЕСТЬ — оно написано рядом со строкой,
просто не в ADR. И числа не дублируют друг друга: они отвечают на РАЗНЫЕ вопросы,
и лестница 36 ≤ 48 ≤ 168 осмысленна — сначала перестаём давать новые деньги, потом
перестаём судить о тире, потом признаём протокол ослепшим.

**Что действительно опасно и чего не было:** ступени объявлены порознь и ничем
не связаны. Поднять 36 ч до 60 можно, не тронув 48 — и лестница молча
перевернётся: аллокатор перестанет финансировать позже, чем куратор перестанет
считать наблюдение доказательством. Этот тест держит порядок.
"""
from __future__ import annotations

import pytest

from spa_core.allocator import allocator as _alloc
from spa_core.analytics import tier_curator as _curator
from spa_core.governance import evidence_staleness as _derisk

FUND_H = _alloc._EVIDENCE_MAX_AGE_H
JUDGE_H = _curator.EVIDENCE_MAX_AGE_H
BLIND_H = _derisk.HARD_STALE_H


def test_the_ladder_is_ordered():
    """36 ≤ 48 ≤ 168. Перевёрнутая лестница ломает смысл каждой ступени."""
    assert FUND_H <= JUDGE_H <= BLIND_H, (
        f"порядок нарушен: финансирование {FUND_H} ч, суждение о тире {JUDGE_H} ч, "
        f"слепота {BLIND_H} ч. Перестать давать новые деньги нужно РАНЬШЕ, чем "
        "перестать судить о тире, и раньше, чем признать протокол ослепшим.")


def test_each_rung_is_distinct_enough_to_mean_something():
    """Ступени, слипшиеся в одно число, — это не лестница, а одно правило."""
    assert JUDGE_H > FUND_H, "суждение о тире не может истекать одновременно с финансированием"
    assert BLIND_H >= 2 * JUDGE_H, (
        "признание слепоты обязано быть заметно дальше суждения о тире — иначе "
        "де-риск срабатывает почти одновременно с обычным устареванием")


def test_the_derisk_module_mirrors_the_allocator_and_does_not_fork_it():
    """Мягкое окно де-риск-модуля — ТА ЖЕ цифра, что у аллокатора, а не своя копия."""
    assert _derisk.SOFT_STALE_H == FUND_H


def test_the_curator_rationale_still_stands_next_to_its_number():
    """48 ч — решение с обоснованием. Исчезнет обоснование — исчезнет и право на число."""
    from pathlib import Path
    src = Path(_curator.__file__).read_text(encoding="utf-8")
    i = src.index("EVIDENCE_MAX_AGE_H = 48.0")
    head = src[max(0, i - 400):i]
    assert "выходной цикла" in head, (
        "у 48 ч пропало обоснование, стоявшее рядом со строкой — число стало "
        "необъяснённым, и его надо либо обосновать заново, либо свести к 36 ч")


@pytest.mark.parametrize("name,value,expect", [
    ("финансирование", FUND_H, 36.0),
    ("суждение о тире", JUDGE_H, 48.0),
    ("слепота", BLIND_H, 168.0),
])
def test_the_numbers_are_the_documented_ones(name, value, expect):
    """Перепись на 2026-08-29. Меняется число — меняется и эта таблица, осознанно."""
    assert value == pytest.approx(expect), f"{name}: было {expect}, стало {value}"
