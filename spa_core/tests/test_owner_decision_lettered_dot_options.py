#!/usr/bin/env python3
"""Буквенный пункт С ТОЧКОЙ — «**А. Закрепить основной рынок.**» — это ВАРИАНТ.

Каждый тест здесь — положительный контроль над живой карточкой, которая уже уехала
владельцу без кнопок или с ЧАСТЬЮ кнопок.

Замер 2026-09-05 (цикл #493) по живой очереди `origin/main` 176e57b47, 233 карточки
решений, секция «Что от тебя нужно»: формой «**Б. …**» написаны ЧЕТЫРЕ карточки, и
разбор не понимал её ни в одном диалекте —

    owner-decision-chisla-treka-na-saite-ne-podtverzhdayuts    написано 2, разобрано 0
    owner-decision-dannye-treka-v-git-fail-dokazatelstv-zam    написано 3, разобрано 0
    owner-decision-sorok-protsentov-knigi-stoyat-na-rynke-k    написано 3, разобрано 0
    owner-decision-storozh-propuschennogo-tsikla-molchit-do    написано 3, разобрано 1

Последняя — ХУДШИЙ исход и причина, по которой диалект выучен ВМЕСТЕ со сверкой
«написано ↔ взято»: владелец видел ОДНУ кнопку там, где предложено три, а сторож
`has_unparsed_options` при этом молчал — он спрашивал «разобрано хоть что-то?», и
непустой список закрывал ему рот. Отсутствие кнопок видно; потерянный пункт — нет.

Живой экземпляр, пойманный в тот же день: карточка `…sorok-protsentov…` ушла владельцу
05.09 16:17Z (message 9653) с `options: []`, `buttons: false` — три варианта прозой.

Цена расширения ИЗМЕРЕНА, а не оценена: по всем 233 карточкам вердикт меняется ровно
у ТРЁХ (две получают полный набор кнопок, одна меняет тихую единственную кнопку на
громкий отказ). Ложных срабатываний замер не дал ни одного.
"""
from __future__ import annotations

from spa_core.telegram import owner_decisions as od

HEAD = """---
trackerStatus:
  type: owner-decision
title: Проверочная карточка
status: needs-owner
---

## Что случилось и почему это важно

Одна строка о сути.

## Что от тебя нужно

"""

TAIL = """

## Как понять, что готово

Одна строка.

## Что будет после

Одна строка.
"""


def _card(section: str) -> str:
    return HEAD + section + TAIL


class TestLetteredDotIsAnOption:
    """Подпись ВНУТРИ жирного: «**А. Закрепить.**» — форма живой карточки про Aave."""

    def test_three_options_are_read(self):
        body = _card(
            "**А. Закрепить основной рынок Aave навсегда (моя рекомендация).**\n"
            "Мы жёстко привязываем ключ к основному рынку.\n\n"
            "**Б. Закрепить И запретить брать рынки с чужим токеном.**\n"
            "То же, что А, плюс общая защита.\n\n"
            "**В. Ничего не менять, оставить как есть.**\n"
            "Сторож теперь называет проблему правильно.\n"
        )
        opts = od.parse_options(body)
        assert [o.num for o in opts] == ["А", "Б", "В"]
        assert opts[0].label == "Закрепить основной рынок Aave навсегда"

    def test_recommendation_marks_the_right_option(self):
        """Звезда стои́т у того, кого агент советует, а не у последнего абзаца."""
        body = _card(
            "**А. Закрепить основной рынок (моя рекомендация).**\nПояснение.\n\n"
            "**Б. Ничего не менять.**\nПояснение.\n"
        )
        opts = od.parse_options(body)
        assert [o.recommended for o in opts] == [True, False]

    def test_label_after_the_bold_is_read_too(self):
        """«- **B.** Оставить как есть…» — подпись стои́т ЗА жирным, а не внутри."""
        body = _card(
            "- **B.** Оставить как есть, но признать это явно: числа подтверждает владелец.\n"
            "- **C.** Заморозить обновление чисел на сайте до решения.\n"
        )
        opts = od.parse_options(body)
        assert [o.num for o in opts] == ["B", "C"]
        assert opts[0].label.startswith("Оставить как есть")


class TestPartialReadRefusesLoudly:
    """Прочитали НЕ ВЕСЬ перечень ⇒ не показываем НИ ОДНОЙ кнопки и говорим об этом.

    Показать часть перечня хуже, чем не показать ничего: владелец нажмёт первую
    попавшуюся, карточка закроется, а непоказанные варианты умрут молча.
    """

    def test_unreadable_item_kills_all_buttons_and_names_itself(self):
        """Метка ЕСТЬ, а подписи нет — пункт написан, но не прочитан.

        Мера здесь — «сколько пунктов НАПИСАНО этой формой» против «сколько ВЗЯТО».
        Пункт без метки вовсе (просто «- **Текст.**») в счёт написанных НЕ идёт и
        кнопок не отменяет: считать его вариантом значило бы выдумать владельцу выбор
        (ADR-075), и обратный контроль на это стои́т в `TestNoInventedChoice`.
        """
        body = _card(
            "- **A. Оставить как есть.** Ничего не делаем.\n"
            "- **B.**\n"
            "- **C. Вычислять час автоматически.** Добавляет зависимость.\n"
        )
        assert od.parse_options(body) == []
        assert od.has_unparsed_options(body) is True, (
            "отказ обязан НАЗЫВАТЬ себя: иначе владелец прочтёт «выбора не предлагали» "
            "под карточкой, где выбор написан"
        )

    def test_two_readable_items_alone_still_give_buttons(self):
        """Обратный контроль к предыдущему: без НЕПРОЧИТАННОГО пункта отказа нет.

        Без этой пары проверка выше была бы зелёной и от кода, который отказывает
        ВСЕГДА, — то есть не измеряла бы ничего.
        """
        body = _card(
            "- **A. Оставить как есть.** Ничего не делаем.\n"
            "- **C. Вычислять час автоматически.** Добавляет зависимость.\n"
        )
        assert [o.num for o in od.parse_options(body)] == ["A", "C"]

    def test_watchdog_sees_the_dialect_even_when_parsing_fails(self):
        """Сторож не делит слепое пятно с разбором.

        Дубль номера закрывает карточку целиком (несколько вопросов) — и именно тогда
        сторож обязан заговорить.
        """
        body = _card(
            "- **A. Первый вопрос, вариант один.** Пояснение.\n"
            "- **B. Первый вопрос, вариант два.** Пояснение.\n\n"
            "- **A. Второй вопрос, вариант один.** Пояснение.\n"
            "- **B. Второй вопрос, вариант два.** Пояснение.\n"
        )
        assert od.parse_options(body) == []
        assert od.has_unparsed_options(body) is True


class TestNoInventedChoice:
    """ADR-075: выдумывать владельцу выбор ЗАПРЕЩЕНО — метка и есть то, что отличает
    пункт перечня от обычного жирного пояснения."""

    def test_plain_bold_paragraph_is_not_an_option(self):
        body = _card(
            "**Это просто жирное пояснение без метки.**\n"
            "**И ещё одно такое же.**\n"
        )
        assert od.parse_options(body) == []
        assert od.has_unparsed_options(body) is False

    def test_numbered_point_is_not_a_lettered_option(self):
        """«**П.1 — …**» — НУМЕРОВАННЫЙ пункт разбора, а не буква выбора.

        Живой предмет: `own-21-agent-cleanup-decisions`. За точкой стои́т цифра, значит
        метка не буквенная; требование «после точки пробел или закрывающее `**`» и есть
        то, что их разводит.
        """
        body = _card(
            "- **П.1 — три агента выгружены:** подробности.\n"
            "- **П.2 — агент переподчинён:** подробности.\n"
        )
        assert od.parse_options(body) == []

    def test_initials_in_prose_do_not_become_options(self):
        """Одиночная буква с точкой ВНУТРИ строки — не метка перечня."""
        body = _card(
            "Мы сверились с записью А. Иванова и с датой.\n"
            "Ответ нужен один: продолжать или нет.\n"
        )
        assert od.parse_options(body) == []


class TestLiveCorpusRegression:
    """Формы, снятые с ЖИВЫХ карточек дословно — чтобы диалект не разучился."""

    def test_aave_card_shape_yields_three_buttons(self):
        body = _card(
            "Выбери один вариант:\n\n"
            "**А. Закрепить основной рынок Aave навсегда (моя рекомендация).**\n"
            "Мы жёстко привязываем `aave_v3` к основному рынку.\n"
            "*Почему рекомендую:* это ровно тот рынок, в котором мы и считали, что стоим.\n\n"
            "**Б. Закрепить основной рынок И запретить второй части системы брать рынки "
            "с чужим токеном.**\n"
            "То же, что А, плюс общая защита.\n\n"
            "**В. Ничего не менять, оставить как есть.**\n"
            "*Чем плохо:* «Umbrella» платит частью токенами.\n"
        )
        opts = od.parse_options(body)
        assert len(opts) == 3
        assert [o.num for o in opts] == ["А", "Б", "В"]
        assert opts[0].recommended is True


class TestDialectDoesNotLeakIntoNeighbours:
    """Две проверки ПРОВОДКИ — без них правку можно сломать, не покраснев.

    Обе написаны после мутационного замера: первые редакции этого файла зеленели и на
    коде, где обе связи сняты, — то есть проверяли не проводку, а совпадение исходов.
    """

    def test_numbered_point_does_not_disable_real_options(self):
        """«**П.1 — …**» стои́т РЯДОМ с настоящими вариантами и не отменяет их.

        Мера «сколько написано» обязана считать метку-БУКВУ, а не любую букву с точкой:
        «П.1» — нумерованный пункт разбора, и если счёт примет его за написанный
        вариант, перечень объявится прочитанным не полностью и владелец потеряет ВСЕ
        кнопки. Живой предмет формы — `own-21-agent-cleanup-decisions`.
        """
        body = _card(
            "- **П.1 — три агента выгружены:** это уже сделано, менять нечего.\n\n"
            "- **A. Оставить как есть.** Ничего не делаем.\n"
            "- **B. Опустить порог.** Тревога приходит раньше.\n"
        )
        assert [o.num for o in od.parse_options(body)] == ["A", "B"]

    def test_steps_inside_an_option_do_not_become_options(self):
        """Внутри абзаца варианта пишут ШАГИ «1. … 2. …» — это не выбор владельца.

        Явный диалект в секции обязан выключать догадку по голому номеру; иначе
        владелец получит смесь «вариант A», «вариант B», «шаг 1», «шаг 2».
        """
        body = _card(
            "- **A. Оставить как есть.** Ничего не делаем.\n"
            "- **B. Починить.** Порядок работ:\n"
            "1. прогнать приёмку;\n"
            "2. переустановить агента.\n"
        )
        assert [o.num for o in od.parse_options(body)] == ["A", "B"]
