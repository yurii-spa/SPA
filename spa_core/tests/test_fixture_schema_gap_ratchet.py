"""Храповик заказа G697 п. 2: объявленный путь, которого фикстура НЕ НЕСЁТ.

# LLM_FORBIDDEN

Форма, за которую платили ЧЕТЫРЕ цикла подряд (#832, #834, #837, #841): в
`_READ_SCHEMA` шага 0-офис объявляется новый раздел, фикстура соседа его не
получает, и ЧУЖАЯ сцена краснеет не о своём предмете. Каждый раз это находили
прогоном и чинили по одному; заказ потребовал мерить население.

Замер 2026-10-12 (ADR-701, заказ G699 п. 1), ПЕРЕМЕРЕННЫЙ исправленным
прибором: площадок двери **121** — фикстура разрешена у 78, имя не объявлено у
16, документ собран ВЫЗОВОМ у 18, НЕ ИЗМЕРЕНО 9, нераскрытых вложенных пар 34.
**Население класса — 0 площадок**, и это не отмена класса, а его РАЗБОР: база
пуста, поэтому ЛЮБОЙ новый ключ краснеет сразу.

Как 18 ключей разошлись по ПРИРОДЕ (заказ G699 п. 1, он же остаток ADR-698):

* **ВРЕД — фикстура отстала от БЕЗУСЛОВНОГО ключа производителя (3 ключа).**
  Лечится ЗНАЧЕНИЕМ. `test_artifact_stamp_clock_doors.py::_doc` ОБЕЩАЛ
  докстрингом «форму, которую РЕАЛЬНО пишет `build_report`», а несла она 1
  объявленный путь из 9 — теперь форму СОБИРАЕТ сам `build_report`, и
  разойтись с ним она не может по построению. `capital_evidence_coverage.json`
  получил 7 путей, `owner_answer_delivery` — 6 площадок (тот же порядок, что у
  `_bridge` в #247).
* **ПРЕДМЕТ — куцый документ и ЕСТЬ смысл сцены.** Помечено
  `# SCHEMA-GAP-OK: <причина>`, освобождений 37 и каждое ВИДНО. Самые частые
  природы: документ третьего исхода (`status=UNMEASURED`) у семьи
  `*_wiring.py`, где полную схему на документе НАСТОЯЩЕГО производителя
  проверяет соседняя сцена того же файла; ДОСЛОВНЫЕ байты прод-снимка
  (`LOOP_HEALTH_PROD`, 27.08 — до доставки `closure_drift`), которым значение
  отменило бы положительный контроль; и ключ, который производитель пишет
  УСЛОВНО (`censuses`: `if censuses is not None`), то есть его отсутствие
  законно по построению.
* **ЛОЖНОЕ ОБВИНЕНИЕ — четвёртая форма объединения (1 ключ, 34 пары).**
  Документ разрешён до словаря, а ВЛОЖЕННЫЙ контейнер собран вызовом:
  `test_list_candidate_readers.py` строит `counts` НАСТОЯЩИМ помощником
  производителя (`census.tally(ROWS)`), разбор ставит там `LEAF`, и
  `has_path` отвечает `False` — не «ключа нет», а «внутрь заглянуть не
  удалось». Выведено в СВОЙ третий исход с СВОИМ потолком: без потолка это
  стало бы лазейкой наружу (собери фикстуру вызовом — и сторожа нет).

Первая редакция прибора (#842) на том же дереве отвечала **47 площадок · 301
пара · 21 ключ**, ADR-699/700 исправили её до 40 · 199 · 18, и ни одно из этих
чисел не было ни нижней, ни верхней границей — все три были СМЕСЬЮ находки и
ошибки разбора.

База может **только уменьшаться**. Дописывать в неё, чтобы погасить падение,
ЗАПРЕЩЕНО (инв. #16, тот же порядок, что у `frozen_date_baseline.json`,
`design_status_baseline.json`, `site_numbers_baseline.json`). Честный выход из
класса два, и оба использованы выше: дать фикстуре значение ЛИБО, если куцый
документ и есть предмет сцены, пометить площадку
`# SCHEMA-GAP-OK: <причина>` — освобождение видно, считается и печатается.

**Две причины из 37 опираются на предмет СЦЕНЫ, а не на природу документа**, и
это сказано вслух: `test_outcomes_completeness.py` (общий помощник, часть
зовущих снимает раздел нарочно) и `test_list_day_axis.py` (сцена про ОСЬ ДНЯ;
прочие оси того же артефакта — предмет своих файлов). Они слабее остальных;
дать им значение означало бы привязать сцену к пяти чужим производителям.
"""
from __future__ import annotations

import importlib
import json
from pathlib import Path

from spa_core.tests import _fixture_schema_gap as gap

_ROOT = Path(__file__).resolve().parents[2]
_BASELINE = Path(__file__).with_name("fixture_schema_gap_baseline.json")


def _office():
    """Шаг 0-офис — ПАКЕТНЫМ импортом, не загрузкой по пути (урок #820)."""
    return importlib.import_module("scripts.consume_office_reports")


def _census() -> gap.Census:
    office = _office()
    return gap.measure(schema=office._READ_SCHEMA, has_path=office._has_path,
                       root=str(_ROOT))


def _baseline() -> dict:
    return json.loads(_BASELINE.read_text(encoding="utf-8"))


def test_the_measurement_had_a_subject_at_all() -> None:
    """Ноль площадок — «НЕ ИЗМЕРЕНО», а не «населения нет» (инв. #17)."""
    census = _census()
    assert census.files_scanned > 0, (
        "НЕ ИЗМЕРЕНО: ни один тест-файл не зовёт дверь "
        f"`{gap.DOOR}` — предмета у замера нет, и нулём это не считается")
    assert census.sites, (
        "НЕ ИЗМЕРЕНО: ни одна площадка двери не разрешена до документа — "
        "«не несомых путей 0» на нуле сравнений есть подделка доказательства")


def test_every_scanned_file_was_actually_parsed() -> None:
    """Неразобранный файл обязан падать ГРОМКО, а не выпадать из населения."""
    broken = [row for row in _census().unmeasured
              if row[1].startswith(("file_unparsed", "file_unreadable"))]
    assert not broken, f"НЕ ИЗМЕРЕНО: файлы не прочитаны/не разобраны: {broken}"


def test_a_marker_without_a_reason_is_not_an_exemption() -> None:
    """Записка без причины освобождением не является (урок `FROZEN-DATE-OK`)."""
    bare = _census().marker_without_reason
    assert not bare, (
        "пометка `SCHEMA-GAP-OK` без причины: причина — часть объявления, "
        f"«и так понятно» причиной не является: {bare}")


def test_the_unmeasured_share_did_not_grow() -> None:
    """Потеря охвата прибором — тоже регресс, и молчать о ней нельзя."""
    census = _census()
    ceiling = _baseline()["unmeasured_max"]
    assert len(census.unmeasured) <= ceiling, (
        f"НЕ ИЗМЕРЕНО выросло: {len(census.unmeasured)} > {ceiling}. "
        "Новая площадка двери не разрешается прибором — её документ надо "
        "собрать так, чтобы разбор его видел, либо расширить прибор; "
        "поднимать потолок запрещено.\n"
        + "\n".join(f"  {where}: {why}" for where, why in census.unmeasured))


def test_no_key_carries_more_unfed_paths_than_the_baseline() -> None:
    """Главный храповик: ключ не вправе вырасти, новый ключ не вправе быть."""
    report = gap.compare(_census(), _baseline()["keys"])
    assert not report, (
        "объявленный путь `_READ_SCHEMA` не несёт фикстура того же "
        "производителя (заказ G697 п. 2, ADR-698). Лечится ЗНАЧЕНИЕМ в "
        "фикстуре либо пометкой `# SCHEMA-GAP-OK: <причина>`, если куцый "
        "документ и есть предмет сцены. ДОПИСЫВАТЬ В БАЗУ ЗАПРЕЩЕНО.\n"
        + "\n".join(report))


def test_the_unresolved_nested_share_did_not_grow() -> None:
    """Исход «контейнер не раскрыт» ОГРАНИЧЕН — иначе он стал бы лазейкой.

    ADR-701 вывел 34 пары из населения, назвав их третьим исходом. Без
    потолка это открыло бы честный выход наружу: достаточно собрать фикстуру
    вызовом, и объявленный путь перестанет стеречь кто-либо — молча и с
    зелёным тестом. Потолок делает цену видимой: новая нераскрытая пара
    краснеет СРАЗУ, а чинится ровно так же, как росла база, — либо фикстура
    строит контейнер так, чтобы разбор его видел, либо прибор учится его
    раскрывать. Поднимать потолок запрещено (инв. #16, тот же порядок, что у
    `unmeasured_max`).
    """
    census = _census()
    ceiling = _baseline()["nested_unresolved_max"]
    assert len(census.nested_unresolved) <= ceiling, (
        f"нераскрытых вложенных пар стало больше: "
        f"{len(census.nested_unresolved)} > {ceiling}. Это НЕ «путь не "
        f"несётся» и НЕ «документа нет» — разбор не заглянул внутрь "
        f"контейнера, и объявленный путь остался без сторожа.\n"
        + "\n".join(f"  {where} [{art}] {path} — не раскрыт родитель "
                    f"`{parent}`"
                    for where, art, path, parent in census.nested_unresolved))
