"""Храповик: `docs/STATE.md` может только сокращаться, но не расти.

**Ловушка.** Файл сам объявляет предел «~150 строк» в собственной шапке и держал **1920** —
превышение в 13 раз. Предел написан не для красоты: `CLAUDE.md` §«Протокол сессии» делает
`docs/STATE.md` обязательным чтением в начале КАЖДОЙ сессии, интерактивной и автономной. То
есть это самый часто читаемый файл репозитория, и каждая сессия платила за 1920 строк, из
которых ~1700 были хроникой циклов, а не состоянием.

**Почему предел не соблюдался.** Он ни на что не опирался. Файл ведётся дописыванием СВЕРХУ,
каждый цикл добавляет свою запись — и ни один цикл не был обязан посмотреть, во что файл
превратился. Правило, которое все нарушают, перестаёт быть правилом: авторы карточек #127 и
#130 оба честно записали, что нарушили его сами, — и оба были правы.

**Почему храповик, а не жёсткий лимит.** Жёсткая проверка `<= 150` покраснела бы в момент,
когда очередная сессия дописала бы 151-ю строку по делу, — и её бы отключили. Это ровно та
cry-wolf-ошибка, за которую репозиторий уже платил (см. `test_frozen_date_ratchet.py`).
Храповик разрешает состояние «сейчас», запрещает ухудшение и вознаграждает сокращение:
починил — опусти базу, и она станет новым потолком.

**Что храповик НЕ проверяет** (честная граница, а не недосмотр): содержательность. Файл из
111 строк воды пройдёт так же, как файл из 111 строк по делу. Длина — прокси, и она выбрана
потому, что измерима без суждения; за смысл отвечает раздел «Правила задач» протокола и
ревью, а не эта проверка.

Сокращение 1920 → 111 выполнено циклом #142; полный дословный снимок файла до сокращения —
`docs/journal/STATE-archive-2026-08-07.md` (ни одна строка не выброшена).
"""
from __future__ import annotations

from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parents[2]
_STATE = _REPO_ROOT / "docs" / "STATE.md"

#: Потолок длины. Только ВНИЗ.
#:
#: История базы (менять эту цифру можно лишь в сторону уменьшения):
#:   1920 → 150  (цикл #142, 2026-08-07): хроника циклов вынесена в `docs/journal/`,
#:                 фактическая длина после сокращения — 111 строк.
#:
#: База стоит на 150, а не на фактических 111, намеренно: это ЗАЯВЛЕННЫЙ файлом предел, и
#: запас в 39 строк — рабочее место для сессий, которым есть что сказать по существу. База,
#: приколоченная вплотную к текущей длине, покраснела бы на первой же честной правке и
#: выучила бы всех её двигать — то есть перестала бы быть храповиком.
STATE_MAX_LINES = 150

#: Предел, который файл объявляет о себе сам. Проверяется отдельно: заявление и проверка
#: обязаны говорить одно и то же, иначе одно из двух — ложь, и неизвестно какое.
DECLARED_LIMIT_TEXT = "**Максимум ~150 строк.**"


def _line_count(path: Path) -> int:
    """Число строк файла. Хвостовой перевод строки не считается лишней строкой."""
    text = path.read_text(encoding="utf-8")
    if text.endswith("\n"):
        text = text[:-1]
    return len(text.split("\n"))


def test_state_md_stays_within_the_ratchet():
    """`docs/STATE.md` не длиннее базы. Растёт — значит, хроника снова течёт в файл состояния."""
    actual = _line_count(_STATE)
    assert actual <= STATE_MAX_LINES, (
        f"docs/STATE.md разросся до {actual} строк при базе {STATE_MAX_LINES}.\n"
        f"Это не «подвинь базу»: база двигается ТОЛЬКО вниз. Хроника цикла — в "
        f"docs/journal/<неделя>.md; в STATE.md пишется только то, что меняет ответ на "
        f"вопрос «что делать дальше».\n"
        f"Если сокращать нечего и рост по делу — это решение, а не умолчание: карточка "
        f"needs-owner (инвариант #16 по духу — не ослаблять сторожа молча)."
    )


def test_declared_limit_and_enforced_limit_agree():
    """Заявленный в шапке предел и проверяемый — одно и то же число.

    Положительный контроль к самой базе: если кто-то поднимет `STATE_MAX_LINES`, не тронув
    шапку (или наоборот), проверка покраснеет. Именно расхождение между «файл говорит ~150»
    и «никто не мерил» и позволило дорасти до 1920.
    """
    head = _STATE.read_text(encoding="utf-8").split("\n")[:12]
    assert any(DECLARED_LIMIT_TEXT in line for line in head), (
        f"В шапке docs/STATE.md нет заявления предела {DECLARED_LIMIT_TEXT!r}. "
        f"Проверка и заявление обязаны совпадать — иначе одно из них врёт."
    )
    assert STATE_MAX_LINES == 150, (
        "База разошлась с числом, объявленным в шапке STATE.md (~150). "
        "Меняешь одно — меняй оба, и только вниз."
    )


def test_chronicle_left_the_file_and_is_not_lost():
    """Снимок до сокращения лежит в журнале и содержит записи, которых больше нигде нет.

    Не косметика. Замер `scripts/audit_state_journal_coverage.py` показал: у 18 записей
    STATE номера циклов, которых в заголовках `docs/journal/` НЕТ (#2, #7, #16, #17, #19,
    #28, #29, #38–#40, #42–#44, #46–#48) — их записи в журнале БЫЛИ и были стёрты теми
    12 молчаливыми перезаписями, что намерил цикл #139. Для этих циклов STATE.md оставался
    последней копией, и «просто удалить» означало бы дописать тринадцатую потерю.
    """
    archive = _REPO_ROOT / "docs" / "journal" / "STATE-archive-2026-08-07.md"
    assert archive.exists(), (
        f"Нет {archive.relative_to(_REPO_ROOT)} — снимок STATE.md до сокращения. "
        f"Без него сокращение перестаёт быть переносом и становится потерей."
    )
    text = archive.read_text(encoding="utf-8")
    # Записи циклов, у которых в журнале собственной записи нет: архив — единственный носитель.
    for cycle in ("#48", "#44", "#40", "#29", "#17", "#7"):
        assert f"{cycle}" in text, (
            f"В снимке нет упоминания цикла {cycle}, а в заголовках docs/journal/ его тоже нет — "
            f"значит запись потеряна безвозвратно."
        )


@pytest.mark.parametrize("bad_length", [151, 400, 1920])
def test_ratchet_would_catch_a_regrown_file(tmp_path, bad_length):
    """Положительный контроль: на файле длиннее базы проверка ОБЯЗАНА краснеть.

    Проверка, никогда не видевшая настоящей поломки, — украшение
    (`.claude/rules/deployment.md`). 1920 в наборе — не круглое число, а реальная длина
    файла в момент, когда карточку взяли в работу.
    """
    fake = tmp_path / "STATE.md"
    fake.write_text("\n".join(["строка"] * bad_length), encoding="utf-8")
    assert _line_count(fake) == bad_length
    assert not (_line_count(fake) <= STATE_MAX_LINES), (
        "Файл длиннее базы прошёл бы храповик — сторож не работает."
    )


def test_ratchet_passes_a_short_file(tmp_path):
    """Контроль в обратную сторону: короткий файл проходит.

    Без него «краснеет всегда» сошло бы за доказательство работоспособности.
    """
    fake = tmp_path / "STATE.md"
    fake.write_text("\n".join(["строка"] * 149), encoding="utf-8")
    assert _line_count(fake) <= STATE_MAX_LINES
