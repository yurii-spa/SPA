"""Свободные порты петли — РАЗНЫЕ ПО ПОСТРОЕНИЮ, а не по везению (ADR-1030).

Класс, ради которого написан модуль, ИЗМЕРЕН на живой аварии, а не придуман.
`spa_core/tests/test_mission_server.py` измерял свободный порт так:

    with socket.socket(AF_INET, SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]          # сокет ЗАКРЫТ выходом из `with`

Одна такая проба честна: номер действительно был свободен у той же двери, которой
потом свяжется сервер. Но **ДВЕ независимые пробы могут вернуть ОДИН И ТОТ ЖЕ
номер** — первый сокет к моменту второй пробы уже закрыт, и ОС вправе выдать его
снова. Сцена, которой нужны ДВА разных порта (локальный слушатель и публичный),
опиралась на «они разные» как на предпосылку, и предпосылку эту не обеспечивал
никто: `mission_server.serve` fail-CLOSED отказывает при равенстве —

    BundleError: public_port 50024 collides with the local listener port 50024

Это ровно то падение, которое пришло в контрольный прогон `43831179477` (шард 3,
фаза `setUp`, `spa_core/studio_os/mission_server.py:718`) и исчезло из следующего
прогона `43845563466` при НЕИЗМЕННЫХ байтах `mission_server`. Вердикт теста был
свойством того, какой номер ОС выдала ДВАЖДЫ, — то есть ни дефектом кода сервера,
ни свойством раннера (род `runner_environment`, ADR-913/915, объявляет «красен в
CI и ЗЕЛЕН на своём дереве»; здесь на своём дереве достижимы ОБА вердикта, и
положительный контроль воспроизводит красный одним входом).

**Дверь здесь ОДНА и правило у неё одно.** :func:`free_ports` держит все сокеты
открытыми ОДНОВРЕМЕННО: пока сокет жив, ОС не может отдать его номер второму, и
различность становится свойством ПОСТРОЕНИЯ, а не удачи. :func:`free_port` — тот
же вызов с ``count=1``, а не вторая копия правила.

**Чего эта дверь НЕ закрывает** (и нулём это не считается): номер, измеренный
свободным в момент T, может быть занят кем-то другим к моменту `bind()` в T+δ —
это ДРУГАЯ ось («гонка замера и связывания»), её население НЕ ИЗМЕРЕНО, и
закрыть её могла бы только передача самого СОКЕТА, а не номера.
"""
from __future__ import annotations

import socket

#: Петля — единственный адрес, на котором агентам флота разрешено слушать
#: (`.claude/rules/deployment.md`, п. 8 «Обязательного»).
LOOPBACK = "127.0.0.1"


class PortsNotMeasured(RuntimeError):
    """Третий исход (инв. #17): столько РАЗНЫХ номеров у двери взять не удалось.

    Не ноль, не дубль молча и не скип: предпосылка сцены НЕ ОБЕСПЕЧЕНА, и тест,
    который этого не скажет вслух, будет судить о занятом номере как о свободном
    (тот же порядок, что у `.claude/rules/deployment.md` § «ЛИЧНОСТЬ ПРОЦЕССА»:
    не нашли свободного ⇒ падать ГРОМКО).
    """


def _bind_loopback(host: str = LOOPBACK) -> socket.socket:
    """ОДИН связанный сокет на порту, выбранном ОС. Отдаётся ОТКРЫТЫМ намеренно.

    Закрыть его — работа :func:`free_ports`, и только ПОСЛЕ того, как измерены
    все номера набора: в этом и состоит различность по построению.
    """
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        sock.bind((host, 0))
    except OSError:
        sock.close()
        raise
    return sock


def free_ports(count: int = 1, *, host: str = LOOPBACK, bind=_bind_loopback) -> list[int]:
    """``count`` РАЗНЫХ свободных портов петли, измеренных у той же двери.

    ``bind`` — дверь к ОС ВХОДОМ, а не окружением: без неё контроль мог бы
    проверить только «сегодня номера разошлись», то есть отвечал бы на вопрос
    «что сейчас у этой машины», а не «цела ли проводка» (`.claude/rules/
    deployment.md`, § про инъекцию).
    """
    want = int(count)
    if want < 1:
        raise PortsNotMeasured(f"портов обязано быть ≥ 1, запрошено {count!r}")

    held: list = []
    try:
        for _ in range(want):
            held.append(bind(host))
        ports = [sock.getsockname()[1] for sock in held]
    finally:
        for sock in held:
            sock.close()

    if len(set(ports)) != want:
        raise PortsNotMeasured(
            f"дверь выдала повторяющийся номер при ОДНОВРЕМЕННО открытых сокетах: {ports} — "
            "предпосылка «номера разные» НЕ ОБЕСПЕЧЕНА. Вернуть дубль молча значило бы отдать "
            "сцене ровно ту пару, на которой fail-CLOSED сервера откажет, и назвать это замером")
    return ports


def free_port(*, host: str = LOOPBACK, bind=_bind_loopback) -> int:
    """Один свободный порт — ТЕМ ЖЕ правилом, что набор, и не его копией."""
    return free_ports(1, host=host, bind=bind)[0]
