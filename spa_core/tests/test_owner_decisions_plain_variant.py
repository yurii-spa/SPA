#!/usr/bin/env python3
"""«Вариант 1 — …» БЕЗ жирного читается, а не пропадает (#351).

КАЖДЫЙ тест здесь — положительный контроль ИЗМЕРЕННОЙ аварии, а не украшение.

**Что случилось.** `own-2026-08-22-snyat-changelog-so-saita` — живой `needs-owner`,
поднятый на `origin/main` из открытого PR #35. Прогон настоящего разбора по этой самой
карточке (цикл #351):

    looks_like_a_choice   -> True     ← это ВЫБОР
    has_unparsed_options  -> True     ← сторож честно говорит «варианты есть, не разобрал»
    parse_options         -> []       ← кнопок не будет

Владелец получил бы «⚠️ варианты в карточке есть, но я не смог собрать из них кнопки…
заведи мне это как дефект» — то есть просьбу починить нас же вместо ответа на вопрос.

**Форма — тот же ЯВНЫЙ диалект, что и жирный, минус оформление.** Автор назвал вариант
вариантом: «Вариант 1 — да, убрать страницу…». Жирное выделение — оформление ровно как
маркер списка и разделитель, про которые модуль уже сказал: «выбор владельца от них не
зависит и пропадать по ним не должен». Показательно, что СТОРОЖ (`_OPTION_MENTION_RE`)
жирного и не требует: он видел выбор там, где разбор его не видел, — расхождение между
сторожем и подопечным и есть источник этого сообщения.

**Цена измерена, а не оценена** (журнал `2026-W34.md`, цикл #351): по всей живой очереди
(609 карточек с `origin/main` 3fe14cd4e) кнопки ПОЯВЛЯЮТСЯ у 2 карточек, ПРОПАДАЮТ у 0,
звезда рекомендации не переезжает НИ У ОДНОЙ, `has_unparsed_options` меняется ровно у тех
же двух — True → False, то есть сторож и разбор сошлись.

**Побочно закрыт мусор на кнопке.** Абзац варианта переносится, разбор идёт построчно ⇒
подпись обрывалась посреди скобки: «…с сайта (рекомендую: ты это уже решил в чате».
Пометка из НЕЗАКРЫТОЙ скобки не вычищалась (`_RECOMMEND_PAREN_RE` требует закрывающей) —
и слово «рекомендую» уезжало владельцу В ПОДПИСИ варианта. Замер по корпусу: подписи
чище у 13 карточек, флаг рекомендации не изменился ни у одной.

Время в тестах не участвует: разбор — чистая функция от текста.
"""
from __future__ import annotations

from spa_core.telegram import owner_decisions as od

_HEAD = ("## Что случилось и почему это важно\n\n"
         "Страница «Журнал изменений» показывает июль четвёртую неделю.\n\n"
         "## Что от тебя нужно\n\n")
_TAIL = "\n\n## Как понять, что готово\n\nСтраницы `/changelog` на сайте нет.\n"


def _card(section: str) -> str:
    return _HEAD + section + _TAIL


# ===========================================================================
# 1. Ядро аварии: живая карточка PR #35
# ===========================================================================
_REAL = _card(
    "Ответь реплаем на это сообщение номером варианта:\n\n"
    "Вариант 1 — да, убрать страницу «Changelog» с сайта (рекомендую: ты это уже решил в чате,\n"
    "карточка — формальная подпись для сторожа).\n\n"
    "Вариант 2 — передумал, страницу оставить (тогда её надо оживлять отдельной задачей).\n"
)


def test_the_real_card_from_pr35_gets_its_buttons():
    opts = od.parse_options(_REAL)

    assert [o.num for o in opts] == ["1", "2"]
    assert opts[0].label == "да, убрать страницу «Changelog» с сайта", (
        "подпись обязана быть целой фразой, а не обрывком до переноса строки")
    assert opts[0].recommended is True, "автор пометил первый вариант рекомендованным"
    assert opts[1].recommended is False


def test_the_sentinel_and_the_parser_now_agree():
    """Расхождение сторожа с подопечным и есть то сообщение, что уезжало владельцу."""
    assert od.looks_like_a_choice(_REAL) is True
    assert od.parse_options(_REAL), "выбор написан — он обязан быть прочитан"
    assert od.has_unparsed_options(_REAL) is False, (
        "«варианты есть, но кнопок я не собрал» после разбора — ложь о самих себе")


# ===========================================================================
# 2. Обратные контроли: новая форма не должна ничего ломать
# ===========================================================================
def test_the_bold_dialect_is_not_hijacked_by_the_plain_one():
    """У жирной формы подпись живёт в `label`; перепутать — отправить не тот текст."""
    bold = _card("- **Вариант 1 — Оживить фиды вне Ethereum.** Подробности ниже.\n"
                 "- **Вариант 2 — Оставить как есть.** Тогда кэш стоит осознанно.\n")

    opts = od.parse_options(bold)

    assert [(o.num, o.label) for o in opts] == [
        ("1", "Оживить фиды вне Ethereum"), ("2", "Оставить как есть")]


def test_steps_inside_a_plain_variant_are_not_read_as_options():
    """Замер #338 на новом диалекте: внутри варианта пишут ШАГИ, и они не варианты."""
    card = _card(
        "Вариант 1 — доставить решение на флот. Для этого:\n"
        "1. прогнать acceptance;\n"
        "2. переустановить агента;\n"
        "3. сверить коды выхода.\n\n"
        "Вариант 2 — отложить до возвращения владельца.\n")

    opts = od.parse_options(card)

    assert [o.num for o in opts] == ["1", "2"]
    assert opts[0].label.startswith("доставить решение на флот"), (
        "подпись первого варианта, а не первый шаг внутри него")


def test_a_bare_variant_word_without_a_label_offers_nothing():
    """Fail-CLOSED: подписи нет ⇒ кнопки нет. Выдумывать выбор запрещено (ADR-075)."""
    card = _card("Вариант 1\n\nВариант 2\n")

    assert od.parse_options(card) == []


def test_a_multiselect_card_still_gets_no_buttons():
    """Обратный контроль: «можно взять несколько» одной кнопкой не сжимается."""
    card = _card("Выбери, как поступаем — можно взять несколько:\n\n"
                 "Вариант 1 — снять страницу.\n\n"
                 "Вариант 2 — оживить генератор.\n")

    assert od.parse_options(card) == []


def test_a_question_mark_option_still_closes_the_whole_card():
    """Обратный контроль: пункт-ВОПРОС по-прежнему обнуляет кнопки всей карточки."""
    card = _card("Вариант 1 — Ставить ли четыре готовых агента?\n\n"
                 "Вариант 2 — Выводить ли шесть из реестра?\n")

    assert od.parse_options(card) == []


# ===========================================================================
# 3. Оборванная скобка: мусор на кнопке и «рекомендую» в подписи
# ===========================================================================
def test_an_unclosed_paren_tail_is_dropped_from_the_label():
    card = _card("Вариант 1 — Оставить как есть и жить с ручными синхронизациями (не рекомендую —\n"
                 "90 %-цель владельца этим не достигается).\n\n"
                 "Вариант 2 — Починить синхронизацию.\n")

    opts = od.parse_options(card)

    assert opts[0].label == "Оставить как есть и жить с ручными синхронизациями", (
        "на кнопке не должно быть обрывка «(не рекомендую —»")


def test_dropping_the_tail_does_not_move_the_recommendation():
    """Рез — только подпись. Флаг считается ДО него, и перевернуться не имеет права."""
    card = _card("Вариант 1 — Оставить как есть (не рекомендую — цель владельца этим не\n"
                 "достигается).\n\n"
                 "Вариант 2 — Починить синхронизацию (рекомендую: дешевле и проверяемо,\n"
                 "и снимает ручную работу).\n")

    opts = od.parse_options(card)

    assert [o.recommended for o in opts] == [False, True]
    assert "рекоменд" not in opts[1].label.lower(), (
        "слово «рекомендую» из пометки не должно уезжать владельцу подписью варианта")


def test_balanced_parens_inside_a_label_survive():
    """Обратный контроль: режется НЕЗАКРЫТЫЙ хвост, а не любые скобки."""
    card = _card("Вариант 1 — Снять страницу (и ссылки из подвала).\n\n"
                 "Вариант 2 — Оставить.\n")

    opts = od.parse_options(card)

    assert opts[0].label == "Снять страницу (и ссылки из подвала)"


def test_a_label_that_is_only_an_unclosed_paren_is_kept_not_emptied():
    """Пустая подпись отбрасывает вариант молча — резать до пустоты нельзя."""
    assert od._drop_unclosed_paren_tail("(рекомендую: так дешевле") == (
        "(рекомендую: так дешевле")


# ===========================================================================
# 4. Проза ≠ перечень: две метки в одной строке
# ===========================================================================
_PROSE = _card("Вариант 1 — похоронить. Вариант 2 — воскресить. Выбери один.\n")


def test_prose_with_two_markers_in_one_line_is_not_a_list():
    """Одна кнопка вместо двух ХУЖЕ, чем ни одной: отсутствие видно, потеря — нет.

    Форма живая: ровно так написана живая копия карточки в
    `test_owner_decision_heal_stale_live_copy` (замер
    `inbox-storozh-knopok-obyavlyaet-v-kartochke-ne`). Разбор построчный, и без правила
    «вторая метка в строке ⇒ проза» он отдаёт РОВНО ОДИН вариант «1 — похоронить»,
    молча теряя второй.
    """
    assert od.parse_options(_PROSE) == []
    assert od.has_unparsed_options(_PROSE) is True, (
        "отказ обязан быть НАЗВАН: «варианты есть, разобрать не смог»")


def test_prose_line_does_not_silence_a_real_numbered_list():
    """Проза не должна объявлять «явный диалект» и тем гасить настоящий перечень.

    Признак диалекта и сам разбор спрашивают ОДНУ функцию (`_plain_word_option`) — две
    копии правила разошлись бы ровно здесь: строка-проза попала бы в диалект, не попав
    в варианты, и карточка осталась бы без кнопок вовсе.
    """
    card = _card("Ниже перечислены варианты 1 и 2, выбери один:\n\n"
                 "1. **Похоронить.** Снять разделы с сайта.\n"
                 "2. **Воскресить.** Достроить канал заявок.\n")

    opts = od.parse_options(card)

    assert [(o.num, o.label) for o in opts] == [("1", "Похоронить"), ("2", "Воскресить")]
