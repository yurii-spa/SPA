#!/usr/bin/env python3
"""Признак «выбор написан, а разбор его не взял» требует ПЕРЕЧНЯ, а не слова (#484).

КАЖДЫЙ тест здесь — положительный контроль ИЗМЕРЕННОГО состояния живой очереди на
2026-09-04 (606 карточек прод-трекера), а не украшение.

**Что было измерено.** `has_unparsed_options` — сторож, отличающий «выбора в карточке
нет» от «выбор есть, а кнопок нет». Второе уезжает владельцу как НАША неполадка
(`buttonless_reason.CODE_UNREADABLE_OPTIONS`) с лекарством «научить `parse_options` этой
форме». Его собственный докстринг проводит границу дословно: признак требует ПЕРЕЧНЯ
(метка-номер, буква пункта, «Варианты:», «выбери…»), **а не одного слова «вариант»**.

Границу нарушал сам признак. В `_UNREAD_CHOICE_RE` метка-БУКВА принималась где угодно —
`(?:вариант\\w*|option)\\s*[—–:-]?\\s*(?:…|[A-Za-zА-Яа-я])\\b`, — и это съедало два разных
класса прозы:

* «…это выбор **варианта** из какой-то карточки?» — движок откатывал жадное `\\w*` на один
  символ и предъявлял ПОСЛЕДНЮЮ БУКВУ САМОГО СЛОВА как метку («варианта» = «вариант» +
  метка «а»). Живой предмет: `owner-decision-utochnenie-po-zametke-1` (`needs-owner`) —
  карточка БЕЗ перечня вообще, она просит владельца уточнить, к чему относился его голый
  ответ «1». Владелец получал просьбу завести несуществующий дефект;
* «**вариантов у** нас пока нет» — односимвольные предлоги и союзы (у, и, а, в, к, о, с,
  я) занимают ровно ту позицию, где стои́т метка «А»/«Б». Этот второй класс нашёл сам
  этот файл при первом прогоне: первая редакция правки закрывала только откат `\\w*`.

Починка — одна и общая на оба: метка-буква признаётся ТОЛЬКО перед концом строки или
знаком, а не перед другим словом. Числовые формы («вариант 2», «вариант А1») однозначны
и ограничения не требуют.

**Почему одной этой правки было мало — и это ГЛАВНЫЙ урок файла.** Дифференциальный
замер по всем 606 карточкам показал ДВЕ смены вердикта, и вторая —
`owner-decision-10-deneg-stoyat-bez-raboty-prichina-naid` — оказалась находкой ВЕРНОЙ:
перечень у неё есть, открыт строкой «Выбрать, чем закрывать простой этих 10% (варианты
не исключают друг друга):», а числилась находкой ТОЛЬКО по дефекту. Потерять её значило
бы обеднить сторожа — ровно то, против чего написан #349. Поэтому рядом с «Варианты:»
(двоеточие вплотную) признак теперь видит и «…(варианты …):» — двоеточие в КОНЦЕ строки.

**Замер после обеих правок (те же 606 карточек):** вердикт меняется ровно у ОДНОЙ —
`owner-decision-utochnenie-po-zametke-1`, True → False. Остальные 20 находок остаются.

Оговорка о числе. Карточка-задание `inbox-storozh-knopok-narushaet-granitsu-kotoru`
(цикл #483) называла ложными ПЯТЬ карточек. Перемер #484 это не подтвердил: у четырёх из
пяти в той же строке стои́т настоящий перечень («Варианты: (а, рекомендую) …»), который
ловится отдельной альтернативой, — счёт вёлся по ТЕКСТУ совпадения, а не по вопросу
«сменится ли вердикт, если убрать дефект». Мерка здесь дифференциальная: прогнать
популяцию до и после и смотреть смену вердикта.

Время в тестах не участвует: разбор — чистая функция от текста.
"""
from __future__ import annotations

import unittest

from spa_core.telegram import owner_decisions as od

_HEAD = ("## Что случилось и почему это важно\n\n"
         "Пришёл ответ, к которому не привязана карточка.\n\n"
         "## Что от тебя нужно\n\n")
_TAIL = "\n\n## Как понять, что готово\n\nОтвет привязан к карточке.\n"


def _card(section: str) -> str:
    return _HEAD + section + _TAIL


# Живая карточка `owner-decision-utochnenie-po-zametke-1`, дословно: перечня нет,
# слово «варианта» стои́т в прозе.
_NO_LIST_PROSE = _card(
    "Сообщение состоит только из «1» — это выбор варианта из какой-то карточки? "
    "Напиши, к какой карточке относится ответ (или пришли вопрос/задачу словами).\n"
)

# Живая карточка `owner-decision-10-deneg-stoyat-bez-raboty-prichina-naid`: перечень
# ЕСТЬ, открыт строкой с двоеточием в конце.
_LIST_OPENED_FAR_COLON = _card(
    "Выбрать, чем закрывать простой этих 10% (варианты не исключают друг друга):\n\n"
    "1. **(рекомендую первым шагом)** Разрешить заняться фидами.\n\n"
    "2. Снизить долю `morpho_steakhouse`.\n"
)

# Живые карточки `…-bezopasnost-admin-panel-…`, `…-chistka-…`, `…-monitor-depega-…`,
# `…-flot-7-agentov-…`: двоеточие вплотную к слову.
_LIST_OPENED_TIGHT_COLON = _card(
    "Закрыть админку от посторонних. Варианты: (а, рекомендую) Cloudflare Access policy "
    "на пути `/admin`; (б) басик-аутентификация.\n"
)


class LabelIsNotAWordEnding(unittest.TestCase):
    """Метка варианта — ОТДЕЛЬНОЕ слово, а не окончание слова «вариант»."""

    def test_inflected_word_in_prose_is_not_a_finding(self):
        """Авария: «варианта из …» читалось как «вариант А» (откат жадного `\\w*`)."""
        self.assertEqual(od.parse_options(_NO_LIST_PROSE), [],
                         "предпосылка теста: разбор вариантов не нашёл")
        self.assertFalse(
            od.has_unparsed_options(_NO_LIST_PROSE),
            "перечня в карточке нет — просить владельца завести дефект не за что")

    def test_regex_does_not_borrow_the_words_own_ending_as_a_label(self):
        """Тот же дефект на уровне самого признака, без обвязки карточки."""
        for prose in ("это выбор варианта из какой-то карточки",
                      "вариант тот же, что вчера — ничего не делать"):
            with self.subTest(prose=prose):
                self.assertIsNone(od._UNREAD_CHOICE_RE.search(prose),
                                  f"голое слово в прозе не перечень: {prose!r}")

    def test_one_letter_word_after_the_word_is_not_a_label(self):
        """Остаток того же класса, найденный ЭТИМ файлом при первом прогоне.

        Первая редакция правки закрывала только откат жадного `\\w*`. Она мала:
        «вариантов у нас пока нет» читается как «вариант У» и с настоящим пробелом —
        односимвольные предлоги и союзы занимают ровно ту позицию, где стои́т метка
        «А»/«Б». Поэтому условие поставлено не на разделитель, а на то, ЧТО СТОИ́Т ЗА
        меткой: конец строки или знак, но не другое слово.
        """
        for prose in ("вариантов у нас пока нет",
                      "вариант и то и другое сразу",
                      "вариантов с чем сравнивать не осталось"):
            with self.subTest(prose=prose):
                self.assertIsNone(od._UNREAD_CHOICE_RE.search(prose), prose)

    def test_real_labels_must_keep_matching(self):
        """Обратный контроль: настоящая метка обязана остаться находкой."""
        for line in ("Вариант 2 — ничего не делать", "вариант Б", "Вариант А1",
                     "option A", "вариант—Б", "вариант: 3"):
            with self.subTest(line=line):
                self.assertIsNotNone(od._UNREAD_CHOICE_RE.search(line), line)

    def test_sibling_rule_agrees_on_the_same_prose(self):
        """Сосед по тому же решению прозу не берёт — расхождение и было дефектом."""
        prose = "это выбор варианта из какой-то карточки"
        self.assertIsNone(od._OPTION_MENTION_RE.match(prose))
        self.assertIsNone(od._UNREAD_CHOICE_RE.search(prose))


class EnumerationOpenerSurvives(unittest.TestCase):
    """Верная находка, которую первая редакция починки чуть не потеряла."""

    def test_far_colon_opener_is_still_a_finding(self):
        """«…(варианты не исключают друг друга):» — перечень открыт, находка ВЕРНА."""
        self.assertEqual(od.parse_options(_LIST_OPENED_FAR_COLON), [],
                         "предпосылка теста: разбор этой формы не берёт")
        self.assertTrue(
            od.has_unparsed_options(_LIST_OPENED_FAR_COLON),
            "перечень есть — потерять эту находку значит обеднить сторожа (#349)")

    def test_tight_colon_opener_is_still_a_finding(self):
        """«Варианты: (а, рекомендую) …» — прежняя альтернатива обязана уцелеть."""
        self.assertEqual(od.parse_options(_LIST_OPENED_TIGHT_COLON), [],
                         "предпосылка теста: разбор этой формы не берёт")
        self.assertTrue(od.has_unparsed_options(_LIST_OPENED_TIGHT_COLON))

    def test_colon_must_end_the_line(self):
        """Без двоеточия в конце строки признак снова свёлся бы к слову в прозе."""
        self.assertIsNone(od._UNREAD_CHOICE_RE.search(
            "варианты не исключают друг друга, решай сам"))


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
