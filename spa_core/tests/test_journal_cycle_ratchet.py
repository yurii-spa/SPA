"""Храповик записей журнала + положительные контроли к детектору номера цикла.

**Что случилось 2026-08-07 (цикл #142 → #150).** Инструмент
`scripts/audit_state_journal_coverage.py` отвечает на вопрос «можно ли удалить запись из
`docs/STATE.md`, не потеряв её» — то есть есть ли у названного цикла СВОЯ запись в
`docs/journal/`. Он доложил: у **16** циклов (#2 #7 #16 #17 #19 #28 #29 #38 #39 #40 #42 #43
#44 #46 #47 #48) записи «НЕТ ВОВСЕ». По этому отчёту завели карточку «восстановить 16
стёртых записей из git-истории».

Записи всё это время лежали в `docs/journal/` **целиком**. Ошибался инструмент: его правило
требовало слово «цикл» ВПЛОТНУЮ перед решёткой (`цикл\\s+#39`), а самая частая форма
заголовка в репозитории — `## … Автономный цикл оркестратора #39 — …`, где между ними стоит
`оркестратора`. Ещё две записи (#7, #17) лежали под `###` вместо `##`, а три (#2, #16, #28)
под заголовками, которые номер цикла не называли вовсе, хотя тело записи его называет.

Цена ошибки была не «лишняя минута разбора»: выполнение карточки буквально **удвоило бы** 16
записей — восстановление из git-истории поверх существующих. Отчёт сторожа читают как факт.

**Что закрепляет этот файл.**

1. **Храповик.** Набор циклов, у которых есть своя запись, может только расти
   (`journal_cycle_baseline.json`). Выпал номер — запись потеряли; это находка, а не повод
   двигать базу. База снята ПОСЛЕ починки (121), а не до (105).
2. **Положительные контроли детектора.** Каждая форма-заголовок ниже взята ДОСЛОВНО из
   журнала и до починки цикла #150 читалась как «цикла тут нет». Проверка, никогда не
   видевшая настоящей поломки, — украшение (`.claude/rules/deployment.md`).
3. **Отрицательные контроли.** Расширение формы обязано остаться узким: `инв. #16`,
   `класс #29/#31`, `идеи реестра #38`, `PR #8`, `отчёт #109` циклами НЕ становятся.
   Ложное «покрыто» стирает запись безвозвратно, поэтому давление — в эту сторону.

Существующий `test_state_journal_coverage_audit.py` не тронут (инвариант #16): здесь только
добавленное.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

_REPO_ROOT = Path(__file__).resolve().parents[2]
_SCRIPT = _REPO_ROOT / "scripts" / "audit_state_journal_coverage.py"
_JOURNAL = _REPO_ROOT / "docs" / "journal"
_BASELINE = Path(__file__).resolve().parent / "journal_cycle_baseline.json"

#: Те самые 16 номеров, которые сторож объявил утраченными 2026-08-07. Ни один утрачен не был.
_FALSE_ALARM_2026_08_07 = [
    "2", "7", "16", "17", "19", "28", "29", "38", "39", "40", "42", "43", "44", "46", "47", "48",
]


@pytest.fixture(scope="module")
def audit_mod():
    assert _SCRIPT.exists(), f"нет {_SCRIPT} — мерить нечем, fail-CLOSED"
    spec = importlib.util.spec_from_file_location("audit_state_journal_coverage", _SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _headed_cycles(audit_mod) -> set:
    heads, _bodies = audit_mod.journal_cycles(_JOURNAL)
    return set(heads)


def _baseline() -> set:
    return set(json.loads(_BASELINE.read_text(encoding="utf-8"))["cycles"])


# ── храповик ─────────────────────────────────────────────────────────────────────────────

def test_baseline_exists_and_is_readable():
    """Нет базы ⇒ храповик ничего не меряет. Fail-CLOSED."""
    assert _BASELINE.exists(), f"нет {_BASELINE}"
    assert _baseline(), "база пуста — это не «всё хорошо», это отсутствие измерения"


def test_journal_never_loses_a_cycle_entry(audit_mod):
    """Каждый цикл из базы по-прежнему имеет СВОЮ запись в журнале."""
    lost = sorted(_baseline() - _headed_cycles(audit_mod), key=int)
    assert not lost, (
        "из docs/journal/ пропали записи циклов: "
        + ", ".join("#" + n for n in lost)
        + ".\nЭто не «обнови базу»: база двигается ТОЛЬКО вверх. Запись цикла — общая память "
        "проекта; молчаливая перезапись журнала уже стирала 68 записей (цикл #139).\n"
        "Восстанавливать из git-истории (`git log -S`), а не переписывать базу."
    )


def test_baseline_is_not_ahead_of_the_journal(audit_mod):
    """База не должна содержать номера, которых в журнале нет НИКОГДА.

    Иначе храповик красен с рождения — и его выключат, а не починят журнал.
    """
    assert _baseline() <= _headed_cycles(audit_mod)


def test_the_sixteen_declared_lost_all_have_their_own_entry(audit_mod):
    """Положительный контроль ровно на аварию 2026-08-07.

    До починки цикла #150 этот тест краснел на ВСЕХ шестнадцати номерах.
    """
    headed = _headed_cycles(audit_mod)
    missing = [n for n in _FALSE_ALARM_2026_08_07 if n not in headed]
    assert not missing, (
        "снова не видны записи циклов " + ", ".join("#" + n for n in missing)
        + " — либо запись потеряли, либо детектор номера цикла сузили обратно"
    )


def test_archive_of_state_is_fully_covered_by_the_journal(audit_mod):
    """Ни одна запись сокращённого STATE не осталась без записи в журнале.

    `docs/journal/STATE-archive-2026-08-07.md` — дословный снимок STATE до сокращения
    (цикл #142). MISSING по нему обязан быть нулём: иначе хроника цикла существует ТОЛЬКО
    в снимке чужого файла.
    """
    archive = _JOURNAL / "STATE-archive-2026-08-07.md"
    assert archive.exists(), f"нет {archive}"
    report = audit_mod.audit(archive, _JOURNAL)
    missing = sorted(
        {c for e in report["entries"] for c in e["missing_cycles"]}, key=int
    )
    assert not missing, "циклы без записи в журнале: " + ", ".join("#" + n for n in missing)


# ── положительные контроли: формы, на которых детектор молчал ────────────────────────────

@pytest.mark.parametrize("header,expected", [
    # доминирующая форма заголовков W31 — между «цикл» и решёткой стоит уточнение
    ("## 2026-07-30 · Автономный цикл оркестратора #39 — карточка ЗАКРЫТА", ["39"]),
    ("## 2026-07-30 · автономный цикл оркестратора #46: невидимые исключения сняты", ["46"]),
    ("## Автономный цикл оркестратора #29 (2026-07-29, вечер) — RISKWIRE", ["29"]),
    # номер впереди, «цикл» — в скобке следом
    ("## 2026-07-17 · Hardening #19 (автономный цикл env-setup-v3) — тесты", ["19"]),
    # два номера в одном заголовке: и подобранная сирота, и сам цикл
    ("## 2026-07-30 · Автономный цикл оркестратора #42 — работа цикла #41", ["41", "42"]),
])
def test_forms_that_the_detector_used_to_miss(audit_mod, header, expected):
    """Каждая строка взята ДОСЛОВНО из `docs/journal/`; до цикла #150 все давали `[]`."""
    assert audit_mod.cycle_ids(header) == expected


@pytest.mark.parametrize("header", [
    # прежние формы обязаны продолжать работать — расширение не должно ничего сломать
    "## Цикл #90 (2026-08-02, автономный) — осиротевшая работа поднята",
    "## 2026-07-16 · Автономный цикл (env-setup-v3, #3) — читаемые имена карточек",
])
def test_previously_working_forms_still_work(audit_mod, header):
    assert audit_mod.cycle_ids(header), f"форма перестала распознаваться: {header}"


# ── отрицательные контроли: расширение осталось узким ────────────────────────────────────

@pytest.mark.parametrize("header", [
    "### Инвариант #16 — проверен арифметикой, а не на слово",
    "### Предсуществующие красные (НЕ мои, не трогал — инв. #16)",
    "### Четыре fail-OPEN в самом модуле (класс #29/#31/#35/#36)",
    "## 2026-07-29 (позже) · разбор PR #8: дубль ALK, коллизия номера",
    "## 2026-08-06 · R&D-итерация (novel-edge-rnd): идеи реестра #38 CBCR и #39 CDR",
    "## 2026-07-17 — Novel-edge R&D: реестр #16 + #17 (первые идеи на РЕАЛЬНОЙ панели)",
    "## 2026-07-16 (novel-edge R&D, автономный цикл) — Идея #15: Kelly KODS",
    "### Сверх отчёта #109: доставка «как есть» сделала бы CI КРАСНЫМ",
    "### Перемер #137: разошлось НОЛЬ чисел",
    "### Подобрана ещё и находка #82, которую она не успела записать",
])
def test_someone_elses_hash_is_still_not_a_cycle(audit_mod, header):
    """Ложное «покрыто» стирает запись безвозвратно — сюда давление сильнее всего.

    Все строки взяты ДОСЛОВНО из `docs/journal/`: это не гипотетические ловушки, а те
    самые соседи, из-за которых голая решётка `#N` разбираться не может.
    """
    assert audit_mod.cycle_ids(header) == [], (
        f"чужая решётка прочитана как номер цикла: {header}"
    )


def test_qualifier_gap_is_one_word_not_a_free_span(audit_mod):
    """Зазор между «цикл» и решёткой — РОВНО одно слово из белого списка.

    Свободный зазор («цикл» и до N слов) прочитал бы вот эту реальную строку как «цикл #16»
    и записал бы ИДЕЮ №16 в покрытие цикла 16 — то есть разрешил бы удалить из STATE запись,
    которой в журнале нет.
    """
    text = "## Цикл #90 — работа цикла #87 поднята и доставлена: числа идей #16/#17"
    assert audit_mod.cycle_ids(text) == ["87", "90"]


def test_unlisted_qualifier_does_not_open_the_gap(audit_mod):
    """Белый список — это список, а не «любое слово»."""
    assert audit_mod.cycle_ids("работа цикла владельца #77 доставлена") == []
