"""`docs/STATE.md` обязан обновляться КАЖДОЙ сессией, которая что-то сделала.

Требование владельца 2026-08-08: «нужно, чтобы всегда его читали и всегда туда записывали».

**Правило уже существовало и не сработало — поэтому здесь сторож, а не ещё одна строчка правила.**
`CLAUDE.md` §1 предписывает читать `docs/STATE.md` в начале сессии, §3 — обновлять в конце цикла.
2026-08-08 автопилотный раунд закрыл восемь решений владельца, написал четыре записи в журнал,
приземлил семь коммитов — и **`STATE.md` остался с текстом «16 из 36 адаптеров возвращают свой
литерал»**, хотя к тому моменту их было ноль, и с описанием замка цикла как сломанного, хотя он
был починен. Следующая сессия прочитала бы это первым и пошла бы чинить уже починенное.

Класс дефекта — тот же, что разбирался весь тот день: **правило, которое никто не проверяет, есть
украшение**. Сторож задаёт ровно один вопрос, на который ни один существующий не отвечал:

    писала ли сессия в журнал, не обновив при этом STATE.md?

Журнал — надёжный признак «сессия что-то сделала»: по §3 в него дописывают в конце цикла, и
пустых записей туда не носят. Если журнал новее `STATE.md`, значит работа была, а точка входа
для следующей сессии осталась устаревшей.

Проверка идёт по истории git, а не по mtime файлов: mtime в рабочем дереве переписывается любым
`git checkout` и не является утверждением о том, что сессия делала.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

_REPO = Path(__file__).resolve().parents[2]
_STATE = "docs/STATE.md"
_JOURNAL_DIR = "docs/journal"


def _git(*args: str) -> str:
    out = subprocess.run(["git", *args], cwd=str(_REPO),
                         capture_output=True, text=True, timeout=60)
    if out.returncode != 0:
        pytest.skip(f"git недоступен ({' '.join(args)}): {out.stderr.strip()[:120]}")
    return out.stdout.strip()


def _last_commit_ts(path: str) -> int | None:
    """UNIX-время последнего коммита, тронувшего путь. None — пути нет в истории."""
    out = _git("log", "-1", "--format=%ct", "--", path)
    return int(out) if out else None


def _newest_journal_file() -> str | None:
    """Файл журнала, тронутый последним коммитом (недельные файлы + STATE-архивы)."""
    listing = _git("ls-tree", "--name-only", "HEAD", f"{_JOURNAL_DIR}/")
    files = [f for f in listing.splitlines() if f.endswith(".md")]
    if not files:
        return None
    stamped = [(ts, f) for f in files if (ts := _last_commit_ts(f)) is not None]
    if not stamped:
        return None
    return max(stamped)[1]


def test_state_md_exists_and_is_tracked():
    """Без этого остальные проверки молча превратились бы в skip."""
    assert (_REPO / _STATE).exists(), f"{_STATE} отсутствует в дереве"
    assert _last_commit_ts(_STATE) is not None, f"{_STATE} не в истории git"


def test_journal_dir_is_not_empty():
    """Контроль стенда: если журнала нет, сторож ниже ничего не стережёт."""
    assert _newest_journal_file() is not None, "в docs/journal нет ни одного .md"


def test_state_md_is_not_older_than_the_newest_journal_entry():
    """ГЛАВНАЯ проверка: сессия писала в журнал ⇒ обязана была обновить и STATE.md.

    Допуск в одни сутки намеренный. Он не «на всякий случай», а признаёт реальный
    порядок работы: журнал и `STATE.md` уезжают РАЗНЫМИ коммитами, между ними
    проходят минуты, а иногда сессия дописывает журнал уже после того, как
    обновила STATE. Жёсткое «STATE строго новее» краснело бы на правильном
    поведении — а сторож, краснеющий на верном состоянии, отключают первым.

    Что ловится: разрыв в СУТКИ и больше. Именно так выглядит пропуск —
    журнал ведут, а точку входа для следующей сессии забывают.
    """
    journal = _newest_journal_file()
    j_ts = _last_commit_ts(journal)
    s_ts = _last_commit_ts(_STATE)
    assert j_ts is not None and s_ts is not None

    lag_hours = (j_ts - s_ts) / 3600.0
    assert lag_hours < 24.0, (
        f"docs/STATE.md отстаёт от {journal} на {lag_hours:.1f} ч.\n"
        "Сессия писала в журнал, но НЕ обновила точку входа для следующей сессии.\n"
        "Требование владельца 2026-08-08: «всегда читать и всегда записывать».\n"
        "Чинить обновлением STATE.md, а НЕ ослаблением этого допуска: 2026-08-08 устаревший "
        "STATE.md утверждал, что 16 адаптеров подставляют литерал, когда их было ноль — "
        "следующая сессия пошла бы переделывать сделанное."
    )


def test_state_md_names_where_the_details_live():
    """`STATE.md` — точка входа, а не архив. Он обязан УКАЗЫВАТЬ на журнал.

    Предел ~150 строк держится храповиком, поэтому хроника физически не помещается;
    без явной ссылки следующая сессия не найдёт, где искать подробности.
    """
    text = (_REPO / _STATE).read_text(encoding="utf-8")
    assert "docs/journal" in text or "журнал" in text.lower(), (
        "STATE.md не упоминает журнал — следующая сессия не узнает, где детали"
    )


def test_state_md_is_not_a_stub():
    """Пустой/обрезанный STATE.md формально «свежий», а по сути его нет."""
    text = (_REPO / _STATE).read_text(encoding="utf-8")
    assert len(text.splitlines()) >= 40, "STATE.md подозрительно короткий — похоже на обрубок"
    assert "Текущий фокус" in text or "фокус" in text.lower(), (
        "в STATE.md нет секции фокуса — это уже не точка входа"
    )


# ── контроль сторожа: он обязан КРАСНЕТЬ на пропуске ─────────────────────────
#
# Сегодняшний отрыв — 2.2 ч (журнал W32 против STATE.md), то есть сторож зелен
# по делу. Но зелёный сторож ничего не доказывает, пока не показано, что он
# умеет краснеть. Логика порога вынесена в чистую функцию и проверяется на
# синтетических отметках — без этого проверка выше была бы «украшением», ровно
# тем, что разбиралось весь день 2026-08-08.

def _lag_is_acceptable(journal_ts: int, state_ts: int, max_hours: float = 24.0) -> bool:
    return (journal_ts - state_ts) / 3600.0 < max_hours


_H = 3600


@pytest.mark.parametrize("lag_h,ok", [
    (0, True),        # обновлены одним заходом
    (-3, True),       # STATE обновили ПОЗЖЕ журнала — нормальный порядок
    (2.2, True),      # фактический отрыв на 2026-08-08 после починки
    (23.9, True),     # ещё в допуске
    (24.0, False),    # ровно порог — уже пропуск
    (30, False),      # сессия отписалась в журнал и забыла точку входа
    (72, False),      # три дня STATE врёт следующим сессиям
])
def test_lag_rule_fires_where_it_should(lag_h, ok):
    base = 1_786_000_000
    assert _lag_is_acceptable(base + int(lag_h * _H), base) is ok


def test_guard_would_have_caught_the_2026_08_08_miss():
    """Положительный контроль на РЕАЛЬНОМ пропуске.

    08.08 автопилотный раунд написал четыре записи в журнал и семь коммитов, а
    `STATE.md` остался утверждать «16 из 36 адаптеров возвращают свой литерал»,
    когда их было ноль. Если бы такая сессия не обновила STATE до следующего дня,
    сторож обязан покраснеть.
    """
    base = 1_786_000_000
    assert not _lag_is_acceptable(base + 25 * _H, base)
