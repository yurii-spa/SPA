#!/usr/bin/env python3
"""Нумерованный список ВНУТРИ варианта — это шаги, а не варианты (цикл #338).

Каждый тест здесь — положительный контроль живой карточки, а не украшение.

**Что случилось.** Разбор допускал два диалекта перечня варианта сразу: явный
(«**Вариант N — …**») и голый нумерованный («1. **…**» / «1. …»). Внутри абзаца
варианта голым нумерованным пишут ШАГИ и ПОЯСНЕНИЯ — и разбор читал их наравне с
вариантами. Обе половины дефекта измерены на живых карточках очереди (133 штуки,
затронуто ровно три):

1. **Кнопки пропадали ВСЕ.** `owner-decision-reshenie-adr-104-zapisano-no-do-mashiny`
   (`needs-owner`, висит у владельца прямо сейчас): три явных варианта, а внутри
   первого — перечень «1…4» («прогнать `deployment_acceptance`», «переустановить
   агента», …). Разбор брал шаги как варианты 1–4, на строке «**Вариант 2 — …**»
   видел ДУБЛЬ номера 2 и по правилу «дубль номера ⇒ карточка задаёт несколько
   вопросов» возвращал ПУСТО. Владелец получал «варианты в карточке есть, но я не
   смог собрать из них кнопки… заведи мне это как дефект». Вот он.

2. **И это ещё не худшая половина: кнопки ВЫДУМЫВАЛИСЬ.**
   `own-aud19-volatile-clmm-vvodim-li-klass` предлагает три варианта (A/B/C), а
   заканчивается абзацем «Ещё два момента, по которым мне нужен твой ответ, если
   выберешь B: 1. … 2. …». Владелец видел **пять** кнопок, и две из них —
   «Стейблкоин USDG… не в белом списке» и «Класс делит общий лимит T3…». Нажатие
   по такой кнопке записало бы в карточку решение владельца, которого он не
   принимал. Это прямое нарушение ADR-075 («выдумывать владельцу выбор запрещено»),
   работавшее в проде. То же у `own-rnd-xsd-rank-demotion-allocator` (A/B/C + 1/2/3).

**Правило.** Диалекты не смешиваются: если в секции есть хоть одна строка явной формы
«**Вариант N — …**», голый нумерованный перечень в этой карточке — не варианты.
Явная форма однозначна (автор назвал вариант вариантом), голая — догадка.

**Fail-CLOSED не ослаблен ни в одну сторону**, и это закреплено обратными контролями:
дубль номера ВНУТРИ одного диалекта по-прежнему закрывает карточку целиком, а карточки,
написанные ТОЛЬКО нумерованным списком (`own-31`: «Два решения: 1. …? 2. …?»),
разбираются ровно как раньше.

Литеральных дат в фикстурах нет: время здесь не предмет.
"""
from __future__ import annotations

from spa_core.telegram import owner_decisions as od

_HEAD = (
    "## Что случилось и почему это важно\n\n"
    "Решение записали, а до машины оно не доехало.\n\n"
    "## Что от тебя нужно\n\n"
    "Выбери один вариант.\n\n"
)

#: Форма живой `owner-decision-reshenie-adr-104-zapisano-no-do-mashiny`: явные варианты,
#: а внутри первого — нумерованные ШАГИ, чьи номера сталкиваются с номерами вариантов.
CARD_STEPS_INSIDE = _HEAD + (
    "**Вариант 1 (рекомендую) — доставить ADR-104 на машину.**\n\n"
    "Править ничего не надо. Нужен перезапуск агента:\n\n"
    "1. `python3 -m spa_core.monitoring.deployment_acceptance` — ДО;\n"
    "2. переустановить агента через гейт;\n"
    "3. `python3 -m spa_core.monitoring.deployment_acceptance` — ПОСЛЕ;\n"
    "4. **тем же заходом** поправить срок годности у здоровья офиса.\n\n"
    "**Вариант 2 — отменить ADR-104 и вернуть суточный такт.**\n"
    "Так делать НЕ рекомендую.\n\n"
    "**Вариант 3 — отложить.** Тогда тест остаётся красным на Маке.\n\n"
    "## Как понять, что готово\n\nТест зелёный.\n"
)

#: Форма живой `own-aud19-volatile-clmm-vvodim-li-klass`: три варианта буквами, а следом
#: абзац «Ещё два момента» с нумерованными ПОЯСНЕНИЯМИ.
CARD_NOTES_AFTER = (
    "## Что случилось и почему это важно\n\nКласс CLMM обещает 79 %.\n\n"
    "## Что от тебя нужно\n\n"
    "Выбери форму, в которой мы вообще рассматриваем этот класс:\n\n"
    # Пометка рекомендации стоит в ПРОДОЛЖЕНИИ абзаца, как в живой карточке, а не в
    # заголовке варианта: свёрнутая в одну строку фикстура звезды бы не дала и тест
    # проверял бы не то, что происходит в проде.
    "- **Вариант A — только исследование, без денег.** Пишу честную записку.\n"
    "  **Рекомендую этот вариант**: он ничего не ломает.\n"
    "- **Вариант B — исследование + захеджированная форма.** Это уже изменение "
    "risk-слоя.\n"
    "- **Вариант C — не вводим совсем.** Тогда я записываю отказ решением.\n\n"
    "Ещё два момента, по которым мне нужен твой ответ, если выберешь B:\n\n"
    "1. Стейблкоин **USDG** из того скриншота у нас не в белом списке.\n"
    "2. Класс делит общий лимит T3 с Pendle, Ethena и поинтами.\n\n"
    "## Как понять, что готово\n\nОтвет записан.\n"
)

#: Обратный контроль: карточка написана ТОЛЬКО нумерованным списком — диалект один,
#: и он обязан разбираться как раньше.
CARD_NUMBERED_ONLY = (
    "## Что случилось и почему это важно\n\nДесять агентов в реестре без флота.\n\n"
    "## Что от тебя нужно\n\n"
    "1. **Довести правило до конца (рекомендую).** Убрать подстановку.\n"
    "2. **Оставить как есть**, но тогда честно записать почему.\n\n"
    "## Как понять, что готово\n\nЗаписано.\n"
)

#: Обратный контроль: дубль номера ВНУТРИ одного диалекта — по-прежнему fail-CLOSED.
CARD_DUPLICATE_IN_ONE_DIALECT = _HEAD + (
    "**Вариант 1 — первое решение, ответ А.**\n"
    "**Вариант 2 — первое решение, ответ Б.**\n"
    "**Вариант 1 — второе решение, ответ А.**\n\n"
    "## Как понять, что готово\n\nЗаписано.\n"
)


# ── 1. кнопки пропадали ВСЕ ──────────────────────────────────────────────────


def test_steps_inside_a_variant_no_longer_erase_every_button():
    """Живая `...adr-104...`: три варианта, а кнопок не было ни одной."""
    options = od.parse_options(CARD_STEPS_INSIDE)

    assert [o.num for o in options] == ["1", "2", "3"]
    assert options[0].label == "доставить ADR-104 на машину"
    assert options[0].recommended is True
    assert not any(o.recommended for o in options[1:])


def test_the_owner_is_no_longer_told_to_file_a_defect_about_it():
    """Текст перестаёт быть отпиской: у карточки появляются настоящие кнопки."""
    text = od.build_message("Решение ADR-104 не доехало", CARD_STEPS_INSIDE,
                            od.parse_options(CARD_STEPS_INSIDE))

    assert "<b>Варианты:</b>" in text
    assert "не смог собрать из них кнопки" not in text
    assert "deployment_acceptance" not in text, "шаг варианта — не подпись кнопки"


# ── 2. худшая половина: кнопки ВЫДУМЫВАЛИСЬ (ADR-075) ───────────────────────


def test_notes_after_the_variants_are_not_offered_as_choices():
    """Живая `own-aud19…`: владелец видел ПЯТЬ кнопок там, где выбора три.

    Две лишние — пояснения «Ещё два момента»; нажатие записало бы в карточку
    решение владельца, которого он не принимал (прямое нарушение ADR-075).
    """
    options = od.parse_options(CARD_NOTES_AFTER)

    assert [o.num for o in options] == ["A", "B", "C"]
    labels = " ".join(o.label for o in options)
    assert "USDG" not in labels
    assert "лимит T3" not in labels


def test_the_recommendation_still_lands_on_the_right_variant():
    """Звезда не должна уехать вместе с выброшенными пунктами."""
    options = od.parse_options(CARD_NOTES_AFTER)

    starred = [o.num for o in options if o.recommended]
    assert starred == ["A"]


# ── 3. обратные контроли: fail-CLOSED не ослаблен ───────────────────────────


def test_a_numbered_only_card_parses_exactly_as_before():
    """Диалект один — правило про смешение к ней не применяется."""
    options = od.parse_options(CARD_NUMBERED_ONLY)

    assert [o.num for o in options] == ["1", "2"]
    assert options[0].recommended is True


def test_duplicate_number_within_one_dialect_still_closes_the_card():
    """Два вопроса в одной карточке — по-прежнему НИ ОДНОЙ кнопки."""
    assert od.parse_options(CARD_DUPLICATE_IN_ONE_DIALECT) == []


def test_the_card_still_says_options_exist_when_it_refuses():
    """Отказ обязан звучать как неполадка, а не как «выбора не предлагали»."""
    assert od.has_unparsed_options(CARD_DUPLICATE_IN_ONE_DIALECT) is True


def test_an_instruction_card_is_untouched_by_the_dialect_rule():
    """Поручение (ADR-115) не становится вариантным от этой правки."""
    body = ("## Что случилось и почему это важно\n\nАгент молчит.\n\n"
            "## Что от тебя нужно\n\nПерезапусти агента и подтверди.\n")

    assert od.parse_options(body) == []
    assert od.offers_ack(body) is True
