"""Коды выхода дневного цикла — ОДИН исход, ОДИН код, свои слова у каждого.

До 2026-08-13 цикл отвечал внешнему миру двумя цифрами: ``0`` — «отработал» и
``1`` — **всё остальное**. В «остальное» одинаково попадали два несовместимых
исхода:

* **штатный отказ политики** — RiskPolicy сказала «нет» ровно так, как обязана
  (fail-CLOSED). Система работает ПРАВИЛЬНО;
* **авария** — цикл сломался, трек за день не записан.

Замер 2026-08-13 (карточка ``inbox-kod-vyhoda-tsikla-ne-otlichaet-shtatnyi``):
``com.spa.daily_cycle`` завершился с кодом 1 на КАЖДОМ прогоне (05:14, 05:29,
06:01, 06:56 UTC), причина — ``blocked_by_policy`` (лимит одной цепочки 95 % >
90 %, ADR-076). ``agent_health`` показывал ``last_exit=1`` и держал агента в
WARNING круглые сутки. Настоящая авария в этом шуме была бы неотличима от нормы —
ровно тот класс «сторож честно отвечает на свой вопрос, а читают его как ответ на
другой», которым полна память проекта.

**Что здесь есть и чего здесь НЕТ.** Здесь — только СЛОВАРЬ: исход цикла → код
выхода → человеческие слова. Ни порогов RiskPolicy, ни лимитов, ни решения о том,
торговать ли, — они не менялись и здесь не живут (money-path, owner-gated).

**Fail-CLOSED.** Неизвестный статус → ``EXIT_ERROR``. Молчаливого «ну, наверное,
всё в порядке» тут не будет: если исход не назван словарём, это авария, пока не
доказано обратное.

**Только один код считается штатным** (``by_design``) — отказ политики. Все
прочие ненулевые коды по-прежнему краснят здоровье агента: задача цикла #219 —
перестать путать отказ с аварией, а не сделать пульт зеленее.

Модуль намеренно БЕЗ единого импорта: его читает read-only слой мониторинга, и
тянуть туда money-path нельзя (инвариант #6). Измерено в дочернем процессе
(``test_dictionary_adds_no_money_path_import_to_the_monitor``): импорт добавляет
к ``import spa_core`` ровно два имени — пустой пакет ``spa_core.paper_trading`` и
сам этот файл. Поэтому здесь ОДИН источник правды на обе стороны, а не вторая
копия констант с parity-тестом, как пришлось сделать в ``cycle_lock_watch``.
"""

from __future__ import annotations

__all__ = [
    "EXIT_OK",
    "EXIT_ERROR",
    "EXIT_LOCK_REFUSED",
    "EXIT_POLICY_REFUSED",
    "EXIT_NO_LIVE_DATA",
    "EXIT_SAFETY_UNMEASURED",
    "EXIT_PROTECTION_TRIGGERED",
    "STATUS_EXIT_CODES",
    "CYCLE_AGENT_LABEL",
    "exit_code_for_status",
    "describe_exit",
    "is_by_design",
]

# ── Коды ────────────────────────────────────────────────────────────────────
# 0 и 1 — общепринятые «успех» / «ошибка», их значение НЕ меняется.
# 2 занят с самого появления замка (``main`` отказывает, когда цикл уже идёт) —
# трогать нельзя: по нему считает отказы ``cycle_lock_watch.count_refusals``.
EXIT_OK = 0
EXIT_ERROR = 1
EXIT_LOCK_REFUSED = 2
EXIT_POLICY_REFUSED = 3
EXIT_NO_LIVE_DATA = 4
EXIT_SAFETY_UNMEASURED = 5
EXIT_PROTECTION_TRIGGERED = 6

# Единственный агент, чьи коды выхода описывает этот словарь. Знание «код 3 =
# отказ политики» верно ТОЛЬКО для него: у любого другого агента тройка означает
# что угодно, и трактовать её как штатный отказ — значит замолчать чужую аварию.
CYCLE_AGENT_LABEL = "com.spa.daily_cycle"

# ``CycleResult.status`` → код выхода. Ключи — ровно те литералы, которые
# выставляет ``cycle_runner`` (см. ``_cycle_status`` и три ранних ``CycleResult``).
STATUS_EXIT_CODES: dict[str, int] = {
    "ok": EXIT_OK,
    # Политика отказала штатно: гейт отработал, капитал не сдвинулся.
    "blocked_by_policy": EXIT_POLICY_REFUSED,
    "blocked_by_daily_limits": EXIT_POLICY_REFUSED,
    # Живых данных не пришло — цикл отказался угадывать (fail-CLOSED). Это не
    # авария кода, но в треке дыра, поэтому свой код и свой голос.
    "skipped_no_live_data": EXIT_NO_LIVE_DATA,
    # LAW-1: сама проверка безопасности не отработала — «не измерено», худший из
    # исходов после аварии, и уж точно не «штатно».
    "blocked_safety_check_error": EXIT_SAFETY_UNMEASURED,
    # Защита сработала: стоп-кран / аварийные автоматы. Событие, а не поломка,
    # но громкость снижать нельзя.
    "kill_switch": EXIT_PROTECTION_TRIGGERED,
}

# Аварийные автоматы дают статус вида ``blocked_by_emergency_<состояние>``:
# конечного списка суффиксов нет, поэтому — по префиксу.
_EMERGENCY_PREFIX = "blocked_by_emergency_"

# Слова для человека. Ключ — код, значение — как это называть в отчётах.
_WORDS: dict[int, str] = {
    EXIT_OK: "цикл отработал",
    EXIT_ERROR: "АВАРИЯ цикла",
    EXIT_LOCK_REFUSED: "отказ замка: цикл уже шёл",
    EXIT_POLICY_REFUSED: "штатный отказ политики (капитал не двигался)",
    EXIT_NO_LIVE_DATA: "отказ по отсутствию живых данных (fail-CLOSED)",
    EXIT_SAFETY_UNMEASURED: "проверка безопасности НЕ ОТРАБОТАЛА (LAW-1)",
    EXIT_PROTECTION_TRIGGERED: "сработала защита (стоп-кран/аварийный автомат)",
}

# Штатным — то есть НЕ поводом красить здоровье агента — считается ровно один
# исход. Список намеренно не «все отказы»: дыра в треке и неотработавшая проверка
# безопасности обязаны оставаться видимыми.
_BY_DESIGN = frozenset({EXIT_POLICY_REFUSED})


def exit_code_for_status(status: object) -> int:
    """Код выхода по ``CycleResult.status``. Неизвестный статус ⇒ ``EXIT_ERROR``.

    Fail-CLOSED по построению: словарь описывает исходы, которые мы ПОНИМАЕМ.
    Всё остальное (новый статус, ``None``, мусор) — авария, а не «наверное, ок».
    """
    if not isinstance(status, str):
        return EXIT_ERROR
    code = STATUS_EXIT_CODES.get(status)
    if code is not None:
        return code
    if status.startswith(_EMERGENCY_PREFIX):
        return EXIT_PROTECTION_TRIGGERED
    return EXIT_ERROR


def describe_exit(code: object) -> str:
    """Человеческие слова для кода выхода цикла.

    Неизвестный код называется вслух как неизвестный — выдумывать ему смысл
    опаснее, чем признать пробел.
    """
    if isinstance(code, int) and code in _WORDS:
        return _WORDS[code]
    return f"неизвестный код выхода {code!r}"


def is_by_design(code: object) -> bool:
    """Это штатный исход (система работала правильно и отказалась)?

    ``True`` только для отказа политики. Для всего прочего — ``False``, включая
    неизвестные коды: «не знаю» здесь обязано читаться как «повод сказать вслух».
    """
    return isinstance(code, int) and code in _BY_DESIGN
