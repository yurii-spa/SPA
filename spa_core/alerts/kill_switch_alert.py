"""Тревога о стоп-кране владельцу — ОДНА дверь для всех, кто её поднимает.

Зачем отдельный модуль
----------------------
06.08 владелец решил: «чинить СЕЙЧАС, не дожидаясь просадки» — потому что
чинить сторожа под давлением плохая идея. Починка того дня закрепила ВЫЗОВ
(`category="p0"` появился в двух местах), и четыре теста это подтверждали.

10.08 в 00:52 UTC стоп-кран сработал по-настоящему (EB-02), и стало видно, что
закреплён был вызов, а не доставка:

* `TelegramManager` отставлен в ходе Phase-1 Telegram rebuild — его `_send_raw`
  ВСЕГДА возвращает False и уводит текст в суточный дайджест
  («RETIRED as a Telegram push»). Оба `p0`-вызова были холостыми;
* `cycle_runner` при этом писал в лог «kill-switch alert отправлен владельцу»
  БЕЗУСЛОВНО, не глядя на возврат, — лог утверждал ровно то, чего не было;
* тесты держались за `inspect.getsource(...)` + `assertIn('category="p0"')`.
  Строка в исходнике присутствовала всё это время. Проверялось написание,
  а обещалась доставка.

Владелец в тот день всё же узнал — но по ДРУГОМУ пути: `threat_reactor` шлёт
через `push_policy` (в состоянии видно `entry_pushed: true`). У внутридневной
проверки (ADR-068) такой дублёрки нет вовсе, и там тишина была бы полной.

Контракт
--------
* Канонический путь — `push_policy.push_critical`; ключ ``kill_switch`` стоит
  ПЕРВЫМ в Tier-1 whitelist: канал построен ровно под это событие.
* Edge-триггер по отпечатку (`dedup_key = reason`) — обязателен: дневной цикл
  запускается десятки раз в сутки, внутридневная проверка — каждые 5 минут.
  Одно срабатывание = одно сообщение; тот же отпечаток молчит; ДРУГАЯ причина
  считается новым инцидентом и проходит.
* Возврат УВАЖАЕТСЯ вызывающим. «Не ушло» — отдельное громкое событие, а не
  запись об успехе.
* Никогда не бросает и никогда не решает: порогов и логики стоп-крана здесь
  нет (инв. 1, ADR-034/048) — только доставка сообщения.

LLM здесь запрещён (мониторинг), внешних зависимостей нет.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Optional

__all__ = ["notify_kill_switch", "EVENT_KEY"]

#: Ключ Tier-1 whitelist. Вынесен константой, чтобы опечатка не превращала
#: тревогу в тихую строку дайджеста (off-list ⇒ demote, fail-closed).
EVENT_KEY = "kill_switch"


def notify_kill_switch(
    reason: str,
    *,
    source: str = "",
    data_dir: Optional[str | Path] = None,
    now: Optional[datetime] = None,
    send: bool = True,
) -> bool:
    """Сообщить владельцу, что стоп-кран сработал. Вернуть «ушло ли сейчас».

    Parameters
    ----------
    reason:
        Причина срабатывания как её вычислил стоп-кран. Она же — отпечаток
        инцидента для дедупликации: одна и та же причина не шлётся повторно,
        другая считается новым событием.
    source:
        Человеческое уточнение, откуда пришла тревога (например
        «внутридневная проверка»). Попадает в заголовок; на дедуп НЕ влияет —
        иначе один инцидент, замеченный двумя сторожами, дал бы два сообщения.
    data_dir, now, send:
        Проброс в ``push_policy`` для тестов (свой каталог состояния,
        фиксированные часы, прогон гейта без транспорта).

    Returns
    -------
    bool
        True — сообщение ушло владельцу ПРЯМО СЕЙЧАС. False — не ушло:
        либо тот же отпечаток уже отправлен (законно), либо канал отказал
        (не законно). Различить их снаружи нельзя by design — ``push_policy``
        fail-closed и причину не раскрывает; поэтому вызывающий обязан сказать
        «не ушло» вслух, а не промолчать.

    Не бросает никогда: сбой доставки не имеет права отменить сам стоп-кран.
    """
    title = "KILL SWITCH"
    if source:
        title = f"{title} ({source})"

    try:
        from spa_core.telegram import push_policy

        return bool(
            push_policy.push_critical(
                EVENT_KEY,
                "CRITICAL",
                title,
                str(reason or ""),
                # Отпечаток — ПРИЧИНА, а не источник: один инцидент, замеченный
                # дневным циклом и внутридневной проверкой, обязан быть одним
                # сообщением.
                dedup_key=str(reason) if reason else None,
                data_dir=data_dir,
                now=now,
                send=send,
            )
        )
    except Exception:  # noqa: BLE001 — тревога не имеет права уронить сторожа
        return False
