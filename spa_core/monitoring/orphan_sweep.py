# ── ЧЕТВЁРТАЯ ДВЕРЬ: «содержимое доставлено ИНЫМ ПУТЁМ» (заказ G913 п. 2) ──
#
# Три двери выше спрашивают о КОММИТЕ («уезжал ли он»), о РАЗМЕРЕ работы и о
# ЧЕЛОВЕКЕ за деревом. Ни одна не умеет спросить о БАЙТАХ, и у этой слепоты
# есть живой предмет, найденный самим прибором.
#
# Замер #1038 поднял `~/Documents/SPA_worktrees/yield01` ФАЙЛАМИ: 21 файл,
# 1646 строк, только добавления. Доставка шла файлами, а не `cherry-pick`, —
# значит БАЙТЫ на `origin/main` есть, а КОММИТОВ дерева там нет и не будет
# никогда. Прибор #1039 назвал то же дерево кандидатом СНОВА, и был прав по
# своей мерке и неверен по предмету: поднимать там нечего.
#
# Цена молчания — не лишняя строка отчёта, а приглашение к ОШИБКЕ: заказ
# следующему циклу велит «поднять кандидата», а подъём уже доставленного есть
# либо пустой пуш, либо — если база дерева отстала — доставка УДАЛЕНИЙ под
# видом работы (от вершины те же коммиты выглядят как −3298 строк, замер #1038).
#
# Вопрос измерим дёшево и без сети: совпадают ли блобы путей, добавленных
# невлитыми коммитами, с блобами на `ref` у ПОЛНОГО клона.

#: Исходы четвёртой двери. Перечень ЗАМКНУТ.
#:
#: ``delivered`` — у КАЖДОГО пути байты на `ref` совпали: дерево не сирота.
#: ``pending`` — хоть один путь расходится или на `ref` отсутствует: кандидат
#: настоящий. ``unmeasured`` — спросить не вышло (базы нет, git не ответил,
#: невлитые коммиты не тронули ни одного пути), и это ТРЕТИЙ исход, а не
#: «доставлено»: ошибаться обязано в сторону ОТКАЗА считать работу доставленной.
CONTENT_STATES = ("delivered", "pending", "unmeasured")

#: Исходы оси РАБОЧЕГО ДЕРЕВА (ADR-929). Перечень ЗАМКНУТ.
#:
#: ``carries`` — дерево несёт незакоммиченные байты ВНЕ ``data/``.
#: ``clean`` — измерено и равно нулю: таких байтов нет.
#: ``unmeasured`` — git не ответил о состоянии дерева; это ТРЕТИЙ исход, а не
#: ``clean`` (инв. #17).
#:
#: Ось НЕ судит, годна ли такая работа к подъёму, — ровно как четвёртая дверь
#: не судит годность кандидата (ADR-902). Она ОТРИЦАЕТ право строки «поднимать
#: нечего» звучать как утверждение обо ВСЕЙ работе: коммита у этих байтов нет,
#: поэтому ни один из четырёх вопросов переписи о них не задаётся ВООБЩЕ.
WORKTREE_STATES = ("carries", "clean", "unmeasured")

#: **Число оси есть число ЗАПИСЕЙ состояния, а не файлов.** `git status
#: --porcelain` сворачивает целиком неотслеживаемый каталог в ОДНУ запись
#: (`?? docs/`), поэтому дерево с сотней новых файлов в одном новом каталоге
#: даёт `1`. Снять свёртку мог бы `--untracked-files=all`, но флаг пришлось бы
#: менять у ТОГО ЖЕ вызова, из которого рядом считается `dirty`, то есть
#: изменить публикуемое число соседа ради своего (тот же порядок, что у
#: `_py_files` в ADR-928). Предел объявлен, а не подразумевается; порядок
#: деревьев он не портит — отметка каталога двигается вместе с записью в него.
#: Сцена предела — `TheUntrackedDirectoryCollapse`.
#:
#: Что из грязи ось НЕ считает, и почему это названо, а не умолчано.
#: ``data/`` — живое состояние прода: по `CLAUDE.md` «в боевом мусор в `data/`
#: не мусор, а состояние», и дневной цикл делает его грязным в КАЖДОМ дереве.
#: Считать его значило бы объявить членом оси все деревья и тем обнулить её.
#: Исключённое печатается ЧИСЛОМ рядом — молчаливое сужение было бы тем же
#: дефектом, что и молчаливое сужение дерева в ADR-928.
WORKTREE_IGNORED_PREFIX = "data/"

#: Исходы ОДНОГО пути. ``absent_on_ref`` держится отдельно от ``differs``
#: намеренно: «на `ref` этого файла нет вовсе» и «есть, но другой» —
#: разные состояния, и склеить их значило бы потерять самый частый вид
#: настоящей сироты (новый файл, которого на `main` нет).
PATH_STATES = ("same", "differs", "absent_on_ref", "unmeasured")

#: Журнал объявлений — единственная дверь к живости сессии (`CLAUDE.md`,
#: шаги 0a/0b). Он живёт в ДАННЫХ переписываемого клона, а правило живости — в
#: КОДЕ своего дерева: это два разных вопроса к двум разным деревьям, и путать
#: их легко (урок #193).
JOURNAL_DEFAULT = "data/session_changes.jsonl"

#: Сколько последних записей журнала читать. `None` — все: журнал на 3341
#: запись читается за доли секунды, а окно по числу записей молча выронило бы
#: объявление сессии, которая объявилась один раз и работает третий час.
JOURNAL_LAST = None


#: Отличает «вызывающий НЕ передал правило живости» от «передал `None`».
#: Второе есть ОСОЗНАННОЕ «мерить живость нечем» (так сцена проверяет слепую
#: дверь), первое — обычный путь, где прибор грузит правило сам. Склеить их
#: значило бы лишить сцену возможности назвать слепоту.
_SENTINEL = object()


def _read_journal(cuw, path: Path) -> tuple[Optional[list], Optional[str]]:
    """Записи журнала объявлений. (записи|None, причина слепоты|None).

    Читает их ТЕМ ЖЕ разборщиком, что шаги 0a/0b (`read_entries`), — своего
    парсера JSONL здесь нет намеренно. Журнал не прочитан ⇒ `None`, и дверь
    объявления становится слепой; пустой список записей слепотой НЕ является
    («журнал пуст» есть ответ).
    """
    if cuw is None:
        return None, "правило живости не загружено — журнал разбирать нечем"
    if not path.exists():
        return None, f"журнала объявлений нет ({path})"
    try:
        entries, _bad = cuw.read_entries(path, JOURNAL_LAST)
    except Exception as exc:                                    # noqa: BLE001
        return None, f"журнал объявлений НЕ ПРОЧИТАН ({path}): {type(exc).__name__}: {exc}"
    return list(entries), None


def load_cuw(path: Optional[Path] = None):
    """Загрузить ЕДИНСТВЕННОЕ правило живости сессии. Возвращает (модуль|None, причина).

    Правило живости (`session_state`: пара ``session_pid`` + ``session_pid_start``,
    ADR-453) живёт в `scripts/check_undelivered_work.py` и загружается, а НЕ
    копируется — тем же приёмом, что `spa_core/studio_os/company_truth.py`. Вторая
    копия правила разошлась бы с первой МОЛЧА, и это не гипотеза: ровно так три
    набора адаптеров звались одним именем и три месяца врал `house_view_gap`.

    `None` сам есть измерение: дверь объявления становится СЛЕПОЙ с названной
    причиной, а не отвечает «сессия мертва».
    """
    import importlib.util
    target = Path(path) if path is not None else _REPO_ROOT / "scripts" / "check_undelivered_work.py"
    try:
        spec = importlib.util.spec_from_file_location("_orphan_sweep_cuw", target)
        if spec is None or spec.loader is None:
            return None, f"правило живости не загрузилось: нет загрузчика для {target}"
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    except Exception as exc:                                    # noqa: BLE001
        return None, f"правило живости не загрузилось ({target}): {type(exc).__name__}: {exc}"
    return mod, None


def load_previous(path: str | Path) -> tuple[Optional[dict], Optional[str]]:
    """Прошлая перепись с диска. Возвращает (замер|None, причина слепоты|None).

    **Читать её обязан сам прибор и ДО записи своей.** Артефакт перезаписывается
    каждым прогоном, поэтому слепок предшественника исчезает в тот же миг, и
    «сравнить с прошлым разом» после записи означает сравнить замер с самим
    собой — знакомый класс (ADR-774: сверять одно и то же с самим собой).
    """
    p = Path(path)
    if not p.exists():
        return None, f"прошлой переписи нет на диске ({p}) — это первый прогон, а не «не двинулось»"
    try:
        doc = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return None, f"прошлая перепись НЕ ПРОЧИТАНА ({p}): {type(exc).__name__}: {exc}"
    if not isinstance(doc, dict):
        return None, f"прошлая перепись не словарь, а {type(doc).__name__} — сверять движение не с чем"
    if doc.get("state") != "measured":
        return None, (f"прошлая перепись сама НЕ ИЗМЕРЕНА (state={doc.get('state')!r}) — "
                      f"её HEAD'ам верить нельзя")
    return doc, None


def movement_door(tree: str, head: Optional[str], previous: Optional[dict],
                  previous_blind_reason: Optional[str] = None) -> dict:
    """Двинулось ли дерево с прошлой переписи.

    Оба написания пути приходят из `git worktree list` ОДНОГО И ТОГО ЖЕ клона
    (своё — сейчас, чужое — из своего же артефакта), поэтому сверка идёт
    побайтно и второго правила нормализации здесь НЕ ЗАВОДИТСЯ: лишняя мерка
    рядом с существующей и есть тот дефект, за который `ADAPTER_REGISTRY`
    получил три имени.
    """
    door = {"door": "movement"}
    if previous is None:
        return {**door, "state": "blind",
                "reason": previous_blind_reason or "прошлая перепись не прочитана"}
    if not isinstance(head, str) or not head:
        return {**door, "state": "blind",
                "reason": "у дерева не назван HEAD сейчас — сравнивать нечего"}
    for row in previous.get("rows") or ():
        if not isinstance(row, dict) or row.get("tree") != tree:
            continue
        was = row.get("head")
        if not isinstance(was, str) or not was:
            return {**door, "state": "blind",
                    "reason": (f"в прошлой переписи у дерева HEAD не назван "
                               f"(её исход {row.get('verdict')!r})")}
        if was != head:
            return {**door, "state": "affirms", "previous_head": was,
                    "previous_generated_at": previous.get("generated_at"),
                    "reason": (f"дерево ДВИНУЛОСЬ с прошлой переписи "
                               f"({previous.get('generated_at')}): {was[:9]} → {head[:9]} — "
                               f"кто-то работал в нём ПОСЛЕ неё")}
        return {**door, "state": "silent", "previous_head": was,
                "previous_generated_at": previous.get("generated_at"),
                "reason": (f"HEAD тот же, что в прошлой переписи "
                           f"({previous.get('generated_at')}) — это НЕ брошенность, "
                           f"а отсутствие улик за этот промежуток")}
    return {**door, "state": "blind",
            "reason": ("дерева в прошлой переписи не было вовсе — оно моложе её, "
                       "и промежутка для сравнения нет")}


def _tree_key(cuw, tree: str) -> tuple[Optional[str], Optional[str]]:
    """Путь дерева меркой ЖУРНАЛА — через публичную дверь `tree_of_path`.

    Ту же дверь внутри себя зовёт `worktree_of`, поэтому обе стороны сверки
    приходят к одному написанию ОДНИМ правилом (`/tmp` ≡ `/private/tmp`), и
    второй копии нормализации здесь не заводится.

    **У этого приёма есть ИЗМЕРЕННАЯ ловушка, и она требует проверки, а не
    доверия.** `tree_of_path` написана для пути ФАЙЛА внутри дерева: она режет
    путь на ПЕРВОМ компоненте, который выглядит каталогом репозитория. Если так
    выглядит компонент самого КОРНЯ дерева, ответ будет про ЧУЖОЕ дерево.
    Замер #1037 на живом хосте: из 81 дерева ловушка у **13** — все
    `~/Documents/SPA_Claude/.claude/worktrees/<имя>` сворачиваются в
    `~/Documents/SPA_Claude`, то есть в ПРОД-дерево, которое объявляет каждый
    цикл. Без проверки дверь объявления утверждала бы «в полёте» для тринадцати
    чужих деревьев, и настоящая сирота в любом из них была бы молча укрыта
    чужим объявлением. Шесть из одиннадцати кандидатов того же замера — ровно
    эти деревья; сегодня они не утверждали лишь потому, что прод-дерево в тот
    час было `not_confirmed`. Это везение, а не устройство.

    Поэтому ответ ПРОВЕРЯЕТСЯ: базовое имя ключа обязано совпасть с базовым
    именем дерева. Усечение всегда отбрасывает хотя бы один компонент, то есть
    меняет базовое имя; складывание `/private/tmp` ≡ `/tmp` его не меняет
    никогда. Не совпало ⇒ `None` + причина, то есть дверь СЛЕПА (fail-CLOSED),
    а не «деревья разные».
    """
    try:
        key = cuw.tree_of_path(str(Path(tree) / "spa_core"))
    except Exception as exc:                                    # noqa: BLE001
        return None, f"`tree_of_path` не ответил: {type(exc).__name__}: {exc}"
    if not key:
        return None, "`tree_of_path` не назвал дерево для этого пути"
    if Path(key).name != Path(tree).name:
        return None, (f"мерка журнала свернула путь дерева в ЧУЖОЙ корень "
                      f"({tree} → {key}): компонент самого корня выглядит каталогом "
                      f"репозитория, и объявления этого чужого дерева читались бы как "
                      f"объявления нашего")
    return key, None


def declaration_door(tree: str, entries: Optional[Sequence[dict]], cuw,
                     *, journal_blind_reason: Optional[str] = None,
                     self_session: str = "", ps_probe=None, cmd_probe=None) -> dict:
    """Объявила ли себя сессия, работающая в этом дереве.

    Живость меряет `check_undelivered_work.session_state` — ЕДИНСТВЕННОЕ правило
    дома, загруженное, а не скопированное. `ACTIVE` ⇒ дверь УТВЕРЖДАЕТ полёт;
    все объявления `NOT_CONFIRMED` (или объявлений нет вовсе) ⇒ дверь МОЛЧИТ, и
    это не «брошена»; хоть один `UNKNOWN` без утверждающего ⇒ дверь СЛЕПА
    (fail-CLOSED: неизмеренную живость нельзя читать как её отсутствие).
    """
    door = {"door": "declaration"}
    if cuw is None:
        return {**door, "state": "blind",
                "reason": journal_blind_reason or "правило живости не загружено"}
    if entries is None:
        return {**door, "state": "blind",
                "reason": journal_blind_reason or "журнал объявлений не прочитан"}
    key, key_blind = _tree_key(cuw, tree)
    if key is None:
        return {**door, "state": "blind", "reason": key_blind}
    seen: list[dict] = []
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        try:
            declared = cuw.worktree_of(entry)
        except Exception as exc:                                # noqa: BLE001
            return {**door, "state": "blind",
                    "reason": f"журнал не разобран: {type(exc).__name__}: {exc}"}
        if not declared or declared != key:
            continue
        try:
            state, why = cuw.session_state(
                entry, self_session,
                **({"ps": ps_probe} if ps_probe is not None else {}),
                **({"cmd_probe": cmd_probe} if cmd_probe is not None else {}))
        except Exception as exc:                                # noqa: BLE001
            return {**door, "state": "blind",
                    "reason": f"живость не измерена: {type(exc).__name__}: {exc}"}
        seen.append({"session": entry.get("session"), "ts": entry.get("ts"),
                     "liveness": state, "why": why})
    if not seen:
        return {**door, "state": "silent", "sessions": [],
                "reason": ("дерево не объявил НИКТО — это отсутствие улик, "
                           "а не доказательство брошенности")}
    alive = [s for s in seen if s["liveness"] == cuw.ACTIVE]
    if alive:
        return {**door, "state": "affirms", "sessions": seen,
                "reason": (f"сессия {alive[0]['session']} объявила это дерево и её "
                           f"активность ПОДТВЕРЖДЕНА: {alive[0]['why']}")}
    unknown = [s for s in seen if s["liveness"] == cuw.UNKNOWN]
    if unknown:
        return {**door, "state": "blind", "sessions": seen,
                "reason": (f"живость объявившей сессии {unknown[0]['session']} НЕ ИЗМЕРЕНА: "
                           f"{unknown[0]['why']}")}
    return {**door, "state": "silent", "sessions": seen,
            "reason": (f"объявлений {len(seen)}, ни одно не подтверждает активность "
                       f"(последнее: {seen[-1]['why']}) — улик работы нет, "
                       f"брошенность этим НЕ доказана")}


def _blob(repo: Path, rev: str, path: str) -> tuple[Optional[str], Optional[str]]:
    """Блоб пути в ревизии. `(sha, None)` · `(None, "absent")` · `(None, причина)`.

    Спрашивается `ls-tree`, а НЕ `rev-parse <rev>:<path>`, и это не вкус:
    `rev-parse` отвечает кодом **128** И на «такого пути в этой ревизии нет»,
    И на «это не репозиторий», И на «нет такой ревизии». Склеив их, дверь
    объявила бы НЕПРОЧИТАННОЕ дерево доставленным — ровно fail-OPEN, против
    которого написан инв. #17. `ls-tree` различает три исхода сам: код 0 с
    выводом · код 0 с ПУСТЫМ выводом (пути нет) · ненулевой код (не ответил).
    """
    code, out = _git(repo, "ls-tree", rev, "--", path)
    if code != 0:
        return None, f"git не ответил о {path} в {rev}: код {code}"
    line = out.strip()
    if not line:
        return None, "absent"
    parts = line.split()
    if len(parts) < 3:
        return None, f"git ответил о {path} формой, которой нет в объявлении: {line[:60]!r}"
    return parts[2], None


def content_door(tree: str, lineage: Path, ref: str, *,
                 base: Optional[str], head: Optional[str]) -> dict:
    """Доставлено ли СОДЕРЖИМОЕ невлитых коммитов ИНЫМ путём.

    Вопрос СВОЙ и к трём соседним дверям не сводится: они отвечают о коммите, о
    размере работы и о живости автора, а этот — о БАЙТАХ. Дерево, чьи файлы
    уже лежат на `ref` (доставлены файлами, а не `cherry-pick`), кандидатом не
    является, сколько бы невлитых коммитов оно ни несло.

    Ссылка `ref` спрашивается у ПОЛНОГО клона (ADR-918): усечённый отвечает о
    родословной молча и неверно, и «пути на `main` нет» он сказал бы о половине
    репозитория.
    """
    door = {"door": "content"}
    if not base or not head:
        return {**door, "state": "unmeasured",
                "reason": ("база невлитых коммитов НЕ ИЗМЕРЕНА — спросить о байтах "
                           "нечем (это НЕ «доставлено»)"),
                "paths": {}}
    code, out = _git(Path(tree), "diff", "--name-only", base, head)
    if code != 0:
        return {**door, "state": "unmeasured",
                "reason": f"git не перечислил пути {base[:9]}..{head[:9]}: код {code}",
                "paths": {}}
    paths = [ln.strip() for ln in out.splitlines() if ln.strip()]
    if not paths:
        return {**door, "state": "unmeasured",
                "reason": ("невлитые коммиты не тронули НИ ОДНОГО пути — о байтах "
                           "спрашивать нечего, и «доставлено» из этого не следует"),
                "paths": {}}
    per = {s: [] for s in PATH_STATES}
    for rel in paths:
        mine, why_mine = _blob(Path(tree), head, rel)
        if mine is None:
            per["unmeasured"].append(f"{rel}: в дереве {why_mine}")
            continue
        theirs, why_theirs = _blob(lineage, ref, rel)
        if theirs is None:
            if why_theirs == "absent":
                per["absent_on_ref"].append(rel)
            else:
                per["unmeasured"].append(f"{rel}: на {ref} {why_theirs}")
            continue
        (per["same"] if mine == theirs else per["differs"]).append(rel)
    counts = {s: len(per[s]) for s in PATH_STATES}
    assert sum(counts.values()) == len(paths), "учёт путей не сошёлся"
    if counts["unmeasured"]:
        return {**door, "state": "unmeasured", "paths": counts,
                "reason": (f"о {counts['unmeasured']} пут(и) из {len(paths)} байты НЕ "
                           f"ИЗМЕРЕНЫ ({per['unmeasured'][0]}) — «доставлено» не "
                           f"утверждается"),
                "examples": per["unmeasured"][:3]}
    if counts["differs"] or counts["absent_on_ref"]:
        example = (per["differs"] or per["absent_on_ref"])[0]
        return {**door, "state": "pending", "paths": counts,
                "reason": (f"на {ref} расходится {counts['differs']} и отсутствует "
                           f"{counts['absent_on_ref']} пут(и) из {len(paths)} "
                           f"(например {example}) — кандидат НАСТОЯЩИЙ"),
                "examples": (per["differs"] + per["absent_on_ref"])[:3]}
    return {**door, "state": "delivered", "paths": counts,
            "reason": (f"все {counts['same']} пут(и) невлитых коммитов побайтово "
                       f"СОВПАЛИ с {ref} — содержимое доставлено ИНЫМ путём, "
                       f"поднимать нечего"),
            "examples": per["same"][:3]}


def flight_verdict(doors: Sequence[dict]) -> dict:
    """Свести ответы дверей в один исход. «Брошена» не возвращается НИКОГДА.

    Утверждает хоть одна дверь ⇒ ``in_flight``: улика работы есть, и чужая
    улика сильнее нашего желания поднять. Иначе ``unmeasured`` с перечислением
    того, что сказала КАЖДАЯ дверь, — читатель обязан видеть, молчала она или
    была слепа.
    """
    affirming = [d for d in doors if d.get("state") == "affirms"]
    if affirming:
        return {"flight": "in_flight",
                "flight_evidence": [d["door"] for d in affirming],
                "flight_reason": " · ".join(d.get("reason", "") for d in affirming),
                "flight_doors": list(doors)}
    return {"flight": "unmeasured",
            "flight_evidence": [],
            "flight_reason": " · ".join(
                f"{d.get('door')}: {d.get('state')} — {d.get('reason', '')}" for d in doors),
            "flight_doors": list(doors)}


def _is_repo_dir(path: Path) -> bool:
    """Каталог САМ является git-деревом. ГОТОВАЯ дверь, а не своя копия.

    Признак границы берётся у :func:`membership_reach_census._is_repo_dir`
    (ADR-928) намеренно: своя копия разошлась бы, а разойтись ей есть куда —
    форма метки там `exists`, а НЕ `is_dir`, потому что у worktree `.git` есть
    ФАЙЛ со строкой `gitdir: …`, и спросить про каталог значило бы пропустить
    ровно те деревья, из-за которых граница понадобилась.

    Дверь не ввезлась ⇒ исключение :class:`Unmeasured`. Подставить здесь свою
    проверку значило бы ответить «копий нет» силами двери, которой нет.
    """
    try:
        from spa_core.monitoring.membership_reach_census import _is_repo_dir as _door
    except BaseException as exc:  # noqa: BLE001 — причина обязана быть названа
        raise Unmeasured(
            f"готовая дверь границы дерева не ввезена: {type(exc).__name__}: {exc}"
        ) from exc
    return _door(path)


def common_dir(tree: Path) -> tuple[Optional[str], Optional[str]]:
    """Административный каталог дерева. `(путь, None)` либо `(None, причина)`.

    `--path-format=absolute` обязателен: без него git отвечает ОТНОСИТЕЛЬНЫМ
    путём от дерева, и два разных дерева получили бы одинаковую строку `.git`,
    то есть признак членства превратился бы в признак «у дерева есть `.git`».
    """
    code, out = _git(tree, "rev-parse", "--path-format=absolute", "--git-common-dir")
    if code != 0 or not out.strip():
        return None, f"git не назвал административный каталог: {out.strip() or 'пусто'} (код {code})"
    try:
        return str(Path(out.strip()).resolve()), None
    except OSError as exc:
        return None, f"путь административного каталога не разрешается: {exc}"


def clone_membership(tree: Path, own: Optional[str]) -> dict:
    """Принадлежит ли дерево НАШЕМУ клону. Три исхода, см. :data:`MEMBERSHIP_STATES`.

    `own` не измерен ⇒ исход `unmeasured` у КАЖДОГО дерева: сравнивать с
    неизвестным и звать результат «чужой» значило бы выдать неизмеренное за
    ответ (инв. #17).
    """
    if not own:
        return {"tree": str(tree), "state": "unmeasured",
                "reason": "административный каталог НАШЕГО клона не измерен — "
                          "сравнивать не с чем"}
    cd, why = common_dir(tree)
    if cd is None:
        return {"tree": str(tree), "state": "unmeasured", "reason": why}
    if cd == own:
        return {"tree": str(tree), "state": "member", "common_dir": cd}
    return {"tree": str(tree), "state": "foreign", "common_dir": cd,
            "reason": f"административный каталог ДРУГОЙ: {cd}"}


def walk_trees(roots: Sequence[str], *, depth_max: int = WALK_DEPTH_MAX,
               skip: frozenset = WALK_SKIP_DIRS,
               is_repo_dir=None) -> dict:
    """Деревья, найденные ОБХОДОМ объявленных корней.

    Корни — ВХОД, а не окружение: тест передаёт свои, боевой путь берёт
    :data:`WALK_ROOTS_DEFAULT`.

    Обход НЕ СПУСКАЕТСЯ внутрь найденного дерева — то же сужение, что у
    ADR-928, и оно НАЗВАНО: дерево, зарегистрированное git'ом ВНУТРИ другого
    дерева, обходу невидимо, и ровно поэтому обход не заменяет перечисление, а
    СКЛАДЫВАЕТСЯ с ним (замер 2026-11-05: такое дерево одно —
    `…/sceneB/.claude/worktrees/nested`).

    Третий исход у каждого корня (:data:`ROOT_STATES`) и у оси в целом
    (:data:`WALK_STATES`): корня нет на машине ⇒ `absent`; не читается ⇒
    `unreadable` с причиной. НИ ОДНОГО корня не обойдено ⇒ ось `unmeasured`, и
    «копий не найдено» не утверждается вовсе — на раннере CI не существует ни
    один объявленный корень, и ноль там был бы ложным.
    """
    probe = is_repo_dir or _is_repo_dir
    rows: list[dict] = []
    found: dict[str, str] = {}   # разрешённый путь → путь, каким его нашли
    walked_any = False
    seen_roots: set[str] = set()
    for raw in roots:
        root = Path(raw)
        try:
            key = str(root.resolve())
        except OSError as exc:
            rows.append({"root": str(root), "state": "unreadable",
                         "reason": f"путь не разрешается: {exc}", "trees": 0})
            continue
        if key in seen_roots:  # `/tmp` и `/private/tmp` — один каталог на macOS
            continue
        seen_roots.add(key)
        if not root.exists():
            rows.append({"root": str(root), "state": "absent",
                         "reason": "каталога на этой машине нет", "trees": 0})
            continue
        here_found = 0
        try:
            if probe(root):
                found.setdefault(key, str(root))
                here_found += 1
            stack: list[tuple[Path, int]] = [(root, 0)]
            while stack:
                cur, depth = stack.pop()
                if depth >= depth_max:
                    continue
                with os.scandir(cur) as it:
                    entries = sorted(it, key=lambda e: e.name)
                for ent in entries:
                    try:
                        if not ent.is_dir(follow_symlinks=False):
                            continue
                    except OSError:
                        continue
                    if ent.name in skip:
                        continue
                    child = Path(ent.path)
                    if probe(child):
                        try:
                            ckey = str(child.resolve())
                        except OSError:
                            continue
                        if ckey not in found:
                            found[ckey] = str(child)
                            here_found += 1
                        # Внутрь дерева не спускаемся — сужение названо выше.
                        continue
                    stack.append((child, depth + 1))
        except OSError as exc:
            rows.append({"root": str(root), "state": "unreadable",
                         "reason": f"обход прерван: {type(exc).__name__}: {exc}",
                         "trees": here_found})
            continue
        walked_any = True
        rows.append({"root": str(root), "state": "walked", "reason": None,
                     "trees": here_found})
    unknown = [r["state"] for r in rows if r["state"] not in ROOT_STATES]
    if unknown:  # перечень ROOT_STATES замкнут
        raise Unmeasured(f"исход корня обхода вне перечня: {sorted(set(unknown))}")
    if not walked_any:
        return {"state": "unmeasured", "roots": rows, "found": {},
                "reason": ("ни один объявленный корень не обойдён — «копий не "
                           "найдено» НЕ утверждается: " +
                           " · ".join(f"{r['root']}: {r['state']}" for r in rows))}
    return {"state": "measured", "roots": rows, "found": found, "reason": None}


def discover_trees(repo: Path, *, walk_roots: Sequence[str] = WALK_ROOTS_DEFAULT,
                   depth_max: int = WALK_DEPTH_MAX,
                   is_repo_dir=None) -> dict:
    """Население деревьев = перечисление git'а ∪ обход, с осью ОТКРЫТИЯ у каждого.

    Перечисление остаётся НЕСУЩИМ (его отказ — отказ всей переписи, см.
    :func:`worktrees`), обход только ДОБАВЛЯЕТ. Обратный порядок был бы хуже:
    обход не знает про деревья, зарегистрированные внутри другого дерева, а
    перечисление их знает.

    Дерево, найденное ТОЛЬКО обходом, обязано ещё и ПРИНАДЛЕЖАТЬ нашему клону
    (:func:`clone_membership`), иначе кандидатом в сироты стало бы каждое чужое
    дерево на машине. Зарегистрированному дереву этот вопрос не задаётся: его
    членство доказано самим фактом регистрации, и лишний зов git'а на 75
    деревьях стоил бы секунду ни за что.
    """
    registered = [str(t) for t in worktrees(repo)]
    reg_keys: dict[str, str] = {}
    for t in registered:
        try:
            reg_keys[str(Path(t).resolve())] = t
        except OSError:
            reg_keys[t] = t
    own, own_why = common_dir(repo)
    walk = walk_trees(walk_roots, depth_max=depth_max, is_repo_dir=is_repo_dir)
    membership: list[dict] = []
    walk_members: dict[str, str] = {}
    for key, shown in sorted((walk.get("found") or {}).items()):
        if key in reg_keys:          # уже доказано регистрацией
            walk_members[key] = reg_keys[key]
            continue
        verdict = clone_membership(Path(shown), own)
        membership.append(verdict)
        if verdict["state"] == "member":
            walk_members[key] = shown
    discovery: dict[str, str] = {}
    trees: list[Path] = []
    for key, shown in sorted(reg_keys.items()):
        discovery[shown] = "both" if key in walk_members else "registered_only"
        trees.append(Path(shown))
    for key, shown in sorted(walk_members.items()):
        if key in reg_keys:
            continue
        discovery[shown] = "walk_only"
        trees.append(Path(shown))
    tally = {s: sum(1 for v in discovery.values() if v == s) for s in DISCOVERY_STATES}
    unknown = [v for v in discovery.values() if v not in DISCOVERY_STATES]
    if unknown:  # перечень DISCOVERY_STATES замкнут
        raise Unmeasured(f"исход оси открытия вне перечня: {sorted(set(unknown))}")
    assert sum(tally.values()) == len(discovery), "учёт оси открытия не сошёлся"
    mt = {s: sum(1 for v in membership if v["state"] == s) for s in MEMBERSHIP_STATES}
    assert sum(mt.values()) == len(membership), "учёт принадлежности не сошёлся"
    return {"trees": trees, "discovery": discovery, "discovery_tally": tally,
            "walk_state": walk["state"], "walk_reason": walk.get("reason"),
            "walk_roots": walk["roots"], "walk_depth_max": depth_max,
            "own_common_dir": own, "own_common_dir_reason": own_why,
            "membership_tally": mt,
            "membership_foreign": [v for v in membership if v["state"] == "foreign"],
            "membership_unmeasured": [v for v in membership
                                      if v["state"] == "unmeasured"]}


def worktrees(repo: Path) -> list[Path]:
    """Деревья клона. git не ответил ⇒ исключение, а не пустой список.

    Пустой список здесь был бы ровно той подменой, против которой написан
    инв. #17: «деревьев нет» неотличимо от «не спросили».
    """
    code, out = _git(repo, "worktree", "list", "--porcelain")
    if code != 0:
        raise Unmeasured(f"git не перечислил деревья клона {repo}: {out or 'пусто'} (код {code})")
    found = [Path(line[len("worktree "):]) for line in out.splitlines()
             if line.startswith("worktree ")]
    if not found:
        raise Unmeasured(f"git перечислил ноль деревьев клона {repo} — это не ответ, а молчание")
    return found


def _present(repo: Path, sha: str) -> Optional[bool]:
    """Есть ли коммит в клоне. `None` — git не ответил (не «нет»)."""
    code, _ = _git(repo, "cat-file", "-e", f"{sha}^{{commit}}")
    if code in (0, 1, 128):
        return code == 0
    return None


def _is_ancestor(repo: Path, sha: str, ref: str) -> Optional[bool]:
    """Предок ли `sha` для `ref`. `None` — git не ответил (не «нет»).

    Коды 0/1 — ответ git'а; всё остальное (нет такого ref, оборванный объект)
    есть «не измерено», и склеивать его с «не предок» запрещено: именно это
    склеивание родило ложного кандидата в первой редакции прибора ADR-918.
    """
    code, _ = _git(repo, "merge-base", "--is-ancestor", sha, ref)
    if code in (0, 1):
        return code == 0
    return None


def measure_span(tree: Path, lineage: Path, sha: str, ref: str,
                 limit: int = SPAN_LIMIT) -> dict:
    """Сколько коммитов работы несёт дерево поверх `ref`.

    Шагаем от HEAD по ПЕРВЫМ родителям, пока не встретим коммит, который в полном
    клоне есть И является предком `ref`. Число шагов до него и есть пролёт.
    Не дошли за `limit` шагов ⇒ ``unmeasured`` с названной причиной.
    """
    cur = sha
    for step in range(1, limit + 1):
        code, parents = _git(tree, "rev-list", "--parents", "-n", "1", cur)
        if code != 0:
            return {"span": None, "span_state": "unmeasured",
                    "reason": f"git не назвал родителей {cur[:9]} в {tree}: код {code}"}
        parts = parents.split()
        if len(parts) < 2:
            return {"span": None, "span_state": "unmeasured",
                    "reason": f"у {cur[:9]} нет родителя (корень истории либо граница усечения)"}
        parent = parts[1]
        present = _present(lineage, parent)
        if present is None:
            return {"span": None, "span_state": "unmeasured",
                    "reason": f"полный клон не ответил, есть ли у него {parent[:9]}"}
        if present:
            anc = _is_ancestor(lineage, parent, ref)
            if anc is None:
                return {"span": None, "span_state": "unmeasured",
                        "reason": f"полный клон не ответил, предок ли {parent[:9]} для {ref}"}
            if anc:
                lag = _count_span(lineage, f"{parent}..{ref}")
                if lag is None:
                    return {"span": step, "span_state": "measured", "base": parent,
                            "base_lag": None, "base_lag_state": "unmeasured",
                            "reason_base_lag": (f"полный клон не сосчитал, насколько {parent[:9]} "
                                                f"отстаёт от {ref}")}
                return {"span": step, "span_state": "measured", "base": parent,
                        "base_lag": lag, "base_lag_state": "measured"}
        cur = parent
    return {"span": None, "span_state": "unmeasured",
            "reason": (f"за {limit} шагов по первым родителям не встретилось коммита, "
                       f"который на {ref} есть — история дерева чужая, размер работы "
                       f"НЕ ИЗМЕРЕН (пределом его называть нельзя)")}


def _count_span(repo: Path, span: str) -> Optional[int]:
    """`git rev-list --count <span>`. `None` — git не ответил (не ноль).

    Ноль здесь ЗНАЧАЩЕЕ значение («база и есть вершина `ref`»), поэтому склеить
    его с «не сосчитали» нельзя ни при каких условиях: ровно эта пара и
    различает свежую сироту от заброшенной ветки четырёхмесячной давности.
    """
    code, out = _git(repo, "rev-list", "--count", span)
    if code != 0:
        return None
    try:
        return int(out)
    except ValueError:
        return None


#: Буквы состояния `git status --porcelain`. Пробел — полноправная буква
#: (` M` = «изменено, не добавлено»), и именно он делает разбор по КОЛОНКЕ
#: негодным: общая дверь `_git` отдаёт вывод `.strip()`-нутым, поэтому ПЕРВАЯ
#: строка теряет ведущий пробел, а остальные — нет. Срез `line[3:]` съедал у
#: неё первый символ пути МОЛЧА: замер 05.11 дал `ata/adapter_status.json`
#: вместо `data/adapter_status.json`, то есть путь, который обязан был
#: попасть в «не считано», уехал в НАХОДКУ. Счётчик `dirty` рядом этого не
#: замечает ПО ПОСТРОЕНИЮ — он считает строки, а не разбирает их.
#:
#: Чинится здесь, а не в `_git`: у общей двери ЧЕТЫРЕ других читателя
#: (`ls-tree`, `worktree list`, `rev-list`, `diff --name-only`), и ни один из
#: них на ведущий пробел не опирается — правка двери была бы правкой чужого
#: ответа ради своего (тот же порядок, что у `_py_files` в ADR-928).
_PORCELAIN_STATUS = " MADRCU?!T"
_PORCELAIN_RE = re.compile(rf"^[{re.escape(_PORCELAIN_STATUS)}]{{1,2}} (.+)$")


def _porcelain_path(line: str) -> Optional[str]:
    """Путь из строки ``git status --porcelain``. Не разобрали ⇒ ``None``.

    Буквы состояния берутся ЖАДНО (две, иначе одна) — так строка переживает
    и обычный вид ` M путь`, и обрезанный вид `M путь` после `.strip()`.
    """
    m = _PORCELAIN_RE.match(line)
    if not m:
        return None
    path = m.group(1)
    # Переименование git печатает как `старое -> новое`; предмет — НОВОЕ имя,
    # потому что именно его байты лежат в дереве.
    if " -> " in path:
        path = path.split(" -> ", 1)[1]
    return path or None


def _mtime(path: Path) -> Optional[float]:
    """Отметка файла. Не прочитали ⇒ ``None`` (не ноль и не «сейчас»)."""
    try:
        return path.stat().st_mtime
    except OSError:
        return None


def worktree_door(status_code: int, status_out: str, *,
                  tree: Optional[Path] = None, mtime_probe=None) -> dict:
    """Ось РАБОЧЕГО ДЕРЕВА: несёт ли дерево незакоммиченные байты вне ``data/``.

    Берёт ГОТОВЫЙ ответ ``git status --porcelain``, который строка и так уже
    спросила: своя дверь к git означала бы второй обход на то же дерево и —
    хуже — ответ о ДРУГОМ моменте, чем счётчик ``dirty`` рядом.

    git не ответил ⇒ ``unmeasured`` с причиной, а не ``clean``: «не спросили»
    обязано отличаться от «спросили и ничего нет» (инв. #17).

    **Отметка — ВХОД, а не окружение** (`.claude/rules/deployment.md`, приём №1):
    ``mtime_probe`` по умолчанию спрашивает настоящую ФС, а тест передаёт свою.
    Отметка нужна затем, что СЧЁТ путей на этот вопрос не отвечает: дерево с
    2916 чужими заметками месячной давности и дерево, в котором цикл умер час
    назад, по счёту неразличимы, а по отметке — нет. Это ИЗМЕРЕНИЕ, а не
    суждение о готовности работы (судить её прибору запрещено, ADR-908).
    """
    probe = mtime_probe or _mtime
    if status_code != 0:
        return {"worktree": "unmeasured", "worktree_reason":
                f"git не назвал состояние дерева (код {status_code}): "
                f"{(status_out or 'пусто')[:120]}",
                "worktree_outside": None, "worktree_ignored": None,
                "worktree_examples": [], "worktree_newest": None,
                "worktree_newest_state": "unmeasured"}
    outside, ignored, unparsed = [], 0, []
    for line in status_out.splitlines():
        if not line.strip():
            continue
        path = _porcelain_path(line)
        if path is None:
            # Строку не разобрали ⇒ она НАЗЫВАЕТСЯ, а не пропускается молча:
            # пропуск сделал бы «не разобрали» неотличимым от «под `data/`».
            unparsed.append(line[:60])
            continue
        # Путь со спецсимволами git отдаёт в кавычках, и тогда префикс не
        # совпадёт ⇒ путь попадёт в `outside`. Ошибка идёт в сторону НАХОДКИ
        # (лишнее имя названо), а не в сторону молчания, и это выбор.
        if path.startswith(WORKTREE_IGNORED_PREFIX):
            ignored += 1
            continue
        outside.append(path)
    if unparsed:
        # Хоть одна неразобранная строка ⇒ ось НЕ ИЗМЕРЕНА целиком: мы не
        # знаем, лежал ли под ней путь вне `data/`, а «carries 0» утверждал бы,
        # что не лежал. Ошибаться обязано в сторону ОТКАЗА отвечать.
        return {"worktree": "unmeasured", "worktree_reason":
                f"не разобрано строк состояния: {len(unparsed)} "
                f"(например {unparsed[0]!r})",
                "worktree_outside": None, "worktree_ignored": ignored,
                "worktree_examples": [], "worktree_newest": None,
                "worktree_newest_state": "unmeasured"}
    if not outside:
        # Отметки нет И НЕ ДОЛЖНО БЫТЬ: мерить нечего. Это НЕ «не измерено» —
        # у чистого дерева вопрос не возникает.
        return {"worktree": "clean", "worktree_reason": None,
                "worktree_outside": 0, "worktree_ignored": ignored,
                "worktree_examples": [], "worktree_newest": None,
                "worktree_newest_state": "no_subject"}
    stamps, unread = [], 0
    for rel in outside:
        got = probe((tree / rel) if tree is not None else Path(rel))
        if got is None:
            unread += 1
        else:
            stamps.append(got)
    if stamps:
        newest, newest_state = max(stamps), "measured"
    else:
        # Ни один путь не прочитан ⇒ ТРЕТИЙ исход с причиной, а не «давно».
        newest, newest_state = None, "unmeasured"
    return {"worktree": "carries",
            "worktree_reason": (f"отметка НЕ ПРОЧИТАНА ни у одного из {unread} путей"
                                if newest_state == "unmeasured" else None),
            "worktree_outside": len(outside),
            "worktree_ignored": ignored,
            "worktree_unread_stamps": unread,
            "worktree_examples": sorted(outside)[:3],
            "worktree_newest": newest,
            "worktree_newest_state": newest_state}


def order_carrying(rows: Sequence[dict]) -> list[dict]:
    """Деревья, несущие незакоммиченные байты, — в порядке НОВИЗНЫ.

    Дверь именованная, а не выражение внутри :func:`sweep`, именно ради
    контроля: сцена, сверявшая порядок со СВОЕЙ копией правила, оставила
    мутанта «сортировать по счёту» ЖИВЫМ (замер #1043, мутация M5) — копия
    правила мерит себя, а не прибор.

    Счёт путей на вопрос оси не отвечает: замер 05.11 поставил первым
    прод-дерево с 2916 чужими заметками месячной давности, тогда как предмет —
    дерево `c1042` с 13 путями, в котором часом ранее умер цикл. Дерево с НЕ
    ПРОЧИТАННОЙ отметкой уходит в КОНЕЦ: «отметки нет» не выдаётся ни за
    свежее, ни за давнее.
    """
    return sorted((r for r in rows if r.get("worktree") == "carries"),
                  key=lambda x: (x.get("worktree_newest") is None,
                                 -(x.get("worktree_newest") or 0.0)))


def _tree_row(tree: Path, lineage: Path, ref: str, *, limit: int = SPAN_LIMIT) -> dict:
    code, sha = _git(tree, "rev-parse", "HEAD")
    if code != 0 or not sha:
        return {"tree": str(tree), "verdict": "no_head",
                "reason": f"git не назвал HEAD дерева: {sha or 'пусто'} (код {code})",
                # Ось рабочего дерева у такой строки НЕ ИЗМЕРЕНА, и это
                # печатается: у дерева без HEAD git не ответил ни на один
                # вопрос, и «чисто» здесь было бы выдумкой.
                "worktree": "unmeasured",
                "worktree_reason": "git не назвал HEAD — о дереве не спрошено ничего",
                "worktree_outside": None, "worktree_ignored": None,
                "worktree_examples": []}
    dcode, dout = _git(tree, "status", "--porcelain")
    dirty = len([x for x in dout.splitlines() if x.strip()]) if dcode == 0 else None
    row = {"tree": str(tree), "head": sha, "dirty": dirty}
    # Ось РАБОЧЕГО ДЕРЕВА (ADR-929) живёт на КАЖДОЙ строке, а не только у
    # кандидатов: её предмет — ровно те деревья, которые вердикт `on_main`
    # из кандидатов ИСКЛЮЧАЕТ, и спрашивать её у одних кандидатов значило бы
    # не задать её там, где она единственно и нужна.
    row.update(worktree_door(dcode, dout, tree=tree))

    present = _present(lineage, sha)
    if present is None:
        return {**row, "verdict": "unmeasured",
                "reason": f"полный клон не ответил, есть ли у него {sha[:9]}"}
    if not present:
        row["verdict"] = "never_pushed"
        row["reason"] = (f"коммита {sha[:9]} нет в полном клоне {lineage} ВОВСЕ — "
                         f"он не уезжал ни под каким именем")
        row.update(measure_span(tree, lineage, sha, ref, limit=limit))
        return row

    anc = _is_ancestor(lineage, sha, ref)
    if anc is None:
        return {**row, "verdict": "unmeasured",
                "reason": f"полный клон не ответил, предок ли {sha[:9]} для {ref}"}
    row["verdict"] = "on_main" if anc else "off_main_branch"
    if not anc:
        row["reason"] = (f"коммит {sha[:9]} в полном клоне ЕСТЬ, но {ref} его не содержит — "
                         f"работа на невлитой ветке, это вопрос мержа, а не подъёма")
    return row


def sweep(repo_root: str | Path = _REPO_ROOT, *, ref: str = REF_DEFAULT,
          lineage_candidates: Sequence[str] = LINEAGE_CANDIDATES_DEFAULT,
          limit: int = SPAN_LIMIT,
          fresh_base_lag_max: int = FRESH_BASE_LAG_MAX,
          previous: Optional[dict] = None,
          previous_blind_reason: Optional[str] = None,
          journal: Optional[str | Path] = None,
          cuw=_SENTINEL, cuw_path: Optional[Path] = None,
          self_session: str = "", ps_probe=None, cmd_probe=None,
          walk_roots: Sequence[str] = WALK_ROOTS_DEFAULT,
          walk_depth_max: int = WALK_DEPTH_MAX,
          is_repo_dir=None) -> dict:
    """Перепись сирот. Возвращает замер; НИЧЕГО не правит и не поднимает.

    `previous` — прошлая перепись (см. :func:`load_previous`): её обязан
    прочитать вызывающий ДО записи новой, иначе дверь движения сверит замер с
    самим собой. Не передана ⇒ дверь движения СЛЕПА с названной причиной, а не
    отвечает «не двинулось».
    """
    repo = Path(repo_root)
    try:
        lineage, rejected = pick_lineage_repo(list(lineage_candidates))
    except Unmeasured as exc:
        return {"state": "unmeasured", "reason": str(exc), "ref": ref,
                "lineage_repo": None, "lineage_rejected": [], "rows": [], "tally": {}}
    try:
        # Население = перечисление git'а ∪ ОБХОД объявленных корней (ADR-930).
        # Перечисление остаётся несущим: его отказ — отказ всей переписи.
        found = discover_trees(repo, walk_roots=walk_roots,
                               depth_max=walk_depth_max, is_repo_dir=is_repo_dir)
        trees = found["trees"]
    except Unmeasured as exc:
        return {"state": "unmeasured", "reason": str(exc), "ref": ref,
                "lineage_repo": str(lineage),
                "lineage_rejected": rejected, "rows": [], "tally": {}}

    rows = [_tree_row(t, lineage, ref, limit=limit) for t in trees]
    # Ось ОТКРЫТИЯ живёт на КАЖДОЙ строке: «кто это дерево увидел» есть
    # свойство строки, а не сводки, и читателю вердикта она нужна там же, где
    # вердикт. У дерева, найденного ТОЛЬКО обходом, печатается ещё и оговорка:
    # его `.git` указывает на ОБЩИЙ административный каталог, поэтому `HEAD`,
    # база и пролёт описывают коммит ОРИГИНАЛА, а не байты, уникальные для
    # копии. Своя у копии ровно ось рабочего дерева — и ровно она была слепа.
    for row in rows:
        row["discovery"] = found["discovery"].get(row["tree"], "both")
        if row["discovery"] == "walk_only":
            row["discovery_caveat"] = (
                "дерево-КОПИЯ: административный каталог общий с оригиналом ⇒ "
                "HEAD/база/пролёт — о коммите ОРИГИНАЛА; своя у копии ось "
                "рабочего дерева (индекс тоже общий, и это НЕ ДОКЛАДЫВАЕТСЯ)")
    worktree_tally = {s: sum(1 for r in rows if r.get("worktree") == s)
                      for s in WORKTREE_STATES}
    unknown_wt = [r.get("worktree") for r in rows
                  if r.get("worktree") not in WORKTREE_STATES]
    if unknown_wt:  # перечень WORKTREE_STATES замкнут
        raise Unmeasured(
            f"исход оси рабочего дерева вне перечня: {sorted(set(map(str, unknown_wt)))}")
    assert sum(worktree_tally.values()) == len(rows), "учёт рабочего дерева не сошёлся"
    carrying = order_carrying(rows)
    tally = {v: sum(1 for r in rows if r["verdict"] == v) for v in VERDICTS}
    unknown = [r["verdict"] for r in rows if r["verdict"] not in VERDICTS]
    if unknown:  # перечень VERDICTS замкнут — расхождение есть дефект прибора
        return {"state": "unmeasured",
                "reason": f"исход вне объявленного перечня: {sorted(set(unknown))}",
                "ref": ref, "lineage_repo": str(lineage),
                "lineage_rejected": rejected, "rows": rows, "tally": tally}
    assert sum(tally.values()) == len(rows), "учёт не сошёлся"
    candidates = [r for r in rows if r["verdict"] in CANDIDATE_VERDICTS]

    # Третий вопрос — только КАНДИДАТАМ: он про решение «поднимать ли», а дерево,
    # чей коммит уже на `ref`, поднимать и не предлагается.
    if cuw is _SENTINEL:
        cuw, cuw_blind = load_cuw(cuw_path)
    else:
        cuw_blind = None if cuw is not None else "правило живости не передано вызывающим"
    journal_path = Path(journal) if journal is not None else repo / JOURNAL_DEFAULT
    entries, journal_blind = _read_journal(cuw, journal_path)
    for row in candidates:
        doors = [
            declaration_door(row["tree"], entries, cuw,
                             journal_blind_reason=cuw_blind or journal_blind,
                             self_session=self_session,
                             ps_probe=ps_probe, cmd_probe=cmd_probe),
            movement_door(row["tree"], row.get("head"), previous, previous_blind_reason),
        ]
        row.update(flight_verdict(doors))
        # Четвёртая дверь (заказ G913 п. 2) — о БАЙТАХ, и она ОТДЕЛЬНАЯ от
        # полёта: «кто-то работает» и «работа уже на `ref`» — разные причины
        # не поднимать, и склеить их значило бы не отличить живого автора от
        # доставленной работы.
        cd = content_door(row["tree"], lineage, ref,
                          base=row.get("base"), head=row.get("head"))
        if cd["state"] not in CONTENT_STATES:  # перечень замкнут
            raise Unmeasured(f"исход четвёртой двери вне перечня: {cd['state']!r}")
        row["content"] = cd["state"]
        row["content_reason"] = cd.get("reason")
        row["content_paths"] = cd.get("paths") or {}
        row["content_examples"] = cd.get("examples") or []
    flight_tally = {s: sum(1 for r in candidates if r.get("flight") == s)
                    for s in FLIGHT_STATES}
    assert sum(flight_tally.values()) == len(candidates), "учёт полёта не сошёлся"
    content_tally = {s: sum(1 for r in candidates if r.get("content") == s)
                     for s in CONTENT_STATES}
    assert sum(content_tally.values()) == len(candidates), "учёт содержимого не сошёлся"

    fresh = [r for r in candidates
             if r.get("base_lag_state") == "measured"
             and r["base_lag"] <= fresh_base_lag_max]
    discovery_tally = found["discovery_tally"]
    assert sum(discovery_tally.values()) == len(rows), "учёт оси открытия не сошёлся"
    return {"state": "measured", "ref": ref, "lineage_repo": str(lineage),
            "lineage_rejected": rejected, "repo_root": str(repo),
            "trees": len(rows), "rows": rows, "tally": tally,
            # Ось ОТКРЫТИЯ (ADR-930). `walk_state` ОБЯЗАН печататься рядом с
            # числом: `walk_only 0` при необойдённых корнях есть ложный ноль.
            "discovery_tally": discovery_tally,
            "walk_state": found["walk_state"],
            "walk_reason": found["walk_reason"],
            "walk_roots": found["walk_roots"],
            "walk_depth_max": found["walk_depth_max"],
            "own_common_dir": found["own_common_dir"],
            "own_common_dir_reason": found["own_common_dir_reason"],
            "membership_tally": found["membership_tally"],
            "membership_foreign": found["membership_foreign"],
            "membership_unmeasured": found["membership_unmeasured"],
            "worktree_tally": worktree_tally,
            "worktree_ignored_prefix": WORKTREE_IGNORED_PREFIX,
            # Деревья, несущие незакоммиченные байты вне `data/`. Годность к
            # подъёму НЕ судится (ADR-929) — называется только факт.
            "worktree_carrying": carrying,
            "candidates": candidates,
            "fresh_base_lag_max": fresh_base_lag_max,
            "candidates_with_measured_span": [
                r for r in candidates if r.get("span_state") == "measured"],
            "fresh_candidates": fresh,
            "flight_tally": flight_tally,
            "content_tally": content_tally,
            # Что реально ПРЕДЛАГАЕТСЯ поднять: свежие кандидаты, у которых
            # содержимое НЕ доставлено иным путём. Дерево с `delivered`
            # остаётся в `fresh_candidates` намеренно — замер его видел, — но
            # в заказ следующему циклу не попадает.
            "fresh_delivered": [r for r in fresh if r.get("content") == "delivered"],
            "fresh_to_raise": [r for r in fresh if r.get("content") != "delivered"],
            "journal": str(journal_path),
            "previous_generated_at": (previous or {}).get("generated_at"),
            "previous_blind_reason": None if previous else (
                previous_blind_reason or "прошлая перепись не передана вызывающим"),
            "fresh_in_flight": [r for r in fresh if r.get("flight") == "in_flight"],
            "fresh_flight_unmeasured": [
                r for r in fresh if r.get("flight") != "in_flight"],
            "span_limit": limit}


def report(doc: dict) -> list[str]:
    """Строки отчёта. Выбор клона ПЕЧАТАЕТСЯ — иначе читатель не узнает, о чьём `main` ответ."""
    if doc.get("state") == "unmeasured":
        return [f"⚠️ перепись сирот НЕ ИЗМЕРЕНА: {doc.get('reason')}"]
    lines = [f"перепись сирот: деревьев {doc['trees']}, ссылка {doc['ref']}",
             f"   родословную спрашивали у ПОЛНОГО клона: {doc['lineage_repo']}"]
    for r in doc.get("lineage_rejected", []):
        lines.append(f"   отвергнут клон {r['repo']}: {r.get('reason', r.get('state'))}")
    # Ось ОТКРЫТИЯ печатается ВЫШЕ исходов намеренно: она отвечает на вопрос
    # «о скольки деревьях вообще спросили», и прочитать исходы, не зная его,
    # значит прочитать долю без знаменателя (ADR-930).
    dt = doc.get("discovery_tally")
    if dt is not None:
        if doc.get("walk_state") == "measured":
            lines.append("   ось ОТКРЫТИЯ: "
                         + " · ".join(f"{k} {dt.get(k, 0)}" for k in DISCOVERY_STATES)
                         + f" (обход глубины {doc.get('walk_depth_max')} по "
                           f"{len(doc.get('walk_roots') or ())} объявленным корням)")
        else:
            # Ложный ноль запрещён: «копий не найдено» и «не обходили» —
            # разные утверждения (инв. #17).
            lines.append(f"   ⚠️ ось ОТКРЫТИЯ НЕ ИЗМЕРЕНА: {doc.get('walk_reason')}"
                         " — число `walk_only` НЕ утверждается")
        for r in doc.get("walk_roots") or ():
            if r.get("state") != "walked":
                lines.append(f"      ▫️ корень {r['state']}: {r['root']} — {r.get('reason')}")
        mt = doc.get("membership_tally") or {}
        if sum(mt.values()):
            lines.append("      принадлежность НАШЕМУ клону (спрошена у "
                         f"{sum(mt.values())} дерев(а), найденных только обходом): "
                         + " · ".join(f"{k} {mt.get(k, 0)}" for k in MEMBERSHIP_STATES)
                         + f"; административный каталог нашего клона — "
                           f"{doc.get('own_common_dir') or 'НЕ ИЗМЕРЕН: ' + str(doc.get('own_common_dir_reason'))}")
        for v in doc.get("membership_unmeasured") or ():
            lines.append(f"      ⚠️ принадлежность НЕ ИЗМЕРЕНА: {v['tree']} — {v.get('reason')}")
        # Слепое пятно ОБХОДА называется поимённо тем же порядком, что и слепое
        # пятно перечисления: «обход добавляет» было бы похвальбой, если бы
        # цена сужения («внутрь дерева не спускаемся») осталась непечатаемой.
        for r in doc.get("rows", []):
            if r.get("discovery") == "registered_only":
                lines.append(f"   ▫️ ТОЛЬКО ПЕРЕЧИСЛЕНИЕМ (обход его не достаёт "
                             f"— дерево зарегистрировано ВНУТРИ другого дерева "
                             f"либо вне объявленных корней): {r['tree']}")
        for r in doc.get("rows", []):
            if r.get("discovery") == "walk_only":
                lines.append(f"   🆕 ТОЛЬКО ОБХОДОМ (перечисление git'а его НЕ "
                             f"видит): {r['tree']}")
                lines.append(f"      {r.get('discovery_caveat')}")
    t = doc["tally"]
    lines.append("   исходы: " + " · ".join(f"{k} {t[k]}" for k in VERDICTS))
    measured = doc["candidates_with_measured_span"]
    fresh = doc["fresh_candidates"]
    lines.append(f"   кандидатов {len(doc['candidates'])}, из них пролёт ИЗМЕРЕН у "
                 f"{len(measured)}, база СВЕЖАЯ (отстаёт ≤ "
                 f"{doc['fresh_base_lag_max']}) у {len(fresh)}")
    for r in sorted(fresh, key=lambda x: x["span"]):
        if r.get("content") == "delivered":
            head = "✅ НЕ ПОДНИМАТЬ (СОДЕРЖИМОЕ УЖЕ ДОСТАВЛЕНО)"
        elif r.get("flight") == "in_flight":
            head = "🛫 НЕ ПОДНИМАТЬ (В ПОЛЁТЕ)"
        else:
            head = "🔶 ПОДНЯТЬ"
        lines.append(f"   {head}: {r['tree']} · {r['head'][:9]} · пролёт {r['span']} "
                     f"коммит(ов) · база отстаёт {r['base_lag']} · грязных файлов {r['dirty']}")
        # Четвёртая дверь печатается ВСЕГДА: «байты сверены и совпали» и «байты
        # не сверялись» обязаны выглядеть по-разному (инв. #17).
        lines.append(f"      содержимое ({r.get('content')}): {r.get('content_reason')}")
        if r.get("flight") == "in_flight":
            lines.append(f"      улика работы ({', '.join(r.get('flight_evidence') or ())}): "
                         f"{r.get('flight_reason')}")
        else:
            lines.append(f"      полёт НЕ ИЗМЕРЕН (брошенность этим НЕ доказана): "
                         f"{r.get('flight_reason')}")
    for r in sorted(measured, key=lambda x: (x.get("base_lag") is None, x.get("base_lag") or 0)):
        if r in fresh:
            continue
        lag = (f"{r['base_lag']}" if r.get("base_lag_state") == "measured"
               else "НЕ ИЗМЕРЕНО")
        lines.append(f"   ▫️ не свежая: {r['tree']} · {r['head'][:9]} · пролёт {r['span']} · "
                     f"база отстаёт {lag}")
    for r in doc["candidates"]:
        if r.get("span_state") != "measured":
            lines.append(f"   ▫️ пролёт НЕ ИЗМЕРЕН: {r['tree']} · {r.get('reason', '')[:90]}")
    # «Поднимать нечего» — утверждение о КОММИТАХ, и оно обязано называть свой
    # предмет (ADR-929). Прежняя безусловная форма читалась как «работы нигде
    # нет»: 05.11 она была напечатана над деревом `c1042`, которое перепись
    # перечислила и у которого сама записала `dirty=13`, — а в нём лежала
    # законченная работа цикла #1042 (ADR-928, тест, журнал, заказ).
    wt = doc.get("worktree_tally") or {}
    carrying = doc.get("worktree_carrying") or []
    if not fresh:
        lines.append("   ✅ поднимать ПО КОММИТАМ нечего: ни одного кандидата "
                     "со свежей базой")
    elif not doc.get("fresh_to_raise"):
        lines.append(f"   ✅ поднимать ПО КОММИТАМ нечего: все {len(fresh)} свежих "
                     f"кандидат(а) несут содержимое, УЖЕ доставленное на "
                     f"{doc['ref']} иным путём")
    if wt:
        lines.append("   ось РАБОЧЕГО ДЕРЕВА (ни один из четырёх вопросов выше о ней "
                     "не спрашивает — у этих байтов нет коммита): "
                     + " · ".join(f"{k} {wt.get(k, 0)}" for k in WORKTREE_STATES)
                     + f" — не считано грязное под {doc.get('worktree_ignored_prefix')!r}"
                       " (живое состояние, грязно в каждом дереве)")
        for r in carrying[:5]:
            if r.get("worktree_newest_state") == "measured":
                import datetime as _dt
                when = _dt.datetime.fromtimestamp(
                    r["worktree_newest"], _dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            else:
                when = f"НЕ ИЗМЕРЕНА ({r.get('worktree_reason')})"
            lines.append(f"   🗃 НЕСЁТ НЕЗАКОММИЧЕННОЕ ({r.get('worktree_outside')} путей "
                         f"вне {doc.get('worktree_ignored_prefix')!r}, "
                         f"ещё {r.get('worktree_ignored')} внутри): {r['tree']}")
            lines.append(f"      новейший байт: {when} · например: "
                         f"{', '.join(r.get('worktree_examples') or ())}"
                         " — ГОДНОСТЬ К ПОДЪЁМУ НЕ СУДИТСЯ, решение за читателем")
        if len(carrying) > 5:
            lines.append(f"   🗃 …и ещё {len(carrying) - 5} дерев(о/а) с "
                         "незакоммиченными байтами вне "
                         f"{doc.get('worktree_ignored_prefix')!r}")
        for r in (x for x in doc.get("rows", []) if x.get("worktree") == "unmeasured"):
            lines.append(f"   ⚠️ ось рабочего дерева НЕ ИЗМЕРЕНА: {r['tree']} · "
                         f"{r.get('worktree_reason')}")
    ct = doc.get("content_tally")
    if ct:
        lines.append("   содержимое у кандидатов: "
                     + " · ".join(f"{k} {ct.get(k, 0)}" for k in CONTENT_STATES)
                     + " — «НЕ ИЗМЕРЕНО» доставленным не считается")
    ft = doc.get("flight_tally")
    if ft:
        lines.append("   полёт у кандидатов: " + " · ".join(f"{k} {ft.get(k, 0)}" for k in FLIGHT_STATES)
                     + " — «брошена» исходом не является (доказать её нечем)")
    if doc.get("previous_blind_reason"):
        lines.append(f"   дверь ДВИЖЕНИЯ слепа: {doc['previous_blind_reason']}")
    return lines


def _stamp_now(now=None) -> str:
    import datetime as _dt
    moment = now or _dt.datetime.now(_dt.timezone.utc)
    return moment.strftime("%Y-%m-%dT%H:%M:%SZ")


def run(repo_root: str | Path = _REPO_ROOT, *, data_dir: Optional[Path] = None,
        dest: Optional[Path] = None, write: bool = True, now=None, **kw) -> dict:
    """Один замер + запись артефакта для шага 0-офис.

    Такта у этого замера НЕТ намеренно: он стои́т секунды, а заказ G911 п. 1
    предписывает его ПЕРВЫМ действием каждого цикла — гейт по сроку сделал бы
    «не мерили в этом цикле» неотличимым от «кандидатов нет».
    """
    root = Path(repo_root)
    source = Path(data_dir) if data_dir is not None else root / "data"
    target = Path(dest) if dest is not None else source / ARTIFACT
    # Прошлый слепок читается ДО записи нового: артефакт перезаписывается этим же
    # вызовом, и после записи дверь движения сверяла бы замер с самим собой.
    if "previous" not in kw:
        kw["previous"], kw["previous_blind_reason"] = load_previous(target)
    doc = sweep(root, **kw)
    doc["invoked_by"] = call_provenance(tree_root=root)
    doc["generated_at"] = _stamp_now(now)
    if write:
        target.parent.mkdir(parents=True, exist_ok=True)
        atomic_save(doc, str(target))
    return {"measured": True, "doc": doc, "artifact": str(target)}


def format_report(doc: dict, max_rows: int = 5) -> list[str]:
    """Отрисовка для шага 0-офис. Правило отрисовки живёт У ПРОИЗВОДИТЕЛЯ —
    вторая копия у читателя разошлась бы с ним молча (ADR-220)."""
    head = ["— перепись СИРОТ: готовая работа предшественника вне `origin/main` (ADR-923) —"]
    return head + ["   " + line for line in report(doc)]


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Коды: 0 — поднимать нечего · 1 — кандидат НАЗВАН · 2 — НЕ ИЗМЕРЕНО."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo-root", default=str(_REPO_ROOT),
                    help="клон, чьи деревья переписываются (умолчание — своё)")
    ap.add_argument("--ref", default=REF_DEFAULT)
    ap.add_argument("--lineage", action="append", default=None,
                    help="клон для вопросов о происхождении; можно несколько, "
                         "порядок — объявленный приоритет")
    ap.add_argument("--span-limit", type=int, default=SPAN_LIMIT)
    ap.add_argument("--journal", default=None,
                    help="журнал объявлений, по которому меряется живость сессии "
                         "(умолчание — data/session_changes.jsonl переписываемого клона)")
    ap.add_argument("--fresh-base-lag-max", type=int, default=FRESH_BASE_LAG_MAX,
                    help="насколько база кандидата вправе отставать от вершины, "
                         "чтобы работа считалась свежей")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--out", default=None)
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args(argv)

    dest = (Path(args.out) if args.out
            else Path(args.repo_root) / "data" / ARTIFACT)
    # ДО замера, не после: иначе прошлый слепок уже затёрт своим же.
    previous, previous_blind = load_previous(dest)
    doc = sweep(args.repo_root, ref=args.ref,
                lineage_candidates=args.lineage or LINEAGE_CANDIDATES_DEFAULT,
                limit=args.span_limit,
                fresh_base_lag_max=args.fresh_base_lag_max,
                previous=previous, previous_blind_reason=previous_blind,
                journal=args.journal,
                self_session=os.environ.get("SPA_SESSION_ID", ""))
    doc["invoked_by"] = call_provenance(tree_root=Path(args.repo_root))
    doc["generated_at"] = _stamp_now()
    if not args.no_write:
        dest.parent.mkdir(parents=True, exist_ok=True)
        atomic_save(doc, str(dest))
    if args.json:
        print(json.dumps(doc, ensure_ascii=False, indent=2, sort_keys=True))
    else:
        print("\n".join(report(doc)))
    if doc.get("state") != "measured":
        return 2
    # Код 1 обязан значить «есть что поднимать», а не «есть кандидат по
    # родословной»: дерево, чьи БАЙТЫ уже на `ref`, звало бы следующий цикл
    # поднимать пустоту — и звало, пока дверь содержимого не появилась.
    return 1 if doc["fresh_to_raise"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
