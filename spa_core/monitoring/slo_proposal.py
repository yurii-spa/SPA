_CADENCE = re.compile(r"interval:(\d+)s")


def cadence_hours(schedule: str | None) -> float | None:
    """Такт агента в часах. `None` — такта нет (демон/событие), судить нельзя."""
    if not schedule:
        return None
    m = _CADENCE.search(schedule)
    if m:
        return max(int(m.group(1)) / 3600.0, 0.0834)      # не мельче 5 минут
    if schedule.startswith("calendar:"):
        # Несколько отметок в сутки → такт = сутки / число отметок.
        marks = [t for t in schedule[len("calendar:"):].split(",") if t]
        return 24.0 / max(len(marks), 1)
    return None


#: ПОТОЛОК запаса поверх такта. ВЫВЕДЕН, а не выбран: правило проверено на парах
#: «такт → курированный человеком slo_hours» из манифеста. «такт + 2 ч» воспроизводит
#: оба известных якоря — часовой агент → 3 ч (`agent_health`), суточный → 26 ч, — и на
#: замере 26.10 (231 пара) эти 2 ч суть выбор, в котором КУРАТОРЫ СОШЛИСЬ: 38 пар
#: суточных агентов проставлены ровно 26 ч. Число не моё и не двигается.
#:
#: **Но это ПОТОЛОК запаса, а не сам запас (ADR-815).** Калибровка шла по МЕДЛЕННЫМ
#: тактам, и у быстрого производителя константа требует срока в десятки тактов:
#: у пятиминутного агента пол 2,08 ч — это 25 его тактов. Сам запас считает
#: :func:`margin_hours`, и у него ОДНА дверь.
_MARGIN_HOURS = 2.0


def margin_hours(tact: float) -> float:
    """Запас поверх такта: **один пропущенный запуск, но не дороже потолка.**

    Смысл запаса объявлен в шапке модуля дословно — «такт × 2, то есть один
    пропущенный запуск не поднимает тревогу». Один пропуск стои́т РОВНО ОДИН ТАКТ,
    то есть запас по природе ПРОПОРЦИОНАЛЕН такту, а не постоянен. Константа
    ``_MARGIN_HOURS`` осталась от калибровки по медленным тактам и работает как
    ПОТОЛОК: у суточного агента один пропуск стоит 24 ч, а кураторы сошлись на 26,
    то есть на 2 ч — значит выше потолка запас не нужен.

    **Форма ВЫБРАНА ЗАМЕРОМ, а не на глаз** (заказ G814 п. 1, замер 26.10 на живой
    конституции; критерий взят из смысла запаса, объявленного строкой выше):

    ======================================  ============  =============  ================
    форма запаса                            ниже пола     ЛОЖНЫХ ТРЕВОГ  спор с кураторами
    ======================================  ============  =============  ================
    константа 2 ч (до ADR-815)              13 · 9        **7 · 6**      20
    такт (чистое «× 2»)                     115 · 126     0 · 0          **6221**
    ``min(такт, 2 ч)`` — эта               **6 · 2**     **0 · 0**      16
    ======================================  ============  =============  ================

    Два числа в клетке — две РАЗНЫЕ оси и два РАЗНЫХ населения (заказ G814 п. 4):
    231 пара «агент × артефакт» по ОБЪЯВЛЕННОМУ расписанию и 200 артефактов по
    НАБЛЮДЁННОЙ медиане. Складывать их нельзя.

    * **ЛОЖНАЯ ТРЕВОГА** — правило объявило срок «ниже пола», то есть физически
      невозможным, а производитель держит обещание С ЗАПАСОМ НА ПРОПУСК
      (``2 × такт ≤ срок``). Константа даёт их 7 и 6; обе пропорциональные формы — ноль.
    * **ПОТЕРЯННАЯ НАХОДКА** — такт ПРЕВЫШАЕТ срок, а «ниже пола» правило не говорит.
      У всех трёх форм ноль, и у этой — ПО ПОСТРОЕНИЮ: пол не ниже такта никогда,
      значит срок ниже такта всегда ниже пола. Это не замер, это доказательство.
    * **СПОР С КУРАТОРАМИ** — правило объявляет ниже пола срок, который люди
      проставили и в котором СОШЛИСЬ (одна пара «такт → срок» встречается многократно).
      Этим чистое «× 2» и отсекается: 6221 против 16.

    Остаток у выбранной формы назван поимённо и обобщению не подлежит:
    ``data/architecture_conformance.json`` (такт 6 ч, срок 7 ч) и
    ``data/investment_os/chief_investment.json`` (такт 1 ч, срок 1 ч — ровно случай
    ADR-549: файл протухает на ~18 с в час ПО ПОСТРОЕНИЮ), плюс на объявленной оси
    четыре пары `deployment_*` суточных агентов со сроком 15 ч, у которых такт
    физически длиннее срока. Ни одна из них не есть предел правила запаса.
    """
    # `min`, а не `max`: запас есть ОДИН ПРОПУСК, и потолок его УДЕШЕВЛЯЕТ для
    # медленных агентов (суточный: 24 ч пропуска → 2 ч потолка), а не удорожает.
    return min(float(tact), _MARGIN_HOURS)


def exact_floor(tact: float) -> float:
    """Точное значение пола, БЕЗ округления. Одно на оба его потребителя.

    Округлять приходится в ДВЕ разные стороны, потому что число служит ДВУМ
    вопросам, и это не вкусовщина (тот же разбор, что у ADR-813/814 этажом ниже):

    ============================  =====================  ==================
    вопрос                       кто спрашивает         сторона ошибки
    ============================  =====================  ==================
    «срок НЕВОЗМОЖЕН?»           :func:`floor_from_tact`  вниз, к «возможно»
    «какой срок ПОСТАВИТЬ?»      :func:`offered_slo`      вверх, к «выполнимо»
    ============================  =====================  ==================

    Судья, ошибившийся вверх, объявляет невозможным возможное (замер: 18 секунд
    округления у пятиминутного производителя). Предложение, ошибившееся вниз,
    отдаёт в манифест срок НИЖЕ физически возможного — ровно дефект ADR-814, с
    которым этот модуль и чинили. Одна сторона на оба вопроса обязана быть
    неверной у одного из них.
    """
    return tact + margin_hours(tact)


def offered_slo(tact: float) -> float:
    """Срок, который можно ПОСТАВИТЬ в манифест: пол, округлённый ВВЕРХ.

    Это число ADR-814 доставил в конституцию (9,28 ч у семьи
    ``com.spa.decision_loop`` при наблюдённой медиане 7,2775 ч), и оно НЕ
    двигается этой правкой: точное значение то же, меняется только сторона
    округления у СУДЬИ.
    """
    return math.ceil(exact_floor(tact) * 100) / 100.0


def floor_from_tact(tact: float) -> float:
    """ЕДИНСТВЕННАЯ дверь к правилу «какой срок физически возможен при таком такте».

    Обе базы (объявленное расписание и наблюдённая медиана) ходят СЮДА. Второй
    копии правила в дереве быть не должно: мутация №2 батареи ADR-814 выжила ровно
    потому, что запас был заведён вторым определением рядом с дверью, и контроль
    «константа одна» этого не видел.

    **Зажима ``max(…, 1.0)`` здесь больше нет, и это ЗАМЕР, а не уборка.** До
    ADR-815 пол считался ``round(max(такт + 2, 1.0), 2)``, и зажим был НЕДОСТИЖИМ
    по построению: самый быстрый такт, который отдаёт :func:`cadence_hours`, —
    0,0834 ч, то есть ``такт + 2 ≥ 2,0834 > 1,0`` всегда. Он не влиял ни на один
    ответ ни разу. С пропорциональным запасом он становится достижимым и держит
    ниже пола РОВНО ОДНУ пару — ``data/resource_health.json`` (такт 5 мин, срок
    0,5 ч), то есть ту самую, которой ADR-814 назвал дефект. Своего вопроса,
    автора и строки объяснения у числа 1,0 не было ни в одном докстринге: это
    второй нигде не объявленный порог внутри пола. Снят с контролем в обе стороны.

    **Округление идёт ВНИЗ, и это нашёл собственный контроль этой же правки.**
    Прежний ``round(…, 2)`` округляет к ближайшему, то есть иногда ВВЕРХ, — и пол,
    поднятый округлением, объявляет невозможным срок, который возможен. Замер:
    такт 0,0834 ч, один пропуск стои́т ровно ``2 × 0,0834 = 0,1668`` ч, а
    ``round(0,1668; 2) = 0,17`` ⇒ срок 0,1668 ч получал «ниже пола» на 18 секундах
    собственного округления. Ошибаться пол обязан в сторону «возможно»: его дело —
    отсекать невозможное, а не спорное.
    """
    exact = exact_floor(tact)
    coarse = math.floor(exact * 100) / 100.0
    # …но НЕ ниже самого такта: свежее своего такта агент не бывает НИКОГДА, и это
    # физика, а не запас. Связывает только при такте мельче 0,01 ч (36 с) — то есть
    # там, где цена округления превысила бы сам запас. Это НЕ зажим `1.0`, снятый
    # выше: у того числа не было ни вопроса, ни автора, а у этого вопрос один и он
    # доказуем.
    return max(coarse, tact)


def architect_floor(schedule: str | None) -> tuple[float | None, str]:
    """Нижняя граница: свежее собственного такта агент физически не бывает."""
    c = cadence_hours(schedule)
    if c is None:
        return None, f"такт не выводится из расписания {schedule!r} — судить не о чем"
    floor = floor_from_tact(c)
    return floor, (f"такт {c:g} ч ⇒ пол {floor:g} ч (такт + запас {margin_hours(c):g} ч на один "
                   f"пропуск, потолок запаса {_MARGIN_HOURS:g} ч; правило восстановлено по "
                   f"курированным срокам, форма запаса выбрана замером ADR-815)")


def observed_floor(median_hours: float | None) -> tuple[float | None, str]:
    """Тот же пол, но от НАБЛЮДЁННОГО такта, а не от объявленного расписания.

    ``architect_floor`` выше спрашивает расписание — и расписание про такт ВРЁТ, что
    измерено: ADR-506 нашёл у ``com.spa.decision_loop`` объявленные ``interval:21600s``
    (6 ч) против наблюдённого такта 7,6 ч, потому что launchd отсчитывает
    ``StartInterval`` от ЗАВЕРШЕНИЯ прогона, а прогон идёт ~1 ч 40 мин. Пол, выведенный
    из объявления, в такой паре НИЖЕ физически возможного — то есть ровно та ошибка, от
    которой пол и должен защищать.

    **Запас тот же самый и взят отсюда же**, не выбран заново: меняется БАЗА (наблюдение
    вместо объявления), а не правило — и считает его одна дверь
    :func:`floor_from_tact`. Калибровка потолка ``_MARGIN_HOURS`` шла по объявленным
    тактам, и это сказано вслух: его переносимость на наблюдённую базу — допущение, а
    не замер. С ADR-815 допущение ДЕШЕВЛЕ, но не исчезло: потолок связывает запас
    только там, где такт длиннее 2 ч, то есть у медленных производителей — ровно у тех,
    по которым он и калиброван.

    **Третий исход (инв. #17).** Такта не наблюдали ⇒ ``None`` с названной причиной.
    Подставить сюда объявленное расписание значило бы вернуть тот самый дефект, а ноль —
    соврать о скорости.
    """
    if median_hours is None:
        return None, ("наблюдённого такта нет — пол из объявленного расписания здесь НЕ "
                      "подставляется (ADR-506: объявление про такт врёт)")
    # `float()` здесь был бы МОЛЧАЛИВЫМ приведением: строка «7.3» прошла бы как
    # замер, то есть разбор чужой формы случился бы в месте, которое за разбор не
    # отвечает. Такт обязан прийти числом ОТ ПРИБОРА.
    if isinstance(median_hours, bool) or not isinstance(median_hours, (int, float)):
        return None, f"наблюдённый такт не число ({median_hours!r}) — судить не о чем"
    middle = float(median_hours)
    if middle <= 0:
        return None, f"наблюдённый такт не положителен ({middle:g} ч) — судить не о чем"
    floor = floor_from_tact(middle)
    return floor, (f"наблюдённая МЕДИАНА такта {middle:g} ч ⇒ пол {floor:g} ч "
                   f"(медиана + тот же запас {margin_hours(middle):g} ч при потолке "
                   f"{_MARGIN_HOURS:g} ч; база — наблюдение, не расписание, ADR-506)")


