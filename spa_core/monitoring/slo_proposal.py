def producer_standing(intent) -> tuple[bool | None, str]:
    """Есть ли у этого агента ТАКТ вообще — то есть идёт ли он.

    **Правило не ново, ново его исполнение — и это ровно тот класс, который
    закрывали три предыдущих цикла.** Оно объявлено дословно в
    ``slo_keepability.ACTIVE``: «только идущие агенты; ``retired``/``designed``
    такта не имеют по построению, и судить их сроки значило бы печатать находку о
    том, чего нет». Соседняя ось (``measure``) правило исполняет и отставных
    считает отдельной строкой ``excluded``. ОБЪЯВЛЕННАЯ ось (ADR-816) обходит
    ``agents[]`` целиком и про ``intent`` не спрашивала НИЧЕГО, поэтому сроки
    отставных агентов она судила — замер 26.10 на живой конституции: **9 пар из
    231**, и все девять получали ``curated_above_floor``, то есть УТВЕРЖДЕНИЕ
    «этот агент срок держит» про агента, который не запускается вовсе.

    **Асимметрии ADR-816 здесь НЕТ, и это существенно.** Там правомочие нужно
    было только отрицанию: «этот агент ОДИН способен держать срок» для файла
    достаточно, кто бы ещё его ни писал. Здесь же НИ ОДНО утверждение любого
    знака не обосновано: у отставного агента нет такта, значит нет и пола, и
    «держит» ровно так же беспредметно, как «не держит». Поэтому дверь
    СИММЕТРИЧНА и спрашивается ПЕРВОЙ — раньше пола и раньше правомочия
    со-производства.

    Три исхода (инв. #17): идёт · объявлен не идущим · ярлык не прочитан.
    Третий сегодня имеет НУЛЕВОЕ население (замер 26.10: ``intent`` — строка у
    всех 107 агентов конституции), и существует он не про запас, а потому что
    подстановка любого из двух первых вместо него была бы угадыванием: молчащий
    ярлык одинаково похож на «забыли проставить» и на «агента вывели».
    """
    if not isinstance(intent, str) or not intent:
        return None, (f"ярлык состояния агента не прочитан ({intent!r}) — идёт он "
                      f"или выведен, сказать нечем")
    if intent == PRODUCER_ACTIVE:
        return True, f"агент объявлен идущим ({intent}) — такт у него есть"
    return False, (f"агент объявлен НЕ идущим ({intent}) — такта у него не "
                   f"существует, и сравнивать срок не с чем ни в одну сторону")


def _as_number(value) -> float | None:
    """Число или ``None``. ``bool`` числом НЕ является (``observed`` судит так же)."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return float(value)


def write_trace(mtime_age_hours, stamp_age_hours, declared_hours, *,
                present) -> tuple[str, str]:
    """Пишет ли артефакт ещё КТО-ТО — вопрос к паре, снятой с суда за отставку.

    **Это НЕ продолжение вопроса о сроке, а другой вопрос о другом предмете.**
    Объявленная ось спрашивает «держит ли агент обещание» и у отставного
    производителя ВЕРНО отказывается отвечать (ADR-818): такта у него нет, пола
    нет, и «держит» беспредметно ровно так же, как «не держит». Но внутри этого
    верного воздержания живёт второй вопрос, которого не задавал никто:
    **а файл-то кто-нибудь пишет?** Ответ на него есть утверждение о
    КОНСТИТУЦИИ, не о сроке, и поэтому вердикт пары он не переписывает ни в одну
    сторону.

    **Почему вопрос разрешим здесь, хотя прибор объявил его неизмеримым.** В
    ``slo_keepability.measure`` в перечне ``not_reported`` стои́т дословно:
    «ПИШЕТ ли производитель артефакт на самом деле — истории ``mtime`` система не
    хранит». Это верно про вопрос С АТРИБУЦИЕЙ («пишет ли файл именно ЭТОТ
    агент»): одна отметка времени не говорит, чья рука её поставила. Здесь же
    вопрос СЛАБЕЕ, и ровно потому отвечаем: про объявленного производителя уже
    известно, что он НЕ ИДЁТ, — значит любая свежая запись сделана КЕМ-ТО ДРУГИМ,
    и атрибуция не нужна, чтобы это утверждать. Асимметрия и есть то, что делает
    слабый вопрос измеримым там, где сильный остаётся нет.

    **Порог НЕ выдуман — это объявленный срок самого артефакта.** Второе
    правило свежести рядом с конституцией было бы ровно тем «третьим местом для
    чисел», против которого написано ``.claude/rules/site-numbers.md``:
    конституция обещала, что файл не будет старше ``declared_hours``; если он
    СВЕЖЕЕ этого при неидущем производителе — обещание кто-то выполняет, и этот
    кто-то в конституции не назван.

    **Вторая проба — собственная отметка артефакта, и она не украшение.**
    ``mtime`` отвечает на вопрос «когда файл последний раз ЗАПИСАН на этой
    файловой системе», но его двигает и ``cp`` без ``-p``, выставляя `now` там,
    где записи не было. Отметка внутри файла поставлена ТЕМ, КТО ПИСАЛ, поэтому
    копия ловится расхождением двух проб. Сравниваются обе с ОДНИМ И ТЕМ ЖЕ
    порогом — так у вопроса «совпали ли они» не появляется своего допуска,
    который снова пришлось бы выдумывать.

    Пять исходов, и каждый отвечает на свой вопрос (инв. #17):

    ==========================  =========================================
    исход                       что утверждается
    ==========================  =========================================
    :data:`TRACE_MISDECLARED`   **НАХОДКА**: файл свежее своего срока, а
                                объявленный производитель не идёт ⇒ пишет
                                его кто-то другой, и конституция называет
                                не того
    :data:`TRACE_UNMAINTAINED`  файл на месте и старше своего срока ⇒ не
                                пишет никто; срок обещан беспризорному
                                файлу (вопрос к КУРАЦИИ, не находка оси)
    :data:`TRACE_ABSENT`        файла нет вовсе ⇒ следа записи не
                                существует; отдельно от предыдущего
                                НАМЕРЕННО — это другое состояние дел, и
                                гора «отсутствует» есть ещё и признак
                                того, что замер сделан не в том дереве
    :data:`TRACE_DISPUTED`      две пробы дали ПРОТИВОПОЛОЖНОЕ ⇒ ни
                                находкой, ни «не пишет» это не выдаётся
    :data:`TRACE_UNMEASURED`    наблюдения нет ⇒ так и сказано
    ==========================  =========================================
    """
    if not isinstance(present, bool):
        return TRACE_UNMEASURED, (
            f"наличие артефакта НЕ ИЗМЕРЕНО ({present!r}) — ни «пишет», ни «не "
            f"пишет» из этого не следует")
    if not present:
        return TRACE_ABSENT, (
            "артефакта нет на месте — следа записи не существует вовсе, и срок "
            "обещан файлу, которого никто не ведёт")
    slo = _as_number(declared_hours)
    if slo is None or slo <= 0:
        return TRACE_UNMEASURED, (
            f"объявленный срок не положительное число ({declared_hours!r}) — "
            f"порога у вопроса нет, а свой значило бы завести ВТОРОЕ правило "
            f"свежести рядом с конституцией")
    age = _as_number(mtime_age_hours)
    if age is None:
        return TRACE_UNMEASURED, (
            f"возраст записи НЕ ИЗМЕРЕН ({mtime_age_hours!r}) — артефакт есть, а "
            f"когда его писали, сказать нечем")
    fresh = age <= slo
    stamp = _as_number(stamp_age_hours)
    if stamp is None:
        second = ("собственной отметки записи у артефакта нет — вторая проба "
                  "недоступна, вердикт стои́т на одной")
    elif (stamp <= slo) != fresh:
        return TRACE_DISPUTED, (
            f"две пробы дали ПРОТИВОПОЛОЖНОЕ при пороге {slo:g} ч: запись "
            f"{age:.1f} ч назад, собственная отметка {stamp:.1f} ч назад — так "
            f"выглядит скопированный файл, и ни находкой, ни «не пишет» это не "
            f"выдаётся")
    else:
        second = (f"собственная отметка артефакта ({stamp:.1f} ч) ПОДТВЕРЖДАЕТ "
                  f"вердикт второй пробой")
    if fresh:
        return TRACE_MISDECLARED, (
            f"артефакт записан {age:.1f} ч назад — СВЕЖЕЕ своего срока {slo:g} ч, "
            f"а объявленный производитель не идёт ⇒ пишет его КТО-ТО ДРУГОЙ, и "
            f"конституция называет не того; {second}")
    return TRACE_UNMAINTAINED, (
        f"артефакт записан {age:.1f} ч назад — СТАРШЕ своего срока {slo:g} ч, и "
        f"производитель не идёт ⇒ не пишет его никто; {second}")


def write_attribution(entry, code_keys, *, present) -> tuple[str, str]:
    """Приписывает ли артефакт свою запись ТОМУ, КОГО ЗАПУСТИЛИ.

    **Это ПЯТЫЙ вопрос и предмет у него свой.** ADR-819 закрыл «пишет ли файл
    кто-то» и НАЗВАЛ остаток дословно: «след говорит КОГДА, а не КТО; для
    со-производимого артефакта с ДВУМЯ ЖИВЫМИ производителями он не различает их
    по построению». Заказ G819 п. 1 запретил искать прибор прежде, чем спрошено:
    **есть ли вообще наблюдаемый канал атрибуции** — и велел замерить население
    артефактов, несущих имя производителя внутри.

    **Различение, на котором стои́т вся дверь: имя КОДА ≠ имя ЗАПУЩЕННОГО.**
    Строка вида ``generated_by: "spa_core/monitoring/x.py"`` есть ЛИТЕРАЛ
    пишущего модуля: она печатается одинаково, кто бы этот модуль ни позвал.
    Ровно этим она слепа к случаю, который ADR-819 и нашёл: снимок
    ``data/governance_proposals.json`` писал НЕ свой агент, а шаг дневного цикла,
    импортировавший производителя БИБЛИОТЕКОЙ. Отметка же вида
    ``invoked_by.entry`` снимается В МОМЕНТ ПРОГОНА у самого процесса
    (``sys.modules['__main__'].__file__``) — она называет того, кого запустили,
    и поэтому библиотечный зов от собственного прогона отличает.

    Пять исходов (инв. #17):

    =================================  ======================================
    исход                              что утверждается
    =================================  ======================================
    :data:`ATTRIBUTION_ENTRY_NAMED`    канал ЕСТЬ: артефакт несёт точку входа
                                       прогона, наблюдённую при записи
    :data:`ATTRIBUTION_CODE_ONLY`      канала НЕТ, хотя похожая строка есть:
                                       назван КОД, и он один и тот же у любого
                                       зова — читатель принял бы литерал за
                                       имя писавшего
    :data:`ATTRIBUTION_ABSENT`         канала нет и похожего ничего нет
    :data:`ATTRIBUTION_CARRIER_ABSENT` носителя нет вовсе (файла нет) —
                                       отдельно НАМЕРЕННО: гора «нет носителя»
                                       есть признак замера не в том дереве
    :data:`ATTRIBUTION_UNMEASURED`     наблюдения нет ⇒ так и сказано
    =================================  ======================================

    **Чего дверь НЕ утверждает:** что названная точка входа сводится к ЯРЛЫКУ
    агента. В конституции у агента объявлена только обёртка (``program``), и
    правила «обёртка → цель» здесь нет ни одной строкой — это отдельный вопрос с
    отдельным замером. ``ATTRIBUTION_ENTRY_NAMED`` означает «канал к
    ЗАПУЩЕННОМУ существует», а не «агент назван».
    """
    if not isinstance(present, bool):
        return ATTRIBUTION_UNMEASURED, (
            f"наличие носителя НЕ ИЗМЕРЕНО ({present!r}) — ни «канал есть», ни "
            f"«канала нет» из этого не следует")
    if not present:
        return ATTRIBUTION_CARRIER_ABSENT, (
            "артефакта нет на месте — носителя у отметки не существует вовсе, и "
            "про канал атрибуции не сказано ничего")
    if entry is not None and (not isinstance(entry, str) or not entry.strip()):
        return ATTRIBUTION_UNMEASURED, (
            f"отметка точки входа есть, но не прочитана ({entry!r}) — назвать "
            f"запущенного ею нечем, и выдать это за «канала нет» было бы "
            f"подстановкой")
    if isinstance(entry, str):
        return ATTRIBUTION_ENTRY_NAMED, (
            f"артефакт несёт точку входа прогона ({entry}) — отметка снята у "
            f"самого процесса, поэтому библиотечный зов от собственного прогона "
            f"она отличает")
    if code_keys is None:
        return ATTRIBUTION_UNMEASURED, (
            "перечень отметок артефакта НЕ ИЗМЕРЕН — про канал атрибуции не "
            "сказано ничего")
    if isinstance(code_keys, (str, bytes)) or not isinstance(code_keys, (list, tuple, set)):
        return ATTRIBUTION_UNMEASURED, (
            f"перечень отметок артефакта не разобран ({type(code_keys).__name__}) "
            f"— про канал атрибуции не сказано ничего")
    named = sorted(str(key) for key in code_keys)
    if named:
        return ATTRIBUTION_CODE_ONLY, (
            f"артефакт несёт имя КОДА ({', '.join(named)}), а не запущенного: эта "
            f"строка — литерал пишущего модуля и печатается одинаково, кто бы его "
            f"ни позвал, поэтому атрибуции в ней нет, а читателю она на неё похожа")
    return ATTRIBUTION_ABSENT, (
        "в артефакте нет ни точки входа прогона, ни имени кода — канала "
        "атрибуции у этого файла не существует")


def declared_axis_standing(co_producers) -> tuple[bool | None, str]:
    """Вправе ли ОБЪЯВЛЕННАЯ ось ОТРИЦАТЬ про этот артефакт?

    Правомочие спрашивается у числа ОБЪЯВЛЕННЫХ производителей — из конституции,
    не из наблюдения. Взять его из наблюдённого списка значило бы свести две оси
    в одно число, что заказ G815 п. 2 запрещает дословно: объявленная ось обязана
    судить по объявленному миру.

    Три исхода (инв. #17), и третий здесь не украшение: «производителей не
    посчитали» и «производитель один» — разные положения дел, а подстановка
    единицы вернула бы ровно тот дефект, который дверь и закрывает.
    """
    if isinstance(co_producers, bool) or not isinstance(co_producers, int):
        return None, f"число объявленных производителей не целое ({co_producers!r})"
    if co_producers < 1:
        return None, (f"объявленных производителей {co_producers} — артефакт без "
                      f"производителя судить не о чем")
    if co_producers == 1:
        return True, "производитель объявлен ОДИН — его такт и есть такт артефакта"
    return False, (f"артефакт объявлен за {co_producers} производителями — такт ОДНОГО "
                   f"из них не есть такт артефакта, и отрицать про файл по нему нельзя")


def audit_declared(declared_hours, schedule: str | None, median_hours,
                   co_producers, *, intent) -> tuple[str, str]:
    """Тот же вопрос, что :func:`audit_curated`, но у пары «АГЕНТ × артефакт».

    **Правила здесь своего нет ни одного**: пол считает :func:`architect_floor`,
    сравнение — :func:`audit_curated`. Новое — только ПРАВОМОЧИЕ, и оно
    спрашивается ровно там, где без него рождается ложная находка.

    **Правомочие асимметрично, и это не поблажка.** Утверждения двух знаков
    говорят о РАЗНОМ:

    ==========================  ====================================  ============
    знак                        что утверждается об АРТЕФАКТЕ         нужно ли
                                                                      правомочие
    ==========================  ====================================  ============
    ``CURATED_ABOVE``           этот агент ОДИН способен держать срок  нет
                                — для файла этого ДОСТАТОЧНО
    ``CURATED_BELOW`` /         этот агент один не способен —         **да**
    ``CURATED_MARGIN_ONLY``     про файл это НЕ СЛЕДУЕТ, пока не
                                спросили про остальных
    ==========================  ====================================  ============

    Замер 26.10 (живая конституция, 231 пара «агент × артефакт» со сроком): ниже
    пола на объявленной оси — **6** пар, и **4** из них суть один и тот же случай.
    ``data/deployment_acceptance.json`` и ``data/deployment_drift.json`` (срок 15 ч)
    объявлены за ДВУМЯ суточными агентами — ``system_health_morning``
    (``calendar:08:00``) и ``system_health_evening`` (``calendar:20:00``). У каждого
    такт 24 ч ⇒ пол 26 ч, и поагентно срок 15 ч читается «ниже пола». У АРТЕФАКТА
    же наблюдённый такт **12 ч** (агенты стоят в 12 ч друг от друга), и срок он
    держит: ``slo_keepability`` зовёт его ``keepable``. **Обе оси правы, и
    расхождение между ними ВЕРНО** — неверно было printing находку.

    **Правило это не ново, ново его ИСПОЛНЕНИЕ.** Докстрока
    ``slo_keepability.measure`` говорит ровно это и теми же двумя агентами в
    примере: «судить такую пару поагентно значило бы печатать находку там, где
    обещание выдерживается». Прозой оно прожило до ADR-816 и четыре пары
    всплывали в каждой переписи заново: у записки нет читателя — знакомый класс
    (``FROZEN-DATE-OK: injected-clock`` сверяется с кодом ровно поэтому).

    Остаток из тех же 6 пар правомочием НЕ лечится и лечиться не должен —
    ``architecture_conformance`` (такт 6 ч, срок 7 ч) и ``chief_investment``
    (1 ч/1 ч, ADR-549): у обоих производитель ОДИН, утверждение про артефакт
    верно, и находка остаётся находкой (инв. #16).
    """
    # ПЕРВЫМ — идёт ли агент вообще (ADR-818). Раньше пола и раньше правомочия
    # со-производства, потому что у отставного агента нет ТАКТА: пол считать не
    # из чего, и «держит» беспредметно ровно так же, как «не держит». Довод
    # живёт в единственной двери `producer_standing`; `intent` объявлен
    # ОБЯЗАТЕЛЬНЫМ именованным, а не со значением по умолчанию — умолчание
    # вернуло бы ровно этот дефект тихо, у первого же нового читателя.
    runs, why_runs = producer_standing(intent)
    if runs is False:
        return DECLARED_PRODUCER_NOT_RUNNING, (
            f"{why_runs}; срок {declared_hours!r} ч объявлен, но судить его "
            f"НЕ О ЧЕМ — ни находкой, ни «выдерживает» это не выдаётся")
    if runs is None:
        return DECLARED_PRODUCER_STANDING_UNMEASURED, (
            f"{why_runs}; пока ярлык не прочитан, вопрос о сроке предмета не "
            f"имеет — ни находкой, ни «выдерживает» это не выдаётся")
    floor, _why_floor = architect_floor(schedule)
    # ПОРЯДОК ВОПРОСОВ ЗДЕСЬ — ПРЕДМЕТ, а не стиль, и нашёл его собственный
    # контроль этой же правки. Сначала «а отрицаем ли мы вообще», и только
    # потом — чем отрицание обосновано. Прежняя редакция звала `audit_curated`
    # первой, и у со-производимого артефакта БЕЗ наблюдённой медианы пара
    # уходила в `CURATED_UNMEASURED` — то есть «различить нечем» вместо
    # «ось об этом не отвечает». Правомочие отрицать от наблюдения НЕ ЗАВИСИТ:
    # производителей объявлено двое независимо от того, мерили мы такт или нет.
    below, why_cmp = below_floor(declared_hours, floor)
    if below is None:
        return CURATED_UNMEASURED, why_cmp
    if not below:
        # Положительная сторона правомочия не требует (см. таблицу в докстроке):
        # «этот агент ОДИН способен держать срок» для файла достаточно.
        return CURATED_ABOVE, why_cmp
    standing, why = declared_axis_standing(co_producers)
    if standing is False:
        return DECLARED_CO_PRODUCED, (
            f"{why}; поагентно вышло бы отрицание ({why_cmp}) — про АРТЕФАКТ это "
            f"утверждение не следует, его меряет наблюдённая ось")
    if standing is None:
        return DECLARED_STANDING_UNMEASURED, (
            f"{why}; поагентно вышло бы отрицание ({why_cmp}), но правомочие НЕ "
            f"ИЗМЕРЕНО — ни находкой, ни «выдерживает» это не выдаётся")
    # Правомочие есть ⇒ отрицание осмысленно, и ДВА его состояния («обещание
    # нарушено» против «запаса нет») различает уже чужая дверь по медиане.
    return audit_curated(declared_hours, floor, median_hours)


def below_floor(declared_hours, floor: float | None) -> tuple[bool | None, str]:
    """Ниже ли курированный срок пола. ЕДИНСТВЕННОЕ место этого сравнения.

    Выделено из :func:`audit_curated` (ADR-816), потому что спрашивают его ДВА
    судьи: сам ``audit_curated`` и :func:`audit_declared`, которому ответ нужен
    РАНЬШЕ медианы — правомочие отрицать не зависит от того, наблюдали такт или
    нет. Копия сравнения рядом с дверью — ровно та форма, на которой выжила
    мутация №2 батареи ADR-814.

    Третий исход (инв. #17): пола нет или срок не число ⇒ ``None`` с причиной.
    """
    if floor is None:
        return None, "пол не выведен — сравнивать не с чем"
    if isinstance(declared_hours, bool) or not isinstance(declared_hours, (int, float)):
        return None, f"курированный срок не число ({declared_hours!r})"
    declared = float(declared_hours)
    if declared >= floor:
        return False, f"курированный срок {declared:g} ч не ниже пола {floor:g} ч"
    return True, f"курированный срок {declared:g} ч НИЖЕ пола {floor:g} ч"


def audit_curated(declared_hours, floor: float | None,
                  median_hours: float | None = None) -> tuple[str, str]:
    """Вопрос, которого у :func:`propose` НЕТ ПО ПОСТРОЕНИЮ.

    ``propose`` при уже проставленном человеком сроке возвращает ``already_curated`` и
    **роли его не переназначают** — для СВОЕГО вопроса («какой срок назначить, если его
    нет») это верно и остаётся. Но из этого следует, что курированный срок НИЖЕ
    собственного пола модуля не может быть назван ни одной его строкой: пол считается,
    сравнивать его не с чем.

    Замер 26.10 на живой конституции: курированных пар «агент × артефакт» со сроком —
    **231**, из них **82** ниже пола, который даёт ``architect_floor`` по ОБЪЯВЛЕННОМУ
    расписанию. Ни об одной `propose` не сказал ничего — и это не промах реализации, а
    предел вопроса.

    **«Ниже пола» — ДВА разных состояния, и путать их значило бы повторить ADR-813
    на один этаж выше.** Поэтому состояния названы раздельно:

    ``CURATED_BELOW``
        срок ниже пола И наблюдённая медиана его ПРЕВЫШАЕТ — производитель
        демонстративно не способен держать обещание. Класс ADR-506, лечится сроком
        либо расписанием. Замер 26.10: **69** пар, все одна семья
        ``com.spa.decision_loop``.
    ``CURATED_MARGIN_ONLY``
        срок ниже пола, но медиана ВНУТРИ срока — такт обещание держит, однако запаса
        на ОДИН ПРОПУСК у срока нет.

        **До ADR-815 этот класс нёс ДВА состояния, как и его предшественник.** Запас
        был КОНСТАНТОЙ 2 ч, а такты агентов различаются на два порядка: у
        пятиминутного агента пол 2,08 ч требовал срока в 25 тактов, и
        ``data/resource_health.json`` (срок 0,5 ч, медиана 0,083 ч) попадал сюда,
        держа обещание с запасом ×6. Из девяти пар замера 26.10 **семь** были
        пределом константы, а не свойством срока. ADR-815 сделал запас равным одному
        пропуску с потолком, и класс остался ровно с теми, у кого утверждение ВЕРНО:
        **2** пары (``architecture_conformance`` — такт 6 ч при сроке 7 ч;
        ``chief_investment`` — такт 1 ч при сроке 1 ч, случай ADR-549).
    ``CURATED_ABOVE``
        срок не ниже пола.
    ``CURATED_UNMEASURED``
        третий исход (инв. #17): пол не выведен, и причина названа.

    Медиана не передана ⇒ различить два состояния НЕЧЕМ, и это ``CURATED_UNMEASURED``,
    а не «превышает»: подставить сюда «да» значило бы выдумать замер.
    """
    below, why_cmp = below_floor(declared_hours, floor)
    if below is None:
        return CURATED_UNMEASURED, why_cmp
    if not below:
        return CURATED_ABOVE, why_cmp
    declared = float(declared_hours)
    if median_hours is None:
        return CURATED_UNMEASURED, (
            f"курированный срок {declared:g} ч ниже пола {floor:g} ч, но медианы такта "
            f"нет — «обещание нарушено» от «запас правила велик» отличить НЕЧЕМ")
    if isinstance(median_hours, bool) or not isinstance(median_hours, (int, float)):
        return CURATED_UNMEASURED, f"наблюдённая медиана не число ({median_hours!r})"
    middle = float(median_hours)
    if middle > declared:
        return CURATED_BELOW, (f"курированный срок {declared:g} ч НИЖЕ пола {floor:g} ч, и "
                               f"медиана такта {middle:g} ч его ПРЕВЫШАЕТ — производитель "
                               f"обещание не держит")
    return CURATED_MARGIN_ONLY, (
        f"курированный срок {declared:g} ч ниже пола {floor:g} ч, но медиана такта "
        f"{middle:g} ч ВНУТРИ срока — обещание держится, а запаса на ОДИН ПРОПУСК "
        f"(нужно {margin_hours(middle):g} ч поверх такта) у срока нет")


def hoi_ceiling(readers: set[str], reaches_owner: bool) -> tuple[float | None, str]:
    """Верхняя граница: через сколько молчание становится опасным."""
    money = sorted(m for m in readers if m.startswith(_MONEY))
    if money:
        # ВНИМАНИЕ, проверено на двух случаях 29.08: близость к money-path — ПОДСКАЗКА,
        # а не приговор. Правило судит по тому, КТО читает, но срочность определяет то,
        # ЧТО читатель с этим делает, и это надо ПРОЧИТАТЬ:
        #   · `risk.scoring_engine` имеет СВОЙ TTL 2 ч и при устаревании уходит в нейтраль
        #     (`ANALYTICS_TTL_S`) — то есть деградирует безопасно, 3 ч ему не требуются;
        #   · `golive_checker` спрашивает «дайджест ушёл СЕГОДНЯ?» — вопрос по природе
        #     суточный, и 3 ч там бессмысленны.
        # Оба выглядели «расхождением ролей», пока читателя не прочитали. Поэтому потолок
        # money-path — повод ОТКРЫТЬ читателя, а не готовое число.
        return 3.0, (f"читает money-path ({', '.join(money[:2])}) — ПОДСКАЗКА, что данные "
                     f"срочные; подтвердить чтением потребителя (у него может быть свой TTL "
                     f"или суточный по природе вопрос)")
    if reaches_owner:
        return 26.0, "результат уезжает владельцу тревогой — молчание заметит человек за сутки"
    if readers:
        return 26.0, "продукт читает код вне money-path — сутки с запасом"
    return 168.0, "исследовательский контур, потребителя нет — опоздание не стоит ничего"


def reconcile(floor: float | None, ceiling: float | None) -> tuple[float | None, str]:
    if floor is None or ceiling is None:
        return None, UNMEASURED
    if floor > ceiling:
        return None, CONTRADICTION
    return ceiling, AGREED


def propose(label: str, repo: Path | None = None) -> dict:
    """Предложение по одному агенту. Никогда не бросает."""
    repo = repo or _REPO
    out = {"label": label, "verdict": UNMEASURED, "slo_hours": None,
           "architect": "", "head_of_investment": "", "artifacts": []}
    try:
        from spa_core.monitoring.artifact_consumers import code_readers, reaches_owner
        from spa_core.monitoring.artifact_contract import _entry_modules, declared_produces
        manifest = json.loads((repo / "architecture" / "manifest.json").read_text(encoding="utf-8"))
        entry = next((a for a in manifest["agents"] if a["label"] == label), None)
        module = _entry_modules(repo).get(label)
        if not entry or not module:
            out["note"] = "агента или его точки входа нет — судить не о чем"
            return out
        f = repo / (module.replace(".", "/") + ".py")
        declared = declared_produces(f) if f.is_file() else None
        if not declared:
            out["note"] = ("агент ничего не объявил (или объявил «ничего») — сроку не к чему "
                           "прикрепиться")
            return out
        arts = set(declared)
        curated = {p["artifact"]: p.get("slo_hours") for p in (entry.get("produces") or [])
                   if p.get("artifact") and p.get("slo_hours")}
        if curated and set(curated) >= arts:
            out.update(verdict="already_curated", artifacts=sorted(arts),
                       note=f"срок уже проставлен человеком ({curated}) — роли его НЕ переназначают")
            return out
        floor, why_a = architect_floor(entry.get("schedule"))
        readers = code_readers(arts, repo, exclude_module=module)
        ceiling, why_h = hoi_ceiling(readers, reaches_owner(module, repo))
        slo, verdict = reconcile(floor, ceiling)
        out.update(artifacts=sorted(arts), architect=why_a, head_of_investment=why_h,
                   floor=floor, ceiling=ceiling, slo_hours=slo, verdict=verdict)
        if verdict == CONTRADICTION:
            out["note"] = (f"РАСХОЖДЕНИЕ РОЛЕЙ: агент способен на {floor:g} ч, а цена опоздания "
                           f"требует {ceiling:g} ч. Это находка «расписание против цены», а не "
                           f"задача на среднее: поле остаётся пустым")
        return out
    except Exception as exc:                                # noqa: BLE001
        out["note"] = f"замер не состоялся: {exc}"
        return out


def main() -> int:
    import sys
    repo = _REPO
    manifest = json.loads((repo / "architecture" / "manifest.json").read_text(encoding="utf-8"))
    rows = [propose(a["label"], repo) for a in manifest["agents"]]
    agreed = [r for r in rows if r["verdict"] == AGREED]
    already = [r for r in rows if r["verdict"] == ALREADY]
    contra = [r for r in rows if r["verdict"] == CONTRADICTION]
    print(f"  агентов: {len(rows)}")
    print(f"  роли СОШЛИСЬ:        {len(agreed)}")
    print(f"  срок уже курирован:  {len(already)} (не переназначаем)")
    print(f"  роли РАЗОШЛИСЬ:      {len(contra)}")
    print(f"  судить не о чем:     {len(rows) - len(agreed) - len(contra) - len(already)}")
    if "--verbose" in sys.argv:
        for r in sorted(agreed, key=lambda x: x["slo_hours"]):
            print(f"\n  {r['label']}  →  {r['slo_hours']:g} ч")
            print(f"      архитектор: {r['architect']}")
            print(f"      HoI:        {r['head_of_investment']}")
        for r in contra:
            print(f"\n  ! {r['label']}: {r['note']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
