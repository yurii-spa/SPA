#: Форма, которой подмена атрибута модуля НЕ видна: имя вида связано на импорте. Сегодня
#: таких связываний в дереве нет (замер 2026-10-18) — и это проверяется, а не предполагается.
_IMPORT_BINDING = re.compile(
    r"^\s*from\s+[\w.]*\b(?P<mod>research_factory\.read|capital_shadow\.read|"
    r"investment_cio\.read|sleeve\.composer)\s+import\s+(?P<names>[^\n#]+)", re.M)


def direct_name_bindings(tree_root: Optional[Path] = None,
                         members: Sequence["Member"] = ()) -> List[str]:
    """Файлы, связавшие имя вида НА ИМПОРТЕ — то есть прошедшие бы мимо счётчика молча.

    Счётчик подменяет атрибут модуля; потребитель, сделавший ``from ...read import latest``,
    держит ссылку на НАСТОЯЩУЮ функцию и подмены не увидит. Поэтому «таких нет» обязано
    быть замером, а не умолчанием: появление первого — находка.
    """
    wanted = {str(m.view).partition(":")[2] for m in members if not callable(m.view)}
    root = Path(tree_root or _ROOT)
    hits: List[str] = []
    for base in ("spa_core", "scripts"):
        base_dir = root / base
        if not base_dir.is_dir():
            continue
        for path in sorted(base_dir.rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if "/tests/" in f"/{rel}" or rel == SELF_REL:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except OSError:
                continue
            for m in _IMPORT_BINDING.finditer(text):
                names = {n.strip().split(" as ")[0].strip()
                         for n in m.group("names").split(",")}
                if names & wanted:
                    hits.append(f"{rel}: from …{m.group('mod')} import {m.group('names').strip()}")
    return hits


def view_reference_files(member: "Member", tree_root: Optional[Path] = None) -> List[str]:
    """ЗАМЕР рядом с решением: сколько файлов не-тестового кода вообще упоминают вид.

    Отвечает не на «полно ли население прогонов» (это решение), а на «есть ли у вида
    читатели за пределами измеренных» — числом, по которому неполноту видно сразу.
    """
    if callable(member.view):
        return []
    mod_name, _, attr = str(member.view).partition(":")
    parts = mod_name.split(".")
    pkg, mod = (parts[-2], parts[-1]) if len(parts) >= 2 else ("", parts[-1])
    #: обе формы ссылки на модуль вида, и вторая важнее первой: ВЛОЖЕННЫЙ читатель
    #: (capital_shadow.readiness → research_factory.read.latest) пишет именно её.
    ref = re.compile(rf"\b{re.escape(pkg)}\s*(?:\.|\s+import\s+){re.escape(mod)}\b"
                     if pkg else rf"\b{re.escape(mod)}\b")
    #: файл, где вид ОПРЕДЕЛЁН, — тоже ссылка: внутримодульные зовы живут там же
    #: (``composer.py`` зовёт свой ``load_ledger`` из ``run_sleeve_shadow``).
    own = mod_name.replace(".", "/") + ".py"
    root = Path(tree_root or _ROOT)
    hits: List[str] = []
    for base in ("spa_core", "scripts"):
        base_dir = root / base
        if not base_dir.is_dir():
            continue
        for path in sorted(base_dir.rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if "/tests/" in f"/{rel}" or rel == SELF_REL:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except OSError:
                continue
            if attr in text and (rel == own or ref.search(text)):
                hits.append(rel)
    return hits


@dataclass(frozen=True)
class CallSites:
    """Кто ЗОВЁТ вид — по разбору кода, а не по вхождению подстроки (заказ G782 п. 1).

    Рядом с решением «население прогонов» прибор с цикла #896 печатал ЗАМЕР неполноты:
    сколько файлов не-тестового кода упоминают вид (:func:`view_reference_files`). Замер
    отвечал на свой вопрос честно, но не на нужный: **упоминание не есть зов.** Замер
    21.10 на ``origin/main`` ``2a367e897``: упоминаний **22**, а зовущих файлов **12** —
    десять файлов из двадцати двух вид только называют (докстрока соседа, объявление
    ленты в ``hash_ledger``, собственный модуль вида). Мера неполноты, стоявшая рядом с
    решением, завышала его почти вдвое.

    Три исхода различимы у КАЖДОГО файла (инв. #17):

    * ``calls`` — файл зовёт вид, и зовов столько;
    * ``mentions_only`` — файл вид упоминает и ИЗМЕРЕННО не зовёт (это не дефект файла,
      а снятие его из меры неполноты);
    * ``unparsed`` / ``unresolved_base`` — про файл НЕ ИЗМЕРЕНО ничего, и названа причина.

    **Четыре двери, и каждая названа.** Зов вида ``<модуль>:<имя>`` виден статически,
    только если известно, под каким именем в файле лежит модуль или сам вид:

    1. ``import <модуль> [as X]`` → ``X.<имя>(…)`` либо полный путь
       ``spa_core.research_factory.read.latest(…)``;
    2. ``from <пакет> import <модуль> [as X]`` → ``X.<имя>(…)``. Эта дверь — самая
       населённая у живых читателей (``from spa_core.research_factory import read as
       rf_read``), и ровно её пропустила ПЕРВАЯ проба этого цикла: она дала **ноль**
       зовущих файлов при четырёх настоящих, то есть классический слепой ноль;
    3. ``from <модуль> import <имя> [as Y]`` → ``Y(…)``. Такое связывание само по себе
       есть находка счётчика зовов (:data:`F_IMPORT_BOUND_VIEW`), но зов через него
       обязан быть ПОСЧИТАН: иначе прибор печатал бы ноль там, где зовущий есть;
    4. внутри самого модуля вида → ``<имя>(…)`` без основания.

    **Пятая дверь объявляется НЕНАБЛЮДАЕМОЙ, а не закрытой.** Зов через словарь или
    ``getattr`` (``READERS["x"]()``, ``getattr(mod, "latest")()``) статикой не виден по
    построению. Поэтому у этого замера есть обратная сторона — ДИНАМИЧЕСКАЯ атрибуция
    зова к файлу (:func:`count_calls`), и расхождение двух замеров судится в ОБЕ стороны:
    зовущий, увиденный на прогоне и не увиденный статикой, есть третий исход
    :data:`U_CALL_SITES_BLIND`, а не тишина.
    """

    calls: Dict[str, int]
    mentions_only: Tuple[str, ...]
    unparsed: Dict[str, str]
    unresolved_base: Dict[str, str]


def _dotted(node: ast.AST) -> Optional[str]:
    """``a.b.c`` → ``"a.b.c"``; основание, которое не есть цепочка имён → ``None``.

    ``None`` тут не «нет основания», а «основание не статическое» (``f()[0].latest()``),
    и наверху оно становится третьим исходом с названным файлом, а не нулём.
    """
    parts: List[str] = []
    while isinstance(node, ast.Attribute):
        parts.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        parts.append(node.id)
        return ".".join(reversed(parts))
    return None


def _module_package(rel: str) -> str:
    """Пакет файла по его пути в дереве — чтобы разрешать ОТНОСИТЕЛЬНЫЙ импорт.

    ``spa_core/investment_cio/read.py`` → ``spa_core.investment_cio``: именно от этого
    имени считаются точки в ``from ..research_factory import read``.
    """
    return rel[:-3].replace("/", ".").rpartition(".")[0]


def _resolve_from(node: ast.ImportFrom, pkg: str) -> Optional[str]:
    """Полное имя модуля в ``from … import …``, включая относительную форму."""
    if not node.level:
        return node.module
    parts = pkg.split(".") if pkg else []
    base = parts[:len(parts) - (node.level - 1)] if node.level > 1 else parts
    if node.level - 1 > len(parts):
        return None
    return ".".join([*base, node.module] if node.module else base) or None


def _calls_in_file(tree: ast.AST, rel: str,
                   wanted: Sequence[Tuple[str, str, str]]) -> Tuple[Dict[str, int],
                                                                    Dict[str, str]]:
    """Зовы каждого искомого вида в ОДНОМ разобранном файле.

    ``wanted`` — тройки ``(ключ, модуль вида, имя вида)``. Возврат: зовы по ключам ·
    ключи, у которых встретился зов с ИМЕНЕМ вида, но основание не статическое.
    """
    pkg = _module_package(rel)
    #: имя в файле → полное имя модуля (двери 1 и 2)
    mod_names: Dict[str, str] = {}
    #: имя в файле → (модуль, имя вида) для двери 3
    view_names: Dict[str, Tuple[str, str]] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    mod_names[alias.asname] = alias.name
                else:
                    #: ``import a.b.c`` связывает ``a``, а зов пишется полным путём —
                    #: он и сверяется ниже как цепочка, поэтому кладём полное имя само на себя
                    mod_names[alias.name] = alias.name
        elif isinstance(node, ast.ImportFrom):
            src = _resolve_from(node, pkg)
            if not src:
                continue
            for alias in node.names:
                mod_names[alias.asname or alias.name] = f"{src}.{alias.name}"
                view_names[alias.asname or alias.name] = (src, alias.name)
    calls: Dict[str, int] = {}
    murky: Dict[str, str] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if isinstance(func, ast.Attribute):
            base = _dotted(func.value)
            for key, mod_name, attr in wanted:
                if func.attr != attr:
                    continue
                if base is None:
                    murky[key] = (f"{U_CALL_BASE_UNRESOLVED}: {rel} зовёт «{attr}» у "
                                  f"основания, которое не есть цепочка имён — статикой "
                                  f"не разрешается, зов не отнесён ни к кому")
                elif base == mod_name or mod_names.get(base) == mod_name:
                    calls[key] = calls.get(key, 0) + 1
        elif isinstance(func, ast.Name):
            for key, mod_name, attr in wanted:
                #: дверь 4 — внутри самого модуля вида; дверь 3 — имя, связанное на импорте
                own = rel == mod_name.replace(".", "/") + ".py"
                if func.id == attr and own:
                    calls[key] = calls.get(key, 0) + 1
                elif view_names.get(func.id) == (mod_name, attr):
                    calls[key] = calls.get(key, 0) + 1
    return calls, murky


#: Память «текст файла × путь × искомые виды → зовы» (spa_core.utils.source_memo).
#: Замер 2026-10-22: перепись G16 зовёт этот прибор двадцать раз за прогон
#: (4 зова × (1 + 4 вложенные переписи `heir_all_rows_price`)), и каждый зов
#: заново разбирал и обходил ~5000 файлов — 32 из 48 с профиля двух зовов.
#: ``_calls_in_file`` — чистая функция разобранного текста, пути (от него
#: зависят относительный импорт и «дверь 4») и набора видов; все три в ключе.
_CALLS_IN_FILE = SourceMemo("ledger_parse_census.calls_in_file")


def view_call_sites(members: Sequence["Member"], tree_root: Optional[Path] = None,
                    ) -> Dict[str, CallSites]:
    """Обход дерева ОДИН раз: кто зовёт каждый объявленный вид (заказ G782 п. 1).

    Население обхода — то же, что у :func:`view_reference_files` (не-тестовый код
    ``spa_core/`` и ``scripts/``, без самого прибора), и сверять два замера между собой
    имеет смысл только на одном населении. Файл разбирается РОВНО один раз на все виды:
    пять отдельных обходов дали бы пять разборов каждого файла — цена, против которой
    этот модуль и написан.
    """
    root = Path(tree_root or _ROOT)
    wanted: List[Tuple[str, str, str]] = []
    for m in members:
        if callable(m.view):
            continue
        mod_name, _, attr = str(m.view).partition(":")
        if mod_name and attr:
            wanted.append((m.id, mod_name, attr))
    calls: Dict[str, Dict[str, int]] = {key: {} for key, _, _ in wanted}
    wanted_key = tuple(wanted)
    unparsed: Dict[str, str] = {}
    murky: Dict[str, Dict[str, str]] = {key: {} for key, _, _ in wanted}
    for base in ("spa_core", "scripts"):
        base_dir = root / base
        if not base_dir.is_dir():
            continue
        for path in sorted(base_dir.rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if "/tests/" in f"/{rel}" or rel == SELF_REL:
                continue
            try:
                text = path.read_text(encoding="utf-8")
                hit, got = _CALLS_IN_FILE.lookup(text, (rel, wanted_key))
                tree = None if hit else ast.parse(text)
            except (OSError, SyntaxError, ValueError) as exc:
                #: про этот файл не измерено НИЧЕГО — ни зовов, ни их отсутствия
                unparsed[rel] = f"{U_CALL_SITE_UNPARSED}: {type(exc).__name__}: {exc}"
                continue
            if not hit:
                got = _CALLS_IN_FILE.store(text, (rel, wanted_key),
                                           _calls_in_file(tree, rel, wanted))
            found, bad = got
            for key, n in found.items():
                calls[key][rel] = n
            for key, why in bad.items():
                murky[key][rel] = why
    out: Dict[str, CallSites] = {}
    for key, mod_name, attr in wanted:
        member = next(m for m in members if m.id == key)
        refs = view_reference_files(member, root)
        mentions_only = tuple(r for r in refs if r not in calls[key]
                              and r not in murky[key] and r not in unparsed)
        out[key] = CallSites(calls=dict(sorted(calls[key].items())),
                             mentions_only=mentions_only,
                             unparsed=dict(sorted(unparsed.items())),
                             unresolved_base=dict(sorted(murky[key].items())))
    return out

def resolve_view_site(member: "Member") -> Tuple[Optional[object], Optional[str], Optional[str]]:
    """Место, где вид ЛЕЖИТ (модуль + имя атрибута) — чтобы было что подменить счётчиком.

    Вид, переданный готовым вызываемым (стенды), места в модуле не имеет: считать его
    вызовы нечем, и это третий исход с причиной, а не ноль.
    """
    if callable(member.view):
        return None, None, f"{U_VIEW_NOT_PATCHABLE}: вид передан вызываемым, атрибута модуля нет"
    mod_name, _, attr = str(member.view).partition(":")
    if not attr:
        return None, None, f"{U_VIEW_UNRESOLVED}: в «{member.view}» нет имени функции после ':'"
    try:
        mod = importlib.import_module(mod_name)
    except Exception as exc:  # noqa: BLE001 — причина НАЗЫВАЕТСЯ, а не съедается
        return None, None, f"{U_VIEW_UNRESOLVED}: {type(exc).__name__}: {exc}"
    if not callable(getattr(mod, attr, None)):
        return None, None, f"{U_VIEW_UNRESOLVED}: {member.view} не вызываемое"
    return mod, attr, None


def ledger_id_split(members: Sequence["Member"]) -> Dict[str, str]:
    """Сверка ДВУХ объявлений личности файла друг с другом — в ОБЕ стороны.

    ``ledger_id`` — ключ, по которому складывается произведение «цена разбора × разборов»,
    и ошибиться в нём значит получить не меньшее число, а ДРУГОЕ:

    * один файл под ДВУМЯ ``ledger_id`` ⇒ счётчиков разборов у него два, и цена этого
      файла сложится дважды (прибор завысит ровно то, что мерит);
    * один ``ledger_id`` на ДВА файла ⇒ в один счётчик попадут разборы двух разных лент,
      и разделить их потом будет нечем.

    Поэтому «одна личность — один путь» не соглашение, а проверяемое утверждение, и его
    нарушение есть третий исход (:data:`U_LEDGER_ID_SPLIT`), а не число. Молча вывести
    ``ledger_id`` из пути было бы той же экономией, из которой вырос заказ G780 п. 1.

    Возврат: ``{личность или путь: причина}`` — пусто, если оба объявления сошлись.
    """
    by_path: Dict[str, set] = {}
    by_id: Dict[str, set] = {}
    for m in members:
        by_path.setdefault(m.ledger, set()).add(m.ledger_id)
        by_id.setdefault(m.ledger_id, set()).add(m.ledger)
    bad: Dict[str, str] = {}
    for path, ids in sorted(by_path.items()):
        if len(ids) > 1:
            bad[path] = (f"{U_LEDGER_ID_SPLIT}: один файл {path} объявлен под личностями "
                         f"{sorted(ids)} — счётчик разборов у него был бы не один, и цена "
                         f"этого файла сложилась бы {len(ids)} раз(а)")
    for lid, paths in sorted(by_id.items()):
        if len(paths) > 1:
            bad[lid] = (f"{U_LEDGER_ID_SPLIT}: личность {lid} объявлена у разных файлов "
                        f"{sorted(paths)} — их разборы попали бы в ОДИН счётчик, и "
                        f"разделить их было бы нечем")
    return bad


def _calling_file(frame: object) -> str:
    """Файл кадра — путём ОТНОСИТЕЛЬНО дерева, если он в дереве, и абсолютным, если нет.

    Различие несущее: сверять динамический замер со статическим можно только на одном
    населении, а статика обходит дерево. Кадр из ``site-packages`` или из ``exec``-строки
    поэтому и обязан выглядеть иначе — иначе «его не видит статика» читалось бы как
    слепота прибора, хотя статике там смотреть нечего.
    """
    name = getattr(getattr(frame, "f_code", None), "co_filename", "") or "<кадра нет>"
    try:
        return Path(name).resolve().relative_to(_ROOT).as_posix()
    except (ValueError, OSError):
        return name


def count_calls(members: Sequence["Member"], workload: Workload,
                data_dir: Path) -> Tuple[Dict[str, int], Dict[str, str], object,
                                         Optional[str], Dict[str, int],
                                         Dict[str, Dict[str, int]]]:
    """Что ОДИН прогон делает с каждой лентой — ДВА числа, и они отвечают на разное.

    * **зовы** (``counts``) — сколько раз прогон позвал ОБЪЯВЛЕННЫЙ вид; мерятся подменой
      атрибута модуля;
    * **разборы** (``opens``) — сколько раз за прогон открылся САМ ФАЙЛ ленты; мерятся у
      файла, по обеим дверям.

    Второе число и есть то, на что умножается цена разбора, и равняться первому оно не
    обязано: замер цикла #898 на живом ``data/`` — сборка Mission Control зовёт
    объявленный вид ``research_factory.read.latest`` ДВА раза, а ленту разбирает **восемь**,
    потому что два других её места идут во ВТОРОЙ вид того же пакета
    (``read.cio_view``), которого население членов не объявляет. Считать цену по зовам
    объявленного вида значило бы печатать половину правды с видом целого.

    **Ключи у двух чисел РАЗНЫЕ, и это несущее различие** (цикл #900): зовы считаются у
    ПАРЫ (``Member.id``), разборы — у ФАЙЛА (``Member.ledger_id``). Дать каждому виду
    одной ленты свой счётчик разборов значило бы сложить цену этого файла столько раз,
    сколько у него видов, — прибор завысил бы ровно то, что мерит.

    **Шестое число — ОТКУДА позвали** (заказ G782 п. 1, цикл #901). Счётчик зовов и так
    стоит у двери вида, и спросить вызывающий кадр стои́т один ``sys._getframe``; зато
    появляется обратная сторона у статического замера :func:`view_call_sites`. Два замера
    отвечают на один вопрос РАЗНЫМИ способами, и расхождение судится в ОБЕ стороны:
    зовущий, увиденный на прогоне, но не увиденный статикой, означает дверь, которую
    статика не смотрит (:data:`U_CALL_SITES_BLIND`) — третий исход, а не тишина; зовущий,
    увиденный статикой, но не достигнутый ни одним прогоном, и есть НАЗВАННАЯ неполнота
    населения прогонов — то, что до этого цикла стояло рядом с решением числом упоминаний.

    Кадр берётся ПЕРВЫЙ над обёрткой: он и есть тот, кто написал зов. Вложенный читатель
    (``capital_shadow.readiness`` → ``research_factory.read.latest``) поэтому называет
    себя сам, а не того, кто поднял прогон, — именно этого класса («цену платит вложенный
    читатель, которого вызывающий не называет») и был дефект ADR-777.

    Возврат: зовы (по парам) · члены, у которых считать нечем (с причиной) · ответ прогона ·
    причина отказа прогона (``None``, если прогон дошёл до конца) · разборы (по файлам) ·
    зовущие файлы (по парам: ``{пара: {файл: зовов}}``).
    """
    counts: Dict[str, int] = {}
    sites: Dict[str, Dict[str, int]] = {}
    cannot: Dict[str, str] = {}
    undo: List[Tuple[object, str, Callable]] = []
    #: ГЕЙТ стоит у той самой двери, которую охраняет: цели счётчика строятся здесь, и
    #: расхождение двух объявлений личности обязано остановить замер ДО него, а не быть
    #: замеченным по странному числу потом.
    split = ledger_id_split(members)
    if split:
        return {}, {}, None, "; ".join(split.values()), {}, {}
    #: ОДИН счётчик на файл: ключ словаря сам сводит виды одной ленты к одной цели
    targets = {m.ledger_id: Path(data_dir) / m.ledger for m in members}
    for m in members:
        mod, attr, why = resolve_view_site(m)
        if mod is None:
            cannot[m.id] = why or U_VIEW_NOT_PATCHABLE
            continue
        real = getattr(mod, attr)
        counts[m.id] = 0
        sites[m.id] = {}

        def make(mid=m.id, real=real):
            def hook(*a, **k):
                counts[mid] += 1
                where = _calling_file(sys._getframe(1))
                sites[mid][where] = sites[mid].get(where, 0) + 1
                return real(*a, **k)
            hook.__wrapped__ = real
            return hook

        setattr(mod, attr, make())
        undo.append((mod, attr, real))
    try:
        with _counting_opens(targets) as opens:
            try:
                answer = workload.run(Path(data_dir))
                err = None
            except Exception as exc:  # noqa: BLE001 — прогон упал ⇒ третий исход с причиной
                answer, err = None, f"{U_WORKLOAD_RAISED}: {type(exc).__name__}: {exc}"
    finally:
        for mod, attr, real in undo:
            setattr(mod, attr, real)
    return counts, cannot, answer, err, dict(opens), sites


#: формат строки запуска, которую пишет ``scripts/agent_template.sh`` каждому агенту флота
_START_LINE = re.compile(r"^\[(?P<ts>\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ)\]\s+START\s+agent=(?P<agent>\S+)")


def declared_daily_rate(plist_path: Path | str) -> Tuple[Optional[float], Optional[float],
                                                         Optional[str]]:
    """ОБЪЯВЛЕННАЯ частота прогона: сколько раз в сутки его зовёт launchd.

    Возврат: прогонов в сутки · интервал в секундах (если расписание интервальное) ·
    причина, по которой ответа нет. Третий исход тут обязателен: plist, которого нет, и
    plist без расписания — РАЗНЫЕ вещи, и ни одна из них не «ноль прогонов в сутки».

    ``StartInterval`` даёт частоту делением суток; ``StartCalendarInterval`` — числом
    объявленных моментов (их столько и наступает за сутки). Разбирается ``plistlib``
    (stdlib), а не регуляркой: формат объявлен Apple, и своя копия разбора расходилась бы
    с ним при первой же правке plist.
    """
    path = Path(plist_path)
    if not path.is_file():
        return None, None, f"{U_SCHEDULE_UNREADABLE}: plist {path} не найден"
    try:
        with open(path, "rb") as fh:
            doc = plistlib.load(fh)
    except Exception as exc:  # noqa: BLE001 — причина НАЗЫВАЕТСЯ
        return None, None, f"{U_SCHEDULE_UNREADABLE}: {type(exc).__name__}: {exc}"
    interval = doc.get("StartInterval")
    if isinstance(interval, int) and interval > 0:
        return 86400.0 / interval, float(interval), None
    cal = doc.get("StartCalendarInterval")
    if isinstance(cal, dict):
        return 1.0, None, None
    if isinstance(cal, list) and cal:
        return float(len(cal)), None, None
    return None, None, (f"{U_SCHEDULE_UNREADABLE}: в {path.name} нет ни StartInterval, ни "
                        f"StartCalendarInterval — чем расписание задано, не измерено")


def observed_daily_rate(log_path: Path | str, agent: str, *, now,
                        window_h: float = 24.0) -> Tuple[Optional[float], Optional[int],
                                                         Optional[str]]:
    """НАБЛЮДЁННАЯ частота прогона: сколько раз агент реально стартовал за окно.

    Возврат: прогонов в сутки · запусков в окне · причина, по которой ответа нет.

    **Окно не вправе быть глубже самого журнала, и это не придирка — это замер цикла
    #898.** Тот же журнал на окне 24 ч дал 272 запуска (272/сутки), а на окне 168 ч — 675
    запусков, то есть 96/сутки. Второе число не про частоту вовсе: журнал начинался 62 ч
    назад, и 168-часовое окно поделило реальные запуски на пустоту, которой в журнале нет.
    Ровно тот класс, что `.claude/rules/deployment.md` ведёт по календарю и по номеру
    процесса: свойство ИЗМЕРИТЕЛЯ, выданное за свойство предмета. Поэтому журнал мельче
    окна ⇒ :data:`U_LOG_SHALLOWER` с ОБОИМИ числами, а не частное.

    ``now`` — ВХОД, а не стенные часы (п. 1 порядка предпочтения того же правила): и окно,
    и глубина журнала считаются от него, поэтому тест закрепляет обе стороны и не
    стареет.
    """
    path = Path(log_path)
    if not path.is_file():
        return None, None, f"{U_RATE_NOT_OBSERVABLE}: журнал {path} не найден"
    stamps: List[_dt.datetime] = []
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                m = _START_LINE.match(line)
                if not m or m.group("agent") != agent:
                    continue
                try:
                    stamps.append(_dt.datetime.strptime(
                        m.group("ts"), "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=_dt.timezone.utc))
                except ValueError:  # pragma: no cover — отметка не разобралась
                    continue
    except OSError as exc:
        return None, None, f"{U_RATE_NOT_OBSERVABLE}: {type(exc).__name__}: {exc}"
    if not stamps:
        return None, None, (f"{U_RATE_NOT_OBSERVABLE}: в журнале {path.name} нет ни одной "
                            f"строки START agent={agent} — глубину журнала мерить нечем, и "
                            f"нулём частота тут не становится")
    depth_h = (now - min(stamps)).total_seconds() / 3600.0
    if depth_h < window_h:
        return None, None, (
            f"{U_LOG_SHALLOWER}: журнал глубиной {depth_h:.1f}ч при окне {window_h:.1f}ч — "
            f"частное поделило бы {len(stamps)} настоящих запусков на пустоту, которой в "
            f"журнале нет (замер #898: то же окно 168ч дало 96/сутки против 272/сутки на 24ч)")
    cut = now - _dt.timedelta(hours=window_h)
    in_window = sum(1 for s in stamps if s >= cut)
    return in_window / (window_h / 24.0), in_window, None


def measure_cadence(workload: Workload, *, tree_root: Optional[Path] = None, now=None,
                    window_h: float = 24.0) -> dict:
    """ТРЕТИЙ множитель одного прогона: объявленная частота рядом с наблюдённой.

    Ни одно из двух чисел не заменяет другое. Расписание отвечает «сколько прогонов
    ДОЛЖНО быть», журнал — «сколько их БЫЛО»; наблюдённый ноль при непустом расписании
    есть НАХОДКА (агент мёртв или не загружен), а отсутствие и расписания, и журнала —
    третий исход с причиной, а не бесплатный прогон.
    """
    now = now or _dt.datetime.now(_dt.timezone.utc)
    cad = workload.cadence
    out: dict = {"declared_per_day": None, "interval_s": None, "observed_per_day": None,
                 "observed_count": None, "window_h": window_h, "reason": cad.reason,
                 "unmeasured": None, "findings": []}
    if cad.plist:
        rate, interval, why = declared_daily_rate(Path(tree_root or _ROOT) / cad.plist)
        out["declared_per_day"], out["interval_s"] = rate, interval
        if why:
            out["unmeasured"] = why
    if cad.log and cad.agent:
        rate, count, why = observed_daily_rate(cad.log, cad.agent, now=now, window_h=window_h)
        out["observed_per_day"], out["observed_count"] = rate, count
        if why and not out["unmeasured"]:
            out["unmeasured"] = why
    if not cad.plist and not cad.log:
        out["unmeasured"] = f"{U_RATE_NOT_OBSERVABLE}: {cad.reason}"
    if (out["declared_per_day"] or 0) > 0 and out["observed_count"] == 0:
        out["findings"].append({
            "kind": F_SCHEDULE_NEVER_OBSERVED,
            "text": (f"расписание объявляет {out['declared_per_day']:.0f} прогонов в сутки, "
                     f"а журнал агента за окно {window_h:.0f}ч не показал НИ ОДНОГО запуска "
                     f"— прогон либо не загружен, либо падает до записи; суточная цена "
                     f"такого прогона не ноль, а неизвестна"),
        })
    return out


def measure_workloads(data_dir: Path | str, *, members: Sequence["Member"] = LEDGERS,
                      workloads: Sequence[Workload] = (),
                      price_by_id: Optional[Dict[str, Optional[float]]] = None,
                      parse_by_id: Optional[Dict[str, Optional[float]]] = None,
                      budget_s: float = WORKLOAD_BUDGET_S,
                      min_factor: float = MIN_GROWTH_FACTOR,
                      tree_root: Optional[Path] = None,
                      now=None, window_h: float = 24.0) -> dict:
    """Второй и ТРЕТИЙ множители, полная цена прогона и СУТОЧНАЯ цена.

    Цена прогона считается по ИЗМЕРЕННЫМ разборам ленты, а не по зовам объявленного вида:
    второе предсказывает первое только там, где население видов ПОЛНО, и у двух из трёх
    прогонов это предсказание разошлось с замером (цикл #898). Расхождение печатается
    находкой в ОБЕ стороны, а не сглаживается в пользу любого из чисел.

    **Модель — СУММА по всем видам одной ленты** (цикл #900, заказ G780 п. 1): пока у
    ленты объявлялся ровно один вид, модель отвечала на вопрос «сколько разборов даёт ЭТОТ
    вид», а читалась как «сколько разборов даёт лента». Теперь она складывает «открытий за
    зов × зовов» по каждому виду, и у ``research_factory`` эта сумма сошлась с замером у
    файла на ВСЕХ трёх прогонах. Находка от этого не ослабла: расхождение по-прежнему
    означает читателя помимо ОБЪЯВЛЕННЫХ видов — просто объявленных стало два.

    Суточная цена есть произведение ТРЁХ: цена разбора × разборов за прогон × прогонов за
    сутки. Нет третьего множителя ⇒ суточной цены нет вовсе (:data:`U_DAILY_PRICE_UNKNOWN`),
    а не ноль: прогон без наблюдаемой частоты не бесплатный, он неизмеренный.
    """
    data = Path(data_dir)
    price_by_id = price_by_id or {}
    parse_by_id = parse_by_id or {}
    opens_per_call = {m.id: m.declared_opens for m in members}
    #: пара → файл: по этому отображению модель вида складывается в модель ЛЕНТЫ
    ledger_of = {m.id: m.ledger_id for m in members}
    #: файл → его виды, чтобы ленту, у которой ни один вид не считаем, не выдать за
    #: «разборов ноль» (у неё разборы могут быть, а модели нет вовсе)
    views_of: Dict[str, List[str]] = {}
    for m in members:
        views_of.setdefault(m.ledger_id, []).append(m.id)
    rows: List[dict] = []
    reached: Dict[str, int] = {m.id: 0 for m in members}
    #: ОТКУДА звали — по паре и по файлу, сложенное по всем прогонам. Обратная сторона
    #: статического замера :func:`view_call_sites`; сверяются они в :func:`measure`.
    observed_sites: Dict[str, Dict[str, int]] = {}
    seen_measured = False
    for w in workloads:
        row: dict = {"id": w.id, "reason": w.reason, "calls": None, "opens": None,
                     "call_sites": None,
                     "opens_modelled": None, "not_countable": None, "unmeasured": None,
                     "price_s": None, "growth_factor": None, "cadence": None,
                     "price_day_s": None, "rate_per_day": None, "rate_source": None,
                     "share_of_day": None, "daily_unmeasured": None, "findings": []}
        counts, cannot, answer, err, opens, sites = count_calls(members, w, data)
        if cannot:
            row["not_countable"] = cannot
        if err:
            row["unmeasured"] = err
            rows.append(row)
            continue
        if counts and not any(counts.values()):
            row["unmeasured"] = (
                f"{U_PROBE_NOT_PROVEN}: прогон дошёл до конца, но ни один из "
                f"{len(counts)} видов не был вызван ни разу. Условие приёма прогона в "
                f"население — что он читает хотя бы одну ленту, поэтому сплошной ноль "
                f"означает, что счётчик не встал (имя вида связано на импорте либо "
                f"прогон подменён), а НЕ что лент он не читает")
            rows.append(row)
            continue
        if not counts:
            row["unmeasured"] = (
                f"{U_VIEW_NOT_PATCHABLE}: ни у одного члена нет атрибута модуля, "
                f"у которого можно считать вызовы")
            rows.append(row)
            continue
        seen_measured = True
        #: зовущие складываются только у ПРИНЯТОГО прогона: у отказавшего (третий исход
        #: выше) замер неполон по построению, и выдать его за наблюдение значило бы
        #: назвать статику слепой по вине упавшего прогона
        for mid, by_file in sites.items():
            for rel, n in by_file.items():
                observed_sites.setdefault(mid, {})[rel] = \
                    observed_sites.setdefault(mid, {}).get(rel, 0) + n
        row["call_sites"] = {mid: dict(sorted(v.items())) for mid, v in sites.items() if v}
        row["calls"] = counts
        counted_ledgers = {ledger_of.get(mid, mid) for mid in counts}
        row["opens"] = {lid: n for lid, n in opens.items()
                        if lid in counted_ledgers or n}
        for mid, n in counts.items():
            reached[mid] = max(reached.get(mid, 0), n)

        # ── цена прогона = цена РАЗБОРА × ИЗМЕРЕННЫХ разборов (не зовов вида) ──────────
        price = 0.0
        price_known = True
        for mid, n in row["opens"].items():
            per_parse = parse_by_id.get(mid)
            if n and per_parse is None:
                price_known = False
                continue
            price += n * (per_parse or 0.0)
        row["price_s"] = price if price_known else None
        if not price_known:
            row["unmeasured"] = (
                f"{U_PRICE_UNKNOWN}: разборы сосчитаны, но цена одного разбора измерена не у "
                f"всех разобранных лент — произведение без множителя не число")
            rows.append(row)
            continue

        # ── расхождения объявленного с измеренным: оба числа, в ОБЕ стороны ───────────
        for mid, n in counts.items():
            declared = w.declared_calls.get(mid)
            if declared is None or n == declared:
                continue
            row["findings"].append({
                "kind": F_CALLS_DRIFTED,
                "text": (f"{mid}: вызовов за прогон {n} против объявленных {declared} — у "
                         f"объявленного числа есть причина: "
                         f"{w.calls_reason.get(mid, 'причина не названа')}"),
            })
        for mid, n in row["opens"].items():
            declared = w.declared_opens.get(mid)
            if declared is None or n == declared:
                continue
            row["findings"].append({
                "kind": F_WORKLOAD_OPENS_DRIFTED,
                "text": (f"{mid}: РАЗБОРОВ ленты за прогон {n} против объявленных {declared} "
                         f"— у объявленного числа есть причина: "
                         f"{w.opens_reason.get(mid, 'причина не названа')}"),
            })

        # ── модель «открытий за вызов × зовов», СУММОЙ по видам ленты, против замера ──
        modelled: Dict[str, int] = {}
        for mid, n in counts.items():
            lid = ledger_of.get(mid, mid)
            modelled[lid] = modelled.get(lid, 0) + opens_per_call.get(mid, 0) * n
        row["opens_modelled"] = modelled
        for lid, n in row["opens"].items():
            want = modelled.get(lid)
            if want is None or n == want:
                continue
            #: НАПРАВЛЕНИЕ расхождения — замер, а не предположение, и оба значат разное:
            #: модель НИЖЕ замера ⇒ ленту читает кто-то помимо объявленного вида (цена
            #: занижалась); модель ВЫШЕ замера ⇒ объявленный вид разбирает реже, чем
            #: объявлено (кэш сработал либо чтение исчезло). Имя находки направления не
            #: утверждает — его называет текст.
            side = ("модель НИЖЕ замера: ленту читает кто-то помимо объявленных видов"
                    if want < n else
                    "модель ВЫШЕ замера: объявленные виды разобрали ленту реже, чем объявлено")
            seen = ", ".join(sorted(views_of.get(lid, [])))
            row["findings"].append({
                "kind": F_MODEL_DISAGREES,
                "text": (f"{lid}: модель «открытий за зов × зовов», сложенная по "
                         f"объявленным видам ({seen or 'ни одного'}), даёт {want}, а у "
                         f"самого файла измерено {n} разбор(ов) — цена прогона считается по "
                         f"ЗАМЕРУ; {side} ({w.opens_reason.get(lid, 'причина не названа')})"),
            })

        if price > 0:
            row["growth_factor"] = budget_s / price
            if row["growth_factor"] < min_factor:
                row["findings"].append({
                    "kind": F_WORKLOAD_MARGIN_SHORT,
                    "text": (f"полная цена прогона {price:.3f} с — запас "
                             f"{row['growth_factor']:.1f}× ниже порога {min_factor:.1f}× при "
                             f"бюджете прогона {budget_s:.2f} с; цена ОДНОГО вызова этот "
                             f"запас завышает ровно во столько раз, сколько разборов"),
                })

        # ── ТРЕТИЙ множитель и суточная цена ─────────────────────────────────────────
        cad = measure_cadence(w, tree_root=tree_root, now=now, window_h=window_h)
        row["cadence"] = cad
        row["findings"].extend(cad["findings"])
        rate = cad["observed_per_day"]
        rate_from = "журнал агента (НАБЛЮДЕНИЕ)"
        if rate is None:
            rate, rate_from = cad["declared_per_day"], "расписание plist (ОБЪЯВЛЕНИЕ)"
        if rate is None:
            row["price_day_s"] = None
            row["daily_unmeasured"] = (
                f"{U_DAILY_PRICE_UNKNOWN}: цена прогона {price:.3f} с измерена, а сколько "
                f"раз в сутки его зовут — нет ({cad['unmeasured'] or cad['reason']}); "
                f"суточная цена поэтому НЕ ИЗМЕРЕНА, а не равна нулю")
        else:
            row["price_day_s"] = price * rate
            row["rate_per_day"] = rate
            row["rate_source"] = rate_from
            row["share_of_day"] = (price * rate) / 86400.0
            interval = cad["interval_s"]
            if interval and price > interval:
                row["findings"].append({
                    "kind": F_PRICE_EXCEEDS_INTERVAL,
                    "text": (f"повторный разбор стои́т прогону {price:.3f} с при его "
                             f"СОБСТВЕННОМ интервале {interval:.0f} с — прогон не успевает "
                             f"к своему же следующему запуску, и порог этот не придуман, "
                             f"а взят из его расписания"),
                })
        rows.append(row)

    unreached: Dict[str, str] = {}
    if seen_measured:
        for m in members:
            if reached.get(m.id, 0) == 0:
                unreached[m.id] = (
                    f"{U_NO_WORKLOAD_REACHES}: ни один из {len(workloads)} объявленных "
                    f"прогонов ЭТОТ ВИД не зовёт — запас одного вызова у него верен, но ни "
                    f"к одному измеренному прогону не относится")
    return {
        "budget_s": budget_s,
        "min_growth_factor": min_factor,
        "declared": len(workloads),
        "rows": rows,
        "calls_by_member": reached if seen_measured else {},
        "call_sites": {mid: dict(sorted(v.items())) for mid, v in sorted(observed_sites.items())},
        "sites_measured": seen_measured,
        "unreached": unreached,
        "unmeasured": [r for r in rows if r["unmeasured"]],
        "daily_unmeasured": [r for r in rows if r.get("daily_unmeasured")],
        "window_h": window_h,
        "findings": [dict(f, id=r["id"]) for r in rows for f in r["findings"]],
    }


def cross_check_call_sites(static: Dict[str, "CallSites"],
                           observed: Dict[str, Dict[str, int]],
                           *, sites_measured: bool) -> dict:
    """Сверка ДВУХ замеров «кто зовёт вид» — статики и прогона, в ОБЕ стороны.

    Замеры добыты разными способами, и именно поэтому их совпадение не тавтология:
    статика читает код и не видит зов через словарь или ``getattr``; прогон видит
    фактический кадр, но только там, куда он дошёл. Поэтому у расхождения ДВА разных
    смысла, и смешать их значило бы потерять оба:

    * **прогон видит, статика нет** ⇒ :data:`U_CALL_SITES_BLIND`: у статики есть
      непросмотренная дверь. Это третий исход (прибор не измерил), а не находка о коде —
      ровно тот дефект, который первая проба этого цикла дала на себе: дверь
      ``from <пакет> import <модуль> as <имя>`` была не разобрана, и замер дал НОЛЬ
      зовущих при четырёх настоящих;
    * **статика видит, ни один прогон не достиг** ⇒ НАЗВАННАЯ неполнота населения
      прогонов. Это не дефект и не третий исход: население прогонов есть РЕШЕНИЕ, и
      прибор лишь перестаёт мерить его числом упоминаний.

    **Сверить было нечем — отдельный исход.** Ни один прогон не принят (``--no-workloads``,
    либо все отказали) ⇒ ``status="not_measured"``: пустые списки тут означают «не
    сверялось», а не «сошлось», и выдать одно за другое запрещает инв. #17.
    """
    blind: Dict[str, Dict[str, str]] = {}
    outside: Dict[str, List[str]] = {}
    agreed: Dict[str, List[str]] = {}
    out_of_tree: Dict[str, List[str]] = {}
    if not sites_measured:
        return {"status": "not_measured",
                "reason": ("ни один объявленный прогон не принят в замер — динамической "
                           "стороны нет, и сверять статику не с чем; пустота здесь "
                           "означает «не сверялось», а не «сошлось»"),
                "blind": {}, "outside_workloads": {}, "agreed": {}, "out_of_tree": {}}
    for mid, sites in sorted(static.items()):
        seen = observed.get(mid) or {}
        for rel in sorted(seen):
            #: кадр вне дерева статике не подсуден: она обходит дерево, и «не видит» там
            #: не слепота, а отсутствие предмета
            if rel.startswith("/") or rel.startswith("<"):
                out_of_tree.setdefault(mid, []).append(rel)
            elif rel == SELF_REL:
                #: сам прибор поднимает прогоны, и его собственный кадр статика не читает
                #: намеренно (SELF_REL исключён из обхода) — это объявлено, а не пропущено
                continue
            elif rel in sites.calls:
                agreed.setdefault(mid, []).append(rel)
            elif rel in sites.unparsed:
                blind[mid] = dict(blind.get(mid) or {})
                blind[mid][rel] = sites.unparsed[rel]
            else:
                blind[mid] = dict(blind.get(mid) or {})
                blind[mid][rel] = (
                    f"{U_CALL_SITES_BLIND}: прогон НАБЛЮДАЛ зов вида «{mid}» из {rel}, а "
                    f"статический обход зова там не видит — значит у него есть дверь, "
                    f"которую он не смотрит (зов через словарь, getattr или форма импорта, "
                    f"которую разбор не знает). Про этот файл статика НЕ измерила ничего")
        missed = [rel for rel in sites.calls if rel not in seen]
        if missed:
            outside[mid] = sorted(missed)
    return {"status": "compared", "reason": None, "blind": blind,
            "outside_workloads": outside, "agreed": {k: sorted(v) for k, v in agreed.items()},
            "out_of_tree": {k: sorted(v) for k, v in out_of_tree.items()}}

def ledger_code_files(tree_root: Optional[Path] = None) -> List[str]:
    """Файлы НЕ-тестового кода, несущие литерал имени ленты — замером по дереву.

    Отвечает на вопрос «сколько лент знает КОД», отдельно от вопроса «сколько лент знает
    этот модуль». Два ответа и сверяются; совпадение их — не тавтология, потому что
    добывались они по-разному.
    """
    root = Path(tree_root or _ROOT)
    found: List[str] = []
    for base in ("spa_core", "scripts"):
        base_dir = root / base
        if not base_dir.is_dir():
            continue
        for path in sorted(base_dir.rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if "/tests/" in f"/{rel}":
                continue
            if rel == SELF_REL:
                continue  # см. SELF_REL: причина исключения названа там, а не «и так понятно»
            try:
                text = path.read_text(encoding="utf-8")
            except OSError:
                continue
            if LEDGER_LITERAL in text:
                found.append(rel)
    return found


def resolve_view(member: Member) -> Tuple[Optional[Callable], Optional[str]]:
    """Вид как вызываемое. Неразрешимый вид — третий исход с причиной, не исключение."""
    if callable(member.view):
        return member.view, None
    try:
        mod_name, _, attr = str(member.view).partition(":")
        if not attr:
            return None, f"{U_VIEW_UNRESOLVED}: в «{member.view}» нет имени функции после ':'"
        mod = importlib.import_module(mod_name)
        fn = getattr(mod, attr, None)
        if not callable(fn):
            return None, f"{U_VIEW_UNRESOLVED}: {member.view} не вызываемое"
        return fn, None
    except Exception as exc:  # noqa: BLE001 — причина обязана быть НАЗВАНА, а не съедена
        return None, f"{U_VIEW_UNRESOLVED}: {type(exc).__name__}: {exc}"


@contextlib.contextmanager
def _counting_opens(targets: Dict[str, Path]):
    """ОДНА реализация подмены обеих дверей ``open`` — для вызова вида и для всего прогона.

    Копий этой подмены не бывает двух: «одно правило — одна копия» здесь не стилистика, а
    предмет самого прибора. Счётчик, написанный во второй раз, смотрел бы на другую
    дверь — ровно тем промахом, из которого вырос третий исход
    :data:`U_DOOR_NOT_WATCHED` (``io.open is builtins.open`` истинно, но ``pathlib`` зовёт
    дверь через своё пространство имён, и подмена одной другую НЕ видит).
    """
    want: Dict[str, str] = {}
    for key, target in targets.items():
        try:
            want[key] = str(Path(target).resolve())
        except OSError:  # pragma: no cover — путь без доступа к родителю
            want[key] = str(target)
    hits: Dict[str, int] = {key: 0 for key in targets}
    real_builtin, real_io = builtins.open, io.open

    def make(real):
        def hook(file, *a, **k):
            try:
                resolved = str(Path(file).resolve())
                for key, path in want.items():
                    if resolved == path:
                        hits[key] += 1
            except (OSError, TypeError, ValueError):
                pass
            return real(file, *a, **k)
        return hook

    builtins.open = make(real_builtin)
    io.open = make(real_io)
    try:
        yield hits
    finally:
        builtins.open, io.open = real_builtin, real_io


def count_opens(target: Path, call: Callable[[], object]) -> Tuple[int, object, Optional[str]]:
    """Сколько раз за ОДИН вызов ``call`` открывается файл ``target`` — по ОБЕИМ дверям.

    ``io.open is builtins.open`` истинно (один объект), но ``pathlib`` зовёт его через
    пространство имён ``io``, поэтому подмена одной двери другую не видит. Замерено на
    ``sleeve/composer.py::load_ledger``: только ``builtins.open`` даёт 0 открытий при 49
    прочитанных строках.
    """
    with _counting_opens({"one": target}) as hits:
        try:
            answer = call()
            err = None
        except Exception as exc:  # noqa: BLE001 — вид упал ⇒ третий исход с причиной
            answer, err = None, f"{U_VIEW_RAISED}: {type(exc).__name__}: {exc}"
    return hits["one"], answer, err


def parse_seconds(path: Path, *, rounds: int = 3) -> Optional[float]:
    """Сколько стои́т ОДИН разбор ленты — замером, не оценкой. Лучшее из ``rounds``
    прогонов: шум машины завышает, и завышенная цена дала бы завышенную тревогу."""
    best: Optional[float] = None
    for _ in range(max(1, rounds)):
        t0 = time.perf_counter()
        try:
            with open(path, "r", encoding="utf-8") as fh:
                for line in fh:
                    line = line.strip()
                    if line:
                        json.loads(line)
        except (OSError, ValueError):
            return None
        took = time.perf_counter() - t0
        best = took if best is None else min(best, took)
    return best


def _answer_is_empty(answer: object) -> bool:
    """Пустой ответ вида. Пустота — законный ответ (ленты может не быть), и тогда ноль
    открытий есть ЗАМЕР. Непустой ответ при нуле открытий — наоборот, улика о двери."""
    if answer is None:
        return True
    if isinstance(answer, (list, tuple, set, dict, str)):
        return len(answer) == 0
    return False


def measure(data_dir: Path | str, *, members: Sequence[Member] = LEDGERS,
            budget_s: float = REPARSE_BUDGET_S,
            min_factor: float = MIN_GROWTH_FACTOR,
            tree_root: Optional[Path] = None,
            parse_rounds: int = 3,
            workloads: Sequence[Workload] = (),
            workload_budget_s: float = WORKLOAD_BUDGET_S,
            now=None, window_h: float = 24.0) -> dict:
    """Замер по населению. Три исхода у КАЖДОГО члена различимы (инв. #17).

    ``workloads`` пусто ПО УМОЛЧАНИЮ намеренно: названные прогоны поднимают настоящую
    сборку и настоящие экраны, и подставлять их стенду, который мерит свой фальшивый вид,
    значило бы мерить не то, о чём спрашивают. Боевое население передаёт CLI.
    """
    data = Path(data_dir)
    probe_now = now or _dt.datetime.now(_dt.timezone.utc)
    #: тот же гейт у СВОЕЙ двери: кэш цены разбора ключён по ledger_id, и разошедшиеся
    #: объявления дали бы одному файлу цену другого. Копии правила тут нет — зовётся
    #: ОДНА реализация (:func:`ledger_id_split`).
    split = ledger_id_split(members)
    rows: List[dict] = []
    #: Цена РАЗБОРА и размер — свойства ФАЙЛА, а не вида: мерить их по разу на каждый вид
    #: значило бы отвечать на вопрос о файле столько раз, сколько у него читателей, и
    #: получать разные ответы из-за шума машины. Поэтому замер один, на ledger_id.
    parse_cache: Dict[str, Tuple[Optional[int], Optional[float]]] = {}
    for m in members:
        row: dict = {
            "id": m.id,
            "ledger_id": m.ledger_id,
            "view": m.view if isinstance(m.view, str) else getattr(m.view, "__name__", "<вызываемое>"),
            "ledger": m.ledger,
            "declared_opens": m.declared_opens,
            "opens_reason": m.opens_reason,
            "scoped_door": m.scoped_door,
            "scoped_reason": m.scoped_reason,
            "opens": None,
            "bytes": None,
            "parse_s": None,
            "cost_s": None,
            "growth_factor": None,
            "unmeasured": None,
            "findings": [],
        }
        if split:
            row["unmeasured"] = split.get(m.ledger) or split.get(m.ledger_id) or \
                "; ".join(split.values())
            rows.append(row)
            continue
        path = data / m.ledger
        fn, why = resolve_view(m)
        if fn is None:
            row["unmeasured"] = why
            rows.append(row)
            continue
        if not path.exists():
            row["unmeasured"] = f"{U_LEDGER_ABSENT}: {path}"
            rows.append(row)
            continue
        row["bytes"] = path.stat().st_size
        #: вид зовётся через АТРИБУТ МОДУЛЯ; адаптер (``Member.invoke``) лишь добавляет
        #: недостающие аргументы тем видам, которым каталога мало (``cio_view(dir, now)``)
        call = ((lambda fn=fn: m.invoke(fn, data, probe_now)) if m.invoke
                else (lambda fn=fn: fn(data)))
        opens, answer, err = count_opens(path, call)
        if err:
            row["unmeasured"] = err
            rows.append(row)
            continue
        row["opens"] = opens
        if opens == 0 and not _answer_is_empty(answer):
            row["unmeasured"] = (
                f"{U_DOOR_NOT_WATCHED}: вид ответил непусто, а ни одна наблюдаемая дверь "
                f"({LEDGER_LITERAL} через builtins.open / io.open) не открывалась — "
                f"значит читает мимо них (например os.open), и ноль тут НЕ есть замер")
            rows.append(row)
            continue
        if m.ledger_id in parse_cache:
            _b, parse_s = parse_cache[m.ledger_id]
        else:
            parse_s = parse_seconds(path, rounds=parse_rounds)
            parse_cache[m.ledger_id] = (row["bytes"], parse_s)
        if parse_s is None:
            row["unmeasured"] = f"{U_LEDGER_ABSENT}: цена разбора не измерена — {path} не прочитан"
            rows.append(row)
            continue
        row["parse_s"] = parse_s
        row["cost_s"] = opens * parse_s
        if opens != m.declared_opens:
            row["findings"].append({
                "kind": F_OPENS_DRIFTED,
                "text": (f"открытий за вид {opens} против объявленных {m.declared_opens} "
                         f"— у объявленного числа есть причина: {m.opens_reason}"),
            })
        if row["cost_s"] > 0:
            row["growth_factor"] = budget_s / row["cost_s"]
            if row["growth_factor"] < min_factor:
                row["findings"].append({
                    "kind": F_MARGIN_SHORT,
                    "text": (f"запас роста {row['growth_factor']:.1f}× ниже порога "
                             f"{min_factor:.1f}× — лента append-only и не усыхает, "
                             f"поэтому бюджет {budget_s:.2f} с будет пройден без единой "
                             f"правки кода"),
                })
        else:
            # Цена строго нулевая бывает только при нуле открытий у пустого ответа:
            # запас тогда не «бесконечен», а НЕ ОПРЕДЕЛЁН, и выдавать его числом нельзя.
            row["growth_factor"] = None
        rows.append(row)

    price_by_id = {r["id"]: r["cost_s"] for r in rows}
    #: цена ОДНОГО разбора — именно она умножается на ИЗМЕРЕННОЕ число разборов прогона;
    #: цена зова (``cost_s``) остаётся рядом и отвечает на свой, прежний вопрос.
    #: Ключ здесь — ФАЙЛ (``ledger_id``), потому что разборы считаются у файла: взять
    #: ключом пару значило бы оставить ленту с двумя видами без цены вовсе.
    parse_by_id: Dict[str, Optional[float]] = {}
    for r in rows:
        if r["parse_s"] is not None or r["ledger_id"] not in parse_by_id:
            parse_by_id[r["ledger_id"]] = r["parse_s"]
    wl = measure_workloads(data, members=members, workloads=workloads,
                           price_by_id=price_by_id, parse_by_id=parse_by_id,
                           budget_s=workload_budget_s, min_factor=min_factor,
                           tree_root=tree_root, now=now, window_h=window_h)
    import_bound = direct_name_bindings(tree_root, members)
    refs = {m.id: view_reference_files(m, tree_root) for m in members}
    #: КТО зовёт вид — замер вместо числа упоминаний (заказ G782 п. 1). Статика рядом с
    #: решением, динамика — в прогонах выше; сверка их двух и есть ответ на заказ.
    static_sites = view_call_sites(members, tree_root)
    cross = cross_check_call_sites(static_sites, wl.get("call_sites") or {},
                                   sites_measured=bool(wl.get("sites_measured")))
    declared_files = sorted(LEDGER_CODE_FILES)
    tree_files = sorted(ledger_code_files(tree_root))
    doc = {
        "budget_s": budget_s,
        "min_growth_factor": min_factor,
        "data_dir": str(data),
        "rows": rows,
        "population": {
            #: ПАР «лента ↔ вид» объявлено столько; лент меньше — у одной их две
            "declared": len(members),
            "ledgers_declared": len({m.ledger_id for m in members}),
            "views_per_ledger": {lid: sorted(m.id for m in members if m.ledger_id == lid)
                                 for lid in sorted({m.ledger_id for m in members})},
            "code_files_declared": declared_files,
            "code_files_in_tree": tree_files,
            "code_files_undeclared": [f for f in tree_files if f not in declared_files],
            "code_files_missing": [f for f in declared_files if f not in tree_files],
        },
        "measured": [r for r in rows if not r["unmeasured"]],
        "unmeasured": [r for r in rows if r["unmeasured"]],
        "workloads": wl,
        "import_bound_views": import_bound,
        "view_reference_files": {k: sorted(v) for k, v in refs.items()},
        "call_sites": {
            "static": {k: {"calls": v.calls,
                           "mentions_only": list(v.mentions_only),
                           "unresolved_base": v.unresolved_base}
                       for k, v in static_sites.items()},
            #: файлы, которые не разобрались, — ОДИН список на обход: про них не измерено
            #: ничего ни по одному виду, и повторять их у каждого вида значило бы выдать
            #: одну непрочитанную страницу за пять разных
            "unparsed": (next(iter(static_sites.values())).unparsed
                         if static_sites else {}),
            "cross": cross,
        },
    }
    doc["findings"] = [dict(f, id=r["id"]) for r in rows for f in r["findings"]]
    doc["findings"].extend(wl["findings"])
    if import_bound:
        doc["findings"].append({
            "kind": F_IMPORT_BOUND_VIEW,
            "id": "counter",
            "text": ("имя вида связано НА ИМПОРТЕ — такой потребитель проходит мимо "
                     "счётчика вызовов молча: " + "; ".join(import_bound)),
        })
    return doc


def format_report(doc: dict) -> List[str]:
    out = [f"— повторный разбор хеш-лент у читающих моделей (заказ G777 п. 1) —",
           f"   каталог: {doc['data_dir']}",
           f"   РЕШЕНИЯ (не замеры): бюджет {doc['budget_s']:.2f} с на вызов вида · "
           f"порог запаса {doc['min_growth_factor']:.1f}×"]
    for r in sorted(doc["rows"], key=lambda x: (x["growth_factor"] is None,
                                                x["growth_factor"] or 0.0)):
        if r["unmeasured"]:
            out.append(f"   [НЕ ИЗМЕРЕНО] {r['id']}: {r['unmeasured']}")
            continue
        door = "область кэша ЕСТЬ" if r["scoped_door"] else "области кэша НЕТ"
        factor = "—" if r["growth_factor"] is None else f"{r['growth_factor']:.1f}×"
        out.append(f"   {r['id']}: {r['bytes']:,} Б · разбор {r['parse_s']:.4f} с · "
                   f"открытий {r['opens']} · цена {r['cost_s']:.3f} с · запас {factor} · {door}")
    wl = doc.get("workloads") or {}
    if wl.get("declared"):
        out.append(f"   — второй и ТРЕТИЙ множители: разборы за прогон × прогоны за сутки "
                   f"(заказы G778 п. 3, G779) —")
        out.append(f"     РЕШЕНИЕ (не замер): бюджет прогона {wl['budget_s']:.2f} с · "
                   f"объявленных прогонов {wl['declared']} — прибор мерит эти, а не "
                   f"утверждает, что других нет; суточного бюджета НЕТ ни одного — такого "
                   f"решения никто не принимал, и прибор его не выдумывает")
        for r in wl["rows"]:
            if r["unmeasured"]:
                out.append(f"     [НЕ ИЗМЕРЕНО] {r['id']}: {r['unmeasured']}")
                continue
            calls = " · ".join(f"{k}×{v}" for k, v in sorted(r["calls"].items()) if v)
            parses = " · ".join(f"{k}×{v}" for k, v in sorted((r["opens"] or {}).items()) if v)
            factor = "—" if r["growth_factor"] is None else f"{r['growth_factor']:.1f}×"
            out.append(f"     {r['id']}: зовы вида {calls or 'ни одного'} · РАЗБОРОВ "
                       f"{parses or 'ни одного'} · полная цена {r['price_s']:.3f} с · "
                       f"запас {factor}")
            cad = r.get("cadence") or {}
            rate_parts = []
            if cad.get("observed_per_day") is not None:
                rate_parts.append(f"наблюдено {cad['observed_per_day']:.0f}/сутки "
                                  f"({cad['observed_count']} зап. за окно {cad['window_h']:.0f}ч)")
            if cad.get("declared_per_day") is not None:
                rate_parts.append(f"объявлено расписанием {cad['declared_per_day']:.0f}/сутки")
            if r.get("price_day_s") is not None:
                out.append(f"       третий множитель: {' · '.join(rate_parts)} ⇒ СУТОЧНАЯ "
                           f"цена {r['price_day_s']:.1f} с/сутки "
                           f"({r['share_of_day'] * 100:.3f} % суток), источник частоты — "
                           f"{r['rate_source']}")
            if r.get("daily_unmeasured"):
                out.append(f"       [НЕ ИЗМЕРЕНО] {r['daily_unmeasured']}")
            if r["not_countable"]:
                for mid, why in sorted(r["not_countable"].items()):
                    out.append(f"       [НЕ ИЗМЕРЕНО] {mid}: {why}")
        for mid, why in sorted(wl["unreached"].items()):
            refs = (doc.get("view_reference_files") or {}).get(mid) or []
            out.append(f"     [НЕ ИЗМЕРЕНО] {mid}: {why}; упоминаний вида в не-тестовом "
                       f"коде: {len(refs)}")
        refs_all = doc.get("view_reference_files") or {}
        if refs_all:
            out.append("     ЗАМЕР рядом с решением — упоминаний вида в не-тестовом коде: "
                       + " · ".join(f"{k}:{len(v)}" for k, v in sorted(refs_all.items()))
                       + f" (прогонов измерено {wl['declared']}; упоминание, однако, не "
                         f"есть зов — зовущие ниже)")
        cs = doc.get("call_sites") or {}
        static = cs.get("static") or {}
        if static:
            out.append("     КТО ЗОВЁТ вид (разбор кода, а не подстрока): "
                       + " · ".join(f"{k}:{len(v.get('calls') or {})}"
                                    for k, v in sorted(static.items())))
            for mid, v in sorted(static.items()):
                only = v.get("mentions_only") or []
                if only:
                    out.append(f"       {mid}: упоминают и НЕ зовут {len(only)} — "
                               f"{', '.join(only)}")
                for rel, why in sorted((v.get("unresolved_base") or {}).items()):
                    out.append(f"       [НЕ ИЗМЕРЕНО] {rel}: {why}")
        for rel, why in sorted((cs.get("unparsed") or {}).items()):
            out.append(f"     [НЕ ИЗМЕРЕНО] {rel}: {why}")
        cross = cs.get("cross") or {}
        if cross.get("status") == "not_measured":
            out.append(f"     [НЕ ИЗМЕРЕНО] сверка статики с прогонами: {cross['reason']}")
        elif cross.get("status") == "compared":
            for mid, bad in sorted((cross.get("blind") or {}).items()):
                for rel, why in sorted(bad.items()):
                    out.append(f"     [НЕ ИЗМЕРЕНО] {mid} ← {rel}: {why}")
            outside = cross.get("outside_workloads") or {}
            if outside:
                out.append("     НЕПОЛНОТА НАСЕЛЕНИЯ ПРОГОНОВ — названная по файлам: "
                           + " · ".join(f"{k}: {', '.join(v)}"
                                        for k, v in sorted(outside.items())))
            else:
                out.append("     население прогонов достаёт КАЖДОГО статического зовущего "
                           "(сверено в обе стороны, а не предположено)")
        if doc.get("import_bound_views") is not None and not doc["import_bound_views"]:
            out.append("     счётчик подменяет АТРИБУТ МОДУЛЯ; связываний имени вида на "
                       "импорте в дереве не найдено — это ЗАМЕР обходом, а не умолчание")
    findings = doc["findings"]
    if findings:
        out.append(f"   🔴 НАХОДОК {len(findings)}:")
        for f in findings:
            out.append(f"      [{f['kind']}] {f['id']}: {f['text']}")
    else:
        out.append("   ✅ у каждого члена открытий столько, сколько объявлено, и запас выше порога")
