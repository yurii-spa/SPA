# модуля, а не решение о предмете. Поэтому ``root=None`` теперь значит «реши
# сам» и решается ЖИВЫМ деревом (`utils.live_paths.live_root` — тот самый модуль,
# написанный 08.08 против этого же класса), а явный ``--root`` остаётся дословным:
# кто назвал дерево — тот его и выбрал.
ROOT_EXPLICIT = "explicit"   # дерево назвал вызывающий — берём дословно
ROOT_LIVE = "live"           # нашли живое дерево (SPA_LIVE_ROOT / прод-каталог)
ROOT_OWN_TREE = "own_tree"   # живого дерева не видно и никто его не назвал

#: Проба «живого дерева нет». ``live_root`` отдаёт fallback ДОСЛОВНО и только
#: когда не нашлось ни ``SPA_LIVE_ROOT``, ни прод-каталога; отличить этот исход
#: чтением кода `live_root` значило бы держать его копию (а копия слепа к
#: расхождению с источником), поэтому спрашиваем сам ``live_root``.
_NO_LIVE_TREE = "\x00-spa-no-live-tree"


def _UNNAMED_TREE_REASON(root: str) -> str:
    """Один текст на обе двери (``scan`` и ``run``) — расходиться им незачем."""
    return (f"НЕ ИЗМЕРЕНО: живого дерева не видно ({LIVE_ROOT_ENV} не задан, "
            f"прод-каталога нет) и --root не назван — судить пришлось бы дерево "
            f"собственного кода {root}, а оно совпадает с origin по построению; "
            f"«весь след на origin» здесь значило бы «сравнивать было нечего». "
            f"Назовите дерево: --root <прод-дерево> либо {LIVE_ROOT_ENV}=<путь>")


def resolve_root(root=None) -> tuple:
    """``(дерево, откуда оно взялось)`` — см. блок выше.

    ``root=None`` НЕ означает «каталог этого файла»: см. замер 30.08. Возврат —
    всегда пара, чтобы вердикт мог отличить «сверено живое дерево» от «сверено
    дерево собственного кода», а не выдавать второе за первое.
    """
    if root is not None:
        return str(root), ROOT_EXPLICIT
    from pathlib import Path
    found = live_root(Path(_NO_LIVE_TREE))
    if str(found) == _NO_LIVE_TREE:
        return REPO_ROOT, ROOT_OWN_TREE
    return str(found), ROOT_LIVE


def _now(now: dt.datetime | None = None) -> dt.datetime:
    return now or dt.datetime.now(dt.timezone.utc)


def is_enabled(env=None) -> bool:
    """По умолчанию сторож ВКЛЮЧЁН."""
    env = os.environ if env is None else env
    return str(env.get(ENV_FLAG, "1")).strip().lower() not in ("0", "off", "false", "no")


# ── разбор следа во frontmatter (байты, без промежуточных представлений) ──────

def _field_re(key: str):
    """Верхнеуровневое поле frontmatter: без отступа (вложенное ``type:`` — не оно)."""
    return re.compile(rb"(?m)^" + re.escape(key.encode()) + rb":[ \t]*(.*)$")


#: Полный след ответа владельца в порядке записи: САМ ответ и — сразу за ним — регистр
#: вытеснения (ADR-180). Порядок объявленный, не словарный: он определяет содержимое
#: коммита, и словарный сделал бы его зависящим от порядка чтения.
#:
#: **Почему регистр возится, но НЕ участвует в споре.** Спор о решении — это только
#: ``owner_choice`` (ADR-175/179). Внеси регистр в :func:`trace_fields`, и его расхождение
#: само стало бы «двумя разными ответами владельца» — новый класс ложных ⛔ ровно того
#: вида, который ADR-175 снимал. Поэтому у регистра одна роль: доехать до origin, где
#: :func:`clash_superseded` его и читает. Без этой строки писатель (ADR-180) пишет регистр
#: в прод-дерево, а сторож ищет его на origin — две половины, не смыкающиеся никогда.
CARRIED_FIELDS = OWNER_ANSWER_FIELDS + tuple(SUPERSEDED_FIELDS.values())


def trace_fields(blob: bytes) -> dict:
    """Поля следа ответа владельца из БАЙТОВ карточки (пусто — следа нет).

    Отдельно от ``owner_answer.read_answer_fields`` только формой входа (байты
    против текста): имена полей берутся из одного списка ``OWNER_ANSWER_FIELDS``,
    второй копии имён здесь нет.
    """
    return _read_fields(blob, OWNER_ANSWER_FIELDS)


def _read_fields(blob: bytes, keys) -> dict:
    """Верхнеуровневые поля frontmatter из ``keys``, У КОТОРЫХ ЕСТЬ ЗНАЧЕНИЕ.

    Поле, написанное пустым скаляром (:data:`EMPTY_SCALARS`), — это объявленное
    отсутствие значения, и здесь оно неотличимо от поля, которого нет вовсе. Так
    и надо: ``owner_choice: ""`` означает «владелец ещё не ответил».
    """
    parts = card_parts(blob)
    if parts is None:
        return {}
    fm = parts[0]
    out: dict = {}
    for key in keys:
        m = _field_re(key).search(fm)
        if m is None:
            continue
        value = m.group(1).strip().decode("utf-8", "replace")
        if value and value not in EMPTY_SCALARS:
            out[key] = value
    return out


def present_keys(blob: bytes, keys) -> set:
    """Ключи, ФИЗИЧЕСКИ присутствующие в frontmatter — без фильтра пустоты.

    Отличается от :func:`_read_fields` ровно этим, и различие существенно.
    ``_read_fields`` отвечает на вопрос «назван ли ответ владельца» и правильно
    считает ``owner_choice: ""`` отсутствием ОТВЕТА. Но строка-то в файле ЕСТЬ, и
    дописать рядом вторую с тем же ключом — значит сделать файл противоречивым.
    """
    parts = card_parts(blob)
    if parts is None:
        return set()
    fm = parts[0]
    return {k for k in keys if _field_re(k).search(fm) is not None}


def unquote_scalar(value: str) -> str:
    """YAML-скаляр без ПАРНЫХ кавычек — или он сам, если раскавычить недоказуемо.

    Сторож читает байты frontmatter (YAML-парсера в рантайме нет — только stdlib),
    поэтому ``1`` и ``"1"`` приходили к сравнению двумя РАЗНЫМИ строками. Значение
    у них одно: это один и тот же скаляр, записанный двумя законными способами.

    Замер 30.08 (цикл #428) на живом прод-дереве, origin ``a04fd645e``: из шести
    расхождений, по которым шаг 0-офис печатал ``⛔ ДВА РАЗНЫХ ОТВЕТА ВЛАДЕЛЬЦА,
    нужен человек``, **два состояли РОВНО из кавычек** (``owner-decision-AI1-approach``
    и ``owner-decision-urovni-dokazatelnosti``: на origin ``"1"``, у нас ``1``), ещё
    у двух кавычки давали одно расхождение из трёх. Настоящий спор был ОДИН —
    ``owner-decision-partiya-2-karantina``: на origin вариант ``"4"``, у нас ``1``,
    решения противоположные. Сторож, зовущий человека на не-спор, глохнет ровно тем
    же способом, что fail-OPEN монитор: единственный настоящий спор лежал в одном
    ряду с четырьмя ложными.

    Цикл #427 починил соседний экземпляр того же корня (пустой скаляр) и кавычки
    оставил НАМЕРЕННО, записав причину в код: «замер того же дня дал НОЛЬ
    расхождений вида ``1`` против ``"1"``, а снятие кавычек могло бы склеить два
    разных ответа». Первая половина опровергнута замером выше. Вторая верна и
    задаёт форму починки — отсюда два свойства:

    * **раскавычивание доказуемое, а не косметическое.** Снимается только ПАРА
      кавычек, обрамляющая ВЕСЬ скаляр, по правилам YAML: у двойных ``\\\\`` и
      ``\\"``, у одинарных ``''``. Любое написание, которого функция не берётся
      разобрать (одиночная кавычка, экранирование помимо этих двух, кавычка внутри
      двойных без экрана), возвращается КАК ЕСТЬ — недоказанное равенство остаётся
      неравенством. Fail-CLOSED: молчание сторожа надо заслужить;
    * **внутренность скаляра не трогается.** ``"1 "`` против ``1`` обязано остаться
      расхождением, ``"4"`` против ``1`` — тоже: это разные ответы, и склеить их
      функция не может.

    Применяется ТОЛЬКО к сравнению (:func:`same_scalar`). В :func:`merge_trace`
    на origin уезжает СЫРАЯ строка нашего frontmatter: раскавыченное значение —
    суждение о равенстве, а не текст карточки, и записывать вместо владельца свою
    нормализацию модуль не смеет (значение вроде ``"да, но позже"`` без кавычек
    перестало бы быть тем же YAML).
    """
    if len(value) < 2 or value[0] != value[-1] or value[0] not in ('"', "'"):
        return value
    inner = value[1:-1]
    if value[0] == '"':
        # Разбираем ровно два экранирования. Всё прочее (\n, \t, \uXXXX) — повод
        # отказаться, а не угадать: неверно раскавыченное значение сравнивается
        # молча и не оставляет следа.
        i, out = 0, []
        while i < len(inner):
            ch = inner[i]
            if ch == "\\":
                nxt = inner[i + 1] if i + 1 < len(inner) else ""
                if nxt not in ('"', "\\"):
                    return value
                out.append(nxt)
                i += 2
                continue
            if ch == '"':  # неэкранированная кавычка внутри — это не один скаляр
                return value
            out.append(ch)
            i += 1
        return "".join(out)
    # Одинарные: единственное экранирование YAML — удвоение кавычки.
    i, out = 0, []
    while i < len(inner):
        ch = inner[i]
        if ch == "'":
            if inner[i + 1:i + 2] != "'":
                return value
            out.append("'")
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def same_scalar(a: str, b: str) -> bool:
    """Один ли это YAML-скаляр, записанный (возможно) по-разному.

    Единственное место, где сторож решает «расходятся ли значения». Одна функция,
    а не два одинаковых сравнения в :func:`merge_trace` и :func:`clash_superseded`:
    условие, размноженное по вызывающим, чинится в одном из них и молча остаётся
    сломанным в другом — регистр вытеснения тогда перестал бы покрывать
    расхождение, объявленное в кавычках, и это был бы НОВЫЙ класс ложных ⛔.
    """
    return a == b or unquote_scalar(a) == unquote_scalar(b)


def superseded_fields(blob: bytes) -> dict:
    """Регистр вытеснения из БАЙТОВ карточки: что именно объявлено вытесненным."""
    return _read_fields(blob, SUPERSEDED_FIELDS.values())


def clash_superseded(clash: dict, remote: bytes) -> tuple:
    """``(bool, причина)`` — назвал ли origin КАЖДОЕ расхождение вытесненным.

    Fail-CLOSED и намеренно узко. ``True`` только если по всем расходящимся
    полям регистр origin (а) существует, (б) совпадает с НАШИМ значением байт в
    байт. Хоть одна дыра ⇒ ``False``, и дыра названа поимённо: «покрыто
    частично» — это спор двух ответов, а не разобранный спор, и молчание по
    непокрытому полю было бы выбором стороны молча.
    """
    reg = superseded_fields(remote)
    covered, gaps = [], []
    for key, (theirs, ours) in sorted(clash.items()):
        reg_key = SUPERSEDED_FIELDS.get(key)
        if reg_key is None:
            gaps.append(f"{key}: поля вытеснения для него не объявлено вовсе")
            continue
        got = reg.get(reg_key)
        if got is None:
            gaps.append(f"{key}: на origin нет {reg_key}")
        elif not same_scalar(got, ours):
            gaps.append(f"{key}: origin вытеснил {got!r}, а у нас {ours!r}")
        else:
            covered.append(f"{key}: {ours!r} → {theirs!r}")
    if gaps or not covered:
        return False, ("вытеснение НЕ покрывает расхождение: " + "; ".join(gaps)
                       if gaps else "регистра вытеснения на origin нет")
    return True, "; ".join(covered)


def attribution_keys(blob: bytes) -> set:
    """Признаки авторства ответа владельца в копии карточки.

    Множество имён — не «да/нет»: частичная атрибуция (одно поле из трёх) обязана
    отличаться от полного её отсутствия, иначе пятый исход поглотил бы форму, о
    которой мы ничего не знаем.

    Читаются те же поля, которыми метит ответ штатный писатель
    (``owner_answer._PROVENANCE_FIELDS``, ИМПОРТИРОВАНЫ — ADR-180: вторая копия
    имён и есть тот дефект), плюс отметка журнала переходов
    (:data:`ANSWER_WRITER_MARK`): она называет писателя прямо, и по ней атрибуция
    видна даже там, где полей нет.
    """
    keys = set(_read_fields(blob, PROVENANCE_FIELDS))
    if ANSWER_WRITER_MARK in blob:
        keys.add("status_trail")
    return keys


def unattributed_remote(local: bytes, remote: bytes) -> bool:
    """Пятый исход: у НАС ответ владельца с автором, на origin — значение без автора.

    Fail-CLOSED и асимметрично (см. :data:`UNATTRIBUTED_MARK`). Все три условия
    обязательны, и каждое закрыто своим обратным контролем:

    1. на origin нет НИ ОДНОГО признака авторства — ни поля, ни отметки журнала;
    2. у нас есть ВСЕ поля провенанса: наша сторона — полноценная запись ответа,
       а не такая же безымянная;
    3. (следствие 1 и 2) сравнивать «кто из двух ответов владельца верен» не с чем:
       ответ владельца здесь ровно один.

    Хоть одно нарушено ⇒ False, и расхождение остаётся спором для человека. Так,
    origin с частичным провенансом (одно поле) — по-прежнему CONFLICT: мы не знаем,
    чем он написан, а догадка в пользу «это агент» стоила бы затёртого ответа.
    """
    if attribution_keys(remote):
        return False
    mine = _read_fields(local, PROVENANCE_FIELDS)
    return all(k in mine for k in PROVENANCE_FIELDS)


def merge_trace(local: bytes, remote: bytes) -> tuple:
    """``(bytes|None, причина, добавленные_поля)`` — remote плюс НАШ след.

    Строим из remote: тело и все прочие строки frontmatter остаются его. Наши —
    только недостающие строки следа. Каждый отказ называет свою причину:
    «сделали не то» и «мы ослепли» — разные аварии.
    """
    lp, rp = card_parts(local), card_parts(remote)
    if lp is None:
        return None, "наша копия не карточка (нет frontmatter) — переносить нечего", {}
    if rp is None:
        return None, "версия на origin не карточка (нет frontmatter) — сравнивать не с чем", {}

    mine = trace_fields(local)
    if not mine:
        return None, "в нашей копии нет следа ответа владельца — переносить нечего", {}
    theirs = trace_fields(remote)

    clash = {k: (theirs[k], mine[k])
             for k in mine if k in theirs and not same_scalar(theirs[k], mine[k])}
    if clash:
        named = "; ".join(f"{k}: на origin {o!r}, у нас {m!r}" for k, (o, m) in sorted(clash.items()))
        resolved, why = clash_superseded(clash, remote)
        if resolved:
            # Третий исход. «Совпало» и «не совпало» — не весь мир: бывает
            # «расходились, и владелец уже решил, вот чем именно». Везти при
            # этом по-прежнему НЕЧЕГО (наш ответ — вытесненный), но и звать
            # человека не на что.
            return None, (f"{SUPERSEDED_MARK} более поздним ответом владельца, и origin "
                          f"называет вытесненное поимённо ({why}) — везти нечего, "
                          f"сторону выбрал владелец"), {}
        if "owner_choice" not in clash:
            # Четвёртый исход. Обе копии называют ОДИН И ТОТ ЖЕ выбор владельца
            # (или наша не называет никакого) — расходятся лишь канал и отметка.
            # Спора о решении нет, значит и стороны выбирать не надо: звать
            # человека тут не на что. Везти всё равно НЕЧЕГО — наша отметка
            # затёрла бы origin'ную запись о том, как ответ пришёл туда.
            return None, (f"{PROVENANCE_MARK}, разошёлся лишь провенанс ({named}) — "
                          f"везти нечего (наша отметка затёрла бы origin'ную), "
                          f"человек не нужен"), {}
        if unattributed_remote(local, remote):
            # Пятый исход. Спорить не с чем: ответ владельца ровно один — наш, с
            # автором. На origin стоит значение, которого владелец не давал и под
            # которым никто не подписан. Везти по-прежнему НЕЧЕГО (строка там
            # есть, а перенос умеет только дописывать) и в `blocked` это остаётся —
            # меняется только имя находки: чинить надо ЗАПИСЬ, а не звать владельца
            # выбирать между собой и агентом.
            return None, (f"{UNATTRIBUTED_MARK}: ни одного признака авторства "
                          f"(ни {', '.join(PROVENANCE_FIELDS)}, ни отметки писателя в "
                          f"status_trail), а наша копия несёт ответ владельца целиком "
                          f"({named}) — это не второй ответ владельца, а запись без "
                          f"автора; сторону выбирать не надо, чинить надо запись на "
                          f"origin [{why}]"), {}
        return None, (f"на origin ДРУГОЙ ответ владельца ({named}) — две копии несут разные "
                      f"решения, выбирать сторону молча нельзя; сверьте руками [{why}]"), {}

    added = {k: v for k, v in mine.items() if k not in theirs}
    # Регистр вытеснения не спорит (см. `CARRIED_FIELDS`), но доехать обязан: сторож
    # читает его ТОЛЬКО на origin.
    reg_mine, reg_theirs = superseded_fields(local), superseded_fields(remote)
    added.update({k: v for k, v in reg_mine.items() if k not in reg_theirs})
    if not added:
        return None, "след уже на origin — везти нечего", {}

    # Fail-CLOSED, замер 30.08 (цикл #429). `theirs` не видит поля, написанного
    # ПУСТЫМ скаляром (`owner_choice: ""` = «владелец ещё не ответил», и это верно),
    # но СТРОКА в файле есть. Дописав рядом вторую с тем же ключом, мы получили бы
    # frontmatter с двумя `owner_choice`, читатель берёт ПЕРВЫЙ — пустой, — и ответ
    # владельца, уехавший на origin, становится НЕВИДИМ. Хуже прежнего: раньше его
    # просто не было, теперь он есть и не читается, а сторож на каждом прогоне
    # дописывает ещё одну копию (цикл без предела).
    #
    # Замена строки на месте — правильная починка, но это уже НЕ «отличается только
    # добавленными строками», на чём стоит всё доказательство переноса
    # (`verify_trace_only`). Такое решение делается своим циклом и своим ADR, а не
    # довеском. Здесь — отказ с названной причиной: карточка
    # `inbox-perenos-sleda-umeet-tolko-dopisyvat-pust`.
    # Спрашиваем про ИМЕННО ТЕ ключи, которые собираемся дописать, а не про заранее
    # выбранный список: разойдясь, второй молча перестал бы покрывать первый.
    dup = sorted(k for k in added if k in present_keys(remote, added))
    if dup:
        return None, ("на origin поле уже НАПИСАНО, но пустым скаляром "
                      f"({', '.join(dup)}) — дописать рядом второе значит сделать "
                      "frontmatter противоречивым, и читатель возьмёт ПУСТОЕ; "
                      "заменять строку на месте этот перенос не умеет (доказательство "
                      "переноса допускает только ДОБАВЛЕННЫЕ строки). Чинить руками"), {}

    r_fm, r_body = rp
    # Дописываем в КОНЕЦ frontmatter в стабильном порядке CARRIED_FIELDS —
    # словарный порядок сделал бы содержимое коммита зависящим от порядка чтения.
    lines = b"".join(f"{k}: {added[k]}\n".encode()
                     for k in CARRIED_FIELDS if k in added)
    candidate = remote[:4] + r_fm + lines + b"---\n" + r_body

    ok, why = verify_trace_only(remote, candidate)
    if not ok:
        return None, f"перенос не доказан: {why}", {}
    return candidate, "", added


def verify_trace_only(remote: bytes, candidate: bytes) -> tuple:
    """``(bool, причина)`` — кандидат отличается от remote ТОЛЬКО следом.

    Независимая проверка: кандидат разбирается заново, как будто его прислал
    кто-то другой. Смысл именно в независимости — конструктор, проверяющий сам
    себя, повторяет свою же ошибку, а этот проект на таком уже горел.
    """
    rp, cp = card_parts(remote), card_parts(candidate)
    if rp is None or cp is None:
        return False, "одна из версий не карточка"
    r_fm, r_body = rp
    c_fm, c_body = cp
    if c_body != r_body:
        return False, "тело отличается от origin — модуль не смеет трогать тело карточки"

    r_lines, c_lines = r_fm.splitlines(True), c_fm.splitlines(True)
    allowed = {k.encode() for k in CARRIED_FIELDS}
    extra: list = []
    i = 0
    for line in c_lines:
        if i < len(r_lines) and line == r_lines[i]:
            i += 1
            continue
        extra.append(line)
    if i != len(r_lines):
        return False, "строки frontmatter с origin изменены или пропали — допускается только добавление"
    for line in extra:
        key = line.split(b":", 1)[0]
        if line[:1].isspace() or key not in allowed:
            return False, (f"добавлена строка не из следа ответа владельца: "
                           f"{line.decode('utf-8', 'replace').strip()!r}")
    if not extra:
        return False, "кандидат ничем не отличается от origin — везти нечего"
    return True, ""


# ── что именно недоставлено ──────────────────────────────────────────────────

def _tracker_dir(root: str) -> str:
    return os.path.join(root, TRACKER_REL)


def scan(root: str | None = None, reader=_default_remote_reader) -> list:
    """Карточки дерева ``root``, чей след ответа владельца на origin не полон.

    Список строится ЗАНОВО каждый прогон — отсюда повтор без отдельного долга.
    Ни одна карточка со следом не исчезает молча: она попадает ровно в один
    вердикт, включая ``unmeasured``.
    """
    root, root_source = resolve_root(root)
    if root_source == ROOT_OWN_TREE:
        # Дерево не назвал никто, живого не видно. Перечислять каталог
        # собственного кода нельзя: он совпадает с origin по построению, и любой
        # вердикт по нему — вердикт о вопросе, которого не задавали (замер 30.08).
        return [{"card": None, "verdict": UNMEASURED, "reason": _UNNAMED_TREE_REASON(root)}]
    out: list = []
    tracker = _tracker_dir(root)
    try:
        names = sorted(n for n in os.listdir(tracker) if n.endswith(".md"))
    except OSError as e:  # noqa: BLE001 — каталога нет: это не «карточек нет»
        return [{"card": None, "verdict": UNMEASURED,
                 "reason": f"каталог трекера нечитаем: {type(e).__name__}: {e}"}]

    for name in names:
        if name in NEVER_DELIVER:
            continue
        absolute = os.path.join(tracker, name)
        try:
            with open(absolute, "rb") as f:
                local = f.read()
        except OSError as e:  # noqa: BLE001 — был ли там след, ТЕПЕРЬ уже не узнать
            out.append({"card": name, "verdict": UNMEASURED,
                        "reason": f"карточка не прочитана: {type(e).__name__}: {e}"})
            continue
        mine = trace_fields(local)
        if not mine:
            continue  # следа ответа нет — это не наша карточка

        repo_path = f"{TRACKER_REL}/{name}".replace(os.sep, "/")
        state, remote, why = reader(root, repo_path)
        if state == REMOTE_ABSENT:
            out.append({"card": name, "path": absolute, "repo_path": repo_path,
                        "verdict": CREATE_ON_ORIGIN, "answer": mine,
                        "content": local,
                        "reason": "карточки на origin нет вовсе — везём как создание"})
            continue
        if state != REMOTE_PRESENT or remote is None:
            out.append({"card": name, "path": absolute, "repo_path": repo_path,
                        "verdict": UNMEASURED, "answer": mine,
                        "reason": why or "версию на origin прочитать не удалось"})
            continue

        merged, reason, added = merge_trace(local, remote)
        if merged is None:
            if "след уже на origin" in reason:
                verdict = ALREADY_ON_ORIGIN
            elif reason.startswith(SUPERSEDED_MARK):
                verdict = SUPERSEDED
            elif reason.startswith(PROVENANCE_MARK):
                verdict = PROVENANCE
            elif reason.startswith(UNATTRIBUTED_MARK):
                verdict = UNATTRIBUTED
            elif "ДРУГОЙ ответ владельца" in reason:
                verdict = CONFLICT
            else:
                verdict = REFUSED
            out.append({"card": name, "path": absolute, "repo_path": repo_path,
                        "verdict": verdict, "answer": mine, "reason": reason})
            continue
        out.append({"card": name, "path": absolute, "repo_path": repo_path,
                    "verdict": NEEDS_TRACE, "answer": mine, "added": added,
                    "content": merged,
                    "reason": f"на origin нет полей: {', '.join(sorted(added))}"})
    return out


# ── отправка ─────────────────────────────────────────────────────────────────

def build_message(items: list) -> str:
    names = [i["card"] for i in items]
    head = ", ".join(names[:3]) + (f" (+{len(names) - 3})" if len(names) > 3 else "")
    return (f"owner-answer: след решения владельца → origin ({len(names)}): {head} — "
            f"ответ жил только в прод-дереве, в git его не было; везётся ТОЛЬКО след "
            f"(поля frontmatter), тело и status: origin не трогаются")


def _load_pusher_module(root: str):
    import importlib.util
    path = os.path.join(root, PUSHER_REL)
    if not os.path.isfile(path):
        return None
    spec = importlib.util.spec_from_file_location("_spa_pusher_for_answer_delivery", path)
    if spec is None or spec.loader is None:
        return None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _default_pusher(root: str, items: list, message: str) -> tuple:
    """``(ok, подробность)`` — один коммит из построенного содержимого.

    Цепочка и её сверки — пушера (`create_blob_from_bytes` сверяет sha blob'а,
    `update_ref` сверяет, что ветка встала на НАШ коммит). Родитель — база,
    прочитанная в этом же прогоне: чужой пуш в окне даст отказ GitHub, а не
    тихую перезапись.
    """
    # Owner-gate ПЕРВЫМ, до загрузки пушера: отказ обязан наступать раньше, чем
    # модуль вообще получит в руки инструмент доставки и PAT. Порядок здесь —
    # часть проверки, а не стиль: пушер, которого нет, погасил бы её собой.
    prefix = f"{TRACKER_REL}/".replace(os.sep, "/")
    for item in items:
        if not str(item.get("repo_path", "")).startswith(prefix):
            return False, f"путь вне трекера — не отправляю: {item.get('repo_path')}"
    mod = _load_pusher_module(root)
    if mod is None:
        return False, f"инструмента доставки нет: {PUSHER_REL}"
    try:
        pat = mod.get_pat()
        base_sha, base_tree = mod.get_base_ref(pat, mod.REPO, "main")
        entries = []
        for item in items:
            blob = mod.create_blob_from_bytes(pat, mod.REPO, item["content"])
            entries.append({"path": item["repo_path"], "mode": "100644",
                            "type": "blob", "sha": blob})
        tree = mod.create_tree(pat, mod.REPO, base_tree, entries)
        commit = mod.create_commit(pat, mod.REPO, message, tree, base_sha)
        mod.update_ref(pat, mod.REPO, "main", commit)
        return True, commit[:8]
    except Exception as e:  # noqa: BLE001 — отказ НАЗЫВАЕТСЯ, а не роняет сторожа
        return False, f"{type(e).__name__}: {e}"


def run(root: str | None = None, now: dt.datetime | None = None,
        reader=_default_remote_reader, pusher=_default_pusher, env=None,
        write_status: bool = True, dry_run: bool = False) -> dict:
    """Найти недоставленный след решения владельца и довезти его. Квитанция.

    Исключений НЕ бросает: сторож не смеет уронить того, кто его позвал. Но и не
    молчит — любой исход попадает в ``status``.
    """
    ts = _now(now)
    root, root_source = resolve_root(root)
    receipt = {"generated_at": ts.isoformat(), "adr": "ADR-086",
               "root": root, "root_source": root_source,
               "scanned": 0, "delivered": [], "already_on_origin": [],
               "refused": [], "unmeasured": [], "conflicts": [], "superseded": [],
               "provenance": [], "unattributed": [],
               "pending": [], "status": UNCHECKED, "reason": "", "commit": None}
    if root_source == ROOT_OWN_TREE:
        # Отказ ДО перечисления и ДО пуша. Не «мы посмотрели и всё хорошо», а
        # «смотреть было не на что»: дерево не назвал никто. Отдельно важно, что
        # отказ стоит перед пушем — иначе сторож повёз бы на origin след из
        # дерева, которое никто не выбирал.
        receipt["reason"] = _UNNAMED_TREE_REASON(root)
        receipt["unmeasured"] = [{"card": None, "reason": receipt["reason"]}]
        return receipt
    try:
        findings = scan(root, reader=reader)
        receipt["scanned"] = len(findings)
        by = {}
        for f in findings:
            by.setdefault(f["verdict"], []).append(f)

        receipt["already_on_origin"] = sorted(f["card"] for f in by.get(ALREADY_ON_ORIGIN, []))
        receipt["unmeasured"] = [{"card": f.get("card"), "reason": f.get("reason")}
                                 for f in by.get(UNMEASURED, [])]
        receipt["conflicts"] = [{"card": f["card"], "reason": f["reason"]}
                                for f in by.get(CONFLICT, [])]
        # Вытесненные НЕ попадают в blocked: везти по ним нечего ровно так же,
        # как по already_on_origin, и держать из-за них статус в REFUSED значило
        # бы чинить громкость, оставив вердикт врать.
        receipt["superseded"] = [{"card": f["card"], "reason": f["reason"]}
                                 for f in by.get(SUPERSEDED, [])]
        # Провенанс — рядом с вытеснением и по той же причине: везти нечего и
        # звать некого, но невидимым расхождение оставлять нельзя.
        receipt["provenance"] = [{"card": f["card"], "reason": f["reason"]}
                                 for f in by.get(PROVENANCE, [])]
        # Пятый исход — НЕ рядом с вытеснением и провенансом, а рядом с отказом:
        # там запись на origin ВЕРНА и просто иная, здесь она НЕВЕРНА. Наш след на
        # origin не доехал, и называть прогон доставленным было бы враньём — поэтому
        # `unattributed` остаётся в `blocked`. Правка меняет ИМЯ находки, а не её
        # громкость: гасить проверку, которая мешает, запрещено правилом доставки.
        receipt["unattributed"] = [{"card": f["card"], "reason": f["reason"]}
                                   for f in by.get(UNATTRIBUTED, [])]
        receipt["refused"] = [{"card": f["card"], "reason": f["reason"]}
                              for f in by.get(REFUSED, [])]

        todo = by.get(NEEDS_TRACE, []) + by.get(CREATE_ON_ORIGIN, [])
        blocked = (receipt["conflicts"] + receipt["unattributed"]
                   + receipt["refused"] + receipt["unmeasured"])
        receipt["pending"] = [{"card": f["card"], "answer": f["answer"],
                               "added": sorted(f.get("added") or {}),
                               "verdict": f["verdict"]} for f in todo]

        if not is_enabled(env):
            receipt["status"] = DISABLED
            receipt["reason"] = (f"сторож выключен переменной {ENV_FLAG}; "
                                 f"недоставленного следа: {len(todo)}")
        elif not todo:
            if blocked:
                receipt["status"] = REFUSED
                receipt["reason"] = ("везти нечего, но НЕ ИЗМЕРЕНО/ОТКАЗАНО по "
                                     f"{len(blocked)} карточк(ам): "
                                     + "; ".join(f"{b['card']}: {b['reason']}" for b in blocked))
            else:
                receipt["status"] = IDLE
                sup = len(receipt["superseded"])
                prov = len(receipt["provenance"])
                receipt["reason"] = (f"весь след решений владельца на origin "
                                     f"({len(receipt['already_on_origin'])} карточк(и))"
                                     + (f"; вытеснено более поздним ответом: {sup}" if sup else "")
                                     + (f"; тот же выбор, разный провенанс: {prov}" if prov else ""))
        elif dry_run:
            receipt["status"] = UNCHECKED
            receipt["reason"] = (f"сухой прогон: доставить нужно {len(todo)} карточк(и) — "
                                 + ", ".join(f["card"] for f in todo))
        else:
            msg = build_message(todo)
            receipt["message"] = msg
            ok, detail = pusher(root, todo, msg)
            if ok and not blocked:
                receipt["status"] = DELIVERED
                receipt["commit"] = detail
                receipt["delivered"] = [f["card"] for f in todo]
                receipt["reason"] = f"след решения владельца на origin, коммит {detail}"
            elif ok:
                receipt["status"] = PARTIAL
                receipt["commit"] = detail
                receipt["delivered"] = [f["card"] for f in todo]
                receipt["reason"] = (f"уехало {len(todo)}, но по {len(blocked)} карточк(ам) "
                                     f"измерить/перенести не удалось: "
                                     + "; ".join(f"{b['card']}: {b['reason']}" for b in blocked))
            else:
                receipt["status"] = FAILED
                receipt["reason"] = f"доставка не удалась: {detail}"
    except Exception as e:  # noqa: BLE001 — «не измерено» честнее, чем падение сторожа
        receipt["status"] = UNCHECKED
        receipt["reason"] = f"сторож не измерен: {type(e).__name__}: {e}"

    if write_status:
        try:
            from spa_core.utils.atomic import atomic_save
            target = os.path.join(root, STATUS_REL)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            atomic_save(receipt, target)
        except Exception as e:  # noqa: BLE001 — квитанция не смеет уронить сторожа
            receipt["receipt_write_error"] = f"{type(e).__name__}: {e}"
    return receipt


def render(receipt: dict) -> str:
    """Одна строка для лога/шага 0-офис. Отказ виден без чтения JSON."""
    if not isinstance(receipt, dict) or not receipt:
        return "owner_answer_delivery: ⚠️ НЕ ИЗМЕРЕНО — квитанции нет"
    st = receipt.get("status")
    n_ok = len(receipt.get("already_on_origin") or [])
    pending = receipt.get("pending") or []
    tail = ""
    if receipt.get("unmeasured"):
        tail += f" · НЕ ИЗМЕРЕНО: {len(receipt['unmeasured'])}"
    if receipt.get("conflicts"):
        tail += f" · РАЗНЫЕ ОТВЕТЫ: {len(receipt['conflicts'])}"
    if receipt.get("superseded"):
        tail += f" · ВЫТЕСНЕНО: {len(receipt['superseded'])}"
    if receipt.get("provenance"):
        tail += f" · ПРОВЕНАНС: {len(receipt['provenance'])}"
    if receipt.get("unattributed"):
        tail += f" · БЕЗ АВТОРА: {len(receipt['unattributed'])}"
    # Чьё дерево сверено — часть вердикта, а не деталь: «весь след на origin»,
    # сказанное о worktree, читается как «ответы владельца в git» (замер 30.08).
    src = receipt.get("root_source")
    if src and src != ROOT_LIVE:
        tail += f" · дерево: {receipt.get('root')} ({src})"
    if st == DELIVERED:
        return (f"owner_answer_delivery: ✅ след решения владельца доставлен "
                f"({len(receipt.get('delivered') or [])}) → origin/main{tail}")
    if st == IDLE:
        return f"owner_answer_delivery: — весь след на origin ({n_ok} карточк(и)){tail}"
    return (f"owner_answer_delivery: ⚠️ {st} (недоставлено {len(pending)}){tail} — "
            f"{receipt.get('reason', '')}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=None,
                    help="дерево, о котором выносится вердикт; "
                         "по умолчанию — ЖИВОЕ дерево, а не каталог этого файла")
    ap.add_argument("--dry-run", action="store_true",
                    help="только измерить, ничего не отправлять")
    ap.add_argument("--show", action="store_true", help="показать последнюю квитанцию")
    ap.add_argument("--json", action="store_true", help="квитанция целиком в stdout")
    args = ap.parse_args(argv)

    if args.show:
        try:
            with open(os.path.join(resolve_root(args.root)[0], STATUS_REL), encoding="utf-8") as f:
                print(json.dumps(json.load(f), ensure_ascii=False, indent=2))
            return 0
        except OSError as e:  # noqa: BLE001
            print(f"квитанции нет: {e}")
            return 2

    r = run(root=args.root, dry_run=args.dry_run, write_status=not args.dry_run)
    if args.json:
        print(json.dumps({k: v for k, v in r.items() if k != "content"},
                         ensure_ascii=False, indent=2, default=str))
    print(render(r))
    return 0 if r["status"] in (DELIVERED, IDLE) else 1


if __name__ == "__main__":
    sys.exit(main())
