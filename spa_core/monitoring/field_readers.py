"""Сколько РАЗНЫХ читателей подпирают имя поля — одна копия правила.

Заказ **G114 п. 1** приказа владельца «Portfolio CIO» (хвост
[ADR-540](../../docs/decisions/ADR-540-a-pair-of-numbers-cannot-be-the-rule.md))
дословно:

> «**Третья ось у кандидата — ЧИСЛО РАЗНЫХ ЧИТАТЕЛЕЙ, а не число списков.**
> Население сегодня считает списки; `message×3` может означать три находки
> одного прибора и три разных подсистемы, и это разные свидетельства.»

Правило целиком — три строки, и ровно поэтому оно живёт отдельным модулем, а не
двумя копиями по месту применения. Копий уже было бы две: сосед
(``list_day_axis.tally``) считает читателей у СВОЕГО населения — имён, оказавшихся
осью дня, — и его замер 11.10 (``forward_date`` ×11 у ОДНОГО читателя против
``cycle_date`` ×11 у девяти) и есть то наблюдение, из которого заказ вырос. Но
население у соседа другое, и его число на вопрос о КАНДИДАТАХ переписи не
отвечает; вторая копия правила разошлась бы с первой молча — ровно тот класс,
который эта семья ловит у читателей.

## Три исхода, и третий не ноль (инв. #17)

* читатель НАЗВАН ⇒ считается один раз, сколько бы списков он ни дал;
* читатель НЕ НАЗВАН ⇒ **считается отдельным числом** (``nameless``), а не
  складывается в фантомного читателя и не отбрасывается молча. Отброшенный
  вклад занижал бы число читателей, и об этом не сказала бы ни одна строка:
  «читателей один» было бы неотличимо от «читателей один плюс сколько-то
  неназванных»;
* имени не дали вклада ВООБЩЕ ⇒ его в своде нет, и это не «читателей ноль»:
  ответ на такое имя даёт ``readers_of``, возвращая ``None``.

## Чего это НЕ доказывает

* **Разные читатели ≠ разные подсистемы.** Читатель здесь — питоний модуль; два
  модуля одной подсистемы считаются двумя, а один модуль, обслуживающий две
  подсистемы, — одним. Заказ говорит «три разных подсистемы», и этого числа
  здесь НЕ измеряется: измеряется число разных МОДУЛЕЙ, и подменять одно другим
  нельзя.
* **Число читателей — наблюдение ОДНОГО ответа**, как население и длина: оно
  меняется со скоростью кода, а не является обещанием писателя.
* Правила «много читателей ⇒ поле годно» здесь нет и быть не может: модуль
  только считает. Гейт по этой оси запрещён составом публичных имён у
  потребителя (``list_identity_census._NO_GATE_NAMES``).
"""
# LLM_FORBIDDEN
from __future__ import annotations

from typing import Dict, Iterable, Optional, Tuple

#: Как называется третий исход в своде. Строка пинится у потребителя, чтобы
#: мутант не переименовал её вместе с проверкой.
NAMELESS_KEY = "nameless"


def tally_readers(
        contributions: Iterable[Tuple[str, Optional[str]]]) -> Dict[str, dict]:
    """``(поле, читатель)`` → ``{поле: {"readers": [имена], "nameless": N}}``.

    Вход — последовательность ВКЛАДОВ, а не словарь: одно и то же поле приходит
    столько раз, сколько списков его подпёрли, и именно разница между «сколько
    вкладов» и «сколько разных читателей» есть предмет заказа. Сворачивать вход
    в словарь до вызова значило бы потерять её ещё до замера.

    Перечень читателей возвращается ОТСОРТИРОВАННЫМ: порядок словаря питона
    зависит от порядка вставки, и артефакт, печатающий его как есть, менялся бы
    побайтово от перестановки читателей при неизменном замере.
    """
    out: Dict[str, dict] = {}
    for field, reader in contributions:
        row = out.setdefault(str(field), {"readers": set(),
                                          NAMELESS_KEY: 0})
        # Пустое имя читателем НЕ считается: оно сложилось бы в одного
        # фантомного и завысило бы разброс. Но и не исчезает — его считает
        # третий исход.
        if reader:
            row["readers"].add(str(reader))
        else:
            row[NAMELESS_KEY] += 1
    return {field: {"readers": sorted(row["readers"]),
                    NAMELESS_KEY: row[NAMELESS_KEY]}
            for field, row in sorted(out.items())}


def readers_of(tally: Dict[str, dict], field: str) -> Optional[int]:
    """Число читателей у имени либо ``None`` — «не измерено», а не ноль.

    ``None`` возвращается в ДВУХ разных случаях, и оба суть отсутствие замера, а
    не наблюдение «читателей ноль»:

    * имени нет в своде вовсе — ему не пришло ни одного вклада;
    * у имени есть неназванные вклады — тогда число НАЗВАННЫХ читателей есть
      нижняя граница, и выдавать нижнюю границу за замер нельзя.

    Второй случай и есть причина, по которой третий исход считается, а не
    отбрасывается: без счётчика ``nameless`` эта функция не смогла бы отличить
    измеренное число от заниженного.
    """
    row = tally.get(str(field))
    if not isinstance(row, dict):
        return None
    readers = row.get("readers")
    if not isinstance(readers, list):
        return None
    if int(row.get(NAMELESS_KEY) or 0):
        return None
    return len(readers)
