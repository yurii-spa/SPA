def const_value(node: ast.AST) -> Optional[str]:
    """Нормализованный исходник значения — или ``None``, если оно не константно.

    Константным считается выражение без единого обращения наружу: ни вызова
    (кроме конструктора контейнера), ни имени, ни атрибута, ни подписки, ни
    f-строки, ни включения. `Path(__file__).resolve()` константой не является
    и сравнивать его с чужим `Path(...)` было бы сравнением ТЕКСТА, а не
    значения — отсюда корзина ``not_constant``, а не «различаются».
    """
    for sub in ast.walk(node):
        # Отдельной ветки на `ast.Call` здесь НЕТ, и это решение, а не пропуск:
        # у любого вызова функция есть либо имя, либо атрибут, либо лямбда — то
        # есть отвергается ветками ниже. Ветка на `Call` отвергала бы то же
        # самое на узел раньше, и батарея мутаций показала её выживающей:
        # неотличимая от умолчания проверка есть украшение, а не сторож.
        if isinstance(sub, ast.Name):
            if sub.id in _CONST_CTORS:
                continue
            return None
        if isinstance(sub, (ast.Attribute, ast.Subscript, ast.Lambda, ast.JoinedStr,
                            ast.ListComp, ast.SetComp, ast.DictComp, ast.GeneratorExp,
                            ast.Await, ast.Starred)):
            return None
    try:
        return ast.unparse(node)
    except Exception:  # noqa: BLE001 — ast.unparse на экзотике
        return None


def toplevel_constants(tree: ast.Module) -> Dict[str, Optional[str]]:
    """Имена верхнего уровня и их значения (``None`` — значение не константно).

    Только верхний уровень: константа внутри функции никому не видна и второй
    копией правила быть не может.
    """
    out: Dict[str, Optional[str]] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    out[target.id] = const_value(node.value)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) \
                and node.value is not None:
            out[node.target.id] = const_value(node.value)
    return out


def imported_modules(tree: ast.Module) -> set:
    """Полные имена модулей, которые файл ВВОЗИТ, включая форму `from pkg import mod`.

    Разбирать ввоз текстом нельзя: `from spa_core.backtesting.tier1 import
    monte_carlo` не содержит строки «spa_core.backtesting.tier1.monte_carlo»
    ни разу, и текстовое правило объявило бы такого сторожа НЕ достающим
    исполнителя — то есть выдумало бы находку ровно там, где сторож честно
    делегирует. Имя собирается из модуля и КАЖДОГО псевдонима: какой из них
    подмодуль, а какой — имя внутри модуля, по одному тексту не различить,
    поэтому в набор кладутся оба прочтения.
    """
    out: set = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                out.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if not node.module:
                continue
            out.add(node.module)
            for alias in node.names:
                out.add(f"{node.module}.{alias.name}")
    return out


def reaches(source: str, imported: set, module_rel: str) -> bool:
    """Достаёт ли сторож исполнителя ХОТЬ ОДНОЙ из четырёх дверей.

    Дверь опознаётся по тому, что исполнитель НАЗВАН, а не по форме зова:

    * ввоз — разбором AST (`imported_modules`), а не текстом;
    * загрузка по ПУТИ (`spec_from_file_location`, `SourceFileLoader`) — путь
      модуля стоит строковым литералом;
    * подпроцесс `python3 -m spa_core.x.y` — точечное имя стоит литералом;
    * `sys.path` + ввоз по короткому имени — тот же литерал.

    Проверять только `import` значило бы выдумать находку у теста, который
    честно зовёт исполнителя подпроцессом.
    """
    dotted = module_rel[:-3].replace("/", ".") if module_rel.endswith(".py") else module_rel
    if dotted in imported:
        return True
    return dotted in source or module_rel in source


def risk_policy_thresholds(root: Path) -> Dict[str, List[str]]:
    """Числовой порог RiskPolicy -> ВСЕ имена, под которыми он объявлен.

    Имён у одного числа бывает несколько, и называть первое попавшееся нельзя:
    замер 19.09 дал у ``0.05`` сразу три порога — `max_drawdown_stop`,
    `max_var_pct`, `min_cash_pct`. Первая редакция этой функции хранила одно
    имя и приписала бы `MIN_CASH` соседство со стоп-краном вместо буфера кэша,
    то есть соврала бы ровно тем способом, против которого написан весь прибор:
    равенство величины НЕ есть тождество смысла.

    Берутся и константы верхнего уровня, и умолчания полей (пороги живут
    полями датакласса `RiskConfig`, поэтому обходится ВЕСЬ модуль, а не
    `tree.body`). Только числа: порог есть величина, и строковая версия
    политики порогом не является — сверка по ней объявила бы предметом
    владельца каждую пару со значением ``'v1.0'``.

    Модуль не прочитан ⇒ ``NotMeasured``: молча решить, что совпадений с
    порогами нет, значило бы выдать «не измерено» за «чисто» и дать агенту
    право чинить то, что он чинить не вправе.
    """
    path = Path(root) / RISK_POLICY_MODULE
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        raise NotMeasured(
            f"пороги RiskPolicy не прочитаны ({RISK_POLICY_MODULE}): "
            f"{type(exc).__name__}: {exc}") from exc
    out: Dict[str, List[str]] = {}
    for node in ast.walk(tree):
        pairs: List[Tuple[str, ast.AST]] = []
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) \
                and node.value is not None:
            pairs.append((node.target.id, node.value))
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    pairs.append((target.id, node.value))
        for name, value_node in pairs:
            if name.startswith("_"):
                continue
            if not (isinstance(value_node, ast.Constant)
                    and isinstance(value_node.value, (int, float))
                    and not isinstance(value_node.value, bool)):
                continue
            text = const_value(value_node)
            if text is not None and name not in out.setdefault(text, []):
                out[text].append(name)
    return {value: sorted(names) for value, names in out.items()}


def subject_witness(text: str, module_rel: str) -> Optional[str]:
    """Называет ли ТЕКСТ файл `module_rel` — по имени модуля или по имени файла.

    Свидетель ОДНОСТОРОННИЙ и слабее двери из :func:`reaches`: упоминание
    исполнителя дверью к нему не является (ADR-417), но доказывает, что о
    чужой копии ЗНАЮТ. Ищется точечный хвост длиной от двух звеньев
    (``owner_queue.queue``) и имя файла (``baseanalytics_migration_summary.py``).

    Граница слева и справа обязательна: голое ``queue.py`` совпало бы внутри
    ``orchestrator_queue.py`` и выдумало бы свидетеля там, где назван СОСЕД.

    **У исполнителя из двух звеньев пути свидетель-хвост СОВПАДАЕТ с дверью**
    (``spa_core/e.py`` → ``spa_core.e``), и такая пара находкой быть перестаёт
    ещё в :func:`reaches` — до разбора форм. Свидетелем там остаётся только имя
    файла. Это не изъян: совпадение означает, что проводка уже есть.
    """
    if not module_rel.endswith(".py"):
        return None
    parts = module_rel[:-3].split("/")
    candidates = [f"{parts[-1]}.py"]
    candidates += [".".join(parts[-n:]) for n in range(2, len(parts) + 1)]
    for cand in candidates:
        if re.search(r"(?<![\w.])" + re.escape(cand) + r"(?![\w])", text):
            return cand
    return None


def artifact_literals(tree: ast.Module) -> set:
    """Имена файлов-артефактов, названные в файле строковым литералом.

    Берётся БАЗОВОЕ имя, а не путь: одна сторона пишет
    ``os.path.join(ROOT, "data", "paper_evidence.json")``, другая —
    ``"data/paper_evidence.json"``, и сравнение путей объявило бы их разными
    предметами там, где предмет один. Голый хвост (``".json"``) артефактом
    не является и отбрасывается — иначе предметом стала бы буква.
    """
    out: set = set()
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Constant) and isinstance(node.value, str)):
            continue
        value = node.value
        if not value.lower().endswith(_ARTIFACT_SUFFIXES):
            continue
        name = value.replace("\\", "/").rsplit("/", 1)[-1]
        if name.startswith("."):        # сам хвост, имени файла нет
            continue
        out.add(name)
    return out


def key_literals(tree: ast.Module) -> set:
    """Строковые литералы, использованные как КЛЮЧ отображения.

    Три формы, и третья существенна: ``assert "adapters" in data`` есть
    обращение к ключу ровно в той же мере, что ``data["adapters"]``, и
    пропустить её значило бы не увидеть половину сторожей этого репозитория.

    Литерал, стоящий где попало (в сообщении об ошибке, в докстринге), ключом
    НЕ считается: свидетель обязан быть поведенческим, а не текстовым, иначе
    он вырождается в правило имени, уже измеренное как негодное (ADR-417).
    """
    out: set = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Subscript) and isinstance(node.slice, ast.Constant) \
                and isinstance(node.slice.value, str):
            out.add(node.slice.value)
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) \
                and node.func.attr in _KEY_METHODS and node.args \
                and isinstance(node.args[0], ast.Constant) \
                and isinstance(node.args[0].value, str):
            out.add(node.args[0].value)
        elif isinstance(node, ast.Compare) and len(node.ops) == 1 \
                and isinstance(node.ops[0], (ast.In, ast.NotIn)) \
                and isinstance(node.left, ast.Constant) \
                and isinstance(node.left.value, str):
            out.add(node.left.value)
    return out


def behaviour_witness(guard_text: str, executor_text: str) -> Tuple[Optional[dict],
                                                                    Optional[str]]:
    """ВТОРОЙ свидетель общего предмета — поведенческий (заказ G43, п. 1).

    Возвращает ``(свидетель | None, причина-не-измерено | None)``.

    Первый свидетель (:func:`subject_witness`) — ТЕКСТОВЫЙ: одна сторона
    называет другую. Он молчит о паре, где обе стороны честно работают с одним
    предметом и просто не знают друг о друге, — а это ровно случай
    ``tests/test_preflight.py`` × ``scripts/preflight_day1.py``: обе читают
    ``data/paper_evidence.json`` и обе спрашивают у него ключ ``start_date``.
    Заказ G43 потребовал поднять такие пары из «не измерено».

    Свидетельством считается пересечение СРАЗУ ПО ДВУМ осям: общий артефакт И
    общий ключ. Одной оси мало и это не осторожность, а замер: имя ``data/``
    стои́т у сотен файлов, и свидетель по одному артефакту объявил бы общим
    предметом любую пару, читающую репозиторий. Две оси оставляют предмет,
    у которого есть и носитель, и поле в нём.

    **Обратная сторона названа.** Пересечение НЕ доказывает, что ключ читается
    ИМЕННО из этого артефакта: статически связать их нечем, и прибор такой
    связи не выдумывает. Свидетель, как и первый, ОДНОСТОРОННИЙ — его наличие
    доказывает общий предмет, его отсутствие не доказывает ничего, и
    ``subject_unproven`` остаётся достижимым исходом (замер: из восьми пар
    свидетель нашёлся у двух).
    """
    try:
        guard_tree = ast.parse(guard_text)
        executor_tree = ast.parse(executor_text)
    except SyntaxError as exc:
        return None, f"сторона не разобрана: {type(exc).__name__}: {exc}"
    artifacts = sorted(artifact_literals(guard_tree) & artifact_literals(executor_tree))
    keys = sorted(key_literals(guard_tree) & key_literals(executor_tree))
    if not artifacts or not keys:
        return None, None
    return {"artifacts": artifacts, "keys": keys,
            "artifact": artifacts[0], "key": keys[0]}, None


def constant_is_loaded(tree: ast.Module, name: str) -> bool:
    """Читается ли имя хоть где-нибудь в файле (загрузка, не присваивание).

    Вопрос СТАТИЧЕСКИЙ, и отвечать на него прогоном нельзя: нечувствительность
    вердикта к значению — другое утверждение. Замер 19.09 разделил их ценой
    одной ошибки: пять пар были названы «константа не читается» по прогону, а
    читаются все пять (`random.Random(SEED)`, `for d in SCAN_DIRS`).

    Имя, которое НЕ читается, правилом на стороне сторожа не является вовсе —
    и это единственный честный способ снять пару с учёта.
    """
    for node in ast.walk(tree):
        if isinstance(node, ast.Name) and node.id == name \
                and isinstance(node.ctx, ast.Load):
            return True
    return False


def probe_key(row: dict) -> str:
    """Координата пары в журнале зонда. Значение входит в ключ НАМЕРЕННО."""
    return f"{row['guard']}|{row['executor']}|{row['name']}"


def load_probe_ledger(path: Path) -> Tuple[Dict[str, dict], Optional[str]]:
    """Журнал зонда независимости: ``(записи по координате, причина-нет | None)``.

    Перепись зонд не зовёт. Журнал устаревает САМ и устаревает в безопасную
    сторону: запись годится, только если совпали и значение находки, и sha
    ОБЕИХ сторон (проверяет :func:`_probe_verdict`). Любая правка любой из
    сторон отменяет вердикт зонда, и пара возвращается в ``subject_unproven``
    — то есть на учёт, а не с учёта. Расписания зонду поэтому не нужно:
    протухший журнал не молчит, он перестаёт отвечать.
    """
    try:
        import json
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except OSError:
        return {}, f"журнала зонда нет ({path.name})"
    except Exception as exc:  # noqa: BLE001
        return {}, f"журнал зонда не прочитан: {type(exc).__name__}: {exc}"
    entries = doc.get("entries")
    if not isinstance(entries, list):
        return {}, "журнал зонда без перечня записей"
    out: Dict[str, dict] = {}
    for entry in entries:
        if isinstance(entry, dict) and isinstance(entry.get("key"), str):
            out[entry["key"]] = entry
    return out, None


def _sha256(path: Path) -> Optional[str]:
    import hashlib
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def right_to_fix(value: object, *, thresholds: Dict[str, List[str]],
                 constitution: Dict[str, List[str]],
                 constitution_unread: Optional[str]) -> Tuple[
                     Optional[str], Optional[str], Dict[str, object]]:
    """ПРАВО чинить величину — одно правило на все три оси (заказ G54 п. 1).

    Возвращает ``(форма, основание, поля)``; ``(None, None, {})`` означает
    «ни одна объявленная поверхность решения этой величины не объявляла» —
    и только тогда ось вправе спрашивать о СПОСОБЕ починки.

    **Почему функция, а не ветка на месте.** До заказа G54 это правило жило
    в ДВУХ видах: первая и вторая оси знали одну поверхность решения (пороги
    `spa_core/risk/policy.py`), третья — две (плюс витрину порогов сайта).
    Прибор, который меряет вторые копии правил, держал вторую копию
    собственного правила — и ровно на ней публиковал «агенту никто не
    возражает» у 14 пар, чья величина объявлена витриной. Свести копии в одну
    здесь можно и должно: обе стороны — этот же модуль, право на правку у
    агента, и `single_copy_by_import` есть та самая форма починки, которую
    прибор прописывает другим.

    **Порядок ветвей существен.** Сначала пороги RiskPolicy: они остаются
    предметом №1 границы ADR-285 и старше витрины. Совпадение с ОБЕИМИ
    поверхностями не теряется — витрина называется полем
    ``also_constitution_fields``, потому что «число объявлено дважды» есть
    отдельный факт, а не оттенок первого.

    Витрина НЕ прочитана ⇒ :data:`REMEDY_RIGHT_UNMEASURED`, а не «совпадений
    нет» (инв. #17). Исключение ровно одно и оно не подмена: у величины,
    равной порогу RiskPolicy, право чинить УЖЕ установлено — вторая
    поверхность могла бы добавить причину, но отнять право не может.
    """
    key = str(value)
    owner_names = thresholds.get(key) or []
    shelf_names = constitution.get(key) or []
    if owner_names:
        named = ", ".join(f"`{n}`" for n in owner_names)
        evidence = (
            f"значение равно порог{'ам' if len(owner_names) > 1 else 'у'} "
            f"RiskPolicy {named} ({RISK_POLICY_MODULE}) — предмет №1 границы "
            f"ADR-285; какой из них ТОТ САМЫЙ, прибор не решает")
        extra: Dict[str, object] = {"owner_threshold_names": list(owner_names)}
        if shelf_names:
            extra["also_constitution_fields"] = list(shelf_names)
            evidence += (
                "; то же число объявлено и витриной порогов сайта пол"
                + ("ями " if len(shelf_names) > 1 else "ем ")
                + ", ".join(f"`{n}`" for n in shelf_names)
                + " — поверхностей решения ДВЕ, и умолчать о второй значило бы "
                  "выдать первую за полный ответ")
        elif constitution_unread is not None:
            extra["constitution_unread"] = constitution_unread
        return REMEDY_OWNER, evidence, extra
    if constitution_unread is not None:
        return REMEDY_RIGHT_UNMEASURED, constitution_unread, {}
    if shelf_names:
        return (REMEDY_CONSTITUTION,
                "то же число объявлено витриной порогов сайта пол"
                + ("ями " if len(shelf_names) > 1 else "ем ")
                + ", ".join(f"`{n}`" for n in shelf_names)
                + f" ({CONSTITUTION_FILE}) — род «решение», меняется только "
                  "ADR-ом; сводить копии ввозом агент не вправе",
                {"constitution_fields": list(shelf_names)})
    return None, None, {}


def is_numeric_value(value: object) -> bool:
    """Может ли витрина порогов вообще говорить об этой величине.

    Витрина и пороги RiskPolicy держат ТОЛЬКО числа — обе по одной причине:
    порог есть величина, и сверка по строке объявила бы предметом владельца
    каждую пару со значением ``'v1.0'``. Значит у пары со строковым значением
    ответ витрины пуст ПО ПОСТРОЕНИЮ, и складывать такие пары в знаменатель
    сдвига значило бы разбавлять замер вопросом, который никому не задавался.
    """
    try:
        float(str(value))
    except (TypeError, ValueError):
        return False
    return True


def classify_remedy(row: dict, *, guard_text: Optional[str],
                    executor_text: Optional[str],
                    thresholds: Dict[str, List[str]],
                    constitution: Dict[str, List[str]],
                    constitution_unread: Optional[str],
                    probe: Optional[dict] = None,
                    guard_loads: Optional[bool] = None) -> dict:
    """Форма починки одной находки (заказы G42 п. 1 и G43). Поля строки.

    Порядок ветвей — не стилистика: право чинить спрашивается раньше способа
    чинить. Пара, чью величину объявила поверхность решения, уходит владельцу
    ДО того, как прибор вообще посмотрит на свидетеля.

    **Поверхностей решения ДВЕ** (с заказа G54 п. 1): пороги RiskPolicy и
    витрина порогов сайта. Правило одно на три оси — :func:`right_to_fix`; до
    этого заказа здесь спрашивалась только первая, и разница была не
    умозрительной: на соседней оси 14 пар публиковались как «никто не
    возражает». Способ починки считается В ЛЮБОМ случае, и когда право
    перебивает способ, прежняя форма остаётся в строке полем
    ``remedy_without_shelf`` — сдвиг обязан быть виден, а не получен даром.

    Дальше порядок такой: **имя не читается · текстовый свидетель ·
    поведенческий свидетель · не доказан**. Первым идёт статический факт «имя
    у сторожа не читается ни разу», потому что он ОДИН снимает пару с учёта:
    правила на стороне сторожа нет вовсе, и спрашивать о свидетелях общего
    предмета уже не о чем.

    **Вердикты зонда в этом порядке НЕ участвуют** и кладутся полями (`drift`,
    `verdict_teeth`). Причина — замер, а не вкус: зонд отвечает на вопрос о
    ВРЕДЕ («поймают ли расхождение»), а не о предмете, и попытка прочесть его
    как ответ о предмете уже один раз сняла бы с учёта пять живых пар
    (ADR-419).
    """
    right, right_evidence, right_extra = right_to_fix(
        row.get("value"), thresholds=thresholds, constitution=constitution,
        constitution_unread=constitution_unread)
    method = _remedy_method(row, guard_text=guard_text,
                            executor_text=executor_text, probe=probe,
                            guard_loads=guard_loads)
    if right is None:
        return method
    out = {"remedy": right, "remedy_evidence": right_evidence, **right_extra}
    # Поля зонда — про ВРЕД, а не про предмет, и правом чинить не отменяются:
    # потерять `drift` при переходе к форме владельца значило бы погасить
    # наблюдение решением о том, кто вправе править.
    for key in ("drift", "drift_evidence", "verdict_teeth"):
        if key in method:
            out[key] = method[key]
    if right in _SHELF_REMEDIES and method["remedy"] != right:
        # СДВИГ формы починки, снятый строкой, а не пересказом (заказ G54 п. 1):
        # чем эта пара была, пока витрину не спрашивали. Сравнение идёт со
        # СТАРЫМ правилом, а не с «способом»: пара, равная порогу RiskPolicy,
        # была формой владельца и до заказа, и записывать ей сдвиг значило бы
        # приписать витрине чужую работу.
        out["remedy_without_shelf"] = method["remedy"]
    return out


def _remedy_method(row: dict, *, guard_text: Optional[str],
                   executor_text: Optional[str],
                   probe: Optional[dict] = None,
                   guard_loads: Optional[bool] = None) -> dict:
    """СПОСОБ починки — отдельно от ПРАВА (заказ G54 п. 1).

    Разделены они не ради опрятности: способ считается ВСЕГДА, в том числе у
    пары, которую право чинить уже отправило владельцу, — иначе сдвиг формы
    («чем пара была до вопроса витрине») пришлось бы домысливать, а заказ
    требовал его ИЗМЕРИТЬ.
    """
    if guard_text is None or executor_text is None:
        side = "guard" if guard_text is None else "executor"
        return {"remedy": REMEDY_UNREADABLE,
                "remedy_evidence": f"текст стороны `{side}` не прочитан повторно"}

    text_witness = subject_witness(guard_text, row["executor"])
    text_side = "guard"
    if text_witness is None:
        text_witness = subject_witness(executor_text, row["guard"])
        text_side = "executor"
    behaviour, behaviour_unmeasured = behaviour_witness(guard_text, executor_text)

    # Зонд НЕ снимает пару с учёта — ни одним своим вердиктом, и это поправка,
    # снятая замером. Заказ G43 предлагал считать «вердикт не изменился»
    # независимостью; замер показал, что так выглядит ВРЕД (расхождение не
    # будет поймано), а первая редакция этого прибора назвала тем же именем
    # нечувствительность вердикта и сняла бы с учёта пять пар, у которых
    # константа читается. Поэтому вклад зонда — ПОЛЕ строки (`drift`,
    # `verdict_teeth`), а снимает пару СТАТИЧЕСКИЙ факт: имя не читается.
    extra: Dict[str, object] = {}
    if probe is not None:
        verdict = probe.get("verdict")
        detail = probe.get("evidence") or "основание зонда не записано"
        if verdict in (PROBE_DRIFT_SILENT, PROBE_DRIFT_LOUD):
            extra = {"drift": verdict, "drift_evidence": detail}
        elif verdict == PROBE_INSENSITIVE:
            extra = {"verdict_teeth": "none", "drift_evidence": detail}

    if guard_loads is False:
        return {"remedy": REMEDY_UNUSED,
                "remedy_evidence": (
                    f"имя `{row['name']}` в стороже НЕ ЧИТАЕТСЯ ни разу "
                    f"(статический разбор) ⇒ правила на его стороне нет, и двух "
                    f"копий одного правила тоже нет"), **extra}

    if text_witness is not None:
        who = "сторож называет исполнителя" if text_side == "guard" \
            else "исполнитель называет сторожа"
        return {"remedy": REMEDY_IMPORT, "witness_side": text_side,
                "remedy_evidence": f"{who}: `{text_witness}`", **extra}
    if behaviour is not None:
        # Представитель НЕ единственный: общих артефактов и ключей бывает
        # много, и называть один, умолчав о числе, значило бы выдать пример
        # за весь свидетельский состав.
        return {"remedy": REMEDY_BEHAVIOUR, "witness_side": "behaviour",
                "behaviour_witness": behaviour,
                "remedy_evidence": (
                    f"обе стороны читают {len(behaviour['artifacts'])} общих "
                    f"артефакт(ов) и спрашивают {len(behaviour['keys'])} общих "
                    f"ключ(ей) — напр. `{behaviour['artifact']}` + "
                    f"`{behaviour['key']}`; общий предмет ДОКАЗАН поведением, "
                    f"дверь к исполнителю не проложена"), **extra}
    evidence = ("ни одна сторона не называет другую и общего артефакта с общим "
                "ключом у них нет — общий предмет НЕ ДОКАЗАН (это не «совпадение»)")
    if behaviour_unmeasured is not None:
        evidence = (f"текстового свидетеля нет; поведенческий НЕ ИЗМЕРЕН "
                    f"({behaviour_unmeasured})")
    return {"remedy": REMEDY_UNPROVEN, "remedy_evidence": evidence, **extra}


def _guard_files(root: Path) -> List[Path]:
    seen: set = set()
    out: List[Path] = []
    for sub in GUARD_DIRS:
        base = root / sub
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("test_*.py")):
            if path in seen:
                continue
            seen.add(path)
            out.append(path)
    if not out:
        raise NotMeasured(f"в дереве {root} не нашлось ни одного файла-сторожа")
    return out


def _executor_files(root: Path) -> List[Path]:
    out: List[Path] = []
    for sub in EXECUTOR_DIRS:
        base = root / sub
        if not base.is_dir():
            raise NotMeasured(f"каталог исполнителей не прочитан: {base}")
        for path in sorted(base.rglob("*.py")):
            rel = path.relative_to(root).as_posix()
            if "/tests/" in f"/{rel}" or path.name.startswith("test_"):
                continue
            if any(rel.startswith(skip) for skip in _EXECUTOR_SKIP):
                continue
            if rel == PRODUCER:      # сам прибор исполнителем правил не является
                continue
            out.append(path)
    if not out:
        raise NotMeasured(f"в дереве {root} не нашлось ни одного файла-исполнителя")
    return out


def _probe_verdict(root: Path, row: dict, ledger: Dict[str, dict],
                   stats: dict) -> Optional[dict]:
    """Запись зонда для пары — ТОЛЬКО если она описывает СЕГОДНЯШНИЕ стороны.

    Годность проверяется тремя равенствами: значение находки и sha обоих
    файлов. Ошибиться эта проверка может лишь в одну сторону — объявить
    годную запись протухшей, — и пара тогда возвращается на учёт как
    ``subject_unproven``. Обратная ошибка (принять запись о ДРУГОМ дереве за
    ответ о сегодняшнем) закрыта: sha меняется от любой правки.
    """
    entry = ledger.get(probe_key(row))
    if entry is None:
        stats["missing"] += 1
        return None
    if entry.get("value") != row.get("value"):
        stats["stale"] += 1
        return None
    for side in ("guard", "executor"):
        if entry.get(f"{side}_sha") != _sha256(root / row[side]):
            stats["stale"] += 1
            return None
    if entry.get("verdict") not in _PROBE_VERDICTS:
        # Зонд честно не измерил пару — это НЕ вердикт и подставлять его
        # вместо вердикта нельзя.
        stats["missing"] += 1
        return None
    stats["fresh"] += 1
    return entry


def peer_pairs(declared: Dict[str, List[Tuple[str, Optional[str]]]], *,
               source_of, imports_of,
               thresholds: Dict[str, List[str]],
               constitution: Dict[str, List[str]],
               constitution_unread: Optional[str]) -> Tuple[List[dict], dict]:
    """Копия правила между двумя ИСПОЛНИТЕЛЯМИ (заказ G52 п. 1).

    ## Почему сужения ровно эти — это замер, а не вкус

    Перенести сюда правило соседней оси дословно нельзя: там пару удерживает
    АСИММЕТРИЯ сторон (сторож утверждает правило, исполнитель его применяет), а
    здесь стороны однородны, и одного имени с равным значением мало настолько
    же, насколько мало было его там. Замер на дереве ``072c418d3``:

    | сужение | пар |
    |---|---|
    | одно имя у двух исполнителей | **263 191** |
    | + имя объявлено РОВНО ДВУМЯ исполнителями | 615 имён |
    | + значение константно и равно | 225 |
    | + ни один не достаёт другого ни одной из четырёх дверей | **189** |

    Первая строка и есть соглашение об именовании: ``LOG_CAP`` объявлен
    столькими модулями, что пар по нему одному 14 028. Отсюда сужение №1 —
    ТОЧНЫЙ аналог правила «исполнитель у имени ровно один» соседней оси: имя,
    объявленное тремя и более исполнителями, одного правила не называет, и это
    своя корзина (``peer_many_executors``), а не находка и не «сошлось».

    ## Приватное имя здесь В НАСЕЛЕНИИ, и асимметрия названа

    Соседняя ось выбрасывает ``_`` -имена с основанием «приватное имя правилом
    наружу не является»: сторож чужое ``_X`` прочитать не может, значит парой
    одного правила они быть не могут. **Сюда это основание не переносится.**
    Два исполнителя, каждый со своим ``_T1_CAP = 0.4``, держат ровно две копии
    одного порога — невозможность прочитать чужое имя делает копию НЕИЗБЕЖНОЙ,
    а не мнимой. Меняется только форма починки: свести к ввозу без
    переименования нельзя. Числа поэтому печатаются врозь (замер: 46 приватных
    и 143 публичных), чтобы разницу правил было видно, а не выводить.

    ## Право чинить спрашивается первым

    Тот же порядок, что у соседней оси (заказ G42 п. 1): величина, равная
    ЧИСЛОВОМУ порогу RiskPolicy, есть предмет №1 границы ADR-285, и агент такую
    пару не чинит. Замер: **23** из 189, среди них ``MIN_ELIGIBLE_APY = 1.0`` и
    ``MAX_ELIGIBLE_APY = 30.0`` у двух модулей money-path. Сверка одностороння
    НАМЕРЕННО и ошибается в сторону «спросить»: равенство числа не есть
    тождество смысла (``SENTINEL = 0.0`` рядом с ``days_held`` — совпадение).

    ## Третий исход различим

    Исходник стороны не перечитан ⇒ вопрос о двери НЕ ИЗМЕРЕН
    (``peer_door_unmeasured``), а не «двери нет»: молчаливое «дверь закрыта»
    превратило бы нечитаемый файл в находку.
    """
    counts = {cls: 0 for cls in _PEER_CLASSES}
    rows: List[dict] = []
    for name, sides in declared.items():
        if len(sides) < 2:
            continue
        if len(sides) > 2:
            counts[CLASS_PEER_MANY] += 1
            continue
        (rel_a, val_a), (rel_b, val_b) = sides
        if val_a is None or val_b is None:
            counts[CLASS_PEER_NOT_CONSTANT] += 1
            continue
        if val_a != val_b:
            counts[CLASS_PEER_VALUE_DIFFERS] += 1
            continue
        src_a, src_b = source_of(rel_a), source_of(rel_b)
        if src_a is None or src_b is None:
            counts[CLASS_PEER_UNMEASURED] += 1
            rows.append({"verdict": CLASS_PEER_UNMEASURED, "name": name,
                         "value": val_a, "left": rel_a, "right": rel_b,
                         "reason": "исходник стороны не перечитан — вопрос о двери не измерен"})
            continue
        if (reaches(src_a, imports_of(rel_a), rel_b)
                or reaches(src_b, imports_of(rel_b), rel_a)):
            counts[CLASS_PEER_DELEGATES] += 1
            continue
        counts[CLASS_PEER_TWO_COPIES] += 1
        # Способ починки эта ось не разбирает вовсе, поэтому её «до витрины»
        # есть ровно одна форма — `subject_unproven`. Право чинить
        # спрашивается ТОЙ ЖЕ функцией, что и на двух других осях (G54 п. 1).
        right, right_evidence, right_extra = right_to_fix(
            val_a, thresholds=thresholds, constitution=constitution,
            constitution_unread=constitution_unread)
        method_evidence = (
            "ни одна сторона не достаёт другую — копия своя у обеих; "
            "общего происхождения значения прибор не доказывает")
        row = {
            "verdict": CLASS_PEER_TWO_COPIES,
            "name": name,
            "value": val_a,
            "left": rel_a,
            "right": rel_b,
            "private_name": name.startswith("_"),
            "remedy": right or REMEDY_UNPROVEN,
            "remedy_evidence": right_evidence or method_evidence,
            **right_extra,
        }
        if right in _SHELF_REMEDIES:
            row["remedy_without_shelf"] = REMEDY_UNPROVEN
        rows.append(row)
    rows.sort(key=lambda r: (r["left"], r["right"], r["name"]))
    return rows, counts


def constitution_values(root: Path) -> Tuple[Dict[str, List[str]], Optional[str]]:
    """Числа витрины порогов сайта -> ВСЕ поля, под которыми число объявлено.

    Возвращает ``(значения, причина_не_прочитано)``. Витрина отсутствует ⇒
    ПРИЧИНА, а не пустой словарь: пустой словарь сказал бы «совпадений нет», то
    есть выдал бы «не измерено» за «чинить можно». Отказом всей переписи это
    НЕ является намеренно — витрина лежит под ``landing/`` и в синтетическом
    дереве её может не быть по построению, в отличие от `spa_core/risk/policy.py`,
    без которого не измеряется само население.

    Берутся только ЧИСЛА (как и у порогов RiskPolicy): строковая метка витрины
    порогом не является, и сверка по ней объявила бы предметом владельца каждую
    пару со значением ``'v1.0'``.
    """
    path = Path(root) / CONSTITUTION_FILE
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        return {}, (f"витрина порогов не прочитана ({CONSTITUTION_FILE}): "
                    f"{type(exc).__name__}: {exc}")
    out: Dict[str, List[str]] = {}

    def walk(node, path_parts: Tuple[str, ...]) -> None:
        if isinstance(node, dict):
            for key, value in node.items():
                walk(value, path_parts + (str(key),))
        elif isinstance(node, list):
            for i, value in enumerate(node):
                walk(value, path_parts + (f"[{i}]",))
        elif isinstance(node, (int, float)) and not isinstance(node, bool):
            field = ".".join(path_parts)
            for text in {repr(float(node)), repr(node)}:
                if field not in out.setdefault(text, []):
                    out[text].append(field)

    walk(doc, ())
    return {value: sorted(names) for value, names in out.items()}, None


def axes_intersection(rows: List[dict], peer_rows: List[dict],
                      declared: Dict[str, List[Tuple[str, Optional[str]]]]) -> dict:
    """Пересечение населений двух осей ПО ИМЕНИ (заказ **G53, п. 1**).

    Заказ спросил ЧИСЛОМ, у скольких имён обе оси говорят одновременно: если
    такое имя есть, копий у правила три, а не две. Число здесь ИЗМЕРЯЕТСЯ, а
    затем отдельно измеряется, ПОЧЕМУ оно такое — и это разные вопросы.

    **Ноль сам по себе ответом не является.** Находка первой оси требует у
    имени РОВНО ОДНОГО исполнителя, находка второй — РОВНО ДВУХ. Условия
    несовместимы, поэтому пересечение пусто при любом дереве, включая дерево, в
    котором три копии есть на самом деле. Чтобы «пусто» нельзя было прочесть
    как «таких правил нет», вердикт различает три исхода, а основание
    печатается ЧИСЛАМИ: гистограммы числа исполнителей у имён обеих осей.
    Ключи гистограмм не пересекаются ⇒ ``EMPTY_BY_CONSTRUCTION``; пересекаются,
    а имён общих всё равно нет ⇒ ``EMPTY_MEASURED`` (тогда ноль — свидетельство).

    **Четвёртый исход найден собственным тестом 20.09** и первой редакции этой
    функции стоил бы неправды: если одна из осей пуста, пересекать НЕЧЕГО, и
    гистограммы «не пересекаются» тривиально. Первая редакция объявила бы такой
    ноль структурным, то есть приписала бы устройству прибора свойство дерева.
    Отсюда ``EMPTY_NOTHING_TO_INTERSECT`` с обоими числами в основании.

    Ровно эту форму ответа («прибор молчит о том, чего не видит по построению»)
    разобрал ADR-430 на соседней паре; повторять её молча было бы не ответом, а
    вторым экземпляром той же ошибки.
    """
    axis_one = sorted({r["name"] for r in rows
                       if r.get("verdict") in _FINDING_CLASSES})
    axis_two = sorted({r["name"] for r in peer_rows
                       if r.get("verdict") == CLASS_PEER_TWO_COPIES})

    def histogram(names: List[str]) -> Dict[str, int]:
        out: Dict[str, int] = {}
        for name in names:
            key = str(len(declared.get(name) or []))
            out[key] = out.get(key, 0) + 1
        return out

    hist_one, hist_two = histogram(axis_one), histogram(axis_two)
    shared = sorted(set(axis_one) & set(axis_two))
    if shared:
        verdict = INTERSECTION_NON_EMPTY
    elif not axis_one or not axis_two:
        # Пустая сторона делает пересечение пустым сама по себе, и объявить
        # этот ноль структурным значило бы приписать устройству прибора то,
        # что есть свойство ДЕРЕВА.
        verdict = INTERSECTION_EMPTY_NOTHING_TO_INTERSECT
    elif set(hist_one) & set(hist_two):
        verdict = INTERSECTION_EMPTY_MEASURED
    else:
        verdict = INTERSECTION_EMPTY_BY_CONSTRUCTION
    return {
        "verdict": verdict,
        "names": shared,
        "count": len(shared),
        "axis_one_names": len(axis_one),
        "axis_two_names": len(axis_two),
        "executors_per_name": {"axis_one": hist_one, "axis_two": hist_two},
        "reason": (
            "находка первой оси требует РОВНО ОДНОГО исполнителя, второй — "
            "РОВНО ДВУХ; гистограммы числа исполнителей не пересекаются, "
            "значит ноль здесь СТРУКТУРНЫЙ и свидетельством не является"
            if verdict == INTERSECTION_EMPTY_BY_CONSTRUCTION else
            f"пересекать было НЕЧЕГО: находок у первой оси {len(axis_one)}, у "
            f"второй {len(axis_two)} — ноль пришёл от пустой стороны, а не от "
            f"устройства осей"
            if verdict == INTERSECTION_EMPTY_NOTHING_TO_INTERSECT else
            "число исполнителей у имён обеих осей совпадает хотя бы на одном "
            "значении — пустое пересечение здесь ИЗМЕРЕНО, а не предрешено"
            if verdict == INTERSECTION_EMPTY_MEASURED else
            "имена, о которых говорят ОБЕ оси: у правила три копии, а не две"),
    }


def triple_name_count(rows: List[dict]) -> int:
    """Сколько ИМЁН у находок третьей оси.

    Отдельная функция, а не выражение на месте: строка «N пар на M имён» —
    главное число оси, а строка `triple_door_unmeasured` именем НАХОДКИ не
    является. Правило «что здесь считается именем» обязано быть одно и
    проверяемое тестом: замер 20.09 дал 18 пар на ОДНОМ имени, и спутать их
    значило бы соврать масштабом в восемнадцать раз.
    """
    return len({r["name"] for r in rows if r.get("verdict") == CLASS_TRIPLE})


def triple_copies(peer_rows: List[dict],
                  guard_declared: Dict[str, List[Tuple[str, Optional[str]]]],
                  *, source_of, imports_of,
                  thresholds: Dict[str, List[str]],
                  constitution: Dict[str, List[str]],
                  constitution_unread: Optional[str]) -> Tuple[List[dict], dict]:
    """ТРИ копии одного правила: сторож × два исполнителя (заказ **G53, п. 1**).

    Координата, которой у пересечения осей нет и быть не может (см.
    :func:`axes_intersection`): имя, объявленное сторожем И ровно двумя
    исполнителями, значение у всех трёх сторон равно, а сторож не достаёт НИ
    ОДНОГО из исполнителей ни одной из четырёх дверей.

    ## Почему сторону-сторожа мало просто «добавить» к паре исполнителей

    Сторож, который достаёт ОДНОГО из двух исполнителей, третьей копии не
    держит — у него копия одна, чужая, и правка доедет. Такой случай кладётся в
    свою корзину (``triple_door_to_one``), а не в находку: смешать его с
    находкой значило бы посчитать копией ввоз.

    ## Равное имя при РАЗНОМ значении находкой не является

    Замер 20.09 даёт такую пару ровно одну: ``SILENT`` у сторожа значит
    ``'pendle'``, а у двух исполнителей — литерал ``'SILENT'``. Это соглашение
    об именовании, а не разошедшиеся копии, и объявить его расхождением было бы
    выдумкой той же природы, что объявить совпадение копией. Корзина своя
    (``triple_value_differs``), находкой не считается.

    ## Право чинить спрашивается ПЕРВЫМ и у ДВУХ поверхностей решения

    Порядок тот же, что у соседних осей (заказ G42 п. 1), но поверхностей здесь
    две: пороги RiskPolicy и витрина порогов сайта (``CONSTITUTION_FILE``).
    Вторая добавлена замером, а не для полноты: единственная находка этой оси —
    ``CAPITAL = 100000.0``, и то же число объявлено витриной полем
    ``start_capital_usd``, то есть это РЕШЕНИЕ, меняемое ADR-ом
    (`.claude/rules/site-numbers.md`). Починить его «ввозом» агент не вправе.

    Витрина не прочитана ⇒ ``REMEDY_RIGHT_UNMEASURED``, а не «совпадений нет».
    """
    counts = {cls: 0 for cls in _TRIPLE_CLASSES}
    rows: List[dict] = []
    for peer in peer_rows:
        if peer.get("verdict") != CLASS_PEER_TWO_COPIES:
            continue
        name = peer["name"]
        for guard_rel, guard_value in guard_declared.get(name, []):
            if guard_value is None:
                counts[CLASS_TRIPLE_NOT_CONSTANT] += 1
                continue
            if guard_value != peer["value"]:
                counts[CLASS_TRIPLE_VALUE_DIFFERS] += 1
                continue
            source = source_of(guard_rel)
            if source is None:
                # Молчаливое «дверь закрыта» превратило бы нечитаемый файл в
                # находку — та же подмена, что у соседней оси.
                counts[CLASS_TRIPLE_UNMEASURED] += 1
                rows.append({
                    "verdict": CLASS_TRIPLE_UNMEASURED, "name": name,
                    "value": guard_value, "guard": guard_rel,
                    "left": peer["left"], "right": peer["right"],
                    "reason": "текст сторожа не перечитан — вопрос о двери не измерен"})
                continue
            imports = imports_of(guard_rel)
            doors = [reaches(source, imports, peer["left"]),
                     reaches(source, imports, peer["right"])]
            if all(doors):
                counts[CLASS_TRIPLE_DOOR_BOTH] += 1
                continue
            if any(doors):
                counts[CLASS_TRIPLE_DOOR_ONE] += 1
                continue
            counts[CLASS_TRIPLE] += 1
            # Право чинить спрашивается ОБЩЕЙ функцией (G54 п. 1). До неё это
            # правило жило здесь своей копией — в приборе, который меряет
            # вторые копии правил; ровно ту форму починки
            # (`single_copy_by_import`) он и прописывает другим.
            remedy, evidence, extra = right_to_fix(
                guard_value, thresholds=thresholds, constitution=constitution,
                constitution_unread=constitution_unread)
            if remedy is None:
                remedy = REMEDY_UNPROVEN
                evidence = (
                    "сторож не достаёт ни одного исполнителя, исполнители не "
                    "достают друг друга — копия своя у всех трёх; общего "
                    "происхождения значения прибор не доказывает")
            rows.append({
                "verdict": CLASS_TRIPLE,
                "name": name,
                "value": guard_value,
                "guard": guard_rel,
                "left": peer["left"],
                "right": peer["right"],
                "remedy": remedy,
                "remedy_evidence": evidence,
                **extra,
            })
    rows.sort(key=lambda r: (r["name"], r["guard"], r["left"], r["right"]))
    return rows, counts


#: Вердикт сдвига формы починки (заказ G54 п. 1). Четыре исхода, и четвёртый
#: существует затем, чтобы ноль нельзя было выдать за ответ: величина, не
#: являющаяся числом, витрине не предъявляется ПО ПОСТРОЕНИЮ, и ось, где таких
#: величин все до одной, отвечает «сравнивать было нечего», а не «сдвига нет».
SHIFT_MEASURED = "SHIFTED"
SHIFT_NONE_MEASURED = "NO_SHIFT_MEASURED"
SHIFT_NOTHING_COMPARABLE = "NOTHING_COMPARABLE"
SHIFT_UNMEASURED = "RIGHT_TO_FIX_UNMEASURED"


def constitution_shift(rows: List[dict], *, finding_classes: Tuple[str, ...],
                       constitution_unread: Optional[str]) -> dict:
    """Что купил оси вопрос к витрине порогов (заказ **G54, п. 1**).

    Заказ поставлен был так: «замерить, сколько из 9 и 189 пар сменили бы форму
    починки, если бы витрину спросили и у них». Замер сделан — и раз он вышел
    ненулевым, вопрос задан всем трём осям, а не оставлен третьей. Поэтому
    координата мерит не гипотезу, а СДВИГ, уже произошедший в строках:
    ``remedy_without_shelf`` хранит форму, которая была у пары, пока право
    чинить спрашивалось у одной поверхности решения.

    **Знаменатель сужен намеренно и это сказано числом.** Витрина держит
    только ЧИСЛА (:func:`is_numeric_value`), поэтому пара со строковым
    значением сменить форму не могла ни при каком дереве. Сложить её в
    знаменатель значило бы разбавить замер вопросом, который ей не задавался,
    — тот же дефект, что и «ноль по построению, объявленный чистотой»
    (ADR-431).

    **Витрина не прочитана ⇒ :data:`SHIFT_UNMEASURED`**, и это не «сдвига
    нет»: при нечитаемой витрине каждая пара без порога RiskPolicy получает
    `right_to_fix_unmeasured`, то есть сдвиг как раз МАКСИМАЛЕН.
    """
    population = [r for r in rows if r.get("verdict") in finding_classes]
    owner = [r for r in population if r.get("remedy") == REMEDY_OWNER]
    rest = [r for r in population if r.get("remedy") != REMEDY_OWNER]
    comparable = [r for r in rest if is_numeric_value(r.get("value"))]
    silent = [r for r in rest if not is_numeric_value(r.get("value"))]
    moved = [r for r in population if r.get("remedy_without_shelf")]
    transitions: Dict[str, int] = {}
    for row in moved:
        key = f"{row['remedy_without_shelf']} → {row['remedy']}"
        transitions[key] = transitions.get(key, 0) + 1
    if constitution_unread is not None:
        verdict = SHIFT_UNMEASURED
        reason = constitution_unread
    elif moved:
        verdict = SHIFT_MEASURED
        reason = (f"{len(moved)} из {len(comparable)} сравнимых пар сменили "
                  f"форму починки — право чинить у них было НЕ спрошено до конца")
    elif comparable:
        verdict = SHIFT_NONE_MEASURED
        reason = (f"витрину спросили у {len(comparable)} сравнимых пар, ни одно "
                  f"значение ей не объявлено — ноль ИЗМЕРЕН, а не структурен")
    else:
        verdict = SHIFT_NOTHING_COMPARABLE
        reason = ("сравнимых пар нет вовсе: у всех значение не число, и витрина "
                  "о них молчит ПО ПОСТРОЕНИЮ — это не «сдвига нет»")
    return {
        "verdict": verdict,
        "reason": reason,
        "population": len(population),
        "owner_by_threshold": len(owner),
        "comparable": len(comparable),
        "silent_by_construction": len(silent),
        "moved": len(moved),
        "transitions": transitions,
        "moved_names": sorted({f"{r['name']} = {r['value']}" for r in moved}),
    }


def measure(root: Path, *, now: Optional[dt.datetime] = None,
            probe_ledger: Optional[Path] = None) -> dict:
    """Перепись пар «сторож × исполнитель × имя»."""
    root = Path(root)
    if not root.is_dir():
        raise NotMeasured(f"корень дерева не прочитан: {root}")

    unreadable: List[dict] = []

    # --- сторона исполнителя: имя -> [(модуль, значение)] --------------------
    executors: Dict[str, List[Tuple[str, Optional[str]]]] = {}
    # Второе население — ВСЕ имена верхнего уровня, включая приватные: ось
    # «исполнитель × исполнитель» (заказ G52 п. 1) считает их копиями, и
    # основание этой разницы названо в докстринге `peer_pairs`.
    declared: Dict[str, List[Tuple[str, Optional[str]]]] = {}
    exec_imports: Dict[str, set] = {}
    executor_files = _executor_files(root)
    for path in executor_files:
        rel = path.relative_to(root).as_posix()
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except Exception as exc:  # noqa: BLE001
            unreadable.append({"file": rel, "side": "executor",
                               "reason": f"{type(exc).__name__}: {exc}"})
            continue
        exec_imports[rel] = imported_modules(tree)
        for name, value in toplevel_constants(tree).items():
            declared.setdefault(name, []).append((rel, value))
            if name.startswith("_"):
                continue        # приватное имя правилом наружу не является
            executors.setdefault(name, []).append((rel, value))

    # --- сторона сторожа ----------------------------------------------------
    rows: List[dict] = []
    counts = {CLASS_TWO_COPIES: 0, CLASS_DELEGATES: 0, CLASS_VALUE_DIFFERS: 0,
              CLASS_NOT_CONSTANT: 0, CLASS_AMBIGUOUS: 0}
    surface: List[str] = []
    # Третья ось (заказ G53 п. 1) спрашивает сторожей о тех же именах, что и
    # ось исполнителей. Держатся ИМЯ и ЗНАЧЕНИЕ (дёшево), а текст сторожа
    # перечитывается лениво и только у кандидатов — тем же `_text`, что и у
    # соседней оси: вторая копия правила «как читать файл» здесь не заводится.
    guard_declared: Dict[str, List[Tuple[str, Optional[str]]]] = {}
    guard_imports_by_rel: Dict[str, set] = {}
    guard_files = _guard_files(root)
    # Пороги спрашиваются ПОСЛЕ корней населения и ДО разбора форм. Порядок
    # обоих отказов измерен тестами: «корень не прочитан» остаётся первым
    # (он отменяет перепись целиком), а «пороги не прочитаны» отменяет право
    # чинить — и ни один из них не выдаётся за пустой результат.
    thresholds = risk_policy_thresholds(root)
    for path in guard_files:
        rel = path.relative_to(root).as_posix()
        try:
            source = path.read_text(encoding="utf-8")
            tree = ast.parse(source)
        except Exception as exc:  # noqa: BLE001
            unreadable.append({"file": rel, "side": "guard",
                               "reason": f"{type(exc).__name__}: {exc}"})
            continue

        guard_imports = imported_modules(tree)
        guard_imports_by_rel[rel] = guard_imports
        touches_state = any(mark in source for mark in _REPO_STATE_MARKS)

        for name, guard_value in toplevel_constants(tree).items():
            if name.startswith("_") or name.startswith("test_"):
                continue
            guard_declared.setdefault(name, []).append((rel, guard_value))
            side = executors.get(name)
            if not side:
                continue
            if len(side) > 1:
                # Имя, объявленное многими исполнителями, не называет ОДНО
                # правило. Это не находка и не «сошлось» — это своя корзина.
                counts[CLASS_AMBIGUOUS] += 1
                continue
            exec_rel, exec_value = side[0]
            if guard_value is None or exec_value is None:
                counts[CLASS_NOT_CONSTANT] += 1
                continue
            if guard_value != exec_value:
                counts[CLASS_VALUE_DIFFERS] += 1
                continue
            if reaches(source, guard_imports, exec_rel):
                counts[CLASS_DELEGATES] += 1
                continue
            counts[CLASS_TWO_COPIES] += 1
            rows.append({
                "verdict": CLASS_TWO_COPIES,
                "guard": rel,
                "executor": exec_rel,
                "name": name,
                "value": guard_value,
            })

        # Сторож трогает состояние репозитория и НИ ОДНОЙ дверью не достаёт
        # дерева-предмета ⇒ каждое проверяемое им условие — его собственная
        # копия ПО ПОСТРОЕНИЮ. Переименованную копию правило имени не видит
        # никогда, и вот её верхняя граница.
        if touches_state and not _reaches_subject_tree(source):
            surface.append(rel)

    rows.sort(key=lambda r: (r["guard"], r["name"]))

    # --- форма починки у каждой находки (заказ G42 п. 1) --------------------
    # Витрина порогов читается ДО разбора форм: с заказа G54 п. 1 её
    # спрашивают ВСЕ ТРИ оси, а не одна лишь третья.
    constitution, constitution_unread = constitution_values(root)
    remedy_counts = {cls: 0 for cls in _REMEDY_CLASSES}
    text_cache: Dict[str, Optional[str]] = {}

    def _text(rel: str) -> Optional[str]:
        if rel not in text_cache:
            try:
                text_cache[rel] = (root / rel).read_text(encoding="utf-8")
            except OSError:
                text_cache[rel] = None
        return text_cache[rel]

    ledger, ledger_absent = load_probe_ledger(
        Path(probe_ledger) if probe_ledger is not None else root / PROBE_LEDGER)
    probe_stats = {"fresh": 0, "stale": 0, "missing": 0,
                   "ledger_absent": ledger_absent}

    for row in rows:
        if row["verdict"] not in _FINDING_CLASSES:
            continue
        probe = _probe_verdict(root, row, ledger, probe_stats)
        guard_text = _text(row["guard"])
        guard_loads: Optional[bool] = None
        if guard_text is not None:
            try:
                guard_loads = constant_is_loaded(ast.parse(guard_text), row["name"])
            except SyntaxError:
                guard_loads = None       # не разобрано ⇒ НЕ «не читается»
        row.update(classify_remedy(row, guard_text=guard_text,
                                   executor_text=_text(row["executor"]),
                                   thresholds=thresholds,
                                   constitution=constitution,
                                   constitution_unread=constitution_unread,
                                   probe=probe, guard_loads=guard_loads))
        remedy_counts[row["remedy"]] += 1

    # --- вторая ось: копия между двумя исполнителями (заказ G52 п. 1) ------
    # Текст стороны перечитывается лениво и только у кандидатов: держать в
    # памяти исходники всех исполнителей ради вопроса, который задаётся
    # шестистам именам, — цена без покупателя.
    peer_rows, peer_counts = peer_pairs(
        declared,
        source_of=_text,
        imports_of=lambda rel: exec_imports.get(rel, set()),
        thresholds=thresholds,
        constitution=constitution,
        constitution_unread=constitution_unread)

    # --- третья ось: ТРИ копии одного правила (заказ G53 п. 1) -------------
    triple_rows, triple_counts = triple_copies(
        peer_rows, guard_declared,
        source_of=_text,
        imports_of=lambda rel: guard_imports_by_rel.get(rel, set()),
        thresholds=thresholds,
        constitution=constitution,
        constitution_unread=constitution_unread)
    intersection = axes_intersection(rows, peer_rows, declared)

    scanned = len(guard_files) + len(executor_files)
    classified = scanned - len(unreadable)
    findings = [r for r in rows if r["verdict"] in _FINDING_CLASSES]
    return {
        "generated_at": (now or _utcnow()).isoformat(),
        "generated_by": PRODUCER,
        "invoked_by": call_provenance(tree_root=root),
        "status": "FINDING" if findings else "CLEAN",
        "question": "у скольких правил есть ИСПОЛНИТЕЛЬ и СТОРОЖ, проверяющие одно условие РАЗНЫМ кодом",
        "population_rule": (
            "сторож — собираемый pytest файл test_*.py из каталогов предписанного "
            "прогона; исполнитель — не-тестовый модуль spa_core/ + scripts/ (без "
            "scripts/archive/); координата — имя верхнего уровня с КОНСТАНТНЫМ "
            "значением, у которого исполнитель РОВНО ОДИН"
        ),
        "scanned": scanned,
        "guards": len(guard_files),
        "executors": len(executor_files),
        "counts": dict(counts, unreadable=len(unreadable)),
        "remedy_counts": remedy_counts,
        # Пара, у которой имя сторожа не читается, из населения не исчезает:
        # строка остаётся, меняется её форма. Число «на учёте» считается здесь,
        # чтобы «стало меньше» нельзя было выдать за «нашлось меньше».
        "findings_on_books": len(
            [r for r in rows if r["verdict"] in _FINDING_CLASSES
             and r.get("remedy") != REMEDY_UNUSED]),
        "probe": probe_stats,
        # Вторая ось — ЧИСЛО поверхности, а не перечень приговоров, и на
        # `status` она НАМЕРЕННО не влияет: 189 строк, влитые в находки,
        # утопили бы девять пар первой оси, а заказ просил числа. Читателем
        # числа служит строка отчёта шага 0-офис, печатаемая каждый прогон;
        # храповика у него сегодня нет, и это сказано вслух, а не подразумевается.
        "peer_counts": peer_counts,
        "peer_rows": peer_rows,
        "peer_owner_subject": len([r for r in peer_rows
                                   if r.get("remedy") == REMEDY_OWNER]),
        "peer_remedy_counts": {
            cls: len([r for r in peer_rows
                      if r.get("verdict") == CLASS_PEER_TWO_COPIES
                      and r.get("remedy") == cls])
            for cls in _PEER_REMEDY_CLASSES},
        # Сдвиг формы починки от вопроса к ВТОРОЙ поверхности решения
        # (заказ G54 п. 1) — по каждой соседней оси отдельно: числа разные,
        # и одно из них ноль, который обязан быть ИЗМЕРЕННЫМ, а не структурным.
        "constitution_shift": {
            "first_axis": constitution_shift(
                rows, finding_classes=_FINDING_CLASSES,
                constitution_unread=constitution_unread),
            "peer_axis": constitution_shift(
                peer_rows, finding_classes=(CLASS_PEER_TWO_COPIES,),
                constitution_unread=constitution_unread),
        },
        "peer_private_names": len([r for r in peer_rows
                                   if r.get("private_name")]),
        "risk_policy_thresholds": len(thresholds),
        # Пересечение осей ПО ИМЕНИ (заказ G53 п. 1) и — отдельным вопросом —
        # ПОЧЕМУ оно такое. Ноль без второго поля был бы не ответом.
        "axes_intersection": intersection,
        # Третья ось. На `status` не влияет по той же причине, что и вторая:
        # она мерит ПОВЕРХНОСТЬ числом, а не выносит приговор каждой строке.
        "triple_counts": triple_counts,
        "triple_rows": triple_rows,
        "triple_names": triple_name_count(triple_rows),
        "triple_remedy_counts": {
            cls: len([r for r in triple_rows if r.get("remedy") == cls])
            for cls in _TRIPLE_REMEDY_CLASSES},
        "constitution_values": len(constitution),
        "constitution_unread": constitution_unread,
        "classified": classified,
        "rows": rows,
        "unreadable": unreadable,
        # Доказанный МИНИМУМ переименованных копий: сторож, ни разу не
        # упомянувший дерево-предмет, держит свою копию наверняка. Потолком это
        # число не является — см. docstring.
        "renamed_copy_surface": sorted(surface),
        "what_it_does_not_prove": [
            "что у найденной пары копия вредит СЕГОДНЯ — вред приходит с правкой одной из копий",
            "что совпавшее значение имеет общее происхождение (SEED = 42 может быть совпадением)",
            "что население полно — переименованная копия невидима; renamed_copy_surface есть доказанный МИНИМУМ, а не потолок",
            "что сторож из delegates не держит второй копии рядом — дверь найдена, пользование ею не спрошено",
            "что пара subject_unproven есть СОВПАДЕНИЕ — свидетели общего предмета односторонние, «не доказан» третий исход",
            "что пара owner_subject есть ОДНА величина — равенство с порогом RiskPolicy отправляет её владельцу, а не выносит приговор",
            "что у пары subject_proven_by_behaviour общий ключ читается ИМЕННО из общего артефакта — статически связать их нечем, и прибор связи не выдумывает",
            "что пара independent_by_probe не имеет общего предмета — зонд мерит ЗАВИСИМОСТЬ ВЕРДИКТА от значения, а не происхождение числа; несогласие со свидетелем называется в строке",
            "что у пары ОСИ ИСПОЛНИТЕЛЕЙ (peer_*) копия вредна — ось мерит ПОВЕРХНОСТЬ числом; вреда у неё не спрашивали, и зонд независимости её пар не трогает",
            "что 189 у оси исполнителей есть потолок класса — переименованная копия невидима ей так же, как и первой оси, и ровно по той же причине",
            "что пустое пересечение осей означает отсутствие правил с ТРЕМЯ копиями — оно пусто ПО ПОСТРОЕНИЮ (1 исполнитель против 2), и на вопрос отвечает отдельная координата triple_copies",
            "что у находки третьей оси копия вредна СЕГОДНЯ — ось мерит поверхность; зонд независимости её строк не трогает так же, как и строк второй оси",
            "что право чинить спрошено у ВСЕХ поверхностей решения — с G54 п. 1 их спрашивают ДВЕ (пороги RiskPolicy и витрина сайта) на ВСЕХ трёх осях, но объявленных поверхностей в репозитории может быть больше, и число их прибор не знает",
            "что пара `constitution_subject` держит ТО ЖЕ число, что и витрина, — равенство величины не есть тождество смысла ровно так же, как у порога RiskPolicy; потому пара и уходит владельцу, а не чинится",
            "что нулевой сдвиг на первой оси есть свойство ДЕРЕВА — знаменатель там 5 сравнимых пар из 9, и это сказано числом, а не словом",
        ],
    }


def _reaches_subject_tree(source: str) -> bool:
    """Достаёт ли сторож дерево-предмет хоть как-нибудь.

    Отдельная функция, а не выражение на месте: поверхность слепоты — второе
    по важности число прибора, и правило её отбора обязано быть одним и
    проверяемым тестом.
    """
    return ("spa_core" in source) or ("scripts" in source)


def report(doc: dict, *, max_rows: int = 20) -> List[str]:
    """Строки отчёта. Единственное место, где перепись превращается в текст."""
    status = str(doc.get("status"))
    if status == "UNMEASURED":
        return [f"НЕ ИЗМЕРЕНО — {observed(doc, 'reason', kind=str) or 'причина не записана'}"]
    counts = observed(doc, "counts", kind=dict) or {}
    out = [
        f"одно правило — две копии (заказ G41 п. 1): {status} · "
        f"две копии {counts.get(CLASS_TWO_COPIES)} · "
        f"сторож достаёт исполнителя {counts.get(CLASS_DELEGATES)} · "
        f"значения разные {counts.get(CLASS_VALUE_DIFFERS)} · "
        f"сравнить нечем {counts.get(CLASS_NOT_CONSTANT)} · "
        f"исполнитель не один {counts.get(CLASS_AMBIGUOUS)}",
        f"[ЗВАВШИЙ] {provenance_line(observed(doc, 'invoked_by', kind=dict))}",
        f"[УЧЁТ] осмотрено {doc.get('scanned')} = разобрано {doc.get('classified')} "
        f"+ не разобрано {counts.get('unreadable')} "
        f"(сторожей {doc.get('guards')}, исполнителей {doc.get('executors')})",
    ]
    remedy = observed(doc, "remedy_counts", kind=dict)
    if remedy is None:
        out.append("[ФОРМА ПОЧИНКИ] НЕ ИЗМЕРЕНА — перепись собрана без разбора форм")
    else:
        out.append(
            f"[ФОРМА ПОЧИНКИ] ввозом {remedy.get(REMEDY_IMPORT)} · "
            f"предмет владельца {remedy.get(REMEDY_OWNER)} · "
            f"предмет витрины порогов {remedy.get(REMEDY_CONSTITUTION)} · "
            f"право чинить НЕ ИЗМЕРЕНО {remedy.get(REMEDY_RIGHT_UNMEASURED)} · "
            f"предмет доказан поведением {remedy.get(REMEDY_BEHAVIOUR)} · "
            f"имя у сторожа не читается {remedy.get(REMEDY_UNUSED)} · "
            f"предмет НЕ доказан {remedy.get(REMEDY_UNPROVEN)} · "
            f"не разобрано {remedy.get(REMEDY_UNREADABLE)}")
        on_books = observed(doc, "findings_on_books", kind=int)
        out.append(
            f"[НА УЧЁТЕ] {on_books if on_books is not None else 'НЕ ИЗМЕРЕНО'} "
            f"из {counts.get(CLASS_TWO_COPIES)} пар — с учёта снимает ровно одно "
            f"основание (имя у сторожа не читается), и снятая пара из НАСЕЛЕНИЯ "
            f"не исчезает")
    probe = observed(doc, "probe", kind=dict)
    if probe is None:
        out.append("[ЗОНД] НЕ ИЗМЕРЕН — перепись собрана без чтения журнала зонда")
    else:
        absent = probe.get("ledger_absent")
        drift = {}
        for row in (doc.get("rows") or []):
            if row.get("drift"):
                drift[row["drift"]] = drift.get(row["drift"], 0) + 1
        out.append(
            f"[ЗОНД] годных записей {probe.get('fresh')} · протухших "
            f"{probe.get('stale')} · нет записи {probe.get('missing')}"
            + (f" · {absent}" if absent else "")
            + " — протухшая запись возвращает пару НА учёт, а не снимает с него")
        toothless = len([r for r in (doc.get("rows") or [])
                         if r.get("verdict_teeth") == "none"])
        out.append(
            f"[СНОС ВРОЗЬ] молча {drift.get(PROBE_DRIFT_SILENT, 0)} · с краснотой "
            f"{drift.get(PROBE_DRIFT_LOUD, 0)} · вердикт сторожа без зубов "
            f"{toothless} — это про ВРЕД, а не про предмет: ни один из трёх пару "
            f"с учёта НЕ снимает; снимает только СТАТИЧЕСКОЕ «имя не читается»")
    findings = [r for r in (doc.get("rows") or []) if r["verdict"] in _FINDING_CLASSES]
    for row in findings[:max_rows]:
        tail = ""
        if row.get("remedy"):
            tail = f" · {row['remedy']}: {row.get('remedy_evidence', 'основание не записано')}"
        out.append(
            f"[НАХОДКА] {row['name']} = {row['value']} — сторож {row['guard']} "
            f"против исполнителя {row['executor']}{tail}")
    if len(findings) > max_rows:
        # Умолчание об укорочении и есть способ соврать усечением.
        out.append(f"[…] показаны {max_rows} находки из {len(findings)}; "
                   f"полный перечень — в артефакте")
    peer = observed(doc, "peer_counts", kind=dict)
    if peer is None:
        out.append("[ПАРА ИСПОЛНИТЕЛЕЙ] НЕ ИЗМЕРЕНА — перепись собрана без второй оси")
    else:
        owner = observed(doc, "peer_owner_subject", kind=int)
        priv = observed(doc, "peer_private_names", kind=int)
        two = peer.get(CLASS_PEER_TWO_COPIES)
        out.append(
            f"[ПАРА ИСПОЛНИТЕЛЕЙ] копия между двумя исполнителями {two} · "
            f"дверь открыта {peer.get(CLASS_PEER_DELEGATES)} · значения разные "
            f"{peer.get(CLASS_PEER_VALUE_DIFFERS)} · сравнить нечем "
            f"{peer.get(CLASS_PEER_NOT_CONSTANT)} · имя у многих исполнителей "
            f"{peer.get(CLASS_PEER_MANY)} · дверь НЕ ИЗМЕРЕНА "
            f"{peer.get(CLASS_PEER_UNMEASURED)}")
        peer_remedy = observed(doc, "peer_remedy_counts", kind=dict) or {}
        out.append(
            f"[ПРАВО ЧИНИТЬ] из них величина равна порогу RiskPolicy у "
            f"{owner if owner is not None else 'НЕ ИЗМЕРЕНО'} · объявлена "
            f"витриной порогов сайта у {peer_remedy.get(REMEDY_CONSTITUTION)} · "
            f"НЕ ИЗМЕРЕНО {peer_remedy.get(REMEDY_RIGHT_UNMEASURED)} · "
            f"не возражает никто {peer_remedy.get(REMEDY_UNPROVEN)} — первые "
            f"две формы агент НЕ чинит; равенство числа не есть тождество "
            f"смысла, и сверка ошибается в сторону «спросить»")
        out.append(
            f"[ИМЯ] приватных {priv if priv is not None else 'НЕ ИЗМЕРЕНО'} из "
            f"{two} — на этой оси приватное имя из населения НЕ выбрасывается: "
            f"прочитать чужое `_X` нельзя, и копия от этого не мнимая, а "
            f"неизбежная; меняется лишь форма починки")
        peer_rows = [r for r in (doc.get("peer_rows") or [])
                     if r.get("verdict") == CLASS_PEER_TWO_COPIES]
        for row in peer_rows[:max_rows]:
            out.append(
                f"[ПАРА] {row['name']} = {row['value']} — {row['left']} × "
                f"{row['right']} · {row.get('remedy')}")
        if len(peer_rows) > max_rows:
            out.append(f"[…] показаны {max_rows} пар(ы) из {len(peer_rows)}; "
                       f"полный перечень — в артефакте")
        out.append(
            "[ПОЧЕМУ ОСЬ ЕСТЬ] молчание первой оси об этой паре было НЕ "
            "свидетельством: в сцене с ВОССТАНОВЛЕННОЙ второй копией её вердикт "
            "оставался побуквенно тем же (ADR-430). Ось не влияет на `status` — "
            "она мерит поверхность числом, а не выносит приговор каждой паре")
    shift = observed(doc, "constitution_shift", kind=dict)
    if shift is None:
        out.append("[ВТОРАЯ ПОВЕРХНОСТЬ] НЕ ИЗМЕРЕНА — перепись собрана без вопроса G54 п. 1")
    else:
        for key, label in (("first_axis", "сторож × исполнитель"),
                           ("peer_axis", "исполнитель × исполнитель")):
            ax = shift.get(key) or {}
            out.append(
                f"[ВТОРАЯ ПОВЕРХНОСТЬ · {label}] {ax.get('verdict')} · "
                f"сменили форму починки {ax.get('moved')} из "
                f"{ax.get('comparable')} сравнимых "
                f"(население {ax.get('population')} = порог RiskPolicy "
                f"{ax.get('owner_by_threshold')} + сравнимых "
                f"{ax.get('comparable')} + витрина молчит по построению "
                f"{ax.get('silent_by_construction')}); {ax.get('reason')}")
            for move, n in sorted((ax.get("transitions") or {}).items()):
                out.append(f"[СДВИГ] {move}: {n}")
            names = ax.get("moved_names") or []
            if names:
                out.append(f"[СДВИГ · имена] {', '.join(names[:max_rows])}"
                           + (f" … ещё {len(names) - max_rows}"
                              if len(names) > max_rows else ""))
    inter = observed(doc, "axes_intersection", kind=dict)
    if inter is None:
        out.append("[ПЕРЕСЕЧЕНИЕ ОСЕЙ] НЕ ИЗМЕРЕНО — перепись собрана без вопроса G53 п. 1")
    else:
        hist = inter.get("executors_per_name") or {}
        out.append(
            f"[ПЕРЕСЕЧЕНИЕ ОСЕЙ] имён, о которых говорят ОБЕ оси: "
            f"{inter.get('count')} — {inter.get('verdict')}; "
            f"{inter.get('reason')}")
        out.append(
            f"[ОСНОВАНИЕ] исполнителей у имён первой оси {hist.get('axis_one')} · "
            f"у имён второй {hist.get('axis_two')} — ноль читается по этим "
            f"числам, а не по слову «нет»")
    triple = observed(doc, "triple_counts", kind=dict)
    if triple is None:
        out.append("[ТРИ КОПИИ] НЕ ИЗМЕРЕНЫ — перепись собрана без третьей оси")
    else:
        names = observed(doc, "triple_names", kind=int)
        remedy3 = observed(doc, "triple_remedy_counts", kind=dict) or {}
        out.append(
            f"[ТРИ КОПИИ] сторож × два исполнителя {triple.get(CLASS_TRIPLE)} "
            f"пар(ы) на {names if names is not None else 'НЕ ИЗМЕРЕНО'} имён(и) · "
            f"дверь к одному {triple.get(CLASS_TRIPLE_DOOR_ONE)} · дверь к обоим "
            f"{triple.get(CLASS_TRIPLE_DOOR_BOTH)} · значения разные "
            f"{triple.get(CLASS_TRIPLE_VALUE_DIFFERS)} · сравнить нечем "
            f"{triple.get(CLASS_TRIPLE_NOT_CONSTANT)} · дверь НЕ ИЗМЕРЕНА "
            f"{triple.get(CLASS_TRIPLE_UNMEASURED)}")
        unread = doc.get("constitution_unread")
        out.append(
            f"[ПРАВО ЧИНИТЬ · 2 ПОВЕРХНОСТИ] предмет RiskPolicy "
            f"{remedy3.get(REMEDY_OWNER)} · предмет витрины порогов "
            f"{remedy3.get(REMEDY_CONSTITUTION)} · право НЕ ИЗМЕРЕНО "
            f"{remedy3.get(REMEDY_RIGHT_UNMEASURED)} · предмет не доказан "
            f"{remedy3.get(REMEDY_UNPROVEN)}"
            + (f" — {unread}" if unread else ""))
        triple_rows = [r for r in (doc.get("triple_rows") or [])
                       if r.get("verdict") == CLASS_TRIPLE]
        for row in triple_rows[:max_rows]:
            out.append(
                f"[ТРОЙКА] {row['name']} = {row['value']} — сторож "
                f"{row['guard']} против {row['left']} × {row['right']} · "
                f"{row.get('remedy')}: {row.get('remedy_evidence', 'основание не записано')}")
        if len(triple_rows) > max_rows:
            # Умолчание об укорочении и есть способ соврать усечением.
            out.append(f"[…] показаны {max_rows} тройки из {len(triple_rows)}; "
                       f"полный перечень — в артефакте")
        unmeasured = [r for r in (doc.get("triple_rows") or [])
                      if r.get("verdict") == CLASS_TRIPLE_UNMEASURED]
        for row in unmeasured[:max_rows]:
            out.append(f"[НЕ ИЗМЕРЕНО] {row['name']} — сторож {row['guard']}: "
                       f"{row.get('reason', 'причина не записана')}")
        out.append(
            "[ПОЧЕМУ ОСЬ ЕСТЬ] пересечение двух прежних осей пусто ПО "
            "ПОСТРОЕНИЮ и о трёх копиях не говорит ничего; храповика у этого "
            "числа сегодня НЕТ, рост виден только в этой строке (остаток G52 п. 2)")
    surface = doc.get("renamed_copy_surface") or []
    out.append(
        f"[ГРАНИЦА ПРАВИЛА ИМЕНИ] сторожей, читающих состояние репозитория и не "
        f"упоминающих дерево-предмет ни разу: {len(surface)} — у них копия своя "
        f"ПО ПОСТРОЕНИЮ; это доказанный МИНИМУМ переименованных копий, не потолок"
        + (f"; напр. {', '.join(surface[:3])}" if surface else ""))
    out.append("НЕ ДОКЛАДЫВАЕТ: вредит ли найденная копия сегодня; общее ли "
               "происхождение у совпавшего значения; является ли "
               "`subject_unproven` совпадением — свидетель односторонний")
    return out


def format_report(doc: dict, *, max_rows: int = 5) -> List[str]:
    """Отрисовка для шага 0-офис. Второй копии правила отрисовки здесь НЕТ:
    ветка офиса делегирует сюда, а эта функция — в ``report``."""
    lines = report(doc, max_rows=max_rows)
    if str(doc.get("status")) == "FINDING":
        lines[0] = f"⚠️ {lines[0]}"
    return lines


def run(root: str | Path = _ROOT, *, dest: Optional[Path] = None,
        data_dir: Optional[Path] = None, write: bool = True,
        now: Optional[dt.datetime] = None) -> dict:
    """Один прогон переписи для ступени моста.

    **Гейта такта здесь нет, и это замер, а не поблажка.** Зов есть разбор AST
    в одном процессе; цена названа в ADR-417. Недельный такт не купил бы
    ничего, а завёл бы ровно ту вторую копию правила о сроке, которую сосед
    (`tact_gate_census`) и ищет.
    """
    root = Path(root)
    target = (Path(dest) if dest is not None
              else (Path(data_dir) if data_dir is not None else root / "data") / ARTIFACT)
    try:
        # Журнал зонда лежит В ДЕРЕВЕ (рядом с кодом), а не в `data/`: он
        # есть замер исходников, и `data_dir` его не касается.
        doc = measure(root, now=now, probe_ledger=root / PROBE_LEDGER)
    except NotMeasured as exc:
        doc = {
            "generated_at": (now or _utcnow()).isoformat(),
            "generated_by": PRODUCER,
            "invoked_by": call_provenance(tree_root=root),
            "status": "UNMEASURED",
            "reason": str(exc),
        }
    if write:
        atomic_save(doc, str(target))
    return {"measured": doc.get("status") != "UNMEASURED", "doc": doc,
            "artifact": str(target)}


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description="перепись «одно правило — две копии»: исполнитель против сторожа (G41 п. 1)")
    ap.add_argument("--root", default=str(_ROOT))
    ap.add_argument("--out", default=None)
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args(argv)

    outcome = run(Path(args.root),
                  dest=Path(args.out) if args.out else None,
                  write=not args.no_write)
    doc = outcome["doc"]
    for line in report(doc):
        print(line)
    return {"UNMEASURED": 2, "FINDING": 1}.get(str(doc.get("status")), 0)


