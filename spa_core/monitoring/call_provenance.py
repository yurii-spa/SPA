"""Кто ПОЗВАЛ этот прогон — измеренный признак, а не объявленный.

Заказ **G36, п. 1** приказа владельца «Portfolio CIO» (хвост ADR-411).

## Вопрос, на который прибор отвечает

ADR-411 провёл артефакт переписи к производителю ДВУМЯ разными способами и
поставил наблюдение: после **25.09** сверить отметки ``generated_at`` у
``list_identity_census.json`` (ступень моста) и ``python_reader_clock_doors.json``
(строка промпта) и узнать, **стои́т ли строка в промпте чего-нибудь вообще**.

Замер 18.09 показал, что наблюдение в этой форме НЕИЗМЕРИМО, и по построению:

* ``generated_at`` — это часы, а не звавший. Отметка сменится одинаково,
  позвала ли прибор ступень моста или рука цикла, набравшая ``python3 -m``;
* ``generated_by`` у соседа — **константа с именем самого производителя**
  (``PRODUCER``). Она отвечает «какой модуль это написал», и ответ у неё один
  и тот же при любом зове;
* оба документа целиком собирает ``measure(data_dir, tree_root, now=…)`` —
  в её подписи звавшего нет вовсе, поэтому запись не может о нём
  свидетельствовать ни при каком состоянии системы.

Отсюда односторонность, которой заказ не заметил: отметка НЕ сменилась ⇒
ступень молчит (вывод верен); отметка сменилась ⇒ **не известно ничего** —
это мог быть и зов ступени, и рука соседнего цикла. То есть наблюдение,
поставленное чтобы ПОДТВЕРДИТЬ проводку, подтвердить её не может.

Этот модуль добавляет запись, которой не хватало: **точку входа процесса,
который документ пишет**.

## Почему измерение, а не объявление

Звавший, переданный параметром, есть его собственное утверждение о себе:
ступень объявила бы себя ступенью и в том случае, когда её никто не звал, —
ровно тот класс, против которого написан приём «проба меряет ИСХОД, не
структуру» (`.claude/rules/acceptance.md`). Поэтому признак берётся у ПРОЦЕССА:

* ``sys.modules["__main__"].__file__`` — файл точки входа. Для
  ``python3 -m spa_core.monitoring.list_identity_census`` это сам модуль
  переписи, для бегуна моста — ``findings_bridge.py``. Это и есть ось, по
  которой заказ различает две проводки;
* ``sys.argv[0]`` — второе, независимое чтение того же факта. Обычно они
  совпадают; **расхождение записывается, а не разрешается молча** — у
  подтверждающего прибора обязана быть своя частота ошибок, иначе он не
  подтверждает, а удваивает.

## Три исхода, и они различимы (инв. #17)

``__main__`` без ``__file__`` (``python3 -c``, REPL, встроенный интерпретатор)
— это **не измерено** с названной причиной, а не строка ``"unknown"``: такая
строка встала бы в отчёт на место наблюдения и читалась бы как имя звавшего.

## Чего признак НЕ доказывает

* **Не «автоматически ли это».** Точка входа называет ПРОГРАММУ, а не то, кто
  её запустил: тот же ``findings_bridge.py`` может набрать и рука. Прибор
  отвечает на вопрос заказа («какой из двух проводок написан документ»), а не
  на вопрос «был ли человек».
* **Не «из какого дерева».** Путь приводится к корню дерева, поэтому прогон из
  одноразового worktree и прогон из прод-дерева дают ОДНУ запись. Это
  намеренно: заказ различает проводки, а не деревья.
* Признак снят в момент СБОРКИ документа. Если документ потом перепишет чужая
  рука, запись будет о том прогоне, который его собрал, — как и всякая запись
  внутри файла.

Прибор только ЧИТАЕТ собственный процесс: ни файлов, ни сети, ни капитала.
"""
# LLM_FORBIDDEN
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Optional

SCHEMA = "call_provenance.v1"

#: Признак берётся у двух дверей процесса. Имена дверей попадают в запись,
#: чтобы читатель документа знал, ЧТО именно было прочитано, а не верил слову.
_DOOR_MAIN = "sys.modules['__main__'].__file__"
_DOOR_ARGV = "sys.argv[0]"

#: «Вход не передан» — отдельно от ``None``, который есть ОТВЕТ двери
#: ``__main__`` у программы без файла. См. docstring ``call_provenance``.
_UNSET = object()


def _relative_to_tree(path: Path, tree_root: Optional[Path]) -> tuple[str, bool]:
    """Путь к корню дерева, если он внутри; иначе — одно имя файла.

    Абсолютный путь снаружи дерева в запись не кладётся намеренно: он несёт
    домашний каталог владельца и при этом ничего не добавляет к ответу — для
    чужой точки входа (``pytest``, свой драйвер) различающим является имя.
    """
    if tree_root is not None:
        try:
            return str(path.relative_to(tree_root)), True
        except ValueError:
            pass
    return path.name, False


def _read_door(raw: Optional[str], tree_root: Optional[Path]) -> Optional[dict]:
    """Одно чтение одной двери. ``None`` = дверь ничего не сказала.

    **Дверь обязана назвать СУЩЕСТВУЮЩИЙ файл**, и это не придирка к форме.
    Первый же прогон через настоящую дверь ``python3 -c`` дал ``sys.argv[0] ==
    "-c"``: строка непустая, ``Path("-c").resolve()`` молча приставляет текущий
    каталог, и запись выходила ``{"measured": true, "entry": "-c"}`` — ненаблюдение
    в одежде наблюдения, ровно тот дефект, против которого написан весь модуль.
    Проверка существования разводит «программа — вот этот файл» и «программы-файла
    нет вовсе» замером, а не догадкой по виду строки.
    """
    if not raw:
        return None
    try:
        resolved = Path(raw).resolve()
        if not resolved.is_file():
            return None
    except (OSError, ValueError, RuntimeError):
        return None
    entry, inside = _relative_to_tree(resolved, tree_root)
    return {"entry": entry, "inside_tree": inside}


def call_provenance(*, tree_root: Optional[Path] = None,
                    main_file: Any = _UNSET,
                    argv: Any = _UNSET) -> dict:
    """Точка входа процесса, собирающего документ.

    ``main_file`` и ``argv`` существуют для проверки РАЗБОРА (расхождение
    дверей вживую не подстроишь). Умолчания читают настоящий процесс, и
    положительные контроли разбора идут отдельными подпроцессами через
    настоящие двери — иначе проверился бы только разбор своего же входа.

    **Почему сторож «не передано», а не ``None``.** ``None`` — это ОТВЕТ двери
    ``__main__``, когда у программы нет файла (``python3 -c``, REPL). Пока он же
    означал «вход не передан», подставить молчащую дверь было НЕВОЗМОЖНО:
    ``main_file=None`` молча уходило читать настоящий процесс, и тест про третий
    исход зеленел на чужом наблюдении. Одно значение с двумя смыслами — ровно
    тот класс, ради которого написан инв. #17; найдено своими же тестами.
    """
    if main_file is _UNSET:
        main_module = sys.modules.get("__main__")
        main_file = getattr(main_module, "__file__", None)
    if argv is _UNSET:
        argv = sys.argv

    root = Path(tree_root).resolve() if tree_root is not None else None
    by_main = _read_door(main_file, root)
    by_argv = _read_door(argv[0] if argv else None, root)

    primary = by_main or by_argv
    if primary is None:
        return {
            "schema": SCHEMA,
            "measured": False,
            "reason": (f"точка входа не прочитана ни одной дверью: ни "
                       f"{_DOOR_MAIN}, ни {_DOOR_ARGV} не назвали существующего "
                       f"файла — так выглядит `python3 -c`, REPL или встроенный "
                       f"интерпретатор"),
        }

    doc = {
        "schema": SCHEMA,
        "measured": True,
        "entry": primary["entry"],
        "inside_tree": primary["inside_tree"],
        "read_by": _DOOR_MAIN if by_main is not None else _DOOR_ARGV,
    }
    # Расхождение дверей — САМО по себе свидетельство, и гасить его выбором
    # «главной» двери значило бы выдать одно чтение за два.
    if by_main is not None and by_argv is not None:
        doc["doors_agree"] = by_main["entry"] == by_argv["entry"]
        if not doc["doors_agree"]:
            doc["entry_by_argv"] = by_argv["entry"]
    else:
        doc["doors_agree"] = None
        doc["one_door_silent"] = _DOOR_ARGV if by_argv is None else _DOOR_MAIN
    return doc


def describe(doc: Optional[dict]) -> str:
    """Одна строка для отчёта. Отсутствие записи не выдаётся за запись."""
    if not isinstance(doc, dict) or "measured" not in doc:
        # Пустой словарь — это ОТСУТСТВИЕ записи, а не запись «не измерено»:
        # у второй обязана быть названная причина, и подменять одно другим
        # значит терять различие между «не звали» и «звали, но не прочли».
        return "позван: НЕ ЗАПИСАНО (в документе нет поля `invoked_by`)"
    if not doc.get("measured"):
        return f"позван: НЕ ИЗМЕРЕНО — {doc.get('reason', 'причина не названа')}"
    line = f"позван из точки входа `{doc.get('entry')}`"
    if doc.get("doors_agree") is False:
        line += f" (двери спорят: {_DOOR_ARGV} назвал `{doc.get('entry_by_argv')}`)"
    elif doc.get("doors_agree") is None:
        line += f" (одна дверь молчала: {doc.get('one_door_silent')})"
    return line


def main() -> int:
    """Печатает провенанс СВОЕГО зова — это стенд для положительных контролей."""
    root = Path(__file__).resolve().parents[2]
    print(json.dumps(call_provenance(tree_root=root), ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
