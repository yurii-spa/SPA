"""_label_band.py — score ВНУТРИ полосы собственного вердикта модуля.

Зачем это есть (замер цикла #143, карточка
``inbox-slepota-mozhet-byt-poteryannoi-koerciei``).

Часть Tier-B движков не отдаёт числа: они отдают собственный вердикт
(``status="SAFE"``, ``health_status="DANGER"``) и монотонно переводят его в
общий словарь ярлыков агрегатора. Дальше ``_ModuleAdapter._coerce_score``
берёт ветку ``label_map`` и возвращает ЯКОРЬ ярлыка — одно и то же число для
всех протоколов. Модуль при этом ИЗМЕРИЛ разницу (buffer_pct 56.25 против
100.0, health_factor 2.29 против inf) — и она пропадает по дороге. Снаружи
это неотличимо от слепого модуля, поэтому такие модули уезжали в разметку
слепоты и переставали исполняться вовсе.

Починить это в агрегаторе нельзя. Что означает `buffer_pct` и в какую сторону
он опаснее, знает ТОЛЬКО модуль; агрегатор, вздумавший коэрсить чужие
доменные поля в риск, начал бы выдумывать (ровно тот класс ложной коэрции,
который audit 2026-08-02 из него убрал вместе с generic ``value``). Поэтому
число отдаёт модуль, а этот помощник лишь следит, чтобы оно НЕ РАЗОШЛОСЬ с
ярлыком, который модуль уже объявил.

Устройство. Ярлыки лестницы модуля (от самого безопасного к самому опасному)
имеют якоря в общем ``LABEL_SCORE_MAP``. Полоса ярлыка — от середины отрезка
до якоря соседа-снизу до середины отрезка до якоря соседа-сверху; у крайних
ярлыков соответствующий край совпадает с якорем. Модуль передаёт положение
своей величины внутри СВОЕГО же порога (0.0 — безопасный край полосы, 1.0 —
опасный), и score линейно кладётся внутрь полосы.

Из этого следует ровно то, что нужно:

* score НИКОГДА не покидает полосу собственного ярлыка — грубый вердикт
  модуля остаётся в силе, число не может ему противоречить;
* внутри ярлыка различие, которое модуль измерил, доживает до агрегатора;
* новых значений в словарь ярлыков не добавляется, ``_SCORE_KEYS`` не растёт —
  вокабуляр агрегатора не трогается вовсе.

Fail-CLOSED: неизвестный ярлык, лестница не из словаря или немонотонные якоря
→ ``None``. Вызывающий модуль в этом случае отдаёт то же, что и раньше (один
ярлык) либо ``None`` — «не измерено» не превращается в «измерен ноль».

Только stdlib. Ничего не пишет.
"""
from __future__ import annotations

from typing import Optional, Sequence

__all__ = ["band_score"]


def band_score(label: str, position: float,
               ladder: Sequence[str]) -> Optional[float]:
    """Score 0-100 внутри полосы ``label``.

    Parameters
    ----------
    label : str
        Общий ярлык (из ``LABEL_SCORE_MAP``), который модуль уже объявил.
    position : float
        Положение измеренной величины внутри порога СВОЕГО ярлыка:
        ``0.0`` — безопасный край полосы, ``1.0`` — опасный. Значения вне
        ``[0, 1]`` подрезаются (модуль мог передать величину на границе).
    ladder : Sequence[str]
        Лестница общих ярлыков этого модуля, от безопасного к опасному.
        Якоря обязаны строго возрастать — иначе ``None``.

    Returns
    -------
    Optional[float]
        Число внутри полосы, либо ``None`` (fail-CLOSED).
    """
    # Импорт внутри функции: signal_aggregator тянет реестр модулей, а модули
    # тянут этот помощник — на уровне модуля это был бы цикл.
    from spa_core.analytics.signal_aggregator import LABEL_SCORE_MAP

    if not ladder:
        return None
    try:
        idx = list(ladder).index(label)
    except ValueError:
        return None

    anchors = []
    for name in ladder:
        anchor = LABEL_SCORE_MAP.get(name)
        if anchor is None:
            return None          # ярлык не из общего словаря — не судим
        anchors.append(float(anchor))

    # Лестница обязана быть монотонной: иначе «безопасный край» полосы мог бы
    # оказаться опаснее «опасного», и score противоречил бы ярлыку.
    for a, b in zip(anchors, anchors[1:]):
        if not b > a:
            return None

    try:
        pos = float(position)
    except (TypeError, ValueError):
        return None
    if pos != pos:               # NaN — величина не измерена
        return None
    pos = max(0.0, min(1.0, pos))

    anchor = anchors[idx]
    safe_edge = (anchor + anchors[idx - 1]) / 2.0 if idx > 0 else anchor
    risk_edge = ((anchor + anchors[idx + 1]) / 2.0
                 if idx + 1 < len(anchors) else anchor)

    score = safe_edge + pos * (risk_edge - safe_edge)
    return max(0.0, min(100.0, score))
