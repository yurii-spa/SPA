def prepare(
    title: str,
    body: str,
    card_id: str,
    *,
    card_name: str = "",
    now: Optional[datetime] = None,
    beacon_path: Optional[str | Path] = None,
) -> Prepared:
    """Собрать сообщение и клавиатуру. Текст уходит ВСЕГДА, кнопки — по условиям.

    Кнопок не будет, если:

    * в карточке не разобрано ни одного варианта (fail-CLOSED — не выдумываем выбор);
    * не жив бот, умеющий обработать нажатие (тот же маячок, что у алертов, ADR-069):
      нажатие по старому боту уходит в неизвестный ``act:``-глагол и ПЕРЕПИСЫВАЕТ
      сообщение панелью настроек, то есть стирает сам вопрос.

    Само уведомление при этом НЕ подавляется: решение владельца важнее украшений.
    """
    options = parse_options(body)
    pid = make_pid(card_id)
    # Клавиатуру решаем ПЕРВОЙ: текст обязан знать, будет ли кнопка, иначе он пообещает
    # несуществующее (замер 08.08 — решение с «Нажми кнопку» и без кнопок).
    keyboard = None
    if options:
        from spa_core.telegram import alert_actions

        # Спрашиваем СВОЁ умение (`act:od:`), а не «умеет ли бот кнопки под тревогой»:
        # до 17.08 решения гейтились отметкой `alert_actions`, которая к ним отношения
        # не имеет — разъедься обработчики, отправитель бы этого не заметил (#194).
        #
        # ПЕРЕХОДНОЕ послабление (снять после первого перезапуска бота с этим кодом):
        # работающий в проде долгожитель объявляет только `alert_actions`, а `act:od:`
        # при этом обрабатывает — обработчики приезжают одним коммитом. Без послабления
        # кнопки решений пропали бы до перезапуска, а перезапуск долгожителя — отдельный
        # цикл с `deployment_acceptance` (правило доставки, п. 6). Послабление гаснет
        # само: как только маячок объявит `owner_decisions`, вторая половина не нужна.
        if alert_actions.handler_available(
            now=now,
            beacon_path=beacon_path,
            capability=alert_actions.CAPABILITY_OWNER_DECISIONS,
            also_accept=(alert_actions.CAPABILITY,),
        ):
            keyboard = build_keyboard(pid, options)
    text = build_message(title, body, options, has_buttons=keyboard is not None,
                         card_name=card_name or card_id)
    return Prepared(pid=pid, text=text, keyboard=keyboard, options=options)


def _live_tracker_dir(override: Optional[str | Path] = None) -> Optional[Path]:
    """Каталог карточек ЖИВОГО дерева. ``None`` — писать туда сейчас нельзя.

    Под pytest — всегда ``None``, если корень не задан явно: правило «модуль с состоянием
    сам уводит тесты в сторону» (инцидент «тесты пишут в живое состояние алертов»)
    относится к карточкам ровно так же, как к журналу.
    """
    if override is not None:
        return Path(override) / "nimbalyst-local" / "tracker"
    if os.environ.get("PYTEST_CURRENT_TEST"):
        return None
    from spa_core.utils.live_paths import live_root

    return live_root(_REPO_ROOT) / "nimbalyst-local" / "tracker"


def materialize_card(card_path: Path,
                     *, live_root: Optional[str | Path] = None) -> Path:
    """Карточка в том дереве, где нажатие будет обработано. Никогда не бросает.

    Нажатие обрабатывает бот из ПРОД-дерева, а карточку почти всегда создаёт сессия в
    своём ``/tmp``-worktree и пушит на origin. Автосинк прод-дерева возит только
    ``spa_core/``·``scripts/``·``tests/`` — карточки не возит НИКТО.

    Замер 10.08: все четыре открытых решения владельца (в т.ч. «прод остановлен») есть на
    origin и нет в прод-дереве. Нажатие по такой кнопке возвращает «Карточка исчезла из
    трекера — ничего не записал», то есть кнопка декоративна. Журнал по этой же причине
    давно живёт в ЖИВОМ ``data/`` — карточку просто забыли перенести следом.

    Копируем ТОЛЬКО когда живой копии нет: существующая может нести ответ владельца
    (его оттуда забирает ``carry_owner_answer``, #178), и затирать её запрещено.
    """
    try:
        target_dir = _live_tracker_dir(live_root)
        if target_dir is None:
            return card_path
        target = target_dir / card_path.name
        if card_path.resolve() == target.resolve():
            return card_path
        if target.is_file():
            return target
        if not card_path.is_file():
            return card_path
        target_dir.mkdir(parents=True, exist_ok=True)
        atomic_save_text(card_path.read_text(encoding="utf-8"), str(target))
        return target
    except Exception:  # noqa: BLE001 — перенос не важнее самого уведомления
        return card_path


def prepare_push(
    card_path: str | Path,
    title: str,
    body: str,
    *,
    now: Optional[datetime] = None,
    beacon_path: Optional[str | Path] = None,
) -> Prepared:
    """То же сообщение, что уйдёт владельцу, но БЕЗ единой записи в живое состояние.

    Пара к :func:`register_push` и причина её существования: сухому прогону
    (``notify … --check``, тесты) нужен ровно текст, а регистрация ему не нужна —
    нажимать нечего, сообщение не ушло. До цикла #216 такой пары не было, поэтому
    ``--check`` шёл через ``register_push`` и оставлял в живом реестре решений
    владельца запись о карточке, которую никто не отправлял (замер #183: запись про
    карточку песочницы `/tmp/c183_probe/…`, которой больше не существует).

    Знание «как собрать сообщение ПО КАРТОЧКЕ» (``pid`` из имени файла, ``card_name``
    из него же) живёт здесь в одном экземпляре — иначе два вызова разошлись бы, и
    сухой прогон начал бы показывать не то, что уедет по-настоящему.
    """
    p = Path(card_path)
    return prepare(title, body, p.stem, card_name=p.name, now=now,
                   beacon_path=beacon_path)


# ── Анти-шторм отправок решений (инцидент 2026-08-20: 200+ копий одной карточки) ──
# Петля: сторож «вопрос НЕ ОТПРАВЛЕН» с предикатом, слепым к чужому дереву, каждый
# цикл «гасил» вопрос повторной отправкой. Журнал держит ОДНУ запись на pid (replace),
# поэтому шторм был невидим даже журналу. Правило: та же карточка БЕЗ ответа не
# уходит чаще раза в окно и не больше потолка попыток; сверх — тишина + WARNING.
# Потерять уведомление хуже, чем послать дважды, — но 20 копий подряд теряют КАНАЛ:
# владелец перестаёт читать. Ответ/снятие вопроса обнуляют счётчик (новая жизнь).
STORM_WINDOW_S = 6 * 3600      # повтор без ответа — не чаще раза в 6 часов
STORM_MAX_SENDS = 5            # и не больше 5 посылок без ответа суммарно


def throttle_state(
    card_id: str,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> tuple[bool, str]:
    """Можно ли СЕЙЧАС отправить решение по карточке. ``(allowed, причина_отказа)``.

    Fail-OPEN намеренно: нечитаемый журнал не смеет прятать вопрос владельцу —
    от шторма тогда защищает только дедуп отправителя (30 мин).
    """
    try:
        rec = _push_by_card_id(card_id, state_path=state_path)
        if not isinstance(rec, dict):
            return True, ""
        if rec.get("choice") or rec.get("withdrawn_at"):
            return True, ""  # вопрос закрыт — новая отправка это НОВАЯ жизнь карточки
        count = int(rec.get("send_count") or 1)
        if count >= STORM_MAX_SENDS:
            return False, (f"anti-storm: {count} посылок без ответа — потолок "
                           f"{STORM_MAX_SENDS}, дальше молчим (владелец уже видел)")
        dt = now or datetime.now(timezone.utc)
        try:
            last = datetime.fromisoformat(str(rec.get("pushed_at")))
        except Exception:  # noqa: BLE001 — битая метка не должна глушить вопрос
            return True, ""
        age_s = (dt - last).total_seconds()
        if 0 <= age_s < STORM_WINDOW_S:
            return False, (f"anti-storm: та же карточка уходила {int(age_s // 60)} мин "
                           f"назад без ответа — повтор не раньше, чем через "
                           f"{int(STORM_WINDOW_S // 3600)}ч")
        return True, ""
    except Exception:  # noqa: BLE001 — защита не важнее самого уведомления
        return True, ""


def register_push(
    card_path: str | Path,
    title: str,
    body: str,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
    beacon_path: Optional[str | Path] = None,
    live_root: Optional[str | Path] = None,
) -> Prepared:
    """Подготовить сообщение и запомнить карточку под её ``pid``.

    Журнал нужен, чтобы в момент нажатия (через час, через три дня) знать, ЧТО именно
    предлагалось: ``callback_data`` несёт только номер варианта, а текст варианта обязан
    попасть в карточку дословно. По той же причине в журнал уходит путь к карточке в
    ЖИВОМ дереве (см. :func:`materialize_card`): нажимать будет бот, а не мы.

    **Функция ПИШЕТ в живое состояние** (журнал + копия карточки в живой трекер) —
    звать её можно только тогда, когда сообщение действительно уходит. Сухому прогону
    предназначена :func:`prepare_push`.
    """
    p = Path(card_path)
    prep = prepare_push(card_path, title, body, now=now, beacon_path=beacon_path)
    dt = now or datetime.now(timezone.utc)
    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    live_card = materialize_card(p, live_root=live_root)
    prev = next((r for r in doc["pushes"]
                 if isinstance(r, dict) and r.get("pid") == prep.pid), None)
    # Счётчик посылок БЕЗ ответа: replace-семантика журнала прятала повторы
    # (инцидент 2026-08-20, 200+ копий) — теперь каждая перезапись его наращивает,
    # а ответ/снятие вопроса начинают счёт заново.
    send_count = 1
    if isinstance(prev, dict) and not (prev.get("choice") or prev.get("withdrawn_at")):
        try:
            send_count = int(prev.get("send_count") or 1) + 1
        except Exception:  # noqa: BLE001
            send_count = 2
    doc["pushes"] = [r for r in doc["pushes"] if r.get("pid") != prep.pid]
    doc["pushes"].append({
        "pid": prep.pid,
        "send_count": send_count,
        "card": str(live_card),
        "card_id": p.stem,
        "title": title,
        "pushed_at": dt.isoformat(),
        "options": [{"num": o.num, "label": o.label, "recommended": o.recommended}
                    for o in prep.options],
        # ИЗМЕРЕНО, а не предположено: уехали ли кнопки вместе с этим решением.
        # Без этой отметки вопрос «получил ли владелец кнопки?» неотвечаем задним числом.
        # 10.08 это и вышло: четыре решения (в т.ч. «прод остановлен») ушли в 04:13Z,
        # ближайший старт бота в логе — 04:22Z, а когда умер предыдущий экземпляр, не
        # записано нигде. Был ли маячок жив в момент отправки — установить УЖЕ НЕЧЕМ.
        "buttons": prep.keyboard is not None,
        "choice": None,
    })
    _save(doc, path_obj)
    return prep


def mark_withdrawn(
    card_path: str | Path,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> bool:
    """Погасить кнопки карточки: вопрос снят, нажимать больше нечего (цикл #172).

    Кнопка живёт в чате столько же, сколько сообщение, — то есть вечно. Без этой
    отметки нажатие через три дня записало бы «ответ владельца» в карточку, которую
    мост уже закрыл как ложную тревогу, и бот бодро ответил бы «записал». Отметку
    ставим на журнальной записи, а не на карточке: карточка к этому моменту `done`,
    и переписывать её ещё раз незачем.
    """
    p = Path(card_path)
    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    stamp = (now or datetime.now(timezone.utc)).isoformat()
    hit = False
    for rec in doc["pushes"]:
        if rec.get("card") == str(p) or rec.get("card_id") == p.stem:
            if not rec.get("choice"):  # ответ уже дан ⇒ вопрос не снимается
                rec["withdrawn_at"] = stamp
                hit = True
    if hit:
        _save(doc, path_obj)
    return hit


# ── до-доставка кнопок: решение уехало, пока бот лежал ───────────────────────
#
# Интерлок ADR-069 честен, но односторонен: маячок протух ⇒ кнопок нет, и на этом
# история заканчивается НАВСЕГДА. Сообщение уже в чате, второго шанса ему никто не
# даёт, а бот через несколько минут поднимается и молча умеет всё, чего не умел.
# Замер 10.08: четыре открытых решения владельца, включая «прод остановлен», отправлены
# в 04:13:56Z; ближайший START бота в логе — 04:22:19Z. Владелец в тот же день прислал
# в чат жалобу с приложенным текстом «⚠️ Кнопки сейчас недоступны — бот не подтвердил,
# что готов их обработать»: этот путь в проде срабатывает, и не по разу.
#
# Лечение поручено ТОМУ, кто и есть недостающее условие: бот, оживая, добирает кнопки
# к решениям, уехавшим без них. Fail-CLOSED в обе стороны:
#   * чиним только записи, где отсутствие кнопок ИЗМЕРЕНО (``buttons is False``);
#     «не измерено» (записи старее этой починки) не трогаем — молчание лучше дубля;
#   * отметку «починено» ставим ТОЛЬКО после успешной отправки — сорвавшаяся посылка
#     не имеет права сжечь единственный шанс.

HEAL_MAX_PER_RUN = 5  # подъём бота не должен превращаться в очередь из сообщений

HEAL_PREFIX = ("🔘 <b>Кнопки подъехали.</b> Это решение уже приходило текстом — тогда бот "
               "не мог обработать нажатие. Теперь может, жми кнопку.")


@dataclass(frozen=True)
class Heal:
    """Решение, которому не хватило кнопок, и готовое к отправке исправление."""

    pid: str
    card: str
    text: str
    keyboard: Dict


def buttonless_pushes(
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
    beacon_path: Optional[str | Path] = None,
    limit: int = HEAL_MAX_PER_RUN,
) -> List[Heal]:
    """Решения, уехавшие БЕЗ кнопок и всё ещё ждущие владельца. Никогда не бросает.

    Пусто — нормальный ответ (и обычный): либо всё уехало с кнопками, либо обработчика
    по-прежнему нет, либо владелец уже ответил.
    """
    from spa_core.owner_queue.queue import load_card

    out: List[Heal] = []
    try:
        doc = _load(_state_path(state_path))
    except Exception:  # noqa: BLE001 — битый журнал не роняет бота
        return out
    for rec in doc.get("pushes", []):
        if len(out) >= max(0, limit):
            break
        if not isinstance(rec, dict):
            continue
        if rec.get("buttons") is not False:
            continue  # кнопки были ИЛИ не измерено — оба случая не трогаем
        if rec.get("choice") or rec.get("withdrawn_at") or rec.get("buttons_fixed_at"):
            continue  # ответ дан / вопрос снят / уже чинили — нажимать нечего
        if not (rec.get("options") or []):
            continue  # вариантов нет — кнопкам неоткуда взяться (fail-CLOSED)
        path = Path(str(rec.get("card") or ""))
        try:
            card = load_card(path)
        except Exception:  # noqa: BLE001 — карточку могли переместить/удалить
            continue
        if card.status != "needs-owner":
            continue  # вопрос уже не на владельце
        try:
            prep = prepare(card.title or path.stem, card.body, path.stem,
                           card_name=path.name, now=now, beacon_path=beacon_path)
        except Exception:  # noqa: BLE001
            continue
        if prep.keyboard is None:
            continue  # обработчика всё ещё нет — чинить нечем, молчим
        out.append(Heal(pid=prep.pid, card=str(path),
                        text=HEAL_PREFIX + "\n\n" + prep.text,
                        keyboard=prep.keyboard))
    return out


#: Сколько сообщений одного решения помним. Их бывает больше одного законно: текст без
#: кнопок, потом до-доставка кнопок (`heal_buttonless`) — и ответить владелец может на
#: любое из них. Потолок нужен только чтобы запись не росла без края.
MESSAGE_IDS_MAX = 8


def message_id_of(result) -> Optional[int]:
    """``message_id`` из ответа Telegram API. ``None`` — его там нет.

    Принимает то, что реально возвращают отправители: полный ответ API
    (``{"ok": true, "result": {"message_id": 123, …}}``), уже развёрнутый ``result``,
    голое число — или ``None``/``False``, когда отправка не состоялась. Никогда не бросает:
    это наблюдение, и оно не имеет права уронить отправку.
    """
    if result is None or result is True or result is False:
        return None
    if isinstance(result, int):
        return int(result) or None
    if isinstance(result, dict):
        inner = result.get("result")
        if isinstance(inner, dict):
            mid = inner.get("message_id")
        else:
            mid = result.get("message_id")
        try:
            return int(mid) if mid not in (None, "") else None
        except (TypeError, ValueError):
            return None
    return None


def _remember_message_id(rec: Dict, message_id: Optional[int]) -> bool:
    """Запомнить сообщение чата, несущее это решение. ``True`` — запись изменилась.

    Копим СПИСОК, а не последнее: у одного решения законно бывает несколько сообщений
    (текст без кнопок + до-доставка кнопок), и ответить владелец может на любое.
    Затирать предыдущее значило бы снова терять адресата — ровно тот дефект, который
    эта запись и заводится лечить.
    """
    if message_id is None:
        return False
    ids = rec.get("message_ids")
    if not isinstance(ids, list):
        ids = []
    clean: List[int] = []
    for v in ids:
        try:
            iv = int(v)
        except (TypeError, ValueError):
            continue
        if iv not in clean:
            clean.append(iv)
    if message_id in clean:
        rec["message_ids"] = clean[-MESSAGE_IDS_MAX:]
        return False
    clean.append(int(message_id))
    rec["message_ids"] = clean[-MESSAGE_IDS_MAX:]
    return True


def mark_send_outcome(
    pid: str,
    *,
    ok: bool,
    message_id: Optional[int] = None,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> bool:
    """Записать ИСХОД отправки решения ``pid``. Никогда не бросает. Идемпотентна.

    Зачем она есть (замер цикла #309, задание владельца «кнопки так и не пришли»)
    ------------------------------------------------------------------------------
    ``register_push`` пишет ``buttons: true`` **ДО** отправки — там измеряется, собралась
    ли клавиатура, а не уехала ли она. Между этой записью и владельцем стоит
    ``guard_outbound``: лимит потока (12 сообщений в минуту НА ВСЕХ отправителей) и дедуп.
    Отправку он роняет молча, возвращая ``None``, — и запись остаётся утверждать, что
    кнопки доставлены.

    Цена этой полуправды измерена, а не предположена:

    * ``heal_buttonless`` чинит ТОЛЬКО записи с ``buttons is False`` («кнопки были ИЛИ не
      измерено — оба случая не трогаем») ⇒ решение, чьё сообщение не ушло ВОВСЕ, для
      починки невидимо навсегда;
    * ``owner_decision_pending`` и разбор жалоб читают тот же журнал и видят «отправлено
      с кнопками».

    Ровно так вопрос «получил ли владелец кнопки?» и оказывался неотвечаемым три цикла
    подряд (#215, #228, #229): журнал отвечал на СВОЙ вопрос («собрали ли мы клавиатуру?»)
    и читался как ответ на нужный.

    ``ok=False`` ставит ``buttons=False`` СОЗНАТЕЛЬНО и по букве поля («уехали ли кнопки
    вместе с этим решением»): не уехало ничего — значит и кнопки не уехали. Тем самым
    запись попадает под уже существующий штатный ремонт ``heal_buttonless``, и новой
    машинерии не заводится.
    """
    path_obj = _state_path(state_path)
    try:
        doc = _load(path_obj)
    except Exception:  # noqa: BLE001 — наблюдение не имеет права уронить отправку
        return False
    stamp = (now or datetime.now(timezone.utc)).isoformat()
    hit = False
    for rec in doc.get("pushes", []):
        if not isinstance(rec, dict) or rec.get("pid") != pid:
            continue
        rec["delivered"] = bool(ok)
        rec["delivered_checked_at"] = stamp
        # Адрес сообщения в чате — часть исхода отправки, а не украшение: ответ владельца
        # «Ответ 1» приходит РЕПЛАЕМ на конкретное сообщение, и без этой отметки узнать,
        # на какое именно, нечем ПО ПОСТРОЕНИЮ (замер 20.08: ни у одной из 38 записей
        # журнала message_id не было, и оба ответа владельца в тот день отвергнуты как
        # «неоднозначно» при 14 открытых вопросах).
        #
        # ТОЛЬКО при удачной отправке. Адрес сообщения, которого владелец не видел, —
        # это приглашение записать ответ на непоказанный вопрос; тот же класс fail-OPEN,
        # что и `buttons: true` до отправки, который эта функция и заводилась лечить.
        if ok:
            _remember_message_id(rec, message_id_of(message_id))
        if not ok:
            # Не уехало ничего ⇒ кнопок владелец не видел. Говорим это ИЗМЕРЕНИЕМ,
            # а не умолчанием: молчаливое `true` и есть чинимый дефект.
            rec["buttons"] = False
        hit = True
    if hit:
        try:
            _save(doc, path_obj)
        except Exception:  # noqa: BLE001
            return False
    return hit


def mark_buttons_delivered(
    pid: str,
    *,
    message_id: Optional[int] = None,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> bool:
    """Записать, что кнопки к решению ``pid`` всё-таки доставлены. Идемпотентно.

    ``message_id`` — адрес ДОСЛАННОГО сообщения. Оно отдельное и живёт в чате рядом с
    первым, поэтому запоминается в дополнение к нему, а не вместо: владелец видит две
    карточки одного вопроса и отвечает реплаем на ту, что под рукой.
    """
    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    stamp = (now or datetime.now(timezone.utc)).isoformat()
    hit = False
    for rec in doc.get("pushes", []):
        if isinstance(rec, dict) and rec.get("pid") == pid:
            rec["buttons"] = True
            rec["buttons_fixed_at"] = stamp
            _remember_message_id(rec, message_id_of(message_id))
            hit = True
    if hit:
        _save(doc, path_obj)
    return hit


def heal_buttonless(
    send,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
    beacon_path: Optional[str | Path] = None,
    limit: int = HEAL_MAX_PER_RUN,
) -> List[str]:
    """Дослать кнопки к решениям, уехавшим без них. Возвращает pid'ы починенных.

    ``send(text, keyboard)`` — отправитель вызывающего (бот остаётся единственной
    инстанцией, которая ходит в сеть); truthy — отправлено. Никогда не бросает:
    украшение не имеет права уронить бота.
    """
    fixed: List[str] = []
    try:
        for heal in buttonless_pushes(now=now, state_path=state_path,
                                      beacon_path=beacon_path, limit=limit):
            try:
                ok = send(heal.text, heal.keyboard)
            except Exception:  # noqa: BLE001 — одна неудача не прячет остальные
                ok = None
            if not ok:
                continue  # не отправилось ⇒ отметку не ставим, попробуем в следующий раз
            if mark_buttons_delivered(heal.pid, message_id=message_id_of(ok),
                                      now=now, state_path=state_path):
                fixed.append(heal.pid)
    except Exception:  # noqa: BLE001
        pass
    return fixed


def record_choice(
    pid: str,
    choice: str,
    actor_chat_id,
    *,
    owner_chat_id: Optional[str] = None,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> Dict:
    """Нажатие владельца: записать выбор в карточку. Никогда не бросает.

    Возвращает словарь с ``ok`` и ``reason``; отказ — это нормальный ответ, а не авария:
    сообщение владельцу должно быть человеческим при любом исходе.
    """
    from spa_core.owner_queue.owner_answer import NotTheOwner, record_owner_answer

    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    rec = None
    for r in reversed(doc["pushes"]):
        if r.get("pid") == pid:
            rec = r
            break
    if rec is None:
        return {"ok": False, "reason": "unknown_card"}
    if rec.get("withdrawn_at") and not rec.get("choice"):
        # Вопрос сняли до нажатия (находка исчезла) — записывать «решение владельца»
        # в закрытую карточку нельзя, но и молчать нельзя: ответ ниже это объясняет.
        return {"ok": False, "reason": "card_withdrawn", "card": rec.get("card")}

    opt = None
    for o in rec.get("options") or []:
        if str(o.get("num", "")).lower() == str(choice).lower():
            opt = o
            break
    if opt is None:
        return {"ok": False, "reason": "unknown_option", "card": rec.get("card")}

    card_path = Path(rec["card"])
    if not card_path.exists():
        return {"ok": False, "reason": "card_gone", "card": str(card_path)}

    try:
        res = record_owner_answer(
            card_path,
            choice_num=str(opt["num"]),
            choice_label=str(opt.get("label") or ""),
            actor_chat_id=actor_chat_id,
            owner_chat_id=owner_chat_id,
            now=now,
        )
    except NotTheOwner:
        return {"ok": False, "reason": "not_owner", "card": str(card_path)}
    except Exception as exc:  # noqa: BLE001 — сбой записи не имеет права ронять бота
        return {"ok": False, "reason": "write_failed", "detail": type(exc).__name__}

    rec["choice"] = str(opt["num"])
    rec["choice_label"] = str(opt.get("label") or "")
    rec["answered_at"] = res.get("answered_at")
    _save(doc, path_obj)
    return {"ok": True, "already": bool(res.get("already")), "card": str(card_path),
            "choice": str(opt["num"]), "label": str(opt.get("label") or "")}


# ── ответ владельцу после нажатия ────────────────────────────────────────────

# Причина отказа → фраза владельцу. Реестр, а не ветвление в коде: владелец в отпуске
# не смотрит логи, и «кнопка молча ничего не сделала» для него неотличимо от поломки.
_REASON_RU: Dict[str, str] = {
    "unknown_card": ("Не нашёл эту карточку — сообщение старое, и журнал её уже не помнит. "
                     "Открой актуальный список кнопкой ниже."),
    "unknown_option": "Такого варианта в этой карточке нет — ничего не записал.",
    "card_gone": "Карточка исчезла из трекера — ничего не записал.",
    "card_withdrawn": ("Этот вопрос уже снят: находка исчезла сама, тревога оказалась "
                       "ложной. Ничего не записал — отвечать не нужно."),
    "not_owner": "Это решение может принять только владелец — ничего не записал.",
    "write_failed": "Не смог записать решение. В карточке ничего не изменилось.",
}


def confirmation_text(result: Dict) -> str:
    """Человеческий ответ на нажатие. Любой исход — внятная фраза, без кодов ошибок."""
    if result.get("ok"):
        num = html.escape(str(result.get("choice", "")))
        label = html.escape(_capitalize(str(result.get("label") or "")))
        if result.get("already"):
            return (f"👌 Это решение уже записано: <b>вариант {num}</b> — {label}.\n"
                    f"Повторно ничего не менял.")
        return (f"✅ Записал: <b>вариант {num}</b> — {label}.\n"
                f"Карточка закрыта твоим решением, беру в работу.")
    reason = str(result.get("reason") or "")
    if reason.startswith("crash:"):
        return "⚠️ Сбой при записи решения. В карточке ничего не изменилось."
    return "⚠️ " + _REASON_RU.get(reason, "Не смог записать решение — ничего не изменилось.")


# ── ответ владельца ТЕКСТОМ («Ответ 1») ──────────────────────────────────────
#
# Обещание даёт сам этот модуль: когда кнопок нет, ``build_message`` пишет владельцу
# «⚠️ Кнопки сейчас недоступны — бот не подтвердил, что готов их обработать. **Ответь
# номером варианта в чат, я разберу.**» Разбирать было НЕЧЕМ: ни одна строка кода не
# читала текстовый ответ, и сообщение уходило в общий классификатор — то есть решение
# владельца превращалось в обычную inbox-задачу и не исполнялось ничем.
#
# Замер в проде (журнал отправок + карточки инбокса): владелец сделал ровно то, что ему
# велели, ДВАЖДЫ — 10.08 (пожаловался, приложив этот самый текст) и 12.08 (прислал
# процитированную тревогу и строку «Ответ 1»). Оба раза родилась inbox-карточка
# `inbox-zadacha-*`, и оба раза никто не записал выбор. Это тот же класс, что #172:
# «у одобрения владельца нет исполнителя» — обещание, у которого нет кода.
#
# Инвариант #14 НЕ ослаблен. ``queue.set_status`` по-прежнему отказывает агенту, а запись
# идёт единственным owner-путём ``owner_answer.record_owner_answer``, который сверяет
# личность ВНУТРИ писателя. Сообщение в личном чате владельца — такое же его действие,
# как нажатие кнопки; канал другой, решение то же.
#
# Fail-CLOSED во всех сомнительных случаях: не угадываем ни карточку, ни вариант. Отказ
# ВСЕГДА называется вслух владельцу — молчаливый отказ здесь неотличим от поломки, а
# именно на этом мы уже теряли его ответы.

#: Номер варианта, как его пишут карточки: «1», «12», «А1», «Б2», «B1».
_OPT_TOKEN = r"[0-9]{1,2}|[A-Za-zА-Яа-яЁё][0-9]{1,2}"
_OPT_LIST = rf"(?:{_OPT_TOKEN})(?:\s*(?:и|,|\+|/)\s*(?:{_OPT_TOKEN}))*"

# «Ответ 1» / «вариант: Б2» / «выбираю 1 и 3» — ОТДЕЛЬНОЙ строкой. Требование строки
# целиком (а не вхождения) — защита от захвата обычной речи: «сделай 2 отчёта» и
# «вариант 2 мне не нравится, поясни» ответом не являются и разбираться должны как всегда.
_ANSWER_LINE_RE = re.compile(
    rf"^[\s>*_]*(?:мой\s+)?(?:ответ|отвечаю|вариант|варианты|выбираю|беру|решение)"
    rf"\s*[:\-—–]?\s*({_OPT_LIST})[\s.!)]*$",
    re.IGNORECASE | re.MULTILINE,
)
# Сообщение, которое целиком есть номер варианта: «1», «1 и 3», «Б2».
_BARE_ANSWER_RE = re.compile(rf"^\s*({_OPT_LIST})[\s.!)]*$", re.IGNORECASE)
# Имя карточки из процитированной тревоги: «📄 owner-decision-….md».
_CARD_NAME_RE = re.compile(r"([a-z0-9][a-z0-9._-]{6,})\.md", re.IGNORECASE)
# Мягкая форма ТОЛЬКО для ответа реплаем: «1. Одобрить», «2) Отклонить», «ответ 1 —
# одобряю». Номер главный, слова после — эхо подписи кнопки (владелец переписывает её
# руками, с опечатками: живой случай 20.08 «1. Ободрить» → классификатор спросил
# «кого подбодрить?»). Вне реплая форма НЕ принимается: без точного адресата хвост
# из слов делает догадку, а не ответ.
_LENIENT_REPLY_RE = re.compile(
    rf"^\s*(?:ответ\s*[:#-]?\s*)?({_OPT_TOKEN})\s*[.)\]:—-]?\s+\S", re.IGNORECASE)


def parse_reply_choice(text: str) -> Optional[str]:
    """Номер варианта из мягкой формы «N. <слова>» — только для reply-привязки."""
    if not text:
        return None
    m = _LENIENT_REPLY_RE.match(str(text))
    return m.group(1) if m else None


_OPT_SPLIT_RE = re.compile(r"\s*(?:и|,|\+|/)\s*", re.IGNORECASE)


@dataclass(frozen=True)
class ParsedTextAnswer:
    """Что удалось ВЫЧИТАТЬ из сообщения владельца. Ничего не додумано."""

    nums: Tuple[str, ...]           # номера вариантов, как написал владелец
    card_id: Optional[str]          # карточка, если владелец процитировал её имя
    raw: str                        # строка, распознанная как ответ (для отчёта)


def parse_text_answer(text: str) -> Optional[ParsedTextAnswer]:
    """Ответ ли это на карточку решения. ``None`` — не ответ (разбирает обычный путь).

    Распознаём ДВЕ формы, обе — строка целиком, а не вхождение в речь:

    * явную — «Ответ 1», «вариант: Б2», «выбираю 1 и 3»;
    * голую — сообщение состоит ровно из номера («1»).

    Имя карточки берём из процитированной тревоги («📄 <имя>.md»), если оно есть:
    владелец часто отвечает, переслав сообщение целиком, и тогда адресат ответа известен
    точно, а не угадан по «последнему открытому».
    """
    raw = str(text or "").replace(" ", " ")
    if not raw.strip():
        return None
    hit = None
    for m in _ANSWER_LINE_RE.finditer(raw):
        hit = m  # последняя строка-ответ: владелец мог процитировать тревогу с «Варианты:»
    if hit is None:
        m = _BARE_ANSWER_RE.match(raw)
        if m is None:
            return None
        hit = m
    nums = tuple(p for p in _OPT_SPLIT_RE.split(hit.group(1).strip()) if p)
    if not nums:
        return None
    card = None
    for cm in _CARD_NAME_RE.finditer(raw):
        card = cm.group(1)  # последнее упоминание — имя карточки печатается в конце тревоги
    return ParsedTextAnswer(nums=nums, card_id=card, raw=hit.group(0).strip())


def card_still_asks(card_path: str | Path) -> bool:
    """Спрашивает ли карточка владельца ПРЯМО СЕЙЧАС — по её собственному статусу.

    Асимметрия намеренная и в одну сторону: закрытой карточка считается только тогда,
    когда её статус ПРОЧИТАН и он не из открытых (`queue._OPEN_STATUSES`). Не прочитали
    статус, файла нет, разбор упал — вопрос остаётся ОТКРЫТЫМ. Потерять вопрос владельца
    дороже, чем показать лишний: первое молча, второе он видит и может поправить.
    """
    try:
        from spa_core.owner_queue.queue import _OPEN_STATUSES, load_card

        status = (load_card(card_path).status or "").strip()
    except Exception:  # noqa: BLE001 — нечитаемая карточка НЕ закрывает вопрос
        return True
    if not status:
        return True
    return status in _OPEN_STATUSES


def open_pushes(*, state_path: Optional[str | Path] = None) -> List[Dict]:
    """Отправленные решения, которые ещё ждут владельца. Свежие — первыми.

    «Ждут» = ответа нет, вопрос не снят, карточка на диске ЕСТЬ **и она всё ещё
    спрашивает** (её статус — открытый). Предпоследнее важно: отвечать на исчезнувшую
    карточку нечем, и такой ответ обязан быть отказан, а не записан в соседнюю.

    Почему статус карточки спрашивается ОТДЕЛЬНО от журнала (замер 20.08, цикл #318)
    ------------------------------------------------------------------------------
    Журнал знает ровно те ответы, которые пришли ЧЕРЕЗ НЕГО — кнопкой или текстом. Любое
    другое закрытие (цикл инжестировал `owner-done`, мост закрыл находку, карточку
    удалили) для него невидимо, и запись остаётся «ждущей» НАВСЕГДА. Счёт открытых
    вопросов из-за этого только растёт и никогда не убывает.

    Цена измерена в тот же день, обе половины настоящие:

    * владельцу отказали в его же ответе «Ответ 1» как «неоднозначно **при 14 открытых**»
      — из тех 14 одиннадцать были УЖЕ ЗАКРЫТЫ (`ingested`), а четыре не имели файла;
      живых вопросов было три;
    * его решение «пришлите вопросы заново, по одному» (вариант 2, 11:04Z), исполненное
      по этому счёту, отправило бы 14 сообщений, 11 из них — о решённом. Это ровно тот
      поток одинаковых сообщений, на который он жаловался дважды (09.08 и 13.08).

    Отказ при неоднозначности НЕ ослаблен: он по-прежнему срабатывает на любых двух
    живых кандидатах. Честнее стал только их СПИСОК.
    """
    doc = _load(_state_path(state_path))
    out: List[Dict] = []
    for rec in reversed(doc.get("pushes") or []):
        if rec.get("choice") or rec.get("withdrawn_at"):
            continue
        card = rec.get("card")
        if not card or not Path(card).exists():
            continue
        if not card_still_asks(card):
            continue
        out.append(rec)
    return out


def _push_by_card_id(card_id: str, *, state_path: Optional[str | Path] = None) -> Optional[Dict]:
    """Запись журнала по имени карточки (с ``.md`` или без). Последняя — свежая."""
    stem = str(card_id or "").strip()
    if stem.lower().endswith(".md"):
        stem = stem[:-3]
    if not stem:
        return None
    doc = _load(_state_path(state_path))
    for rec in reversed(doc.get("pushes") or []):
        if str(rec.get("card_id") or "") == stem:
            return rec
    return None


def _push_by_message_id(
    message_id: Optional[int], *, state_path: Optional[str | Path] = None,
) -> Optional[Dict]:
    """Запись журнала по адресу сообщения в чате. ``None`` — совпадения нет.

    Совпадение ТОЧНОЕ и потому не является угадыванием: владелец физически указал на
    сообщение, ответив на него реплаем. Это единственный источник адресата, который не
    зависит ни от порядка вопросов, ни от их количества.
    """
    if message_id is None:
        return None
    try:
        mid = int(message_id)
    except (TypeError, ValueError):
        return None
    doc = _load(_state_path(state_path))
    for rec in reversed(doc.get("pushes") or []):
        if not isinstance(rec, dict):
            continue
        ids = rec.get("message_ids")
        if not isinstance(ids, list):
            continue
        for v in ids:
            try:
                if int(v) == mid:
                    return rec
            except (TypeError, ValueError):
                continue
    return None


def _last_answered_push(*, state_path: Optional[str | Path] = None) -> Optional[Dict]:
    """Последнее решение, на которое владелец УЖЕ ответил. ``None`` — таких нет."""
    doc = _load(_state_path(state_path))
    for rec in reversed(doc.get("pushes") or []):
        if rec.get("choice"):
            return rec
    return None


def resolve_text_answer(
    text: str,
    actor_chat_id,
    *,
    owner_chat_id: Optional[str] = None,
    reply_to_message_id: Optional[int] = None,
    state_path: Optional[str | Path] = None,
    now: Optional[datetime] = None,
) -> Optional[Dict]:
    """Текстовый ответ владельца → запись решения в карточку. Никогда не бросает.

    ``None`` — сообщение ответом не является; обычный разбор (вопрос/задача/непонятно)
    работает как работал. Словарь — сообщение РАЗОБРАНО как ответ: либо решение записано
    (``ok=True``), либо честно отказано с названной причиной (``ok=False``).

    Ничего не угадываем: нет однозначного адресата — отказ, а не «похоже, это про неё».
    """
    try:
        parsed = parse_text_answer(text)
    except Exception:  # noqa: BLE001 — разбор не имеет права уронить бота
        return None
    if parsed is None:
        # Мягкая форма («1. Одобрить», любые слова/опечатки после номера) — ТОЛЬКО
        # когда адресат известен ТОЧНО, по реплаю на нашу отправку (живой случай
        # 20.08: «1. Ободрить» ушло в классификатор вместо записи решения).
        lenient = parse_reply_choice(text)
        if lenient is None or reply_to_message_id is None:
            return None
        if _push_by_message_id(reply_to_message_id, state_path=state_path) is None:
            return None
        parsed = ParsedTextAnswer(nums=(lenient,), card_id=None, raw=str(text).strip())

    if len(parsed.nums) > 1:
        # «1 и 3» — карточка могла и правда разрешать несколько, но записать можно
        # ровно один вариант. Выбрать за владельца первый значило бы решить за него.
        return {"ok": False, "reason": "multiple_choices",
                "nums": list(parsed.nums), "card_id": parsed.card_id}
    num = parsed.nums[0]

    # Реплай владельца — САМЫЙ точный из адресов, и потому спрашивается первым.
    #
    # Замер 20.08 (эта починка): владелец дважды прислал «Ответ 1» (11:08 и 11:16), и оба
    # раза ответ отвергнут как `ambiguous` — открытых решений было 14. Адресат при этом
    # был известен Телеграму ТОЧНО, но недостижим нам по построению: бот не читал
    # `reply_to_message` вовсе, а в журнале отправок не было ни одного `message_id`.
    #
    # Подсказка работает ТОЛЬКО в плюс: совпало — адресат известен точно, не совпало —
    # ниже работает ровно тот же разбор, что и раньше, слово в слово. Отвечать реплаем на
    # постороннее сообщение владелец вправе, и это не должно делать ответ ХУЖЕ, чем без
    # реплая. Отказ при неоднозначности не ослаблен: он просто перестал быть единственным
    # исходом там, где точный ответ существовал.
    rec = _push_by_message_id(reply_to_message_id, state_path=state_path)
    resolved_by = "reply_to" if rec is not None else None

    if rec is not None:
        pass
    elif parsed.card_id:
        rec = _push_by_card_id(parsed.card_id, state_path=state_path)
        if rec is None:
            # Ровно случай 12.08: владелец процитировал тревогу и ответил «1», а карточки
            # `owner-decision-sait-packages-astro-…` нет ни в трекере, ни в журнале —
            # ответ применять НЕ К ЧЕМУ. Молчать нельзя: владелец считает, что ответил.
            return {"ok": False, "reason": "card_unknown", "card_id": parsed.card_id}
    else:
        candidates = open_pushes(state_path=state_path)
        if not candidates:
            # Владелец мог просто повторить свой ответ (из другого чата, после
            # переотправки). Открытых вопросов нет — но сказать ему «не понял, к чему
            # это» значит соврать: понял, и записано. Сверяем с последним ОТВЕЧЕННЫМ
            # и только при совпадении номера — угадывать по одному лишь порядку нельзя.
            last = _last_answered_push(state_path=state_path)
            if last is not None and str(last.get("choice") or "").lower() == num.lower():
                return {"ok": False, "reason": "already_answered",
                        "card_id": last.get("card_id"), "choice": last.get("choice"),
                        "label": last.get("choice_label"), "title": last.get("title")}
            return {"ok": False, "reason": "no_open_decision"}
        if len(candidates) > 1:
            return {"ok": False, "reason": "ambiguous",
                    "candidates": [{"card_id": c.get("card_id"), "title": c.get("title")}
                                   for c in candidates[:5]],
                    "candidates_total": len(candidates)}
        rec = candidates[0]

    if rec.get("choice"):
        return {"ok": False, "reason": "already_answered", "card_id": rec.get("card_id"),
                "choice": rec.get("choice"), "label": rec.get("choice_label"),
                "title": rec.get("title")}

    result = record_choice(rec["pid"], num, actor_chat_id,
                           owner_chat_id=owner_chat_id, now=now, state_path=state_path)
    result.setdefault("card_id", rec.get("card_id"))
    result.setdefault("title", rec.get("title"))
    result["via"] = "text"
    # ЧЕМ определён адресат — отдельным полем, а не подменой ``via``: канал остался
    # текстовым (это влияет на запись в карточку), изменился только способ узнать, к чему
    # ответ относится. Слить их в одно значило бы сделать вопрос «как мы поняли адресата»
    # неотвечаемым задним числом — тем самым, на котором мы и стояли.
    if resolved_by:
        result["resolved_by"] = resolved_by
    if not result.get("ok"):
        result.setdefault("nums", [num])
    return result


#: Отказы, после которых слова владельца обязаны быть СОХРАНЕНЫ (вопрос остался открыт).
#: «Уже отвечено» сюда не входит: там ничего не теряется.
PRESERVE_ON_REFUSAL = frozenset({
    "card_unknown", "ambiguous", "no_open_decision", "multiple_choices",
    "unknown_option", "unknown_card", "card_gone", "card_withdrawn", "write_failed",
})

_TEXT_REASON_RU: Dict[str, str] = {
    "no_open_decision": ("Сейчас у меня нет ни одного открытого вопроса к тебе — не понял, "
                         "к чему относится ответ. Ничего не записал."),
    "multiple_choices": ("В ответе несколько номеров, а записать я могу ровно один вариант — "
                         "выбирать за тебя не буду. Ответь одним номером. Сообщение сохранил."),
}


def text_answer_reply(result: Dict) -> str:
    """Человеческий ответ на текстовый ответ владельца. Любой исход — внятная фраза."""
    if result.get("ok"):
        return confirmation_text(result)
    reason = str(result.get("reason") or "")
    if reason == "card_unknown":
        name = html.escape(str(result.get("card_id") or ""))
        return ("⚠️ Ответ принял, но применить его НЕ К ЧЕМУ: карточки "
                f"<code>{name}</code> нет ни в трекере, ни в журнале отправок — "
                "сообщение старое, а карточка не сохранилась.\n"
                "Ничего не записал. Сообщение сохранил, разберу циклом и вернусь с "
                "актуальным вопросом.")
    if reason == "ambiguous":
        cands = result.get("candidates") or []
        lines = ["⚠️ Открытых вопросов сейчас несколько — не понял, к какому относится "
                 "ответ, и угадывать не стал. Ничего не записал.", ""]
        for c in cands:
            lines.append(f"• <code>{html.escape(str(c.get('card_id') or ''))}</code> — "
                         f"{html.escape(_shorten(str(c.get('title') or ''), 70))}")
        total = int(result.get("candidates_total") or len(cands))
        if total > len(cands):
            lines.append(f"…и ещё {total - len(cands)}")
        lines += ["", "Ответь кнопкой под нужным решением или пришли имя карточки вместе "
                      "с номером."]
        return "\n".join(lines)
    if reason == "already_answered":
        num = html.escape(str(result.get("choice") or ""))
        label = html.escape(_capitalize(str(result.get("label") or "")))
        return (f"👌 На эту карточку ответ уже записан: <b>вариант {num}</b> — {label}.\n"
                f"Повторно ничего не менял.")
    if reason in _TEXT_REASON_RU:
        return "⚠️ " + _TEXT_REASON_RU[reason]
    return confirmation_text(result)


def pending_decisions(
    *,
    tracker_dir: Optional[str | Path] = None,
    state_path: Optional[str | Path] = None,
    now: Optional[datetime] = None,
    register: bool = True,
) -> List[Dict]:
    """Открытые решения владельца (``needs-owner``), готовые к показу в меню.

    Заодно РЕГИСТРИРУЕТ их в журнале: экран списка — самостоятельный вход, владелец мог
    ни одного пуша не получить (бот лежал, связи не было). Без регистрации pid из списка
    не с чем сопоставить, и кнопка на экране оказалась бы мёртвой.

    Никогда не бросает: сломанный трекер не имеет права уронить меню.
    """
    try:
        from spa_core.owner_queue.queue import list_cards

        kwargs = {"tracker_type": "owner-decision", "status": "needs-owner"}
        if tracker_dir is not None:
            kwargs["tracker_dir"] = tracker_dir
        cards = list(list_cards(**kwargs))
    except Exception:  # noqa: BLE001
        return []

    out: List[Dict] = []
    for card in cards:
        try:
            options = parse_options(card.body)
            pid = make_pid(card.path.stem)
            if register:
                register_push(card.path, card.title or card.path.stem, card.body,
                              now=now, state_path=state_path,
                              beacon_path=None)
            out.append({"pid": pid, "title": card.title or card.path.stem,
                        "card": str(card.path), "options": options})
        except Exception:  # noqa: BLE001 — одна кривая карточка не прячет остальные
            continue
    return out


def card_details(
    pid: str,
    *,
    limit: int = 3500,
    state_path: Optional[str | Path] = None,
) -> str:
    """Карточка целиком, человеческим текстом (кнопка «Подробнее»).

    Разметку снимаем: владельцу едет текст, а не звёздочки. Режем по лимиту Telegram —
    сообщение длиннее 4096 просто не доставляется, и кнопка выглядит сломанной.
    """
    rec = find_push(pid, state_path=state_path)
    if rec is None:
        return "⚠️ " + _REASON_RU["unknown_card"]
    path = Path(rec.get("card") or "")
    try:
        raw = path.read_text(encoding="utf-8")
    except Exception:  # noqa: BLE001 — карточку могли переместить/переименовать
        return "⚠️ " + _REASON_RU["card_gone"]
    # Frontmatter владельцу не нужен — это служебное.
    body = raw.split("---", 2)[2] if raw.startswith("---") and raw.count("---") >= 2 else raw
    text = _plain(body).strip()
    head = f"📖 <b>{html.escape(str(rec.get('title') or path.stem))}</b>\n\n"
    room = max(0, limit - len(head))
    if len(text) > room:
        text = text[:room].rstrip() + "…"
    return head + html.escape(text)
