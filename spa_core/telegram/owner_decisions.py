# ── Живая копия карточки ОТСТАЛА от источника правды ─────────────────────────
#
# **Замер 21.08 (циклы #332/#333).** `own-33-plist-marker-for-cycle-origin` стоял перед
# владельцем без кнопок с 20.08 и был отправлен ЧЕТЫРЕ раза — каждый раз честно без
# кнопок. Причина не в разборе: варианты в карточке ЕСТЬ, но только на `origin/main`
# (цикл #321 переписал вопрос перечнем «Вариант 1 / Вариант 2» в 19:53Z — через 52
# минуты после отправки в 19:01Z). Бот шлёт из ПРОД-дерева, а каталог очереди туда не
# возит никто (автосинк возит `spa_core/`·`scripts/`·`tests/`, #193), поэтому в живом
# дереве до сих пор лежала версия прозой, где вариантов нет.
#
# **Почему это не лечилось уже написанным.** `materialize_card` копирует карточку в
# живое дерево ТОЛЬКО когда её там нет: существующая может нести ответ владельца, и
# затирать её запрещено (#178). `parse_options` отказывается видеть варианты там, где
# их нет, — и отказ верен (ADR-075: выдумывать владельцу выбор запрещено). Оба правила
# правы поодиночке, а вместе давали состояние БЕЗ ЛЕКАРСТВА: одно не даёт скопировать,
# другое не даёт собрать кнопки. Циклом #332 причина стала измеряться и называться
# (`buttonless_reason.CODE_STALE_VS_ORIGIN`) — видимой, но не вылеченной.
#
# **Что здесь решено, и это решение ИЗМЕРЯЕМОЕ, а не умолчание.** При расхождении живой
# копии и ref побеждает ref — но только когда ДОКАЗАНО, что терять нечего. Все четыре
# условия обязаны выполниться, любое «не измерено» ⇒ не трогаем (fail-CLOSED в сторону
# сохранения живой копии, потому что цена ошибки здесь несимметрична: потерянный ответ
# владельца невосстановим, а лишний цикл без кнопок — нет):
#
# 1. в живой копии НЕТ следа ответа владельца (`read_answer_fields` пуст);
# 2. статус живой копии — `needs-owner` (вопрос всё ещё на владельце);
# 3. на ref карточка есть, разбирается, статус тот же `needs-owner`, следа ответа нет;
# 4. тело на ref строго богаче В ТОМ ИЗМЕРЕНИИ, которое лечим: там варианты
#    разбираются, здесь — ни одного.
#
# Условие 4 нарочно узкое. «Тело на ref длиннее» или «ref новее по дате» открыли бы
# перезапись живой копии в случаях, где терять как раз есть что, — а класс аварии,
# который мы чиним, ровно один и опознаётся точно.
#
# Перед самой записью текст живой копии перечитывается и сверяется с прочитанным на
# шаге 1: между проверкой и записью владелец мог нажать кнопку, и запись поверх его
# ответа была бы ровно той аварией, от которой защищает запрет #178.

#: Статус карточки, при котором вопрос всё ещё стоит перед владельцем.
NEEDS_OWNER_STATUS = "needs-owner"

REFRESH_DONE = "refreshed_from_ref"        # живая копия обновлена с ref
REFRESH_NOT_STALE = "not_stale"            # ref не богаче — обновлять нечего
REFRESH_OWNER_ANSWER = "owner_answer_present"   # есть след ответа — НЕ трогаем
REFRESH_STATUS = "status_not_needs_owner"  # вопрос уже не на владельце
REFRESH_ABSENT_ON_REF = "absent_on_ref"    # на ref карточки нет — сверять не с чем
REFRESH_RACE = "changed_under_us"          # копия изменилась между проверкой и записью
REFRESH_UNMEASURED = "unmeasured"          # сверка не выполнилась. НЕ «всё в порядке»


def _refresh_verdict(code: str, detail: str, path: Path) -> dict:
    return {"verdict": code, "detail": detail, "path": str(path),
            "measured": code != REFRESH_UNMEASURED}


def refresh_live_copy_from_ref(card_path: str | Path, *,
                               ref: str = "origin/main") -> dict:
    """Обновить копию карточки с ``ref`` — ТОЛЬКО когда доказано, что терять нечего.

    Возвращает вердикт словарём (``verdict`` + ``detail``); **никогда не бросает** —
    перенос не важнее самого уведомления, и упасть здесь значило бы потерять вопрос
    владельцу целиком.

    Полный разбор оснований — в комментарии над функцией. Коротко: пишем поверх живой
    копии только если в ней нет ни следа ответа владельца, ни закрытого статуса, а на
    ``ref`` лежит та же карточка в том же статусе, где варианты разбираются, а здесь —
    ни одного.
    """
    from spa_core.owner_queue.owner_answer import read_answer_fields
    from spa_core.owner_queue.queue import load_card_text

    p = Path(card_path)
    try:
        local_text = p.read_text(encoding="utf-8")
    except OSError as exc:
        return _refresh_verdict(REFRESH_UNMEASURED,
                                f"живая копия не прочитана: {exc}", p)
    try:
        if read_answer_fields(local_text):
            return _refresh_verdict(
                REFRESH_OWNER_ANSWER,
                "в живой копии есть след ответа владельца — перезапись запрещена (#178)",
                p)
        local = load_card_text(local_text, p.name, path=p)
    except Exception as exc:  # noqa: BLE001 — сторож не роняет отправку
        return _refresh_verdict(REFRESH_UNMEASURED,
                                f"живая копия не разобралась: {exc}", p)
    if str(local.status or "").strip() != NEEDS_OWNER_STATUS:
        return _refresh_verdict(
            REFRESH_STATUS,
            f"статус живой копии `{local.status}` — вопрос уже не на владельце", p)

    try:
        from spa_core.owner_queue.origin_view import card_sources

        texts, sha = card_sources(p.parent, [p.stem], ref=ref)
    except Exception as exc:  # noqa: BLE001 — включая Unmeasured
        return _refresh_verdict(REFRESH_UNMEASURED,
                                f"сверка с `{ref}` не выполнилась: {exc}", p)
    raw = texts.get(p.stem)
    short = (sha or "?")[:9]
    if raw is None:
        return _refresh_verdict(REFRESH_ABSENT_ON_REF,
                                f"на `{ref}` ({short}) карточки нет — сверять не с чем", p)
    try:
        if read_answer_fields(raw):
            return _refresh_verdict(
                REFRESH_OWNER_ANSWER,
                f"на `{ref}` ({short}) у карточки есть след ответа владельца — это "
                f"перенос следа (`carry_owner_answer`), а не обновление вопроса", p)
        remote = load_card_text(raw, p.name, path=p)
    except Exception as exc:  # noqa: BLE001
        return _refresh_verdict(REFRESH_UNMEASURED,
                                f"карточка на `{ref}` ({short}) не разобралась: {exc}", p)
    if str(remote.status or "").strip() != NEEDS_OWNER_STATUS:
        return _refresh_verdict(
            REFRESH_STATUS,
            f"статус на `{ref}` ({short}) — `{remote.status}`, вопрос там уже закрыт", p)

    remote_options = parse_options(remote.body or "")
    if not remote_options or parse_options(local.body or ""):
        return _refresh_verdict(
            REFRESH_NOT_STALE,
            f"на `{ref}` ({short}) вариантов {len(remote_options)}, в живой копии "
            f"{len(parse_options(local.body or ''))} — ref не богаче, обновлять нечего", p)

    # Перечитываем ПЕРЕД записью: между проверкой и записью владелец мог нажать кнопку.
    try:
        if p.read_text(encoding="utf-8") != local_text:
            return _refresh_verdict(
                REFRESH_RACE,
                "живая копия изменилась между проверкой и записью — не трогаем", p)
        atomic_save_text(raw, str(p))
    except Exception as exc:  # noqa: BLE001
        return _refresh_verdict(REFRESH_UNMEASURED,
                                f"запись живой копии не выполнилась: {exc}", p)
    nums = ", ".join(str(o.num) for o in remote_options)
    return _refresh_verdict(
        REFRESH_DONE,
        f"живая копия обновлена с `{ref}` ({short}): вариантов было 0, стало "
        f"{len(remote_options)} ({nums}); следа ответа владельца в ней не было", p)


def materialize_card(card_path: Path,
                     *, live_root: Optional[str | Path] = None) -> Path:
    """Карточка в том дереве, где нажатие будет обработано. Никогда не бросает.

    Нажатие обрабатывает бот из ПРОД-дерева, а карточку почти всегда создаёт сессия в
    своём ``/tmp``-worktree и пушит на origin. Автосинк прод-дерева возит только
    ``spa_core/``·``scripts/``·``tests/`` — карточки не возит НИКТО.

    Замер 10.08: все четыре открытых решения владельца (в т.ч. «прод остановлен») есть на
    origin и нет в прод-дереве. Нажатие по такой кнопке возвращает «Карточка исчезла из
    трекера — ничего не записал», то есть кнопка декоративна. Журнал по этой же причине
    давно живёт в ЖИВОМ ``data/`` — карточку просто забыли перенести следом.

    Копируем ТОЛЬКО когда живой копии нет: существующая может нести ответ владельца
    (его оттуда забирает ``carry_owner_answer``, #178), и затирать её запрещено.

    Существующая при этом может и ОТСТАВАТЬ от источника правды — тогда владельца
    четвёртый раз спрашивают по копии без вариантов. Это лечит
    :func:`refresh_live_copy_from_ref`, и лечит узко: пишет поверх только когда
    доказано, что терять нечего. Запрет выше не ослаблен — он и есть первое из
    четырёх условий там.
    """
    try:
        target_dir = _live_tracker_dir(live_root)
        if target_dir is None:
            return card_path
        target = target_dir / card_path.name
        if card_path.resolve() == target.resolve():
            return card_path
        if target.is_file():
            refresh_live_copy_from_ref(target)
            return target
        if not card_path.is_file():
            return card_path
        target_dir.mkdir(parents=True, exist_ok=True)
        atomic_save_text(card_path.read_text(encoding="utf-8"), str(target))
        return target
    except Exception:  # noqa: BLE001 — перенос не важнее самого уведомления
        return card_path


def prepare_push(
    card_path: str | Path,
    title: str,
    body: str,
    *,
    now: Optional[datetime] = None,
    beacon_path: Optional[str | Path] = None,
) -> Prepared:
    """То же сообщение, что уйдёт владельцу, но БЕЗ единой записи в живое состояние.

    Пара к :func:`register_push` и причина её существования: сухому прогону
    (``notify … --check``, тесты) нужен ровно текст, а регистрация ему не нужна —
    нажимать нечего, сообщение не ушло. До цикла #216 такой пары не было, поэтому
    ``--check`` шёл через ``register_push`` и оставлял в живом реестре решений
    владельца запись о карточке, которую никто не отправлял (замер #183: запись про
    карточку песочницы `/tmp/c183_probe/…`, которой больше не существует).

    Знание «как собрать сообщение ПО КАРТОЧКЕ» (``pid`` из имени файла, ``card_name``
    из него же) живёт здесь в одном экземпляре — иначе два вызова разошлись бы, и
    сухой прогон начал бы показывать не то, что уедет по-настоящему.
    """
    p = Path(card_path)
    # Право на подтверждение меряется ЗДЕСЬ, где есть путь к файлу: `prepare` чистая
    # и в git не ходит. Отказ сверки — молчание, а не подтверждение (fail-CLOSED).
    allow_ack, _why = ack_allowed(p, body)
    return prepare(title, body, p.stem, card_name=p.name, now=now,
                   beacon_path=beacon_path, allow_ack=allow_ack)


# ── Анти-шторм отправок решений (инцидент 2026-08-20: 200+ копий одной карточки) ──
# Петля: сторож «вопрос НЕ ОТПРАВЛЕН» с предикатом, слепым к чужому дереву, каждый
# цикл «гасил» вопрос повторной отправкой. Журнал держит ОДНУ запись на pid (replace),
# поэтому шторм был невидим даже журналу. Правило: та же карточка БЕЗ ответа не
# уходит чаще раза в окно и не больше потолка попыток; сверх — тишина + WARNING.
# Потерять уведомление хуже, чем послать дважды, — но 20 копий подряд теряют КАНАЛ:
# владелец перестаёт читать. Ответ/снятие вопроса обнуляют счётчик (новая жизнь).
STORM_WINDOW_S = 6 * 3600      # повтор без ответа — не чаще раза в 6 часов
STORM_MAX_SENDS = 5            # и не больше 5 посылок без ответа суммарно


def throttle_state(
    card_id: str,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> tuple[bool, str]:
    """Можно ли СЕЙЧАС отправить решение по карточке. ``(allowed, причина_отказа)``.

    Fail-OPEN намеренно: нечитаемый журнал не смеет прятать вопрос владельцу —
    от шторма тогда защищает только дедуп отправителя (30 мин).
    """
    try:
        rec = _push_by_card_id(card_id, state_path=state_path)
        if not isinstance(rec, dict):
            return True, ""
        if rec.get("choice") or rec.get("withdrawn_at"):
            return True, ""  # вопрос закрыт — новая отправка это НОВАЯ жизнь карточки
        count = int(rec.get("send_count") or 1)
        if count >= STORM_MAX_SENDS:
            return False, (f"anti-storm: {count} посылок без ответа — потолок "
                           f"{STORM_MAX_SENDS}, дальше молчим (владелец уже видел)")
        dt = now or datetime.now(timezone.utc)
        try:
            last = datetime.fromisoformat(str(rec.get("pushed_at")))
        except Exception:  # noqa: BLE001 — битая метка не должна глушить вопрос
            return True, ""
        age_s = (dt - last).total_seconds()
        if 0 <= age_s < STORM_WINDOW_S:
            return False, (f"anti-storm: та же карточка уходила {int(age_s // 60)} мин "
                           f"назад без ответа — повтор не раньше, чем через "
                           f"{int(STORM_WINDOW_S // 3600)}ч")
        return True, ""
    except Exception:  # noqa: BLE001 — защита не важнее самого уведомления
        return True, ""


def register_push(
    card_path: str | Path,
    title: str,
    body: str,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
    beacon_path: Optional[str | Path] = None,
    live_root: Optional[str | Path] = None,
) -> Prepared:
    """Подготовить сообщение и запомнить карточку под её ``pid``.

    Журнал нужен, чтобы в момент нажатия (через час, через три дня) знать, ЧТО именно
    предлагалось: ``callback_data`` несёт только номер варианта, а текст варианта обязан
    попасть в карточку дословно. По той же причине в журнал уходит путь к карточке в
    ЖИВОМ дереве (см. :func:`materialize_card`): нажимать будет бот, а не мы.

    **Функция ПИШЕТ в живое состояние** (журнал + копия карточки в живой трекер) —
    звать её можно только тогда, когда сообщение действительно уходит. Сухому прогону
    предназначена :func:`prepare_push`.
    """
    p = Path(card_path)
    prep = prepare_push(card_path, title, body, now=now, beacon_path=beacon_path)
    dt = now or datetime.now(timezone.utc)
    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    live_card = materialize_card(p, live_root=live_root)
    prev = next((r for r in doc["pushes"]
                 if isinstance(r, dict) and r.get("pid") == prep.pid), None)
    # Счётчик посылок БЕЗ ответа: replace-семантика журнала прятала повторы
    # (инцидент 2026-08-20, 200+ копий) — теперь каждая перезапись его наращивает,
    # а ответ/снятие вопроса начинают счёт заново.
    send_count = 1
    if isinstance(prev, dict) and not (prev.get("choice") or prev.get("withdrawn_at")):
        try:
            send_count = int(prev.get("send_count") or 1) + 1
        except Exception:  # noqa: BLE001
            send_count = 2
    doc["pushes"] = [r for r in doc["pushes"] if r.get("pid") != prep.pid]
    doc["pushes"].append({
        "pid": prep.pid,
        "send_count": send_count,
        "card": str(live_card),
        "card_id": p.stem,
        "title": title,
        "pushed_at": dt.isoformat(),
        "options": [{"num": o.num, "label": o.label, "recommended": o.recommended}
                    for o in prep.options],
        # Кнопки были ПОДТВЕРЖДЕНИЕМ поручения, а не выбором варианта. Отдельно от
        # `options` (тот по контракту — только вычитанное из карточки) и отдельно от
        # `buttons` («кнопки уехали»): три разных факта, и склеивать их нельзя.
        "ack": bool(prep.ack),
        # ИЗМЕРЕНО, а не предположено: уехали ли кнопки вместе с этим решением.
        # Без этой отметки вопрос «получил ли владелец кнопки?» неотвечаем задним числом.
        # 10.08 это и вышло: четыре решения (в т.ч. «прод остановлен») ушли в 04:13Z,
        # ближайший старт бота в логе — 04:22Z, а когда умер предыдущий экземпляр, не
        # записано нигде. Был ли маячок жив в момент отправки — установить УЖЕ НЕЧЕМ.
        "buttons": prep.keyboard is not None,
        "choice": None,
    })
    _save(doc, path_obj)
    return prep


def mark_withdrawn(
    card_path: str | Path,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> bool:
    """Погасить кнопки карточки: вопрос снят, нажимать больше нечего (цикл #172).

    Кнопка живёт в чате столько же, сколько сообщение, — то есть вечно. Без этой
    отметки нажатие через три дня записало бы «ответ владельца» в карточку, которую
    мост уже закрыл как ложную тревогу, и бот бодро ответил бы «записал». Отметку
    ставим на журнальной записи, а не на карточке: карточка к этому моменту `done`,
    и переписывать её ещё раз незачем.
    """
    p = Path(card_path)
    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    stamp = (now or datetime.now(timezone.utc)).isoformat()
    hit = False
    for rec in doc["pushes"]:
        if rec.get("card") == str(p) or rec.get("card_id") == p.stem:
            if not rec.get("choice"):  # ответ уже дан ⇒ вопрос не снимается
                rec["withdrawn_at"] = stamp
                hit = True
    if hit:
        _save(doc, path_obj)
    return hit


# ── до-доставка кнопок: решение уехало, пока бот лежал ───────────────────────
#
# Интерлок ADR-069 честен, но односторонен: маячок протух ⇒ кнопок нет, и на этом
# история заканчивается НАВСЕГДА. Сообщение уже в чате, второго шанса ему никто не
# даёт, а бот через несколько минут поднимается и молча умеет всё, чего не умел.
# Замер 10.08: четыре открытых решения владельца, включая «прод остановлен», отправлены
# в 04:13:56Z; ближайший START бота в логе — 04:22:19Z. Владелец в тот же день прислал
# в чат жалобу с приложенным текстом «⚠️ Кнопки сейчас недоступны — бот не подтвердил,
# что готов их обработать»: этот путь в проде срабатывает, и не по разу.
#
# Лечение поручено ТОМУ, кто и есть недостающее условие: бот, оживая, добирает кнопки
# к решениям, уехавшим без них. Fail-CLOSED в обе стороны:
#   * чиним только записи, где отсутствие кнопок ИЗМЕРЕНО (``buttons is False``);
#     «не измерено» (записи старее этой починки) не трогаем — молчание лучше дубля;
#   * отметку «починено» ставим ТОЛЬКО после успешной отправки — сорвавшаяся посылка
#     не имеет права сжечь единственный шанс.

HEAL_MAX_PER_RUN = 5  # подъём бота не должен превращаться в очередь из сообщений

HEAL_PREFIX = ("🔘 <b>Кнопки подъехали.</b> Это решение уже приходило текстом — тогда бот "
               "не мог обработать нажатие. Теперь может, жми кнопку.")


@dataclass(frozen=True)
class Heal:
    """Решение, которому не хватило кнопок, и готовое к отправке исправление."""

    pid: str
    card: str
    text: str
    keyboard: Dict
    #: Варианты, СОБРАННЫЕ СЕЙЧАС, — их же несут досылаемые кнопки. Журнал обязан
    #: узнать о них вместе с кнопками: иначе нажатие ищет вариант в снимке момента
    #: отправки, где его нет, и владелец получает «такого варианта нет».
    options: List[ParsedOption] = field(default_factory=list)
    #: Досылка — подтверждение поручения, а не выбор варианта.
    ack: bool = False


def _heal_prepare(path: Path, *, now: Optional[datetime],
                  beacon_path: Optional[str | Path]):
    """Карточка с диска + собранное по ней сообщение. ``None`` — читать нечего.

    Отдельной функцией, потому что читать её приходится ДВАЖДЫ: второй раз — после
    обновления живой копии с ref. Повторять четыре строки на месте значило бы
    получить два слегка разных чтения одной карточки, а расхождение здесь стоит
    владельцу нажатия.
    """
    from spa_core.owner_queue.queue import load_card

    try:
        card = load_card(path)
    except Exception:  # noqa: BLE001 — карточку могли переместить/удалить
        return None
    if card.status != "needs-owner":
        return None  # вопрос уже не на владельце
    try:
        allow_ack, _why = ack_allowed(path, card.body)
        prep = prepare(card.title or path.stem, card.body, path.stem,
                       card_name=path.name, now=now, beacon_path=beacon_path,
                       allow_ack=allow_ack)
    except Exception:  # noqa: BLE001
        return None
    return card, prep


def buttonless_pushes(
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
    beacon_path: Optional[str | Path] = None,
    limit: int = HEAL_MAX_PER_RUN,
) -> List[Heal]:
    """Решения, уехавшие БЕЗ кнопок и всё ещё ждущие владельца. Никогда не бросает.

    Пусто — нормальный ответ (и обычный): либо всё уехало с кнопками, либо обработчика
    по-прежнему нет, либо владелец уже ответил.
    """
    out: List[Heal] = []
    try:
        doc = _load(_state_path(state_path))
    except Exception:  # noqa: BLE001 — битый журнал не роняет бота
        return out
    for rec in doc.get("pushes", []):
        if len(out) >= max(0, limit):
            break
        if not isinstance(rec, dict):
            continue
        if rec.get("buttons") is not False:
            continue  # кнопки были ИЛИ не измерено — оба случая не трогаем
        if rec.get("choice") or rec.get("withdrawn_at") or rec.get("buttons_fixed_at"):
            continue  # ответ дан / вопрос снят / уже чинили — нажимать нечего
        # Вариантов в ЗАПИСИ намеренно НЕ спрашиваем. Запись — снимок момента
        # отправки, а вопрос здесь стоит про СЕГОДНЯ: карточка законно получает
        # варианты уже после того, как уехала без них (замер 21.08: `own-33`
        # дописан через 52 минуты после доставки). Судя по замороженному снимку,
        # ремонт объявлял такую запись нечинимой НАВСЕГДА — fail-CLOSED, который
        # уже никогда не открывается обратно. Спрашиваем тело карточки —
        # `_heal_prepare` ниже: нет вариантов или нет обработчика ⇒
        # `keyboard is None` ⇒ мы всё равно молчим. Отказ тот же, основание —
        # измеренное сейчас, а не запомненное тогда.
        #
        # Тело живой копии при этом источником правды НЕ является: очередь живёт
        # на `origin/main`, а сюда её не возит никто (#193). Поэтому «вариантов
        # нет» здесь — ещё не ответ, и ниже он перепроверяется по ref.
        path = Path(str(rec.get("card") or ""))
        got = _heal_prepare(path, now=now, beacon_path=beacon_path)
        if got is None:
            continue
        card, prep = got
        if prep.keyboard is None and not parse_options(card.body or ""):
            # Живая копия могла ОТСТАТЬ от источника правды: каталог очереди в
            # прод-дерево не возит никто (#193), и вариантов здесь нет ровно
            # потому, что их дописали уже после того, как копия сюда попала.
            # Лекарство есть (#339) — но до УЖЕ доставленного вопроса оно не
            # доезжало: `notify` по нему больше не пойдёт (звать владельца ради
            # своей же недоставки запрещено, ADR-084), а ремонт спрашивал только
            # копию и получал честный отказ о ней. Спрашиваем ref здесь, где
            # чинится ЭТА запись, — иначе вылечится следующая, а эта висит.
            #
            # Цена платится только на БОЛЬНОМ пути: варианты разбираются ⇒
            # `keyboard is None` про обработчика, а не про тело, и git мы не
            # трогаем вовсе. Все четыре условия безопасности (следа ответа
            # владельца нет · статус `needs-owner` · та же карточка на ref ·
            # ref богаче ИМЕННО вариантами) остаются ВНУТРИ
            # `refresh_live_copy_from_ref`: копия с ответом владельца не
            # перезаписывается ни при каком расхождении.
            if refresh_live_copy_from_ref(path).get("verdict") == REFRESH_DONE:
                got = _heal_prepare(path, now=now, beacon_path=beacon_path)
                if got is None:
                    continue
                card, prep = got
        if prep.keyboard is None:
            continue  # обработчика всё ещё нет — чинить нечем, молчим
        out.append(Heal(pid=prep.pid, card=str(path),
                        text=HEAL_PREFIX + "\n\n" + prep.text,
                        keyboard=prep.keyboard,
                        options=list(prep.options), ack=prep.ack))
    return out


#: Сколько сообщений одного решения помним. Их бывает больше одного законно: текст без
#: кнопок, потом до-доставка кнопок (`heal_buttonless`) — и ответить владелец может на
#: любое из них. Потолок нужен только чтобы запись не росла без края.
MESSAGE_IDS_MAX = 8


def message_id_of(result) -> Optional[int]:
    """``message_id`` из ответа Telegram API. ``None`` — его там нет.

    Принимает то, что реально возвращают отправители: полный ответ API
    (``{"ok": true, "result": {"message_id": 123, …}}``), уже развёрнутый ``result``,
    голое число — или ``None``/``False``, когда отправка не состоялась. Никогда не бросает:
    это наблюдение, и оно не имеет права уронить отправку.
    """
    if result is None or result is True or result is False:
        return None
    if isinstance(result, int):
        return int(result) or None
    if isinstance(result, dict):
        inner = result.get("result")
        if isinstance(inner, dict):
            mid = inner.get("message_id")
        else:
            mid = result.get("message_id")
        try:
            return int(mid) if mid not in (None, "") else None
        except (TypeError, ValueError):
            return None
    return None


def _remember_message_id(rec: Dict, message_id: Optional[int]) -> bool:
    """Запомнить сообщение чата, несущее это решение. ``True`` — запись изменилась.

    Копим СПИСОК, а не последнее: у одного решения законно бывает несколько сообщений
    (текст без кнопок + до-доставка кнопок), и ответить владелец может на любое.
    Затирать предыдущее значило бы снова терять адресата — ровно тот дефект, который
    эта запись и заводится лечить.
    """
    if message_id is None:
        return False
    ids = rec.get("message_ids")
    if not isinstance(ids, list):
        ids = []
    clean: List[int] = []
    for v in ids:
        try:
            iv = int(v)
        except (TypeError, ValueError):
            continue
        if iv not in clean:
            clean.append(iv)
    if message_id in clean:
        rec["message_ids"] = clean[-MESSAGE_IDS_MAX:]
        return False
    clean.append(int(message_id))
    rec["message_ids"] = clean[-MESSAGE_IDS_MAX:]
    return True


def mark_send_outcome(
    pid: str,
    *,
    ok: bool,
    message_id: Optional[int] = None,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> bool:
    """Записать ИСХОД отправки решения ``pid``. Никогда не бросает. Идемпотентна.

    Зачем она есть (замер цикла #309, задание владельца «кнопки так и не пришли»)
    ------------------------------------------------------------------------------
    ``register_push`` пишет ``buttons: true`` **ДО** отправки — там измеряется, собралась
    ли клавиатура, а не уехала ли она. Между этой записью и владельцем стоит
    ``guard_outbound``: лимит потока (12 сообщений в минуту НА ВСЕХ отправителей) и дедуп.
    Отправку он роняет молча, возвращая ``None``, — и запись остаётся утверждать, что
    кнопки доставлены.

    Цена этой полуправды измерена, а не предположена:

    * ``heal_buttonless`` чинит ТОЛЬКО записи с ``buttons is False`` («кнопки были ИЛИ не
      измерено — оба случая не трогаем») ⇒ решение, чьё сообщение не ушло ВОВСЕ, для
      починки невидимо навсегда;
    * ``owner_decision_pending`` и разбор жалоб читают тот же журнал и видят «отправлено
      с кнопками».

    Ровно так вопрос «получил ли владелец кнопки?» и оказывался неотвечаемым три цикла
    подряд (#215, #228, #229): журнал отвечал на СВОЙ вопрос («собрали ли мы клавиатуру?»)
    и читался как ответ на нужный.

    ``ok=False`` ставит ``buttons=False`` СОЗНАТЕЛЬНО и по букве поля («уехали ли кнопки
    вместе с этим решением»): не уехало ничего — значит и кнопки не уехали. Тем самым
    запись попадает под уже существующий штатный ремонт ``heal_buttonless``, и новой
    машинерии не заводится.
    """
    path_obj = _state_path(state_path)
    try:
        doc = _load(path_obj)
    except Exception:  # noqa: BLE001 — наблюдение не имеет права уронить отправку
        return False
    stamp = (now or datetime.now(timezone.utc)).isoformat()
    hit = False
    for rec in doc.get("pushes", []):
        if not isinstance(rec, dict) or rec.get("pid") != pid:
            continue
        rec["delivered"] = bool(ok)
        rec["delivered_checked_at"] = stamp
        # Адрес сообщения в чате — часть исхода отправки, а не украшение: ответ владельца
        # «Ответ 1» приходит РЕПЛАЕМ на конкретное сообщение, и без этой отметки узнать,
        # на какое именно, нечем ПО ПОСТРОЕНИЮ (замер 20.08: ни у одной из 38 записей
        # журнала message_id не было, и оба ответа владельца в тот день отвергнуты как
        # «неоднозначно» при 14 открытых вопросах).
        #
        # ТОЛЬКО при удачной отправке. Адрес сообщения, которого владелец не видел, —
        # это приглашение записать ответ на непоказанный вопрос; тот же класс fail-OPEN,
        # что и `buttons: true` до отправки, который эта функция и заводилась лечить.
        if ok:
            _remember_message_id(rec, message_id_of(message_id))
        if not ok:
            # Не уехало ничего ⇒ кнопок владелец не видел. Говорим это ИЗМЕРЕНИЕМ,
            # а не умолчанием: молчаливое `true` и есть чинимый дефект.
            rec["buttons"] = False
        hit = True
    if hit:
        try:
            _save(doc, path_obj)
        except Exception:  # noqa: BLE001
            return False
    return hit


def mark_buttons_delivered(
    pid: str,
    *,
    message_id: Optional[int] = None,
    options: Optional[List[ParsedOption]] = None,
    ack: Optional[bool] = None,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> bool:
    """Записать, что кнопки к решению ``pid`` всё-таки доставлены. Идемпотентно.

    ``message_id`` — адрес ДОСЛАННОГО сообщения. Оно отдельное и живёт в чате рядом с
    первым, поэтому запоминается в дополнение к нему, а не вместо: владелец видит две
    карточки одного вопроса и отвечает реплаем на ту, что под рукой.

    ``options`` — варианты, которые несут ДОСЛАННЫЕ кнопки. Без них журнал остаётся
    снимком момента первой отправки, и нажатие по свежедосланной кнопке отвечает
    «Такого варианта в этой карточке нет». Замер (цикл #338, ровно сценарий `own-33`
    от 21.08): пуш без вариантов → карточка получает их через 52 минуты → досылка
    рисует кнопки «1»/«2» → нажатие `unknown_option`. Кнопка, ведущая в никуда, —
    это ровно та жалоба владельца, ради которой досылку и писали. ``None`` — не
    трогать (совместимость с вызовами, которые про варианты ничего не знают).
    """
    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    stamp = (now or datetime.now(timezone.utc)).isoformat()
    hit = False
    for rec in doc.get("pushes", []):
        if isinstance(rec, dict) and rec.get("pid") == pid:
            rec["buttons"] = True
            rec["buttons_fixed_at"] = stamp
            if options is not None:
                rec["options"] = [{"num": o.num, "label": o.label,
                                   "recommended": o.recommended} for o in options]
            if ack is not None:
                rec["ack"] = bool(ack)
            _remember_message_id(rec, message_id_of(message_id))
            hit = True
    if hit:
        _save(doc, path_obj)
    return hit


def heal_buttonless(
    send,
    *,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
    beacon_path: Optional[str | Path] = None,
    limit: int = HEAL_MAX_PER_RUN,
) -> List[str]:
    """Дослать кнопки к решениям, уехавшим без них. Возвращает pid'ы починенных.

    ``send(text, keyboard)`` — отправитель вызывающего (бот остаётся единственной
    инстанцией, которая ходит в сеть); truthy — отправлено. Никогда не бросает:
    украшение не имеет права уронить бота.
    """
    fixed: List[str] = []
    try:
        for heal in buttonless_pushes(now=now, state_path=state_path,
                                      beacon_path=beacon_path, limit=limit):
            try:
                ok = send(heal.text, heal.keyboard)
            except Exception:  # noqa: BLE001 — одна неудача не прячет остальные
                ok = None
            if not ok:
                continue  # не отправилось ⇒ отметку не ставим, попробуем в следующий раз
            if mark_buttons_delivered(heal.pid, message_id=message_id_of(ok),
                                      options=heal.options, ack=heal.ack,
                                      now=now, state_path=state_path):
                fixed.append(heal.pid)
    except Exception:  # noqa: BLE001
        pass
    return fixed


def record_choice(
    pid: str,
    choice: str,
    actor_chat_id,
    *,
    owner_chat_id: Optional[str] = None,
    now: Optional[datetime] = None,
    state_path: Optional[str | Path] = None,
) -> Dict:
    """Нажатие владельца: записать выбор в карточку. Никогда не бросает.

    Возвращает словарь с ``ok`` и ``reason``; отказ — это нормальный ответ, а не авария:
    сообщение владельцу должно быть человеческим при любом исходе.
    """
    from spa_core.owner_queue.owner_answer import NotTheOwner, record_owner_answer

    path_obj = _state_path(state_path)
    doc = _load(path_obj)
    rec = None
    for r in reversed(doc["pushes"]):
        if r.get("pid") == pid:
            rec = r
            break
    if rec is None:
        return {"ok": False, "reason": "unknown_card"}
    if rec.get("withdrawn_at") and not rec.get("choice"):
        # Вопрос сняли до нажатия (находка исчезла) — записывать «решение владельца»
        # в закрытую карточку нельзя, но и молчать нельзя: ответ ниже это объясняет.
        return {"ok": False, "reason": "card_withdrawn", "card": rec.get("card")}

    from spa_core.owner_queue.owner_answer import KIND_ACK, KIND_OPTION

    # Подтверждение поручения резолвится КОНСТАНТОЙ, а не журналом. Журнал — снимок
    # момента отправки, а «Принято»/«Не надо» не зависят от содержимого карточки
    # вовсе: кнопка либо была нарисована (и тогда её нарисовали мы, по правилу
    # `offers_ack`), либо владелец её не увидит. Привязка к записи здесь дала бы
    # ровно ту поломку, что уже есть у вариантов: досланные `heal_buttonless`
    # кнопки не обновляют `options`, и нажатие отвечает «такого варианта нет».
    ack_choice = str(choice).lower() if str(choice).lower() in ACK_LABELS else None
    kind = KIND_OPTION
    if ack_choice:
        opt = {"num": ack_choice, "label": ACK_LABELS[ack_choice]}
        kind = KIND_ACK
    else:
        opt = None
        for o in rec.get("options") or []:
            if str(o.get("num", "")).lower() == str(choice).lower():
                opt = o
                break
    if opt is None:
        return {"ok": False, "reason": "unknown_option", "card": rec.get("card")}

    card_path = Path(rec["card"])
    if not card_path.exists():
        return {"ok": False, "reason": "card_gone", "card": str(card_path)}

    try:
        res = record_owner_answer(
            card_path,
            choice_num=str(opt["num"]),
            choice_label=str(opt.get("label") or ""),
            actor_chat_id=actor_chat_id,
            owner_chat_id=owner_chat_id,
            kind=kind,
            now=now,
        )
    except NotTheOwner:
        return {"ok": False, "reason": "not_owner", "card": str(card_path)}
    except Exception as exc:  # noqa: BLE001 — сбой записи не имеет права ронять бота
        return {"ok": False, "reason": "write_failed", "detail": type(exc).__name__}

    rec["choice"] = str(opt["num"])
    rec["choice_label"] = str(opt.get("label") or "")
    rec["answered_at"] = res.get("answered_at")
    _save(doc, path_obj)
    return {"ok": True, "already": bool(res.get("already")), "card": str(card_path),
            "choice": str(opt["num"]), "label": str(opt.get("label") or ""),
            "kind": kind}


