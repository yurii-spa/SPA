# ── разбор вариантов из тела карточки ────────────────────────────────────────

# Заголовки секции «что от тебя нужно» — те же, что понимает queue.first_instruction_line,
# плюс английские варианты. Список ОДИН на модуль: разойдутся — разъедется и разбор.
_NEED_HEADINGS = (
    "## что от тебя нужно",
    "## инструкц",
    "## instruction",
    "## what",
)

# `* **Вариант 1 (рекомендую) — перезаполнять освободившийся бюджет.** …`
# `- **Вариант B — оставить как есть.** …`
# Номер — цифра или одна буква (встречается «Вариант А/Б»). Тире — любое из трёх.
# Форма со словом «Вариант». Суть может стоять ВНУТРИ жирного после тире…
#     * **Вариант 1 (рекомендую) — перезаполнять освободившийся бюджет.** Текст…
# …а может и ЗА его пределами, когда в жирном только пометка:
#     - **Вариант 1 (рекомендую).** НЕ заводить третий paper-трек и НЕ создавать агента…
# Обе формы живые (замер по 76 карточкам), поэтому хвост после `**` тоже забираем.
#
# Маркер списка НЕОБЯЗАТЕЛЕН, а разделитель — не только тире (замер 10.08 по журналу
# отправок: из 21 карточки ДЕСЯТЬ уехали владельцу без единой кнопки, и НИ НА ОДНУ из
# этих десяти он не ответил — при том что каждая карточка с кнопками хоть иногда, но
# отвечена). Две из десяти — не «карточка без выбора», а именно непрочитанный выбор:
#   * `owner-decision-reshenie-adr-070-p-6…` — `**Вариант A (рекомендую) — …**` отдельным
#     абзацем, БЕЗ `- ` в начале строки; прежний якорь `^\s*[*\-+]\s+` её не видел;
#   * `owner-decision-sistema-ostanovlena-avariinym-vyklyuchat` — `- **Вариант А (⭐
#     рекомендую): …**`, где суть отделена ДВОЕТОЧИЕМ, а не тире.
# Вторая держала остановленную систему: владелец в отъезде отвечает кнопкой, кнопок не
# было — и остановка стояла. Разделитель и маркер — оформление; выбор владельца от них
# не зависит и пропадать по ним не должен.
#
# Метка варианта бывает и СОСТАВНОЙ — «А1», «Б2»: так метит варианты карточка, где решений
# несколько (буква — решение, цифра — вариант внутри него). Составная форма стоит в
# альтернативе ПЕРВОЙ: иначе `[A-Za-zА-Яа-я]` возьмёт одну букву и споткнётся о цифру, а
# строка целиком окажется неразобранной — ровно так «Вариант А1» и был невидим 10.08.
_OPTION_RE = re.compile(
    r"^\s*(?:[*\-+]\s+)?\*\*\s*(?:вариант|option)\s+"
    r"(?P<num>[A-Za-zА-Яа-я]\d{1,2}|\d{1,2}[A-Za-zА-Яа-я]|\d{1,2}|[A-Za-zА-Яа-я])\s*"
    r"(?P<paren>\([^)]*\))?\s*"
    r"(?:[—–:-]\s*(?P<label>.+?))?"
    r"\s*\.?\s*\*\*"
    r"(?P<tail>.*)$",
    re.IGNORECASE,
)

# Первое предложение хвоста — суть варианта. Дальше идут обоснования («Почему рекомендую…»),
# которым на кнопке не место.
_FIRST_SENTENCE_RE = re.compile(r"^(.+?)(?:\.\s|\.$|$)", re.DOTALL)

# Вторая — и на деле САМАЯ ЧАСТАЯ — форма: нумерованный список, где вариант выделен жирным.
#     1. **Довести правило до конца (рекомендую).** Убрать подстановку…
#     2. **Оставить как есть**, но тогда честно записать…
# Замер по 76 живым карточкам решений: нумерованная форма — 69 строк в 23 карточках,
# «* **Вариант N — …**» — 44 строки в 15. Поддерживать только вторую значило бы оставить
# без кнопок большинство карточек ровно тогда, когда владелец на них рассчитывает.
#
# Голый «* **Текст**» (34 строки в 13 карточках) НАМЕРЕННО не разбирается: этой же формой
# пишут обычные пояснения внутри секции, и выдуманный вариант — ровно то, что запрещает
# ADR-075. Такая карточка приходит без кнопок; это видно сразу и лечится карточкой.
# Жирное выделение НЕ обязательно: живая карточка про табличку честности пишет
# «4. Оставить как есть — но тогда надо понимать…» простым текстом, и такой вариант
# молча пропадал. Спрятать существующий выбор ХУЖЕ, чем не показать кнопок вовсе:
# владелец видит три кнопки там, где карточка предлагает четыре, и не узнаёт об этом.
_OPTION_NUMBERED_RE = re.compile(
    r"^\s*(?P<num>\d{1,2})[.)]\s+\*\*\s*(?P<label>.+?)\s*\*\*",
    re.DOTALL,
)

# Тот же нумерованный список, но БЕЗ жирного. Отдельной регуляркой, а не веткой в первой:
# альтернатива внутри одного выражения перехватывала жирные строки целиком (замерено —
# подпись превращалась в «**Довести правило…** Убрать подстановку…»). Отрицательный
# просмотр вперёд гарантирует, что жирную форму разбирает ТОЛЬКО первая регулярка.
_OPTION_PLAIN_RE = re.compile(
    r"^\s*(?P<num>\d{1,2})[.)]\s+(?!\*\*)(?P<plain>\S.*)$",
)

# Пометка рекомендации живёт не только в заголовке варианта: карточки пишут
# «⭐ **Рекомендация агента:** …» ВНУТРИ абзаца варианта. Смотреть только на заголовок —
# значит потерять звёздочку там, где автор её поставил.
_RECOMMEND_INLINE_RE = re.compile(r"⭐|рекомендац|рекомендую|recommend", re.IGNORECASE)

# «можно взять несколько» / «не исключают друг друга» — карточка допускает НЕСКОЛЬКО
# ответов. Одна кнопка, закрывающая карточку, исказила бы такой вопрос: владелец выбрал
# бы один пункт, а остальные молча отпали. Fail-CLOSED: кнопок нет, ответ словами.
_MULTISELECT_RE = re.compile(
    r"можно\s+взять\s+нескольк|можно\s+выбрать\s+нескольк|"
    r"не\s+исключают\s+друг\s+друга|выбери\s+один\s+или\s+нескольк",
    re.IGNORECASE,
)

_RECOMMEND_RE = re.compile(r"рекоменд|recommend", re.IGNORECASE)

# Упоминание варианта в начале строки секции — БЕЗ требований к оформлению. Служит
# только одному: отличить «карточка не предлагает выбора» от «выбор написан, а кнопок
# нет». Разбирать по нему нельзя — подписи он не даёт.
#
# Метка номера здесь описана ШИРЕ, чем в `_OPTION_RE`, и это условие работоспособности, а
# не небрежность. Замер 10.08 (`own-rnd-killswitch-rearm-policy-missing`): оба выражения
# описывали номер ОДИНАКОВО — один знак, — живая карточка написала «Вариант А1», где
# после буквы стоит цифра и границы слова между ними нет, и сторож, заведённый РАДИ фразы
# «владелец прочёл „вариантов не нашёл“ под карточкой, где их пять», не увидел ровно эти
# пять и подтвердил разбору его же слепое пятно. Сторож, делящий слепое пятно с тем, кого
# сторожит, — не сторож. Поэтому здесь любая короткая метка-номер (1, 12, А, А1, 1а, Б2).
# Шире — до произвольного слова — намеренно НЕ идём: «Вариант тот же» стал бы «варианты
# есть, кнопок нет — заведи дефект», то есть ложью в другую сторону, с просьбой завести
# несуществующий дефект.
_OPTION_MENTION_RE = re.compile(
    r"^\s*(?:[*\-+]\s+)?\**\s*(?:вариант|option)\s+"
    r"(?:[A-Za-zА-Яа-я]\d{1,2}|\d{1,2}[A-Za-zА-Яа-я]|\d{1,2}|[A-Za-zА-Яа-я])\b",
    re.IGNORECASE,
)

# Рекомендация, называющая СВОЙ номер: «Рекомендация агента — вариант 1», «рекомендую
# вариант 2», «вариант 3 — рекомендую». Такая фраза живёт отдельным абзацем ПОСЛЕ перечня,
# то есть в хвосте последнего варианта; вывод по расположению абзаца её переворачивает.
_RECOMMEND_NAMED_RE = re.compile(
    r"(?:рекоменд\w*|recommend\w*)[^.\n]{0,60}?вариант\w*\s*[—–:-]?\s*(\d{1,2})"
    r"|вариант\w*\s*(\d{1,2})[^.\n]{0,60}?(?:рекоменд\w*|recommend\w*)",
    re.IGNORECASE,
)

# «не рекомендую» / «not recommended» — та же фраза с обратным знаком.
_RECOMMEND_NEGATED_RE = re.compile(
    r"\bне\s+рекоменд\w*|\bне\s+совет\w*|\bnot\s+recommend\w*", re.IGNORECASE)

# «(рекомендую)» внутри подписи — пометка, а не часть сути: на кнопке её заменяет ⭐.
_RECOMMEND_PAREN_RE = re.compile(r"\s*\((?:[^)]*(?:рекоменд|recommend)[^)]*)\)\s*", re.IGNORECASE)


def _marks_recommendation(text: str, pattern: re.Pattern = _RECOMMEND_RE) -> bool:
    """Пометка рекомендации в тексте ЭТОГО варианта, из которой вычтено отрицание.

    Отрицание проверяется ПЕРЕД положительной пометкой и всегда сильнее: «агент это **не
    рекомендует**» содержит подстроку «рекоменд», и голый поиск по ней ставит звезду ровно
    тому варианту, от которого автор карточки отговаривает. Владелец в отъезде отвечает
    кнопкой — перевёрнутая подсказка здесь дороже отсутствующей, поэтому fail-CLOSED:
    сомнительный текст остаётся без звезды, а не получает её.
    """
    if not text:
        return False
    if _RECOMMEND_NEGATED_RE.search(text):
        return False
    return bool(pattern.search(text))


@dataclass(frozen=True)
class ParsedOption:
    """Вариант ответа, ВЫЧИТАННЫЙ из карточки (не придуманный)."""

    num: str          # «1», «2», «B» — как в карточке
    label: str        # короткая суть варианта («перезаполнять освободившийся бюджет»)
    recommended: bool

    @property
    def callback_choice(self) -> str:
        """Часть callback_data. Нормализуем регистр — иначе «B» и «b» разъедутся."""
        return self.num.lower()


#: Сколько строк переноса склеиваем максимум. Незакрытая `**` — это опечатка автора
#: карточки, и она не должна съесть всю секцию в одну строку.
_WRAP_MAX_LINES = 4


def _fold_wrapped_bold(lines: List[str]) -> List[str]:
    """Склеить пункт, у которого жирный `**…**` перенесён на следующую строку.

    Разбор построчный, а карточки пишутся с переносом по ширине — и пункт вида::

        * **Вариант 1 (рекомендую) — убрать «идёт paper-трек» из статуса, пока в
          книге не появятся позиции.** Останется «ИССЛЕДОВАНИЕ · без live-аллокации».

    не совпадал ни с одним шаблоном и пропадал МОЛЧА. Замер 13.08 на живой карточке
    `owner-decision-sbalansirovannyi-tir-na-saite-idet-paper`: три варианта в тексте,
    две кнопки владельцу, и исчез именно **рекомендуемый** — владелец увидел бы
    «Варианты: 2, 3». ``has_unparsed_options`` при этом молчал (варианты-то разобрались,
    просто не все), то есть ни один сторож не назвал потерю.

    Склеиваем ТОЛЬКО по доказуемому признаку — нечётное число `**` в строке, то есть
    жирный буквально не закрыт. Всё остальное (в т.ч. хвост абзаца с «⭐ Рекомендация
    агента», который разбор нарочно относит к последнему варианту) не трогаем.
    """
    out: List[str] = []
    i = 0
    while i < len(lines):
        cur = lines[i]
        joined = 0
        while cur.count("**") % 2 == 1 and joined < _WRAP_MAX_LINES and i + 1 < len(lines):
            nxt = lines[i + 1]
            if not nxt.strip():  # пустая строка закрывает пункт вернее любой звёздочки
                break
            cur = cur.rstrip() + " " + nxt.strip()
            i += 1
            joined += 1
        out.append(cur)
        i += 1
    return out


def _section_lines(body: str) -> List[str]:
    """Строки секции «Что от тебя нужно». Пустой список — секции нет."""
    out: List[str] = []
    inside = False
    for ln in body.splitlines():
        stripped = ln.strip()
        if stripped.startswith("##"):
            low = stripped.lower()
            # Новый заголовок закрывает секцию — иначе «Вариант» из секции «Что будет
            # после» уехал бы в кнопки как ещё один выбор.
            inside = any(low.startswith(h) for h in _NEED_HEADINGS)
            continue
        if inside:
            out.append(ln)
    return _fold_wrapped_bold(out)


def _capitalize(text: str) -> str:
    """Заглавная первая буква. ``str.capitalize`` не годится — он гасит регистр остального
    («ADR-053» стал бы «Adr-053»)."""
    return text[:1].upper() + text[1:] if text else text


def _shorten(text: str, limit: int = BUTTON_LABEL_MAX) -> str:
    """Обрезать по границе слова, добавив многоточие. Никогда не рвём слово пополам."""
    text = text.strip().rstrip(".;,")
    if len(text) <= limit:
        return text
    cut = text[: limit - 1]
    if " " in cut:
        cut = cut.rsplit(" ", 1)[0]
    return cut.rstrip(".,;:—–-") + "…"


def has_unparsed_options(body: str) -> bool:
    """Есть ли в секции строки, ЯВНО называющие варианты, которых разбор не взял.

    Нужно, чтобы не врать владельцу об одном и том же двумя разными причинами. Раньше
    любая карточка без кнопок получала «вариантов в карточке не нашёл» — и это верно для
    карточки-поручения («сделай то-то»), но ЛОЖНО для карточки, где варианты написаны, а
    прочитать их не смогли мы. Замер 10.08: ровно так уехала остановленная система —
    владелец прочёл «вариантов не нашёл» под карточкой, где их пять.

    Признак намеренно грубый — слово «вариант»/«option» с номером в начале строки секции.
    Он не решает, ЧТО предлагать (это по-прежнему ``parse_options``), он лишь отличает
    «выбора нет» от «выбор есть, а кнопок нет» — и второе обязано звучать как неполадка.
    """
    if parse_options(body):
        return False
    return any(_OPTION_MENTION_RE.match(ln) for ln in _section_lines(body))


def allows_multiple(body: str) -> bool:
    """Разрешает ли карточка выбрать НЕСКОЛЬКО пунктов.

    Живой пример: «Выбери, как поступаем — можно взять несколько». Одна кнопка, которая
    закрывает карточку, превратила бы такой вопрос в «выбери ровно один»: остальные пункты
    молча отпали бы, а владелец бы об этом не узнал. Кнопок в этом случае нет, и текст
    ЧЕСТНО называет причину — не «вариантов не нашёл», а «их можно выбрать несколько».
    """
    return any(_MULTISELECT_RE.search(ln) for ln in _section_lines(body))


def _named_recommendation(
    section: List[str], valid: set,
) -> Tuple[Optional[str], bool]:
    """Номер варианта, НАЗВАННЫЙ рекомендацией. Возвращает ``(номер, спорно)``.

    Спорно (звезды не будет ни у кого) — когда мы не можем ручаться за подсказку:
    названо несколько РАЗНЫХ номеров · назван номер, которого в перечне нет.

    Отрицательная формулировка («агент это **не рекомендует**») ОТМЕНЯЕТ переопределение
    по номеру, но больше НЕ гасит звёзды у всех подряд. Раньше гасила — и это стоило
    подсказки там, где карточка написана лучше всего: замер 10.08 по
    ``own-rnd-killswitch-rearm-policy-missing`` — автор пометил рекомендованный вариант в
    его собственном заголовке и честно предупредил про соседний («не рекомендует»), после
    чего рекомендация исчезала у ВСЕХ ТРЁХ. Перевернуть звезду отрицание больше не может:
    пометку каждого варианта читает ``_marks_recommendation``, для которого отрицание
    сильнее положительной пометки в том же тексте.

    Ничего не названо ⇒ ``(None, False)`` — прежнее поведение (звезда по расположению).
    """
    if _RECOMMEND_NEGATED_RE.search("\n".join(section)):
        return None, False
    found: List[str] = []
    for ln in section:
        for m in _RECOMMEND_NAMED_RE.finditer(ln):
            num = (m.group(1) or m.group(2) or "").strip().lower()
            if num and num not in found:
                found.append(num)
    if not found:
        return None, False
    if len(found) > 1 or found[0] not in valid:
        return None, True
    return found[0], False


def parse_options(body: str) -> List[ParsedOption]:
    """Варианты ответа из тела карточки. Пусто ⇒ кнопок не будет (fail-CLOSED).

    Разбираем ТОЛЬКО секцию «Что от тебя нужно»: в карточках слово «вариант» встречается
    и в «Что будет после», и в разборе причин — там это не выбор владельца.
    """
    section = _section_lines(body)

    # Карточка допускает НЕСКОЛЬКО ответов ⇒ одна закрывающая кнопка исказила бы вопрос.
    if allows_multiple(body):
        return []

    options: List[ParsedOption] = []
    seen: set[str] = set()
    # Продолжение абзаца принадлежит ПОСЛЕДНЕМУ варианту: пометка «⭐ Рекомендация агента»
    # часто стоит там, а не в заголовке.
    tails: Dict[str, List[str]] = {}
    last_key: Optional[str] = None
    for ln in section:
        m = _OPTION_RE.match(ln)
        numbered = False
        if m is None:
            m = _OPTION_NUMBERED_RE.match(ln) or _OPTION_PLAIN_RE.match(ln)
            numbered = m is not None
        if not m:
            if last_key is not None:
                tails.setdefault(last_key, []).append(ln)
            continue
        num = m.group("num").strip()
        key = num.lower()
        if key in seen:
            # Дубль номера значит, что карточка задаёт НЕ ОДИН вопрос, а несколько:
            # «Решение 1 — вариант А/Б», «Решение 2 — вариант А/Б/В». Раньше здесь
            # молча брался первый, а НЕсовпавшие номера второго перечня (В) попадали
            # в кнопки наравне с первым — владелец получал смесь из двух разных
            # вопросов и не мог этого увидеть. Смешать два вопроса хуже, чем не
            # показать кнопок: fail-CLOSED на всю карточку, как и у пункта-вопроса ниже.
            return []
        last_key = key
        groups = m.groupdict()
        paren = "" if numbered else (groups.get("paren") or "")
        # Точка в конце — часть предложения карточки, а не подписи кнопки: «Вариант 1.»
        # с точкой посреди списка читается как оборванный текст.
        label = (groups.get("label") or "").strip()
        if not label and numbered:
            # Нумерованный пункт без жирного — тоже вариант (живая карточка 08.08).
            plain = (groups.get("plain") or "").strip()
            sentence = _FIRST_SENTENCE_RE.match(plain)
            label = (sentence.group(1) if sentence else plain).strip()
        if not label and not numbered:
            # В жирном была одна пометка — суть стоит СРАЗУ ЗА ним, первым предложением.
            tail = (groups.get("tail") or "").strip()
            sentence = _FIRST_SENTENCE_RE.match(tail)
            label = (sentence.group(1) if sentence else tail).strip()
        recommended = _marks_recommendation(paren) or _marks_recommendation(label)
        label = _RECOMMEND_PAREN_RE.sub(" ", label).strip().rstrip(" .,;:")
        if not label:
            continue  # подпись состояла из одной пометки — предлагать нечего
        seen.add(key)
        options.append(ParsedOption(num=num, label=label, recommended=recommended))

    # Составная метка выдаёт ВТОРОЙ вопрос там, где правило «дубль номера ⇒ fail-CLOSED»
    # его не выдаёт: «А1/А2/А3» и «Б1/Б2» — пять РАЗНЫХ номеров, дубля нет, а буква перед
    # цифрой ровно и означает, к какому решению вариант относится. Больше одной семьи —
    # больше одного вопроса; смешать их в одном ряду кнопок значит закрыть карточку первым
    # же нажатием и молча похоронить второй вопрос (то же основание, что у дубля выше).
    # Кнопок не будет, а причину владельцу назовёт `has_unparsed_options` — он увидит
    # «варианты есть, кнопок нет», а не «выбора не предлагали».
    #
    # Семья простого номера — пустая строка: карточки «Вариант 1/2/3» и «Вариант А/Б»
    # (метка в один знак) остаются ОДНИМ вопросом и кнопки сохраняют.
    families = {n[0] if len(n) > 1 and n[0].isalpha() else "" for n in
                (o.num.lower() for o in options)}
    if len(families) > 1:
        return []

    # Рекомендация, НАЗЫВАЮЩАЯ свой номер, сильнее любого вывода по расположению абзаца.
    # Замер 08.08 (`owner-decision-geit-i-allokator-schitayut-zhivoi-tvl-po`): фраза
    # «**Рекомендация агента — вариант 1.**» стоит ОТДЕЛЬНЫМ абзацем после перечня, то есть
    # физически в хвосте ПОСЛЕДНЕГО варианта — и звезда уезжала на вариант 3, ровно на тот,
    # который автор не советовал. Владелец отвечает кнопкой, значит перевёрнутая
    # рекомендация — это не оформление, а подсказка в обратную сторону.
    named, ambiguous = _named_recommendation(section, {o.num.lower() for o in options})
    if ambiguous:
        # Спорная или отрицающая формулировка ⇒ звезды нет НИ У КОГО. Кнопки остаются:
        # выбор владельца никуда не девается, исчезает только наша подсказка, за которую
        # мы не можем ручаться. Ложная звезда хуже отсутствующей.
        options = [ParsedOption(o.num, o.label, False) for o in options]
    elif named is not None:
        options = [ParsedOption(o.num, o.label, o.num.lower() == named) for o in options]
    # Звёздочка могла стоять в ПРОДОЛЖЕНИИ абзаца, а не в заголовке варианта. Отрицание в
    # том же абзаце сильнее: «Агент это **не рекомендует**» стоит именно в хвосте варианта,
    # и голый поиск «рекоменд» ставил бы звезду отговариваемому варианту.
    elif not any(o.recommended for o in options):
        options = [
            ParsedOption(o.num, o.label,
                         any(_marks_recommendation(t, _RECOMMEND_INLINE_RE)
                             for t in tails.get(o.num.lower(), [])))
            for o in options
        ]

    # Карточка может задавать НЕСКОЛЬКО НЕЗАВИСИМЫХ вопросов, а не предлагать выбор одного
    # варианта. Живой пример (`own-31-desyat-agentov-v-reestre-bez-flota`): «Два решения:
    # 1. **Ставить ли четыре готовых?** 2. **Выводить ли шесть из реестра?**» — у каждого своя
    # рекомендация «да». Кнопки сделали бы их взаимоисключающими: владелец нажал бы «1»,
    # карточка закрылась бы, а второй вопрос умер бы молча.
    #
    # Признак — подпись ЗАКАНЧИВАЕТСЯ вопросительным знаком: вариант выбора формулируют
    # действием («Оживить фиды»), а вопрос — вопросом. Хоть один такой пункт ⇒ кнопок нет
    # у всей карточки (fail-CLOSED), уходит обычный текст. Потерять оформление можно;
    # потерять половину вопроса владельца — нет.
    if any(o.label.rstrip().endswith("?") for o in options):
        return []
    return options


# ── идентификатор карточки в callback_data ───────────────────────────────────


def make_pid(card_id: str) -> str:
    """Короткий стабильный идентификатор карточки для callback_data.

    Стабильный (хэш от имени файла, без времени): повторная отправка той же карточки
    обязана давать ТОТ ЖЕ pid, иначе старое сообщение в переписке становится мёртвым —
    владелец жмёт кнопку вчерашнего пуша и не получает ничего.
    """
    return hashlib.sha256(card_id.encode("utf-8")).hexdigest()[:PID_LEN]


def build_callback(pid: str, choice: str) -> str:
    """``act:od:<pid>:<choice>``. Гарантированно в лимите Telegram."""
    data = f"{CALLBACK_PREFIX}{pid}:{choice}"
    if len(data.encode("utf-8")) > CALLBACK_MAX_BYTES:  # pragma: no cover — защита от будущих правок
        raise ValueError(f"callback_data too long: {data!r}")
    return data


def parse_callback(data: str) -> Optional[Tuple[str, str]]:
    """``act:od:<pid>:<choice>`` → ``(pid, choice)``; не наш формат → ``None``."""
    if not data.startswith(CALLBACK_PREFIX):
        return None
    rest = data[len(CALLBACK_PREFIX):]
    if ":" not in rest:
        return None
    pid, choice = rest.split(":", 1)
    if not pid or not choice:
        return None
    return pid, choice


# ── журнал отправленных решений ──────────────────────────────────────────────


def _load(path: Path) -> Dict:
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(doc, dict) and isinstance(doc.get("pushes"), list):
            return doc
    except Exception:  # noqa: BLE001 — битый журнал не имеет права мешать доставке
        pass
    return {"schema_version": 1, "pushes": []}


def _save(doc: Dict, path: Path) -> None:
    doc["pushes"] = doc["pushes"][-HISTORY_MAX:]
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_save(doc, str(path))


def find_push(pid: str, *, state_path: Optional[str | Path] = None) -> Optional[Dict]:
    """Запись журнала по pid (последняя). ``None`` — не находили такой карточки."""
    doc = _load(_state_path(state_path))
    for rec in reversed(doc["pushes"]):
        if rec.get("pid") == pid:
            return rec
    return None


# ── человеческий текст сообщения ─────────────────────────────────────────────

_MD_BOLD = re.compile(r"\*\*(.+?)\*\*", re.DOTALL)
_MD_ITALIC = re.compile(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", re.DOTALL)
_MD_CODE = re.compile(r"`([^`]+)`")
_MD_LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)")

_WHAT_HEADINGS = ("## что случилось", "## what happened")

SUMMARY_MAX = 600


def _plain(text: str) -> str:
    """Markdown → человеческий текст. Разметку убираем, СОДЕРЖИМОЕ оставляем."""
    text = _MD_LINK.sub(r"\1", text)
    text = _MD_BOLD.sub(r"\1", text)
    text = _MD_ITALIC.sub(r"\1", text)
    text = _MD_CODE.sub(r"\1", text)
    return text


def summarize(body: str, limit: int = SUMMARY_MAX) -> str:
    """«Что случилось» простыми словами — из одноимённой секции карточки.

    Секции нет ⇒ первый осмысленный абзац тела. Обрезаем по границе ПРЕДЛОЖЕНИЯ:
    оборванная на полуслове тревога читается как сбой, а не как краткость.
    """
    lines: List[str] = []
    inside = False
    saw_section = False
    for ln in body.splitlines():
        stripped = ln.strip()
        if stripped.startswith("##"):
            low = stripped.lower()
            inside = any(low.startswith(h) for h in _WHAT_HEADINGS)
            saw_section = saw_section or inside
            continue
        if inside:
            lines.append(stripped)
    if not saw_section:
        for ln in body.splitlines():
            stripped = ln.strip()
            if stripped and not stripped.startswith(("#", "---")):
                lines.append(stripped)

    text = _plain(" ".join(x for x in lines if x)).strip()
    text = re.sub(r"\s+", " ", text)
    if len(text) <= limit:
        return text
    cut = text[:limit]
    for sep in (". ", "; ", ", "):
        if sep in cut:
            head = cut.rsplit(sep, 1)[0]
            if len(head) > limit // 2:
                return head + "…"
    return _shorten(cut, limit)


def build_message(title: str, body: str, options: List[ParsedOption],
                  *, has_buttons: bool = True, card_name: str = "") -> str:
    """HTML-сообщение владельцу: заголовок, суть, перечень вариантов.

    HTML, а не Markdown: в карточках сплошь пути с подчёркиваниями (`agent_health`),
    на которых Markdown отдаёт 400 (урок telegram-alerts).

    ``has_buttons`` — приедет ли клавиатура. Раньше текст ВСЕГДА заканчивался «Нажми
    кнопку», и владелец получил решение с этой фразой и без единой кнопки (замер 08.08).
    Обещать несуществующее хуже, чем не обещать ничего: владелец решает, что сломан бот,
    и перестаёт верить всему каналу. Текст и клавиатура должны говорить ОДНО.
    """
    parts = [
        "🧑‍⚖️ <b>Нужно твоё решение</b>",
        "",
        f"<b>{html.escape(title)}</b>",
    ]
    summary = summarize(body)
    if summary:
        parts += ["", html.escape(summary)]
    if options:
        parts += ["", "<b>Варианты:</b>"]
        for opt in options:
            star = " ⭐ <i>рекомендую</i>" if opt.recommended else ""
            label = html.escape(_capitalize(opt.label))
            parts.append(f"<b>{html.escape(opt.num)}.</b> {label}{star}")
        if has_buttons:
            parts += ["", "Нажми кнопку — запишу решение и возьму в работу."]
        else:
            # Варианты есть, а обработать нажатие сейчас некому (бот не подтвердил, что
            # умеет). Говорим ЧЕСТНО, как ответить без кнопок, вместо ссылки на пустоту.
            parts += ["", "⚠️ Кнопки сейчас недоступны — бот не подтвердил, что готов их "
                          "обработать. Ответь номером варианта в чат, я разберу."]
    elif allows_multiple(body):
        # Варианты ЕСТЬ, но карточка разрешает взять несколько — кнопкой это не выразить.
        parts += ["", "В этой карточке можно выбрать НЕСКОЛЬКО пунктов, поэтому кнопок нет.",
                  "Ответь номерами в чат (например «1 и 3») — разберу."]
    elif has_unparsed_options(body):
        # Варианты в карточке ЕСТЬ, а кнопок нет — это неполадка на нашей стороне либо
        # карточка с несколькими независимыми вопросами. Молча выдать «вариантов не нашёл»
        # значит спрятать её: владелец решит, что выбора и не предлагали.
        parts += ["", "⚠️ Варианты в карточке есть, но я не смог собрать из них кнопки "
                      "(так бывает, когда в одной карточке несколько разных решений). "
                      "Открой её целиком и ответь словами — и заведи мне это как дефект."]
    else:
        # Fail-CLOSED: вариантов не разобрали — не выдумываем их, честно зовём в карточку.
        tail = ("Вариантов в карточке не нашёл — открой её целиком кнопкой ниже."
                if has_buttons else
                "Вариантов в карточке не нашёл — открой её в трекере.")
        parts += ["", tail]
    if card_name:
        # Имя карточки нужно всегда: без кнопок это ЕДИНСТВЕННЫЙ способ найти её в трекере,
        # а с кнопками — способ сослаться на неё в разговоре. Раньше оно было только в
        # запасном виде сообщения и пропало, как только заработал богатый.
        parts += ["", f"📄 <code>{html.escape(card_name)}</code>"]
    return "\n".join(parts)


def build_keyboard(pid: str, options: List[ParsedOption]) -> Dict:
    """Inline-клавиатура: по кнопке на вариант (⭐ у рекомендованного) + «Подробнее».

    По одной кнопке в ряд: подписи вариантов длинные, в два столбца Telegram их режет.
    """
    rows: List[List[Dict]] = []
    for opt in options:
        star = "⭐ " if opt.recommended else ""
        label = f"{star}{opt.num}. {_capitalize(_shorten(opt.label))}"
        rows.append([{"text": label,
                      "callback_data": build_callback(pid, opt.callback_choice)}])
    rows.append([{"text": "📖 Подробнее", "callback_data": build_callback(pid, "more")}])
    return {"inline_keyboard": rows}


