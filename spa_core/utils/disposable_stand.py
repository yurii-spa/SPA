"""Одноразовый стенд прибора: снимает его ТОТ, КТО ЕГО СОЗДАЛ.

ПОЧЕМУ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ (авария 2026-10-03, цикл #759)
----------------------------------------------------------
Приборы ряда G-nn меряют цену починки на КОПИИ живого ``data/`` — это верно и
менять незачем: живой каталог нельзя открывать на запись. Неверным было другое:
копию никто не снимал. ``heir_all_rows_price`` копирует ``data/`` ПЯТЬ раз за
зов (пять стендов), ``judge_alone_price`` — своей карусели, и каждый зов
оставлял каталог ``g17_*`` / ``g18_*`` в общем временном корне навсегда.

Замер того дня: **957 брошенных стендов, 87 ГБ** за трое суток (286 ``g17_``
и 671 ``g18_``; 195 из них — полные копии по ~1,1 ГБ). Диск Mac Mini дошёл до
**нуля свободных байт**, и в этом состоянии падает ЛЮБАЯ запись, включая
``atomic_save``: дневной цикл, трек, маячок бота и все сторожа одновременно
теряют способность записать результат. Два предыдущих разбора той же аварии
(26.09 и цикл #756) назвали виновником журнал ``/tmp/spa_decision_loop.log`` —
в день замера он весил **0,6 ГБ**, то есть в 140 раз меньше стендов. Названная
причина была верной по форме и НЕ ГЛАВНОЙ по величине, поэтому авария вернулась
третий раз.

ПРАВИЛО
-------
Владение каталогом принадлежит тому, кто его создал, и снятие — часть зова, а
не чья-то будущая уборка. Стенд, чей путь НАЗВАЛ вызов (``stand_root=``), не
снимается никогда: это каталог вызывающего, и удалить его значило бы унести
чужие данные (ровно тот класс, которым ``git checkout -- data/`` стёр 116
файлов, `.claude/rules/deployment.md`).

ТРИ ИСХОДА, И ОНИ РАЗЛИЧИМЫ (инв. #17)
--------------------------------------
Поле ``stand_disposal`` в отчёте прибора несёт ровно одно из трёх значений:

* ``removed`` — стенд был наш и снят, место освобождено;
* ``caller_owns`` — путь назвал вызов, снимать его не наше дело;
* ``failed:<ТипИсключения>`` — снять НЕ УДАЛОСЬ, причина названа.

Третье значение существует затем, чтобы «место не освобождено» не было
неотличимо от «освобождено»: молчание здесь и есть та форма отказа, которая
трижды довела машину до нуля. Отказ уборки при этом НЕ отменяет замер —
прибор обязан отдать свой вердикт, а не потерять работу из-за мусора.
"""
from __future__ import annotations

import shutil
import tempfile
from pathlib import Path
from typing import Optional, Tuple

#: имя поля в отчёте прибора — одно, чтобы читателю не приходилось угадывать
FIELD = "stand_disposal"
REASON_FIELD = "stand_disposal_reason"

DISPOSAL_REMOVED = "removed"
DISPOSAL_CALLER_OWNS = "caller_owns"
DISPOSAL_FAILED = "failed"


def make_stand(prefix: str, stand_root: Optional[Path] = None) -> Tuple[Path, bool]:
    """Каталог стенда и признак «его создали МЫ».

    Признак — не удобство, а запись о владении: по нему и только по нему
    решается, кому каталог снимать.
    """
    if stand_root is not None:
        path = Path(stand_root)
        owned = False
    else:
        path = Path(tempfile.mkdtemp(prefix=prefix))
        owned = True
    path.mkdir(parents=True, exist_ok=True)
    return path, owned


def drop_stand(path, *, owned: bool) -> dict:
    """Снять свой стенд и НАЗВАТЬ исход. Возвращает поля для отчёта прибора."""
    if not owned:
        return {FIELD: DISPOSAL_CALLER_OWNS,
                REASON_FIELD: (f"каталог {path} назвал вызов (stand_root=) — "
                               f"снимать его не наше дело")}
    try:
        shutil.rmtree(path)
    except BaseException as exc:  # noqa: BLE001 — причина обязана быть названа
        return {FIELD: f"{DISPOSAL_FAILED}:{type(exc).__name__}",
                REASON_FIELD: (f"стенд {path} НЕ снят: {type(exc).__name__}: "
                               f"{exc} — место на диске не освобождено")}
    return {FIELD: DISPOSAL_REMOVED,
            REASON_FIELD: f"стенд {path} снят тем, кто его создал"}
