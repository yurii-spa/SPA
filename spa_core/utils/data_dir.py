#!/usr/bin/env python3
"""Каталог состояния модуля, разрешаемый В МОМЕНТ ВЫЗОВА, а не при импорте.

Зачем этот модуль
------------------------------------------------------------------------------
Заслон герметичности тестов (`tests/conftest.py::_isolate_data_dir`) обещает, что
«любой код, разрешающий свой каталог состояния штатным механизмом, никогда не
прочитает и не запишет живой data/». Механизм — переменная ``SPA_DATA_DIR``.
Замер цикла #361: модулей рантайма, берущих каталог состояния литералом
``_REPO_ROOT / "data"``, — 209; из них спрашивают ``SPA_DATA_DIR`` — ОДИН.
Значит, у остальных вердикт теста определяет живой файл хоста, а не код.

Доказанная жертва (карточка `inbox-zaslon-izolyatsii-data-v-testah-pokryvae`):
``_adapter_class_gate("spark_susds")`` создаёт настоящий адаптер, тот читает живой
``data/adapter_status.json`` мимо заслона, и один и тот же код даёт
``(False, 'gsm_not_confirmed')`` на каноне origin/main и ``(True, None)`` в боевом
дереве. Тест-сторож денежного гейта менял вердикт от того, из какого дерева его
запустили.

Почему В МОМЕНТ ВЫЗОВА
------------------------------------------------------------------------------
``_DEFAULT_DATA_DIR = _REPO_ROOT / "data"`` вычисляется при ИМПОРТЕ модуля.
Autouse-фикстура выставляет ``SPA_DATA_DIR`` на каждый тест — то есть намного
позже импорта. Константа, разрешённая при импорте, заслона не увидит никогда:
переписать её на ``os.environ.get(...)`` на уровне модуля значило бы починить
только тот случай, когда переменная выставлена ДО запуска pytest. Поэтому
резолв — функцией, и зовут её из ``__init__``/точки чтения.

Почему НЕ ``live_paths.live_data_dir()``
------------------------------------------------------------------------------
Тот модуль отвечает на ДРУГОЙ вопрос — «где живёт ПРОД-состояние» — и при
невыставленной переменной уводит на ``~/Documents/SPA_Claude/data``. Для
адаптера, запущенного из worktree или из CI, это смена поведения: он начал бы
читать чужое дерево. Здесь умолчание остаётся ровно тем, чем было — каталог
СВОЕГО дерева, — и меняется только одно: появляется штатный способ его перебить.

Порядок разрешения (первый сработавший выигрывает)
------------------------------------------------------------------------------
1. ``SPA_DATA_DIR`` — песочница герметичного прогона / пред-деплойного гейта.
   Она сильнее умолчания — та же расстановка, что в ``live_paths`` и в
   ``paper_trading/_cycle_io`` (``SPA_DATA_DIR`` обязана быть сильнее всего,
   иначе гейт начнёт писать в живое).
2. Умолчание модуля — каталог ``data/`` его собственного дерева.

**В проде переменная не выставлена, поэтому поведение бит-в-бит прежнее.**
Явно переданный вызывающим ``data_dir`` этот модуль не касается вовсе: он
разрешает только УМОЛЧАНИЕ, и остаётся честным «вызывающий сказал — вызывающий
прав».

stdlib, без побочных эффектов: ни одного каталога этот модуль не создаёт.
"""
from __future__ import annotations

import os
from pathlib import Path

#: Единственный источник правды для имени переменной — чтобы вызывающие и тесты
#: не расходились в написании строки.
DATA_DIR_ENV = "SPA_DATA_DIR"


def own_data_dir(module_default: Path | str) -> Path:
    """Каталог состояния по умолчанию для модуля, с учётом ``SPA_DATA_DIR``.

    ``module_default`` — то, чем каталог был до этой правки (обычно
    ``_REPO_ROOT / "data"`` самого модуля). Возвращается он же, если переменная
    не выставлена или пуста.

    Пустая строка трактуется как «не выставлено», а не как «текущий каталог»:
    ``Path("")`` — это ``.``, и молчаливый переезд состояния в cwd был бы ровно
    тем классом отказа, ради которого написан ``live_paths``.
    """
    override = os.environ.get(DATA_DIR_ENV, "").strip()
    if override:
        return Path(override)
    return Path(module_default)
