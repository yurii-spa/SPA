#!/usr/bin/env python3
"""Где лежит ЖИВОЕ состояние — независимо от того, из какого дерева нас запустили.

Зачем этот модуль
------------------------------------------------------------------------------
Замер 2026-08-08: владельцу пришло решение с текстом «Нажми кнопку», но БЕЗ кнопок.
Разбор: отправляла сессия, работавшая из своего рабочего дерева (worktree). Маячок живого
бота (`data/telegram_bot_capabilities.json`) существует ТОЛЬКО в прод-дереве — бот пишет его
там и больше нигде. Отправитель же искал маячок у себя, не находил и по правилу fail-CLOSED
кнопок не вешал. Молча.

Это тот же родовой класс, что и весь остальной сегодняшний день: **путь, разрешаемый
относительно исполняемого дерева, тихо меняет поведение**. Хост-дерево дрейфует от origin по
построению, сессии работают из worktree — значит «мой каталог data/» и «живой data/» это
разные вещи, и рассчитывать на их совпадение нельзя.

Порядок разрешения (первый сработавший выигрывает)
------------------------------------------------------------------------------
1. ``SPA_DATA_DIR`` — устоявшаяся песочница (её экспортирует пред-деплойный гейт и
   герметичные прогоны). Она обязана быть СИЛЬНЕЕ всего: иначе гейт начал бы писать в живое.
2. ``SPA_LIVE_ROOT`` — явное указание корня, если прод переедет.
3. Прод-дерево по умолчанию (``~/Documents/SPA_Claude``), если оно существует. Именно его
   исполняет флот launchd — это не «какой-то путь», а единственное дерево, где живёт состояние.
4. Дерево вызывающего — последний рубеж (CI, чужая машина, распакованный архив).

Почему последний рубеж — НЕ ``Path.cwd()``
------------------------------------------------------------------------------
Замер 2026-08-14 (CI, цикл #223): job гоняет тесты как ``cd spa_core && pytest tests/``,
и ``live_data_dir(None)`` отдавал ``<репо>/spa_core/data`` — каталог, которого нет.
«Дерево вызывающего» и «текущий рабочий каталог» — РАЗНЫЕ вещи: агенты стартуют из разных
каталогов (launchd задаёт свой, обёртки делают ``cd``, сессии живут в worktree), и путь,
зависящий от cwd, — тот же самый родовой класс, ради которого написан этот модуль.
Поэтому без явного ``fallback`` берётся дерево, в котором лежит САМ этот файл: оно
детерминировано и не меняется от того, откуда нас позвали.

Тесты сюда не попадают: модули состояния сами уводят прогон во временный файл под
``PYTEST_CURRENT_TEST`` — правило появилось после инцидента «тесты пишут в живое состояние
алертов» и здесь не ослабляется. Общая реализация этого увода —
:func:`sandboxed_state_path` ниже (цикл #274): «сами уводят» существовало как ПРАВИЛО и
десяток независимых копий, а у producer-логов копии не было вовсе.

stdlib, без побочных эффектов: ни одного каталога этот модуль не создаёт.
"""
from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path

#: Каталог прод-дерева по умолчанию. Флот launchd исполняет ИМЕННО его.
DEFAULT_LIVE_ROOT = Path.home() / "Documents" / "SPA_Claude"

DATA_DIR_ENV = "SPA_DATA_DIR"
LIVE_ROOT_ENV = "SPA_LIVE_ROOT"

#: Дерево, в котором лежит сам этот модуль. Последний рубеж, когда вызывающий не
#: назвал своё дерево: детерминирован, в отличие от cwd (см. докстринг модуля).
OWN_TREE = Path(__file__).resolve().parents[2]


def live_root(fallback: Path | None = None) -> Path:
    """Корень живого дерева. ``fallback`` — дерево вызывающего.

    ``fallback=None`` ⇒ дерево ЭТОГО модуля, а не ``Path.cwd()``: рабочий каталог
    процесса ничего не говорит о том, где живёт код, и меняется под нами.
    """
    env = os.environ.get(LIVE_ROOT_ENV)
    if env:
        return Path(env)
    if DEFAULT_LIVE_ROOT.is_dir():
        return DEFAULT_LIVE_ROOT
    return fallback or OWN_TREE


def live_data_dir(fallback_root: Path | None = None) -> Path:
    """``data/`` живого состояния. См. порядок разрешения в докстринге модуля.

    ``fallback_root`` — корень дерева вызывающего (обычно ``Path(__file__).parents[2]``),
    используется только если живого дерева не видно.
    """
    sandbox = os.environ.get(DATA_DIR_ENV)
    if sandbox:
        return Path(sandbox)
    return live_root(fallback_root) / "data"


# ──────────────────────────────────────────────────────────────────────────────
# Увод ПРОИЗВОДНОГО состояния из дерева на время прогона тестов (цикл #274)
# ──────────────────────────────────────────────────────────────────────────────
#
# Что измерено 2026-08-17 (карточка ``agent-test-run-dirties-tracked-fixtures``).
# Прогон ``pytest spa_core/tests/`` оставлял ``git status`` с ТРИНАДЦАТЬЮ
# изменёнными git-tracked файлами. Писатели названы поимённо (файл:строка) —
# ни одного «теста, забывшего подменить путь» среди причин нет: каждый писатель
# это ПРОДОВЫЙ модуль, который берёт путь лога из модульной константы, собранной
# из своего ``__file__``, и потому пишет в дерево, что бы тест ни передал.
#
# Самый показательный случай — ``test_cash_attribution_policy_refusals.py::
# test_run_cycle_wires_the_refusal_into_the_owner_facing_artifact``: тест
# передаёт ``data_dir=str(tmp_path)`` и ``allow_live_write=False``, его докстринг
# дословно обещает «the live track is never read or written», и при этом ОДИН
# этот тест пачкает ДЕВЯТЬ трекаемых путей — ``run_cycle`` не протаскивает
# ``data_dir`` в веер (adapter_status_generator, gap_monitor,
# apy_milestone_tracker и аналитику, вызываемую через signal_aggregator), а те
# резолвят свои пути сами. Починка «в тесте» тут невозможна по построению:
# тест уже сделал всё правильно.
#
# Почему НЕ через ``SPA_DATA_DIR``. Во-первых, константы вычисляются на ИМПОРТЕ,
# то есть до любой фикстуры. Во-вторых — измерено — ``test_alerts.py::
# TestRunAlertsCli`` работает под ``mock.patch.dict(os.environ, {}, clear=True)``:
# любой env-переменной там уже нет, включая ``PYTEST_CURRENT_TEST``. Поэтому
# признак «мы под тестами» берётся из ``sys.modules`` (так же, как в
# ``strategy_lab/rates_desk/proof_chain.py::_under_test``) И из env — первый
# работает при вычищенном окружении, второй в дочернем процессе.
#
# Это РЕДИРЕКТ, не мок: весь код записи (ring-buffer, atomic_save, makedirs)
# исполняется целиком, меняется только каталог назначения. Прод не задет:
# без pytest в ``sys.modules`` функция возвращает ровно то, что ей дали.

#: Осознанный обход: прод-ветка обязана оставаться проверяемой. Дочерний процесс
#: (или тест, который МЕРЯЕТ прод-путь) выставляет флаг и получает живой путь.
LIVE_STATE_IN_TESTS_ENV = "SPA_ALLOW_LIVE_STATE_IN_TESTS"

#: Куда уводить. Обычно ставит фикстура ``_no_live_producer_logs``; если не
#: выставлено — общий per-process каталог в tempdir (детерминированный, свой).
TEST_STATE_DIR_ENV = "SPA_TEST_STATE_DIR"

_TEST_STATE_ROOT: Path | None = None

#: Явный признак «этому запуску РАЗРЕШЕНО писать производное состояние в дерево».
#: Нужен для ad-hoc прод-запуска, где ``SPA_ENV`` не выставлен (ручной прогон
#: агента, восстановление, отладка на проде).
LIVE_WRITE_ENV = "SPA_LIVE_WRITE"

#: Уже существующий признак прод-запуска — НЕ изобретаем новый (замер 18.08).
#: Стоит в ``EnvironmentVariables`` четырёх плистов (`com.spa.daily_cycle`,
#: `apiserver`, `hy_cycle`, `lp_cycle`) и экспортируется `scripts/agent_template.sh`,
#: через который идут 75 из 82 обёрток флота — включая `analytics_tier_b/c`,
#: единственных продовых писателей уводимых логов помимо дневного цикла.
ENV_NAME_ENV = "SPA_ENV"
PRODUCTION_ENV_VALUE = "production"


def live_state_writes_allowed() -> bool:
    """Разрешена ли ЖИВАЯ запись производного состояния в git-tracked дерево.

    Замер 2026-08-18 (карточка ``inbox-uvod-putei-ne-deistvuet-vne-pytest-obych``).
    ``under_test()`` отвечает на вопрос «мы под pytest», а нужный вопрос — «это
    прод-запуск, которому положено писать в дерево». Это РАЗНЫЕ вопросы, и
    расхождение между ними и есть дефект: обычный запуск скрипта
    (``scripts/audit_tier_c_wiring_feasibility.py``) не под pytest, но и не прод —
    и пачкал 56 трекаемых путей.

    Признак ПОЛОЖИТЕЛЬНЫЙ (что-то разрешает), а не отрицательный (что-то
    запрещает): по умолчанию — песочница, живая запись включается явно. Иначе
    каждый следующий способ запустить модуль пришлось бы опознавать заново, и
    класс вернулся бы в третий раз — ровно то, что предсказывала карточка про
    вариант B.
    """
    if os.environ.get(LIVE_WRITE_ENV) == "1":
        return True
    if os.environ.get(ENV_NAME_ENV) == PRODUCTION_ENV_VALUE:
        return True
    return False


def under_test() -> bool:
    """Исполняемся ли мы внутри прогона тестов.

    ``sys.modules`` — основной признак: он не зависит от ``os.environ`` и потому
    выживает ``mock.patch.dict(os.environ, {}, clear=True)`` (замер: именно так
    устроен ``test_alerts.py::TestRunAlertsCli``, и env-признак там уже стёрт).
    ``PYTEST_CURRENT_TEST`` оставлен вторым признаком — он есть в дочерних
    процессах, которым pytest не импортирован.
    """
    return "pytest" in sys.modules or bool(os.environ.get("PYTEST_CURRENT_TEST"))


def test_state_root() -> Path:
    """Песочница для производного состояния (создаётся при первом обращении)."""
    global _TEST_STATE_ROOT
    env = os.environ.get(TEST_STATE_DIR_ENV)
    if env:
        return Path(env)
    if _TEST_STATE_ROOT is None:
        _TEST_STATE_ROOT = Path(tempfile.mkdtemp(prefix="spa_test_state_"))
    return _TEST_STATE_ROOT


def sandboxed_state_path(default_path) -> Path:
    """Путь для ЗАПИСИ производного состояния: под тестами — в песочницу.

    Порядок разрешения:

    1. не под тестами (прод) → ``default_path`` без изменений;
    2. выставлен :data:`LIVE_STATE_IN_TESTS_ENV` → ``default_path`` (осознанный
       обход, чтобы прод-ветка оставалась измеримой);
    3. иначе → ``<песочница>/<имя файла>``.

    Имя файла сохраняется: тесты и отладка узнают артефакт по имени, а совпадений
    имён среди уводимых логов нет (проверяется тестом-сторожем).
    """
    default = Path(default_path)
    if not under_test():
        return default
    if os.environ.get(LIVE_STATE_IN_TESTS_ENV):
        return default
    return test_state_root() / default.name


def sandboxed_state_dir(default_dir) -> Path:
    """То же для КАТАЛОГА-приёмника (например ``OUTPUT_DIR`` выгрузки).

    Отдельная функция, а не ``sandboxed_state_path(dir / "x").parent``: каталог
    и файл — разные вещи, и склейка через фиктивное имя читалась бы как ошибка.
    В проде возвращает ``default_dir`` без изменений.
    """
    default = Path(default_dir)
    if not under_test():
        return default
    if os.environ.get(LIVE_STATE_IN_TESTS_ENV):
        return default
    return test_state_root()


def sandboxed_default(path, tree_default):
    """Увести в песочницу ТОЛЬКО СОБСТВЕННОЕ умолчание дерева.

    Зачем отдельно от :func:`sandboxed_state_path`. Семейство
    ``spa_core/analytics/*`` устроено так, что путь лога приходит в писателя
    ПАРАМЕТРОМ (``cfg["log_path"]``, аргумент по умолчанию, поле экземпляра), и
    этот параметр бывает двух разных природ:

    * умолчание модуля — тот самый git-tracked ``data/<имя>_log.json``, из-за
      которого прогон пачкал дерево;
    * путь, который вызывающий назвал САМ (``tmp_path``, monkeypatch модульной
      константы, ``--data-dir`` в CLI) — им владеет вызывающий.

    Безусловный увод ломает вторую природу: замер партии #1 показал три класса
    покрасневших тестов, и каждый из них был ПРАВ — тест подменял
    ``m.LOG_PATH`` на ``tmp`` и требовал записи именно туда. Поэтому сравнение
    с умолчанием дерева здесь не оптимизация, а условие корректности: не своё —
    не трогаем.

    Тот же смысл уже записан руками в ``analytics/borrowing_cost_optimizer.py``
    (цикл #274); эта функция — его общая форма, чтобы 180 модулей не заводили
    180 копий.

    **Когда увод действует (изменено 2026-08-18, вариант A карточки
    ``inbox-uvod-putei-ne-deistvuet-vne-pytest-obych``).** Раньше — только под
    pytest, и это закрывало ровно один сценарий из трёх. Замер: из чистого дерева
    ``scripts/audit_tier_c_wiring_feasibility.py --tier B`` оставлял 32 изменённых
    git-tracked пути (union A+B+C — 56), потому что скрипт запускается БЕЗ pytest
    и признака не имел. Третий сценарий — ``python3 -c "import
    spa_core.analytics.x"`` при отладке — пачкал дерево так же.

    Теперь увод — УМОЛЧАНИЕ, а живая запись включается явно
    (:func:`live_state_writes_allowed`). Это меняет вопрос с опознавательного
    («узнали ли мы этот способ запуска?») на структурный («названо ли право
    писать?»), и потому не требует опознавать каждый следующий инструмент.

    **Область изменения — ТОЛЬКО эта функция.** :func:`sandboxed_state_path` и
    :func:`sandboxed_state_dir` оставлены на прежней pytest-семантике намеренно:
    замер показал, что ``sandboxed_default`` вызывается ИСКЛЮЧИТЕЛЬНО из
    ``spa_core/analytics/`` (169 файлов), а чокпоинты выгрузки и money-path —
    ``export_data.py:106``, ``adapter_status_generator.py:1074``,
    ``gap_monitor.py:349,356``, ``alert_dispatcher.py:239,566``,
    ``defillama_fetcher.py:646``, ``engine_bridge.py:205`` — ходят через ДРУГИЕ
    две функции. Расширять увод на них одним заходом означало бы менять поведение
    выгрузки дашборда без замера её писателей; это отдельная работа.

    **Тип возврата повторяет тип входа** (``str`` → ``str``, ``Path`` → ``Path``).
    Это не косметика: функция вставляется В СЕРЕДИНУ чужого писателя, где
    следующая строка — то ``path.parent.mkdir(...)``, то ``log_path + ".tmp"``.
    Замер партии #3: подмена ``Path`` на ``str`` покрасила 30 тестов
    ``bridge_risk_assessor`` разом (``'str' object has no attribute 'parent'``).
    Увод обязан менять КАТАЛОГ, а не тип.
    """
    if path is None:
        # «Пути ещё нет» — не наш случай: уводить нечего, а Path(None) падает.
        # Писатель сам подставит своё умолчание строкой ниже, и увод обязан
        # стоять ПОСЛЕ этой подстановки (замер партии #4: 21 тест
        # protocol_insider_activity_monitor покраснел именно на Path(None)).
        return None
    if _same_target(path, tree_default):
        result = _tree_default_target(Path(path))
    else:
        result = Path(path)
    return str(result) if isinstance(path, str) else result


def _tree_default_target(default: Path) -> Path:
    """Куда на самом деле писать СОБСТВЕННОЕ умолчание дерева.

    Порядок разрешения (первый сработавший выигрывает):

    1. :data:`LIVE_STATE_IN_TESTS_ENV` — осознанный обход из теста, который
       МЕРЯЕТ прод-ветку (сохранён без изменений: на нём стоят существующие
       положительные контроли);
    2. :func:`under_test` — прогон тестов уводится ВСЕГДА. Стоит ВЫШЕ
       прод-признака намеренно: иначе унаследованный ``SPA_ENV=production``
       (прогон pytest на прод-машине, где переменная уже в окружении) вернул бы
       ровно ту аварию цикла #274, ради которой увод и появился. Гарантия
       «прогон тестов не пачкает дерево» не имеет права зависеть от env;
    3. :func:`live_state_writes_allowed` — прод-запуск, пишем в дерево;
    4. иначе — песочница. Сюда попадает третий сценарий, из-за которого всё
       затевалось: обычный запуск инструмента (аудит, ``python3 -c "import
       spa_core.analytics.x"``) — не pytest и не прод.

    Имя файла сохраняется — как и в :func:`sandboxed_state_path`.
    """
    if os.environ.get(LIVE_STATE_IN_TESTS_ENV):
        return default
    if under_test():
        return test_state_root() / default.name
    if live_state_writes_allowed():
        return default
    return test_state_root() / default.name


def _same_target(a, b) -> bool:
    """Указывают ли два пути на ОДИН файл — с точностью до нормализации.

    Сравнивать сырые строки нельзя: писатели этого семейства резолвят путь
    по-разному (``os.path.normpath(_LOG_PATH)``, ``os.path.abspath(...)``,
    ``Path(...)``), а замороженное умолчание хранится «как объявлено» —
    с ``../..`` внутри. Замер партии #3: из-за этого восемь трекаемых
    ``data/*_log.json`` продолжали писаться в дерево, хотя увод формально стоял.
    """
    return os.path.normpath(os.path.abspath(str(a))) == os.path.normpath(
        os.path.abspath(str(b))
    )
