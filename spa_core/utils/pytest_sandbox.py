#!/usr/bin/env python3
"""Песочница состояния под pytest — СВОЯ на прогон, а не общая на весь хост.

Зачем этот модуль
------------------------------------------------------------------------------
Модули с состоянием (`telegram/owner_decisions.py`, `telegram/prefs.py`,
`telegram/alert_actions.py`) сами уводят тесты в сторону от живого `data/` — это
правильно и приехало уроком «прогон тестов ЗАГЛУШИЛ живой чат владельца»: модуль
обязан защищаться сам, а не надеяться, что каждый автор теста вспомнит подменить путь.

Но уводили они в ОДИН файл на весь хост — `tempfile.gettempdir()/spa_*_pytest.json`,
без сброса между тестами, между файлами и между ПРОГОНАМИ. Файл жил, пока его не
уберёт ОС.

До 20.08 это было безвредно: историю журнала между прогонами никто не читал.
Анти-шторм (`owner_decisions.throttle_state`, окно 6 ч; приехал по инциденту
«200+ копий одного решения за ночь») стал ПЕРВЫМ таким читателем — и песочница
оказалась самоотравляющейся: прогон подавлял отправку, потому что «эта же карточка
уходила N минут назад», где N минут назад был ПРЕДЫДУЩИЙ прогон на этой машине.

Замер (цикл #320, чистый origin/main 5e431566c): два прогона подряд в пределах часа —
первый зелёный, второй роняет ровно пять тестов
(`test_owner_notify.py` ×4, `test_telegram_outbound_guard.py` ×1) со строкой
«anti-storm: та же карточка уходила 0 мин назад без ответа».

Почему этого никто не поймал
------------------------------------------------------------------------------
У дефекта период полураспада 6 часов, и он невидим обеим штатным проверкам:

* **CI зелёный по построению** — Linux-раннер одноразовый, песочница всегда пуста;
* **сверка «моё дерево против контроля на чистом origin» это НЕ ловит** — обе стороны
  читают ОДНУ И ТУ ЖЕ песочницу и краснеют одинаково, разница остаётся нулевой.

Тот же родовой класс, что ведётся в очереди: изоляция честно отвечает на СВОЙ вопрос
(«не трогаем ли мы живое состояние?») и читается как ответ на нужный
(«независим ли прогон от прошлых прогонов?»).

Как устроено
------------------------------------------------------------------------------
Одна временная директория на прогон, все песочницы — файлы внутри неё:

1. путь директории лежит в окружении (`SPA_PYTEST_SANDBOX_DIR`) ⇒ **дочерние процессы
   наследуют её вместе с окружением**. Это обязательное свойство: эффекты, которые
   видны только в проде, меряются в ДОЧЕРНЕМ процессе (урок «pytest-диверсия ослепляет
   тесты эффекта») — разъедься там песочница, тест мерил бы пустоту;
2. имя детерминированное (`spa_pytest_sandbox_<pid>`) — путь можно назвать в отчёте и
   найти руками, в отличие от `mkdtemp`;
3. pid на macOS переиспользуются, поэтому создатель директории, найдя её уже
   существующей, СНОСИТ её содержимое: чужой мусор под нашим именем — не наше состояние;
4. по выходу создателя (и только его) директория убирается. `SPA_PYTEST_SANDBOX_KEEP=1`
   оставляет её для разбора;
5. у каждого воркера `pytest-xdist` песочница СВОЯ (ключ окружения несёт `gw*`): воркеры
   наследуют окружение контроллера, и общая на всех песочница вернула бы тот же дефект
   внутри одного прогона — параллельная полоса описана в `pytest.ini` как штатная.

**Живое состояние по-прежнему не трогается ни одной строкой** — меняется только адрес
песочницы. Заслоны (анти-шторм, дедуп) НЕ ослаблены: внутри одного прогона они работают
ровно как раньше, что закреплено обратным контролем в
`spa_core/tests/test_pytest_sandbox_is_per_run.py`.
"""

from __future__ import annotations

import atexit
import os
import shutil
import tempfile
from pathlib import Path

#: Директория песочницы этого прогона. Наследуется дочерними процессами.
SESSION_DIR_ENV = "SPA_PYTEST_SANDBOX_DIR"

#: Не убирать директорию по выходу (разбор после падения).
KEEP_ENV = "SPA_PYTEST_SANDBOX_KEEP"

_DIR_PREFIX = "spa_pytest_sandbox_"


#: Идентификатор воркера pytest-xdist (пусто — обычный, однопроцессный прогон).
XDIST_WORKER_ENV = "PYTEST_XDIST_WORKER"


def _keep_requested() -> bool:
    return os.environ.get(KEEP_ENV, "").strip().lower() in ("1", "true", "yes", "on")


def _worker() -> str:
    """Кто мы в параллельном прогоне: ``gw0``/``gw1``/… либо пусто."""
    return os.environ.get(XDIST_WORKER_ENV, "").strip()


def _env_key() -> str:
    """Ключ окружения СВОЙ у каждого воркера xdist.

    Воркеры наследуют окружение контроллера. Будь ключ один на всех, они поделили бы
    одну песочницу — и анти-шторм подавлял бы отправку в одном воркере из-за записи
    другого. Это ровно тот же дефект, что чинится здесь, только на масштабе одного
    прогона (`pytest.ini` описывает параллельную полосу как штатную).
    """
    worker = _worker()
    return f"{SESSION_DIR_ENV}__{worker}" if worker else SESSION_DIR_ENV


def _cleanup(path: str) -> None:
    """Убрать директорию прогона. Никогда не бросает — это уборка, а не проверка."""
    if _keep_requested():
        return
    shutil.rmtree(path, ignore_errors=True)


def session_dir() -> Path:
    """Директория песочницы ЭТОГО прогона (создаётся при первом обращении).

    Повторный вызов в том же процессе и любой вызов в дочернем процессе отдают ТУ ЖЕ
    директорию (адрес живёт в окружении). Новый прогон — новая директория.
    """
    key = _env_key()
    existing = os.environ.get(key, "").strip()
    if existing:
        path = Path(existing)
        # Дочерний процесс мог стартовать раньше, чем родитель что-либо записал.
        path.mkdir(parents=True, exist_ok=True)
        return path

    worker = _worker()
    suffix = f"_{worker}" if worker else ""
    path = Path(tempfile.gettempdir()) / f"{_DIR_PREFIX}{os.getpid()}{suffix}"
    # pid переиспользуются: то, что лежит под нашим именем ДО нас, — чужой мусор.
    # Оставить его = вернуть ровно тот дефект, ради которого написан модуль.
    if path.exists():
        shutil.rmtree(path, ignore_errors=True)
    path.mkdir(parents=True, exist_ok=True)
    os.environ[key] = str(path)
    # Регистрирует уборку ТОЛЬКО создатель: дочерний процесс, унаследовавший адрес,
    # не смеет унести песочницу из-под родителя, когда завершится раньше него.
    atexit.register(_cleanup, str(path))
    return path


def sandbox_path(name: str) -> Path:
    """Файл-песочница ``name`` внутри директории этого прогона.

    ``name`` — простое имя файла (``spa_owner_decisions_pytest.json``), без разделителей
    пути: песочница обязана оставаться внутри своей директории.
    """
    if not name or "/" in name or "\\" in name or name in (".", ".."):
        raise ValueError(f"имя песочницы должно быть простым именем файла, получено: {name!r}")
    return session_dir() / name
