#!/bin/bash
# scripts/lib/starvation_verdict.sh — классификация вердикта шага 0a-ГОЛОД.
#
# Вынесено из `agent_orchestrator.sh` отдельным файлом ровно затем, чтобы у классификации
# был ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: тело обёртки целиком запускает цикл и потому в тесте
# исполнимо только целиком, через песочницу с подменой путей. Отдельный sourceable-файл
# проверяется вызовом функции с конкретной парой (код, вывод) — а именно на паре
# «код 1, трассировка» прежний контроль и промахивался.
#
# **Почему это вообще функция, а не три строки `if`.** 12.09 сторож голодания умер на
# собственном импорте, вышел с кодом 1 — и обёртка, у которой 1 означало «НАХОДКА»,
# вклеила трассировку в промпт цикла словами «возьми ЭТУ карточку первой». Единицу
# выдаёт CPython при любом необработанном исключении, поэтому «сторож упал» было
# неотличимо от «сторож нашёл голодающий приказ» ПО ПОСТРОЕНИЮ. Тест, который обязан
# был это поймать, изображал поломку кодом 7 — кодом, которого у падающего python-скрипта
# не бывает: контроль существовал и ни разу не видел настоящей аварии.
#
# Контракт (см. докстринг `scripts/check_owner_order_starvation.py`):
#   0 — измерено, голода нет            → промпт не трогаем
#   1 — сторож НЕ ДОШЁЛ до вердикта     → «НЕ ИЗМЕРЕНО» в промпт
#   2 — измерено не полностью (ref)     → «НЕ ИЗМЕРЕНО» в промпт
#   3 — НАХОДКА                         → находка в начало промпта
#   иное / файла нет                    → «НЕ ИЗМЕРЕНО» в промпт
#
# Перекос версий обёртки и скрипта (прод-дерево отстаёт от origin по построению) падает
# в безопасную сторону в ОБЕ стороны: старый скрипт отдаст находку кодом 1 и она станет
# «НЕ ИЗМЕРЕНО» (сессия проверит руками), новый скрипт отдаст 3 старой обёртке — тоже
# «НЕ ИЗМЕРЕНО». Ни один перекос не превращает находку в тишину.

# starvation_prefix <код> <вывод> → печатает префикс промпта (пустая строка = не трогать).
starvation_prefix() {
    local rc="$1" out="$2"
    case "$rc" in
        3)
            printf '%s' "ШАГ 0a-ГОЛОД — НАХОДКА, исполняется ПЕРВЫМ, до шага 0a и до разбора \
очереди (исключение — активная авария/стоп-кран): ${out}. Возьми ЭТУ карточку первой; если \
берёшь другую — назови причину в журнале. Дальше — обычный протокол. "
            ;;
        0)
            : # голода нет — промпт не засоряем, иначе находка перестанет быть сигналом
            ;;
        1)
            printf '%s' "ШАГ 0a-ГОЛОД НЕ ИЗМЕРЕН: сторож НЕ ДОШЁЛ ДО ВЕРДИКТА (код 1 — \
необработанное исключение в самом стороже, а НЕ находка): ${out}. Это НЕ «приказ владельца \
не голодает» — проверь голодание руками перед выбором задачи и заведи карточку на сам сторож. "
            ;;
        *)
            printf '%s' "ШАГ 0a-ГОЛОД НЕ ИЗМЕРЕН (код ${rc}): ${out}. Это НЕ «приказ владельца \
не голодает» — проверь голодание руками перед выбором задачи и заведи карточку на сам сторож. "
            ;;
    esac
}
