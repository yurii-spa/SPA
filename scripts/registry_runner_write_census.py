def _func_index(tree: ast.Module) -> Dict[Tuple[str, ...], Any]:
    """Функции модуля и методы его классов — тем же ключом, что `measure_module` (`f`/`m`)."""
    out: Dict[Tuple[str, ...], Any] = {}
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out[("f", n.name)] = n
        elif isinstance(n, ast.ClassDef):
            for b in n.body:
                if isinstance(b, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    out[("m", n.name, b.name)] = b
    return out


def _entry_key_of(entry: Optional[str]) -> Optional[Tuple[str, ...]]:
    if not entry:
        return None
    if "." in entry:
        cls, meth = entry.split(".", 1)
        return ("m", cls, meth)
    return ("f", entry)


def _call_edges(funcs: Dict[Tuple[str, ...], Any]) -> Dict[Tuple[str, ...], List[Tuple[int, Tuple[str, ...]]]]:
    """Рёбра графа вызовов ВНУТРИ модуля с номером СТРОКИ вызова.

    Правило совпадает с обходом `measure_module` (по имени, с избытком: `self.x()` берёт метод `x`
    любого класса модуля) — иначе причина объясняла бы ДРУГОЙ граф, чем тот, которым получен
    вердикт `WRITE_REACHABLE`, и предмет разошёлся бы с мерой (знакомый дефект D6).
    """
    plain = {k[1] for k in funcs if k[0] == "f"}
    by_attr: Dict[str, List[Tuple[str, ...]]] = {}
    for k in funcs:
        if k[0] == "m":
            by_attr.setdefault(k[2], []).append(k)
    out: Dict[Tuple[str, ...], List[Tuple[int, Tuple[str, ...]]]] = {}
    for key, fn in funcs.items():
        edges: List[Tuple[int, Tuple[str, ...]]] = []
        for node in ast.walk(fn):
            if not isinstance(node, ast.Call):
                continue
            f = node.func
            if isinstance(f, ast.Name) and f.id in plain:
                edges.append((node.lineno, ("f", f.id)))
            elif isinstance(f, ast.Attribute):
                for ck in by_attr.get(f.attr, []):
                    edges.append((node.lineno, ck))
        out[key] = edges
    return out


def _body_span(fn: Any) -> Set[int]:
    """Строки ТЕЛА функции: строка `def` исключена — она исполняется при импорте у КАЖДОГО метода."""
    return set(range(fn.lineno + 1, (fn.end_lineno or fn.lineno) + 1))


def _write_holders(funcs: Dict[Tuple[str, ...], Any], write_lines: Set[int]) -> Set[Tuple[str, ...]]:
    return {k for k, fn in funcs.items()
            if write_lines & set(range(fn.lineno, (fn.end_lineno or fn.lineno) + 1))}


def _leads_to_write(key: Tuple[str, ...], edges, holders: Set[Tuple[str, ...]],
                    seen: Optional[Set[Tuple[str, ...]]] = None) -> bool:
    if key in holders:
        return True
    seen = seen or set()
    if key in seen:
        return False
    seen = seen | {key}
    return any(_leads_to_write(ck, edges, holders, seen) for _ln, ck in edges.get(key, []))


def _branch_ifs(fn: Any, line: int) -> List[Tuple[ast.If, Set[int]]]:
    """`If`, в ТЕЛЕ которых (а не в тесте) лежит строка, с диапазоном ВЗЯТОЙ ветви.

    Возвращает от внешнего к внутреннему: (узел, строки той ветви, где лежит `line`). Диапазон
    нужен, чтобы отличить «условие исполнено и ЛОЖНО» (ни одна строка ветви не исполнена) от
    «условие исполнено, ветвь взята, а вызов всё равно не исполнился» — второе causa не является.
    """
    out: List[Tuple[ast.If, Set[int]]] = []
    for node in ast.walk(fn):
        if not isinstance(node, ast.If):
            continue
        for branch in (node.body, node.orelse):
            if any(b.lineno <= line <= (b.end_lineno or b.lineno) for b in branch):
                span: Set[int] = set()
                for b in branch:
                    span |= set(range(b.lineno, (b.end_lineno or b.lineno) + 1))
                out.append((node, span))
                break
    out.sort(key=lambda t: t[0].lineno)
    return out


def _false_guard(fn: Any, line: int, executed: Set[int]) -> Optional[ast.If]:
    """УСЛОВИЕ, которое бегун ВЫЧИСЛИЛ и которое оказалось ЛОЖНЫМ прямо перед вызовом.

    Иначе — вызов не исполнился ПОСЛЕДСТВИЕМ: управление до его условия не дошло вовсе, и
    называть такое место причиной значило бы выдать следствие за причину (на оси в 129 модулей
    это ровно та разница, из-за которой первый замер дал `MIXED` у 80 из них).
    """
    best: Optional[ast.If] = None
    for node, span in _branch_ifs(fn, line):
        if node.lineno not in executed:
            continue          # условие не вычислялось — ветвь ниже судить нечем
        if span & executed:
            continue          # ветвь ВЗЯТА: ложным это условие не было
        best = node           # вычислено и ложно; внутреннее перекрывает внешнее
    return best


_FALSY_SENTINEL = object()


def _is_falsy_const(node: Optional[ast.AST]) -> bool:
    if node is None:
        return False
    try:
        return not bool(ast.literal_eval(node))
    except (ValueError, TypeError, SyntaxError, MemoryError, RecursionError):
        return False


def _guard_operands(test: ast.AST) -> Tuple[Set[str], Set[str]]:
    """(имена, строковые КЛЮЧИ), от которых зависит условие."""
    names: Set[str] = set()
    keys: Set[str] = set()
    for n in ast.walk(test):
        if isinstance(n, ast.Name):
            names.add(n.id)
        elif isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) \
                and n.func.attr in ("get", "pop") and n.args and _const(n.args[0]):
            keys.add(str(_const(n.args[0])))
        elif isinstance(n, ast.Subscript) and _const(n.slice):
            keys.add(str(_const(n.slice)))
    return names, keys


def _guard_cause(tree: ast.Module, holder: Any, test: ast.AST) -> Tuple[str, str]:
    """Откуда у условия взялась ЛОЖЬ: модуль сам передал · умолчание ложно · условие о данных.

    Порядок объявлен и значим: «модуль САМ передал ложную константу» сильнее «умолчание ложно»,
    потому что при обоих признаках исполнился именно переданный аргумент (контекст-путь зовёт свой
    легаси-движок), а умолчание до него не доходит.
    """
    names, keys = _guard_operands(test)
    want = names | keys
    if not want:
        return "DATA_CONDITION", "условие без операндов-имён"
    # (1) ложная константа, которую модуль САМ ПЕРЕДАЁТ под этим именем/ключом.
    # Судятся ТОЛЬКО аргументы вызова: словарь-литерал где угодно в файле вызовом не является, и
    # первый замер на этом ошибся — `{"opportunities": []}` в теле ОТВЕТА пустой ветви
    # `defi_cross_chain_yield_comparator` прочитался как «модуль сам выключает запись».
    passed: Set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        payloads: List[ast.AST] = list(node.args)
        for kw in node.keywords:
            if kw.arg and kw.arg in want and _is_falsy_const(kw.value):
                passed.add(kw.arg)
            payloads.append(kw.value)
        for arg in payloads:
            for sub in ast.walk(arg):
                if not isinstance(sub, ast.Dict):
                    continue
                for k, v in zip(sub.keys, sub.values):
                    ck = _const(k)
                    if ck and str(ck) in want and _is_falsy_const(v):
                        passed.add(str(ck))
    # имена, связанные с ключом: `x = cfg.get("k", d)` — условие об `x` есть условие о ключе `k`
    linked: Dict[str, Optional[ast.AST]] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and len(node.targets) == 1 \
                and isinstance(node.targets[0], ast.Name) and node.targets[0].id in want:
            for sub in ast.walk(node.value):
                if isinstance(sub, ast.Call) and isinstance(sub.func, ast.Attribute) \
                        and sub.func.attr in ("get", "pop") and sub.args and _const(sub.args[0]):
                    key = str(_const(sub.args[0]))
                    linked[key] = sub.args[1] if len(sub.args) > 1 else None
    for key in linked:
        if key in passed:
            return "SELF_DISABLED", f"модуль передаёт `{key}` ложной константой"
    if passed:
        return "SELF_DISABLED", f"модуль передаёт `{sorted(passed)[0]}` ложной константой"
    # (2) ложное УМОЛЧАНИЕ: параметр со значением по умолчанию либо `.get(key, <ложь>)`
    for key, default in linked.items():
        if _is_falsy_const(default) or default is None:
            return "FLAG_DEFAULT_FALSY", f"умолчание ключа `{key}` ложно, вызывающий его не кладёт"
    # ключ, прочитанный В САМОМ УСЛОВИИ: умолчание берётся ОТТУДА ЖЕ, а не из любого `.get` файла.
    # Первый замер сканировал весь файл и ошибся: `(analyze([_ctx_profile]) or {}).get("opportunities")`
    # в СОСЕДНЕЙ ветви `defi_cross_chain_yield_comparator` — чтение РЕЗУЛЬТАТА чужого вызова, а не флага.
    for node in ast.walk(test):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) \
                and node.func.attr in ("get", "pop") and node.args and _const(node.args[0]):
            key = str(_const(node.args[0]))
            if len(node.args) < 2 or _is_falsy_const(node.args[1]):
                return "FLAG_DEFAULT_FALSY", f"умолчание ключа `{key}` ложно, вызывающий его не кладёт"
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        a = node.args
        pos = list(a.posonlyargs) + list(a.args)
        for prm, dflt in zip(pos[len(pos) - len(a.defaults):], a.defaults):
            if prm.arg in want and _is_falsy_const(dflt):
                return "FLAG_DEFAULT_FALSY", f"умолчание параметра `{prm.arg}` ложно у {node.name}"
        for prm, dflt in zip(a.kwonlyargs, a.kw_defaults):
            if dflt is not None and prm.arg in want and _is_falsy_const(dflt):
                return "FLAG_DEFAULT_FALSY", f"умолчание параметра `{prm.arg}` ложно у {node.name}"
    # (3) условие о самих ВХОДНЫХ данных: операнды — параметры держателя либо локальные значения
    hold_params = _params_of(holder, is_method=True)[1] | _params_of(holder, is_method=False)[1]
    if names & hold_params:
        return "DATA_CONDITION", f"условие о входных данных: {sorted(names & hold_params)[0]}"
    return "UNNAMED", "операнд условия не разрешён ни во флаг, ни во входные данные"


def _module_silent_cause(repo: Path, mv: ModuleVerdict, lines: Optional[List[int]]) -> Dict[str, Any]:
    """Причина тишины ОДНОГО модуля: статика даёт граф, наблюдение — исполненные строки."""
    if lines is None:
        return {"cause": "UNNAMED", "detail": "наблюдение не несёт исполненных строк модуля",
                "sites": []}
    executed = set(lines)
    try:
        tree = _read_tree(repo / mv.path)
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        return {"cause": "UNNAMED", "detail": f"файл не разобран: {type(exc).__name__}: {exc}",
                "sites": []}
    write_lines = {w.line for w in mv.writes}
    if write_lines & executed:
        hit = sorted(write_lines & executed)
        return {"cause": "WRITE_LINE_EXECUTED",
                "detail": f"строка записи исполнена ({', '.join(map(str, hit[:3]))}), корзина пуста",
                "sites": []}
    funcs = _func_index(tree)
    entry = _entry_key_of(mv.entry)
    if entry not in funcs:
        return {"cause": "UNNAMED", "detail": f"входа `{mv.entry}` в файле нет — граф не построен",
                "sites": []}
    edges = _call_edges(funcs)
    holders = _write_holders(funcs, write_lines)
    # расходящиеся места: вызывающий ВОШЁЛ, вызов ведёт к записи, а СТРОКА вызова не исполнена
    sites: List[Dict[str, Any]] = []
    downstream: List[Dict[str, Any]] = []
    for key, fn in funcs.items():
        if not (_body_span(fn) & executed):
            continue
        for line, callee in edges.get(key, []):
            if callee == key or line in executed:
                continue
            if not _leads_to_write(callee, edges, holders):
                continue
            label = key[1] if key[0] == "f" else f"{key[1]}.{key[2]}"
            guard = _false_guard(fn, line, executed)
            if guard is not None:
                cause, detail = _guard_cause(tree, fn, guard.test)
                sites.append({"where": f"{label}:{line}", "cause": cause,
                              "guard": ast.unparse(guard.test)[:120], "detail": detail})
                continue
            rets = [n.lineno for n in ast.walk(fn)
                    if isinstance(n, ast.Return) and n.lineno in executed and n.lineno < line]
            downstream.append({"where": f"{label}:{line}",
                               "cause": "RETURNED_BEFORE_WRITE" if rets else "UNNAMED",
                               "guard": None,
                               "detail": (f"исполненный return в строке {max(rets)}" if rets else
                                          "ни вычисленного условия на вызове, ни выхода раньше него")})
    if not sites:
        # ни одного ВЫЧИСЛЕННОГО и ложного условия: причина — выход раньше вызова, если он наблюдён
        sites = [d for d in downstream if d["cause"] == "RETURNED_BEFORE_WRITE"] or downstream
    if not sites:
        return {"cause": "UNNAMED",
                "detail": "расходящегося места не нашлось: ни один вызов к записи не объяснён",
                "sites": []}
    kinds = {s["cause"] for s in sites}
    if len(kinds) == 1:
        one = sites[0]
        return {"cause": sites[0]["cause"], "detail": one["detail"], "sites": sites}
    return {"cause": "MIXED", "detail": "причины расходящихся мест РАЗНЫЕ: " + ", ".join(sorted(kinds)),
            "sites": sites}


def silent_causes(repo: Path, census: Census, obs: Optional[Dict[str, Any]],
                  axis: str = SILENT_CAUSE_AXIS) -> Dict[str, Any]:
    """Причины тишины у «вошёл и промолчал» внутри предмета объявленной оси (ADR-1008).

    Предмет вопроса — ПЕРЕСЕЧЕНИЕ двух объявлений: предмет оси (`axis_observed`, та же единственная
    дверь, которой его считает `measure()`) И статус бегуна `ok`. Остальные статусы молчат по
    основаниям, которые объясняются раньше всякого пути (ADR-1007 § 6б/в), и подстановка им причины
    ПУТИ была бы ответом не на их вопрос.

    Три исхода различимы (инв. #17): причина НАЗВАНА · причина НЕ НАЗВАНА (`UNNAMED` с основанием) ·
    наблюдения не было вовсе (`subject` пуст, `unmeasured_reason` назван). Ноль причин и
    «не мерили» не совпадают ни в одном выводе.
    """
    sputnik = axis_observed(census, obs, axis)
    if obs is None:
        return {"axis": axis, "status": SILENT_CAUSE_STATUS, "subject": 0, "causes": {},
                "per_module": [], "parity": {"silent_ok": None, "subject": 0, "agrees": None},
                "unmeasured_reason": "наблюдение не запускалось (--observe не задан)"}
    # Предмет взят У ОСИ, поэтому ось, спорящая сама с собой, делает и этот разбор НЕ ИЗМЕРЕННЫМ:
    # печатать причины над предметом, который прибор сам отказался назвать, значило бы объяснять
    # население, которого он не подтвердил (сцена-контроль: врущий счёт оси ⇒ разбор молчит).
    axis_parity = sputnik["parity"]
    if axis_parity["agrees"] is not True:
        return {"axis": axis, "status": SILENT_CAUSE_STATUS, "subject": 0, "causes": {},
                "per_module": [], "parity": {"silent_ok": None, "subject": 0, "agrees": None},
                "unmeasured_reason": (
                    f"предмет оси `{axis}` не подтверждён её же счётом "
                    f"(предмет {axis_parity['subject']}, счёт {axis_parity['exposure']})")}
    by_name = {m.module: m for m in census.modules}
    lines_of = {r["module"]: r.get("lines") for r in obs.get("per_module", [])}
    subject = [e for e in sputnik["per_module"]
               if e["outcome"] == "SILENT" and e["runner_status"] == SILENT_CAUSE_STATUS]
    causes = {k: 0 for k in SILENT_CAUSES}
    per_module: List[Dict[str, Any]] = []
    for e in subject:
        mv = by_name.get(e["module"])
        if mv is None:
            row = {"cause": "UNNAMED", "detail": "модуля нет в переписи", "sites": []}
        else:
            row = _module_silent_cause(repo, mv, lines_of.get(e["module"]))
        causes[row["cause"]] += 1
        per_module.append({"module": e["module"], **row})
    declared = sputnik["silent_by_status"].get(SILENT_CAUSE_STATUS)
    parity = {"silent_ok": declared, "subject": len(subject),
              "agrees": None if declared is None else declared == len(subject)}
    return {"axis": axis, "status": SILENT_CAUSE_STATUS, "subject": len(subject), "causes": causes,
            "per_module": per_module, "parity": parity, "unmeasured_reason": None}



# ─────── причина НЕВХОДА: почему бегун ответил `unchecked` (ADR-1009 = ADR-1008 § 7а) ───────


def read_runner_unchecked_markers(repo: Path) -> Dict[int, str]:
    """Литералы, которыми БЕГУН объясняет свой `unchecked` — из его AST, а не из копии в приборе.

    ADR-1007 § 6б и ADR-1008 § 2 назвали 42 `unchecked` словами «бегун не входит вовсе», и это
    УТВЕРЖДЕНИЕ О МЕХАНИЗМЕ, которого ни один замер не проверял: в `run()` бегуна к статусу
    `unchecked` ведут ДВА РАЗНЫХ пути — сентинел `UNCHECKED` из `_invoke` («ни один вход не
    биндит контекст», бегун действительно не вошёл) и ПАДЕНИЕ входа, который контекст принять
    МОГ, с диагнозом `_foreign_input_entrypoint` («вход требует доменный тип») — а туда бегун
    ВОШЁЛ. Один ярлык на два механизма, и ярлык назван по одному из них.

    Поэтому вторая, независимая сторона ответа берётся у САМОГО бегуна, но его слова читаются
    ПАРИТЕТОМ С ОБЪЯВЛЕНИЕМ (`RUNNER_UNCHECKED_MARKERS`), а не подстрокой, зашитой в прибор:
    появись у бегуна третий путь к `unchecked` или смени он формулировку — прибор обязан сказать
    НЕ ИЗМЕРЕНО, а не разложить новый механизм по двум старым именам. Своя копия текста молча
    отвечала бы о бегуне, которого в дереве уже нет (знакомый класс: мерка, сверяющая свои
    константы САМА С СОБОЙ, ADR-913).

    Возвращает {строка объявления → литерал}. Пусто ⇒ `NotMeasured`: судить о причинах
    `unchecked`, не найдя в бегуне ни одного объяснения, значило бы выдать догадку за замер.
    """
    runner = repo / RUNNER_REL
    if not runner.is_file():
        raise NotMeasured(f"бегуна нет: {runner}")
    try:
        tree = _read_tree(runner)
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        raise NotMeasured(f"бегун не разобран: {type(exc).__name__}: {exc}")
    found: Dict[int, str] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Return) or not isinstance(node.value, ast.Tuple):
            continue
        elts = node.value.elts
        if len(elts) != 3:
            continue
        if not (isinstance(elts[1], ast.Constant) and elts[1].value == UNENTERED_CAUSE_STATUS):
            continue
        detail = elts[2]
        # `"…" % (…)` — литерал в ЛЕВОЙ части: голова объяснения объявлена, хвост подставляется
        if isinstance(detail, ast.Constant) and isinstance(detail.value, str):
            found[node.lineno] = detail.value
        elif isinstance(detail, ast.BinOp) and isinstance(detail.left, ast.Constant) \
                and isinstance(detail.left.value, str):
            found[node.lineno] = detail.left.value
        else:
            raise NotMeasured(
                f"бегун объясняет `{UNENTERED_CAUSE_STATUS}` в строке {node.lineno} не литералом "
                f"({type(detail).__name__}) — объявление прибора такой формы не несёт")
    if not found:
        raise NotMeasured(
            f"в бегуне не найдено ни одного объявленного объяснения статуса `{UNENTERED_CAUSE_STATUS}`")
    return found


def _marker_head(literal: str) -> str:
    """ГОЛОВА объяснения: литерал до первой подстановки — она объявлена, хвост подставляется."""
    return literal.split("%")[0].rstrip()


def _marker_cause(detail: str, declared: Dict[int, str]) -> Optional[str]:
    """Причина по СЛОВАМ бегуна: голова объявленного литерала — начало его `detail`.

    Длинные головы пробуются первыми: вложись одно объяснение в другое, выбор «какое попалось
    раньше» зависел бы от порядка обхода, а не от текста (тот же довод, что у `PYTHONHASHSEED`).
    """
    for head in sorted({_marker_head(lit) for lit in declared.values() if _marker_head(lit)},
                       key=len, reverse=True):
        if detail.startswith(head):
            return RUNNER_UNCHECKED_MARKERS.get(head)
    return None


def _candidate_entries(tree: ast.Module, entry_methods: Tuple[str, ...]) -> Dict[str, Any]:
    """Входы-КАНДИДАТЫ: функции модуля и методы его классов, чьё ИМЯ объявлено бегуном.

    Спрашивается именно кандидат, а не выбранный статикой вход: выбор статики — её ответ, а
    вопрос «входил ли бегун» принадлежит ЛЮБОМУ входу, который бегун мог позвать. Перечень имён
    берётся у бегуна (`RunnerSide.entry_methods`, то же чтение AST, которым его получает
    `measure()`), поэтому второй копии правила у прибора нет.
    """
    out: Dict[str, Any] = {}
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name in entry_methods:
            out[n.name] = n
        elif isinstance(n, ast.ClassDef):
            for b in n.body:
                if isinstance(b, (ast.FunctionDef, ast.AsyncFunctionDef)) and b.name in entry_methods:
                    out[f"{n.name}.{b.name}"] = b
    return out


def _module_unentered_cause(repo: Path, mv: ModuleVerdict, lines: Optional[List[int]],
                            detail: Optional[str], entry_methods: Tuple[str, ...],
                            declared: Dict[int, str]) -> Dict[str, Any]:
    """Причина `unchecked` ОДНОГО модуля: исполненные строки входа — первая сторона, слова бегуна — вторая.

    Первая сторона НАБЛЮДЕНА и ни о чём не догадывается: строка тела входа исполнилась ⇒ бегун в
    него ВОШЁЛ. Вторая — ответ самого бегуна. Расхождение сторон есть НАХОДКА (`DISAGREED`), а не
    повод выбрать удобную: подставить одну из двух значило бы вернуть ровно тот дефект, которым
    ярлык `unchecked` и оказался на двух механизмах.
    """
    if lines is None:
        return {"cause": "UNNAMED", "detail": "наблюдение не несёт исполненных строк модуля",
                "entered_entries": [], "runner_said": None}
    said = _marker_cause(detail or "", declared)
    try:
        tree = _read_tree(repo / mv.path)
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        return {"cause": "UNNAMED", "detail": f"файл не разобран: {type(exc).__name__}: {exc}",
                "entered_entries": [], "runner_said": said}
    cands = _candidate_entries(tree, entry_methods)
    if not cands:
        return {"cause": "UNNAMED",
                "detail": "в файле нет ни одного входа с объявленным бегуном именем — входить было некуда",
                "entered_entries": [], "runner_said": said}
    executed = set(lines)
    entered = sorted(name for name, fn in cands.items() if _body_span(fn) & executed)
    by_lines = "ENTERED_RAISED_FOREIGN" if entered else "NO_ENTRY_BOUND"
    if said is None:
        return {"cause": "UNNAMED",
                "detail": (f"бегун объяснил статус словами, которых объявление прибора не несёт: "
                           f"{(detail or '')[:80]!r}"),
                "entered_entries": entered, "runner_said": None}
    if said != by_lines:
        return {"cause": "DISAGREED",
                "detail": (f"стороны РАСХОДЯТСЯ: исполненные строки говорят `{by_lines}`"
                           + (f" (вход {', '.join(entered)})" if entered else " (ни одна строка входа)")
                           + f", бегун — `{said}`"),
                "entered_entries": entered, "runner_said": said}
    if by_lines == "ENTERED_RAISED_FOREIGN":
        return {"cause": by_lines,
                "detail": (f"бегун ВОШЁЛ (исполнены строки тела {', '.join(entered)}) и вход отказал на "
                           f"Mapping — предмет статики существует, мешает ФОРМА контекста, а не отсутствие входа"),
                "entered_entries": entered, "runner_said": said}
    return {"cause": by_lines,
            "detail": (f"ни одна строка тела входов ({', '.join(sorted(cands))}) не исполнена — "
                       f"контекст не биндится ни одной формой; предмет статики под бегуном НЕ СУЩЕСТВУЕТ"),
            "entered_entries": [], "runner_said": said}


def unentered_causes(repo: Path, census: Census, obs: Optional[Dict[str, Any]],
                     axis: str = SILENT_CAUSE_AXIS) -> Dict[str, Any]:
    """Причины статуса `unchecked` внутри предмета объявленной оси (ADR-1009 = ADR-1008 § 7а).

    Предмет вопроса — ПЕРЕСЕЧЕНИЕ предмета оси (`axis_observed`, та же единственная дверь) И
    статуса бегуна `unchecked`, ровно как `silent_causes` делает это для `ok`. Вопрос у них
    РАЗНЫЙ: у `ok` спрашивают, почему вошедший не записал, здесь — ВХОДИЛ ЛИ ОН ВООБЩЕ.

    Три исхода различимы (инв. #17): причина НАЗВАНА · НЕ НАЗВАНА (`UNNAMED`/`DISAGREED` с
    основанием) · наблюдения не было вовсе (`subject` пуст, `unmeasured_reason` назван).
    """
    sputnik = axis_observed(census, obs, axis)
    empty = {"axis": axis, "status": UNENTERED_CAUSE_STATUS, "subject": 0, "causes": {},
             "per_module": [], "parity": {"unchecked": None, "subject": 0, "agrees": None}}
    if obs is None:
        return {**empty, "unmeasured_reason": "наблюдение не запускалось (--observe не задан)"}
    axis_parity = sputnik["parity"]
    if axis_parity["agrees"] is not True:
        return {**empty, "unmeasured_reason": (
            f"предмет оси `{axis}` не подтверждён её же счётом "
            f"(предмет {axis_parity['subject']}, счёт {axis_parity['exposure']})")}
    try:
        declared = read_runner_unchecked_markers(repo)
    except NotMeasured as exc:
        return {**empty, "unmeasured_reason": str(exc)}
    unknown = sorted({_marker_head(lit) for lit in declared.values()}
                     - set(RUNNER_UNCHECKED_MARKERS))
    if unknown:
        # Паритет с объявлением: новый путь бегуна к `unchecked` обязан СТАТЬ ВИДИМЫМ, а не
        # разойтись по двум старым именам — иначе прибор ответит о бегуне, которого нет в дереве.
        return {**empty, "unmeasured_reason": (
            "бегун объясняет `%s` словами, которых объявление прибора не несёт: %s"
            % (UNENTERED_CAUSE_STATUS, "; ".join(repr(u) for u in unknown)))}
    by_name = {m.module: m for m in census.modules}
    obs_of = {r["module"]: r for r in obs.get("per_module", [])}
    subject = [e for e in sputnik["per_module"]
               if e["outcome"] == "SILENT" and e["runner_status"] == UNENTERED_CAUSE_STATUS]
    causes = {k: 0 for k in UNENTERED_CAUSES}
    per_module: List[Dict[str, Any]] = []
    for e in subject:
        mv = by_name.get(e["module"])
        r = obs_of.get(e["module"]) or {}
        if mv is None:
            row = {"cause": "UNNAMED", "detail": "модуля нет в переписи",
                   "entered_entries": [], "runner_said": None}
        else:
            row = _module_unentered_cause(repo, mv, r.get("lines"), r.get("detail"),
                                          census.runner.entry_methods, declared)
        causes[row["cause"]] += 1
        per_module.append({"module": e["module"], **row})
    declared_n = sputnik["silent_by_status"].get(UNENTERED_CAUSE_STATUS)
    parity = {"unchecked": declared_n, "subject": len(subject),
              "agrees": None if declared_n is None else declared_n == len(subject)}
    return {"axis": axis, "status": UNENTERED_CAUSE_STATUS, "subject": len(subject),
            "causes": causes, "per_module": per_module, "parity": parity, "unmeasured_reason": None}


def unentered_causes_by_axis(repo: Path, census: Census,
                             obs: Optional[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """Разбор у КАЖДОЙ оси из `UNENTERED_AXES` — перечень осей объявлен, а не выбран зовом."""
    return {axis: unentered_causes(repo, census, obs, axis) for axis in UNENTERED_AXES}


# ───────────── различается ли МЕХАНИЗМ по протоколам (ADR-1010, заказ G999 п. 1б) ─────────────

def read_runner_protocols(repo: Path) -> Tuple[str, ...]:
    """Перечень протоколов — из AST БЕГУНА (`DEFAULT_PROTOCOLS`), а не из копии в приборе.

    Протокол — ВХОД наблюдения, и семь решений подряд (ADR-1002…1009) сняли свои числа на одном
    `aave_v3`, потому что вход имел умолчание и никто не спрашивал, зависит ли от него ОТВЕТ.
    Перечень берётся у того, кого мерим: смени бегун список — прибор обязан поехать за ним, а не
    отвечать о протоколах, которых в дереве нет.

    Пусто / не литерал / нет объявления ⇒ `NotMeasured`. Выдумать перечень здесь значило бы
    объявить инвариантность по множеству, которого бегун не знает.
    """
    runner = repo / RUNNER_REL
    if not runner.is_file():
        raise NotMeasured(f"бегуна нет: {runner}")
    try:
        tree = _read_tree(runner)
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        raise NotMeasured(f"бегун не разобран: {type(exc).__name__}: {exc}")
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        if not any(isinstance(t, ast.Name) and t.id == RUNNER_PROTOCOLS_NAME for t in node.targets):
            continue
        try:
            value = ast.literal_eval(node.value)
        except (ValueError, TypeError, SyntaxError) as exc:
            raise NotMeasured(
                f"`{RUNNER_PROTOCOLS_NAME}` у бегуна не литерал ({type(node.value).__name__}): {exc}")
        if not isinstance(value, (list, tuple)):
            raise NotMeasured(
                f"`{RUNNER_PROTOCOLS_NAME}` у бегуна не перечень, а {type(value).__name__}")
        names = tuple(str(v) for v in value)
        if not names:
            raise NotMeasured(f"`{RUNNER_PROTOCOLS_NAME}` у бегуна ПУСТ — мерить не на чем")
        return names
    raise NotMeasured(f"у бегуна нет объявления `{RUNNER_PROTOCOLS_NAME}`")


def _compare_across_values(by_value: Dict[str, Dict[str, str]]) -> Dict[str, Any]:
    """ПОИМЁННОЕ сравнение одного ярлыка у одних и тех же модулей между значениями ВХОДА.

    Ядро ОДНО на все входы наблюдения (протокол — ADR-1010, предел модуля — ADR-1011): своя
    копия у второго входа отвечала бы на свой вопрос, а имя, называющее один из входов, уже
    было бы обещанием, которого ядро не держит.

    Основание — модуль, а не счёт: равные счёта при разных модулях есть ровно тот зелёный ответ
    на СВОЙ вопрос, которым три сторожа сайта пропустили шестнадцать перепечатанных литералов.
    """
    values = sorted(by_value)
    seen = [set(by_value[v]) for v in values]
    everywhere = set.intersection(*seen) if seen else set()
    union = set().union(*seen) if seen else set()
    moved = [{"module": m,
              "in": [v for v in values if m in by_value[v]],
              "out": [v for v in values if m not in by_value[v]]}
             for m in sorted(union - everywhere)]
    differs = []
    for m in sorted(everywhere):
        labels = {v: by_value[v][m] for v in values}
        if len(set(labels.values())) > 1:
            differs.append({"module": m, "labels": labels})
    found = {_PD_MOVED: moved, _PD_DIFFERS: differs}
    return {"verdict": _PV_INVARIANT if not moved and not differs else _PV_VARIES,
            "values": values,
            "subject": {v: len(by_value[v]) for v in values},
            "union": len(union), "intersection": len(everywhere),
            # «Предмет ПУСТ под всеми протоколами» и «сверено поимённо» — РАЗНЫЕ ответы, хотя
            # вердикт у них один: пустому предмету различаться нечем, и выдать это за сверку
            # значило бы назвать инвариантностью отсутствие населения (инв. #17, то же правило,
            # которым `unentered_causes` печатает пустой предмет своими словами).
            "subject_empty": not union,
            "differences": found,
            "counts": {k: len(v) for k, v in found.items()},
            "unmeasured_reason": None}


def _side_labels(repo: Path, census: Census, obs: Dict[str, Any], side: str) -> Dict[str, str]:
    """Ярлык объявленной стороны у каждого модуля её предмета. Неизмеренная сторона ⇒ `NotMeasured`."""
    if side == "runner_status":
        return {r["module"]: r["status"] for r in obs.get("per_module", [])}
    if side == "silent":
        sc = silent_causes(repo, census, obs)
        if sc.get("unmeasured_reason"):
            raise NotMeasured(f"сторона `{side}`: {sc['unmeasured_reason']}")
        return {e["module"]: e["cause"] for e in sc["per_module"]}
    if side.startswith("unentered:"):
        axis = side.split(":", 1)[1]
        uc = unentered_causes(repo, census, obs, axis)
        if uc.get("unmeasured_reason"):
            raise NotMeasured(f"сторона `{side}`: {uc['unmeasured_reason']}")
        if uc["parity"]["agrees"] is False:
            raise NotMeasured(
                f"сторона `{side}`: предмет ({uc['parity']['subject']}) расходится со свёрткой "
                f"статуса ({uc['parity']['unchecked']})")
        return {e["module"]: e["cause"] for e in uc["per_module"]}
    raise NotMeasured(f"сторона `{side}` прибору неизвестна (объявление — `PROTOCOL_SIDES`)")


def protocol_variance(repo: Path, census: Census,
                      observations: Optional[Dict[str, Dict[str, Any]]],
                      absent_reason: Optional[str] = None) -> Dict[str, Any]:
    """Различается ли механизм бегуна по ПРОТОКОЛАМ (заказ G999 п. 1б = ADR-1009 § 7б).

    Вопрос появился потому, что ответ семи решений подряд снят на ОДНОМ протоколе: `--protocol`
    имел умолчание, и «измерено на `aave_v3`» читалось как «измерено». Это не придирка к форме:
    если население предмета зависит от протокола, то число, снятое на одном, есть число О НЁМ, и
    починка, назначенная по нему, лечит одну восьмую.

    Три исхода различимы (инв. #17): `INVARIANT` (ИЗМЕРЕНО и поимённо совпало) · `VARIES`
    (различие НАЗВАНО — модулями, протоколами и видом) · `UNMEASURED` с причиной (наблюдений
    меньше `PROTOCOL_VARIANCE_MIN` · сторона не разобралась хотя бы под одним протоколом ·
    объявление бегуна не прочитано). Отдельно печатается `declared_not_observed`: ответ
    принадлежит НАБЛЮДЁННЫМ протоколам, а не всему объявлению бегуна.
    """
    empty: Dict[str, Any] = {"verdict": _PV_UNMEASURED, "protocols": [], "sides": {},
                             "min_required": PROTOCOL_VARIANCE_MIN,
                             "declared": [], "declared_not_observed": []}
    if not observations:
        return {**empty, "unmeasured_reason": (
            absent_reason or "наблюдение не запускалось (--observe не задан)")}
    protocols = sorted(observations)
    if len(protocols) < PROTOCOL_VARIANCE_MIN:
        return {**empty, "protocols": protocols, "unmeasured_reason": (
            f"наблюдений {len(protocols)} < {PROTOCOL_VARIANCE_MIN}: один протокол даёт ЗНАЧЕНИЕ, "
            f"а не различие — «различий нет» из него не следует")}
    try:
        declared = list(read_runner_protocols(repo))
    except NotMeasured as exc:
        return {**empty, "protocols": protocols, "unmeasured_reason": (
            f"перечень протоколов бегуна не прочитан: {exc}")}
    sides: Dict[str, Dict[str, Any]] = {}
    for side in PROTOCOL_SIDES:
        by_protocol: Dict[str, Dict[str, str]] = {}
        reason: Optional[str] = None
        for p in protocols:
            try:
                by_protocol[p] = _side_labels(repo, census, observations[p], side)
            except NotMeasured as exc:
                reason = f"протокол `{p}`: {exc}"
                break
        if reason is not None:
            sides[side] = {"verdict": _PV_UNMEASURED, "values": protocols, "subject": {},
                           "union": 0, "intersection": 0, "subject_empty": None,
                           "differences": {k: [] for k in PROTOCOL_DIFFERENCES},
                           "counts": {k: 0 for k in PROTOCOL_DIFFERENCES},
                           "unmeasured_reason": reason}
            continue
        sides[side] = _compare_across_values(by_protocol)
    verdicts = {s["verdict"] for s in sides.values()}
    # fail-CLOSED: неизмеренная сторона НЕ даёт итогу права сказать «инвариантно» по остальным.
    if _PV_UNMEASURED in verdicts:
        overall = _PV_UNMEASURED
        reason: Optional[str] = "; ".join(
            f"{name}: {s['unmeasured_reason']}" for name, s in sides.items()
            if s["verdict"] == _PV_UNMEASURED)
    else:
        overall = _PV_VARIES if _PV_VARIES in verdicts else _PV_INVARIANT
        reason = None
    return {"verdict": overall, "protocols": protocols, "sides": sides,
            "min_required": PROTOCOL_VARIANCE_MIN, "declared": declared,
            "declared_not_observed": [p for p in declared if p not in observations],
            "observed_not_declared": [p for p in protocols if p not in declared],
            "unmeasured_reason": reason}


def render_protocol_variance(pv: Dict[str, Any]) -> List[str]:
    """Печать сравнения. Различие НАЗЫВАЕТСЯ поимённо, инвариантность — числом СВЕРЕННЫХ модулей."""
    out = [f"  РАЗЛИЧИЕ МЕХАНИЗМА ПО ПРОТОКОЛАМ (ADR-1010) — наблюдений {len(pv['protocols'])}"
           f" ({', '.join(pv['protocols']) or '—'})"]
    # Охват печатается ДО вердикта и при любом вердикте: «о каких протоколах этот ответ» —
    # вопрос, на который НЕ ИЗМЕРЕНО отвечать не отказывается.
    if pv.get("declared"):
        if pv["declared_not_observed"]:
            out.append(f"    ответ принадлежит НАБЛЮДЁННЫМ протоколам: объявлено бегуном "
                       f"{len(pv['declared'])}, не наблюдалось "
                       f"{len(pv['declared_not_observed'])} "
                       f"({', '.join(pv['declared_not_observed'])})")
        else:
            out.append(f"    наблюдены ВСЕ {len(pv['declared'])} протокола объявления бегуна "
                       f"`{RUNNER_PROTOCOLS_NAME}`")
        if pv["observed_not_declared"]:
            out.append(f"    наблюдались НЕ ОБЪЯВЛЕННЫЕ бегуном: "
                       f"{', '.join(pv['observed_not_declared'])}")
    if pv["verdict"] == _PV_UNMEASURED:
        out.append(f"    ⚠️ НЕ ИЗМЕРЕНО — {pv['unmeasured_reason']}")
        return out
    for side, s in pv["sides"].items():
        if s["verdict"] == _PV_UNMEASURED:
            out.append(f"    {side:<42} ⚠️ НЕ ИЗМЕРЕНО — {s['unmeasured_reason']}")
            continue
        counts = "/".join(str(s["subject"][p]) for p in s["values"])
        if s["verdict"] == _PV_INVARIANT and s.get("subject_empty"):
            out.append(f"    {side:<42} предмет ПУСТ под всеми протоколами — измерено и равно "
                       f"нулю, сверкой это не является")
            continue
        if s["verdict"] == _PV_INVARIANT:
            out.append(f"    {side:<42} INVARIANT — предмет {counts}; совпал ПОИМЁННО "
                       f"({s['intersection']} модул(ей), union = intersect)")
            continue
        out.append(f"    {side:<42} VARIES — предмет {counts}; union {s['union']}, "
                   f"intersect {s['intersection']}; SUBJECT_MOVED "
                   f"{s['counts']['SUBJECT_MOVED']} · LABEL_DIFFERS {s['counts']['LABEL_DIFFERS']}")
        moved, differs = s["differences"][_PD_MOVED], s["differences"][_PD_DIFFERS]
        for e in moved[:_PV_SHOWN]:
            out.append(f"      ↔ {e['module']}: в предмете под {', '.join(e['in'])}; "
                       f"вне — {', '.join(e['out'])}")
        for e in differs[:_PV_SHOWN]:
            shown = ", ".join(f"{p}={lab}" for p, lab in e["labels"].items())
            out.append(f"      ≠ {e['module']}: {shown}")
        # Остаток считается по КАЖДОМУ виду отдельно: «всего минус 20» врёт, когда один вид короче
        # предела, — и это было бы число, не называющее своего производителя.
        rest = (len(moved) - min(_PV_SHOWN, len(moved))) + (len(differs) - min(_PV_SHOWN, len(differs)))
        if rest > 0:
            out.append(f"      … и ещё {rest} (полный перечень — `--json`, ключ "
                       f"`protocol_variance.sides['{side}'].differences`)")
    out.append("    НЕ ДОКЛАДЫВАЕТ: корзины ЗАПИСИ по протоколам (вопрос ADR-1002, и у `tree_data` "
               "есть свой конфаунд — накопление файлов последовательными прогонами в одном дереве)")
    return out


# ───────── предел модуля: ВТОРОЙ объявленный вход (ADR-1011, заказ G1000 п. 1г) ─────────

def read_runner_timeout(repo: Path) -> float:
    """Предел модуля — из AST БЕГУНА (`MODULE_TIMEOUT`), а не копией-литералом в приборе.

    Тот же довод, что у `read_runner_protocols`, и та же ловушка с другой стороны: перечень
    протоколов прибор у себя не держал вовсе, а предел держал — и держал ВЕРНЫЙ. Поэтому дефект
    и прожил девять решений: расхождения сегодня нет, и назвать его нечем, кроме вопроса «а кто
    тут объявляет?».

    Нет объявления · не числовой литерал · не положительное ⇒ `NotMeasured`. Подставить здесь
    `3.0` значило бы ответить о пределе, которого бегун не объявляет (инв. #17).
    """
    runner = repo / RUNNER_REL
    if not runner.is_file():
        raise NotMeasured(f"бегуна нет: {runner}")
    try:
        tree = _read_tree(runner)
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        raise NotMeasured(f"бегун не разобран: {type(exc).__name__}: {exc}")
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        if not any(isinstance(t, ast.Name) and t.id == RUNNER_TIMEOUT_NAME for t in node.targets):
            continue
        try:
            value = ast.literal_eval(node.value)
        except (ValueError, TypeError, SyntaxError) as exc:
            raise NotMeasured(
                f"`{RUNNER_TIMEOUT_NAME}` у бегуна не литерал ({type(node.value).__name__}): {exc}")
        # `bool` — подкласс `int`, и `MODULE_TIMEOUT = True` пределом не является.
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise NotMeasured(
                f"`{RUNNER_TIMEOUT_NAME}` у бегуна не число, а {type(value).__name__}")
        if value <= 0:
            raise NotMeasured(f"`{RUNNER_TIMEOUT_NAME}` у бегуна не положителен: {value}")
        return float(value)
    raise NotMeasured(f"у бегуна нет объявления `{RUNNER_TIMEOUT_NAME}`")


def _handler_is_timeout(handler: ast.ExceptHandler) -> bool:
    """Ловит ли обработчик именно ПРЕДЕЛ. Имя исключения читается у бегуна, род — по слову."""
    names: List[str] = []
    for node in ast.walk(handler.type) if handler.type is not None else []:
        if isinstance(node, ast.Name):
            names.append(node.id)
        elif isinstance(node, ast.Attribute):
            names.append(node.attr)
    return any(RUNNER_TIMEOUT_EXC_MARK in n.lower() for n in names)


def read_runner_timeout_status(repo: Path) -> str:
    """Каким СЛОВОМ бегун отвечает на сработавший предел — читается У НЕГО, паритетом.

    Ожидание контроля («при пределе ниже сна бегун обязан сказать `timeout`») есть утверждение
    О БЕГУНЕ, и вписать это слово в прибор значило бы снова свериться с собой: переименуй бегун
    статус — контроль объявил бы ЖИВОЙ вход мёртвым, то есть соврал бы в сторону ложной находки.
    Поэтому слово берётся из обработчика предела внутри `_run_module`.

    Нет обработчика · он ничего не записывает · записывает РАЗНЫЕ слова ⇒ `NotMeasured`: появись
    у бегуна второй ответ на предел — прибор обязан сказать «не измерено», а не выбрать удобное
    (тот же порядок, что у `RUNNER_UNCHECKED_MARKERS` в ADR-1009).
    """
    runner = repo / RUNNER_REL
    if not runner.is_file():
        raise NotMeasured(f"бегуна нет: {runner}")
    try:
        tree = _read_tree(runner)
    except (SyntaxError, UnicodeDecodeError, OSError) as exc:
        raise NotMeasured(f"бегун не разобран: {type(exc).__name__}: {exc}")
    calls: List[str] = []
    seen_entry = False
    for node in ast.walk(tree):
        if not (isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                and node.name == RUNNER_MODULE_CALL):
            continue
        seen_entry = True
        for sub in ast.walk(node):
            if not (isinstance(sub, ast.ExceptHandler) and _handler_is_timeout(sub)):
                continue
            for call in ast.walk(sub):
                if (isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute)
                        and call.func.attr == RUNNER_RECORD and len(call.args) >= 2
                        and isinstance(call.args[1], ast.Constant)
                        and isinstance(call.args[1].value, str)):
                    calls.append(call.args[1].value)
    if not seen_entry:
        raise NotMeasured(f"у бегуна нет `{RUNNER_MODULE_CALL}` — предел звать некому")
    if not calls:
        raise NotMeasured(
            f"`{RUNNER_MODULE_CALL}` не записывает статуса в обработчике предела "
            f"(искали `{RUNNER_RECORD}` со строковым литералом)")
    if len(set(calls)) > 1:
        raise NotMeasured(
            f"на предел бегун отвечает РАЗНЫМИ словами {sorted(set(calls))} — выбрать удобное "
            f"значило бы раскладывать новый механизм по старым именам")
    return calls[0]


#: Сцена положительного контроля. Синтетический модуль СЕЕТСЯ в `sys.modules` (бегун входит
#: `importlib.import_module`), поэтому дерево под прибором не правится ни байтом.
_KNOB_CONTROL = r'''
import json, os, sys, tempfile, time, types
repo, mod_name, sleep_s, below, above, out_path = sys.argv[1:7]
sys.path.insert(0, repo)
from spa_core.analytics import signal_aggregator as sa

_sleep = float(sleep_s)
mod = types.ModuleType("spa_core.analytics." + mod_name)


def analyze(context):
    time.sleep(_sleep)
    return 1.0


mod.analyze = analyze
sys.modules["spa_core.analytics." + mod_name] = mod
info = {"module": mod_name, "class": None, "weight": 0.0, "category": "knob-control"}
out = {}
with tempfile.TemporaryDirectory(prefix="rrwc_knob_") as sandbox:
    for side, t in (("below", float(below)), ("above", float(above))):
        t0 = time.time()
        try:
            agg = sa.SignalAggregator(data_dir=sandbox, module_timeout=t)
            agg._run_module(info, "knob_control",
                            {"cycle_ts": "knob", "source": "timeout_knob_control"})
            log = getattr(agg, "_log", None)
            status = log[-1].get("status") if log else None
            error = None if status is not None else "бегун не записал ни одной строки"
        except BaseException as exc:
            status, error = None, "%s: %s" % (type(exc).__name__, exc)
        out[side] = {"timeout": t, "status": status, "error": error,
                     "seconds": round(time.time() - t0, 3)}
json.dump(out, open(out_path, "w", encoding="utf-8"), ensure_ascii=False)
'''


def timeout_knob_control(repo: Path, *, python: str = sys.executable,
                         sleep_s: float = KNOB_SLEEP_S, below: float = KNOB_BELOW_S,
                         above: float = KNOB_ABOVE_S) -> Dict[str, Any]:
    """Доходит ли вход «предел» до РЕШЕНИЯ бегуна — положительный контроль, а не чтение кода.

    Без него «население не зависит от предела» неотличимо от «предел ни на что не влияет»:
    первое есть свойство системы, второе — дефект проводки, и НАБЛЮДЕНИЕ у них одно и то же.
    Контроль ставит сцену, где ответ ОБЯЗАН различаться: модуль спит дольше одного предела и
    короче другого, и зовёт его НАСТОЯЩИЙ бегун названного дерева.

    Три исхода (инв. #17): `KNOB_LIVE` — ниже сна бегун сказал своё слово предела, выше не
    сказал; `KNOB_DEAD` — обе стороны ответили ОДИНАКОВО (вход до решения не доходит);
    `UNMEASURED` с причиной — слово предела не прочитано, бегун не ввезён, сцена не отработала.
    """
    empty: Dict[str, Any] = {"verdict": _KB_UNMEASURED, "expected_status": None, "sides": {},
                             "sleep_s": sleep_s, "below_s": below, "above_s": above,
                             "dead_reason": None}
    if not (below < sleep_s < above):
        return {**empty, "unmeasured_reason": (
            f"сцена контроля неисполнима: требуется {below} < {sleep_s} < {above}")}
    try:
        expected = read_runner_timeout_status(repo)
    except NotMeasured as exc:
        return {**empty, "unmeasured_reason": f"слово предела у бегуна не прочитано: {exc}"}
    with tempfile.TemporaryDirectory(prefix="rrwc_knob_out_") as tmp:
        out_path = Path(tmp) / "knob.json"
        try:
            proc = subprocess.run(
                [python, "-c", _KNOB_CONTROL, str(repo), KNOB_MODULE_NAME, str(sleep_s),
                 str(below), str(above), str(out_path)],
                capture_output=True, text=True, timeout=_KNOB_RUN_TIMEOUT_S)
        except (OSError, subprocess.SubprocessError) as exc:
            return {**empty, "expected_status": expected, "unmeasured_reason": (
                f"сцена контроля не запустилась: {type(exc).__name__}: {exc}")}
        if not out_path.is_file():
            return {**empty, "expected_status": expected, "unmeasured_reason": (
                f"сцена контроля не отдала результата (код {proc.returncode}): "
                f"{(proc.stderr or '').strip()[-300:]}")}
        try:
            sides = json.loads(out_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            return {**empty, "expected_status": expected, "unmeasured_reason": (
                f"результат контроля не прочитан: {type(exc).__name__}: {exc}")}
    if set(sides) != {"below", "above"}:
        return {**empty, "expected_status": expected, "sides": sides, "unmeasured_reason": (
            f"сцена вернула не обе стороны, а {sorted(sides)}")}
    errs = {s: v.get("error") for s, v in sides.items() if v.get("error")}
    if errs:
        return {**empty, "expected_status": expected, "sides": sides, "unmeasured_reason": (
            "бегун сцены не ответил: " + "; ".join(f"{k}: {v}" for k, v in errs.items()))}
    below_hit = sides["below"].get("status") == expected
    above_hit = sides["above"].get("status") == expected
    live = below_hit and not above_hit
    return {"verdict": _KB_LIVE if live else _KB_DEAD, "expected_status": expected,
            "sides": sides, "sleep_s": sleep_s, "below_s": below, "above_s": above,
            "unmeasured_reason": None,
            "dead_reason": None if live else (
                f"предел на решение бегуна НЕ ВЛИЯЕТ так, как объявлено: при {below} с статус "
                f"`{sides['below'].get('status')}`, при {above} с — `{sides['above'].get('status')}`; "
                f"ожидалось `{expected}` РОВНО у первой")}


def observer_margin_control(repo: Path, *, sleep_s: float = OBS_SLEEP_S,
                            under: float = OBS_LIMIT_UNDER_SLEEP_S,
                            over: float = OBS_LIMIT_OVER_SLEEP_S,
                            busy_s: float = OBS_BUSY_S,
                            busy_repeats: int = OBS_BUSY_REPEATS,
                            repeats: int = OBS_REPEATS,
                            python: str = sys.executable,
                            observe_door=None) -> Dict[str, Any]:
    """Кусает ли предел на ПУТИ НАБЛЮДЕНИЯ — и сколько стоит сам наблюдатель.

    Сцена ставит модуль с ЗАДАННОЙ длительностью `sleep_s` и гоняет его ЕДИНСТВЕННОЙ дверью
    наблюдения дважды: предел НИЖЕ сна и предел ВЫШЕ сна. Ответ обязан различаться, и каждая
    сторона отвечает на свой вопрос:

    * предел ниже сна ⇒ бегун обязан сказать своё слово предела. Сказал — чтение 2
      («предел не кусает») ОПРОВЕРГНУТО наблюдением, а не рассуждением;
    * предел выше сна ⇒ модуль дорабатывает, и `наблюдённые − sleep_s` есть НАКЛАД
      наблюдателя. Это число и переводит `MARGIN_KIND_LOWER_BOUND` из объявления в замер:
      пока наклад не назван, «0.012 с при пределе 0.01 с» объясняется обоими чтениями сразу.

    Три исхода (инв. #17): ``OBS_LIMIT_BITES`` · ``OBS_LIMIT_DEAD`` (находка о проводке) ·
    ``OBS_MARGIN_UNMEASURED`` с названной причиной. Наклад НЕ ИЗМЕРЕН — тоже третий исход, а не
    нуль: нуль читался бы как «наблюдатель бесплатен», то есть как утверждение о системе.
    """
    empty: Dict[str, Any] = {"verdict": _OB_UNMEASURED, "expected_status": None, "sides": {},
                             "sleep_s": sleep_s, "under_s": under, "over_s": over,
                             "busy_s": busy_s, "busy_limit": {
                                 "verdict": _BZ_UNMEASURED, "ok_n": None, "timeout_n": None,
                                 "total_n": 0, "over_x": None,
                                 "unmeasured_reason": "сцена занятости не отработала"},
                             "overhead_s": None, "overhead_kind": None,
                             "overhead_split": {"call_s": None, "bookkeeping_s": None,
                                                "warm_s": None, "warm_n": 0,
                                                "idle_s": None, "idle_n": 0,
                                                "unmeasured_reason": "сцена не отработала"},
                             "dead_reason": None, "unmeasured_reason": None}
    if not (under < sleep_s < over):
        return {**empty, "unmeasured_reason": (
            f"сцена контроля неисполнима: требуется {under} < {sleep_s} < {over}")}
    try:
        expected = read_runner_timeout_status(repo)
    except NotMeasured as exc:
        return {**empty, "unmeasured_reason": f"слово предела у бегуна не прочитано: {exc}"}
    # Имена модулей сцены — ОДНА дверь на обе стороны: разойдись они, строки стороны не нашлись
    # бы по имени, и «сцена не отработала» стало бы неотличимо от «имя разошлось».
    def _mod(i: int) -> str:
        return f"{OBS_CONTROL_MODULE}_{i}"

    sides: Dict[str, Dict[str, Any]] = {}
    # ЧЕТЫРЕ стороны, и каждая отвечает на СВОЙ вопрос — свести их в одну нельзя:
    #   1-2 `limit_*_sleep` — кусает ли предел СПЯЩИЙ модуль (чтение 2 ADR-1014 § 7а);
    #   3   `no_sleep`      — сколько наблюдатель стои́т у модуля, который НЕ СПИТ (чтение 1);
    #   4   `busy_under_limit` — кусает ли предел ЗАНЯТЫЙ ВЫЧИСЛЕНИЕМ модуль. Реестр населён
    #       именно такими, и ответ у них ПРОТИВОПОЛОЖНЫЙ ответу спящего (§ 4).
    for name, limit, repeats, sl, kind in (
            ("limit_under_sleep", under, 1, sleep_s, "sleep"),
            ("limit_over_sleep", over, repeats, sleep_s, "sleep"),
            ("no_sleep", over, repeats, 0.0, "sleep"),
            ("busy_under_limit", under, busy_repeats, busy_s, "busy")):
        names = [_mod(i) for i in range(1, repeats + 1)]
        entries: List[Dict[str, object]] = [
            {"module": n, "class": None, "weight": 0.0,
             "category": "observer-margin-control"} for n in names]
        seed = [{"module": n, "sleep_s": sl, "kind": kind} for n in names]
        try:
            ran = (observe_door or _observer_run)(
                repo, entries, protocol="observer_margin_control",
                timeout=limit, python=python, seed=seed, run_timeout=_OBS_RUN_TIMEOUT_S)
        except (NotMeasured, OSError, ValueError, KeyError) as exc:
            return {**empty, "expected_status": expected, "sides": sides, "unmeasured_reason": (
                f"сторона `{name}` не отработала: {type(exc).__name__}: {exc}")}
        by_mod = {r.get("module"): r for r in ran["results"]}
        missing = [n for n in names if n not in by_mod]
        if missing:
            return {**empty, "expected_status": expected, "sides": sides, "unmeasured_reason": (
                f"сторона `{name}`: наблюдатель не отдал строк о модулях сцены {missing} — "
                f"предпосылка не обеспечена, и судить по остатку значило бы мерить не ряд")}
        series: List[Dict[str, Any]] = []
        for n in names:
            row = by_mod[n]
            sec, sec_call = row.get("seconds"), row.get("seconds_call")
            if not isinstance(sec, (int, float)) or isinstance(sec, bool):
                return {**empty, "expected_status": expected, "sides": sides,
                        "unmeasured_reason": (
                            f"сторона `{name}`, модуль `{n}`: секундомер наблюдателя ответил "
                            f"{sec!r} — вычитать нельзя, а подстановка нуля сделала бы "
                            f"наблюдателя бесплатным")}
            series.append({"module": n, "status": row.get("status"),
                           "detail": row.get("detail"), "seconds": float(sec),
                           "seconds_call": (float(sec_call)
                                            if isinstance(sec_call, (int, float))
                                            and not isinstance(sec_call, bool) else None)})
        if not series:
            # Пустой ряд — третий исход с причиной, а НЕ падение и не «сторона ответила».
            # Нашёл эту дыру положительный контроль на `busy_repeats=0`: до него сторона с
            # нулём повторов роняла прибор на `series[0]`, то есть «не измерено» приходило
            # исключением вместо вердикта.
            return {**empty, "expected_status": expected, "sides": sides,
                    "unmeasured_reason": (
                        f"сторона `{name}` пуста: повторов заказано {repeats}, строк 0 — "
                        f"у ряда из нуля наблюдений доли не бывает")}
        first = series[0]
        sides[name] = {"timeout": limit, "sleep_s": sl, "status": first["status"],
                       "detail": first["detail"], "seconds": first["seconds"],
                       "seconds_call": first["seconds_call"], "series": series,
                       "observer_returncode": ran["observer_returncode"]}
    under_hit = sides["limit_under_sleep"]["status"] == expected
    # На стороне «предел выше сна» слово предела не должно звучать НИ У ОДНОЙ строки ряда:
    # «у первой не звучало» ответом не является, иначе тёплые строки судились бы по холодной.
    over_hit = any(r["status"] == expected for r in sides["limit_over_sleep"]["series"])
    overhead: Optional[float] = None
    overhead_kind: Optional[str] = None
    if over_hit:
        overhead_kind = "НЕ ИЗМЕРЕН: при пределе выше сна бегун всё равно сказал слово предела"
    else:
        raw = sides["limit_over_sleep"]["seconds"] - sleep_s
        if raw < 0:
            overhead_kind = (f"НЕ ИЗМЕРЕН: наблюдённые {sides['limit_over_sleep']['seconds']} с "
                             f"КОРОЧЕ заданного сна {sleep_s} с — сцена не обеспечила свою "
                             f"предпосылку, и отрицательный наклад был бы выдуманным числом")
        else:
            overhead, overhead_kind = round(raw, 4), MARGIN_KIND_LOWER_BOUND
    # Расклад наклада на ДВА слагаемых. Он и отвечает на вопрос «кого называет причиной вердикта
    # запас»: `call` — зов модуля вместе с трассировкой, `bookkeeping` — снимок дерева ПОСЛЕ
    # зова, к модулю не относящийся вовсе. Нет второго числа ⇒ НЕ ИЗМЕРЕНО с причиной.
    split: Dict[str, Any] = {"call_s": None, "bookkeeping_s": None, "warm_s": None,
                             "warm_n": 0, "idle_s": None, "idle_n": 0,
                             "unmeasured_reason": "наклад не измерен"}
    o_side = sides.get("limit_over_sleep") or {}
    if overhead is not None and o_side.get("seconds_call") is not None:
        call_overhead = round(float(o_side["seconds_call"]) - sleep_s, 4)
        book = round(float(o_side["seconds"]) - float(o_side["seconds_call"]), 4)
        if call_overhead < 0 or book < 0:
            split["unmeasured_reason"] = (
                f"раскладка отрицательна (зов {call_overhead} с, бухгалтерия {book} с) — "
                f"секундомеры сцены не согласны, и выдуманное слагаемое было бы хуже пустоты")
        else:
            # ТЁПЛЫЙ наклад — по ОСТАЛЬНЫМ строкам ряда; берётся МИНИМУМ, потому что вопрос
            # «сколько наблюдатель стои́т неизбежно», а не «сколько он стоил в среднем под
            # чужой загрузкой». Ряда нет ⇒ третий исход, а не холодное число под тёплым именем.
            warm_rows = [r for r in o_side["series"][1:]
                         if r.get("seconds_call") is not None
                         and float(r["seconds_call"]) >= sleep_s]
            warm = (round(min(float(r["seconds_call"]) for r in warm_rows) - sleep_s, 4)
                    if warm_rows else None)
            # НАКЛАД У НЕ СПЯЩЕГО МОДУЛЯ — берётся МАКСИМУМ ряда, потому что вопрос «сколько
            # наблюдатель МОГ приписать модулю», а не «сколько он приписал в среднем»: объяснять
            # им `ok` при длительности выше предела вправе только самая щедрая оценка.
            idle_rows = [r for r in (sides.get("no_sleep") or {}).get("series", [])
                         if r.get("seconds_call") is not None]
            idle = (round(max(float(r["seconds_call"]) for r in idle_rows), 4)
                    if idle_rows else None)
            split = {"call_s": call_overhead, "bookkeeping_s": book, "warm_s": warm,
                     "warm_n": len(warm_rows), "idle_s": idle, "idle_n": len(idle_rows),
                     "unmeasured_reason": None if (warm is not None and idle is not None) else (
                         f"часть раскладки НЕ ИЗМЕРЕНА: тёплых строк "
                         f"{len(warm_rows)} из {repeats - 1}, строк у не спящего модуля "
                         f"{len(idle_rows)} из {repeats}")}
    # ЗАНЯТЫЙ модуль и предел — отдельный вердикт у той же сцены. Ответом является ДОЛЯ:
    # исход не детерминирован (гонка за GIL), и одно наблюдение дало бы монетку вместо замера.
    bz_rows = (sides.get("busy_under_limit") or {}).get("series", [])
    bz_ok = sum(1 for r in bz_rows if r["status"] != expected)
    bz_to = sum(1 for r in bz_rows if r["status"] == expected)
    over_x = round(busy_s / under, 1) if under > 0 else None
    # Полноту ряда здесь НЕ перепроверяют, и это решение, а не упущение: на вопрос «ряд
    # полон?» отвечает ОДИН сторож — полнота стороны выше (пустой ряд и недостающие имена, оба
    # с НАЗВАННЫМИ причинами). Второй ответ на тот же вопрос дал бы два разных «не измерено» об
    # одной причине (класс ADR-220), а мутация, снимающая здешнюю копию, никакой сценой не
    # убивается — ветка недостижима ПО ПОСТРОЕНИЮ (мутант M12 выжил именно так).
    if bz_ok == 0:
        busy_limit = {"verdict": _BZ_BITES, "ok_n": bz_ok, "timeout_n": bz_to,
                      "total_n": len(bz_rows), "over_x": over_x, "unmeasured_reason": None}
    else:
        busy_limit = {"verdict": _BZ_BLIND, "ok_n": bz_ok, "timeout_n": bz_to,
                      "total_n": len(bz_rows), "over_x": over_x, "unmeasured_reason": None}
    empty = {**empty, "busy_limit": busy_limit}
    if not under_hit:
        return {**empty, "expected_status": expected, "sides": sides,
                "overhead_s": overhead, "overhead_kind": overhead_kind,
                "overhead_split": split,
                "verdict": _OB_DEAD, "dead_reason": (
                    f"предел на ПУТИ НАБЛЮДЕНИЯ не кусает: модуль спал {sleep_s} с при пределе "
                    f"{under} с (в {round(sleep_s / under, 1)}× дольше), а бегун записал "
                    f"`{sides['limit_under_sleep']['status']}` вместо `{expected}` ⇒ «ни один "
                    f"модуль не подошёл к пределу» было свойством ПРИБОРА, не системы")}
    if over_hit:
        return {**empty, "expected_status": expected, "sides": sides,
                "overhead_kind": overhead_kind, "unmeasured_reason": (
                    f"обе стороны ответили `{expected}`: при пределе {over} с выше сна "
                    f"{sleep_s} с слово предела не должно звучать, и сцена различающей не стала")}
    return {"verdict": _OB_BITES, "expected_status": expected, "sides": sides,
            "sleep_s": sleep_s, "under_s": under, "over_s": over, "busy_s": busy_s,
            "busy_limit": busy_limit,
            "overhead_s": overhead, "overhead_kind": overhead_kind,
            "overhead_split": split,
            "dead_reason": None, "unmeasured_reason": None}


def _duration_of_module(name: str, per_pass: Dict[int, Dict[str, Any]], *, passes: int,
                        timeout: float, margin_floor_x: float, expected: str) -> Dict[str, Any]:
    """Вердикт ОДНОГО модуля по РЯДУ проходов (ADR-1016).

    Вердикт считается по МАКСИМУМУ ряда, а не по среднему и не по первому: предмет — «выходил ли
    ХОТЯ БЫ РАЗ», и среднее здесь утопило бы ровно тот модуль, ради которого замер делается.

    Три исхода различимы (инв. #17) и ни один не сливается с соседом: измерено · измерено и
    ВНУТРИ предела · НЕ ИЗМЕРЕНО с названной причиной. Отдельно от них стои́т `NOT_ENTERED` —
    это не «не измерено» (длительность как раз измерена) и не «внутри предела» (вычисления не
    было вовсе), а СВОЙ исход: бегун заплатил стенное время за ввоз, а тела модуля не исполнил.
    """
    out: Dict[str, Any] = {"module": name, "verdict": _DU_UNMEASURED, "max_s": None,
                           "wall_max_s": None, "kind": None, "entered_n": None,
                           "over_passes": [], "series": [], "reason": None}
    missing = [p for p in range(passes) if p not in per_pass]
    if missing:
        return {**out, "reason": (
            f"нет строк о проходах {missing} из {passes} — ряд неполон, а судить по остатку "
            f"значило бы мерить не ряд")}
    series: List[Dict[str, Any]] = []
    for p in range(passes):
        row = per_pass[p]
        sec = row.get("seconds_call")
        if not isinstance(sec, (int, float)) or isinstance(sec, bool):
            return {**out, "reason": (
                f"проход {p}: секундомер наблюдателя ответил {sec!r} — подстановка нуля "
                f"сделала бы модуль бесплатным, то есть заведомо прошедшим предел")}
        series.append({"pass": p, "status": row.get("status"), "seconds_call": float(sec),
                       "detail": str(row.get("detail") or "")[:120]})
    out = {**out, "series": series}
    wall_max = max(s["seconds_call"] for s in series)
    out = {**out, "wall_max_s": round(wall_max, 3)}
    broken = [s["pass"] for s in series if s["status"] == OBSERVER_ERROR_STATUS]
    if broken:
        return {**out, "reason": (
            f"наблюдатель упал на проходах {broken} — его поломка не есть длительность модуля")}
    unentered = [s for s in series if s["status"] == DURATION_NOT_ENTERED_STATUS]
    if len(unentered) == passes:
        return {**out, "verdict": _DU_NOT_ENTERED, "entered_n": 0, "reason": (
            f"бегун не вошёл в тело ни в одном из {passes} проходов (`"
            f"{DURATION_NOT_ENTERED_STATUS}`): ВЫЧИСЛЕНИЯ не было, и считать такой модуль "
            f"вычисляющим значило бы ответить на другой вопрос — стенную цену его ввоза "
            f"несёт `wall_max_s`")}
    if unentered:
        return {**out, "entered_n": passes - len(unentered), "reason": (
            f"ряд СМЕШАН: бегун вошёл в тело в {passes - len(unentered)} проходах из {passes}, "
            f"в остальных ответил `{DURATION_NOT_ENTERED_STATUS}` — у разнородного ряда "
            f"максимума не бывает, а выбрать удобную половину значило бы подделать род числа")}
    # Слово предела у бегуна есть САМОСТОЯТЕЛЬНОЕ свидетельство выхода за предел, и оно НЕ
    # заменяется сравнением чисел: когда предел кусает, модуль продолжает работать в своём
    # потоке, а секундомер останавливается на возврате бегуна — наблюдённая длительность
    # оказывается НИЖНЕЙ границей настоящей, и по ней одной выход был бы невидим.
    over = [s for s in series if s["status"] == expected or s["seconds_call"] > timeout]
    measured_max = round(max(s["seconds_call"] for s in series), 3)
    kind = (MARGIN_KIND_LOWER_BOUND if any(s["status"] == expected for s in series) else None)
    out = {**out, "max_s": measured_max, "kind": kind, "entered_n": passes,
           "over_passes": [s["pass"] for s in over]}
    if over:
        return {**out, "verdict": _DU_OVER, "reason": None}
    if margin_floor_x > 0 and measured_max >= timeout / margin_floor_x:
        return {**out, "verdict": _DU_NEAR, "reason": (
            f"запас до предела меньше объявленного пола {margin_floor_x:g}× "
            f"({measured_max} с при пределе {timeout} с)")}
    return {**out, "verdict": _DU_UNDER, "reason": None}


def duration_population(repo: Path, *, protocol: str, timeout: float,
                        passes: int = DURATION_MIN_PASSES,
                        python: str = sys.executable,
                        observe_door=None,
                        entries: Optional[List[Dict[str, object]]] = None,
                        seed: Optional[List[Dict[str, Any]]] = None,
                        margin_floor_x: float = MARGIN_FLOOR_X,
                        expected_status: Optional[str] = None,
                        run_timeout: Optional[float] = None) -> Dict[str, Any]:
    """НАСЕЛЕНИЕ класса «дольше предела хотя бы иногда» — поимённо и по РЯДУ проходов (ADR-1016).

    Закрывает ADR-1015 § 7 (в) ровно в той части, в какой его можно закрыть НАБЛЮДЕНИЕМ: сколько
    записей реестра выходят за `MODULE_TIMEOUT` хотя бы в одном проходе. Прибор только ЧИТАЕТ и
    НИЧЕГО не чинит: правка `_run_bounded` — вход денежного пути (`cycle_gates` Step 2c-pre), и
    `.claude/rules/risk-engine.md` запрещает её прицепом.

    **Два населения, и складывать их нельзя.** `computing_population` — модули, в чьё ТЕЛО бегун
    вошёл и чей максимум вышел за предел (дословный предмет § 7в). `wall_over_limit_n` — модули
    ЛЮБОГО рода, чья стенная длительность вышла за предел, включая `NOT_ENTERED`: цену ввоза
    бегун платит и за них. Первое отвечает «кого чинить», второе — «сколько теряет цикл».

    Ответ печатается ТОЛЬКО над живым контролем оси (`duration_population_control`): «население
    пусто» и «мера не способна увидеть предмет» дают ОДНО наблюдение, и это ровно тот класс,
    против которого написан весь прибор. Проходов меньше `DURATION_MIN_PASSES` ⇒ НЕ ИЗМЕРЕНО с
    причиной, а не нуль.
    """
    base: Dict[str, Any] = {
        "protocol": protocol, "timeout": timeout, "passes": passes,
        "margin_floor_x": margin_floor_x, "expected_timeout_status": expected_status,
        "modules": 0, "counts": {v: 0 for v in DURATION_VERDICTS},
        "computing_population": None, "near_population": None, "wall_over_limit_n": None,
        "one_pass_counts": None, "one_pass_disagrees": None, "disagreeing_modules": [],
        "subject": [], "unmeasured_modules": [], "unmeasured_reason": None}
    if passes < DURATION_MIN_PASSES:
        return {**base, "unmeasured_reason": (
            f"проходов заказано {passes} при минимуме {DURATION_MIN_PASSES}: вопрос «дольше "
            f"предела ХОТЯ БЫ ИНОГДА» ряду из одного наблюдения не задать — оно отвечает про "
            f"ОДИН момент, а не про разброс, и нуль по такой мере читался бы как ответ")}
    if timeout <= 0:
        return {**base, "unmeasured_reason": (
            f"предел {timeout} не положителен — запас от него не считается, а выдуманное "
            f"частное было бы хуже пустоты")}
    if expected_status is None:
        try:
            expected_status = read_runner_timeout_status(repo)
        except NotMeasured as exc:
            return {**base, "unmeasured_reason": f"слово предела у бегуна не прочитано: {exc}"}
        base = {**base, "expected_timeout_status": expected_status}
    if entries is None:
        try:
            entries = read_registry(repo)
        except NotMeasured as exc:
            return {**base, "unmeasured_reason": f"реестр не прочитан: {exc}"}
    if not entries:
        return {**base, "unmeasured_reason": (
            "в реестре ноль записей — у пустой поверхности населения не бывает (fail-CLOSED: "
            "пустой ответ здесь неотличим от «предмет пуст»)")}
    try:
        # СЕМЕНА (ADR-1015) идут ТОЙ ЖЕ дверью: различает перепись и её положительный контроль
        # ровно `seed`, и своя копия зова у контроля доказывала бы поведение пути, которым
        # перепись не мерит. Перепись зовётся без семян — и это не «нет семян», а их отсутствие
        # по предмету: она судит НАСТОЯЩИЕ модули дерева.
        ran = (observe_door or _observer_run)(
            repo, entries, protocol=protocol, timeout=timeout, python=python,
            seed=seed, passes=passes, run_timeout=run_timeout)
    except (NotMeasured, OSError, ValueError, KeyError) as exc:
        return {**base, "unmeasured_reason": (
            f"наблюдение не отработало: {type(exc).__name__}: {exc}")}
    rows = ran.get("series")
    if not isinstance(rows, list) or not rows:
        return {**base, "unmeasured_reason": (
            "наблюдатель не отдал РЯДА проходов (`series`) — судить по `results` значило бы "
            "ответить одним проходом на вопрос о разбросе")}
    got = ran.get("passes")
    if got != passes:
        return {**base, "unmeasured_reason": (
            f"наблюдатель отдал проходов {got!r}, заказано {passes}: ряд не тот, что заказан, "
            f"и считать по нему значило бы подделать объявленный вход")}
    by_mod: Dict[str, Dict[int, Dict[str, Any]]] = {}
    for r in rows:
        name, p = r.get("module"), r.get("pass")
        if not isinstance(name, str) or not name:
            return {**base, "unmeasured_reason": f"строка ряда без имени модуля: {r!r}"}
        if not isinstance(p, int) or isinstance(p, bool):
            return {**base, "unmeasured_reason": (
                f"строка ряда модуля `{name}` без номера прохода: {p!r} — ряд не упорядочить, "
                f"а «иногда» без порядка проходов есть догадка")}
        by_mod.setdefault(name, {})[p] = r
    verdicts: List[Dict[str, Any]] = []
    one_pass: Dict[str, str] = {}
    for name in sorted(by_mod):
        per_pass = by_mod[name]
        v = _duration_of_module(name, per_pass, passes=passes, timeout=timeout,
                                margin_floor_x=margin_floor_x, expected=expected_status)
        verdicts.append(v)
        # Что сказал бы ОДИН проход — считается ТЕМ ЖЕ ядром по первой строке ряда. Своя копия
        # правила здесь означала бы, что «ряд отличается от одного прохода» доказано РАЗНЫМИ
        # мерками, то есть ничем.
        head = {0: per_pass[0]} if 0 in per_pass else {}
        one_pass[name] = _duration_of_module(
            name, head, passes=1, timeout=timeout, margin_floor_x=margin_floor_x,
            expected=expected_status)["verdict"]
    counts = {v: 0 for v in DURATION_VERDICTS}
    for v in verdicts:
        counts[v["verdict"]] = counts.get(v["verdict"], 0) + 1
    one_counts: Dict[str, int] = {v: 0 for v in DURATION_VERDICTS}
    for name in one_pass:
        one_counts[one_pass[name]] = one_counts.get(one_pass[name], 0) + 1
    disagree = sorted(v["module"] for v in verdicts
                      if one_pass.get(v["module"]) != v["verdict"])
    wall_over = [v for v in verdicts
                 if isinstance(v.get("wall_max_s"), (int, float)) and v["wall_max_s"] > timeout]
    subject = sorted((v for v in verdicts if v["verdict"] in (_DU_OVER, _DU_NEAR)),
                     key=lambda v: (-(v.get("max_s") or 0.0), v["module"]))
    return {**base, "expected_timeout_status": expected_status, "modules": len(verdicts),
            "counts": counts, "computing_population": counts[_DU_OVER],
            "near_population": counts[_DU_NEAR], "wall_over_limit_n": len(wall_over),
            "wall_over_limit": sorted(v["module"] for v in wall_over),
            "one_pass_counts": one_counts, "one_pass_disagrees": len(disagree),
            "disagreeing_modules": disagree, "subject": subject,
            "unmeasured_modules": [{"module": v["module"], "reason": v["reason"]}
                                   for v in verdicts if v["verdict"] == _DU_UNMEASURED],
            "per_module": verdicts, "one_pass": one_pass, "unmeasured_reason": None}


def duration_population_control(repo: Path, *, timeout: float = DUR_CTL_TIMEOUT_S,
                                python: str = sys.executable,
                                observe_door=None,
                                passes: int = DUR_CTL_PASSES) -> Dict[str, Any]:
    """Положительный контроль ОСИ ПРОХОДОВ: различает ли ряд то, чего не различает один проход.

    Сцена ставит ЧЕТЫРЕ синтетических модуля с ЗАДАННЫМИ длительностями и гоняет их той же
    ЕДИНСТВЕННОЙ дверью наблюдения, которой идёт перепись (`_observer_run`; своя копия зова
    доказывала бы поведение пути, которым никто не мерит):

    * выше предела ⇒ обязан выйти `OVER_LIMIT_SOMETIMES`;
    * ниже предела, но выше пола запаса ⇒ `NEAR_LIMIT`;
    * ниже пола ⇒ `UNDER_LIMIT`;
    * ЧЕРЕДУЮЩИЙСЯ (первый проход короткий, второй длинный) ⇒ ряд обязан сказать
      `OVER_LIMIT_SOMETIMES`, а ОДИН проход — `UNDER_LIMIT`. Это и есть различающая сцена: без
      неё «ряд» и «первый проход» неразличимы наблюдением, и ось была бы декорацией.

    Три исхода (инв. #17): ``DPC_SEPARATES`` · ``DPC_BLIND`` (находка о проводке: ряд собран, а
    отличия от одного прохода нет) · ``DPC_UNMEASURED`` с названной причиной.
    """
    sides = {"over": DUR_CTL_OVER_X, "near": DUR_CTL_NEAR_X, "under": DUR_CTL_UNDER_X}
    expect = {"over": _DU_OVER, "near": _DU_NEAR, "under": _DU_UNDER,
              "alternate": _DU_OVER}
    empty: Dict[str, Any] = {"verdict": _DP_UNMEASURED, "timeout": timeout, "passes": passes,
                             "sides": {}, "expected": expect, "alternate_one_pass": None,
                             "blind_reason": None, "unmeasured_reason": None}
    if passes < DURATION_MIN_PASSES:
        return {**empty, "unmeasured_reason": (
            f"проходов у сцены {passes} при минимуме {DURATION_MIN_PASSES} — различать нечем")}
    if passes < len(DUR_CTL_ALTERNATE_X):
        return {**empty, "unmeasured_reason": (
            f"проходов у сцены {passes}, а чередующаяся сторона объявлена на "
            f"{len(DUR_CTL_ALTERNATE_X)} длительностей — её второй половины сцена не увидит")}
    if not (DUR_CTL_UNDER_X < 1.0 / MARGIN_FLOOR_X <= DUR_CTL_NEAR_X < 1.0 < DUR_CTL_OVER_X):
        return {**empty, "unmeasured_reason": (
            f"стороны сцены не упорядочены: требуется {DUR_CTL_UNDER_X} < "
            f"{1.0 / MARGIN_FLOOR_X:g} <= {DUR_CTL_NEAR_X} < 1 < {DUR_CTL_OVER_X}")}
    try:
        expected_status = read_runner_timeout_status(repo)
    except NotMeasured as exc:
        return {**empty, "unmeasured_reason": f"слово предела у бегуна не прочитано: {exc}"}
    names = {k: f"{DUR_CONTROL_MODULE}_{k}" for k in list(sides) + ["alternate"]}
    entries = [{"module": n, "class": None, "weight": 0.0,
                "category": "duration-population-control"} for n in names.values()]
    seed = [{"module": names[k], "sleep_s": round(x * timeout, 4),
             "kind": DUR_CTL_OCCUPANCY} for k, x in sides.items()]
    seed.append({"module": names["alternate"], "kind": "alternate",
                 "occupancy": DUR_CTL_OCCUPANCY,
                 "durations": [round(x * timeout, 4) for x in DUR_CTL_ALTERNATE_X]})
    pop = duration_population(repo, protocol="duration_population_control", timeout=timeout,
                              passes=passes, python=python, observe_door=observe_door,
                              entries=entries, seed=seed, expected_status=expected_status,
                              run_timeout=_DUR_CTL_RUN_TIMEOUT_S)
    if pop["unmeasured_reason"]:
        return {**empty, "unmeasured_reason": f"сцена не отработала: {pop['unmeasured_reason']}"}
    got = {v["module"]: v for v in pop.get("per_module") or []}
    out_sides: Dict[str, Any] = {}
    for key, name in names.items():
        v = got.get(name)
        if v is None:
            return {**empty, "sides": out_sides, "unmeasured_reason": (
                f"сторона `{key}`: наблюдатель не отдал строк о модуле `{name}` — предпосылка "
                f"не обеспечена, и судить по остатку значило бы мерить не сцену")}
        out_sides[key] = {"module": name, "verdict": v["verdict"], "expected": expect[key],
                          "max_s": v.get("max_s"), "series": v.get("series"),
                          "reason": v.get("reason")}
    wrong = [k for k in names if out_sides[k]["verdict"] != expect[k]]
    if wrong:
        return {**empty, "sides": out_sides, "unmeasured_reason": (
            "сцена не воспроизвела своих же сторон " + ", ".join(
                f"`{k}`: ждали {expect[k]}, вышло {out_sides[k]['verdict']}" for k in wrong)
            + " — пока сцена не различает заведомо разные длительности, её ответ о населении "
              "ничего не стои́т")}
    # Несущая половина контроля: ОДИН проход обязан ответить о чередующемся модуле ИНАЧЕ, чем
    # ряд. Сравниваются вердикты, посчитанные ОДНИМ ядром (`_duration_of_module`), — иначе
    # «отличается» доказывалось бы разными мерками, то есть ничем.
    alt_one_pass = (pop.get("one_pass") or {}).get(names["alternate"])
    if alt_one_pass == out_sides["alternate"]["verdict"]:
        return {**empty, "sides": out_sides, "verdict": _DP_BLIND,
                "alternate_one_pass": alt_one_pass, "blind_reason": (
                    f"ряд из {passes} проходов ответил о чередующемся модуле то же, что ОДИН "
                    f"проход (`{alt_one_pass}`) — ось проходов ничего не различает, и "
                    f"«население» по ней есть свойство меры, а не системы")}
    if alt_one_pass != _DU_UNDER:
        return {**empty, "sides": out_sides, "alternate_one_pass": alt_one_pass,
                "unmeasured_reason": (
                    f"один проход ответил о чередующемся модуле `{alt_one_pass}`, а сцена "
                    f"объявлена на `{_DU_UNDER}` (первая длительность ряда — "
                    f"{DUR_CTL_ALTERNATE_X[0]:g}× предела): различие есть, но не то, которое "
                    f"объявлено, и зачесть его значило бы принять чужое наблюдение за своё")}
    return {**empty, "verdict": _DP_SEPARATES, "sides": out_sides,
            "alternate_one_pass": alt_one_pass, "unmeasured_reason": None}


def timeout_key(value: float) -> str:
    """Ключ наблюдения по пределу. Одна дверь: ключ и печать обязаны быть одной строкой, иначе
    «наблюдений 2» легко получить из одного предела, записанного двумя способами (`3` и `3.0`)."""
    return repr(float(value))


def _margin_at(slowest: Optional[Dict[str, Any]]) -> str:
    """Адрес наблюдения СЛОВАМИ, по объявленному роду. Неизвестный род — третий исход, а не
    молчаливая подстановка «при пределе»: подделанный род и есть предмет `MARGIN_AT_KINDS`."""
    if not slowest:
        return "адрес не измерен"
    kind, at = slowest.get("at_kind"), slowest.get("at")
    if kind not in _AT_WORDS:
        return f"род адреса НЕ ОБЪЯВЛЕН (`{kind}`), адрес `{at}`"
    return _AT_WORDS[kind].format(at)


def _slowest_observed_module(observations: Dict[str, Dict[str, Any]],
                            at_kind: str = _AT_TIMEOUT) -> Optional[Dict[str, Any]]:
    """Самый медленный модуль среди наблюдений — ЗАПАС, которым объясняется инвариантность.

    Наблюдение без `seconds` ответа не даёт, и это НЕ нуль (инв. #17): «запас не измерен» и
    «запаса нет» — разные утверждения, а второе читалось бы как находка.

    `at_kind` объявляет, ЧЕМ является ключ наблюдений: пределом (одиночный замер) или
    клеткой матрицы. Род уезжает в запись вместе с адресом — читатель JSON не обязан
    угадывать, о чём ему назвали адрес.
    """
    if at_kind not in MARGIN_AT_KINDS:  # pragma: no cover — объявление, а не ветка данных
        raise ValueError(f"род адреса `{at_kind}` не объявлен в MARGIN_AT_KINDS")
    best: Optional[Dict[str, Any]] = None
    for key, obs in observations.items():
        rows = obs.get("per_module")
        if not rows:
            return None
        for r in rows:
            sec = r.get("seconds")
            if not isinstance(sec, (int, float)) or isinstance(sec, bool):
                return None
            if best is None or float(sec) > best["seconds"]:
                best = {"module": r.get("module"), "seconds": float(sec),
                        "at": key, "at_kind": at_kind}
    return best


def margin_floor_verdict(declared: Optional[float],
                         slowest: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """Прошёл ли ИЗМЕРЕННЫЙ запас объявленный порог `MARGIN_FLOOR_X` (ADR-1013).

    Запас — это та величина, которой объясняется `INVARIANT` по пределу, и до ADR-1013 она не
    гатила ничего: прибор её печатал. Здесь она становится условием, и у ответа ТРИ исхода
    (`MARGIN_VERDICTS`, инв. #17), а не два:

    * `MARGIN_CLEARS_FLOOR` — запас измерен и порог прошёл. Оценка запаса есть НИЖНЯЯ граница
      (`MARGIN_KIND_LOWER_BOUND`), поэтому пройденный порог ДОКАЗЫВАЕТ, что настоящий запас его
      прошёл: настоящий не меньше оценки.
    * `MARGIN_BELOW_FLOOR` — измерен и НЕ прошёл. Утверждением о системе это НЕ является по тому
      же знаку: нижняя граница ниже порога не доказывает, что настоящий запас тонок, — она
      перестаёт доказывать, что он безопасен. Поэтому вердикт у вызывающего — НЕ ИЗМЕРЕНО, а не
      находка (fail-CLOSED, и ошибка идёт в сторону отказа, не выдуманного числа).
    * `MARGIN_UNMEASURED` — запаса нет вовсе, и это НЕ нуль: «запас не измерен» и «запаса нет» —
      разные утверждения, второе читалось бы находкой.

    Нулевая длительность попадает в ТРЕТИЙ исход намеренно. Нуль здесь неотличим от «длительность
    не измерялась»: модуль, который успел импортироваться и отработать за время НИЖЕ разрешения
    часов, и сломанный секундомер дают одну и ту же запись. Считать такой нуль бесконечным
    запасом значило бы выдать неизмеренное за самый безопасный исход — ровно наоборот к инв. #17.
    """
    if slowest is None:
        return {"verdict": _MG_UNMEASURED, "margin": None, "floor": MARGIN_FLOOR_X,
                "kind": MARGIN_KIND_LOWER_BOUND, "slowest": None, "reason": (
                    "запас НЕ ИЗМЕРЕН: у наблюдений нет длительностей модулей, а именно запасом "
                    "объясняется инвариантность — без него «предел ни на что не влияет» нечем "
                    "отличить от «до предела никто и не доходит»")}
    seconds = slowest.get("seconds")
    if not isinstance(seconds, (int, float)) or isinstance(seconds, bool) or seconds <= 0:
        return {"verdict": _MG_UNMEASURED, "margin": None, "floor": MARGIN_FLOOR_X,
                "kind": MARGIN_KIND_LOWER_BOUND, "slowest": slowest, "reason": (
                    f"длительность самого медленного модуля не является положительным числом "
                    f"({seconds!r}): делить на неё нельзя, а нуль неотличим от «секундомер не "
                    f"сработал» — считать его бесконечным запасом значило бы выдать НЕ ИЗМЕРЕНО "
                    f"за самый безопасный исход")}
    if declared is None:
        return {"verdict": _MG_UNMEASURED, "margin": None, "floor": MARGIN_FLOOR_X,
                "kind": MARGIN_KIND_LOWER_BOUND, "slowest": slowest, "reason": (
                    "предел бегуна не прочитан — запас есть ОТНОШЕНИЕ к нему, и без объявления "
                    "бегуна его числитель пришлось бы выдумать (класс ADR-913)")}
    margin = round(float(declared) / float(seconds), 1)
    if margin < MARGIN_FLOOR_X:
        return {"verdict": _MG_BELOW, "margin": margin, "floor": MARGIN_FLOOR_X,
                "kind": MARGIN_KIND_LOWER_BOUND, "slowest": slowest, "reason": (
                    f"запас {margin}× НИЖЕ порога {MARGIN_FLOOR_X}×: самый медленный модуль "
                    f"`{slowest.get('module')}` занял {seconds} с при объявленном пределе "
                    f"{declared} с (наблюдение {_margin_at(slowest)}). "
                    f"Оценка запаса — НИЖНЯЯ граница ({MARGIN_KIND_LOWER_BOUND}), поэтому она НЕ "
                    f"доказывает, что настоящий запас тонок; она перестаёт доказывать, что он "
                    f"безопасен, и «инвариантно» теряет свою названную причину")}
    return {"verdict": _MG_CLEARS, "margin": margin, "floor": MARGIN_FLOOR_X,
            "kind": MARGIN_KIND_LOWER_BOUND, "slowest": slowest, "reason": None}


def timeout_variance(repo: Path, census: Census,
                     observations: Optional[Dict[str, Dict[str, Any]]],
                     knob: Optional[Dict[str, Any]] = None,
                     absent_reason: Optional[str] = None) -> Dict[str, Any]:
    """Различается ли механизм бегуна по ПРЕДЕЛУ модуля (заказ G1000 п. 1г = ADR-1010 § 7г).

    ADR-1010 закрыл первый вход наблюдения (протокол) и НАЗВАЛ второй: предел стоял `3 с` во
    всех замерах ADR-1002…1010, и зависимость населения `dormant`/`failed`/`timeout` от него не
    измерял никто. Сравнение — ПОИМЁННОЕ и тем же ядром, что у протокола: своя копия ядра
    отвечала бы на свой вопрос (`_compare_across_values`), а равные счёта при разных модулях уже
    были зелёным ответом сторожа мимо предмета.

    Отличие от протокола ОДНО и оно несущее: у предела инвариантность обязана ЗАРАБОТАТЬ право
    быть напечатанной. «Население не зависит от предела» и «предел ни на что не влияет» дают
    ОДНО наблюдение, поэтому `INVARIANT` печатается только над живым контролем входа
    (`timeout_knob_control`); контроль мёртв или не измерен ⇒ итог НЕ ИЗМЕРЕН (fail-CLOSED).
    Названное различие (`VARIES`) в контроле не нуждается: различие само и есть доказательство,
    что вход до решения доходит.
    """
    kb = knob or {"verdict": _KB_UNMEASURED, "expected_status": None, "sides": {},
                  "dead_reason": None, "unmeasured_reason": "контроль входа не запускался"}
    empty: Dict[str, Any] = {"verdict": _PV_UNMEASURED, "timeouts": [], "sides": {},
                             "min_required": VARIANCE_MIN, "declared": None,
                             "declared_observed": None, "knob": kb, "margin": None,
                             "slowest": None,
                             "margin_gate": margin_floor_verdict(None, None)}
    if not observations:
        return {**empty, "unmeasured_reason": (
            absent_reason or "наблюдение не запускалось (--observe не задан)")}
    try:
        timeouts = sorted(observations, key=float)
    except (TypeError, ValueError) as exc:
        return {**empty, "timeouts": sorted(observations), "unmeasured_reason": (
            f"ключи наблюдений не читаются как предел ({exc}) — ключ обязан делать "
            f"`timeout_key`, иначе «наблюдений 2» получается из одного предела")}
    if len(timeouts) < VARIANCE_MIN:
        return {**empty, "timeouts": timeouts, "unmeasured_reason": (
            f"наблюдений {len(timeouts)} < {VARIANCE_MIN}: один предел даёт ЗНАЧЕНИЕ, "
            f"а не различие — «различий нет» из него не следует")}
    try:
        declared = read_runner_timeout(repo)
    except NotMeasured as exc:
        return {**empty, "timeouts": timeouts, "unmeasured_reason": (
            f"объявление предела у бегуна не прочитано: {exc} — без него нельзя сказать, "
            f"входит ли в наблюдённые тот предел, которым бегун живёт")}
    declared_observed = timeout_key(declared) in observations
    slowest = _slowest_observed_module(observations)
    # ОДНА дверь к запасу: и число, и вердикт порога выходят из `margin_floor_verdict`. Своя
    # формула рядом дала бы второе объявление одной величины — класс «одно имя, один объект».
    margin_gate = margin_floor_verdict(declared, slowest)
    margin = margin_gate["margin"]
    sides: Dict[str, Dict[str, Any]] = {}
    for side in PROTOCOL_SIDES:
        by_value: Dict[str, Dict[str, str]] = {}
        reason: Optional[str] = None
        for t in timeouts:
            try:
                by_value[t] = _side_labels(repo, census, observations[t], side)
            except NotMeasured as exc:
                reason = f"предел `{t}`: {exc}"
                break
        if reason is not None:
            sides[side] = {"verdict": _PV_UNMEASURED, "values": timeouts, "subject": {},
                           "union": 0, "intersection": 0, "subject_empty": None,
                           "differences": {k: [] for k in PROTOCOL_DIFFERENCES},
                           "counts": {k: 0 for k in PROTOCOL_DIFFERENCES},
                           "unmeasured_reason": reason}
            continue
        sides[side] = _compare_across_values(by_value)
    verdicts = {s["verdict"] for s in sides.values()}
    if _PV_UNMEASURED in verdicts:
        overall = _PV_UNMEASURED
        reason = "; ".join(f"{name}: {s['unmeasured_reason']}" for name, s in sides.items()
                           if s["verdict"] == _PV_UNMEASURED)
    elif _PV_VARIES in verdicts:
        overall, reason = _PV_VARIES, None
    elif kb["verdict"] != _KB_LIVE:
        # fail-CLOSED, и это НЕСУЩАЯ половина решения: все стороны совпали поимённо, но без
        # живого контроля такой ответ в равной мере описывает дефект проводки.
        overall = _PV_UNMEASURED
        reason = (f"стороны совпали ПОИМЁННО, но вход не подтверждён контролем "
                  f"({kb['verdict']}: {kb.get('dead_reason') or kb.get('unmeasured_reason')}) — "
                  f"«население не зависит от предела» и «предел ни на что не влияет» по "
                  f"наблюдению НЕРАЗЛИЧИМЫ")
    elif margin_gate["verdict"] != _MG_CLEARS:
        # fail-CLOSED по ЗАПАСУ (ADR-1013). Контроль входа выше доказывает, что предел ДОХОДИТ до
        # решения; запас отвечает на другой вопрос — ПОЧЕМУ при живом входе население всё равно
        # не меняется. Ответ один: никто не подходит к пределу близко. Перестань это быть правдой
        # — и `INVARIANT` останется напечатанным, а его причина тихо исчезнет. Поэтому причина
        # вердикта обязана быть УСЛОВИЕМ вердикта, а не строкой рядом с ним.
        overall = _PV_UNMEASURED
        reason = (f"стороны совпали ПОИМЁННО при живом контроле входа, но причина, которой этот "
                  f"ответ объясняется, не подтверждена: {margin_gate['reason']}")
    else:
        overall, reason = _PV_INVARIANT, None
    return {"verdict": overall, "timeouts": timeouts, "sides": sides,
            "min_required": VARIANCE_MIN, "declared": declared,
            "declared_observed": declared_observed, "knob": kb,
            "slowest": slowest, "margin": margin, "margin_gate": margin_gate,
            "unmeasured_reason": reason}


def render_timeout_variance(tv: Dict[str, Any]) -> List[str]:
    """Печать сравнения по пределу. Запас печатается ВСЕГДА: инвариантность без названной
    причины — число без своего производителя, а именно запасом она здесь и объясняется."""
    out = [f"  РАЗЛИЧИЕ МЕХАНИЗМА ПО ПРЕДЕЛУ МОДУЛЯ (ADR-1011) — наблюдений "
           f"{len(tv['timeouts'])} ({', '.join(tv['timeouts']) or '—'} с)"]
    if tv.get("declared") is not None:
        out.append(f"    объявление бегуна `{RUNNER_TIMEOUT_NAME}` = {tv['declared']} с — "
                   + ("СРЕДИ наблюдённых" if tv["declared_observed"]
                      else "⚠️ среди наблюдённых ЕГО НЕТ: ответ принадлежит пределам, "
                           "которыми бегун не живёт"))
    kb = tv["knob"]
    if kb["verdict"] == _KB_LIVE:
        s = kb["sides"]
        out.append(f"    контроль входа KNOB_LIVE — модуль спит {kb['sleep_s']} с: при "
                   f"{kb['below_s']} с бегун сказал `{s['below']['status']}`, при "
                   f"{kb['above_s']} с — `{s['above']['status']}`")
    elif kb["verdict"] == _KB_DEAD:
        out.append(f"    ❗ контроль входа KNOB_DEAD — {kb['dead_reason']}")
    else:
        out.append(f"    ⚠️ контроль входа НЕ ИЗМЕРЕН — {kb.get('unmeasured_reason')}")
    # Запас печатается ВСЕГДА и ВМЕСТЕ со своим вердиктом порога: с ADR-1013 он не причина
    # «рядом», а условие вердикта, и читателю нужны оба — число и то, прошло ли оно порог.
    mg = tv.get("margin_gate") or margin_floor_verdict(None, None)
    sl = mg.get("slowest")
    if sl is None:
        out.append(f"    запас НЕ ИЗМЕРЕН ({mg['verdict']}) — {mg['reason']}")
    else:
        head = (f"    самый медленный модуль наблюдения: {sl['module']} {sl['seconds']} с "
                f"({_margin_at(sl)})")
        if mg["verdict"] == _MG_CLEARS:
            out.append(head + f"; запас до объявленного предела ≥{mg['margin']}× "
                              f"(НИЖНЯЯ граница) — порог {mg['floor']}× ПРОЙДЕН")
        elif mg["verdict"] == _MG_BELOW:
            out.append(head + f"; ❗ запас ≥{mg['margin']}× НИЖЕ порога {mg['floor']}×")
            out.append(f"    {mg['reason']}")
        else:
            out.append(head + f"; ⚠️ запас НЕ ИЗМЕРЕН ({mg['verdict']})")
            out.append(f"    {mg['reason']}")
    if tv["verdict"] == _PV_UNMEASURED:
        out.append(f"    ⚠️ НЕ ИЗМЕРЕНО — {tv['unmeasured_reason']}")
        return out
    for side, s in tv["sides"].items():
        if s["verdict"] == _PV_UNMEASURED:
            out.append(f"    {side:<42} ⚠️ НЕ ИЗМЕРЕНО — {s['unmeasured_reason']}")
            continue
        counts = "/".join(str(s["subject"][t]) for t in s["values"])
        if s["verdict"] == _PV_INVARIANT and s.get("subject_empty"):
            out.append(f"    {side:<42} предмет ПУСТ под всеми пределами — измерено и равно "
                       f"нулю, сверкой это не является")
            continue
        if s["verdict"] == _PV_INVARIANT:
            out.append(f"    {side:<42} INVARIANT — предмет {counts}; совпал ПОИМЁННО "
                       f"({s['intersection']} модул(ей), union = intersect)")
            continue
        out.append(f"    {side:<42} VARIES — предмет {counts}; union {s['union']}, "
                   f"intersect {s['intersection']}; SUBJECT_MOVED "
                   f"{s['counts']['SUBJECT_MOVED']} · LABEL_DIFFERS {s['counts']['LABEL_DIFFERS']}")
        moved, differs = s["differences"][_PD_MOVED], s["differences"][_PD_DIFFERS]
        for e in moved[:_PV_SHOWN]:
            out.append(f"      ↔ {e['module']}: в предмете при {', '.join(e['in'])} с; "
                       f"вне — {', '.join(e['out'])} с")
        for e in differs[:_PV_SHOWN]:
            shown = ", ".join(f"{t}с={lab}" for t, lab in e["labels"].items())
            out.append(f"      ≠ {e['module']}: {shown}")
        rest = (len(moved) - min(_PV_SHOWN, len(moved))) + (len(differs) - min(_PV_SHOWN, len(differs)))
        if rest > 0:
            out.append(f"      … и ещё {rest} (полный перечень — `--json`, ключ "
                       f"`timeout_variance.sides['{side}'].differences`)")
    out.append("    НЕ ДОКЛАДЫВАЕТ: матрица «предел × протокол» (прибор мерит входы ПО ОДНОМУ; "
               "смешанный зов отказывает) и цена предела в секундах прогона")
    return out


# ───────── матрица двух объявленных входов (ADR-1012, заказ G1001 п. 1а) ─────────

def cell_key(protocol: str, timeout: float) -> str:
    """Ключ КЛЕТКИ матрицы: протокол И предел сразу, одной дверью.

    Вся суть отказа ADR-1011 § 6 была в том, что наблюдения двух входов легли бы в словарь с
    ОДНИМ ключом. Матрица отменяет не отказ, а одноклю­чевой словарь: ключ несёт оба входа, и
    молчаливого выбора «главного» входа не остаётся ни одного.

    Предел печатается ЕДИНСТВЕННОЙ дверью `timeout_key` — своя форма здесь дала бы `3` и `3.0`
    двумя клетками одного предела, то есть «наблюдений 2» из одного наблюдения.

    Имя протокола с разделителем внутри ⇒ `NotMeasured`: ключ стал бы неоднозначным, а срез
    отвечал бы о ЧУЖОЙ клетке. Угадывать разбор на таком имени значило бы вернуть ровно тот
    молчаливый выбор, против которого матрица и написана.
    """
    name = str(protocol)
    if not name.strip():
        raise NotMeasured("клетка матрицы без протокола: имя пусто")
    if MATRIX_CELL_SEP in name:
        raise NotMeasured(
            f"протокол `{name}` несёт разделитель клетки `{MATRIX_CELL_SEP}`: ключ стал бы "
            f"неоднозначным, и срез отвечал бы о чужой клетке")
    return f"{name}{MATRIX_CELL_SEP}{timeout_key(timeout)}"


def split_cell_key(key: str) -> Tuple[str, str]:
    """Обратная дверь `cell_key`. Неразбираемый ключ — третий исход, а не половина ответа."""
    protocol, sep, t = str(key).rpartition(MATRIX_CELL_SEP)
    if not sep or not protocol or not t:
        raise NotMeasured(
            f"ключ клетки `{key}` не разбирается: ждали `<протокол>{MATRIX_CELL_SEP}<предел>`")
    try:
        float(t)
    except (TypeError, ValueError):
        raise NotMeasured(f"ключ клетки `{key}`: `{t}` не читается как предел")
    return protocol, t


def _matrix_grid(by_cell: Dict[str, Any]) -> Tuple[List[str], List[str], Dict[str, Tuple[str, str]]]:
    """Протоколы, пределы и карта `ключ → (протокол, предел)`.

    ПОЛНОТА проверяется здесь и является предпосылкой, а не удобством: у рваной матрицы срез
    одного протокола сравнивал бы ДВА предела, а соседнего — три, и «инвариантно» первого
    описывало бы другое население. Дыра ⇒ `NotMeasured` с ПЕРЕЧНЕМ дыр.
    """
    grid = {k: split_cell_key(k) for k in by_cell}
    protocols = sorted({p for p, _ in grid.values()})
    try:
        timeouts = sorted({t for _, t in grid.values()}, key=float)
    except (TypeError, ValueError) as exc:  # pragma: no cover — split_cell_key уже проверил
        raise NotMeasured(f"пределы клеток не упорядочиваются: {exc}")
    holes = [f"{p}{MATRIX_CELL_SEP}{t}" for p in protocols for t in timeouts
             if f"{p}{MATRIX_CELL_SEP}{t}" not in by_cell]
    if holes:
        raise NotMeasured(
            f"матрица РВАНАЯ: клеток {len(by_cell)} при {len(protocols)}×{len(timeouts)} = "
            f"{len(protocols) * len(timeouts)}; нет — {', '.join(holes[:8])}"
            + (f" … и ещё {len(holes) - 8}" if len(holes) > 8 else ""))
    return protocols, timeouts, grid


def _slice_cell_key(axis: str, fixed: str, moving: str) -> str:
    """Ключ клетки СРЕЗА: ось говорит, какая половина ключа неподвижна.

    Дверь одна на двух читателей — сравнение ярлыков и запас. Разойдись они, запас мерился бы
    по одному набору клеток, а вердикт выносился по другому, и расхождение было бы молчаливым.
    """
    return (f"{fixed}{MATRIX_CELL_SEP}{moving}" if axis == _MX_T_IN_P
            else f"{moving}{MATRIX_CELL_SEP}{fixed}")


def _slice_margin(by_cell: Dict[str, Dict[str, Any]], axis: str, fixed: str,
                  moving: List[str], declared: Optional[float]) -> Dict[str, Any]:
    """Запас до предела у ОДНОГО среза матрицы (ADR-1014).

    Мерится у СРЕЗА, а не у оси, и различие несущее: «инвариантно при `aave_v3`» объясняется
    запасом ТЕХ клеток, по которым этот срез и сравнивался. Запас, снятый по всей матрице,
    осудил бы вместе со тонким срезом и все остальные — утверждение встало бы у оси целиком
    и не сработало бы никогда (ADR-1013 § 7а дословно). Предел по-прежнему берётся У БЕГУНА
    (класс ADR-913), двери к величине и к порогу — те же, что у одиночного замера.
    """
    cells = {key: by_cell[key] for key in
             (_slice_cell_key(axis, fixed, m) for m in moving)}
    return margin_floor_verdict(declared, _slowest_observed_module(cells, _AT_CELL))


def _axis_liveness(axis: str, side_axis: Dict[str, Dict[str, Any]],
                   knob: Dict[str, Any]) -> Tuple[str, str]:
    """Чем доказано, что вход этой оси ДОХОДИТ до решения.

    Несущее правило ADR-1011 § 4 — «`INVARIANT` обязано заработать право быть напечатанным» —
    принадлежит не пределу, а ВОПРОСУ: «население не зависит от входа» и «вход ни на что не
    влияет» по наблюдению неразличимы у ЛЮБОГО входа. У матрицы для этого есть доказательство,
    которого у одиночного замера нет вовсе: если по этой оси РАЗЛИЧАЕТСЯ хоть одна объявленная
    сторона, то вход доходит — и доказано это ТЕМИ ЖЕ наблюдениями, а не отдельной сценой.

    Внешний контроль зачитывается только своей оси (`AXIS_KNOB_INPUT`): принять контроль
    предела за доказательство живости протокола значило бы зачесть одной оси контроль другой.
    """
    # Доказательством служит НАЗВАННОЕ РАЗЛИЧИЕ, а не сводный вердикт стороны, и с ADR-1014
    # это перестало быть одним и тем же: гейт запаса вправе увести сводку стороны в
    # `UNMEASURED` из-за ДРУГОГО, тонкого среза — и спроси мы сводку, ось потеряла бы
    # доказательство живости, которое у неё есть, а причина отказа назвала бы НЕ ТО звено
    # («живость не доказана» вместо «запас тонок»).
    varying = sorted(s for s, v in side_axis.items()
                     if v["verdict"] == _PV_VARIES or v.get("slices_varying"))
    if varying:
        return _AX_BY_DIFF, (f"по этой оси РАЗЛИЧАЮТСЯ стороны: {', '.join(varying)} — вход "
                             f"доходит до решения, доказано теми же наблюдениями")
    if axis in AXIS_KNOB_INPUT and knob.get("verdict") == _KB_LIVE:
        return _AX_BY_KNOB, (f"ни одна сторона не различается, но вход `{AXIS_KNOB_INPUT[axis]}` "
                             f"подтверждён внешним контролем ({_KB_LIVE})")
    if axis in AXIS_KNOB_INPUT:
        return _AX_UNPROVEN, (
            f"ни одна сторона не различается, а внешний контроль входа "
            f"`{AXIS_KNOB_INPUT[axis]}` не живой ({knob.get('verdict')}: "
            f"{knob.get('dead_reason') or knob.get('unmeasured_reason')})")
    return _AX_UNPROVEN, ("ни одна сторона не различается, а внешнего контроля у этого входа "
                          "прибор не имеет — «инвариантно» и «вход никуда не идёт» "
                          "по наблюдению НЕРАЗЛИЧИМЫ")


def matrix_variance(repo: Path, census: Census,
                    by_cell: Optional[Dict[str, Dict[str, Any]]],
                    knob: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Держится ли ответ об ОДНОМ входе, когда двигается ВТОРОЙ (заказ G1001 п. 1а).

    ADR-1010 ответил о протоколе при одном пределе 3 с, ADR-1011 — о пределе при одном
    протоколе `aave_v3`. Оба ответа верны ПРИ неподвижном соседе, и ни один из них не есть
    ответ вообще: тот же замер ADR-1010 показал, что предмет `silent` протокол-ЗАВИСИМ
    (117…129), то есть сосед двигает САМО НАСЕЛЕНИЕ, по которому меряется второй вход.

    Ответ печатается ПО ОСЯМ (`MATRIX_AXES`), и это ровно те два ключа, которых не хватало
    однокле­точному словарю. Сравнение — тем же ядром `_compare_across_values`: третья копия
    ядра отвечала бы на свой вопрос, а счёта вместо модулей были бы зелёным ответом мимо
    предмета.

    Три исхода различимы (инв. #17): `INVARIANT` (все срезы совпали ПОИМЁННО, живость оси
    доказана И запас КАЖДОГО среза прошёл порог) · `VARIES` (срез НАЗВАН — осью, значением
    соседа, стороной и модулями) · `UNMEASURED` с причиной (клеток по одной оси меньше
    `VARIANCE_MIN` · матрица рваная · сторона не разобралась хотя бы в одной клетке ·
    живость оси НЕ ДОКАЗАНА · запас среза не подтверждён).

    ЗАПАС — УСЛОВИЕ вердикта и здесь (ADR-1014, заказ G1003 п. 1а = ADR-1013 § 7а), и он
    мерится у СРЕЗА: «инвариантно при `aave_v3`» объясняется запасом ТЕХ клеток, по которым
    срез и сравнивался. Запас по всей матрице осудил бы вместе с тонким срезом и все
    остальные — утверждение встало бы у оси целиком и не сработало бы никогда.
    """
    kb = knob or {"verdict": _KB_UNMEASURED, "dead_reason": None,
                  "unmeasured_reason": "контроль входа не запускался"}
    empty: Dict[str, Any] = {"verdict": _PV_UNMEASURED, "protocols": [], "timeouts": [],
                             "cells": 0, "min_required": VARIANCE_MIN, "sides": {},
                             "axes": {}, "knob": kb, "declared_protocols": [],
                             "declared_protocols_not_observed": [], "declared_timeout": None,
                             "declared_timeout_observed": None}
    if not by_cell:
        return {**empty, "unmeasured_reason": (
            "матрица не снималась (--protocols и --timeouts вместе не заданы)")}
    try:
        protocols, timeouts, _ = _matrix_grid(by_cell)
    except NotMeasured as exc:
        return {**empty, "cells": len(by_cell), "unmeasured_reason": str(exc)}
    short = [name for name, axis_values in (("протоколов", protocols), ("пределов", timeouts))
             if len(axis_values) < VARIANCE_MIN]
    if short:
        return {**empty, "protocols": protocols, "timeouts": timeouts, "cells": len(by_cell),
                "unmeasured_reason": (
                    f"{' и '.join(short)} меньше {VARIANCE_MIN}: матрица из одного столбца "
                    f"матрицей не является — она даёт ЗНАЧЕНИЕ по неподвижной оси, а не "
                    f"различие (протоколов {len(protocols)}, пределов {len(timeouts)})")}
    declared_protocols: List[str] = []
    declared_timeout: Optional[float] = None
    try:
        declared_protocols = list(read_runner_protocols(repo))
        declared_timeout = read_runner_timeout(repo)
    except NotMeasured as exc:
        return {**empty, "protocols": protocols, "timeouts": timeouts, "cells": len(by_cell),
                "unmeasured_reason": (
                    f"объявление бегуна не прочитано: {exc} — без него нельзя сказать, о каких "
                    f"входах этот ответ")}
    coverage = {
        "declared_protocols": declared_protocols,
        "declared_protocols_not_observed": [p for p in declared_protocols if p not in protocols],
        "observed_protocols_not_declared": [p for p in protocols if p not in declared_protocols],
        "declared_timeout": declared_timeout,
        "declared_timeout_observed": timeout_key(declared_timeout) in timeouts,
    }
    # Запас среза не зависит от СТОРОНЫ (он свойство наблюдений, а не ярлыков), поэтому
    # считается ОДИН раз на срез — до сторон. Посчитай его внутри стороны, и одна величина
    # получила бы столько объявлений, сколько сторон, то есть класс «одно имя — один объект».
    margins: Dict[str, Dict[str, Dict[str, Any]]] = {}
    for axis in MATRIX_AXES:
        fixed_values = protocols if axis == _MX_T_IN_P else timeouts
        moving = timeouts if axis == _MX_T_IN_P else protocols
        margins[axis] = {f: _slice_margin(by_cell, axis, f, moving, declared_timeout)
                         for f in fixed_values}
    # Ярлыки снимаются ОДИН раз на клетку: `_side_labels` зовёт разборы ADR-1008/1009, и второй
    # проход по тем же клеткам стоил бы вдвое, отвечая то же самое.
    sides: Dict[str, Dict[str, Any]] = {}
    for side in PROTOCOL_SIDES:
        labels: Dict[str, Dict[str, str]] = {}
        reason: Optional[str] = None
        for key in sorted(by_cell):
            try:
                labels[key] = _side_labels(repo, census, by_cell[key], side)
            except NotMeasured as exc:
                reason = f"клетка `{key}`: {exc}"
                break
        if reason is not None:
            sides[side] = {axis: {"verdict": _PV_UNMEASURED, "slices": {},
                                  "slices_varying": [], "slices_unmeasured": [],
                                  "unmeasured_reason": reason} for axis in MATRIX_AXES}
            continue
        per_axis: Dict[str, Dict[str, Any]] = {}
        for axis in MATRIX_AXES:
            outer = protocols if axis == _MX_T_IN_P else timeouts
            inner = timeouts if axis == _MX_T_IN_P else protocols
            slices: Dict[str, Dict[str, Any]] = {}
            for fixed in outer:
                by_value = {v: labels[_slice_cell_key(axis, fixed, v)] for v in inner}
                sl = _compare_across_values(by_value)
                gate = margins[axis][fixed]
                sl["margin_gate"] = gate
                if sl["verdict"] == _PV_INVARIANT and gate["verdict"] != _MG_CLEARS:
                    # fail-CLOSED по ЗАПАСУ, у СРЕЗА (ADR-1014). Порядок звеньев тот же, что
                    # у одиночного замера: `VARIES` запасом НЕ гатится — названное различие
                    # само есть доказательство, что вход доходит, и гасить находку порогом
                    # значило бы ослаблять проверку.
                    sl["verdict"] = _PV_UNMEASURED
                    sl["unmeasured_reason"] = (
                        f"срез совпал ПОИМЁННО, но причина, которой этот ответ объясняется, "
                        f"не подтверждена: {gate['reason']}")
                slices[fixed] = sl
            varies = sorted(f for f, s in slices.items() if s["verdict"] == _PV_VARIES)
            thin = sorted(f for f, s in slices.items() if s["verdict"] == _PV_UNMEASURED)
            per_axis[axis] = {
                # Порядок исходов — тот же, что у ОСИ (ADR-1012): неизмеренный срез НЕ даёт
                # стороне права сказать «инвариантно» по остальным. Названные различия при
                # этом не теряются: они остаются в `slices_varying` и печатаются.
                "verdict": (_PV_UNMEASURED if thin else
                            (_PV_VARIES if varies else _PV_INVARIANT)),
                "slices": slices, "slices_varying": varies, "slices_unmeasured": thin,
                "unmeasured_reason": ("; ".join(
                    f"срез `{f}`: {slices[f]['unmeasured_reason']}" for f in thin)
                    if thin else None)}
        sides[side] = per_axis
    axes: Dict[str, Dict[str, Any]] = {}
    for axis in MATRIX_AXES:
        side_axis = {name: s[axis] for name, s in sides.items()}
        liveness, liveness_reason = _axis_liveness(axis, side_axis, kb)
        # ГАТЕ стои́т у СТОРОНЫ, а не у оси, и различие существенно: в настоящем замере по оси
        # протоколов `runner_status` РАЗЛИЧАЕТСЯ, а три оси ADR-1009 — нет, и именно их
        # «инвариантно» и есть тот ответ, которому нужно доказательство живости входа. ADR-1010
        # напечатал его над живым контролем — но контролем НЕНАЗВАННЫМ: живость доказывали
        # соседние стороны того же наблюдения, и не скажи они ничего, то же «инвариантно»
        # вышло бы над мёртвой проводкой.
        if liveness == _AX_UNPROVEN:
            for name, v in side_axis.items():
                if v["verdict"] == _PV_INVARIANT:
                    v["verdict"] = _PV_UNMEASURED
                    v["unmeasured_reason"] = (
                        f"срезы совпали ПОИМЁННО, но живость оси НЕ ДОКАЗАНА — {liveness_reason}")
        unmeasured = {name: v["unmeasured_reason"] for name, v in side_axis.items()
                      if v["verdict"] == _PV_UNMEASURED}
        if unmeasured:
            # fail-CLOSED: неизмеренная сторона НЕ даёт оси права сказать «инвариантно» по
            # остальным — тот же порядок, что у обоих одиночных входов.
            verdict: str = _PV_UNMEASURED
            reason = "; ".join(f"{n}: {r}" for n, r in unmeasured.items())
        elif any(v["verdict"] == _PV_VARIES for v in side_axis.values()):
            verdict, reason = _PV_VARIES, None
        else:
            verdict, reason = _PV_INVARIANT, None
        axes[axis] = {"verdict": verdict, "liveness": liveness,
                      "liveness_reason": liveness_reason,
                      "margins": margins[axis],
                      "margin_floor": MARGIN_FLOOR_X,
                      "slices_unmeasured": {n: v.get("slices_unmeasured", [])
                                            for n, v in side_axis.items()},
                      "sides": {n: v["verdict"] for n, v in side_axis.items()},
                      # Спрашивается РАЗЛИЧИЕ, а не сводка стороны: с ADR-1014 сводка вправе
                      # уйти в `UNMEASURED` из-за тонкого среза, и названная находка
                      # исчезла бы из сводки оси молча.
                      "sides_varying": {n: v.get("slices_varying", [])
                                        for n, v in side_axis.items()
                                        if v.get("slices_varying")},
                      "unmeasured_reason": reason}
    verdicts = {a["verdict"] for a in axes.values()}
    if _PV_UNMEASURED in verdicts:
        overall = _PV_UNMEASURED
        overall_reason: Optional[str] = "; ".join(
            f"{name}: {a['unmeasured_reason']}" for name, a in axes.items()
            if a["verdict"] == _PV_UNMEASURED)
    else:
        overall = _PV_VARIES if _PV_VARIES in verdicts else _PV_INVARIANT
        overall_reason = None
    return {"verdict": overall, "protocols": protocols, "timeouts": timeouts,
            "cells": len(by_cell), "min_required": VARIANCE_MIN, "sides": sides,
            "axes": axes, "knob": kb, "unmeasured_reason": overall_reason, **coverage}


def _render_axis_margin(a: Dict[str, Any]) -> List[str]:
    """Запас СРЕЗОВ оси (ADR-1014). Печатается ВСЕГДА и обоими исходами раздельно: «запас
    тонок» требует искать подорожавший модуль, «длительностей нет» — чинить наблюдателя.
    Худший срез назван ИМЕНЕМ: лидер не устойчив, устойчива величина, а действовать надо
    по срезу, который ответ и держит."""
    gates: Dict[str, Dict[str, Any]] = a.get("margins") or {}
    if not gates:
        return ["      запас до предела: НЕ ИЗМЕРЕН — срезов у этой оси нет"]
    head = f"      запас до предела (порог {a.get('margin_floor', MARGIN_FLOOR_X)}×)"
    out: List[str] = []
    blind = sorted(f for f, g in gates.items() if g["verdict"] == _MG_UNMEASURED)
    if blind:
        out.append(head + f": ⚠️ НЕ ИЗМЕРЕН в {len(blind)} из {len(gates)} срезов "
                          f"({', '.join(blind[:_MX_SHOWN])}) — {gates[blind[0]]['reason']}")
    measured = {f: g for f, g in gates.items() if g["margin"] is not None}
    if measured:
        worst = min(measured, key=lambda f: measured[f]["margin"])
        g = measured[worst]
        below = sorted(f for f, m in measured.items() if m["verdict"] == _MG_BELOW)
        out.append(head + f": худший ИЗМЕРЕННЫЙ срез `{worst}` ≥{g['margin']}× "
                          f"({g['kind']}, самый медленный {g['slowest']['module']} "
                          f"{g['slowest']['seconds']} с, {_margin_at(g['slowest'])}) — "
                   + ("ПРОЙДЕН" if g["verdict"] == _MG_CLEARS
                      else f"❗ НИЖЕ порога; таких срезов {len(below)} из {len(gates)}"))
    return out


def render_matrix_variance(mx: Dict[str, Any]) -> List[str]:
    """Печать матрицы. Ось печатает свой вердикт И чем доказана её живость: «инвариантно» без
    названного доказательства живости входа описывает ещё и мёртвую проводку."""
    out = [f"  МАТРИЦА ДВУХ ВХОДОВ «предел × протокол» (ADR-1012) — клеток {mx['cells']}: "
           f"протоколов {len(mx['protocols'])} × пределов {len(mx['timeouts'])}"]
    if mx["protocols"] and mx["timeouts"]:
        out.append(f"    протоколы: {', '.join(mx['protocols'])}")
        out.append(f"    пределы, с: {', '.join(mx['timeouts'])}")
    if mx.get("declared_protocols"):
        miss = mx["declared_protocols_not_observed"]
        out.append(f"    охват: объявлено бегуном протоколов {len(mx['declared_protocols'])}, "
                   + (f"НЕ наблюдалось {len(miss)} ({', '.join(miss)})" if miss
                      else "наблюдены ВСЕ")
                   + f"; объявленный предел {mx['declared_timeout']} с — "
                   + ("СРЕДИ наблюдённых" if mx.get("declared_timeout_observed")
                      else "⚠️ среди наблюдённых ЕГО НЕТ"))
    if mx["verdict"] == _PV_UNMEASURED and not mx.get("axes"):
        out.append(f"    ⚠️ НЕ ИЗМЕРЕНО — {mx['unmeasured_reason']}")
        return out
    titles = {_MX_T_IN_P: "держится ли ответ ADR-1011 (ПРЕДЕЛ) у КАЖДОГО протокола",
              _MX_P_IN_T: "держится ли ответ ADR-1010 (ПРОТОКОЛ) у КАЖДОГО предела"}
    for axis, a in mx["axes"].items():
        out.append(f"    ось {axis} — {titles[axis]}")
        out.append(f"      живость оси: {a['liveness']} — {a['liveness_reason']}")
        out.extend(_render_axis_margin(a))
        mark = {_PV_INVARIANT: "✅", _PV_VARIES: "❗", _PV_UNMEASURED: "⚠️"}[a["verdict"]]
        out.append(f"      {mark} ОСЬ: {a['verdict']}"
                   + (f" — {a['unmeasured_reason']}" if a["unmeasured_reason"] else ""))
        # Вердикт КАЖДОЙ объявленной стороны печатается всегда: «ось различается» ничего не
        # говорит о стороне, которая НЕ различается, а именно её инвариантность и заказана.
        for name, v in mx["sides"].items():
            sv = v[axis]
            if sv["verdict"] == _PV_UNMEASURED:
                out.append(f"        {name:<40} ⚠️ НЕ ИЗМЕРЕНО — {sv['unmeasured_reason']}")
                continue
            if sv["verdict"] == _PV_INVARIANT:
                out.append(f"        {name:<40} INVARIANT во ВСЕХ {len(sv['slices'])} срезах")
                continue
            out.append(f"        {name:<40} VARIES в {len(sv['slices_varying'])} "
                       f"из {len(sv['slices'])} срезов")
            for fixed in sv["slices_varying"][:_MX_SHOWN]:
                s = sv["slices"][fixed]
                out.append(f"          @ {fixed}: предмет "
                           + "/".join(str(s["subject"][x]) for x in s["values"])
                           + f"; SUBJECT_MOVED {s['counts'][_PD_MOVED]} · "
                           f"LABEL_DIFFERS {s['counts'][_PD_DIFFERS]}")
    out.append("    НЕ ДОКЛАДЫВАЕТ: третий вход наблюдения (ADR-1011 § 7в — кандидаты `python`, "
               "cwd, каталог песочницы); ПОЧЕМУ срез подорожал (ADR-1013 § 7г — у вопроса нет "
               "носителя) и перемер самого порога (§ 7б)")
    return out


