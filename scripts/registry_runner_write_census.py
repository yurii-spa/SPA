def render_observer_margin(ctl: Optional[Dict[str, Any]]) -> List[str]:
    """Печать контроля ADR-1015. Заголовки строк РАЗНЫЕ намеренно: утверждение о печати обязано
    вырезать свой предмет по заголовку, а не искать подстроку по всему тексту (урок #1136 —
    так мутант «печатать не то» выживает, потому что слова находятся в соседней строке)."""
    out = ["  НАКЛАД НАБЛЮДАТЕЛЯ И УКУС ПРЕДЕЛА НА ПУТИ НАБЛЮДЕНИЯ (ADR-1015):"]
    if not ctl:
        out.append("    укус предела: НЕ ИЗМЕРЕН — сцена не запускалась")
        out.append("    наклад наблюдателя: НЕ ИЗМЕРЕН — сцена не запускалась")
        return out
    v = ctl.get("verdict")
    why = ctl.get("dead_reason") or ctl.get("unmeasured_reason")
    sides = ctl.get("sides") or {}
    if v == _OB_BITES:
        u, o = sides.get("limit_under_sleep", {}), sides.get("limit_over_sleep", {})
        out.append(f"    укус предела: {v} — модуль спал {ctl.get('sleep_s')} с; при пределе "
                   f"{u.get('timeout')} с бегун сказал `{u.get('status')}`, при {o.get('timeout')} с — "
                   f"`{o.get('status')}`")
    else:
        out.append(f"    укус предела: {v} — {why}")
    oh, kind = ctl.get("overhead_s"), ctl.get("overhead_kind")
    if oh is None:
        out.append(f"    наклад наблюдателя: НЕ ИЗМЕРЕН — {kind}")
    else:
        out.append(f"    наклад наблюдателя: {oh} с ({kind}) — наблюдённая длительность модуля "
                   f"ЗАВЫШЕНА на эту величину, и запас есть НИЖНЯЯ граница настоящего")
    sp = ctl.get("overhead_split") or {}
    if sp.get("call_s") is None or sp.get("bookkeeping_s") is None:
        out.append(f"    расклад наклада: НЕ ИЗМЕРЕН — {sp.get('unmeasured_reason')}")
    else:
        out.append(f"    расклад наклада: зов модуля {sp['call_s']} с · бухгалтерия наблюдателя "
                   f"{sp['bookkeeping_s']} с (снимок дерева ПОСЛЕ зова, к модулю не относится)")
    if sp.get("warm_s") is None:
        out.append(f"    тёплый наклад: НЕ ИЗМЕРЕН — {sp.get('unmeasured_reason')}")
    else:
        out.append(f"    тёплый наклад: {sp['warm_s']} с по {sp.get('warm_n')} строкам ряда "
                   f"(холодный зов — первый в процессе, перепись же гоняет модули подряд)")
    bz = ctl.get("busy_limit") or {}
    if bz.get("verdict") == _BZ_UNMEASURED:
        out.append(f"    предел у ЗАНЯТОГО модуля: НЕ ИЗМЕРЕН — {bz.get('unmeasured_reason')}")
    else:
        out.append(f"    предел у ЗАНЯТОГО модуля: {bz.get('verdict')} — модуль считал "
                   f"{ctl.get('busy_s')} с при пределе {ctl.get('under_s')} с (в "
                   f"{bz.get('over_x')}× дольше), и бегун сказал `ok` у {bz.get('ok_n')} из "
                   f"{bz.get('total_n')} повторов")
    if sp.get("idle_s") is None:
        out.append(f"    наклад у НЕ СПЯЩЕГО модуля: НЕ ИЗМЕРЕН — {sp.get('unmeasured_reason')}")
    else:
        out.append(f"    наклад у НЕ СПЯЩЕГО модуля: {sp['idle_s']} с (МАКСИМУМ ряда из "
                   f"{sp.get('idle_n')}) — ровно такие модули перепись и наблюдает, и ровно этим "
                   f"числом вправе объясняться `ok` при длительности выше предела клетки")
    return out


def render_duration_population(pop: Optional[Dict[str, Any]],
                               ctl: Optional[Dict[str, Any]]) -> List[str]:
    """Печать населения класса ADR-1016. Заголовки строк РАЗНЫЕ намеренно (урок #1136: утверждение
    о печати обязано вырезать свой предмет заголовком, иначе мутант «печатать не то» выживает).

    Население печатается ТОЛЬКО над живым контролем оси: «класс пуст» и «мера не видит класса»
    дают одно наблюдение, и выдать второе за первое значило бы сделать ровно ту подмену, против
    которой написан прибор.
    """
    out = ["  НАСЕЛЕНИЕ КЛАССА «ДОЛЬШЕ ПРЕДЕЛА ХОТЯ БЫ ИНОГДА» (ADR-1016, ADR-1015 § 7в):"]
    cv = (ctl or {}).get("verdict")
    if not ctl:
        out.append("    контроль оси проходов: НЕ ИЗМЕРЕН — сцена не запускалась")
    elif cv == _DP_SEPARATES:
        out.append(f"    контроль оси проходов: {cv} — чередующийся модуль: ряд сказал "
                   f"`{(ctl.get('sides') or {}).get('alternate', {}).get('verdict')}`, ОДИН "
                   f"проход — `{ctl.get('alternate_one_pass')}`")
    elif cv == _DP_BLIND:
        out.append(f"    контроль оси проходов: {cv} — {ctl.get('blind_reason')}")
    else:
        out.append(f"    контроль оси проходов: {cv} — {ctl.get('unmeasured_reason')}")
    if not pop:
        out.append("    население: НЕ ИЗМЕРЕНО — ряд проходов не снимался")
        out.append("    стенное население: НЕ ИЗМЕРЕНО — ряд проходов не снимался")
        return out
    if pop.get("unmeasured_reason"):
        out.append(f"    население: НЕ ИЗМЕРЕНО — {pop['unmeasured_reason']}")
        out.append("    стенное население: НЕ ИЗМЕРЕНО — по той же причине")
        return out
    if cv != _DP_SEPARATES:
        out.append(f"    население: НЕ ИЗМЕРЕНО — контроль оси проходов ответил `{cv}`, и над "
                   f"мерой, чья различающая способность не доказана, число было бы свойством "
                   f"прибора (модулей в ряду {pop.get('modules')}, проходов {pop.get('passes')})")
        out.append("    стенное население: НЕ ИЗМЕРЕНО — по той же причине")
        return out
    counts = pop.get("counts") or {}
    out.append(f"    ряд: модулей {pop.get('modules')} · проходов {pop.get('passes')} · предел "
               f"{pop.get('timeout')} с · протокол {pop.get('protocol')} · слово предела у бегуна "
               f"`{pop.get('expected_timeout_status')}`")
    out.append("    вычисляющее население (вошёл в тело И вышел за предел хотя бы раз): "
               f"{pop.get('computing_population')} из {pop.get('modules')}")
    out.append(f"    у предела (запас ниже пола {pop.get('margin_floor_x')}×): "
               f"{pop.get('near_population')}")
    out.append(f"    стенное население (ЛЮБОЙ род, стенная длительность выше предела): "
               f"{pop.get('wall_over_limit_n')} — это ДРУГОЙ вопрос: цену ввоза бегун платит и "
               f"за модуль, в тело которого не вошёл")
    out.append("    раскладка: " + " · ".join(f"{v} {counts.get(v, 0)}" for v in DURATION_VERDICTS))
    out.append(f"    ОДИН проход сказал бы иначе у {pop.get('one_pass_disagrees')} модулей — "
               f"ровно столько прежний замер (#1136, один проход) назвать не мог ПО ПОСТРОЕНИЮ")
    for v in (pop.get("subject") or [])[:_DUR_SHOWN]:
        kind = f", {v['kind']}" if v.get("kind") else ""
        out.append(f"    [{v['verdict']}] {v['module']}: максимум ряда {v.get('max_s')} с"
                   f"{kind}, проходы за пределом {v.get('over_passes')}")
    extra = len(pop.get("subject") or []) - _DUR_SHOWN
    if extra > 0:
        out.append(f"    … ещё {extra} строк(и) предмета (полный перечень — `--json`)")
    for u in (pop.get("unmeasured_modules") or [])[:_DUR_SHOWN]:
        out.append(f"    [НЕ ИЗМЕРЕНО] {u['module']}: {u['reason']}")
    out.append("    НЕ ДОКЛАДЫВАЕТ: длительность под ЖИВЫМ циклом (наблюдение идёт в песочнице, "
               "и фиды там не те) · настоящую длительность укушенного пределом модуля (она "
               "НИЖНЯЯ граница: модуль работает дальше в своём потоке) · поведение при другом "
               "протоколе и другом пределе (это оси ADR-1010/1011)")
    out.append("    ADVISORY: прибор только ЧИТАЕТ — `_run_bounded` не правится (вход денежного "
               "пути, `.claude/rules/risk-engine.md`); вердикта кода возврата не меняет")
    return out


def render(c: Census, obs: Optional[Dict[str, Any]] = None,
           observations: Optional[Dict[str, Dict[str, Any]]] = None,
           by_timeout: Optional[Dict[str, Dict[str, Any]]] = None,
           knob: Optional[Dict[str, Any]] = None,
           by_cell: Optional[Dict[str, Dict[str, Any]]] = None,
           obs_margin: Optional[Dict[str, Any]] = None,
           duration: Optional[Dict[str, Any]] = None,
           duration_control: Optional[Dict[str, Any]] = None) -> str:
    out = [f"РЕЕСТР → БЕГУН: куда пишут аналитики под песочницей (ADR-999 § 6в) · дерево {c.root}",
           f"  бегун {c.runner.runner_path}: входы {list(c.runner.entry_methods)}; кладёт data_dir в контекст "
           f"модуля — {'ДА' if c.runner.passes_data_dir else 'НЕТ'}",
           f"  записей реестра: {len(c.modules)}"]
    for v in VERDICTS:
        out.append(f"  {v:<17} {c.counts.get(v, 0)}")
    out.append("  предмет (достижимое умолчание у бегуна):")
    for k, v in c.exposure.items():
        out.append(f"    {k:<32} {v}")
    if c.blind_subset is not None:
        out.append("  подмножество «76 реестра» (callers.json): "
                   + " · ".join(f"{k} {v}" for k, v in c.blind_subset.items() if v))
    writers = [m for m in c.modules if m.verdict == "WRITE_REACHABLE"]
    if writers:
        out.append("  достигают записи от входа бегуна (поимённо, первые 40):")
        for m in writers[:40]:
            forms = sorted({w.form for w in m.writes})
            door = f" · дверь контекста: {m.data_dir_door}" if m.reads_context_data_dir else ""
            env = " · SPA_DATA_DIR" if m.reads_env_data_dir else ""
            cli = f" · CLI-умолчание {m.blind_cli}" if m.blind_cli else ""
            out.append(f"    {m.module} [{m.tier}] {m.entry} → {', '.join(forms)} "
                       f"({len(m.writes)} мест){door}{env}{cli}")
    foreign = [m for m in c.modules if m.data_dir_door in ("FOREIGN_PARAM", "UNRESOLVED")]
    if foreign:
        out.append("  читают ключ data_dir НЕ у связанного имени (ось ADR-1004 § 6а, поимённо):")
        for m in foreign[:40]:
            bases = sorted({f"{r.func}:{r.line} у `{r.base}`" for r in m.data_dir_reads})
            why = f" — {m.data_dir_door_reason}" if m.data_dir_door_reason else ""
            out.append(f"    {m.module} [{m.verdict}] {m.data_dir_door}{why}: " + "; ".join(bases[:4]))
    for axis, fo in observed_axes(c, obs).items():
        if not fo["subject"]:
            continue
        oc, n = fo["outcomes"], fo["subject"]
        out.append(f"  что сделал БЕГУН с этими {n} по оси `{axis}` — {fo['description']} "
                   f"(наблюдённый спутник статики, ADR-1006/1007):")
        silent = (" (" + " · ".join(f"{k} {v}" for k, v in sorted(fo["silent_by_status"].items())) + ")"
                  if fo["silent_by_status"] else "")
        out.append(f"    ПИСАЛ {oc['WROTE']} · вошёл и НЕ ПИСАЛ {oc['SILENT']}{silent} · "
                   f"НЕ ИЗМЕРЕНО {oc['UNMEASURED']}"
                   + (f" — {fo['unmeasured_reason']}" if fo["unmeasured_reason"] else ""))
        for e in fo["per_module"][:40]:
            tail = (", ".join(f"{k}: {', '.join(v[:3])}" for k, v in e["written"].items())
                    if e["written"] else (e["reason"] or f"статус бегуна `{e['runner_status']}`"))
            out.append(f"    {e['module']}: {e['outcome']} — {tail}")
        if len(fo["per_module"]) > 40:
            out.append(f"    … и ещё {len(fo['per_module']) - 40} (полный перечень — `--json`, "
                       f"ключ `observed_axes.{axis}`)")
        par = fo["parity"]
        if par["agrees"] is False:
            out.append(f"    ⚠️ НЕ ИЗМЕРЕНО: предмет оси ({par['subject']}) расходится с печатаемым "
                       f"счётом ({par['exposure']}) — вывод НЕ печатается, пока мерки не одна")
        elif par["agrees"] is None:
            out.append("    ⚠️ НЕ ИЗМЕРЕНО: счёта этой оси в сводке нет — вывод НЕ печатается")
        elif oc["UNMEASURED"] == 0 and oc["WROTE"] == 0 and oc["SILENT"]:
            out.append(f"    ⇒ ни один из них под бегуном НЕ ПИСАЛ: {OBSERVED_AXES[axis][2]}")
        elif oc["UNMEASURED"] == 0 and oc["WROTE"]:
            gap = n - oc["WROTE"]
            out.append(f"    ⇒ писали {oc['WROTE']} из {n}: статический счёт `{axis}` "
                       + (f"БОЛЬШЕ числа наблюдённых записей на {gap}" if gap
                          else "совпал с числом наблюдённых записей"))
    sc = silent_causes(Path(c.root), c, obs)
    if sc["unmeasured_reason"]:
        out.append(f"  ПРИЧИНЫ тишины «вошёл и промолчал» (ADR-1008): ⚠️ НЕ ИЗМЕРЕНО — {sc['unmeasured_reason']}")
    elif sc["parity"]["agrees"] is False:
        out.append(f"  ПРИЧИНЫ тишины «вошёл и промолчал» (ADR-1008): ⚠️ НЕ ИЗМЕРЕНО — предмет "
                   f"({sc['parity']['subject']}) расходится со свёрткой тишины "
                   f"({sc['parity']['silent_ok']}); разбор НЕ печатается, пока мерки не одна")
    elif sc["subject"]:
        named = sum(v for k, v in sc["causes"].items() if k != "UNNAMED")
        out.append(f"  ПРИЧИНЫ тишины у {sc['subject']} «вошёл и промолчал» (статус `{sc['status']}`, "
                   f"предмет оси `{sc['axis']}`; основание — ИСПОЛНЕННЫЕ строки под бегуном, ADR-1008):")
        for cause in SILENT_CAUSES:
            if sc["causes"][cause]:
                out.append(f"    {cause:<22} {sc['causes'][cause]}")
        for e in sc["per_module"][:40]:
            g = f" · условие `{e['sites'][0]['guard']}`" if e["sites"] and e["sites"][0].get("guard") else ""
            where = f" @ {e['sites'][0]['where']}" if e["sites"] else ""
            out.append(f"    {e['module']}: {e['cause']}{where} — {e['detail']}{g}")
        if len(sc["per_module"]) > 40:
            out.append(f"    … и ещё {len(sc['per_module']) - 40} (полный перечень — `--json`, "
                       f"ключ `silent_causes.per_module`)")
        out.append(f"    ⇒ причина НАЗВАНА у {named} из {sc['subject']}, НЕ НАЗВАНА у "
                   f"{sc['causes']['UNNAMED']}: причина решает, была бы починка двери каталога "
                   f"дверью с ЧИТАТЕЛЕМ или ложным усилением (ADR-940…944)")
    for axis, uc in unentered_causes_by_axis(Path(c.root), c, obs).items():
        head = f"  ПРИЧИНЫ статуса `{UNENTERED_CAUSE_STATUS}` у оси `{axis}` (ADR-1009)"
        if uc["unmeasured_reason"]:
            out.append(f"{head}: ⚠️ НЕ ИЗМЕРЕНО — {uc['unmeasured_reason']}")
            continue
        if uc["parity"]["agrees"] is False:
            out.append(f"{head}: ⚠️ НЕ ИЗМЕРЕНО — предмет ({uc['parity']['subject']}) расходится "
                       f"со свёрткой статуса ({uc['parity']['unchecked']}); разбор НЕ печатается, "
                       f"пока мерки не одна")
            continue
        if not uc["subject"]:
            out.append(f"{head}: предмет ПУСТ — ни одного модуля с этим статусом внутри оси "
                       f"(измерено и равно нулю, не «не мерили»)")
            continue
        out.append(f"{head} — предмет {uc['subject']}; основание: ИСПОЛНЕННЫЕ строки тела входа "
                   f"+ слова бегуна паритетом с объявлением:")
        for cause in UNENTERED_CAUSES:
            if uc["causes"][cause]:
                out.append(f"    {cause:<24} {uc['causes'][cause]}")
        for e in uc["per_module"][:40]:
            out.append(f"    {e['module']}: {e['cause']} — {e['detail']}")
        if len(uc["per_module"]) > 40:
            out.append(f"    … и ещё {len(uc['per_module']) - 40} (полный перечень — `--json`, "
                       f"ключ `unentered_causes.{axis}.per_module`)")
        not_entered = uc["causes"]["NO_ENTRY_BOUND"]
        entered = uc["causes"]["ENTERED_RAISED_FOREIGN"]
        # Пояснение печатается ТОЛЬКО у непустой стороны: фраза «там бегун вошёл» при нуле
        # описывала бы население, которого замер не нашёл, — число без своего смысла.
        out.append(f"    ⇒ премиса «бегун не входит» (ADR-1007 § 6б) ВЕРНА у {not_entered} из "
                   f"{uc['subject']} и ЛОЖНА у {entered}"
                   + (f"; у этих {entered} бегун ВОШЁЛ и вход отказал на Mapping — предмет статики "
                      f"существует, мешает ФОРМА контекста (класс ADR #136), и починка у них ДРУГАЯ"
                      if entered else "")
                   + (f"; у этих {not_entered} контекст не биндится ни одной формой — предмет "
                      f"статики под бегуном НЕ СУЩЕСТВУЕТ (ось ADR-999/1000)" if not_entered else ""))
        if uc["causes"]["DISAGREED"] or uc["causes"]["UNNAMED"]:
            out.append(f"    ⚠️ третий исход: DISAGREED {uc['causes']['DISAGREED']} · "
                       f"UNNAMED {uc['causes']['UNNAMED']} — основание названо у каждого поимённо")
    unm = [m for m in c.modules if m.verdict == "UNMEASURED"]
    if unm:
        out.append("  НЕ ИЗМЕРЕНО (модули):")
        for m in unm[:10]:
            out.append(f"    {m.module}: {m.reason}")
    if obs is not None:
        out.append(f"  НАБЛЮДЕНИЕ в {obs['repo']} (протокол {obs['protocol']}, таймаут {obs['timeout']} с): "
                   f"модулей {obs['modules']}, статусы бегуна {obs['statuses']}")
        out.append(f"    корзины записи (модулей): {obs['baskets']} · прочее в дереве: {len(obs['elsewhere_in_tree'])}")
        out.append(f"    парность со статикой: {obs['parity']}")
        for w in obs["writers"][:40]:
            out.append(f"    ✍ {w['module']} ({w['status']}): " + "; ".join(
                f"{k}: {', '.join(v[:4])}{' …' if len(v) > 4 else ''}" for k, v in w["written"].items()))
        if obs["elsewhere_in_tree"]:
            out.append("    прочее в дереве: " + ", ".join(obs["elsewhere_in_tree"][:10]))
        out.append("    записи по абсолютным путям вне дерева/cwd/песочницы наблюдение НЕ видит")
    # ADR-1010: сравнение по протоколам печатается ВСЕГДА — без второго наблюдения это НЕ
    # «различий нет», а названный третий исход. Подстановка «один протокол ⇒ инвариантно» и
    # держала семь решений подряд на одном `aave_v3`.
    # ADR-1012: в матричном зове одиночные ответы НЕ выбирают клетку молча — ответ по одному
    # входу принадлежит срезам матрицы, и «взять первую клетку» было бы ровно тем молчаливым
    # выбором, от которого ADR-1011 § 6 отказывался.
    out.extend(render_protocol_variance(protocol_variance(
        Path(c.root), c, None if by_cell else (observations if observations is not None
        else ({obs["protocol"]: obs} if obs is not None else None)),
        absent_reason=_MATRIX_ABSENT_REASON if by_cell else None)))
    # ADR-1011: предел модуля — ВТОРОЙ вход, и о нём печатается тот же ответ и тем же порядком.
    # Без второго наблюдения это НЕ «различий нет», а названный третий исход; и `INVARIANT` тут
    # обязан стоять над ЖИВЫМ контролем входа, иначе он описывает ещё и мёртвую проводку.
    out.extend(render_timeout_variance(timeout_variance(
        Path(c.root), c, None if by_cell else (by_timeout if by_timeout is not None
        else ({timeout_key(obs["timeout"]): obs} if obs is not None else None)), knob,
        absent_reason=_MATRIX_ABSENT_REASON if by_cell else None)))
    # ADR-1012: матрица печатается ВСЕГДА — без матричного зова это НЕ «различий нет», а
    # названный третий исход тем же порядком, что у обоих одиночных входов.
    out.extend(render_matrix_variance(matrix_variance(Path(c.root), c, by_cell, knob)))
    # ADR-1015: наклад наблюдателя и укус предела НА ПУТИ НАБЛЮДЕНИЯ печатаются ВСЕГДА — без
    # сцены это НЕ «наклада нет» (нуль читался бы как «наблюдатель бесплатен»), а названный
    # третий исход тем же порядком, что у всех соседей выше.
    out.extend(render_observer_margin(obs_margin))
    # ADR-1016: население класса «дольше предела хотя бы иногда» печатается ВСЕГДА — без ряда
    # проходов это НЕ нуль (нуль читался бы как «класс пуст»), а названный третий исход тем же
    # порядком, что у всех соседей выше.
    out.extend(render_duration_population(duration, duration_control))
    verdict = {0: "✅ предмет пуст: ни одна запись реестра не доводит вход бегуна до записи в своё умолчание",
               1: "❗ предмет НАЗВАН: бегун каталога не передаёт, а вход достигает записи — она ляжет в умолчание модуля",
               2: f"⚠️ НЕ ИЗМЕРЕНО: {c.unmeasured_reason}"}[c.code]
    out.append(verdict)
    return "\n".join(out)


def _parse_timeouts(spec: str, repo: Path) -> List[float]:
    """`declared` — предел БЕГУНА; числа — названные вслух. Дверь ОДНА на одиночный зов и на
    матричный: вторая копия разбора дала бы `declared` два разных значения в одном приборе."""
    wanted: List[float] = []
    for tok in (s.strip() for s in spec.split(",")):
        if not tok:
            continue
        if tok == "declared":
            wanted.append(read_runner_timeout(repo))
            continue
        try:
            wanted.append(float(tok))
        except ValueError:
            raise NotMeasured(f"--timeouts: `{tok}` не предел и не `declared`")
    if not wanted:
        raise NotMeasured("--timeouts не назвал ни одного предела")
    return wanted


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    ap.add_argument("--repo-root", default=None, help="дерево, которое переписывается (умолчание — своё; ПЕЧАТАЕТСЯ)")
    ap.add_argument("--readers-json", default=None, help="callers.json ADR-999 — пометить подмножество «76 реестра»")
    ap.add_argument("--observe", default=None, metavar="TREE",
                    help="одноразовое НЕ-git дерево: настоящий бегун зовёт каждый модуль, записи наблюдаются")
    ap.add_argument("--protocol", default="aave_v3")
    ap.add_argument("--protocols", default=None, metavar="СПИСОК",
                    help="`all` (весь перечень бегуна `DEFAULT_PROTOCOLS`) либо имена через запятую: "
                         "наблюдение снимается у КАЖДОГО, и прибор отвечает, различается ли механизм "
                         "по протоколам (ADR-1010). Один протокол на этот вопрос НЕ отвечает. "
                         "Вместе с --timeouts снимается МАТРИЦА «предел × протокол» (ADR-1012)")
    ap.add_argument("--timeout", type=float, default=None,
                    help="предел модуля у бегуна, с. Умолчания-литерала у прибора НЕТ: не назван — берётся ОБЪЯВЛЕНИЕ бегуна `MODULE_TIMEOUT`, и выбор ПЕЧАТАЕТСЯ (ADR-1011)")
    ap.add_argument("--timeouts", default=None, metavar="СПИСОК",
                    help="`declared` (предел бегуна) и/или числа через запятую: наблюдение снимается у КАЖДОГО, и прибор отвечает, различается ли механизм по пределу (ADR-1011). Один предел на этот вопрос НЕ отвечает")
    ap.add_argument("--duration-repeats", type=int, default=1, metavar="N",
                    help=f"сколько ПРОХОДОВ по всему реестру снять ради населения класса «дольше "
                         f"предела хотя бы иногда» (ADR-1016, минимум {DURATION_MIN_PASSES}). "
                         f"Умолчание 1 означает НЕ ИЗМЕРЕНО с причиной, а не «класс пуст»: ряду "
                         f"из одного наблюдения вопрос «иногда» не задать вовсе")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)
    repo = Path(args.repo_root).resolve() if args.repo_root else ROOT
    if args.repo_root is None:
        print(f"[реестр→бегун] дерево не названо — беру своё: {repo}", file=sys.stderr)
    try:
        c = measure(repo, Path(args.readers_json) if args.readers_json else None)
        obs = None
        observations: Optional[Dict[str, Dict[str, Any]]] = None
        by_timeout: Optional[Dict[str, Dict[str, Any]]] = None
        by_cell: Optional[Dict[str, Dict[str, Any]]] = None
        knob: Optional[Dict[str, Any]] = None
        obs_margin: Optional[Dict[str, Any]] = None
        duration: Optional[Dict[str, Any]] = None
        dur_control: Optional[Dict[str, Any]] = None
        if args.observe:
            # ADR-1011: предел НЕ имеет умолчания-литерала у прибора. Своё `3.0` совпадало с
            # объявлением бегуна, и совпадение делало вопрос «кто тут объявляет» невидимым.
            #
            # ADR-1012: и спрашивается он ТОЛЬКО когда есть наблюдение. Предел — вход
            # НАБЛЮДЕНИЯ, и до 15.11 он читался безусловно: дерево без объявления
            # `MODULE_TIMEOUT` получало код 2 даже на чисто СТАТИЧЕСКИЙ вопрос, которому предел
            # не нужен ни для чего. Отказ был верен по форме и мимо по предмету — «не измерено»
            # печаталось о том, чего не спрашивали. Красным это держало
            # `test_main_prints_three_outcomes_and_returns_the_code`.
            base_timeout = args.timeout
            if base_timeout is None:
                base_timeout = read_runner_timeout(repo)
                print(f"[реестр→бегун] предел не назван — беру ОБЪЯВЛЕНИЕ бегуна "
                      f"`{RUNNER_TIMEOUT_NAME}` = {base_timeout} с", file=sys.stderr)
            if args.protocols and args.timeouts:
                # ADR-1012: МАТРИЦА двух входов. Отказ ADR-1011 § 6 был верен для словаря с
                # ОДНИМ ключом — здесь ключ клетки несёт оба входа (`cell_key`), поэтому
                # молчаливого выбора «главного» входа не остаётся ни одного.
                wanted = (list(read_runner_protocols(repo)) if args.protocols.strip() == "all"
                          else [s.strip() for s in args.protocols.split(",") if s.strip()])
                if not wanted:
                    raise NotMeasured("--protocols не назвал ни одного протокола")
                wanted_t = _parse_timeouts(args.timeouts, repo)
                by_cell = {}
                for name in wanted:
                    for t in wanted_t:
                        print(f"[реестр→бегун] клетка матрицы: протокол {name}, предел {t} с",
                              file=sys.stderr)
                        by_cell[cell_key(name, t)] = observe(Path(args.observe), c,
                                                             protocol=name, timeout=t)
                # Разборы ОДНОГО наблюдения (спутники осей, ADR-1006…1009) печатаются от
                # НАЗВАННОЙ клетки, и выбор ПЕЧАТАЕТСЯ: молчаливая «первая клетка» была бы тем
                # же необъявленным входом на уровень ниже.
                head = cell_key(wanted[0], wanted_t[0])
                print(f"[реестр→бегун] разборы одного наблюдения — от клетки {head}",
                      file=sys.stderr)
                obs = by_cell[head]
            elif args.protocols:
                # Перечень — у БЕГУНА (`all`) либо назван вслух. Своей копии списка у прибора нет.
                wanted = (list(read_runner_protocols(repo)) if args.protocols.strip() == "all"
                          else [s.strip() for s in args.protocols.split(",") if s.strip()])
                if not wanted:
                    raise NotMeasured("--protocols не назвал ни одного протокола")
                observations = {}
                for name in wanted:
                    print(f"[реестр→бегун] наблюдение, протокол {name}", file=sys.stderr)
                    observations[name] = observe(Path(args.observe), c, protocol=name,
                                                 timeout=base_timeout)
                # Разборы «одного протокола» печатаются от ПЕРВОГО названного, и render его называет.
                obs = observations[wanted[0]]
                by_timeout = {timeout_key(base_timeout): obs}
            elif args.timeouts:
                wanted_t = _parse_timeouts(args.timeouts, repo)
                by_timeout = {}
                for t in wanted_t:
                    print(f"[реестр→бегун] наблюдение, предел {t} с", file=sys.stderr)
                    by_timeout[timeout_key(t)] = observe(Path(args.observe), c,
                                                         protocol=args.protocol, timeout=t)
                obs = by_timeout[timeout_key(wanted_t[0])]
                observations = {args.protocol: obs}
            else:
                obs = observe(Path(args.observe), c, protocol=args.protocol, timeout=base_timeout)
                observations = {args.protocol: obs}
                by_timeout = {timeout_key(base_timeout): obs}
            # Контроль входа стои́т РЯДОМ с наблюдением и на ТОМ ЖЕ дереве: ответ о пределе
            # принадлежит тому бегуну, которого мерили, а не тому, из которого запущен прибор.
            knob = timeout_knob_control(Path(args.observe))
            # ADR-1015: второй контроль того же входа, но на ПУТИ НАБЛЮДЕНИЯ — и на том же
            # дереве, по той же причине, что у первого.
            obs_margin = observer_margin_control(Path(args.observe))
            # ADR-1016: население класса «дольше предела хотя бы иногда». Ряд проходов стои́т
            # дорого (каждый проход — весь реестр), поэтому он снимается ТОЛЬКО по названному
            # входу `--duration-repeats`; не назван ⇒ НЕ ИЗМЕРЕНО с причиной, а не нуль.
            dur_control = duration_population_control(Path(args.observe))
            if args.duration_repeats >= DURATION_MIN_PASSES:
                print(f"[реестр→бегун] ряд проходов ради населения: {args.duration_repeats} "
                      f"проход(ов) по всему реестру, предел {base_timeout} с",
                      file=sys.stderr)
            # Зов идёт в ОБОИХ случаях одной дверью: при недостаточном числе проходов прибор сам
            # отвечает НЕ ИЗМЕРЕНО с причиной И НЕ ТРОГАЕТ наблюдателя (проверка проходов стои́т
            # до него). Ветка «не звать вовсе» дала бы `None`, то есть «не запускали», —
            # неотличимо от «наблюдатель не отдал ряда», а это разные причины.
            duration = duration_population(
                Path(args.observe), protocol=args.protocol, timeout=base_timeout,
                passes=args.duration_repeats)
    except NotMeasured as exc:
        if args.json:
            print(json.dumps({"code": 2, "unmeasured_reason": str(exc)}, ensure_ascii=False))
        else:
            print(f"⚠️ НЕ ИЗМЕРЕНО: {exc}")
        return 2
    if args.json:
        doc = to_doc(c)
        if obs is not None:
            doc["observation"] = obs
        # ADR-1006/1007: спутник печатается ВСЕГДА и у КАЖДОЙ объявленной оси — без наблюдения он
        # несёт НЕ ИЗМЕРЕНО, а не нули. Машинный читатель, получивший нули вместо «не мерили», и
        # был бы предметом этих решений с другой стороны.
        doc["foreign_observed"] = foreign_observed(c, obs)
        doc["observed_axes"] = observed_axes(c, obs)
        # ADR-1008: причины тишины «вошёл и промолчал» — ВСЕГДА, и без наблюдения это НЕ нули,
        # а названная причина «не мерили» (машинный читатель, получивший нули, был бы предметом
        # этого решения с другой стороны — тот же довод, что у `observed_axes`).
        doc["silent_causes"] = silent_causes(repo, c, obs)
        # ADR-1009: причины статуса `unchecked` у КАЖДОЙ объявленной оси (`UNENTERED_AXES`) —
        # тот же порядок, что у `observed_axes`/`silent_causes`: без наблюдения это НЕ нули, а
        # названная причина «не мерили».
        doc["unentered_causes"] = unentered_causes_by_axis(repo, c, obs)
        # ADR-1010: протокол — ОБЪЯВЛЕННЫЙ вход, и ответ о нём печатается всегда. Одно наблюдение
        # даёт НЕ ИЗМЕРЕНО с причиной, а не «инвариантно».
        doc["protocol_variance"] = protocol_variance(
            repo, c, None if by_cell else observations,
            absent_reason=_MATRIX_ABSENT_REASON if by_cell else None)
        # ADR-1011: тот же порядок у второго входа — предел. Без наблюдения это НЕ нули, а
        # названная причина; `INVARIANT` без живого контроля входа не печатается вовсе.
        doc["timeout_variance"] = timeout_variance(
            repo, c, None if by_cell else by_timeout, knob,
            absent_reason=_MATRIX_ABSENT_REASON if by_cell else None)
        # ADR-1012: матрица — третий объявленный ответ, и порядок у неё тот же: без матричного
        # зова это НЕ нули, а названная причина.
        doc["matrix_variance"] = matrix_variance(repo, c, by_cell, knob)
        doc["timeout_knob_control"] = knob or {
            "verdict": _KB_UNMEASURED, "unmeasured_reason": "контроль входа не запускался"}
        # ADR-1015: наклад наблюдателя и укус предела на ПУТИ НАБЛЮДЕНИЯ — тем же порядком, что
        # у контроля входа: без сцены это НЕ нули, а названная причина.
        doc["observer_margin_control"] = obs_margin or {
            "verdict": _OB_UNMEASURED, "overhead_s": None, "overhead_kind": None,
            "unmeasured_reason": "сцена наклада не запускалась"}
        # ADR-1016: население класса и контроль его оси — тем же порядком: без ряда это НЕ нули,
        # а названная причина (машинный читатель, получивший нуль вместо «не мерили», и был бы
        # предметом этого решения с другой стороны).
        doc["duration_population"] = duration or {
            "computing_population": None, "wall_over_limit_n": None,
            "unmeasured_reason": "ряд проходов не снимался"}
        doc["duration_population_control"] = dur_control or {
            "verdict": _DP_UNMEASURED, "unmeasured_reason": "сцена оси проходов не запускалась"}
        if observations is not None and len(observations) > 1:
            doc["observations"] = observations
        if by_timeout is not None and len(by_timeout) > 1:
            doc["observations_by_timeout"] = by_timeout
        if by_cell is not None and len(by_cell) > 1:
            doc["observations_by_cell"] = by_cell
        print(json.dumps(doc, ensure_ascii=False, indent=2))
    else:
        print(render(c, obs, observations, by_timeout, knob, by_cell, obs_margin,
                     duration, dur_control))
    return c.code


