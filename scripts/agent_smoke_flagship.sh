# ПОЧЕМУ ИМЕННО ХОСТ, А НЕ CI — это измерено, а не предположено. Прогон 15.08 в чистом дереве:
# 5 отказов из 5, и ни один не про флагман. `git ls-files data/rates_desk` = 0 (живые артефакты
