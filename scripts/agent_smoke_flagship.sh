# в CI неисполнима по построению: смоук читает ЖИВЫЕ данные и собирает лендинг. Обе предпосылки
# есть только на Маке — поэтому агент, а не workflow.
#
# КАДЭНС — раз в неделю (604800 с). Смоук тяжёлый (живой движок exit_nav + `npm run build`),
# ежедневный прогон конкурировал бы с дневным циклом за ту же машину и те же артефакты, а
# ежемесячный узнавал бы о поломке слишком поздно.
#
# КОД ВОЗВРАТА НЕ ГАСИМ: смоук возвращает 1 при любом отказе, и это единственный канал, по
# которому «флагман сломался» доедет до agent_health (last_exit). Обернуть в ноль = вернуть
# состояние «его никто не запускал».
#
# УСТАНОВКА — ДЕЙСТВИЕ ВЛАДЕЛЬЦА (.claude/rules/deployment.md, п. 6): этот файл, plist и строка
# установщика — код; `launchctl bootstrap` делает владелец, предварительно убедившись, что в
# `landing/` выполнен `npm install` (иначе шаг 4 смоука честно упадёт каждую неделю).
# ВНИМАНИЕ: гейт `check_agent_before_deploy.sh` здесь безопасен (агент расписанный, не
# KeepAlive-долгожитель), но первый прогон стоит сделать руками и прочитать вывод.
