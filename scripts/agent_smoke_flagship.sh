#
# ЗАЧЕМ АГЕНТ. `scripts/smoke_test_flagship.py` называет себя «единственной командой, которую
# запускает владелец (или CI), чтобы убедиться, что флагман здоров» — и не запускался НИКЕМ.
# До цикла #228 он числился подключённым по докстрингу соседнего `scripts/smoke.py` («в отличие
