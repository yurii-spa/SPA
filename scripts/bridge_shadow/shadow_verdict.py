#!/usr/bin/env python3
"""Studio Bridge · классы расхождения и ВЕРДИКТ теневого прогона.

Почему это отдельный модуль
===========================
``shadow_gate.py`` импортирует прототип моста (``~/studio-os-scratch``) на уровне
модуля, и в CI такого каталога нет по построению. Правило и вердикт от прототипа не
зависят ни одной строкой — они чистые. Разведя их, мы получаем сторожа, который
исполняется ВЕЗДЕ, а не только на машине владельца: проверка, которую CI не может
запустить, не отличима от отсутствующей.

Что здесь починено (цикл #690, заказ G83 п. 3; пятый заказ подряд числил это остатком)
=====================================================================================
``classify_mismatch`` умеет вернуть ``OLD_DECISION_NOT_RECORDED`` — «старому решению
не с чем сравниваться, потому что оно НЕ ЗАПИСАНО». Прежний вердикт читал счётчик
двумя именованными ключами::

    'CLEAN' if not counts.get(UNEXPLAINED) and not counts.get(WEAKENING) else 'DIRTY'

и потому объявлял ЧИСТЫМ прогон, в котором не состоялось НИ ОДНОГО сравнения. Замер
на живом коде перед починкой (обе сцены — код возврата 0):

==================================  ========  ==================================  =======
сцена                               событий   by_mismatch                         вердикт
==================================  ========  ==================================  =======
базы моста нет на пути                     0  ``{}``                              CLEAN
база есть, сравнимых событий ноль           6  ``{OLD_DECISION_NOT_RECORDED: 6}``  CLEAN
==================================  ========  ==================================  =======

Это инвариант #17 дословно: «не измерено» обязано быть ОТДЕЛЬНЫМ значением, а не
успехом. Цена ошибки здесь выше обычной: весь смысл теневого прогона — доказать, что
новый гейт НИКОГДА не ослабляет старый. «Ослаблений 0» на нуле сравнений — не
доказательство безопасности, а его подделка, и выглядит оно в точности как настоящее.

Три исхода и закрытый перечень
==============================
* ``CLEAN`` — сравнения СОСТОЯЛИСЬ (их не ноль) и вреда в них нет;
* ``DIRTY`` — сравнение состоялось и нашло вред (``UNEXPLAINED`` / ``WEAKENING``);
* ``UNMEASURED`` — судить не о чем: источник не прочитан, либо сравнимых событий ноль,
  либо классификатор вернул класс ВНЕ объявленного перечня.

Последнее важно отдельно. Прежний вердикт спрашивал про два ИМЕНИ, поэтому любой
будущий класс — не только сегодняшний ``OLD_DECISION_NOT_RECORDED`` — проходил бы
насквозь молча. Теперь перечень ЗАКРЫТ: незнакомый класс есть отказ с названной
причиной, а не тишина. Правило то же, что у ``deployment.md``: отсутствие
наблюдения — самостоятельный третий исход, а не число и не пропуск.

Только stdlib. Ничего не исполняет и никуда не пишет.
"""
from __future__ import annotations

WOULD_ALLOW = 'WOULD_ALLOW'
WOULD_BLOCK = 'WOULD_BLOCK'

OLD_ALLOWED = 'OLD_ALLOWED'
OLD_BLOCKED = 'OLD_BLOCKED'
OLD_UNKNOWN = 'OLD_UNKNOWN'

#: Виды расхождения. Один из них недопустим ни в одном случае.
AGREE = 'AGREE'
EXPLAINED_STRICTER = 'EXPLAINED_STRICTER'      # новый строже, причина названа
UNEXPLAINED = 'UNEXPLAINED'                    # новый строже, причины нет
WEAKENING = 'WEAKENING'                        # новый пустил то, что старый закрыл
#: Сравнения НЕ БЫЛО: старое решение не записано. Не «чисто» и не «грязно».
OLD_DECISION_NOT_RECORDED = 'OLD_DECISION_NOT_RECORDED'

#: Классы, в которых сравнение состоялось.
COMPARED = (AGREE, EXPLAINED_STRICTER, UNEXPLAINED, WEAKENING)
#: Классы, в которых сравнения не было.
NOT_COMPARED = (OLD_DECISION_NOT_RECORDED,)
#: ЗАКРЫТЫЙ перечень. Класс вне его — отказ с названной причиной, а не тишина.
MISMATCH_CLASSES = COMPARED + NOT_COMPARED
#: Вред. Ровно то, ради чего теневой прогон и существует.
HARM = (UNEXPLAINED, WEAKENING)

CLEAN = 'CLEAN'
DIRTY = 'DIRTY'
UNMEASURED = 'UNMEASURED'

#: Код возврата по вердикту. Порядок тот же, что у прочих приборов дерева:
#: 0 — измерено и чисто, 1 — находка, 2 — НЕ ИЗМЕРЕНО.
EXIT_CODE = {CLEAN: 0, DIRTY: 1, UNMEASURED: 2}


class SourceNotRead(Exception):
    """Источник событий не прочитан.

    Отдельный тип, а не пустой список: «базы нет» и «база пуста» — разные
    утверждения, и прежний код возвращал на оба одно и то же ``[]``.
    """


def classify_mismatch(old, shadow, why):
    """Тип расхождения. ``WEAKENING`` недопустим ни в одном случае."""
    if old == OLD_ALLOWED and shadow == WOULD_BLOCK:
        return (EXPLAINED_STRICTER if why and why != ['все условия доставки выполнены']
                else UNEXPLAINED)
    if old == OLD_BLOCKED and shadow == WOULD_ALLOW:
        return WEAKENING
    if old == OLD_ALLOWED and shadow == WOULD_ALLOW:
        return AGREE
    if old == OLD_BLOCKED and shadow == WOULD_BLOCK:
        return AGREE
    return OLD_DECISION_NOT_RECORDED


def shadow_verdict(counts, *, events, source_read):
    """Вердикт теневого прогона и ПРИЧИНА одной строкой.

    ``counts`` — счётчик классов расхождения; ``events`` — сколько событий прочитано;
    ``source_read`` — прочитан ли источник вообще.

    Возвращает ``(вердикт, причина)``. Причина обязательна у каждого исхода: вердикт
    без причины нечем поверить, а у ``UNMEASURED`` причина и есть указание, что чинить.

    Порядок ветвей выбран, а не случаен. Измеренный вред объявляется ПЕРВЫМ: ослабление
    — факт, и прятать его за «не измерено» значило бы потерять единственную находку,
    ради которой прогон затеян. Незнакомый класс при этом не исчезает — он назван в той
    же причине и всплывёт сам, как только вред будет починен.
    """
    unknown = sorted(k for k in counts if k not in MISMATCH_CLASSES)
    harm = {k: counts[k] for k in HARM if counts.get(k)}
    compared = sum(counts.get(k, 0) for k in COMPARED)
    not_compared = sum(counts.get(k, 0) for k in NOT_COMPARED)
    tail = (f'; и КРОМЕ ТОГО классификатор вернул класс вне перечня: '
            f'{", ".join(unknown)}') if unknown else ''

    if harm:
        found = ', '.join(f'{k} {n}' for k, n in sorted(harm.items()))
        return DIRTY, f'сравнение состоялось и нашло вред: {found}{tail}'
    if unknown:
        return UNMEASURED, (
            f'классификатор вернул класс вне закрытого перечня: {", ".join(unknown)}. '
            'Судить о вреде нечем: вердикт читает ОБЪЯВЛЕННЫЕ классы, а незнакомый '
            'класс может нести и вред, и его отсутствие')
    if not source_read:
        return UNMEASURED, ('источник событий не прочитан: базы моста нет на '
                            'объявленном пути — сравнивать было нечего')
    if compared == 0:
        return UNMEASURED, (
            f'сравнения не состоялось ни одного: событий {events}, из них без '
            f'записанного старого решения {not_compared}. «Ослаблений 0» здесь пусто '
            'по построению и безопасности не доказывает')
    return CLEAN, (f'сравнений {compared}, вреда в них нет; событий без записанного '
                   f'старого решения {not_compared} — они в вердикт не входят')
