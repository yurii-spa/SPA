def read_reap_ledger(root):
    """({путь снятого дерева: запись}, причина-если-не-прочитано).

    **Зачем.** Уборка мёртвых деревьев (`scripts/reap_stale_worktrees.py`) убирает осадок
    находок — и на её месте появился бы худший класс: объявленный путь внутри снятого дерева
    даёт «измерить нечем» и код 2 НАВСЕГДА. Квитанция — измерение, сделанное тогда, когда
    дерево ещё было: пофайловый вердикт плюс путь архива.

    Ослабления нет: пропуск получает только путь, названный в квитанции `delivered` или
    `superseded`. Нет квитанции · нет пути в ней · вердикт другой — прежнее «не измерено» /
    находка. Отсутствие журнала — норма (уборку могли ни разу не запускать), причиной оно не
    становится."""
    path = Path(root) / "data" / REAP_LEDGER_NAME
    if not path.exists():
        return {}, None
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as exc:
        return {}, f"журнал снятых рабочих деревьев не прочитан ({path}): {exc}"
    rows, bad = {}, 0
    for line in raw.splitlines():
        if not line.strip():
            continue
        try:
            obj = json.loads(line)
        except json.JSONDecodeError:
            bad += 1
            continue
        wt = obj.get("worktree")
        if wt:
            rows[str(Path(wt))] = obj          # последняя запись о дереве главнее
    return rows, (f"битых строк в журнале снятых деревьев: {bad}" if bad else None)


def churn_rule():
    """(предикат «уборщик отсеивает этот путь как рабочее состояние», причина-если-не-прочитан).

    **Почему импортом, а не копией.** Правило отсева живёт в уборщике
    (`reap_stale_worktrees.CHURN_PREFIXES` / `CHURN_PATHS`), и менять его будут там — вслед за
    писателями, которые пачкают дерево. Своя копия правила здесь разошлась бы МОЛЧА, а от
    точности этого предиката зависит вердикт «поднимать нечего»: путь, отсеянный уборщиком,
    в квитанцию не попадает, даже если он в дереве лежал. Тот же приём, которым #234 перенёс
    `main_worktree` в уборщик, — импорт в обратную сторону.

    Импорт ЛЕНИВЫЙ намеренно: уборщик импортирует этот модуль на верхнем уровне, и встречный
    импорт на верхнем уровне замкнул бы кольцо. К моменту вызова оба модуля уже загружены.

    ``None`` — правило прочитать не удалось: вердикта не будет (fail-CLOSED, класс #226 —
    fail-OPEN внутри fail-CLOSED-сторожа)."""
    import sys
    scripts_dir = str(Path(__file__).resolve().parent)
    if scripts_dir not in sys.path:
        sys.path.insert(0, scripts_dir)
    try:
        from reap_stale_worktrees import CHURN_PATHS, CHURN_PREFIXES
    except Exception as exc:                   # noqa: BLE001 — «не прочитано» это тоже измерение
        return None, ("правило отсева уборщика (churn) прочитать не удалось "
                      f"({type(exc).__name__}: {exc}) — попал бы путь в квитанцию или нет, "
                      "НЕ ИЗМЕРЕНО")
    return (lambda rel: rel.startswith(tuple(CHURN_PREFIXES)) or rel in CHURN_PATHS), None


def reap_where(row) -> str:
    """Общая шапка квитанции: «какое дерево, когда снято, где архив».

    Вынесена, чтобы у вердикта (`reaped_state`) и у сборщика записи была ОДНА строка, а не две
    похожие: рендер отчёта отделяет шапку от хвоста вычитанием префикса, и разойдись эти две
    формулировки — группировка молча перестала бы срабатывать (текст остался бы верным, а
    свёртка исчезла). Один источник — расхождение невозможно."""
    return f"дерево снято {row.get('ts')} по правилу уборки, архив: {row.get('archive')}"


def reap_match(path_str, ledger):
    """(worktree, строка-квитанция, путь относительно дерева) для объявленного пути, либо тройка None.

    Сопоставление вынесено из `reaped_state`, потому что оно нужно ДВАЖДЫ: вердикту и сборщику
    записи отчёта (тому нужны дерево/время/архив, чтобы сгруппировать квитанции по деревьям).
    `/tmp` и `/private/tmp` на macOS — один каталог, поэтому сверяются обе формы (см. #303)."""
    p = Path(str(path_str))
    if not p.is_absolute():
        return None, None, None
    for wt, row in ledger.items():
        prefix = wt.rstrip("/") + os.sep
        variants = {str(p), str(p).replace("/private/tmp/", "/tmp/", 1),
                    str(p).replace("/tmp/", "/private/tmp/", 1)}
        hit = next((v for v in variants if v.startswith(prefix)), None)
        if hit is None:
            continue
        return wt, row, hit[len(prefix):]
    return None, None, None


def reaped_state(path_str, ledger, root, base_ref, git=_git):
    """(вердикт, объяснение) для объявленного пути внутри СНЯТОГО дерева, либо (None, None).

    Вердикты: ``delivered`` — снятие было измерено и работа объяснена; ``nowhere`` — путь в
    квитанции не назван и на базе его нет вовсе, то есть в дереве его на момент снятия НЕ БЫЛО
    (поднимать нечего); ``deleted_on_origin`` — то же, но имя на базе БЫЛО и было оттуда удалено
    (тоже поднимать нечего, см. ниже); ``absent`` — вывод сделать НЕЛЬЗЯ, и находка остаётся;
    ``unmeasured`` — квитанция называет путь недоставленным (снятия такого дерева быть не должно,
    но если оно случилось — молчать нельзя).

    **Почему «нет в квитанции» — это вывод, а не пустота (цикл #292).** Квитанция снятия
    перечисляет КАЖДЫЙ путь, которым дерево расходилось с базой, и составляется она ТОГДА, когда
    дерево ещё существует. Путь, которого в ней нет, с базой не расходился; если вдобавок на базе
    такого файла нет вовсе — в дереве его не было. Улики модуль печатал и раньше, не хватало
    ровно вердикта: находка проваливалась в «НЕ ДОСТАВЛЕНО» по умолчанию, и раздел набивался
    осадком — тем самым, которым сторожа глохнут (#243 сбивал его с 42 до 4).
    Это НЕ новое допущение: на том же «нет в квитанции ⇒ не расходился» уже держится ветка
    `delivered` ниже (замер по журналу 18.08 — 741 путь).

    **Две границы, и обе fail-CLOSED, а не «на всякий случай».** Уборщик отсеивает из квитанции
    churn-пути (`data/`, три именованные фикстуры) — такой путь в неё не попал бы, даже если бы
    в дереве лежал, поэтому вывода о нём нет: остаётся находка. И если путь в истории базы
    ВСТРЕЧАЛСЯ, «нигде» ложно: имя существовало. Обе ветки измеряются, а не предполагаются.

    **Почему «встречался в истории» перестал быть находкой (цикл #298).** Прежде эта ветка
    отдавала `absent`, и вердикт спорил с уликой в собственной же строке: раздел звал «сверить
    руками и поднять», а объяснение рядом говорило «это удаление, а не пропажа». Поднимать при
    этом звали НАШУ доставленную работу — корневой `__init__.py`, осознанно снятый с origin
    циклом #297. Довод, по которому поднимать нечего, тот же, на котором уже держится ветка
    `nowhere` выше: квитанция называет КАЖДЫЙ расходившийся путь и составлена ДО снятия ⇒ путь,
    которого в ней нет, с базой не расходился, а содержимое базы никуда не делось — оно в её
    истории. Разница между `nowhere` и `deleted_on_origin` ровно одна: существовало имя или нет;
    на «что можно поднять» она не влияет.

    **Что этой веткой НЕ измеряется — названо, а не умолчано.** Уборщик собирает работу как
    пересечение «изменено в дереве» и «расходится с базой», поэтому файл, ЗАКОММИЧЕННЫЙ в
    дереве локально, в квитанцию не попадает. Такое дерево уборщик снимет и без этой правки —
    дефект принадлежит уборщику, а не вердикту здесь (карточка
    `inbox-uborschik-snimaet-derevo-s-lokalnym-komm`)."""
    wt, row, rel = reap_match(path_str, ledger)
    if wt is None:
        return None, None
    state = (row.get("paths") or {}).get(rel)
    where = reap_where(row)
    explained, _why_fallback = reap_explained()
    if state in explained:
        return DELIVERED, f"{where}; содержимое пути объяснено при снятии ({state})"
    if state == DROPPED:
        # Уборщик снял дерево, потому что сессия ОБЪЯВИЛА этот путь намеренно недоставленным
        # (#354). Без этой ветки квитанция читалась бы веткой ниже как «помечен неизвестно
        # чем» ⇒ код 2 навсегда: починка уборщика родила бы в шаге 0a ровно тот класс
        # необратимого «не измерено», ради снятия которого квитанция и писалась.
        decl = (row.get("dropped") or {}).get(rel) or {}
        reason = str(decl.get("reason") or "").strip()
        if not reason:
            # Слово в квитанции есть, причины нет — судить «это решение» нечем. Fail-CLOSED:
            # прежнее «не измерено», а не молчаливый пропуск.
            return UNMEASURED, (f"{where}, путь помечен при снятии как {DROPPED!r}, НО причина "
                                "в квитанции не названа — решение это было или порча записи, "
                                "НЕ ИЗМЕРЕНО")
        who = f"сессия {decl.get('session')}, {decl.get('ts')}"
        card = f", карточка {decl['card']}" if decl.get("card") else ""
        return DROPPED, (f"{where}; путь объявлен НАМЕРЕННО не доставленным: {reason} "
                         f"[{who}{card}]")
    if state is not None:
        return UNMEASURED, (f"{where}, НО путь помечен при снятии как {state!r} — "
                            "снятие такого дерева правилом не предусмотрено")
    rc, _, _ = git(root, "cat-file", "-e", f"{base_ref}:{rel}")
    if rc != 0:
        head = (f"{where}, путь в квитанции не назван, и на {base_ref} такого файла "
                "нет вовсе")
        is_churn, why_churn = churn_rule()
        if is_churn is None:
            return ABSENT, f"{head}; {why_churn}"
        if is_churn(rel):
            return ABSENT, (f"{head} — НО под правило отсева уборщика (churn) этот путь "
                            "подпадает, и в квитанцию он не попал бы, даже если бы лежал "
                            "в дереве: был он там или нет, НЕ ИЗМЕРЕНО")
        hist = origin_blob_history(root, base_ref, rel, git=git)
        if hist is None:
            return ABSENT, (f"{head}; историю {base_ref} по этому пути прочитать не "
                            "удалось — существовало ли имя, НЕ ИЗМЕРЕНО")
        if hist:
            return DELETED_ON_ORIGIN, (
                f"{head}, но в истории {base_ref} путь встречался ({len(hist)} версий) — "
                "это удаление/переименование на origin, а не пропажа объявленной работы. "
                "Квитанция перечисляет КАЖДЫЙ расходившийся с базой путь и составлена ДО "
                "снятия: этого пути в ней нет ⇒ в дереве лежало ровно то, что и на базе, "
                "а содержимое базы живёт в её истории. ПОДНИМАТЬ НЕЧЕГО")
        return NOWHERE, (f"{head}. Квитанция перечисляет КАЖДЫЙ расходившийся с базой путь "
                         "дерева и составлена ДО снятия; под правило отсева (churn) путь не "
                         "подпадает, в истории базы не встречался ни разу — значит в дереве "
                         "его на момент снятия НЕ БЫЛО. ПОДНИМАТЬ НЕЧЕГО: имя объявлено "
                         "авансом, файла под ним не появилось")
    return DELIVERED, (f"{where}; путь при снятии не расходился с {base_ref} "
                       "(правки в дереве не было)")


def group_tree_gone(unmeasured):
    """[{session, common_root, count, sample, paths}] — записи «дерево снято» одной на дерево.

    **Зачем группировка, а не строка на путь.** Одно снятое руками дерево даёт СТОЛЬКО строк,
    сколько путей объявила сессия (замер 16.08: `/tmp/spa_c256` — 12 строк), и все они об
    одном и том же событии с одним и тем же действием читателя: никаким. Это тот самый
    механизм, которым сторожа глохнут, — и модуль уже решал его так же для мёртвых
    регистраций: «НАЗЫВАЕТСЯ одной строкой на каталог».

    **Что НЕ меняется:** записи остаются в `report["unmeasured"]` все до одной (счёт в
    заголовке раздела и код возврата 2 считаются по ним), в JSON-выводе они тоже все. Сжат
    ровно ЧЕЛОВЕЧЕСКИЙ вывод. Ослабления нет: ни одна запись не исчезает и не меняет вердикт.

    Корень дерева не угадывается: берётся общий префикс объявленных путей (`commonpath`) и
    называется тем, что он есть, — общим корнем объявленного, а не «тем самым деревом»."""
    groups, order = {}, []
    for u in unmeasured:
        if not u.get("tree_gone") or not u.get("path"):
            continue
        key = u.get("session")
        if key not in groups:
            groups[key] = {"session": key, "paths": []}
            order.append(key)
        groups[key]["paths"].append(str(u["path"]))
    out = []
    for key in order:
        paths = groups[key]["paths"]
        try:
            common = os.path.commonpath(paths) if len(paths) > 1 else str(Path(paths[0]).parent)
        except ValueError:                     # разные корни — общего пути нет, и это честно
            common = "общего корня у объявленных путей нет"
        out.append({"session": key, "common_root": common, "count": len(paths),
                    "sample": [Path(p).name for p in paths[:3]], "paths": paths})
    return out


def resolve_rel(path_str, root, git=_git):
    """(repo-relative POSIX-путь, None) либо (None, причина). Тот же принцип, что в пушере:
    принадлежность ТОМУ ЖЕ репозиторию определяется по общему git-каталогу."""
    p = Path(str(path_str))
    if not p.is_absolute():
        return p.as_posix(), None

    root = Path(root).resolve()
    try:
        return p.resolve().relative_to(root).as_posix(), None
    except ValueError:
        pass

    probe = p if p.is_dir() else p.parent          # `git -C` хочет каталог, не файл
    climbed = not probe.is_dir()                   # пришлось лезть выше — каталогов уже нет
    while not probe.is_dir() and probe != probe.parent:
        probe = probe.parent
    if not probe.is_dir() or probe == probe.parent:
        return None, (f"путь вне хост-репо, каталога больше нет (worktree удалён?): {path_str}")

    ours = _git_common_dir(root, git)
    theirs = _git_common_dir(probe, git)
    if ours is None or theirs is None or ours != theirs:
        # Две РАЗНЫЕ причины с одинаковым исходом «измерить нельзя», и называть их одинаково
        # нечестно. Если каталогов объявленного пути уже нет, а уцелевший предок — не наш
        # репозиторий, то дело не в чужом репозитории: рабочее дерево УДАЛЕНО вместе с
        # работой. Прежний текст «путь не принадлежит этому репозиторию» звучал как ошибка
        # объявления (кто-то объявил чужой файл), тогда как это потеря своего.
        # Вердикт не меняется — по-прежнему «не измерено» (код 2): доехала ли работа, из
        # удалённого дерева не узнать. Меняется только то, что сессия об этом прочитает.
        if climbed:
            return None, (f"{TREE_GONE} — доставку измерить нечем: {path_str}")
        return None, f"путь не принадлежит этому репозиторию: {path_str}"

    rc, top, _ = git(probe, "rev-parse", "--show-toplevel")
    if rc != 0 or not top.strip():
        return None, f"не удалось определить корень worktree для {path_str}"
    try:
        return p.resolve().relative_to(Path(top.strip()).resolve()).as_posix(), None
    except ValueError:
        return None, f"путь вне найденного корня worktree: {path_str}"


def declaring_tree(path_str, root, git=_git, announce_cwd=None):
    """Рабочее дерево, ИЗ КОТОРОГО объявлен путь: (str-корень, None) либо (None, причина).

    Дерево не угадывается и не выводится из совпадения имён — его называет САМА запись
    журнала: `log_session_change.py` принимает абсолютные пути, и сессия объявляет пути
    своего дерева (протокол §3.4 обязывает работать в worktree). Разрешение — тем же
    принципом, что в `resolve_rel`: принадлежность репозиторию по общему git-каталогу,
    корень — `rev-parse --show-toplevel`.

    ``announce_cwd`` — каталог, из которого сделано объявление (поле ``cwd``,
    `log_session_change.py`). Он нужен ровно для относительных путей: ``--files``
    документирован как абсолютные пути, но ничем это не проверяется, и 24.08 сессия
    `rnd-75-rearm` объявила три пути относительными — их дерево стало неопределимым НАВСЕГДА.
    Догадкой это не чинится: каталог берётся из САМОЙ записи, тем же принципом, что и
    абсолютный путь. Записи без ``cwd`` (все, что написаны до этого поля) судятся ровно как
    раньше.

    ``None`` — судить по «своему дереву» нечем, и это НЕ повод считать работу доставленной:
    вызывающий обязан оставить прежнее (более строгое) поведение. Причины: относительный путь
    без каталога объявления (дерева в записи нет вовсе), каталог объявления, которого больше
    нет, и удалённый каталог самого пути.
    """
    p = Path(str(path_str))
    if not p.is_absolute():
        base = Path(str(announce_cwd)) if announce_cwd else None
        if base is None:
            return None, "путь объявлен относительным — рабочее дерево в записи не названо"
        if not base.is_absolute():
            return None, ("путь объявлен относительным, и каталог объявления в записи тоже не "
                          f"абсолютен ({announce_cwd}) — рабочее дерево не определить")
        if not base.is_dir():
            return None, ("путь объявлен относительным, а каталога объявления "
                          f"({announce_cwd}) больше нет — рабочее дерево не определить")
        p = base / p

    try:
        p.resolve().relative_to(Path(root).resolve())
        return _real(root), None
    except ValueError:
        pass

    probe = p if p.is_dir() else p.parent
    climbed = not probe.is_dir()           # каталогов уже нет — лезем вверх за уцелевшим предком
    while not probe.is_dir() and probe != probe.parent:
        probe = probe.parent
    if not probe.is_dir() or probe == probe.parent:
        return None, "каталогов объявленного пути больше нет — дерево объявления не определить"

    ours = _git_common_dir(root, git)
    theirs = _git_common_dir(probe, git)
    if ours is None or theirs is None or ours != theirs:
        # Различие то же, что в `resolve_rel`: «чужой репозиторий» и «дерево удалено вместе с
        # работой» дают один исход и НЕ одну причину. Соседнее дерево с тем же путём под
        # удалённое НЕ подставляется — это была бы выдуманная атрибуция, ровно та, что чинится.
        if climbed:
            return None, "каталогов объявленного пути больше нет — дерево объявления не определить"
        return None, "объявленный путь не из этого репозитория"

    rc, top, _ = git(probe, "rev-parse", "--show-toplevel")
    if rc != 0 or not top.strip():
        return None, "корень рабочего дерева объявления не определяется"
    return _real(top.strip()), None


def _real(path) -> str:
    """Канонический путь. На macOS `/tmp` — симлинк на `/private/tmp`, и объявления пишут обе
    формы; сравнивать деревья по строке без этого нельзя (совпадение молча не найдётся)."""
    return os.path.realpath(str(path))


def _same_tree(a, b) -> bool:
    return _real(a) == _real(b)


