def list_checkouts(root, git=_git):
    """(живые рабочие деревья, [мёртвые регистрации], причина-если-не-разрешилось).

    Осиротевшая работа лежит ИМЕННО в worktree (протокол §3.4 обязывает там работать), а в
    хост-дереве её нет — пуш идёт прямо в origin через API, локальный git дрейфует. Сверка
    только с хост-деревом такую правку не увидит (проверено на историческом прогоне).

    **Мёртвая регистрация ≠ рабочее дерево.** Каталог остался, а git-привязка мертва: файл
    `.git` внутри дерева исчез, служебная запись в `.git/worktrees/` осталась. Признак «каталог
    существует» (`p.is_dir()`) такое дерево пропускал в сверку, git-вызов в нём падал, и
    `collect_diff_sets` честно писал «рабочее дерево с базой НЕ сверено».
    Замер 06.08 (карточка `inbox-shag-0a-iz-worktree-daet-18-strok-ne-izm`): 16 таких
    регистраций давали **18 строк «НЕ ИЗМЕРЕНО» и код 2** на пустом месте, и разбирать их
    следующая сессия обязана руками — то есть очень скоро перестанет читать вовсе, а однажды
    в этих же строках окажется настоящая находка (класс «необратимое „не измерено“ морит
    очередь»).

    Различаются ДВА состояния, и это не педантизм, а разные вопросы:

    - **git сам объявил запись `prunable`** — это его собственный вердикт о СВОЁМ реестре,
      мерить там нечего: перед нами не чекаут, а остатки файлов. Такая регистрация НАЗЫВАЕТСЯ
      (одной строкой на каталог, с причиной от git), но «не измерено» из неё не делается.
    - **git считает дерево живым, а привязка не читается** — вот это не объяснено ничем, и
      остаётся `unmeasured` (код 2), как было. Ослабления нет: fail-CLOSED снимается ровно
      там, где авторитетный источник — сам git — сказал, что мерить нечего.

    Каталоги мёртвых регистраций из СВЕРКИ исключаются, но не из поиска карточек:
    `scan_tracker_cards` читает файловую систему, а не git, и остатки трекера в таком каталоге
    по-прежнему видит (покрытие сторожа карточек не сужается)."""
    rc, out, err = git(root, "worktree", "list", "--porcelain")
    if rc != 0:
        return None, [], f"`git worktree list` завершился rc={rc}: {err.strip()[:200]!r}"

    dirs, dead = [], []
    path, prunable = None, None

    def flush():
        if path is None or not path.is_dir():
            return
        if prunable is not None:
            reason = prunable.strip() or "git пометил запись prunable без пояснения"
            dead.append({"path": str(path), "prunable": True,
                         "reason": f"git пометил регистрацию prunable: {reason}"})
            return
        # git считает дерево живым — проверяем, читается ли привязка.
        prc, _, perr = git(path, "rev-parse", "--git-dir")
        if prc != 0:
            dead.append({"path": str(path), "prunable": False,
                         "reason": f"git считает дерево живым, но привязка не читается: "
                                   f"`rev-parse --git-dir` rc={prc} {perr.strip()[:120]!r}"})
            return
        dirs.append(path)

    for line in out.splitlines():
        if line.startswith("worktree "):
            flush()
            path, prunable = Path(line.split(" ", 1)[1].strip()), None
        elif line == "prunable" or line.startswith("prunable "):
            prunable = line[len("prunable"):]
    flush()

    if Path(root) not in dirs:
        dirs.insert(0, Path(root))
    return dirs, dead, None


# ── осиротевшая регистрация: четвёртое вместилище недоставленного ────────────
#
# Каталоги, которые не являются работой сессии ни в каком дереве: служебные кеши и
# устанавливаемые зависимости. Список ЗАКРЫТЫЙ и поимённый — по образцу `CHURN_PATHS`
# уборщика; расширять его, чтобы «скорлупа наконец замолчала», — то же самое, что гасить
# сторожа. Отсеянное СЧИТАЕТСЯ и печатается: разница между «не считаем» и «не видим»
# обязана быть видна в самом отчёте.
SHELL_SKIP_DIRS = frozenset({
    ".git", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache",
    "node_modules", ".astro", ".venv", "venv", ".egg-info",
})


def _walk_shell(shell_dir):
    """(отсортированные относительные пути, отсеяно-каталогами, причина-если-не-прочиталось).

    Обычный обход файловой системы, а НЕ git: привязка мертва именно git-а, и спрашивать
    его тут не у кого. Симлинки не разыменовываются (за пределы скорлупы обход не выходит).

    ``onerror`` обязателен: по умолчанию `os.walk` ошибки чтения ГЛОТАЕТ, и нечитаемый
    подкаталог вернул бы пустой список — то есть «файлов вне churn нет, цена снятия ноль»
    над содержимым, которое не прочитано ВООБЩЕ. Это ровно тот fail-OPEN, ради закрытия
    которого написана вся проверка, только этажом ниже."""
    base = Path(shell_dir)
    rels, skipped = [], 0

    def _boom(exc):
        raise exc

    try:
        for dirpath, dirnames, filenames in os.walk(base, onerror=_boom, followlinks=False):
            keep = [d for d in dirnames if d not in SHELL_SKIP_DIRS]
            skipped += len(dirnames) - len(keep)
            dirnames[:] = keep
            for name in filenames:
                p = Path(dirpath) / name
                if p.is_symlink() or not p.is_file():
                    continue
                rels.append(str(p.relative_to(base)))
    except OSError as exc:                       # каталог исчез/нет прав — это НЕ «пусто»
        return None, skipped, f"обход каталога не удался: {exc!r}"
    return sorted(rels), skipped, None


def _base_tree(root, base_ref, git=_git):
    """({путь: blob-sha} для базового ref, причина-если-не-прочиталось).

    ``core.quotePath=false`` обязателен: по умолчанию git экранирует не-ASCII путь
    (``"\\320\\264..."``), а обход файловой системы даёт его сырым — совпадения не будет,
    и доставленный файл посчитался бы «старой копией». Находкой это не станет (блоб-то в
    базе есть), но число в отчёте врало бы."""
    rc, out, err = git(root, "-c", "core.quotePath=false",
                       "ls-tree", "-r", "--format=%(objectname) %(path)", base_ref)
    if rc != 0:
        return None, (f"`git ls-tree {base_ref}` завершился rc={rc}: {err.strip()[:160]!r} — "
                      "сверить содержимое скорлупы с базой НЕ УДАЛОСЬ")
    tree = {}
    for line in out.splitlines():
        sha, sep, path = line.partition(" ")
        if sep:
            tree[path] = sha
    return tree, None


def orphan_registration_scan(root, base_ref, dead, git=_git):
    """[строка на осиротевшую регистрацию] — ЧТО в ней лежит, вместо «сверять нечего».

    **Дефект, который это закрывает** (карточка `inbox-shag-0a-obyavlyaet-osirotevshuyu-registr`,
    замер цикла #323). Мёртвая регистрация — каталог рабочего дерева, у которого умерла
    git-привязка (`.git`-файл внутри исчез, служебная запись в `.git/worktrees/` осталась).
    Шаг 0a называл такую регистрацию строкой «**сверять нечего**, но и молчать не о чем» и
    советовал `git worktree prune`. Утверждение «сверять нечего» НЕВЕРНО, и это выяснилось
    при попытке выполнить его же совет: в 21 скорлупе уцелело **70 настоящих файлов** вне
    churn (`docs/STATE.md`, ADR, карточки трекера, `spa_core/monitoring/*`), из них **51**
    расходился с `origin/main`. Слепое `prune` стёрло бы последний указатель на них.

    Осиротевшая регистрация — **четвёртое** вместилище недоставленной работы: после рабочего
    дерева (шапка), удалённой ветки (ADR-100) и снятого дерева с квитанцией. На нём сторож
    молчал УТВЕРДИТЕЛЬНО — тот же класс, что вся очередь #146–#195: зелёный ответ на свой
    вопрос («git-привязки нет») выдавался за ответ на нужный («работа не потеряна?»).

    **Три исхода, и они РАЗНЫЕ** — сегодня все три схлопнуты в одну строку:

    - ``delivered`` — содержимое побайтово совпадает с `base_ref` (blob-sha равны);
    - ``stale`` — расходится с базой, НО сам блоб известен объектной базе репозитория
      (`cat-file --batch-check`): содержимое когда-то коммитилось ⇒ это старая копия,
      поднимать нечего. Именно этим оказались ВСЕ 51 расхождения замера #323;
    - ``undelivered`` — блоба нет в объектной базе ВООБЩЕ: байтов, которых не помнит
      репозиторий, нет больше нигде. **Вот это и есть находка** (код 1).

    **fail-CLOSED не ослаблен.** Любой шаг, который не отработал (правило отсева churn ·
    `ls-tree` базы · `hash-object` скорлупы · `cat-file --batch-check` · обход каталога),
    даёт ``unchecked`` и код 2 — «не смог измерить» не сворачивается в «поднимать нечего».
    Обратная сторона названа: молчаливого «всё в порядке» здесь не появляется ни в одной ветке.

    Стоимость измерена и ограничена: три вызова git на скорлупу (`hash-object --stdin-paths`
    и `cat-file --batch-check` — пакетные, по одному на регистрацию), плюс ОДИН `ls-tree`
    на весь отчёт. Потолка на число файлов НЕТ намеренно: тихо срезанное покрытие читалось бы
    как «проверено всё»."""
    rows = []
    if not dead:
        return rows

    is_churn, why_churn = churn_rule()
    tree, why_tree = _base_tree(root, base_ref, git=git)

    for d in dead:
        row = {"path": d["path"], "files": 0, "skipped_dirs": 0, "churn": 0,
               "delivered": 0, "stale": 0, "undelivered": [], "unchecked": []}
        rows.append(row)

        rels, skipped, why_walk = _walk_shell(d["path"])
        row["skipped_dirs"] = skipped
        if rels is None:
            row["unchecked"].append(why_walk)
            continue
        if is_churn is None:
            row["unchecked"].append(f"{why_churn} — отделить работу от churn НЕ УДАЛОСЬ, "
                                    f"файлов в скорлупе: {len(rels)}")
            continue
        if tree is None:
            row["unchecked"].append(why_tree)
            continue

        work = [r for r in rels if not is_churn(r)]
        row["churn"] = len(rels) - len(work)
        row["files"] = len(work)
        if not work:
            continue

        # Хеши считаем ПАКЕТНО и в главном дереве: объектная база у worktree общая, а в самой
        # скорлупе git не работает по условию задачи.
        rc, out, err = git(root, "hash-object", "--stdin-paths",
                           stdin="\n".join(str(Path(d["path"]) / r) for r in work) + "\n")
        shas = out.split()
        if rc != 0 or len(shas) != len(work):
            row["unchecked"].append(
                f"`git hash-object` по скорлупе не отработал (rc={rc}, "
                f"хешей {len(shas)} на {len(work)} файлов): {err.strip()[:160]!r} — "
                "содержимое скорлупы НЕ ИЗМЕРЕНО")
            continue

        unknown = []                     # расходится с базой ⇒ спросить объектную базу
        for rel, sha in zip(work, shas):
            if tree.get(rel) == sha:
                row["delivered"] += 1
            else:
                unknown.append((rel, sha))
        if not unknown:
            continue

        rc, out, err = git(root, "cat-file", "--batch-check",
                           stdin="\n".join(sha for _rel, sha in unknown) + "\n")
        verdicts = out.splitlines()
        if rc != 0 or len(verdicts) != len(unknown):
            row["unchecked"].append(
                f"`git cat-file --batch-check` не отработал (rc={rc}, "
                f"ответов {len(verdicts)} на {len(unknown)} блобов): {err.strip()[:160]!r} — "
                f"известны ли репозиторию {len(unknown)} расходящ(ийся/ихся) файл(ов), "
                "НЕ ИЗМЕРЕНО")
            continue

        for (rel, sha), verdict in zip(unknown, verdicts):
            parts = verdict.split()
            if len(parts) >= 2 and parts[1] == "blob":
                row["stale"] += 1        # блоб известен ⇒ старая копия, поднимать нечего
            elif len(parts) >= 2 and parts[1] == "missing":
                row["undelivered"].append({"path": rel, "sha": sha,
                                           "on_base": rel in tree})
            else:
                row["unchecked"].append(
                    f"{rel}: `cat-file --batch-check` ответил {verdict.strip()[:80]!r} — "
                    "ни 'blob', ни 'missing'; известен ли блоб репозиторию, НЕ ИЗМЕРЕНО")
    return rows


def collect_diff_sets(base_ref, checkouts, git=_git):
    """{чекаут: множество путей с НЕЗАКОММИЧЕННОЙ работой, которой нет на базе}.

    Пересечение двух множеств, по два вызова git на чекаут:
    - ``diff --name-only HEAD`` — что в этом дереве изменено руками (собственно работа
      сессии: пуш идёт прямо в origin через API, локально работа так и остаётся правкой);
    - ``diff --name-only <base>`` — что расходится с origin.

    Пересечение обязательно: заброшенный worktree стоит на СТАРОМ коммите и расходится с
    origin в сотнях файлов, к которым никто не притрагивался. Без пересечения живой прогон
    дал 45 находок на 12 записях — почти все ложные (измерено 30.07).

    Новые файлы, не попавшие в индекс, `git diff` не покажет — но их и нет на базе,
    так что они ловятся проверкой `cat-file` как ``absent``."""
    sets, failed = {}, []
    for loc in checkouts:
        rc, dirty, err = git(loc, "-c", "core.quotepath=false", "diff", "--name-only", "HEAD")
        if rc != 0:
            failed.append(f"{loc}: `git diff HEAD` rc={rc} {err.strip()[:120]!r}")
            continue
        rc, vs_base, err = git(loc, "-c", "core.quotepath=false", "diff", "--name-only", base_ref)
        if rc != 0:
            failed.append(f"{loc}: `git diff {base_ref}` rc={rc} {err.strip()[:120]!r}")
            continue
        sets[str(loc)] = ({ln for ln in dirty.split("\n") if ln}
                          & {ln for ln in vs_base.split("\n") if ln})
    return sets, failed


# ── НЕобъявленное расхождение: пятое вместилище недоставленного ──────────────
#
# Пути, которые пачкает САМ прогон тестов, а не работа сессии. Правило уборщика
# (`churn_rule`) знает `data/` целиком, но из `spa_core/data/` — ровно ДВА файла поимённо,
# и это не недосмотр: по этому правилу уборщик решает, снимать ли дерево, и расширять его
# «заодно» значит менять ЧУЖОЙ вердикт (#283 — уборщик судит о доставленности). Поэтому
# у сканера свой список, ЗАКРЫТЫЙ и поимённый.
#
# Замер #316 (карточка `agent-test-run-dirties-tracked-fixtures`): класс «прогон перезаписывает
# tracked-фикстуры» — 81 путь (`data/` 80 + `spa.db`), и в живом прогоне #335 именно
# `spa_core/data/*_log.json` дали 65 из 145 кандидатов в семи деревьях, включая ДВА КОНТРОЛЬНЫХ
# дерева, где работы не было ни одной строки по построению. Отсеянное СЧИТАЕТСЯ и печатается:
# разница между «не считаем» и «не видим» обязана быть видна в самом отчёте.
TEST_STATE_PREFIXES = ("spa_core/data/",)

# Потолок хеширования. Выше него содержимое с базой не сверяется — но вердикт по файлу всё
# равно выносится, из более дешёвого источника (есть ли ИМЯ на базе). См. `oversized` в
# `unannounced_divergence_scan`: замер #335 — три архива резерва в прод-дереве (0.2 + 0.6 +
# 1.26 ГБ) стоили шагу 0a +29 с процессорного времени каждый прогон.
HASH_SIZE_CEILING = 64 * 1024 * 1024


def declared_rel_paths(entries, checkouts=()):
    """Множество путей (относительно корня дерева), объявленных ХОТЬ КЕМ-ТО в журнале.

    Сканер ищет расхождение, которого НИКТО не объявлял, — значит вычитать надо объявления
    ВСЕХ сессий, а не только той, чьё это дерево: объявленный путь уже разбирается основным
    отчётом (`file_state` называет там КАЖДОЕ дерево, где он расходится), и вторая строка о
    тех же байтах была бы не находкой, а эхом.

    **Корень отрезается по СПИСКУ известных деревьев, а не по догадке.** `tree_of_path` выводит
    корень из формы пути — по первому компоненту, который является каталогом репо
    (`spa_core/`, `docs/`, …), — и для файла В КОРНЕ дерева (`repo/in_flight.py`) не даёт
    ничего: отрезать нечего, и путь остался бы абсолютным, то есть с относительным именем
    кандидата не совпал бы никогда. Замер #335: на этом покраснели 10 существующих тестов
    шага 0a — объявленный `in_flight.py` объявлялся заново как «никем не объявленный».
    Точное совпадение с корнем чекаута такой формы не имеет и потому надёжнее; `tree_of_path`
    остаётся ЗАПАСНЫМ — им читаются объявления СНЯТЫХ деревьев, которых в списке уже нет.

    Оба написания корня (`/tmp` и `/private/tmp`) приводятся к одному `_normalize_tree`.
    Путь, из которого корень не читается ничем, берётся как есть: объявление относительным
    путём в журнале встречается, и молча терять такую строку значило бы сузить вычитание,
    то есть завести ложную находку."""
    roots = sorted({r for r in (_normalize_tree(str(c)) for c in (checkouts or ())) if r},
                   key=len, reverse=True)
    declared = set()
    for entry in entries or ():
        for f in (entry or {}).get("files") or ():
            raw = _normalize_tree(str(f))
            if not raw:
                continue
            for root in roots:
                if raw.startswith(root.rstrip("/") + "/"):
                    raw = raw[len(root.rstrip("/")) + 1:]
                    break
            else:
                tree = tree_of_path(f)
                if tree and raw.startswith(tree.rstrip("/") + "/"):
                    raw = raw[len(tree.rstrip("/")) + 1:]
            declared.add(raw.lstrip("/"))
    return declared


def unannounced_divergence_scan(root, base_ref, checkouts, declared, active_trees,
                                diff_sets, git=_git):
    """[строка на рабочее дерево] — что в нём расходится с базой, но НИКЕМ не объявлено.

    **Дефект, который это закрывает** (карточка `inbox-shag-0a-ne-vidit-neobyavlennyi-kod-v-osi`,
    замер цикла #334). Сессия `cycle-72429` умерла между работой и пушем, оставив два дерева.
    Шаг 0a показал из них ТОЛЬКО карточку: сторож сверяет с origin **объявленные пути**, а
    `buttonless_reason.py` (211 строк, новый модуль) и правки двух прод-модулей объявлены не
    были — прямой замер полного вывода дал слово `buttonless_reason` **0 раз при 144 строках
    отчёта**. Работу нашли руками, открыв `git status` в осиротевшем дереве; спасло случайное
    соседство карточки, которую сторож находит ДРУГИМ механизмом (сканом трекеров).

    Это ровно вариант (2) закрытой карточки `agent-claim-without-announce-is-invisible`
    («сканировать worktree на НЕобъявленные расхождения»), осознанно отложенный тогда до
    условия «если сироты всё равно появятся». Условие наступило и ИЗМЕРЕНО.

    **Отсев — четыре ступени, и каждая названа числом в отчёте** (иначе «не считаем» читается
    как «не видим»; порядок отсева выбран по цене — сначала бесплатное, потом git):

    1. дерево ЖИВОЙ сессии — не находка вовсе. Расхождение там норма: сессия работает. Признак
       тот же, что у `#233`, — сессия ПОДТВЕРЖДЁННО активна (`ACTIVE`); «не измерено» активностью
       не считается, то есть направление отсева fail-CLOSED (молчим только по доказательству);
    2. churn уборщика (`churn_rule`) и состояние, которое пишет сам прогон тестов
       (`TEST_STATE_PREFIXES`) — это не работа, а след запуска;
    3. путь, объявленный хоть кем-то, — им занят основной отчёт (`declared_rel_paths`);
    4. содержимое, которое репозиторий ПОМНИТ (`cat-file --batch-check` отвечает `blob`), —
       старая копия или локальный коммит: байты не в одном экземпляре, поднимать нечего.

    Находка — то, что пережило все четыре: байты, которых объектная база репозитория не знает
    ВООБЩЕ. Такая работа существует ровно в одном экземпляре и ровно в этом дереве; снимут
    дерево — и её не станет. Код 1, как у соседних вместилищ (`on_branch`, скорлупа).

    **Ограничение названо, а не замолчано.** Ступень 4 отвечает на «помнит ли репозиторий эти
    байты», а не на «есть ли они на origin/main»: сессия, сделавшая локальный коммит (save-point),
    сюда не попадёт — её блоб известен объектной базе. Это осознанный обмен: спрашивать историю
    origin по каждому пути стоило бы `git log` на файл (в живом замере — сотни вызовов), а класс
    «локальный коммит вместо пуша» держит отдельный сторож уборщика (`reaped_state`).

    **fail-CLOSED не ослаблен.** Любая ступень, которая не отработала (правило churn ·
    `ls-files` дерева · `hash-object` · `cat-file`), даёт `unchecked` и код 2 — «не смог
    измерить» не сворачивается в «поднимать нечего».

    Стоимость ограничена и измерена: два ПАКЕТНЫХ вызова git на дерево-кандидат плюс один
    `ls-files`; деревья живых сессий не стоят ничего. Потолка на число файлов нет намеренно —
    тихо срезанное покрытие читалось бы как «проверено всё»."""
    rows = []
    is_churn, why_churn = churn_rule()
    base_tree, why_tree = _base_tree(root, base_ref, git=git)

    for loc in checkouts:
        tree = _normalize_tree(str(loc))
        row = {"tree": tree, "path": str(loc), "active": tree in (active_trees or ()),
               "candidates": 0, "churn": 0, "test_state": 0, "declared": 0, "gone": 0,
               "by_card_scan": 0, "known": 0, "oversized": [],
               "undelivered": [], "unchecked": []}
        rows.append(row)
        if row["active"]:
            continue                     # дерево живой сессии: расхождение — норма, не находка

        raw = diff_sets.get(str(loc))
        if raw is None:
            # Дерево с базой не сверено — об этом уже сказано отдельной строкой «НЕ ИЗМЕРЕНО»
            # (см. `collect_diff_sets` в build_report). Второй раз тот же факт не заводим,
            # но и молча полным отсутствием находок его не подменяем.
            row["unchecked"].append(
                f"рабочее дерево с {base_ref} не сверено — НЕобъявленное расхождение в нём "
                "НЕ ИЗМЕРЕНО")
            continue

        rc, out, err = git(loc, "-c", "core.quotepath=false",
                           "ls-files", "--others", "--exclude-standard")
        if rc != 0:
            row["unchecked"].append(
                f"`git ls-files --others` rc={rc}: {err.strip()[:160]!r} — новых файлов в "
                "дереве НЕ ИЗМЕРЕНО (именно ими был невидимый модуль 21.08)")
            continue
        untracked = [ln for ln in out.split("\n") if ln]

        cand = sorted(set(raw) | set(untracked))
        row["candidates"] = len(cand)
        if is_churn is None:
            row["unchecked"].append(f"{why_churn} — отделить работу от churn НЕ УДАЛОСЬ, "
                                    f"кандидатов в дереве: {len(cand)}")
            continue
        if base_tree is None:
            row["unchecked"].append(why_tree)
            continue

        work = []
        for rel in cand:
            if is_churn(rel):
                row["churn"] += 1
            elif rel.startswith(TEST_STATE_PREFIXES):
                row["test_state"] += 1
            elif rel.startswith(TRACKER_REL + "/"):
                # Карточками занят СВОЙ раздел (п. 4 шапки, `undelivered_cards`), а расхождением
                # их содержимого — доставка следа ответа владельца (ADR-086). Замер #335: без
                # этой ступени прод-дерево давало 77 строк о карточках из 115, то есть раздел
                # выродился бы в копию соседнего. Убирается ТЕНЬ, а не находка — тот же приём,
                # которым выше снимается «расходятся чужие деревья» при наличии настоящей.
                # Ограничение названо: карточку в ТЕРМИНАЛЬНОМ статусе, которой нет на базе,
                # п. 4 пропускает намеренно, и сюда она теперь тоже не попадёт.
                row["by_card_scan"] += 1
            elif rel in (declared or ()):
                row["declared"] += 1
            else:
                try:
                    size = (Path(loc) / rel).stat().st_size
                except OSError:
                    size = None
                if size is None:
                    # Путь УДАЛЁН в дереве (`git diff HEAD` показывает удаление наравне с
                    # правкой). Байтов, которые существовали бы только здесь, у удаления нет по
                    # построению — содержимое лежит на базе. Считаем и НАЗЫВАЕМ числом, но в
                    # вопрос «что можно потерять вместе с деревом» не берём. Живой замер #335:
                    # без этой ступени `hash-object` падал на первом же удалённом пути
                    # прод-дерева (`rc=128, не удалось открыть файл`) и ВСЁ дерево уходило в
                    # «НЕ ИЗМЕРЕНО» навсегда — необратимое «не измерено» внутри сторожа,
                    # заведённого против него же.
                    row["gone"] += 1
                elif size > HASH_SIZE_CEILING:
                    # Крупный файл не хешируем — и это НЕ тихий потолок: ответ по нему всё равно
                    # даётся, просто из более дешёвого источника. Имени нет на базе ⇒ байты
                    # существуют ровно здесь, и это верно БЕЗ сверки содержимого; имя на базе
                    # есть ⇒ сравнить было нечем, и это честное «не измерено» (код 2).
                    # Замер #335: три архива резерва (0.2 + 0.6 + 1.26 ГБ) стоили +29 с
                    # процессорного времени КАЖДОМУ прогону шага 0a (16.6 с → 49.5 с) ради
                    # вывода, известного заранее.
                    row["oversized"].append({"path": rel, "size": size,
                                             "on_base": rel in base_tree})
                else:
                    work.append(rel)

        for big in row["oversized"]:
            if big["on_base"]:
                row["unchecked"].append(
                    f"{big['path']}: {big['size'] // (1024 * 1024)} МБ — содержимое с {base_ref} "
                    f"НЕ сверялось (потолок хеширования {HASH_SIZE_CEILING // (1024 * 1024)} МБ), "
                    "а имя на базе есть: расходится ли содержимое, НЕ ИЗМЕРЕНО")
            else:
                row["undelivered"].append({"path": big["path"], "sha": None,
                                           "on_base": False, "size": big["size"]})
        if not work:
            continue

        rc, out, err = git(root, "hash-object", "--stdin-paths",
                           stdin="\n".join(str(Path(loc) / r) for r in work) + "\n")
        shas = out.split()
        if rc != 0 or len(shas) != len(work):
            row["unchecked"].append(
                f"`git hash-object` по дереву не отработал (rc={rc}, хешей {len(shas)} "
                f"на {len(work)} файлов): {err.strip()[:160]!r} — содержимое НЕ ИЗМЕРЕНО")
            continue

        rc, out, err = git(root, "cat-file", "--batch-check", stdin="\n".join(shas) + "\n")
        verdicts = out.splitlines()
        if rc != 0 or len(verdicts) != len(work):
            row["unchecked"].append(
                f"`git cat-file --batch-check` не отработал (rc={rc}, ответов "
                f"{len(verdicts)} на {len(work)} блобов): {err.strip()[:160]!r} — известны ли "
                "репозиторию эти файлы, НЕ ИЗМЕРЕНО")
            continue

        for rel, sha, verdict in zip(work, shas, verdicts):
            parts = verdict.split()
            if len(parts) >= 2 and parts[1] == "blob":
                row["known"] += 1        # репозиторий помнит байты ⇒ не единственный экземпляр
            elif len(parts) >= 2 and parts[1] == "missing":
                row["undelivered"].append({"path": rel, "sha": sha,
                                           "on_base": rel in base_tree})
            else:
                row["unchecked"].append(
                    f"{rel}: `cat-file --batch-check` ответил {verdict.strip()[:80]!r} — "
                    "ни 'blob', ни 'missing'; известен ли блоб репозиторию, НЕ ИЗМЕРЕНО")
    return rows


def _blob_sha(path):
    """git-хеш содержимого файла, посчитанный локально (без вызова git)."""
    try:
        data = Path(path).read_bytes()
    except OSError:
        return None
    h = hashlib.sha1()
    h.update(b"blob %d\0" % len(data))
    h.update(data)
    return h.hexdigest()


def origin_blob_history(root, base_ref, rel, git=_git):
    """Все версии (blob-хеши) этого пути в истории базового ref. None — прочитать не удалось."""
    rc, out, _ = git(root, "log", "--format=%H", "--raw", "--no-abbrev", "--no-renames",
                     base_ref, "--", rel)
    if rc != 0:
        return None
    shas = set()
    for line in out.splitlines():
        if line.startswith(":"):
            parts = line.split()
            if len(parts) >= 4:
                shas.add(parts[3])
    return shas


_SPLIT_HINT_RE = re.compile(r"[\s,;]")


def never_existed(rel, root, base_ref, checkouts, git=_git, hist_cache=None):
    """Существовало ли объявленное ИМЯ хоть где-нибудь: (True/False/None, объяснение).

    Вызывается только для путей, которых на базе НЕТ (``ABSENT``). Три независимых источника,
    и «нигде» — это когда молчат все три:

    1. история базового ref для этого пути (``origin_blob_history``) — путь мог быть доставлен
       и затем удалён/переименован уже НА origin; тогда это не пропажа работы;
    2. файловая система КАЖДОГО живого рабочего дерева — там и лежит осиротевшая работа;
    3. (только в объяснении) форма самой строки: пробел/запятая внутри «пути» означает, что
       объявление слепило несколько файлов в одну строку, и такого файла не существует по
       построению — измерено 5 случаев из 38.

    ``None`` — измерить не удалось (``git log`` не отработал): вердикт не выносится, запись
    идёт прежним путём и остаётся находкой. Ослабления тут нет: «нигде» УЖЕ означает, что
    поднимать нечего физически — байтов не существует ни в одном дереве и никогда не было на
    origin. Обратная сторона названа вслух: если сессия создала файл и её дерево УДАЛИЛИ, байты
    и правда исчезли — но об удалённом дереве говорит отдельный, более строгий класс
    «не измерено» (код 2, см. ``resolve_rel``), а сюда попадают пути живых деревьев.
    """
    hist = origin_blob_history(root, base_ref, rel, git=git) if hist_cache is None \
        else hist_cache.setdefault(rel, origin_blob_history(root, base_ref, rel, git=git))
    if hist is None:
        return None, (f"историю {base_ref} для {rel} прочитать не удалось — "
                      "существовало ли имя, НЕ ИЗМЕРЕНО")
    if hist:
        return False, (f"на {base_ref} сейчас нет, но в его истории путь встречался "
                       f"({len(hist)} версий) — это удаление/переименование на origin, "
                       "а не пропажа объявленной работы")
    trees = sorted(str(c) for c in (checkouts or []) if (Path(c) / rel).exists())
    if trees:
        return False, (f"на {base_ref} файла нет, но он ЛЕЖИТ в: {', '.join(trees)} — "
                       "это настоящая недоставленная работа, её надо поднять")
    detail = (f"имени не существует НИГДЕ: на {base_ref} нет, в истории {base_ref} не было "
              f"ни разу, ни в одном из {len(checkouts or [])} рабочих деревьев файла нет")
    if _SPLIT_HINT_RE.search(rel):
        detail += ("; в строке есть пробел/запятая — объявление слепило несколько путей в один, "
                   "такого файла не существует по построению")
    return True, detail


def deleted_on_origin(rel, root, base_ref, checkouts, git=_git, hist_cache=None):
    """Удалён ли объявленный путь НА базе: (True/False/None, объяснение).

    Спрашивается только для путей, которых на базе нет (``ABSENT``), и ДО вопроса «существовало
    ли имя» (``never_existed``): у того первый же источник — история базы, и он обрывает разбор
    выводом «это удаление», не дойдя до деревьев. Из-за этого подсказка «байты ЛЕЖАТ в дереве X»
    при удалённом на origin имени была недостижима по построению — измерено циклом #298 на живом
    журнале (1011 записей): 3 находки из 63 попадали в «НЕ ДОСТАВЛЕНО» с объяснением, которое
    в той же строке отрицало находку.

    ``True`` — удаление на базе, и поднимать нечего:
    1. история пути на базе НЕ пуста — значит имя существовало и было доставлено, а удаление
       есть такая же доставка (пример: корневой `__init__.py`, снятый циклом #297 через
       `github_delete` по решению карточки);
    2. ни в одном живом рабочем дереве под этим именем нет содержимого, хеша которого НЕТ в
       истории этого пути. То есть байтов, которых история базы не помнит, не существует.

    ``False`` с непустым объяснением — п.1 выполнен, п.2 НЕТ: в дереве лежит незнакомое
    содержимое. Это может быть настоящая работа, и находка обязана остаться находкой; объяснение
    называет КАЖДОЕ такое дерево. ``False`` с пустым объяснением — истории нет вовсе, вопрос не
    об этой ветке (дальше спрашивает ``never_existed``).

    ``None`` — историю прочитать не удалось: вердикта нет, находка остаётся (fail-CLOSED, класс
    #226 — fail-OPEN внутри fail-CLOSED-сторожа).

    Хеш содержимого сверяется с историей ровно так же, как в ветке ``stale_copies`` для
    ``DIFFERS``: «содержимое уже было на origin» там уже принято доказательством того, что работа
    не потеряна. Своего допущения здесь не заводится."""
    hist = origin_blob_history(root, base_ref, rel, git=git) if hist_cache is None \
        else hist_cache.setdefault(rel, origin_blob_history(root, base_ref, rel, git=git))
    if hist is None:
        return None, (f"историю {base_ref} для {rel} прочитать не удалось — удаление это на "
                      "origin или пропажа работы, НЕ ИЗМЕРЕНО")
    if not hist:
        return False, ""
    unseen = sorted(str(c) for c in (checkouts or [])
                    if (Path(c) / rel).exists() and (_blob_sha(Path(c) / rel) or "") not in hist)
    if unseen:
        return False, (f"на {base_ref} путь удалён (в истории {len(hist)} версий), НО в "
                       f"{', '.join(unseen)} под этим именем лежит содержимое, которого в истории "
                       "этого пути НЕТ — удалением это не объясняется, поднимать может быть что")
    return True, (f"на {base_ref} файла нет, но в его истории путь встречался ({len(hist)} "
                  "версий) — имя существовало и было доставлено, а затем удалено/переименовано "
                  f"НА {base_ref}: удаление — тоже доставка. Ни в одном из "
                  f"{len(checkouts or [])} рабочих деревьев нет содержимого, которого не было бы "
                  "в истории этого пути. ПОДНИМАТЬ НЕЧЕГО")


def repo_refuses(rel, root, git=_git):
    """Берёт ли репозиторий этот путь ВООБЩЕ: (True/False/None, объяснение с ПРАВИЛОМ).

    Спрашивается САМ git (`check-ignore`), а не наш список каталогов: правило живёт в
    `.gitignore`, менять его будут без оглядки на этот сторож, и зашитая сюда копия правила
    разошлась бы молча.

    Семантика `git check-ignore` ровно та, что нужна, и это ИЗМЕРЕНО, а не вычитано:
    - rc 0 — путь игнорируется, в stdout лежит правило (`.gitignore:48:data/**/*.jsonl`);
    - rc 1 — не игнорируется, **включая ОТСЛЕЖИВАЕМЫЕ файлы**: `data/audit_trail.jsonl`
      подходит под тот же самый шаблон `data/**/*.jsonl`, но лежит в индексе, и git отвечает
      «не игнорируется». То есть однажды доставленный файл этой веткой прощён не будет —
      проверка сужена индексом, а не нашим мнением;
    - иное (128, git недоступен) — `None`: вердикта нет.

    `None` НЕ гасит находку: непонятность в fail-CLOSED-стороже обязана оставаться находкой,
    а не превращаться в тишину (класс #226 — fail-OPEN внутри fail-CLOSED).

    ГРАНИЦА НАЗВАНА ЗАРАНЕЕ, а не найдена потом: спрашивается индекс ГЛАВНОГО дерева (`root`),
    как и вся остальная сверка. Если сессия внесла игнорируемый путь силой в индекс СВОЕГО
    `/tmp`-дерева и умерла до пуша, здесь он всё равно будет прощён. Ловить это правильно не
    здесь (у сторожа один `root` по построению), а тем, что доставку такого пути объявляют
    явно; случая в живом журнале нет, и выдумывать под него ветку — значит усложнять сторож
    ради ненаблюдавшейся аварии.
    """
    rc, out, err = git(root, "check-ignore", "--verbose", "--", rel)
    if rc == 0:
        rule = (out.splitlines() or [""])[0].split("\t")[0].strip()
        return True, ("этот путь НЕ БЕРЁТ САМ РЕПОЗИТОРИЙ по своему правилу "
                      f"[{rule or '.gitignore'}] — доставлять его нечем и не требуется: "
                      "это рабочее состояние, а не потерянная работа")
    if rc == 1:
        return False, ""
    return None, (f"берёт ли репозиторий этот путь, НЕ ИЗМЕРЕНО: git check-ignore rc={rc} "
                  f"{err.strip()[:120]!r}")


def remote_branch_refs(root, base_ref, git=_git):
    """Удалённые ветки репозитория, кроме базовой: ([{ref, tip}], ошибка|None).

    Читаются ЛОКАЛЬНЫЕ `refs/remotes/*` — `git fetch` здесь не вызывается, как и во всей
    остальной сверке (без сети). Отсюда та же осознанная граница, что у базового ref: устаревшая
    локальная копия ветки даёт ЛОЖНУЮ находку, а не ложную тишину.
    """
    rc, out, err = git(root, "for-each-ref",
                       "--format=%(refname:short)\t%(committerdate:iso8601-strict)",
                       "refs/remotes/")
    if rc != 0:
        return None, (f"список удалённых веток НЕ ПРОЧИТАН (git for-each-ref rc={rc} "
                      f"{err.strip()[:120]!r}) — лежит ли недоставленное на ветке, не измерено")
    rows = []
    for line in out.splitlines():
        ref, _, tip = line.partition("\t")
        ref = ref.strip()
        if not ref or ref in _NOT_A_BRANCH or ref == base_ref:
            continue
        rows.append({"ref": ref, "tip": tip.strip()})
    return rows, None


def _tree_paths(ref, root, git=_git):
    """Все пути дерева ref'а, либо None — прочитать не удалось."""
    rc, out, _ = git(root, "ls-tree", "-r", "--name-only", ref)
    if rc != 0:
        return None
    return {line for line in out.splitlines() if line}


def branch_scan(root, base_ref, git=_git):
    """Что лежит на удалённых ветках и чего из этого нет на базе: (строки, «не измерено»).

    Одна строка на ветку: ``ref`` · ``tip`` (дата последнего коммита) · ``ahead`` (коммитов
    сверх базы) · ``files`` (полное дерево ветки, в отчёт НЕ кладётся) · ``unique``
    (пути, которых на базе нет ВООБЩЕ) · ``owner_work`` / ``code`` (разбиение `unique`).

    **Влитая ветка пропускается по измерению, а не по имени:** `merge-base --is-ancestor` —
    ветка, целиком лежащая в истории базы, недоставленного не держит по построению. Так же
    отсеивается и сама база, когда `--base` задан не именем, а sha.

    Стоимость измерена, а не оценена: 14 веток этого репозитория — 0.34 с (`ls-tree -r` на
    каждую + один на базу). Шаг 0a гоняется раз в цикл, это не тот порядок, ради которого
    стоит заводить кэш и его протухание.
    """
    unmeasured = []
    refs, err = remote_branch_refs(root, base_ref, git=git)
    if refs is None:
        return None, [err]
    base_files = _tree_paths(base_ref, root, git=git)
    if base_files is None:
        return None, [f"дерево базы {base_ref} НЕ ПРОЧИТАНО (git ls-tree) — сверка веток с базой "
                      "не выполнена"]
    rows = []
    for row in refs:
        ref = row["ref"]
        rc, _, _ = git(root, "merge-base", "--is-ancestor", ref, base_ref)
        if rc == 0:                              # ветка целиком в истории базы
            continue
        if rc != 1:                              # ни «влита», ни «не влита» — это не измерение
            unmeasured.append(f"ветка {ref}: влита ли она в {base_ref}, НЕ ИЗМЕРЕНО "
                              f"(git merge-base --is-ancestor rc={rc})")
            continue
        files = _tree_paths(ref, root, git=git)
        if files is None:
            unmeasured.append(f"ветка {ref}: дерево НЕ ПРОЧИТАНО (git ls-tree) — что на ней "
                              "лежит, не измерено")
            continue
        rc, ahead, _ = git(root, "rev-list", "--count", f"{base_ref}..{ref}")
        unique = sorted(files - base_files)
        owner_work = [p for p in unique if p.startswith(OWNER_WORK_PREFIXES)]
        touch, touch_unmeasured = owner_work_last_touch(root, base_ref, ref, owner_work, git=git)
        if touch_unmeasured:
            unmeasured.append(touch_unmeasured)
        rows.append({
            "ref": ref,
            "tip": row["tip"],
            "ahead": int(ahead.strip()) if rc == 0 and ahead.strip().isdigit() else None,
            "files": files,
            "unique": unique,
            "owner_work": owner_work,
            "code": [p for p in unique if p.startswith(CODE_PREFIXES)],
            "owner_touch": touch,
        })
    return rows, unmeasured


def owner_work_last_touch(root, base_ref, ref, owner_work, git=_git):
    """Когда решения и карточки ветки трогали в последний раз: (замер|None, «не измерено»|None).

    Замер — ``{"date", "sha", "commits_above"}``: дата последнего коммита ветки, который трогает
    ХОТЯ БЫ ОДИН из путей `owner_work`, и число коммитов, лежащих поверх него и не трогающих
    НИ ОДНОГО из них.

    **Почему спрашивается именно это, а не «свежий ли у ветки коммит».** Вершину ветки двигает
    и merge НАШЕЙ ЖЕ базы: облачная сессия подмерживает `origin/main` сама, и `committerdate`
    вершины после этого говорит о нашем цикле, а не о работе автора. 21.08 у
    `origin/claude/unreadable-description-ltyucb` вершина была свежестью 24 минуты, а последний
    коммит АВТОРА — шестичасовой давности: три merge базы поверх. Шаг 0a печатал первую дату, и
    читалась она как «работа идёт». Это не косметика: карточка разбора ветки разводит по этой
    дате два ПРОТИВОПОЛОЖНЫХ действия — «не трогать живую работу» и «разобрать брошенную», —
    а ветка, которую мержат с базой раз в час, выглядит вечно живой, и потерянные на ней решения
    владельца не поднимаются НИКОГДА. Fail-OPEN внутри fail-CLOSED-сторожа (класс #226).

    **Почему признак — пути, а не `--no-merges`.** Merge МОЖЕТ нести содержимое автора (разрешение
    конфликта), и `--no-merges` объявил бы такую ветку замороженной — то есть позвал бы разбирать
    ЖИВУЮ работу, а это ровно та разрушительная сторона, от которой предостерегает карточка.
    Спрашивается поэтому не «какой природы коммит», а «трогал ли он предмет находки»: решения и
    карточки, которых на базе нет ВООБЩЕ. Ответ на этот вопрос ТОЧЕН — коммит либо есть в
    ``rev-list -- <пути>``, либо его там нет, — и он же есть ровно тот вход, по которому решают
    судьбу ветки: если карточки владельца не двигались, они брошены независимо от того, чем занят
    автор в других файлах.

    Ветка без решений и карточек замера не получает (`None`): предмета нет — нечего и датировать.
    """
    if not owner_work:
        return None, None
    rc, out, err = git(root, "rev-list", "--max-count=1", "--format=%H%x09%cI",
                       f"{base_ref}..{ref}", "--", *owner_work)
    if rc != 0:
        return None, (f"ветка {ref}: когда в последний раз трогали её решения и карточки, "
                      f"НЕ ИЗМЕРЕНО (git rev-list rc={rc} {err.strip()[:120]!r}) — свежесть "
                      "вершины про них не говорит, а другого основания нет")
    # `rev-list --format` печатает строку «commit <sha>» и следом саму строку формата.
    payload = [ln for ln in out.splitlines() if not ln.startswith("commit ")]
    if not payload:
        return None, None
    sha, _, date = payload[0].partition("\t")
    sha, date = sha.strip(), date.strip()
    if not sha or not date:
        return None, (f"ветка {ref}: дату последнего касания решений и карточек прочитать не "
                      f"удалось (git rev-list вернул {payload[0].strip()[:80]!r}) — НЕ ИЗМЕРЕНО")
    # `^sha ^base_ref`, а не `sha..ref`: merge базы втягивает в ветку и коммиты НАШЕГО ЖЕ main,
    # и без второго исключения счёт мерил бы наш цикл вместо работы автора (живой замер 21.08:
    # 16 против 2). Число обязано отвечать ровно на «сколько автор сделал поверх, не тронув
    # предмет находки».
    rc, above, _ = git(root, "rev-list", "--count", ref, f"^{sha}", f"^{base_ref}")
    if rc != 0 or not above.strip().isdigit():
        return None, (f"ветка {ref}: сколько коммитов лежит поверх последнего касания её решений "
                      f"и карточек, НЕ ИЗМЕРЕНО (git rev-list --count rc={rc})")
    return {"date": date, "sha": sha, "commits_above": int(above.strip())}, None


def paths_on_branches(rel, branches):
    """Ветки, на которых ЛЕЖИТ этот путь. `branches is None` ⇒ не измерено ⇒ пустой список.

    Вопрос задаётся ТОЛЬКО путям, которых нет ни на базе, ни в её истории, ни в одном рабочем
    дереве (см. `never_existed`). Ответ «лежит на ветке X» точнее и полезнее, чем «нигде»:
    поднимать есть что, и место названо.
    """
    return [b["ref"] for b in (branches or []) if rel in b["files"]]


def delivered_by_session(session, entries, root, base_ref, git=_git, diff_sets=None, limit=6):
    """Что ЭТА ЖЕ сессия объявляла и что из объявленного лежит на базе — подсказка «переименовано?».

    Закрывающее объявление (``card_state == "done"``) перечисляет фактически доставленное,
    поэтому идёт первым. Утверждения «это переименование» здесь НЕ делается: доказать связь
    имён нечем, и выдумывать её — тот же fail-OPEN, что чинили в #226. Печатается факт:
    объявлено X, на базе лежит Y — сверьте.
    """
    mine = [e for e in entries if e.get("session") == session]
    mine.sort(key=lambda e: 0 if (e.get("card_state") == "done") else 1)
    found, seen = [], set()
    for entry in mine:
        for raw in entry.get("files") or []:
            rel, err = resolve_rel(raw, root, git=git)
            if rel is None or rel in seen:
                continue
            seen.add(rel)
            st, _, _ = file_state(root, base_ref, rel, git=git, diff_sets=diff_sets)
            if st == DELIVERED:
                found.append(rel)
                if len(found) >= limit:
                    return found
    return found


def file_state(root, base_ref, rel, git=_git, diff_sets=None):
    """(состояние, объяснение, список рабочих деревьев с расхождением)."""
    rc, _, err = git(root, "cat-file", "-e", f"{base_ref}:{rel}")
    if rc != 0:
        local = "" if (Path(root) / rel).exists() else "; локально файла тоже нет"
        return ABSENT, f"на {base_ref} файла нет{local}", []

    differing = sorted(loc for loc, paths in (diff_sets or {}).items() if rel in paths)
    if differing:
        return (DIFFERS,
                f"есть на {base_ref}, но содержимое отличается в: {', '.join(differing)}",
                differing)
    return DELIVERED, f"совпадает с {base_ref} во всех рабочих деревьях", []


# ── карточки: «создана → доставлена?» ────────────────────────────────────────
#
# Второй вопрос, НЕ сводимый к первому. Первый спрашивает «объявленное доехало?» и по
# построению видит только то, что кто-то объявил. Карточка, созданная ПОСРЕДИ цикла, не
# объявляется никогда: `orchestrator_queue.py create` пишет её в трекер ТОГО дерева, чья
# копия скрипта запущена (измерено циклом #140: копия из worktree пишет в worktree, копия
# из хост-дерева — в хост-дерево, cwd не влияет), а списки файлов на пуш собираются по
# рабочему дереву цикла. Живой случай: `inbox-audit-prigodnosti-ne-videl-186-modulei-t`
# создана 19:34, уже ПОСЛЕ финального объявления цикла #138 в 19:18 («ДОСТАВЛЕН» — честного,
# он доставил ровно то, что было в его дереве); на origin её не было, она лежала
# неотслеживаемой в хост-дереве и нашлась случайной сверкой имён, а не сторожем.
#
# Свежести здесь НЕТ намеренно (в отличие от объявлений): шаг 0a исполняется в НАЧАЛЕ цикла,
# и карточки этого цикла в этот момент ещё не существует ⇒ любая находка — про прошлые
# циклы. Возраст файла в находку выводится, чтобы своя минуту назад созданная карточка
# опознавалась глазом, но тишиной она не покупается (fail-CLOSED).

TRACKER_REL = "nimbalyst-local/tracker"
BOARD_NAME = "_BOARD.md"          # производный индекс, пересобирается целиком — не карточка
# Отработанная карточка. Список шире набора шага 0b (там он про снятие захвата, здесь — про
# доставку): карточку, осознанно закрытую без доставки, находкой звать не за что.
CARD_TERMINAL_STATUSES = {"done", "ingested", "owner-done", "rejected", "archived"}


def card_status(text: str):
    """Значение top-level ``status:`` из frontmatter карточки, либо None.

    Свой минимальный разбор (как в `build_tracker_board.py` / `check_card_claim.py`):
    скрипт остаётся stdlib-only и не тянет `spa_core`. Читается ТОЛЬКО блок frontmatter —
    строка `status:` в теле карточки статусом не является."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None                      # без frontmatter статуса нет — и это не «терминальная»
    for raw in lines[1:]:
        if raw.strip() == "---":
            break
        if not raw.strip() or raw[:1].isspace():
            continue
        key, sep, val = raw.partition(":")
        if sep and key.strip() == "status":
            v = val.strip()
            if len(v) >= 2 and v[0] == v[-1] and v[0] in ("'", '"'):
                v = v[1:-1]
            return v or None
    return None


def base_card_names(root, base_ref, git=_git):
    """(множество имён файлов карточек на базовом ref, None) либо (None, причина).

    Пустой перечень — тоже отказ, а не «на базе карточек нет»: в норме их сотни, и пустое
    множество сделало бы находкой КАЖДУЮ карточку (fail-CLOSED в обе стороны)."""
    rc, out, err = git(root, "ls-tree", "-r", "--name-only", base_ref, "--", f"{TRACKER_REL}/")
    if rc != 0:
        return None, (f"`git ls-tree {base_ref} -- {TRACKER_REL}/` rc={rc} "
                      f"{err.strip()[:160]!r} — состав карточек на базе НЕ измерен")
    names = {ln.rsplit("/", 1)[-1] for ln in out.splitlines() if ln.strip().endswith(".md")}
    if not names:
        return None, (f"на {base_ref} в {TRACKER_REL}/ не нашлось ни одной карточки — "
                      "так не бывает в норме; сверка карточек НЕ выполнена (иначе находкой "
                      "стала бы каждая карточка)")
    return names, None


