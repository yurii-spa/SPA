def _stamp(iso):
    """Отметка времени до МИНУТ: «2026-08-21 01:56». Непонятный вход отдаётся как есть.

    До дня не обрезаем осознанно: у ветки, которую мержат несколько раз в сутки, весь разрыв
    между вершиной и последним касанием предмета — внутрисуточный (21.08: 05:40 против 01:56),
    и «2026-08-21» с обеих сторон читалось бы как «разрыва нет».
    """
    s = str(iso or "")
    return s[:16].replace("T", " ") if len(s) >= 16 and s[10:11] == "T" else s


def render(report) -> str:
    out = []
    base = report["base_ref"]
    sha = (report["base_sha"] or "?")[:9]
    out.append(f"Сверка «объявил → доставил» против {base} ({sha}); "
               f"записей: {report['entries_checked']}, "
               f"подтверждённо активных сессий: {report['sessions_active']}, "
               f"свежих (окно {report.get('grace_hours')}ч): {len(report.get('fresh') or [])}, "
               f"проверено: {report['sessions_checked']}")

    def _findings_block(items):
        for f in items:
            mark = "отсутствует" if f["state"] == ABSENT else "отличается"
            out.append(f"  [{mark}] {f['path']}")
            out.append(f"      сессия {f['session']} ({f['ts']}): {f['session_state']}")
            out.append(f"      {f['detail']}")
            if f.get("also_declared_by"):
                out.append(f"      тот же файл объявляли ещё: {', '.join(f['also_declared_by'])}")
            if f["summary"]:
                out.append(f"      объявляла: {f['summary']}")

    # Сироты в окне — первыми: работа свежая, дерево ещё на диске, поднять её дешевле всего.
    # «Только чужие деревья» выведено из обоих разделов в свой: это НЕ потерянная работа
    # объявившей сессии, и держать её среди «подними руками» значит учить пролистывать раздел.
    foreign = [f for f in report["findings"] if f.get("foreign_only")]
    orphans = [f for f in report["findings"]
               if f.get("within_grace") and not f.get("foreign_only")]
    expired = [f for f in report["findings"]
               if not f.get("within_grace") and not f.get("foreign_only")]

    if orphans:
        out.append("")
        out.append(f"🕳  ОСИРОТЕЛО, НО ОКНО НЕ ИСТЕКЛО ({len(orphans)}) — объявлено недавно, "
                   f"объявленный долгоживущий процесс сессии завершился, а на {base} этого нет "
                   "(ждать больше некого — сверить руками и поднять):")
        _findings_block(orphans)

    if expired:
        out.append("")
        out.append(f"⚠️  НЕ ДОСТАВЛЕНО ({len(expired)}) — объявлено давно, "
                   f"активность не подтверждена, а объявленного на {base} нет:")
        _findings_block(expired)

    if foreign:
        out.append("")
        out.append(f"🌲 РАСХОЖДЕНИЕ ТОЛЬКО В ЧУЖИХ ДЕРЕВЬЯХ ({len(foreign)}) — объявившая сессия "
                   f"своё доставила (её дерево совпадает с {base} или его историей), а байты, "
                   f"которых на {base} не было, лежат в деревьях ДРУГИХ сессий. Это не потерянная "
                   "работа объявившего; чья она — не измерено, и находкой остаётся:")
        _findings_block(foreign)

    if report.get("on_branch"):
        out.append("")
        out.append(f"🌿 ОБЪЯВЛЕНО И ЛЕЖИТ НА ВЕТКЕ ({len(report['on_branch'])}) — "
                   f"на {base} этого нет, в рабочих деревьях нет, но работа не пропала: она "
                   "уехала на удалённую ветку. Поднимать есть что, место названо:")
        for f in report["on_branch"]:
            out.append(f"  [на ветке] {f['path']} → {', '.join(f.get('branches') or [])}")
            out.append(f"      сессия {f['session']} ({f['ts']}): {f['session_state']}")
            out.append(f"      {f['detail']}")
            if f.get("also_declared_by"):
                out.append(f"      то же имя объявляли ещё: {', '.join(f['also_declared_by'])}")
            if f["summary"]:
                out.append(f"      объявляла: {f['summary']}")

    if report.get("branches_with_owner_work"):
        rows = report["branches_with_owner_work"]
        out.append("")
        out.append(f"🌿 НА ВЕТКЕ ЛЕЖАТ РЕШЕНИЯ И КАРТОЧКИ ВЛАДЕЛЬЦА ({len(rows)}) — этих файлов "
                   f"на {base} нет ВООБЩЕ. Код на ветке находкой не считается (обычная "
                   "параллельная работа), а решение или карточка означают, что очередь "
                   "владельца потеряла пункт: восстановить его нечем, кроме самой ветки:")
        for b in rows:
            out.append(f"  [ветка] {b['ref']} (последний коммит {_stamp(b['tip'])}, "
                       f"коммитов сверх базы: {b['ahead']})")
            touch = b.get("owner_touch")
            if touch and touch["commits_above"] > 0:
                # Вершину двигает и merge НАШЕЙ ЖЕ базы: без этой строки свежая дата вершины
                # читается как «работа идёт» и уводит разбор ветки в противоположное действие.
                # Обе даты печатаются С МИНУТАМИ намеренно: у ветки, которую мержат несколько раз
                # в сутки, весь разрыв внутрисуточный, и обрезка до дня стёрла бы ровно его.
                out.append(f"      решения и карточки этой ветки не трогали с "
                           f"{_stamp(touch['date'])} — поверх лежат {touch['commits_above']} "
                           f"коммит(ов) автора, ни один их не касается: свежесть ВЕРШИНЫ про "
                           f"предмет находки НЕ ГОВОРИТ, судить о судьбе ветки по ней нельзя")
            out.append(f"      уникальных путей: {b['unique']} · решений: {len(b['decisions'])} "
                       f"· карточек: {len(b['cards'])} · кода: {b['code']}")
            for p in (b["decisions"] + b["cards"])[:8]:
                out.append(f"        • {p}")
            hidden = len(b["decisions"]) + len(b["cards"]) - 8
            if hidden > 0:
                out.append(f"        … и ещё {hidden} (полный список: "
                           f"git diff --name-only {base} {b['ref']})")

    if report.get("branches_code_only"):
        rows = report["branches_code_only"]
        out.append("")
        out.append("🌿 ветки с уникальным КОДОМ, но без решений и карточек "
                   f"({len(rows)}) — НЕ находки (признак выбран замером, см. шапку), названы "
                   "числами, чтобы «не считаем» не читалось как «не видим»: "
                   + " · ".join(f"{b['ref']} (уник. {b['unique']}, кода {b['code']}, "
                                f"{b['tip'][:10]})" for b in rows))

    if report.get("nowhere"):
        out.append("")
        out.append(f"🏷  ОБЪЯВЛЕНО, НО НЕ СУЩЕСТВУЕТ НИГДЕ ({len(report['nowhere'])}) — "
                   f"ни на {base}, ни в его истории, ни в одном рабочем дереве. "
                   "ПОДНИМАТЬ НЕЧЕГО: имя объявлено авансом, файла под ним не было. "
                   "Проверьте, не вышел ли результат под другим именем:")
        for f in report["nowhere"]:
            out.append(f"  [нигде] {f['path']}")
            out.append(f"      сессия {f['session']} ({f['ts']}): {f['session_state']}")
            out.append(f"      {f['detail']}")
            if f.get("delivered_instead"):
                out.append("      эта же сессия объявляла и ДОСТАВИЛА: "
                           + ", ".join(f["delivered_instead"]))
            if f.get("also_declared_by"):
                out.append(f"      то же имя объявляли ещё: {', '.join(f['also_declared_by'])}")
            if f["summary"]:
                out.append(f"      объявляла: {f['summary']}")

    if report.get("card_findings"):
        out.append("")
        out.append(f"🗂  КАРТОЧКИ НЕ ДОСТАВЛЕНЫ ({len(report['card_findings'])}) — есть в рабочем "
                   f"дереве в НЕтерминальном статусе, на {base} их нет:")
        for c in report["card_findings"]:
            out.append(f"  [{c['status']}] {c['card']}")
            out.append(f"      {c['reason']}; в деревьях: {', '.join(c['trees'])}")
            if c.get("age_hours") is not None:
                out.append(f"      файлу {c['age_hours']}ч — если это карточка ЭТОГО цикла, "
                           "добавь её в список пуша")

    if report["unmeasured"]:
        out.append("")
        out.append(f"❓ НЕ ИЗМЕРЕНО ({len(report['unmeasured'])}) — молчаливого «всё в порядке» "
                   "здесь не будет:")
        for u in report["unmeasured"]:
            if u.get("tree_gone"):
                continue                      # свой раздел ниже: одной строкой на дерево
            where = f" · {u['path']}" if u.get("path") else ""
            out.append(f"  - {u.get('session') or '-'}{where}: {u['reason']}")
        for g in group_tree_gone(report["unmeasured"]):
            out.append(f"  - {g['session'] or '-'} · {g['common_root']}: снятое БЕЗ квитанции "
                       f"рабочее дерево, объявленных путей {g['count']} "
                       f"({', '.join(g['sample'])}{'…' if g['count'] > len(g['sample']) else ''})")
            out.append("      измерить нечем и уже не станет: байтов нет ни в дереве, ни в "
                       "архиве — ПОДНИМАТЬ НЕЧЕГО, разбирать эти строки следующим циклом "
                       "бессмысленно. Вердикт остаётся «не измерено» (код 2): доставили ли "
                       "работу, из снятого дерева не узнать.")
            # Полное имя файла здесь снова можно (цикл #278): храповик неподключённых
            # скриптов (`spa_core/tests/_unwired.py`) научился отличать путь-в-ЗАПУСКЕ от
            # пути-в-СООБЩЕНИИ, и упоминание в этой подсказке больше не объявляет уборщик
            # «подключённым». До #278 расширение приходилось опускать — иначе настоящая
            # сирота молча снималась с учёта одной строкой текста.
            out.append("      Дефект здесь — САМО снятие: убирать за собой обязан "
                       "`scripts/reap_stale_worktrees.py --worktree <путь> --apply` "
                       "(меряет, архивирует, оставляет квитанцию; протокол §3.4). "
                       "Снятое руками неизмеримо навсегда.")

    rows_by_path = {r["path"]: r for r in (report.get("orphan_registrations") or [])}
    orphan_hits = [r for r in rows_by_path.values() if r["undelivered"]]

    if orphan_hits:
        out.append("")
        total = sum(len(r["undelivered"]) for r in orphan_hits)
        out.append(f"🥚 В ОСИРОТЕВШЕЙ РЕГИСТРАЦИИ ЛЕЖИТ НЕДОСТАВЛЕННОЕ ({len(orphan_hits)} "
                   f"скорлуп(а/ы), файлов: {total}) — каталог рабочего дерева остался, "
                   "git-привязка мертва, и содержимого этих файлов НЕТ в объектной базе "
                   "репозитория ВООБЩЕ: ни на базе, ни в одном коммите. Байты существуют "
                   "ровно здесь. `git worktree prune` сотрёт последний указатель на них:")
        for r in orphan_hits:
            out.append(f"  [скорлупа] {r['path']}")
            out.append(f"      файлов вне churn: {r['files']} · совпадает с {base}: "
                       f"{r['delivered']} · старых копий (блоб известен репо): {r['stale']} · "
                       f"НЕТ В РЕПО: {len(r['undelivered'])}")
            for f in r["undelivered"][:20]:
                where = f"есть на {base} под другим содержимым" if f["on_base"] \
                    else f"имени нет и на {base}"
                out.append(f"      • {f['path']} ({f['sha'][:9]}, {where})")
            if len(r["undelivered"]) > 20:
                out.append(f"      … и ещё {len(r['undelivered']) - 20} "
                           f"(полный список — `--json`, ключ `orphan_registrations`)")

    unann = report.get("unannounced") or []
    unann_hits = [r for r in unann if r["undelivered"]]
    if unann_hits:
        out.append("")
        total = sum(len(r["undelivered"]) for r in unann_hits)
        out.append(f"🙈 РАСХОЖДЕНИЕ, КОТОРОГО НИКТО НЕ ОБЪЯВЛЯЛ ({len(unann_hits)} дерев(о/а), "
                   f"файлов: {total}) — работа лежит в рабочем дереве, объявления на неё нет НИ "
                   "ОДНОГО, и содержимого этих файлов НЕТ в объектной базе репозитория ВООБЩЕ. "
                   "Байты существуют ровно здесь. Сессия дерева НЕ подтверждена активной — "
                   "поднимать есть что, и место названо:")
        for r in unann_hits:
            out.append(f"  [не объявлено] {r['tree']}")
            out.append(f"      кандидатов: {r['candidates']} · отсеяно: churn {r['churn']}, "
                       f"состояние прогона тестов {r['test_state']}, карточки (свой раздел) "
                       f"{r['by_card_scan']}, объявлено кем-то {r['declared']}, удалено в "
                       f"дереве {r['gone']} · старых копий (блоб известен репо): {r['known']} · "
                       f"НЕТ В РЕПО: {len(r['undelivered'])}")
            for f in r["undelivered"][:20]:
                where = f"есть на {base} под другим содержимым" if f["on_base"] \
                    else f"имени нет и на {base}"
                mark = f"{f['size'] // (1024 * 1024)} МБ, содержимое не сверялось" \
                    if f.get("size") is not None else (f["sha"] or "?")[:9]
                out.append(f"      • {f['path']} ({mark}, {where})")
            # Потолок печати — тот же, что у скорлупы, и он НЕ тихий: срезанное названо числом,
            # полный список лежит в `--json`. Замер #335: 11 деревьев, 100 файлов, причём два
            # дерева несут ОДНИ И ТЕ ЖЕ 28 путей — безадресная простыня каждый цикл научила бы
            # раздел пролистывать (прецедент п. 3d шапки), а это тот же дефект, только медленнее.
            if len(r["undelivered"]) > 20:
                out.append(f"      … и ещё {len(r['undelivered']) - 20} "
                           f"(полный список — `--json`, ключ `unannounced`)")
        skipped_active = [r for r in unann if r["active"]]
        if skipped_active:
            out.append(f"      деревьев пропущено как ЖИВЫЕ (сессия подтверждённо активна, "
                       f"расхождение там норма): {len(skipped_active)} — "
                       f"{', '.join(r['tree'] for r in skipped_active)}")

    if report.get("dead_worktrees"):
        out.append("")
        out.append(f"🧹 мёртвые регистрации рабочих деревьев ({len(report['dead_worktrees'])}) — "
                   "каталог остался, git-привязки нет (лечится `git worktree prune`, но цену "
                   "снятия смотреть в строке КАЖДОЙ скорлупы — она измерена, а не оценена):")
        for d in report["dead_worktrees"]:
            r = rows_by_path.get(d["path"])
            out.append(f"  - {d['path']}: {d['reason']}")
            if r is None:
                continue
            if r["unchecked"]:
                out.append(f"      содержимое НЕ ИЗМЕРЕНО: {r['unchecked'][0]}")
            elif r["undelivered"]:
                out.append(f"      ⚠️ снимать НЕЛЬЗЯ: {len(r['undelivered'])} файл(ов) нет в "
                           "объектной базе репо — см. раздел «в осиротевшей регистрации»")
            elif r["files"]:
                out.append(f"      цена снятия НОЛЬ: файлов вне churn {r['files']}, из них "
                           f"совпадает с {base} {r['delivered']}, старых копий {r['stale']}; "
                           "содержимого, неизвестного репозиторию, нет")
            else:
                out.append(f"      цена снятия НОЛЬ: файлов вне churn нет "
                           f"(отсеяно churn-путей: {r['churn']})")

    if report.get("by_design"):
        out.append("")
        out.append(f"📛 НЕ ДОСТАВЛЯЕТСЯ ПО ПРАВИЛУ РЕПОЗИТОРИЯ ({len(report['by_design'])}) — "
                   f"объявлено честно, в дереве лежит, на {base} никогда не было и не будет: "
                   "путь под `.gitignore`. Правило названо в каждой строке — если оно неверно, "
                   "менять надо ПРАВИЛО, а не отчёт:")
        for f in report["by_design"]:
            out.append(f"  [по правилу] {f['path']}")
            out.append(f"      сессия {f['session']} ({f['ts']}): {f['session_state']}")
            out.append(f"      {f['detail']}")
            if f.get("also_declared_by"):
                out.append(f"      тот же путь объявляли ещё: {', '.join(f['also_declared_by'])}")

    if report.get("dropped"):
        out.append("")
        out.append(f"🚮 НАМЕРЕННО НЕ ДОСТАВЛЕНО ({len(report['dropped'])}) — это РЕШЕНИЕ, а не "
                   "забывчивость: сессия разобрала путь и объявила отказ везти его на "
                   f"{base} вместе с причиной. Раздел не прячет путь, а называет автора и "
                   "основание — «решено не везти» без автора закрыло бы что угодно. Не "
                   "согласен с решением — доставляй вручную, отчёт этому не мешает:")
        for f in report["dropped"]:
            out.append(f"  [не везём] {f['path']}"
                       + (f" (было: {f['was']})" if f.get("was") else ""))
            if f.get("reason"):
                who = f.get("decided_by") or "?"
                when = f.get("decided_at") or "?"
                card = f", карточка {f['card']}" if f.get("card") else ""
                out.append(f"      решила сессия {who} ({when}{card}): {f['reason']}")
            if f.get("detail"):
                # Замер печатается как ЗАМЕР, а не как указание. Строка написана для раздела
                # «НЕ ДОСТАВЛЕНО» и кончается словами «её надо поднять» — в разделе решения
                # она бы спорила с собственным заголовком. Текст не переписывается (это
                # измерение, сделанное ДО решения) — называется его место во времени.
                out.append(f"      измерено до решения: {f['detail']}")
            if f.get("also_declared_by"):
                out.append(f"      тот же путь объявляли ещё: {', '.join(f['also_declared_by'])}")

    if report.get("deleted_on_origin"):
        out.append("")
        out.append(f"🗑  УДАЛЕНО НА {base} ({len(report['deleted_on_origin'])}) — имя там БЫЛО и "
                   "было доставлено, а затем осознанно удалено/переименовано; удаление — тоже "
                   "доставка. Байтов, которых не помнит история этого пути, нет ни в одном "
                   "рабочем дереве. ПОДНИМАТЬ НЕЧЕГО. Если удаление ошибочно, чинить надо "
                   f"{base}, а не отчёт:")
        for f in report["deleted_on_origin"]:
            out.append(f"  [удалено на {base}] {f['path']}")
            out.append(f"      сессия {f['session']} ({f['ts']}): {f['session_state']}")
            out.append(f"      {f['detail']}")
            if f.get("also_declared_by"):
                out.append(f"      тот же путь объявляли ещё: {', '.join(f['also_declared_by'])}")
            if f["summary"]:
                out.append(f"      объявляла: {f['summary']}")

    if report.get("card_closed"):
        out.append("")
        out.append(f"🗃  КАРТОЧКА ОБЪЯВЛЕНИЯ ЗАКРЫТА НА {base} ({len(report['card_closed'])}) — "
                   "работу довели, и закрытие уже доставлено (обычно ПОДЪЁМ другой сессией, "
                   "протокол §3.4); в дереве объявившего осталась промежуточная копия, которой "
                   "на базу не попасть уже никогда. ПОДНИМАТЬ НЕЧЕГО — дерево снимается "
                   "квитанцией. Карточка названа в каждой строке: если она закрыта неверно, "
                   "менять надо СТАТУС КАРТОЧКИ, а не отчёт:")
        for f in report["card_closed"]:
            out.append(f"  [карточка закрыта] {f['path']}")
            out.append(f"      сессия {f['session']} ({f['ts']}): {f['session_state']}")
            out.append(f"      {f['detail']}")
            if f.get("also_declared_by"):
                out.append(f"      тот же путь объявляли ещё: {', '.join(f['also_declared_by'])}")
            if f["summary"]:
                out.append(f"      объявляла: {f['summary']}")

    if report.get("reaped"):
        # Свёртка по ДЕРЕВЬЯМ, а не построчно. Шапка квитанции («дерево снято …, архив: …»)
        # одинакова у всех путей одного дерева и занимает ~120 символов; печатая её у каждого
        # пути, раздел разрастался в 87 строк осадка (замер #307) — в отчёте, который протокол
        # предписывает читать КАЖДЫЙ цикл. Ни один путь при этом не пропадает: шапка выносится
        # один раз, пути перечисляются под своим вердиктом. Раздел `reaped` по построению
        # держит только DELIVERED («поднимать нечего»); настоящие находки живут в разделах выше
        # и здесь не сворачиваются ничем.
        out.append("")
        groups = {}
        for r in report["reaped"]:
            groups.setdefault(r.get("tree") or "", []).append(r)
        declared = sum(1 + len(r.get("also_declared_by") or []) for r in report["reaped"])
        extra = "" if declared == len(report["reaped"]) else f"; объявлений {declared}"
        out.append(f"🧾 снятые деревья с квитанцией (путей {len(report['reaped'])} "
                   f"в {len(groups)} дерев.{extra}) — дерева нет, но измерение сделано ДО "
                   "снятия, и работа объяснена:")
        for tree, rows in groups.items():
            if not tree:
                # Дерево не опознано — сворачивать нечем, печатаем как раньше, пофайлово.
                for r in rows:
                    out.append(f"  - {r.get('session') or '-'} · {r['path']}: {r['reason']}")
                continue
            who = []
            for r in rows:
                for s in [r.get("session")] + list(r.get("also_declared_by") or []):
                    if s and s not in who:
                        who.append(s)
            out.append(f"  ▪ {tree} — снято {rows[0].get('reap_ts')} · путей {len(rows)} · "
                       f"объявляли: {', '.join(who) or '-'} · архив: {rows[0].get('archive')}")
            by_verdict = {}
            for r in rows:
                by_verdict.setdefault(r.get("verdict") or r["reason"], []).append(r)
            for verdict, rs in by_verdict.items():
                paths = ", ".join(r.get("rel") or r["path"] for r in rs)
                out.append(f"      {verdict} ({len(rs)}): {paths}")

    if report.get("fresh"):
        out.append("")
        out.append(f"⏳ свежие объявления ({len(report['fresh'])}) — не находки, работа может идти:")
        for f in report["fresh"]:
            out.append(f"  - {f['session']} ({f['ts']}, файлов: {f['files']}): {f['reason']}")

    if (not report["findings"] and not report["unmeasured"]
            and not report.get("card_findings") and not report.get("nowhere")
            and not report.get("on_branch") and not report.get("branches_with_owner_work")):
        # «Всё доставлено» при непустом разделе выше было бы неправдой в собственном отчёте:
        # эти пути не доставлены и доставлены не будут. Утверждается ровно то, что измерено —
        # потерянной работы нет, а недоставленное названо и объяснено (правилом репозитория
        # либо закрытой на базе карточкой объявления).
        explained = []
        if report.get("by_design"):
            explained.append("по правилу репозитория")
        if report.get("card_closed"):
            explained.append("карточка объявления закрыта на базе")
        if report.get("deleted_on_origin"):
            explained.append(f"путь удалён на {base}")
        if report.get("dropped"):
            explained.append("решено не доставлять (с причиной)")
        out.append("✅ измерено полностью, всё доставлено" if not explained
                   else "✅ измерено полностью, потерянной работы нет (недоставленное — "
                        + "; ".join(explained) + ", разделы выше)")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="Read-only проверка: объявленная в session_changes.jsonl работа "
                    "мёртвых сессий — доехала ли она до origin. Сети не касается.")
    # Умолчания разрешаются в ГЛАВНОЕ рабочее дерево, а не в дерево этого файла: запущенный
    # из worktree (а протокол §3.4 обязывает работать именно там) шаг 0a иначе читает пустой
    # журнал и отвечает «НЕ ИЗМЕРЕНО» о ЛЮБОЙ сессии. Явный флаг по-прежнему главнее.
    ap.add_argument("--log", default=None, help="журнал объявлений (JSONL)")
    ap.add_argument("--root", default=None, help="корень репозитория для сверки")
    ap.add_argument("--base", default=DEFAULT_BASE, help=f"базовый ref (по умолчанию {DEFAULT_BASE})")
    ap.add_argument("--last", type=int, default=DEFAULT_LAST, help="сколько последних записей")
    ap.add_argument("--all", action="store_true", help="проверить весь журнал")
    ap.add_argument("--grace-hours", type=float, default=DEFAULT_GRACE_HOURS,
                    help="сколько часов после объявления считать работу возможно идущей "
                         f"(по умолчанию {DEFAULT_GRACE_HOURS})")
    ap.add_argument("--json", action="store_true", help="машинный вывод")
    args = ap.parse_args(argv)

    shared_root, root_error = main_worktree()
    log_path = Path(args.log) if args.log else shared_log()[0]
    root = args.root or (str(shared_root) if shared_root else str(ROOT))

    if not log_path.exists():
        payload = {"base_ref": args.base, "base_sha": None, "log": str(log_path),
                   "grace_hours": args.grace_hours, "entries_checked": 0,
                   "sessions_active": 0, "sessions_checked": 0, "findings": [], "fresh": [],
                   "stale_copies": [],
                   "unmeasured": [{"session": None, "path": str(log_path),
                                   "reason": "журнала объявлений нет — сверка НЕ ВЫПОЛНЕНА"
                                             + (f"; главное рабочее дерево не определено: "
                                                f"{root_error}" if root_error else "")}],
                   "exit_code": 2}
        print(json.dumps(payload, ensure_ascii=False, indent=2) if args.json else render(payload))
        return 2

    entries, malformed = read_entries(log_path, None if args.all else args.last)
    # Доверенная личность — только явно названная сессией. `pid<os.getpid()>` — pid
    # ОДНОКРАТНОЙ CLI-команды: по нему пропускать чужие объявления нельзя (см. session_state).
    env_session = os.environ.get("SPA_SESSION_ID")
    self_session = env_session or f"pid{os.getpid()}"
    report = build_report(entries=entries, root=root, base_ref=args.base,
                          self_session=self_session, ps=_ps_lstart, git=_git,
                          malformed_lines=malformed, log_path=log_path,
                          grace_hours=args.grace_hours,
                          self_session_trusted=bool(env_session),
                          # ГЛАВНОЕ дерево, а не `root`: `--root` может указывать на worktree,
                          # и тогда исключилось бы не то дерево. Не измерено ⇒ None ⇒ родство
                          # по дереву выключено целиком (fail-CLOSED).
                          shared_trees=(str(shared_root),) if shared_root else None)
    print(json.dumps(report, ensure_ascii=False, indent=2) if args.json else render(report))
    return int(report["exit_code"])


if __name__ == "__main__":
    raise SystemExit(main())
