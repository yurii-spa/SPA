DURABLE_KEYS = ("session_pid", "session_pid_start")


def durable_fields(entry):
    """Подмножество ключей записи, описывающих долгоживущий процесс сессии (может быть пусто).

    Нужно тем, кто строит СИНТЕТИЧЕСКУЮ запись для `session_state` (шаг 0b собирает её из
    (session, ts)): без этих полей улучшение до них просто не доезжает."""
    return {k: entry[k] for k in DURABLE_KEYS if isinstance(entry, dict) and k in entry}


def anchor_of(entry):
    """``(pid, «старт verbatim»)`` или None — ИЗМЕРЕННАЯ личность процесса, написавшего запись.

    Требуются ОБА поля. `session_pid` без `session_pid_start` личностью не считается: pid
    переиспользуется операционной системой, поэтому «тот же номер» без времени старта — не
    «тот же процесс», а совпадение числа.

    **Одно определение на оба шага протокола.** Раньше эта функция жила в `check_card_claim`
    (шаг 0b), а шаг 0a знал только `_durable_state`; здесь она стоит потому, что зависимость
    между модулями односторонняя (`check_card_claim` грузит этот файл как `sibling`, не
    наоборот), и копия в двух файлах разошлась бы молча."""
    if not isinstance(entry, dict):
        return None
    raw, start = entry.get("session_pid"), entry.get("session_pid_start")
    if raw is None or start is None:
        return None
    pid = raw if isinstance(raw, int) and not isinstance(raw, bool) else None
    if pid is None and isinstance(raw, str) and raw.strip().isdigit():
        pid = int(raw.strip())
    if pid is None or pid <= 1:
        return None
    start = str(start).strip()
    return (pid, start) if start else None


def durable_by_session(entries):
    """ярлык сессии → её поля долгоживущего процесса, ТОЛЬКО когда они однозначны.

    Ярлык — не идентификатор процесса, и один и тот же ярлык в принципе может нести разные
    якоря (перезапуск цикла под тем же `SPA_SESSION_ID`). Разные пары ⇒ ключа нет ⇒ у
    вызывающего поведение остаётся побайтово прежним (fail-CLOSED): угадывать, который из
    процессов написал запись, инструмент не станет."""
    found, ambiguous = {}, set()
    for entry in entries or ():
        label = str((entry or {}).get("session") or "").strip()
        if not label or label in ambiguous:
            continue
        anchor = anchor_of(entry)
        if anchor is None:
            continue
        if label in found and found[label][0] != anchor:
            del found[label]
            ambiguous.add(label)
            continue
        found[label] = (anchor, durable_fields(entry))
    return {label: fields for label, (_anchor, fields) in found.items()}


def labels_with_conflicting_anchors(entries):
    """Ярлыки, под которыми журнал знает НЕСКОЛЬКО РАЗНЫХ якорей (перезапуск цикла под тем же
    `SPA_SESSION_ID`).

    Зачем отдельный вопрос, когда есть `durable_by_session` (цикл #327). Тот отвечает «можно ли
    ЗАИМСТВОВАТЬ личность» и на неоднозначном ярлыке молчит — а молчание читается одинаково в
    двух РАЗНЫХ случаях: якоря нет ни у кого (ничего не известно) и якорей несколько
    (известно, что ярлык носили разные процессы). Для запасного критерия `pid_from_label` это
    различие решающее: во втором случае журнал прямо ОПРОВЕРГ ярлык как носителя личности —
    в живом примере ярлык `cycle-264-pid80387` несёт якоря 80373 и 99999, то есть названный им
    pid не совпадает НИ С ОДНИМ из них. Померить такой pid значит спросить `ps` о постороннем
    процессе, и живой посторонний дал бы ложный ACTIVE — fail-OPEN внутри fail-CLOSED-сторожа.
    """
    seen, conflicting = {}, set()
    for entry in entries or ():
        label = str((entry or {}).get("session") or "").strip()
        if not label:
            continue
        anchor = anchor_of(entry)
        if anchor is None:
            continue
        if label in seen and seen[label] != anchor:
            conflicting.add(label)
            continue
        seen.setdefault(label, anchor)
    return conflicting


_LABEL_PID_TOKEN = re.compile(r"(?:\A|[-_])(pid\d+)(?=\Z|[-_])")


def pid_tokens(label):
    """Токены вида `pidN` в ярлыке сессии — КОМПОНЕНТОМ, а не подстрокой.

    `cycle-292-pid71239` → `{'pid71239'}`, `pid71239` → `{'pid71239'}`, `pid7` НЕ находится
    внутри `pid71239` (иначе одна сессия «породнилась» бы с другой по общему префиксу числа —
    ровно подстрочная коллизия, на которой уже обжёгся храповик неподключённых скриптов, #227)."""
    return set(_LABEL_PID_TOKEN.findall(str(label or "")))


# Каталоги верхнего уровня репозитория: по ним объявленный путь читается как «<корень>/<каталог>/…».
# Список — свойство ЭТОГО репо, а не догадка: всё, что в нём есть, лежит в git и объявляется
# сессиями. Незнакомый первый компонент ⇒ дерево из пути НЕ читается (а не угадывается).
_REPO_TOP_DIRS = frozenset({
    ".claude", ".github", "architecture", "cabinet", "data", "docs", "inbox", "landing",
    "launchd", "nimbalyst-local", "research", "scripts", "spa_core", "strategies", "tests",
})


def _normalize_tree(path):
    """Путь к дереву в ОДНОМ написании: macOS отдаёт `/tmp/x` и `/private/tmp/x` за один каталог.

    Именно на этом расхождении родство по дереву споткнулось бы в живом замере #301: захват
    объявил `/private/tmp/spa_c301/…`, а объявление владения — `/tmp/spa_c301/…`. Побайтовое
    сравнение двух написаний одного дерева ответило бы «разные деревья» — тот же класс, что
    сама чинимая слепота. `realpath` здесь НЕ годится: снятого дерева на диске уже нет, а
    ответ обязан быть одинаковым для живого и для снятого."""
    p = str(path or "").strip()
    if not p:
        return None
    for prefix in ("/private/tmp/", "/private/var/"):
        if p.startswith(prefix):
            p = "/" + p[len("/private/"):]
            break
    return p.rstrip("/") or "/"


def tree_of_path(path):
    """Корень рабочего дерева, читаемый из объявленного АБСОЛЮТНОГО пути, либо None.

    `/tmp/spa_c301/scripts/x.py` → `/tmp/spa_c301`. Относительный путь и путь, первый
    компонент которого не является каталогом репо, дерева не дают: домысливать корень по
    «предпоследнему каталогу» значило бы выдавать догадку за измерение."""
    p = _normalize_tree(path)
    if not p or not p.startswith("/"):
        return None
    parts = Path(p).parts
    for i, part in enumerate(parts):
        if i > 0 and part in _REPO_TOP_DIRS:
            return str(Path(*parts[:i]))
    return None


def dropped_declarations(entries):
    """{ключ: объявление} для путей, которые сессии объявили НАМЕРЕННО не доставленными.

    Сверка идёт по СТРОКЕ, которую написала сессия (плюс `/tmp` ≡ `/private/tmp`), а не по
    repo-relative форме — и это граница, а не мелочь. Один и тот же относительный путь
    (`nimbalyst-local/tracker/x.md`) лежит в ДЕСЯТКАХ рабочих деревьев; сведи ключ к нему — и
    отказ одной сессии везти СВОЮ копию погасил бы находку о ЧУЖОЙ. Поэтому находка несёт
    объявленный путь как есть (`declared_as`), и сверяется именно он.

    Причина обязательна: пара без неё пропускается (fail-CLOSED, зеркало `normalize_dropped`
    у писателя). Окна нет — см. `reap_stale_worktrees.dropped_declarations`."""
    out = {}
    for entry in entries or ():
        for row in (entry or {}).get("dropped") or ():
            declared = str((row or {}).get("path") or "").strip()
            reason = str((row or {}).get("reason") or "").strip()
            if not declared or not reason:
                continue
            decl = {"path": declared, "reason": reason, "session": entry.get("session"),
                    "ts": entry.get("ts"), "card": entry.get("card")}
            for k in {declared, _normalize_tree(declared) or declared,
                      declared.replace("/private/tmp/", "/tmp/", 1),
                      declared.replace("/tmp/", "/private/tmp/", 1)}:
                out[k] = decl
    return out


def worktree_of(entry):
    """Рабочее дерево, названное файлами записи, либо None, если оно из них НЕ читается.

    Читается ровно тогда, когда все объявленные пути, из которых дерево вообще выводится,
    называют ОДНО дерево. Запись, объявившая файлы в двух деревьях (в журнале таких ярлыков
    26 из 630), дерева не имеет — угадывать, какое из них «настоящее», инструмент не станет."""
    roots = set()
    for f in (entry or {}).get("files") or ():
        root = tree_of_path(f)
        if root:
            roots.add(root)
    return next(iter(roots)) if len(roots) == 1 else None


def anchors_with_kin(entries, extra_labels=(), shared_trees=None):
    """`durable_by_session`, где ярлык БЕЗ якоря получает якорь СОСЕДНЕГО ярлыка ТОЙ ЖЕ сессии.

    **Дефект, который это закрывает (цикл #293).** Одна сессия пишет в журнал под ДВУМЯ
    ярлыками: захват — под тем, что передан флагом `--session pidN` (так велит шаг 0b
    протокола), а объявление владения — под своим `SPA_SESSION_ID` вида `cycle-N-pidN`. Якорь
    (`session_pid`/`session_pid_start`) `log_session_change.record` ставит ТОЛЬКО когда ярлык
    записи совпадает с собственным id писателя — и это верно, менять там нечего (карточка
    `agent-claim-guard-blind-when-session-pid-is-set`: якорь на чужом ярлыке читался бы как
    «запись моя»). Значит запись-захват якоря не несёт ПО ПОСТРОЕНИЮ, и `borrow_durable`,
    который ищет якорь строго под ТЕМ ЖЕ ярлыком, до него не дотягивается.

    Цена измерена, а не предположена (журнал 18.08, 996 записей): захватов — 430, из них без
    якоря 116, и у 6 (5 карточек) якорь сессии лежал в соседнем ярлыке, причём во ВСЕХ шести
    случаях соседний ярлык был к моменту замера измеримо мёртв. Один из них — живой случай
    этого же цикла: шаг 0b объявил `⛔ ЗАНЯТА` о сессии #292, смерть которой напечатал в том же
    отчёте двумя строками ниже, и запретил подъём осиротевшей работы, к которому звал шаг 0a.
    Класс известен (#238 чинил его же с другого входа), но там знание о смерти в отчёте БЫЛО и
    не доезжало до вердикта; здесь оно не доезжало до самого измерения.

    **Три сужения, каждое fail-CLOSED** (несработавшее оставляет прежнее «не измерено»):

    1. свой якорь всегда сильнее — ярлык, у которого он есть, не трогаем;
    2. ярлык, чей СОБСТВЕННЫЙ якорь неоднозначен (`durable_by_session` его выбросил), родни не
       получает: иначе правило неоднозначности снималось бы с чёрного хода;
    3. токен должен вести к ОДНОМУ якорю, и токен у ярлыка — ровно один. Два разных якоря на
       токен или два токена в ярлыке ⇒ родства нет: угадывать, которая из сессий писала, этот
       инструмент не станет (то же правило, что у `durable_by_session`).

    Проверку «процесс стартовал не позже записи» здесь НЕ дублируем — она живёт в
    `borrow_durable` и применяется к заимствованию любой природы, своей и родственной.

    `extra_labels` — ярлыки, которых в записях может не быть вовсе: захват во frontmatter
    карточки несёт ЯРЛЫК держателя, и спрашивать о нём приходится отдельно (в журнале он есть
    почти всегда, но «почти» у сторожа означает молчаливую дыру).

    ── Второй признак родства: РАБОЧЕЕ ДЕРЕВО (цикл #303) ──────────────────────

    **Дефект, который это закрывает.** Токен `pidN` берётся из САМОГО ярлыка, а ярлык формы
    `cycle-<PID>` (без слова `pid`) не даёт токена ВООБЩЕ: `pid_tokens('cycle-64036')` — пустое
    множество. Значит починка #293 до такой пары не дотягивается ПО ПОСТРОЕНИЮ, а не по
    недосмотру. Мало того, два ярлыка одной сессии несут РАЗНЫЕ числа (#301: захват под
    `pid64051` — pid однократной CLI-команды, объявление под `cycle-64036` — долгоживущий
    процесс), поэтому даже одинаковая форма родства бы не дала: совпадение чисел — счастливая
    случайность, а не свойство. Живой замер #302 (журнал 19.08, 1021 запись): 328 захватов из
    445 объявлены под ярлыком без токена, то есть вне досягаемости родства по токену.

    Дерево — признак МАШИННЫЙ и общий у обоих ярлыков: сессия работает в одном изолированном
    worktree (§3.4) и объявляет пути внутри него. Замер по всему журналу: 17 записей-захватов
    получают якорь этим путём, и ни одна из них не получала его токеном.

    **Четыре сужения, каждое fail-CLOSED:**

    1. свой якорь и родство по ТОКЕНУ сильнее — дерево спрашивается только у ярлыка, которому
       ни то, ни другое якоря не дало;
    2. у ярлыка должно быть РОВНО ОДНО дерево на все его записи (иначе связывать нечем);
    3. дерево должно вести к ОДНОМУ якорю — два разных якоря на дерево ⇒ родства нет;
    4. `shared_trees` — деревья, ОБЩИЕ для многих сессий (главное рабочее дерево прежде
       всего): в них живут все, и «то же дерево» там не значит «та же сессия». `None` =
       общие деревья НЕ измерены ⇒ родство по дереву не применяется вовсе.

    Сужение 4 — не теория: в живом журнале прод-дерево называют **101 ярлык с 17 разными
    якорями**, то есть п.3 его и так отбрасывает. Но отбрасывает СЛУЧАЙНО (историей записей),
    а сторож обязан быть шире подопечного — на коротком журнале того же прод-дерева хватило бы
    одного якоря, и живая сессия получила бы чужую смерть. Ровно этой случайной безопасностью
    обжёгся #234 («уцелел по случайному свежему объявлению, не по правилу»)."""
    direct = durable_by_session(entries)
    self_ambiguous = {str((e or {}).get("session") or "").strip()
                      for e in entries or () if anchor_of(e) is not None}
    self_ambiguous -= set(direct)

    by_token, spoiled = {}, set()
    for label, fields in direct.items():
        key = (fields.get("session_pid"), str(fields.get("session_pid_start") or ""))
        for tok in pid_tokens(label):
            if tok in spoiled:
                continue
            prev = by_token.get(tok)
            if prev is not None and prev[0] != key:
                del by_token[tok]
                spoiled.add(tok)
                continue
            by_token[tok] = (key, label, fields)

    labels = [str((e or {}).get("session") or "").strip() for e in entries or ()]
    labels += [str(x or "").strip() for x in extra_labels or ()]

    widened, kin_source = dict(direct), {}
    for label in labels:
        if not label or label in widened or label in self_ambiguous:
            continue
        tokens = pid_tokens(label)
        if len(tokens) != 1:
            continue
        found = by_token.get(next(iter(tokens)))
        if found is None:
            continue
        _key, source, fields = found
        if source == label:
            continue
        widened[label] = fields
        kin_source[label] = source

    if shared_trees is not None:
        _widen_by_tree(entries, labels, direct, self_ambiguous, widened, kin_source,
                       {_normalize_tree(t) for t in shared_trees})
    return widened, kin_source


def _widen_by_tree(entries, labels, direct, self_ambiguous, widened, kin_source, shared):
    """Второй проход `anchors_with_kin`: родство по общему рабочему дереву (см. её докстринг).

    Правит `widened`/`kin_source` НА МЕСТЕ и только там, где после первого прохода не было
    ничего: ярлык, получивший якорь свой или по токену, сюда не доходит."""
    tree_by_label, split_labels = {}, set()
    for e in entries or ():
        label = str((e or {}).get("session") or "").strip()
        tree = worktree_of(e)
        if not label or tree is None:
            continue
        if tree_by_label.setdefault(label, tree) != tree:
            split_labels.add(label)          # сессия объявляла файлы в разных деревьях

    by_tree, spoiled = {}, set(shared)
    for label, fields in direct.items():
        tree = tree_by_label.get(label)
        if tree is None or label in split_labels or tree in spoiled:
            continue
        key = (fields.get("session_pid"), str(fields.get("session_pid_start") or ""))
        prev = by_tree.get(tree)
        if prev is not None and prev[0] != key:
            del by_tree[tree]
            spoiled.add(tree)
            continue
        by_tree[tree] = (key, label, fields)

    for label in labels:
        if not label or label in widened or label in self_ambiguous or label in split_labels:
            continue
        tree = tree_by_label.get(label)
        found = by_tree.get(tree) if tree else None
        if found is None:
            continue
        _key, source, fields = found
        if source == label:
            continue
        widened[label] = fields
        kin_source[label] = source


def borrow_durable(entry, anchors, kin_source=None):
    """``(запись, пояснение)`` — запись как есть, либо её копия с личностью ИЗ ЖУРНАЛА.

    **Дефект, который это закрывает** (догфуд цикла #265). Шаг 0a мерил каждую запись в
    ОДИНОЧКУ: нет своей пары (`session_pid`, `session_pid_start`) ⇒ `_measured_session_state`
    падал на разбор ЯРЛЫКА (`_PID_RE`), а ярлык вида `cycle-264-pid80387` под него не подходит
    ⇒ `UNKNOWN` ⇒ вся запись уходит в «НЕ ИЗМЕРЕНО» (код 2), и её объявленные файлы не
    разбираются ВОВСЕ — ни квитанция снятого дерева, ни закрытая на базе карточка до них уже
    не доезжают. Живой замер 16.08: 3 строки «не измерено» из 20 записей, все три — записи
    `[check_card_claim] захват карточки`, то есть наша СОБСТВЕННАЯ автоматика; из 908 записей
    журнала таких 12.

    **Личность при этом БЫЛА** — соседней записью того же журнала, который инструмент уже
    прочитал: `claim` пишет запись без якоря (его даёт окружение `SPA_SESSION_PID`, и у
    однократной CLI-команды его может не быть), а объявление владения секундой позже несёт
    якорь под ТЕМ ЖЕ ярлыком. Ровно этот вопрос уже задаёт шаг 0b (`durable_by_session`,
    карточка `agent-frontmatter-claim-locks-card-forever`) — здесь тот же класс с другого
    входа: необратимое «не измерено» над познаваемым фактом.

    **Два сужения, каждое измеримо** (несработавшее оставляет `UNKNOWN` как было):

    1. ярлык несёт в журнале ОДНОЗНАЧНЫЙ якорь (`durable_by_session`);
    2. процесс якоря стартовал НЕ ПОЗЖЕ самой записи (допуск `CLOCK_SKEW`). Процесс,
       родившийся после объявления, написать его не мог: это переиспользованный ярлык, и
       заимствование дало бы ложный `ACTIVE` — fail-OPEN внутри fail-CLOSED-сторожа.

    Заимствование НАЗЫВАЕТСЯ вслух: измерение уходит читателю с пояснением, откуда взята
    личность, — иначе отчёт утверждал бы про запись то, чего в ней не написано."""
    if not isinstance(entry, dict) or not anchors:
        return entry, ""
    if anchor_of(entry) is not None:
        return entry, ""
    label = str(entry.get("session") or "").strip()
    fields = anchors.get(label)
    if not fields:
        return entry, ""
    ts = _parse_ts(entry.get("ts"))
    started = _parse_lstart(str(fields.get("session_pid_start") or ""))
    if ts is None or started is None or started > ts + CLOCK_SKEW:
        return entry, ""
    source = (kin_source or {}).get(label)
    whose = (f"по ярлыку {label!r}" if source is None else
             f"по РОДСТВЕННОМУ ярлыку {source!r} той же сессии (у {label!r} своего якоря нет: "
             f"`record` не ставит его на ярлык, переданный флагом, а без SPA_SESSION_PID его "
             f"нет и у собственного)")
    return {**entry, **fields}, (f"личность взята из журнала {whose} "
                                 f"(pid{fields.get('session_pid')}, старт "
                                 f"{fields.get('session_pid_start')}): в самой записи её нет")


def _durable_state(entry, ts, ps):
    """None — сессия долгоживущего процесса не объявляла; иначе (state, измерение словами).

    **Основной критерий активности** (карточка `agent-durable-session-id`). `session` по
    умолчанию — pid ОДНОКРАТНОЙ CLI-команды, умирающий вместе с ней, поэтому `ps` по нему
    бессодержателен для ЛЮБОЙ записи, а id без pid (`cycle49`, `cycle61`) не измерялся вовсе.
    `session_pid` пишет `log_session_change.durable_process` только когда процесс подтверждён
    в момент записи, вместе с его временем старта.

    Совпадение старта — это проверка ЛИЧНОСТИ процесса: без неё переиспользованный ОС pid
    читался бы как живая сессия (ложный ACTIVE ⇒ шаг 0a молча пропустил бы недоставленную
    работу). Расхождение старта — не «не измерено», а измеренный факт «это другой процесс»."""
    if not isinstance(entry, dict) or "session_pid" not in entry:
        return None
    raw = entry.get("session_pid")
    pid = raw if isinstance(raw, int) and not isinstance(raw, bool) else None
    if pid is None and isinstance(raw, str) and raw.strip().isdigit():
        pid = int(raw.strip())
    if pid is None or pid <= 1:
        return UNKNOWN, (f"session_pid={raw!r} не разобран как pid процесса — "
                         "активность не измерена")

    rc, out = ps(pid)
    if rc == 1:
        return NOT_CONFIRMED, (f"долгоживущий процесс сессии pid{pid} завершился "
                               "(активность не подтверждена)")
    if rc != 0:
        return UNKNOWN, f"`ps -p {pid}` не отработал (rc={rc}) — активность не измерена"
    if not str(out).strip():
        return UNKNOWN, f"`ps -p {pid}` вернул пустой ответ — активность не измерена"
    started = _parse_lstart(out)
    if started is None:
        return UNKNOWN, (f"pid{pid} существует, но время старта не разобрано: "
                         f"{str(out).strip()!r} — активность не измерена")

    recorded_raw = entry.get("session_pid_start")
    if recorded_raw is None:
        # Долгоживущий pid без записанного старта: сверяемся с объявлением, как для pid-id.
        if started > ts + CLOCK_SKEW:
            return NOT_CONFIRMED, (f"pid{pid} занят ДРУГИМ процессом: старт "
                                   f"{started.isoformat()} позже объявления {ts.isoformat()}")
        return ACTIVE, f"долгоживущий процесс сессии pid{pid} жив (старт {started.isoformat()})"
    recorded = _parse_lstart(str(recorded_raw))
    if recorded is None:
        return UNKNOWN, (f"записанное время старта pid{pid} не разобрано: "
                         f"{str(recorded_raw)!r} — активность не измерена")
    if abs((started - recorded).total_seconds()) > CLOCK_SKEW.total_seconds():
        return NOT_CONFIRMED, (f"pid{pid} занят ДРУГИМ процессом: старт {started.isoformat()} "
                               f"вместо записанного {recorded.isoformat()}")
    return ACTIVE, (f"долгоживущий процесс сессии pid{pid} жив — тот же процесс "
                    f"(старт {started.isoformat()})")


def durable_process_gone(entry, ps=_ps_lstart):
    """True — сессия ОБЪЯВЛЯЛА долгоживущий процесс, и его измеренно больше нет.

    Единственное основание снять окно ожидания досрочно (см. докстринг модуля). Условие
    намеренно узкое — это НЕ «`ps` не нашёл pid»:

    - запись без `session_pid` (таких большинство) → False. `session` там — pid ОДНОКРАТНОЙ
      CLI-команды `log_session_change.py`, он мёртв ВСЕГДА, и живая сессия ничем не отличалась
      бы от осиротевшей. Ровно на этом окно и стоит;
    - `session_pid` есть, но `ps` не отработал / не разобран старт → False (`UNKNOWN`).
      «Не измерено» смертью не объявляем; запись доживёт в окне и будет измерена обычным
      порядком, когда окно истечёт — потери сигнала здесь нет, есть отсрочка;
    - `session_pid` есть, процесса нет ЛИБО pid занят другим процессом (`NOT_CONFIRMED`) →
      True. `log_session_change.durable_process` пишет эту пару только когда процесс
      подтверждён в момент записи, поэтому его исчезновение — измеренный факт, а не догадка.

    Смерть сессии сама по себе находкой НЕ является: она лишь снимает ожидание, а находкой
    делает недоставленный файл (`absent`/`differs`) — все три условия карточки вместе.
    """
    ts = _parse_ts(entry.get("ts"))
    if ts is None:
        return False                       # метка времени не разобрана → это UNKNOWN, не смерть
    durable = _durable_state(entry, ts, ps)
    return durable is not None and durable[0] == NOT_CONFIRMED


def session_state(entry, self_session, ps=_ps_lstart, self_session_trusted=True,
                  label_identity_disproved=False):
    """(ACTIVE|NOT_CONFIRMED|UNKNOWN, измерение словами).

    ACTIVE — активность ПОДТВЕРЖДЕНА (это мы сами; объявленный сессией долгоживущий процесс
    жив; либо живой процесс из pid-идентификатора, стартовавший до объявления).
    NOT_CONFIRMED — подтверждения нет; это НЕ вывод «сессия умерла» (см. докстринг модуля),
    решает возраст объявления. UNKNOWN — измерить не смогли.

    Порядок: своя сессия → долгоживущий процесс записи (**основной критерий**) → pid из
    идентификатора (как раньше, для записей без новых полей). Окно ожидания у вызывающих
    остаётся запасным критерием и не трогается.

    **`self_session_trusted` — доверенная ли личность проверки.** Пропуск «это мы сами»
    имеет право молчать о записи, поэтому он допустим ТОЛЬКО по личности, которую сессия
    назвала явно (`SPA_SESSION_ID`). Личность вида `pid<os.getpid()>` выведена из pid
    ОДНОКРАТНОЙ CLI-команды и доверенной не является: совпадение такого pid'а с чужим
    идентификатором молча выронило бы чужое объявление из отчёта — fail-OPEN внутри
    сторожа, который весь построен как fail-CLOSED. Это не гипотеза: на Linux-раннере
    прогон получил pid **4242**, совпавший с фикстурой `pid4242`, и проверка вернула
    «всё измерено» вместо «не измерено» (цикл #223; тест починили тогда же, прод — нет).
    При недоверенной личности запись меряется ОБЫЧНЫМИ правилами, а совпадение
    называется вслух; находкой она становится по возрасту объявления, а не автоматически.
    """
    session = str(entry.get("session") or "")
    if session and session == self_session:
        if self_session_trusted:
            return ACTIVE, "это текущая сессия"
        state, why = _measured_session_state(
            entry, session, ps, label_identity_disproved=label_identity_disproved)
        return state, (f"идентификатор совпал с личностью этой проверки ({self_session}), но "
                       f"она выведена из pid однократного процесса и доверенной не является "
                       f"(нет SPA_SESSION_ID) — меряем запись как чужую: {why}")

    return _measured_session_state(entry, session, ps,
                                   label_identity_disproved=label_identity_disproved)


def pid_from_label(session):
    """``(pid, откуда, причина отказа)`` — pid, названный самим идентификатором сессии.

    **Дефект, который это закрывает** (замер цикла #326). Запасной критерий активности
    разбирал ТОЛЬКО точную форму `pid<N>` (`_PID_RE`), а сессии давно называют себя составным
    ярлыком — `cycle-325-pid40372`, `cycle-323-pid61319`. Когда у такой записи нет своей пары
    (`session_pid`, `session_pid_start`) и нечего заимствовать у соседей по журналу
    (`borrow_durable`), измерение упиралось в «идентификатор не содержит pid» — при том, что
    pid в нём написан открытым текстом и стоил одной команды `ps`.

    **Самое неприятное: ответ уже лежал в этом же файле.** `pid_tokens` умеет доставать
    `pidN` из составного ярлыка с #303, где эту механику написали для РОДСТВА ярлыков одной
    сессии. Родство её спрашивало, измерение активности — ни разу. Поэтому здесь не заводится
    вторая регулярка: разбор ровно один (`_LABEL_PID_TOKEN`, разделители `-`/`_`, токен
    компонентом а не подстрокой), и ужесточение его правил автоматически ужесточает оба
    читателя вместо того, чтобы разводить их по разным определениям.

    Цена этого «не измерено» — не косметическая, и она измерена на живом случае. 21.08 цикл
    #325 умер, не доставив работу; его единственное объявление несло ярлык
    `cycle-325-pid40372` без якоря. Шаг 0a отправил запись в «❓ НЕ ИЗМЕРЕНО» ⇒ объявленные ею
    файлы не разбирались ВООБЩЕ (тот же ущерб, что описан у `borrow_durable`), а шаг 0b
    прочитал неизмеримую личность как **живого держателя карточки** и запретил подъём
    осиротевшей работы. Неизмеримость здесь работает как утверждение — и оба раза не в ту
    сторону.

    **Fail-CLOSED не ослаблен, а сужен до настоящей неизвестности:**

    * pid нет в ярлыке вовсе ⇒ отказ, как было;
    * ярлык называет НЕСКОЛЬКО РАЗНЫХ pid ⇒ отказ: гадать, который из них процесс сессии,
      значит менять «не измерено» на выдумку;
    * `pid0`/`pid1` ⇒ отказ (это не pid сессии, а `ps` по ним ответит утвердительно).

    Доверие ярлыку не повышается: pid из ярлыка — тот же ЗАПАСНОЙ критерий, что и `pid<N>`,
    с той же защитой от переиспользования pid (старт позже объявления ⇒ «занят ДРУГИМ
    процессом», см. `_measured_session_state`) и с тем же запретом на пропуск «это мы сами»
    (`session_state`: доверенная личность — только явный `SPA_SESSION_ID`). Источник pid
    НАЗЫВАЕТСЯ в измерении вслух, чтобы читатель не принял ярлык за объявленный якорь.
    """
    session = str(session or "")
    m = _PID_RE.match(session)
    if m:
        pid = int(m.group(1))
        if pid <= 1:
            return None, "", (f"идентификатор сессии {session!r} называет pid{pid} — "
                              "это не процесс сессии, активность не измерена")
        return pid, "id", ""

    distinct = sorted(int(token[3:]) for token in pid_tokens(session))
    if not distinct:
        return None, "", (f"идентификатор сессии {session!r} не содержит pid — "
                          "активность процесса не измерена")
    if len(distinct) > 1:
        names = ", ".join(f"pid{p}" for p in distinct)
        return None, "", (f"идентификатор сессии {session!r} называет несколько разных pid "
                          f"({names}) — который из них процесс сессии, не измерено")
    pid = distinct[0]
    if pid <= 1:
        return None, "", (f"идентификатор сессии {session!r} называет pid{pid} — "
                          "это не процесс сессии, активность не измерена")
    return pid, "label", ""


def _measured_session_state(entry, session, ps=_ps_lstart, label_identity_disproved=False):
    """Измерение активности записи без ветки «это мы сами» (см. `session_state`)."""
    ts = _parse_ts(entry.get("ts"))
    if ts is None:
        return UNKNOWN, (f"метка времени записи не разобрана: {entry.get('ts')!r} — "
                         "возраст объявления не измерен")

    durable = _durable_state(entry, ts, ps)
    if durable is not None:
        return durable

    pid, origin, why = pid_from_label(session)
    if pid is None:
        return UNKNOWN, why
    # Ярлык как носитель личности ОПРОВЕРГНУТ журналом (несколько разных якорей под ним) —
    # запасной критерий отказывает, а не спрашивает `ps` о постороннем процессе. Отличать
    # «якоря нет ни у кого» от «якорей несколько» обязательно: первое молчит, второе
    # утверждает (`labels_with_conflicting_anchors`, цикл #327).
    if origin == "label" and label_identity_disproved:
        return UNKNOWN, (f"идентификатор сессии {session!r} называет pid{pid}, но в журнале под "
                         "этим же ярлыком НЕСКОЛЬКО РАЗНЫХ долгоживущих процессов — ярлык как "
                         "личность опровергнут, активность не измерена")
    # Ярлык — не объявленный якорь, и читатель обязан видеть разницу: `session_pid` пишется
    # только по подтверждённому процессу, а pid из ярлыка сессия назвала сама.
    named = f"pid{pid}" if origin == "id" else f"pid{pid} (назван ярлыком сессии {session!r})"

    rc, out = ps(pid)
    if rc == 1:
        return NOT_CONFIRMED, f"процесса {named} нет (активность не подтверждена)"
    if rc != 0:
        return UNKNOWN, (f"`ps -p {pid}` не отработал (rc={rc}) — активность {named} "
                         "не измерена")
    if not out.strip():
        return UNKNOWN, (f"`ps -p {pid}` вернул пустой ответ — активность {named} "
                         "не измерена")

    started = _parse_lstart(out)
    if started is None:
        return UNKNOWN, (f"{named} существует, но время старта не разобрано: "
                         f"{out.strip()!r} — активность не измерена")

    if started > ts + CLOCK_SKEW:
        return NOT_CONFIRMED, (f"{named} занят ДРУГИМ процессом: старт {started.isoformat()} "
                               f"позже объявления {ts.isoformat()}")
    return ACTIVE, f"{named} жив (старт {started.isoformat()})"


