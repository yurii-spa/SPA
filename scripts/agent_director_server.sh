#!/bin/bash
# scripts/agent_director_server.sh — launchd-обёртка для com.spa.director_server.
#
# ЧТО ЭТО. Минимальная раздача закрытого кокпита: ТОЛЬКО 127.0.0.1, ТОЛЬКО три файла из
# таблицы адресов, ТОЛЬКО GET/HEAD. Наружу ведёт существующий туннель Cloudflare, а не сокет.
#
# ПОЧЕМУ НЕ agent_template.sh. Шаблон рассчитан на завершающийся шаг: он сам зовёт
# code_sync и выходит. Эта служба — долгожитель (KeepAlive), и правило доставки прямо
# запрещает гонять на долгожителе пробный запуск: второй экземпляр на том же порту не
# поднимется, а сторож будет выглядеть зависшим. Поэтому вызов прямой, а свежесть кода
# сюда приносит перезапуск службы, не обёртка.
#
# ПОЧЕМУ ПУТЬ И ПОРТ ЗАШИТЫ. Ни одного значения из окружения: launchd не наследует
# оболочку, и «${DIR}» превратилось бы в пустую строку, то есть в раздачу текущего
# каталога. Расширения пути оболочкой здесь нет вовсе — оба аргумента литеральные.
#
# КОРЕНЬ РАЗДАЧИ ВНЕ РЕПОЗИТОРИЯ намеренно: сгенерированные владельческие данные в
# публичный репозиторий не попадают ни при какой ошибке.
#
# Логи: /tmp/spa_director_server.log (свой, не общий).
exec /Users/yuriikulieshov/miniconda3/bin/python3 \
    /Users/yuriikulieshov/Documents/SPA_Claude/scripts/cartographer/director_server.py \
    --root /Users/yuriikulieshov/studio-os-serve/director \
    --port 8788 \
    >> /tmp/spa_director_server.log 2>&1
