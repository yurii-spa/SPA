#!/bin/bash
# scripts/agent_director_server.sh — launchd-обёртка для com.spa.director_server.
#
# ЧТО ЭТО. Минимальная раздача закрытого кокпита: ТОЛЬКО 127.0.0.1, ТОЛЬКО три файла из
# таблицы адресов, ТОЛЬКО GET/HEAD. Наружу ведёт существующий туннель Cloudflare, а не сокет.
#
# ЦЕЛЬ ОБЪЯВЛЕНА ЯВНО (RUN_SCRIPT ниже). Без объявления статический зонд отказывает
# fail-CLOSED: «это python-агент, но цель не разрешается». Отказ верный — проверять
# нечего, если цель известна только внутри строки exec. Объявление делает обёртку
# проверяемой БЕЗ запуска, а для долгожителя это единственный допустимый способ.
#
# ПОЧЕМУ НЕ agent_template.sh. Шаблон рассчитан на завершающийся шаг: он зовёт code_sync
# и выходит. Эта служба — долгожитель (KeepAlive); правило доставки запрещает пробный
# запуск долгожителя, а свежесть кода сюда приносит перезапуск службы, не обёртка.
#
# ПОЧЕМУ ПУТЬ И ПОРТ ЗАШИТЫ. Ни одного значения из окружения: launchd не наследует
# оболочку, и «${DIR}» превратилось бы в пустую строку, то есть в раздачу текущего
# каталога. Расширения пути оболочкой в исполняемой части нет вовсе.
#
# КОРЕНЬ РАЗДАЧИ ВНЕ РЕПОЗИТОРИЯ намеренно: сгенерированные владельческие данные в
# публичный репозиторий не попадают ни при какой ошибке.
#
# Логи: /tmp/spa_director_server.log
RUN_SCRIPT="/Users/yuriikulieshov/Documents/SPA_Claude/scripts/cartographer/director_server.py"
SERVE_ROOT="/Users/yuriikulieshov/studio-os-serve/director"
PORT="8788"

exec /Users/yuriikulieshov/miniconda3/bin/python3 \
    "$RUN_SCRIPT" --root "$SERVE_ROOT" --port "$PORT" \
    >> /tmp/spa_director_server.log 2>&1
