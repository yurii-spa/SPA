@dataclass
class EnumCall:
    """Один перечисляющий зов: где стои́т, что перечисляет, как разобран.

    ГЛОБ хранится рядом с каталогом, потому что без него каталог отвечает лишь
    на половину вопроса. `X.glob("INDEX-archive-*.md")` зависит не от НАБОРА
    каталога, а от набора ИМЁН, глобу удовлетворяющих, и зонд с чужим именем
    растит первое, не растя второго (см. PATTERN_UNMEASURED).
    """
    lineno: int
    attr: str
    kind: str
    rel_dir: str | None = None     # repo-relative каталог, когда разобран
    reason: str = ""               # почему именно этот ярлык
    # `None` = перечисление БЕЗ глоба (`iterdir`/`listdir`/`walk`): набор растит
    # ЛЮБОЕ имя. Непустая `pattern_note` = глоб ЕСТЬ и НЕ РАЗОБРАН (третий исход).
    pattern: str | None = None
    pattern_note: str = ""


@dataclass
class FileEntry:
    path: str                      # repo-relative путь тест-файла
    calls: list[EnumCall] = field(default_factory=list)

    @property
    def kind(self) -> str:
        """Ярлык ФАЙЛА: ошибаемся в сторону БОЛЬШЕЙ поверхности (см. докстринг)."""
        kinds = {c.kind for c in self.calls}
        if SOURCE_DIR in kinds:
            return SOURCE_DIR
        if UNRESOLVED in kinds:
            return UNRESOLVED
        if STATE_DIR in kinds:
            return STATE_DIR
        return SANDBOX

    @property
    def source_dirs(self) -> list[str]:
        out: list[str] = []
        for c in self.calls:
            if c.kind == SOURCE_DIR and c.rel_dir and c.rel_dir not in out:
                out.append(c.rel_dir)
        return out

    def dir_patterns(self, rel_dir: str) -> tuple[list[str | None], list[str]]:
        """Глобы, которыми перечисляется ЭТОТ каталог, и причины неразобранных.

        `None` в перечне глобов означает «перечисление без глоба», то есть
        набор растит любое имя. Неразобранный глоб уходит ВТОРЫМ списком и
        остаётся НАЗВАННОЙ причиной: молча считать его «любым именем» значило бы
        подставить самый выгодный ответ вместо измеренного (инв. #17).
        """
        pats: list[str | None] = []
        notes: list[str] = []
        for c in self.calls:
            if c.kind != SOURCE_DIR or c.rel_dir != rel_dir:
                continue
            if c.pattern_note:
                note = f"{self.path}:{c.lineno} `{c.attr}` — {c.pattern_note}"
                if note not in notes:
                    notes.append(note)
            elif c.pattern not in pats:
                pats.append(c.pattern)
        return pats, notes

    def dir_origin(self, rel_dir: str) -> str:
        """ОТКУДА у файла взялся этот каталог: ДОГАДКА или НАБЛЮДЕНИЕ.

        Половина хопа `_helper_calls` ставит каталог, который ИМЕНУЕТ тест, на
        зов помощника, перечисляющего каталог ИЗ АРГУМЕНТА, — и сама же говорит
        вслух: «названный каталог может и не дойти до помощника, и тогда член
        предмета окажется лишним кандидатом». Это ВЕРНО для поверхности (ошибка
        в сторону большей) и НЕВЕРНО для вердикта дифференциала: зонд ложится в
        каталог, которого сторож может не судить вовсе, и «вердикт тот же»
        становится ответом о КАТАЛОГЕ, а не о стороже.

        Замер #1612 на ИЗВЕСТНОМ ЧЛЕНЕ: `test_adr_index_titles` (ADR-889,
        колонка реестра решений) несёт РОВНО ОДИН разобранный каталог —
        `docs/journal`, — а членство его класса стои́т на `docs/decisions`.
        Дифференциал подложил файл в `docs/journal`, вердикт не сдвинулся, и
        прибор объявил известного члена «не предметом». Форма, потерявшая
        известного члена, ОПРОВЕРГНУТА, а не подкручена.
        """
        origins = {ORIGIN_GUESS if "по аргументу" in (c.reason or "") else ORIGIN_OBSERVED
                   for c in self.calls
                   if c.kind == SOURCE_DIR and c.rel_dir == rel_dir}
        # Наблюдение ПЕРЕБИВАЕТ догадку: если тот же каталог у файла есть и
        # прямым зовом, зонд ляжет туда, куда сторож действительно смотрит.
        return ORIGIN_OBSERVED if ORIGIN_OBSERVED in origins else ORIGIN_GUESS


def _is_pytest_fixture(node: ast.AST) -> bool:
    """Функция объявлена фикстурой pytest.

    Спрашивается ДЕКОРАТОР, а не имя: «похоже на фикстуру по имени» — ровно
    та мерка по соглашению об имени, которую положительный контроль реестра
    опроверг у переписи дверей доставки (ADR-1127, п. 4а заказа G1101).
    """
    for dec in getattr(node, "decorator_list", ()):
        target = dec.func if isinstance(dec, ast.Call) else dec
        name = (target.attr if isinstance(target, ast.Attribute)
                else getattr(target, "id", None))
        if name == "fixture":
            return True
    return False


class _PathResolver:
    """Прослеживает выражение пути по привязкам ОДНОГО модуля.

    Привязкой считается `Name = <выражение>` на любом уровне (модуль, класс,
    функция). Контейнер привязкой НЕ является — тот же выбор, что у
    `_injected_clock` (§ «Время в тестах» правила доставки): считать «RHS
    содержит имя» происхождением значило бы оправдать ложную привязку.
    """

    def __init__(self, tree: ast.AST, self_rel: pathlib.PurePosixPath) -> None:
        self._bind: dict[str, ast.expr] = {}
        self._attr: dict[str, ast.expr] = {}     # `self.<имя> = …`
        self.aliases: set[str] = set()           # `import ast as _ast`
        # ── вход ОДНОГО ХОПА ЧЕРЕЗ ПАРАМЕТР (ADR-1129) ──────────────────────
        # Карта «ребёнок → родитель» нужна ровно для одного вопроса: какая
        # функция ОБЪЕМЛЕТ перечисляющий зов. Без неё параметр пришлось бы
        # искать «есть ли в модуле функция с таким аргументом», а это та же
        # подмена, что «RHS содержит имя» в § «Время в тестах»: в замере 28.11
        # имя `data_dir` было параметром ШЕСТНАДЦАТИ функций одного файла.
        self._parent: dict[ast.AST, ast.AST] = {}
        self._funcs: dict[str, list[ast.AST]] = {}
        self._fixtures: dict[str, ast.AST] = {}
        self._scope: tuple = ()                  # объемлющие функции зова
        for node in ast.walk(tree):
            for child in ast.iter_child_nodes(node):
                self._parent[child] = node
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                self._funcs.setdefault(node.name, []).append(node)
                if _is_pytest_fixture(node):
                    # Одноимённых фикстур две ⇒ вопрос о значении неоднозначен,
                    # и первая ПЕРЕСТАЁТ быть ответом: держим None-маркер.
                    self._fixtures[node.name] = (
                        None if node.name in self._fixtures else node)
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign):
                for tgt in node.targets:
                    if isinstance(tgt, ast.Name):
                        self._bind.setdefault(tgt.id, node.value)
                    elif (isinstance(tgt, ast.Attribute) and isinstance(tgt.value, ast.Name)
                          and tgt.value.id in {"self", "cls"}):
                        self._attr.setdefault(tgt.attr, node.value)
            elif isinstance(node, ast.AnnAssign) and node.value is not None:
                if isinstance(node.target, ast.Name):
                    self._bind.setdefault(node.target.id, node.value)
                elif (isinstance(node.target, ast.Attribute) and isinstance(node.target.value, ast.Name)
                      and node.target.value.id in {"self", "cls"}):
                    self._attr.setdefault(node.target.attr, node.value)
            elif isinstance(node, ast.Import):
                # `import ast as _ast` — тот же не-путь под другим именем.
                # Без этого 20 зовов `_ast.walk`/`pyast.walk` числились
                # неразобранными путями, а путями они не были вовсе.
                for alias in node.names:
                    if alias.name in NON_PATH_RECEIVERS and alias.asname:
                        self.aliases.add(alias.asname)
            elif isinstance(node, ast.With):
                # `with tempfile.TemporaryDirectory() as td:` — настоящая привязка,
                # и без неё 69 имён (`td`, `tmp`, `d`) читались как неразобранные.
                for item in node.items:
                    if isinstance(item.optional_vars, ast.Name):
                        self._bind.setdefault(item.optional_vars.id, item.context_expr)
        self._self_rel = self_rel
        self._tree = tree

    # ── вход ────────────────────────────────────────────────────────────────
    def bindings(self) -> dict[str, ast.expr]:
        """Привязки модуля — читает поиск помощников, своей копии у него нет."""
        return self._bind

    def as_rel_public(self, expr: ast.expr) -> pathlib.PurePosixPath | None:
        """Разбор пути БЕЗ классификации: нужен поиску помощников по `.py`."""
        return self._as_rel(expr, depth=0)

    def resolve(self, expr: ast.expr,
                at: ast.AST | None = None) -> tuple[str, str | None, str]:
        """→ (ярлык, repo-relative каталог или None, причина).

        `at` — УЗЕЛ ЗОВА, а не выражение пути: по нему берутся объемлющие
        функции, и только они дают право на хоп через параметр. Умолчание
        `None` оставляет прибор таким, каким он был до ADR-1129 (хопа нет),
        поэтому «параметр разобран» и «параметр не спрошен» различимы.
        """
        self._scope = self._enclosing_funcs(at) if at is not None else ()
        try:
            rel = self._as_rel(expr, depth=0)
        except _Sandbox as exc:
            return SANDBOX, None, str(exc)
        except _Unresolved as exc:
            return UNRESOLVED, None, str(exc)
        if rel is None:
            return UNRESOLVED, None, f"путь не привязан к корню репозитория: {_unparse(expr)[:90]}"
        parts = rel.parts
        if parts and parts[0] in STATE_PREFIXES:
            return STATE_DIR, str(rel), f"каталог состояния (`{parts[0]}/`), доставкой кода не растёт"
        return SOURCE_DIR, str(rel), "каталог исходников репозитория"

    # ── рекурсивный разбор ──────────────────────────────────────────────────
    def _as_rel(self, expr: ast.expr, depth: int) -> pathlib.PurePosixPath | None:
        if depth > 12:
            raise _Unresolved("разбор не сошёлся за 12 шагов (циклическая привязка?)")

        # Признак одноразовой сцены спрашивается НА КАЖДОМ шаге, а не только у
        # исходного выражения: `with tempfile.TemporaryDirectory() as td` даёт
        # получателя `td`, и в ЕГО тексте маркера нет — маркер живёт в привязке.
        # Первая редакция спрашивала один раз и записала 130 таких зовов в
        # «НЕ РАЗОБРАН», то есть завысила вилку на разобранном материале.
        text = _unparse(expr)
        for marker in SANDBOX_MARKERS:
            if marker in text:
                raise _Sandbox(f"одноразовая сцена: в выражении «{marker}»")

        # ── `<левое> / "сегмент"` ──
        if isinstance(expr, ast.BinOp) and isinstance(expr.op, ast.Div):
            left = self._as_rel(expr.left, depth + 1)
            seg = _str_const(expr.right)
            if seg is None:
                raise _Unresolved(f"сегмент пути не литерал: {_unparse(expr.right)[:70]}")
            if left is None:
                raise _Unresolved(f"левая часть пути не привязана: {_unparse(expr.left)[:70]}")
            if seg.startswith("/"):
                raise _Unresolved(f"абсолютный сегмент вне репозитория: {seg}")
            return left / seg

        # ── имя: идём по привязке ──
        if isinstance(expr, ast.Name):
            if expr.id in PYTEST_TMP_FIXTURES:
                raise _Sandbox(f"фикстура pytest `{expr.id}` — одноразовый каталог харнесса")
            bound = self._bind.get(expr.id)
            if bound is None:
                # ОДИН ХОП ЧЕРЕЗ ПАРАМЕТР: имя может быть аргументом объемлющей
                # функции, и тогда его значение назначает ВЫЗЫВАЮЩИЙ. Хоп сам
                # отказывает с НАЗВАННОЙ причиной, если ответа нет.
                return self._param_hop(expr.id, depth)
            return self._as_rel(bound, depth + 1)

        # ── `Path(__file__)` и его якоря ──
        if isinstance(expr, ast.Call):
            return self._call_as_rel(expr, depth)

        # ── `X.parent` / `X.parents[N]` / `self.<имя>` ──
        if isinstance(expr, ast.Attribute):
            if expr.attr == "parent":
                base = self._as_rel(expr.value, depth + 1)
                return _up(base, 1)
            if isinstance(expr.value, ast.Name) and expr.value.id in {"self", "cls"}:
                bound = self._attr.get(expr.attr)
                if bound is None:
                    raise _Unresolved(f"`self.{expr.attr}` в модуле не присваивается")
                return self._as_rel(bound, depth + 1)
            if expr.attr == "name":
                # `X.name` у `TemporaryDirectory()` ЕСТЬ путь каталога (а у
                # `Path` это строка-имя, перечислять которую нечем). Спрашиваем
                # ПОЛУЧАТЕЛЯ: сцена ответит `_Sandbox`, и это ОТВЕТ. 75 зовов
                # шли через эту форму и числились неразобранными.
                self._as_rel(expr.value, depth + 1)
                raise _Unresolved("`.name` у получателя, который сценой не оказался")
            raise _Unresolved(f"неизвестное свойство пути `.{expr.attr}`")

        if isinstance(expr, ast.Subscript):
            # `X.parents[N]`
            if isinstance(expr.value, ast.Attribute) and expr.value.attr == "parents":
                n = _int_const(expr.slice)
                if n is None:
                    raise _Unresolved(f"индекс `parents[...]` не литерал: {_unparse(expr.slice)[:50]}")
                base = self._as_rel(expr.value.value, depth + 1)
                return _up(base, n + 1)
            raise _Unresolved(f"индексация не по `parents`: {_unparse(expr)[:70]}")

        if isinstance(expr, ast.Constant) and isinstance(expr.value, str):
            s = expr.value
            if s.startswith("/"):
                raise _Unresolved(f"абсолютный литерал вне репозитория: {s[:60]}")
            # Относительный литерал зависит от cwd прогона — это НЕ разобрано.
            raise _Unresolved(f"относительный литерал зависит от cwd: {s[:60]}")

        raise _Unresolved(f"форма выражения не разбирается: {type(expr).__name__}")

    # ── ОДИН ХОП ЧЕРЕЗ ПАРАМЕТР (ADR-1129) ──────────────────────────────────
    #
    # ЗАМЕР, РАДИ КОТОРОГО ДВЕРЬ ПОСТАВЛЕНА (28.11, цикл #1275, заказ G1101
    # п. 2 направление 3). Третий исход переписи — 106 файлов «путь сторожа
    # прибором НЕ РАЗОБРАН», и верхний край вилки предмета (265 … 371) держали
    # именно они. Форма причины у 52 из 106 одна: «имя `X` в модуле не
    # привязано», а 78 её зовов разложились так:
    #
    #     64  имя есть ПАРАМЕТР объемлющей функции
    #      8  распаковка кортежа
    #      4  цель цикла `for`
    #      2  не найдено нигде
    #
    # То есть дверь у класса ОДНА и она названа: значение параметра назначает
    # не модуль, а ВЫЗЫВАЮЩИЙ (или фикстура pytest того же имени).
    #
    # ТРИ ИСТОЧНИКА, И НИ ОДИН НЕ СТАРШЕ ДРУГОГО. Ответы собираются со ВСЕХ
    # трёх и СВЕРЯЮТСЯ: расхождение есть `unresolved` с названным расхождением,
    # а не «возьму первый». Старшинство источника молча выбрало бы одну из двух
    # несогласных правд — это та же подмена, что «первый зов `ps` победил».
    #
    #     фикстура   в модуле есть `@pytest.fixture` РОВНО этого имени
    #     умолчание  у параметра объявлено значение по умолчанию
    #     зовы       все зовы объемлющей функции в ЭТОМ модуле
    #
    # ХОП ОДИН НАМЕРЕННО, и граница ИЗМЕРЕНА, а не объявлена: аргумент зова,
    # сам являющийся параметром, получает `unresolved` со СВОЕЙ причиной
    # («аргумент зова сам есть параметр — второй хоп не делается»), поэтому
    # население за границей одного хопа ВИДНО в выводе, а не выдано за ноль.
    def _enclosing_funcs(self, node: ast.AST) -> tuple:
        """Объемлющие функции зова, от ВНУТРЕННЕЙ к внешней."""
        out = []
        cur = self._parent.get(node)
        while cur is not None:
            if isinstance(cur, (ast.FunctionDef, ast.AsyncFunctionDef)):
                out.append(cur)
            cur = self._parent.get(cur)
        return tuple(out)

    @staticmethod
    def _param_slot(owner: ast.AST, name: str) -> tuple[int | None, ast.expr | None]:
        """→ (позиция среди позиционных или None, выражение умолчания или None).

        Позиция спрашивается у СИГНАТУРЫ: «имя встречается в аргументах зова»
        привязкой не является (§ «Время в тестах»: контейнер привязкой не
        является). `None` в умолчании — не значение, а его отсутствие.
        """
        pos = list(owner.args.posonlyargs) + list(owner.args.args)
        names = [a.arg for a in pos]
        default = None
        if name in names:
            tail = names[len(names) - len(owner.args.defaults):] if owner.args.defaults else []
            if name in tail:
                default = owner.args.defaults[tail.index(name)]
            idx = names.index(name)
        elif name in [a.arg for a in owner.args.kwonlyargs]:
            k = [a.arg for a in owner.args.kwonlyargs].index(name)
            default = owner.args.kw_defaults[k]
            idx = None
        else:
            return None, None
        if isinstance(default, ast.Constant) and default.value is None:
            default = None                     # объявленное «ничего» значением не является
        return idx, default

    def _owns(self, owner: ast.AST, name: str) -> bool:
        pos = [a.arg for a in list(owner.args.posonlyargs) + list(owner.args.args)]
        return name in pos or name in [a.arg for a in owner.args.kwonlyargs]

    def _caller_args(self, owner: ast.AST, name: str, idx: int | None) -> list[ast.expr]:
        """Выражения, которые зовы ЭТОГО модуля подставляют параметру."""
        pos = [a.arg for a in list(owner.args.posonlyargs) + list(owner.args.args)]
        bound_self = bool(pos) and pos[0] in {"self", "cls"}
        out: list[ast.expr] = []
        for node in ast.walk(self._tree):
            if not isinstance(node, ast.Call):
                continue
            func = node.func
            called = (func.attr if isinstance(func, ast.Attribute)
                      else getattr(func, "id", None))
            if called != owner.name:
                continue
            got = None
            for kw in node.keywords:
                if kw.arg == name:
                    got = kw.value
            if got is None and idx is not None:
                # `self.f(a)` съедает первый позиционный — смещение спрашивается
                # у ФОРМЫ зова, а не угадывается по имени метода.
                off = 1 if (bound_self and isinstance(func, ast.Attribute)) else 0
                at = idx - off
                if 0 <= at < len(node.args):
                    got = node.args[at]
            if got is not None:
                out.append(got)
        return out

    def _fixture_value(self, node: ast.AST) -> ast.expr:
        """Единственное возвращаемое фикстурой выражение, иначе отказ."""
        seen: dict[str, ast.expr] = {}
        for sub in ast.walk(node):
            if isinstance(sub, ast.Return) and sub.value is not None:
                seen[_unparse(sub.value)] = sub.value
            elif isinstance(sub, ast.Yield) and sub.value is not None:
                seen[_unparse(sub.value)] = sub.value
        if not seen:
            raise _Unresolved(f"фикстура `{node.name}` ничего не возвращает")
        if len(seen) > 1:
            raise _Unresolved(
                f"фикстура `{node.name}` возвращает {len(seen)} разных выражений")
        return next(iter(seen.values()))

    @staticmethod
    def _verdict_key(kind: str, payload: object) -> str:
        """Ключ СОГЛАСИЯ — ВЕРДИКТ, а не текст причины.

        Две одноразовые сцены объясняются разными словами (`tmp_path` против
        `TemporaryDirectory`), и ключ по тексту объявил бы их расхождением —
        то есть отказал бы там, где оба источника говорят ОДНО И ТО ЖЕ. Для
        разобранного пути ключ несёт сам путь: `scripts` и `docs` расхождение.
        """
        return kind if kind == SANDBOX else f"{kind}:{payload}"

    def _probe(self, expr: ast.expr, depth: int) -> tuple[str, object]:
        """Разбор КАНДИДАТА без второго хопа: область зова снимается.

        ⚠️ Снятие области здесь ВЕРНО ПО ПОСТРОЕНИЮ и НЕНАБЛЮДАЕМО, и это
        ЗАМЕР, а не оговорка. Мутация «область сохраняется» (M15 спецификации
        ADR-1129) — единственная из двадцати, которую не убила ни одна сцена;
        прогон полной поверхности с ней дал на **2628** настоящих файлах
        **0** файлов с другим вердиктом и **0** зовов с другой причиной.
        Причина: `self._scope` есть цепочка функций, объемлющих ПЕРЕЧИСЛЯЮЩИЙ
        зов, а кандидат (аргумент вызывающего, умолчание, возврат фикстуры)
        живёт в ДРУГОЙ лексической области — пересечься они могут только на
        самом хопаемом имени, а этот путь перехвачен проверкой ниже. Мутант
        записан ЭКВИВАЛЕНТНЫМ; выдумывать ему сцену значило бы подогнать
        число под круглое (урок цикла #1217).
        """
        keep = self._scope
        self._scope = ()
        try:
            rel = self._as_rel(expr, depth + 1)
        except _Sandbox as exc:
            return SANDBOX, str(exc)
        except _Unresolved as exc:
            return UNRESOLVED, str(exc)
        finally:
            self._scope = keep
        if rel is None:
            return UNRESOLVED, "кандидат не привязан к корню репозитория"
        return SOURCE_DIR, rel

    def _param_hop(self, name: str, depth: int) -> pathlib.PurePosixPath | None:
        # Объемлющая функция берётся САМАЯ ВНУТРЕННЯЯ из владеющих именем:
        # замыкание внутри теста объявляет своё `where`, и ответ внешней
        # области был бы ответом о ДРУГОМ значении того же имени.
        #
        # Защиты «от самоповтора хопа» здесь НЕТ намеренно: `_probe` снимает
        # область зова, поэтому второго хопа не бывает ПО ПОСТРОЕНИЮ, а
        # ветвление, которого не видела ни одна сцена, есть украшение
        # (`.claude/rules/deployment.md` § «Проверка сторожа сторожей»).
        owner = next((f for f in self._scope if self._owns(f, name)), None)
        if owner is None:
            raise _Unresolved(
                f"имя `{name}` в модуле не привязано (параметр/фикстура/импорт)")
        if len(self._funcs.get(owner.name, ())) > 1:
            raise _Unresolved(
                f"имя функции `{owner.name}` в модуле не единственно — "
                f"чьи зовы подставляют `{name}`, НЕ ИЗМЕРЕНО")
        idx, default = self._param_slot(owner, name)
        answers: dict[str, object] = {}
        causes: list[str] = []

        # Зовы спрашиваются ПЕРВЫМИ не из старшинства, а ради ПРИМЕНИМОСТИ
        # следующего источника: pytest внедряет фикстуру в параметр, который
        # сам не подставлен зовом, и у помощника, зовомого руками, фикстура
        # источником не является ВОВСЕ. Замер 28.11 (сцена `inner_scope_wins`)
        # нашёл это дефектом двери: замыкание `def _dirs(where)` внутри
        # `def test_x(where)` получало ОБА источника и уходило в «РАСХОДЯТСЯ»,
        # то есть дверь отказывала там, где ответ был один.
        args = self._caller_args(owner, name, idx)
        if not args:
            causes.append(f"зовов `{owner.name}` с аргументом `{name}` в модуле нет")
            fixture = self._fixtures.get(name, "absent")
            if fixture is None:
                causes.append(f"одноимённых фикстур `{name}` в модуле больше одной")
            elif fixture != "absent":
                try:
                    kind, payload = self._probe(self._fixture_value(fixture), depth)
                except _Unresolved as exc:
                    kind, payload = UNRESOLVED, str(exc)
                if kind == UNRESOLVED:
                    causes.append(f"фикстура: {payload}")
                else:
                    answers[self._verdict_key(kind, payload)] = (kind, payload)

        if default is not None:
            kind, payload = self._probe(default, depth)
            if kind == UNRESOLVED:
                causes.append(f"умолчание: {payload}")
            else:
                answers[self._verdict_key(kind, payload)] = (kind, payload)

        for arg in args:
            if (isinstance(arg, ast.Name) and arg.id not in self._bind
                    and arg.id not in PYTEST_TMP_FIXTURES):
                causes.append(
                    f"аргумент `{arg.id}` зова сам есть параметр — "
                    f"второй хоп не делается")
                continue
            kind, payload = self._probe(arg, depth)
            if kind == UNRESOLVED:
                causes.append(f"зов: {payload}")
            else:
                answers[self._verdict_key(kind, payload)] = (kind, payload)

        if not answers:
            why = "; ".join(dict.fromkeys(causes)) or "источников значения не нашлось"
            raise _Unresolved(f"параметр `{name}` ({owner.name}): {why}")
        if len(answers) > 1:
            named = ", ".join(sorted(answers))
            raise _Unresolved(
                f"параметр `{name}` ({owner.name}): источники РАСХОДЯТСЯ — {named}")
        kind, payload = next(iter(answers.values()))
        if kind == SANDBOX:
            raise _Sandbox(
                f"параметр `{name}` ({owner.name}) ведёт в одноразовую сцену: {payload}")
        return payload

    def _call_as_rel(self, call: ast.Call, depth: int) -> pathlib.PurePosixPath | None:
        func = call.func
        # `X.resolve()` / `X.absolute()` — путь не меняют
        if isinstance(func, ast.Attribute) and func.attr in {"resolve", "absolute", "expanduser"}:
            return self._as_rel(func.value, depth + 1)
        # `os.path.dirname(X)` — то же, что `.parent`
        if isinstance(func, ast.Attribute) and func.attr == "dirname" and call.args:
            return _up(self._as_rel(call.args[0], depth + 1), 1)
        # `str(X)` / `os.fspath(X)` — обёртки, путь не меняют
        if isinstance(func, ast.Name) and func.id == "str" and len(call.args) == 1:
            return self._as_rel(call.args[0], depth + 1)
        if isinstance(func, ast.Attribute) and func.attr == "fspath" and len(call.args) == 1:
            return self._as_rel(call.args[0], depth + 1)
        # `X.joinpath("a", "b")`
        if isinstance(func, ast.Attribute) and func.attr == "joinpath":
            base = self._as_rel(func.value, depth + 1)
            if base is None:
                raise _Unresolved("joinpath: основание не привязано")
            for a in call.args:
                seg = _str_const(a)
                if seg is None:
                    raise _Unresolved(f"joinpath: сегмент не литерал: {_unparse(a)[:60]}")
                base = base / seg
            return base
        # `os.path.join(a, b)`
        if isinstance(func, ast.Attribute) and func.attr == "join":
            if not call.args:
                raise _Unresolved("join без аргументов")
            base = self._as_rel(call.args[0], depth + 1)
            if base is None:
                raise _Unresolved("join: основание не привязано")
            for a in call.args[1:]:
                seg = _str_const(a)
                if seg is None:
                    raise _Unresolved(f"join: сегмент не литерал: {_unparse(a)[:60]}")
                base = base / seg
            return base
        # `Path(...)` / `pathlib.Path(...)`
        name = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", None)
        if name == "Path":
            if len(call.args) != 1:
                raise _Unresolved(f"Path() с {len(call.args)} аргументами не разбирается")
            arg = call.args[0]
            if isinstance(arg, ast.Name) and arg.id == "__file__":
                return self._self_rel           # САМ тест-файл, repo-relative
            return self._as_rel(arg, depth + 1)
        raise _Unresolved(f"зов не является построением пути: {_unparse(call)[:70]}")


class _Unresolved(RuntimeError):
    """Путь не разобран — несёт НАЗВАННУЮ причину."""


class _Sandbox(RuntimeError):
    """Путь разобран и ведёт в одноразовую сцену — это ОТВЕТ, а не отказ."""


def _up(base: pathlib.PurePosixPath | None, n: int) -> pathlib.PurePosixPath:
    if base is None:
        raise _Unresolved("подъём по дереву от непривязанного основания")
    cur = base
    for _ in range(n):
        if str(cur) in {".", ""}:
            raise _Unresolved("подъём выше корня репозитория")
        cur = cur.parent
    return cur


def _str_const(expr: ast.expr) -> str | None:
    if isinstance(expr, ast.Constant) and isinstance(expr.value, str):
        return expr.value
    return None


def _int_const(expr: ast.expr) -> int | None:
    if isinstance(expr, ast.Constant) and isinstance(expr.value, int):
        return expr.value
    return None


def _unparse(expr: ast.AST) -> str:
    try:
        return ast.unparse(expr)
    except Exception:                                    # pragma: no cover - защита формы
        return f"<{type(expr).__name__}>"


