def render_surface(s: Surface, *, names: bool = False) -> str:
    c = s.counts
    lines = [
        f"ПОВЕРХНОСТЬ класса «производный артефакт уехал без перемера» (дерево {s.root}):",
        f"  `spa_core/tests/test_*.py` всего: {s.tests_total}",
        f"  из них несут перечисляющий зов: {len(s.entries)}",
        f"  ├─ ПРЕДМЕТ (каталог ИСХОДНИКОВ): {c[SOURCE_DIR]}",
        f"  ├─ каталог состояния `data/`:     {c[STATE_DIR]}",
        f"  ├─ одноразовая сцена:             {c[SANDBOX]}",
        f"  └─ НЕ РАЗОБРАН (третий исход):    {c[UNRESOLVED]}",
    ]
    if c[UNRESOLVED]:
        lines.append("  ⚠️ НЕ РАЗОБРАННОЕ нулём не считается: население предмета есть ВИЛКА")
        lines.append(f"     {c[SOURCE_DIR]} … {c[SOURCE_DIR] + c[UNRESOLVED]}")
    lost = s.lost_known_members
    if lost:
        lines.append("  ⛔ ФОРМА ОПРОВЕРГНУТА: известный член класса ВНЕ предмета —")
        for p, why in lost.items():
            lines.append(f"       {p} ({why})")
        lines.append("     число предмета НЕ ПЕЧАТАЕТСЯ как население класса (код 2)")
    else:
        lines.append(f"  ✅ все {len(KNOWN_MEMBERS)} известных члена класса ВНУТРИ предмета "
                     "(положительный контроль поверхности)")
    if names:
        lines.append("")
        lines.append("ПРЕДМЕТ ПОИМЁННО:")
        for e in s.subject:
            lines.append(f"  • {e.path} → {', '.join(e.source_dirs)}")
    return "\n".join(lines)


def render_differential(d: Differential) -> str:
    c = d.counts
    lines = [
        f"ДИФФЕРЕНЦИАЛ (дерево {d.root}): подложен новый публичный файл в САМ перечисляемый каталог",
        f"  ПРЕДМЕТ КЛАССА (зелёный стал НЕ зелёным): {c[SUBJECT]}",
        f"  зависит от набора, но ЗЕЛЕН:        {c[SET_DEPENDENT_GREEN]}",
        f"  КРАСЕН ДО подкладывания:            {c[ALREADY_RED]}",
        f"  не предмет (ОБА зонда вердикта не сдвинули): {c[NOT_SUBJECT]}",
        f"  НЕ ИЗМЕРЕНО:                       {c[DIFF_UNMEASURED]}",
        f"  НЕ ИЗМЕРЕНО содержательным зондом: {c[COPY_UNMEASURED]}",
        f"  НЕ ИЗМЕРЕНО: каталог записи — ДОГАДКА поверхности: {c[GUESSED_DIR_UNMEASURED]}",
        f"  НЕ ИЗМЕРЕНО: имя зонда под ГЛОБ перечисления не синтезируется: "
        f"{c[PATTERN_UNMEASURED]}",
        # ── ГРАНИЦА ДИФФЕРЕНЦИАЛА ПЕЧАТАЕТСЯ, а не живёт в прозе ────────────
        # Иначе читатель примет «не предмет» за ответ о классе там, где зонд
        # ответить не способен ПО ПОСТРОЕНИЮ (замер #1259, см. PLANTED_INERT).
        f"  ⚠️ ЗОНД ИНЕРТЕН: {PLANTED_INERT}",
        # С цикла #1612 граница не только НАЗВАНА, но и СПРОШЕНА у каждой
        # записи-кандидата: «не предмет» ставится лишь когда вердикта не сдвинул
        # И содержательный зонд (копия существующего члена каталога под новым
        # именем), а «донора нет» есть ТРЕТИЙ исход с названной причиной.
        f"  ✅ граница СПРОШЕНА у каждого кандидата в «не предмет»: второй зонд — "
        f"КОПИЯ существующего члена НАБОРА под новым именем (донор ≤ "
        f"{COPY_DONOR_MAX_BYTES} Б, выбор ПЕЧАТАЕТСЯ)",
        # ── ТРЕТЬЯ ГРАНИЦА: ИМЯ ЗОНДА ЕСТЬ ЧАСТЬ МЕРКИ ──────────────────────
        # Замер #15626 на известном члене ADR-889: каталог был назван ВЕРНО, а
        # зонд с фиксированным именем растил КАТАЛОГ и не растил НАБОРА
        # `INDEX-archive-*.md`. Поэтому имя диктует глоб, и «глоб без `*`» либо
        # «глоб с `[…]`» есть ТРЕТИЙ исход, а не «не предмет».
        f"  ✅ имя зонда ДИКТУЕТ глоб перечисления и СВЕРЯЕТСЯ с ним (`fnmatch`): "
        f"каталог и НАБОР, который сторож читает, — разные множества",
    ]
    refuted = d.refuted_known_members
    if refuted:
        lines.append("  ⛔ МЕРКА ОПРОВЕРГНУТА: известный член класса пришёл «не предметом» —")
        for path, why in refuted.items():
            lines.append(f"       {path} ({why})")
        lines.append("     число `ПРЕДМЕТ` есть НИЖНЯЯ ГРАНИЦА, а не сужение предмета (код 2)")
    else:
        lines.append(f"  ✅ ни один из {len(KNOWN_MEMBERS)} известных членов не пришёл "
                     "«не предметом» (положительный контроль ВЕРДИКТА)")
    for e in d.entries:
        if e.kind == SUBJECT:
            lines.append(f"  🔴 {e.path} ← {e.enumerated_dir}")
            lines.append(f"       было: {e.before}  →  стало: {e.after}")
        elif e.kind in (DIFF_UNMEASURED, COPY_UNMEASURED, GUESSED_DIR_UNMEASURED,
                        PATTERN_UNMEASURED):
            lines.append(f"  ⚠️ НЕ ИЗМЕРЕНО {e.path} ← {e.enumerated_dir}: {e.reason}")
        elif e.kind == NOT_SUBJECT:
            lines.append(f"  ⚪ не предмет {e.path} ← {e.enumerated_dir}: {e.reason}")
    if d.leftovers:
        lines.append("  ⛔ ПОДЛОЖЕННЫЙ ФАЙЛ НЕ СНЯТ — дерево грязное:")
        for item in d.leftovers:
            lines.append(f"       {item}")
    return "\n".join(lines)


