# тихим «не предмет». Три исхода различимы и здесь.
COPY_DONOR_MAX_BYTES = 200_000

COPY_UNMEASURED = "copy_unmeasured"   # донора нет либо копия не прочиталась

# Каталог у записи — ДОГАДКА поверхности, и «вердикт тот же» на нём есть ответ о
# КАТАЛОГЕ, а не о стороже (см. `FileEntry.dir_origin`). Третий исход, не ноль.
GUESSED_DIR_UNMEASURED = "guessed_dir_unmeasured"


def _copy_donor(target_dir: pathlib.Path, *,
                pattern: str | None = None) -> tuple[pathlib.Path | None, str]:
    """Донор второго зонда: СУЩЕСТВУЮЩИЙ член НАБОРА, принятый сторожем.

    Отбор ДЕТЕРМИНИРОВАН (первый по имени среди подходящих) — «выберу
    поинтереснее» было бы вкусом автора, а не меркой, и воспроизвести такой
    замер было бы нечем. Выбранный донор ПЕЧАТАЕТСЯ.

    Глоб перечисления ОТБИРАЕТ донора (замер #15626): «член каталога» и «член
    НАБОРА, который сторож читает» — разные множества, и у `docs/journal` они
    расходятся в сотни раз (набор `INDEX-archive-*.md` против всего каталога).
    Донор не из набора делал бы копию двойне бесполезной: ни имя, ни содержимое
    сторожа не касались бы.
    """
    pat = pattern
    while pat and pat.startswith("**/"):
        pat = pat[3:]
    cands: list[pathlib.Path] = []
    for child in sorted(target_dir.iterdir(), key=lambda q: q.name):
        if not child.is_file():
            continue
        if PLANTED_STEM in child.stem:
            continue            # свой же зонд донором быть не может
        if pat is not None:
            if not fnmatch.fnmatch(child.name, pat):
                continue
        elif child.suffix not in PLANTED_SUFFIXES:
            continue
        try:
            size = child.stat().st_size
        except OSError:
            continue
        if size == 0 or size > COPY_DONOR_MAX_BYTES:
            continue
        cands.append(child)
    if not cands:
        what = (f"удовлетворяющего глобу `{pattern}`" if pat is not None
                else f"с расширением {', '.join(PLANTED_SUFFIXES)}")
        return None, (f"в каталоге нет члена {what}, непустого и не крупнее "
                      f"{COPY_DONOR_MAX_BYTES} Б — содержательный зонд построить "
                      "НЕ ИЗ ЧЕГО")
    donor = cands[0]
    return donor, donor.name


@dataclass
class DiffEntry:
    path: str
    enumerated_dir: str
    kind: str
    before: str = ""
    after: str = ""
    reason: str = ""


@dataclass
class Differential:
    root: str
    entries: list[DiffEntry]
    leftovers: list[str] = field(default_factory=list)

    @property
    def counts(self) -> dict[str, int]:
        out = {SUBJECT: 0, SET_DEPENDENT_GREEN: 0, NOT_SUBJECT: 0,
               ALREADY_RED: 0, DIFF_UNMEASURED: 0, COPY_UNMEASURED: 0,
               GUESSED_DIR_UNMEASURED: 0, PATTERN_UNMEASURED: 0}
        for e in self.entries:
            out[e.kind] += 1
        return out

    @property
    def refuted_known_members(self) -> dict[str, str]:
        """Известные члены класса, которых дифференциал назвал «не предметом».

        ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ, зеркальный `Surface.lost_known_members`. У
        поверхности он стои́т с первой редакции прибора; у ВЕРДИКТА его не было —
        и замер #1612 показал, зачем он нужен: `test_adr_index_titles` (ADR-889)
        приходит `not_subject` при ОБОИХ зондах, потому что поверхность разобрала
        у него РОВНО ОДИН каталог — `docs/journal`, — а членство класса стои́т на
        `docs/decisions`. Каталог НАБЛЮДЁН (прямой зов), содержательный зонд
        отработал (копия `2026-W29.md`), и всё равно ответ неверен: зонд лёг не
        туда, куда смотрит сторож своего КЛАССА.

        Пока хоть один известный член приходит «не предметом», число `subject`
        есть НИЖНЯЯ ГРАНИЦА, а не сужение предмета, и прибор обязан сказать это
        вслух, а не отдать «предмет N» молча.
        """
        out: dict[str, str] = {}
        for e in self.entries:
            if e.kind == NOT_SUBJECT and e.path in KNOWN_MEMBERS:
                out[e.path] = KNOWN_MEMBERS[e.path]
        return out

    @property
    def code(self) -> int:
        if self.leftovers:
            return 2
        if self.refuted_known_members:
            return 2
        if (self.counts[DIFF_UNMEASURED] or self.counts[COPY_UNMEASURED]
                or self.counts[GUESSED_DIR_UNMEASURED]
                or self.counts[PATTERN_UNMEASURED]):
            return 2
        return 1 if self.counts[SUBJECT] else 0


def _verdict(root: pathlib.Path, rel_test: str, timeout: int) -> tuple[str, str]:
    """Вердикт ОДНОГО тест-файла: («passed=N,…» либо `unmeasured`, подробность).

    Переход в `skipped` меряется наравне с красным (урок #465): такой тест не
    краснеет и не проходит — он ИСЧЕЗАЕТ, и глазами это читается как порядок.
    """
    env = dict(os.environ, SPA_ENV="ci", PYTHONHASHSEED="0")
    cmd = [sys.executable, "-m", "pytest", rel_test, "-q", "--tb=no",
           "-p", "no:randomly", "--rootdir", str(root)]
    try:
        proc = subprocess.run(cmd, cwd=str(root), env=env, timeout=timeout,
                              capture_output=True, text=True)
    except subprocess.TimeoutExpired:
        return "unmeasured", f"прогон не дошёл до вердикта за {timeout} с"
    except OSError as exc:
        return "unmeasured", f"pytest не запущен: {exc}"
    out = proc.stdout + proc.stderr
    tail = [ln for ln in out.splitlines() if ln.strip()]
    summary = next((ln for ln in reversed(tail)
                    if (" passed" in ln or " failed" in ln or " error" in ln
                        or " skipped" in ln or "no tests ran" in ln)), "")
    if not summary:
        return "unmeasured", f"сводки pytest в выводе нет (код {proc.returncode})"
    # Состав вердикта, а не код возврата: код 1 бывает и у `error`, и у `failed`.
    parts = []
    for word in ("failed", "error", "errors", "passed", "skipped", "xfailed", "deselected"):
        import re
        m = re.search(rf"(\d+) {word}\b", summary)
        if m:
            parts.append(f"{word}={m.group(1)}")
    if "no tests ran" in summary:
        parts.append("collected=0")
    return (",".join(parts) or summary.strip()), summary.strip()


def _counts_of(verdict: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for part in verdict.split(","):
        if "=" in part:
            k, _, v = part.partition("=")
            try:
                out[k] = int(v)
            except ValueError:
                pass
    return out


def _classify(before: str, after: str) -> tuple[str, str]:
    """Ось вердикта: «зелёный стал НЕ зелёным» — и ТОЛЬКО это есть предмет.

    Первая редакция сличала СТРОКУ состава и записала в предмет три файла, у
    которых выросло только число `passed` (160→165, 127→129, 2875→2876). Это
    параметризованные по НАБОРУ сторожа, которые новый файл УВИДЕЛИ и приняли —
    то есть ровно противоположность класса. Мерка «строка изменилась» отвечала
    на вопрос «зависит ли вердикт от набора», а предмет класса — «КРАСНЕЕТ ли он
    от роста набора». Зависимость от набора сохранена отдельным ярлыком, потому
    что она сама по себе сведение полезное, а не шум.
    """
    b, a = _counts_of(before), _counts_of(after)
    bad_before = b.get("failed", 0) + b.get("error", 0) + b.get("errors", 0)
    bad_after = a.get("failed", 0) + a.get("error", 0) + a.get("errors", 0)
    # «Зелёный стал НЕ зелёным» требует, чтобы ДО он был ЗЕЛЁНЫМ. Первая редакция
    # спрашивала только `bad_after` и записала в предмет ПЯТЬ файлов, красных в
    # ОБА прогона: они зелёными не были, и подложенный файл их вердикта не менял
    # ни на байт (`failed=1,passed=47` → `failed=1,passed=47`). Красное ДО меня
    # членством в классе не является — это отдельный род, и он НАЗВАН.
    if bad_before:
        return ALREADY_RED, (f"красен ДО подкладывания (failed/error {bad_before}) — зелёным "
                             "не был, о зависимости от набора этот прогон не говорит ничего")
    if bad_after:
        return SUBJECT, (f"зелёный стал НЕ зелёным: failed/error {bad_after} — "
                         "сторож краснеет от роста набора своего каталога")
    if a.get("skipped", 0) > b.get("skipped", 0):
        return SUBJECT, ("вердикт ИСЧЕЗ в `skipped` (урок #465): тест не краснеет и не "
                         "проходит, и глазами это читается как порядок")
    if a.get("passed", 0) < b.get("passed", 0):
        return SUBJECT, "число пройденных УПАЛО: часть проверок перестала собираться"
    if before != after:
        return SET_DEPENDENT_GREEN, ("состав вырос и остался зелёным: сторож параметризован "
                                     "по набору и новый файл ПРИНЯЛ")
    return NOT_SUBJECT, "вердикт тот же"


def measure_differential(root: pathlib.Path, surface: Surface, *,
                         limit: int | None = None, timeout: int = 300,
                         only: list[str] | None = None) -> Differential:
    """Гоняет предмет поверхности ДВАЖДЫ: как есть и с подложенным файлом."""
    subject = surface.subject
    if only:
        wanted = set(only)
        subject = [e for e in subject if e.path in wanted or pathlib.PurePosixPath(e.path).name in wanted]
    if limit is not None:
        subject = subject[:limit]

    entries: list[DiffEntry] = []
    leftovers: list[str] = []
    total = len(subject)
    for i, entry in enumerate(subject, 1):
        # Долгий прогон ОБЯЗАН быть виден (`.claude/rules/deployment.md`
        # § «ОКНО МУТАЦИОННОГО ПРИБОРА» п. 8): полностью буферизованный вывод
        # делает «работает» и «умер» неразличимыми, и ровно эта неразличимость
        # пригласила неверное действие в аварии #906.
        print(f"[прибор] {i}/{total} {entry.path}", file=sys.stderr, flush=True)
        for rel_dir in entry.source_dirs:
            target_dir = root / rel_dir
            if not target_dir.is_dir():
                entries.append(DiffEntry(entry.path, rel_dir, DIFF_UNMEASURED,
                                         reason=f"перечисляемый каталог не существует в дереве: {rel_dir}"))
                continue
            before, before_line = _verdict(root, entry.path, timeout)
            if before == "unmeasured":
                entries.append(DiffEntry(entry.path, rel_dir, DIFF_UNMEASURED,
                                         before=before, reason=f"первый прогон: {before_line}"))
                continue
            # ── ИМЕНА ЗОНДОВ ДИКТУЕТ ГЛОБ ПЕРЕЧИСЛЕНИЯ ─────────────────────
            # Замер #15626: у известного члена ADR-889 каталог назван ВЕРНО, а
            # зонд с фиксированным именем растил каталог и не растил набора
            # `INDEX-archive-*.md`. Глоба нет вовсе ⇒ прежнее поведение (по
            # файлу на каждое расширение), и это ровно случай `iterdir`/`listdir`.
            pats, pat_notes = entry.dir_patterns(rel_dir)
            plant: list[tuple[str, str | None]] = []
            refused: list[str] = list(pat_notes)
            for pat in pats:
                names, why = _plant_names(pat, stem=PLANTED_STEM)
                if why:
                    refused.append(why)
                    continue
                for nm in names:
                    if nm not in [q for q, _ in plant]:
                        plant.append((nm, pat))
            if not plant:
                entries.append(DiffEntry(
                    entry.path, rel_dir, PATTERN_UNMEASURED,
                    reason="ни одного имени зонда, удовлетворяющего глобам "
                           "перечисления этого каталога: " + " · ".join(refused)))
                continue

            existing = [p for p in (target_dir / nm for nm, _ in plant) if p.exists()]
            if existing:
                # Измеренный случай (цикл #1218): убитый первый прогон оставил
                # подложенный файл в `landing/src/pages/admin`, и ВТОРОЙ прогон
                # честно отказал вместо того, чтобы судить о дереве с чужими
                # байтами. Это та же форма, что § «ОКНО МУТАЦИОННОГО ПРИБОРА»:
                # возврат живёт в `finally` и обеспечен для исключения, но НЕ для
                # смерти процесса. Несущая половина — запись на диске, и она ниже.
                entries.append(DiffEntry(entry.path, rel_dir, DIFF_UNMEASURED, before=before,
                                         reason="подкладываемое имя уже занято: "
                                                + ", ".join(p.name for p in existing)
                                                + " — наследство убитого прогона; снять "
                                                  "`--clean-planted` и перемерить"))
                continue
            # Один зонд на КАЖДОЕ расширение: вердикт берётся по ХУДШЕМУ исходу,
            # потому что сторож ключуется на своё расширение (см. PLANTED_SUFFIXES).
            probes: list[tuple[str, str, str]] = []
            for nm, _nm_pat in plant:
                planted = target_dir / nm
                sfx = planted.suffix
                try:
                    planted.write_text(PLANTED_BODY.get(sfx, PLANTED_TEXT), encoding="utf-8")
                    after, after_line = _verdict(root, entry.path, timeout)
                finally:
                    try:
                        planted.unlink()
                    except OSError as exc:
                        leftovers.append(f"{planted}: {exc}")
                    for pyc in (target_dir / "__pycache__").glob(f"*{PLANTED_STEM}*"):
                        try:
                            pyc.unlink()
                        except OSError:
                            pass
                probes.append((nm, after, after_line))

            unmeasured = [pr for pr in probes if pr[1] == "unmeasured"]
            # Глоб, который не разобрался, доехать ОБЯЗАН: запись с частью
            # зондов — ответ о ЧАСТИ набора, и молчание сделало бы её
            # неотличимой от полной (инв. #17).
            refused_note = (" · ГЛОБЫ БЕЗ ЗОНДА: " + " · ".join(refused)) if refused else ""
            graded = [(sfx, after, line) + _classify(before, after)
                      for sfx, after, line in probes if after != "unmeasured"]
            worst = next((g for g in graded if g[3] == SUBJECT), None) \
                or next((g for g in graded if g[3] == SET_DEPENDENT_GREEN), None) \
                or next((g for g in graded if g[3] == ALREADY_RED), None) \
                or (graded[0] if graded else None)
            if worst is None:
                entries.append(DiffEntry(entry.path, rel_dir, DIFF_UNMEASURED, before=before,
                                         reason="ни один зонд не дошёл до вердикта: "
                                                + "; ".join(f"{s}: {l}" for s, _, l in probes)))
                continue
            sfx, after, _line, kind, why = worst
            if unmeasured:
                why += (" · зонды БЕЗ вердикта: "
                        + ", ".join(pr[0] for pr in unmeasured))
            why += refused_note

            # ── ВТОРОЙ ЗОНД идёт ТОЛЬКО у кандидата в `not_subject` ─────────
            # Здесь и только здесь ответ инертного зонда двусмыслен (см.
            # PLANTED_INERT): «вердикт тот же» означает либо «сторож набором не
            # судит», либо «мой зонд его предиката не касается». Остальные три
            # исхода однозначны и второго прогона не стоят.
            if kind == NOT_SUBJECT:
                # Каталог — ДОГАДКА ⇒ в него не стои́т и класть второй зонд: любой
                # зонд ляжет мимо сторожа, и ответ был бы о каталоге. Вопрос
                # задаётся ДО траты прогона — цена меры есть часть меры.
                if entry.dir_origin(rel_dir) == ORIGIN_GUESS:
                    entries.append(DiffEntry(
                        entry.path, rel_dir, GUESSED_DIR_UNMEASURED,
                        before=before, after=after,
                        reason=f"инертный зонд [{sfx}] вердикта не сдвинул, НО каталог "
                               f"`{rel_dir}` — ДОГАДКА поверхности (его ИМЕНУЕТ тест, а "
                               f"перечисляет помощник по аргументу): зонд мог лечь мимо "
                               f"сторожа, и «вердикт тот же» есть ответ о КАТАЛОГЕ. "
                               f"Второй зонд НЕ ТРАЧЕН — он лёг бы туда же"))
                    continue
                # Глоб второго зонда ДЕТЕРМИНИРОВАН: первый из разобранных у
                # этого каталога, и он ПЕЧАТАЕТСЯ. «Возьму поинтереснее» было бы
                # вкусом автора, а воспроизвести такой замер нечем.
                copy_pat = plant[0][1]
                copy_names, copy_why = _plant_names(
                    copy_pat, stem=f"{PLANTED_STEM}{COPY_SUFFIX_MARK}")
                if copy_why:
                    entries.append(DiffEntry(
                        entry.path, rel_dir, PATTERN_UNMEASURED,
                        before=before, after=after,
                        reason=f"инертный зонд [{sfx}] вердикта не сдвинул, а имя "
                               f"СОДЕРЖАТЕЛЬНОГО под глоб `{copy_pat}` не "
                               f"синтезируется: {copy_why}"))
                    continue
                donor, donor_note = _copy_donor(target_dir, pattern=copy_pat)
                if donor is None:
                    entries.append(DiffEntry(entry.path, rel_dir, COPY_UNMEASURED,
                                             before=before, after=after,
                                             reason=f"[зонд {sfx}] инертный зонд вердикта не "
                                                    f"сдвинул, а содержательный построить НЕ ИЗ "
                                                    f"ЧЕГО: {donor_note}"))
                    continue
                copy_name = next((q for q in copy_names if q.endswith(donor.suffix)),
                                 copy_names[0])
                copy_path = target_dir / copy_name
                if copy_path.exists():
                    entries.append(DiffEntry(entry.path, rel_dir, DIFF_UNMEASURED,
                                             before=before, after=after,
                                             reason=f"имя второго зонда уже занято: "
                                                    f"{copy_path.name} — наследство убитого "
                                                    f"прогона; снять `--clean-planted`"))
                    continue
                try:
                    copy_path.write_bytes(donor.read_bytes())
                    c_after, c_line = _verdict(root, entry.path, timeout)
                finally:
                    try:
                        copy_path.unlink()
                    except OSError as exc:
                        leftovers.append(f"{copy_path}: {exc}")
                    for pyc in (target_dir / "__pycache__").glob(
                            f"*{PLANTED_STEM}{COPY_SUFFIX_MARK}*"):
                        try:
                            pyc.unlink()
                        except OSError:
                            pass
                if c_after == "unmeasured":
                    entries.append(DiffEntry(entry.path, rel_dir, COPY_UNMEASURED,
                                             before=before, after=c_after,
                                             reason=f"инертный зонд вердикта не сдвинул, а "
                                                    f"содержательный (копия `{donor_note}`) не "
                                                    f"дошёл до вердикта: {c_line}"))
                    continue
                c_kind, c_why = _classify(before, c_after)
                if c_kind == NOT_SUBJECT:
                    entries.append(DiffEntry(
                        entry.path, rel_dir, NOT_SUBJECT,
                        before=before, after=c_after,
                        reason=f"вердикт тот же И у инертного зонда [{sfx}], И у "
                               f"СОДЕРЖАТЕЛЬНОГО (копия `{donor_note}` под именем "
                               f"`{copy_name}`, глоб `{copy_pat}`), а каталог НАБЛЮДЁН "
                               f"— ответ ИЗМЕРЕН, а не свойство зонда" + refused_note))
                else:
                    entries.append(DiffEntry(entry.path, rel_dir, c_kind,
                                             before=before, after=c_after,
                                             reason=f"[зонд КОПИЯ `{donor_note}` → "
                                                    f"`{copy_name}`] {c_why} — инертный зонд "
                                                    f"этого НЕ показал: граница PLANTED_INERT "
                                                    f"наблюдена на этом стороже" + refused_note))
                continue

            entries.append(DiffEntry(entry.path, rel_dir, kind, before=before, after=after,
                                     reason=f"[зонд {sfx}] {why}"))
    return Differential(str(root), entries, leftovers)


